/**
 * Модель данных приложения «Кухня 3D».
 * Все размеры — в МИЛЛИМЕТРАХ (как в чертежах). Внутри 3D они переводятся в метры делением на 1000.
 * Файл проекта (.kitchen) — это JSON ровно этой структуры, см. src/lib/schema.ts
 */

export type Vec3 = [number, number, number];

/** Габариты: ш — ширина (X), г — глубина (Z), в — высота (Y) */
export interface Dims {
  ш: number;
  г: number;
  в: number;
}

/** Как ведёт себя модуль */
export type Kind =
  | 'корпус' // шкаф, тумба, пенал — коробка с полками и фасадом
  | 'навесной' // крепится к стене на высоте
  | 'столешница' // плоская плита
  | 'техника' // холодильник, плита, мойка, вытяжка
  | 'стол'
  | 'стул'
  | 'проём' // окно, дверь
  | 'декор'; // растение, светильник, посуда, ковёр

export type Facade = 'нет' | 'распашной' | 'push' | 'зеркало' | 'ящики';

/** Описание типа модуля в каталоге */
export interface ModuleDef {
  id: string;
  название: string;
  категория: string;
  вид: Kind;
  /** Заводские габариты, мм */
  габариты: Dims;
  /** Границы, в которых пользователь может менять размер (по умолчанию 50…4000) */
  мин?: Dims;
  макс?: Dims;
  /** Высота цоколя, мм (0 — без цоколя) */
  цоколь?: number;
  /** Число полок; 'авто' — пересчитываются по высоте (шаг 320) */
  полки?: number | 'авто';
  фасад?: Facade;
  /** Число ящиков (для фасада «ящики») */
  ящиков?: number;
  /** Высота ножек, мм */
  ножки?: number;
  крепление: 'напольное' | 'навесное';
  /** Для навесных: высота низа по умолчанию, мм */
  подъём_по_умолчанию?: number;
  материал?: string;
  цвет?: string;
  /** Пометка о происхождении/спорности размера */
  заметка?: string;
}

/** Один объект, поставленный в комнату */
export interface Obj {
  id: string;
  /** id из каталога или 'свободный' */
  модуль: string;
  название?: string;
  /** Позиция: X и Z — центр, Y — низ объекта, мм */
  позиция: Vec3;
  /** Поворот вокруг вертикали, градусы (0…359) */
  поворот: number;
  /** Наклон вперёд-назад (вокруг оси X), градусы. Необязательно. */
  наклон_X?: number;
  /** Наклон влево-вправо (вокруг оси Z), градусы. Необязательно. */
  наклон_Z?: number;
  /** Дверцы показаны открытыми */
  открыт?: boolean;
  /** С какой стороны петли: слева | справа | сверху | снизу */
  петли?: 'слева' | 'справа' | 'сверху' | 'снизу';
  габариты: Dims;
  /** Для навесных: высота низа, мм */
  подъём?: number;
  цвет?: string;
  материал?: string;
  ящиков?: number;
  полок?: number;
  цоколь?: number;
  ножки?: number;
  вид?: Kind;
  фасад?: Facade;
}

export type RoomShape = 'прямоугольник' | 'Г' | 'П';

export interface Room {
  /** Длина по X, мм */
  длина: number;
  /** Ширина по Z, мм */
  ширина: number;
  /** Высота стен, мм. Потолка в приложении нет. */
  высота_стен: number;
  толщина_стен: number;
  форма: RoomShape;
  /** Цвет/материал обоев */
  обои: string;
  /** Цвет/материал пола */
  пол: string;
  /** Фон рабочей области (самого 3D-конструктора) */
  фон: string;
}

export const SCHEMA_VERSION = 1;

export interface Project {
  schemaVersion: number;
  название: string;
  создан: string;
  изменён: string;
  комната: Room;
  объекты: Obj[];
  /** Настройки пользователя, которые едут вместе с проектом */
  настройки?: {
    шаг_сетки?: number;
    толщина_плиты?: number;
    режим_обзора?: CameraMode;
    тема?: 'тёмная' | 'светлая';
  };
}

export type CameraMode = 'сверху' | 'прогулка';

export const пустая_комната = (длина = 3600, ширина = 2800, высота = 2700): Room => ({
  длина,
  ширина,
  высота_стен: высота,
  толщина_стен: 100,
  форма: 'прямоугольник',
  обои: '#cbb79a',
  пол: '#8a6a4b',
  фон: '#171a1f',
});

export const новый_проект = (название: string, комната: Room = пустая_комната()): Project => ({
  schemaVersion: SCHEMA_VERSION,
  название,
  создан: new Date().toISOString(),
  изменён: new Date().toISOString(),
  комната,
  объекты: [],
  настройки: { шаг_сетки: 50, толщина_плиты: 16, режим_обзора: 'сверху', тема: 'тёмная' },
});
