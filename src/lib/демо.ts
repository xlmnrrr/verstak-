/**
 * Демо-кухня: собирается из каталога кодом, а не хранится картинкой.
 * Используется и кнопкой «Пример» в приложении, и скриптом, который делает
 * файл public/Библиотека/пример-проекта.kitchen для Claude.
 */
import { модульПоИд } from '../data/modules';
import { ОБОИ, ПОЛЫ, ФАСАДЫ } from '../data/materials';
import { новый_проект, type Obj, type Project } from '../types';
import { автоПолки, новыйИд } from './utils';

function сделать(
  ид: string,
  x: number,
  z: number,
  доп: Partial<Obj> = {},
): Obj | null {
  const опр = модульПоИд(ид);
  if (!опр) return null;
  const низПоУмолчанию = опр.крепление === 'навесное' ? (опр.подъём_по_умолчанию ?? 1500) : 0;
  const подъём = доп.подъём ?? низПоУмолчанию;
  return {
    id: новыйИд(),
    модуль: опр.id,
    название: опр.название,
    позиция: [Math.round(x), подъём, Math.round(z)],
    поворот: доп.поворот ?? 0,
    габариты: доп.габариты ?? { ...опр.габариты },
    подъём,
    цвет: доп.цвет ?? опр.цвет,
    материал: доп.материал ?? опр.материал,
    ящиков: доп.ящиков ?? опр.ящиков ?? 0,
    полок:
      доп.полок ??
      (опр.полки === 'авто' ? автоПолки(опр.габариты.в, опр.цоколь ?? 0) : (опр.полки ?? 0)),
    цоколь: доп.цоколь ?? опр.цоколь ?? 0,
    ножки: доп.ножки ?? опр.ножки ?? 0,
    вид: опр.вид,
    фасад: доп.фасад ?? опр.фасад ?? 'нет',
  };
}

/** Готовая кухня: нижний ряд, столешница, навесные шкафы, техника, стол со стульями, окно */
export function собратьДемо(название = 'Пример: кухня из шаблонов'): Project {
  const проект = новый_проект(название);
  проект.комната.длина = 4200;
  проект.комната.ширина = 3000;
  проект.комната.высота_стен = 2700;
  проект.комната.обои = ОБОИ[3]?.цвет ?? '#cbb79a';
  проект.комната.пол = ПОЛЫ[0]?.цвет ?? '#8a6a4b';

  const к = проект.комната;
  const задняяZ = -к.ширина / 2;
  const базаZ = задняяZ + к.толщина_стен / 2; // плоскость стены

  const объекты: Obj[] = [];
  const добавить = (о: Obj | null) => {
    if (о) объекты.push(о);
  };

  // --- нижний ряд вдоль задней стены ---
  const низ = ['fridge-600', 'cabinet-drawers-600', 'cabinet-base-400', 'cabinet-sink-600', 'stove-600'];
  let x = -к.длина / 2 + 150;
  let столНачало = 0;
  let столКонец = 0;

  for (const ид of низ) {
    const опр = модульПоИд(ид);
    if (!опр) continue;
    const ш = опр.габариты.ш;
    const о = сделать(ид, x + ш / 2, базаZ + опр.габариты.г / 2, {
      цвет: ФАСАДЫ.find((ф) => ф.название.includes('Дуб'))?.цвет,
    });
    добавить(о);
    if (ид !== 'fridge-600') {
      if (!столНачало) столНачало = x;
      столКонец = x + ш;
    }
    x += ш;
  }

  // --- столешница поверх нижних модулей ---
  const длинаСтолешницы = Math.max(600, Math.round(столКонец - столНачало));
  const центрСтолешницы = (столНачало + столКонец) / 2;
  добавить(
    сделать('worktop-3000', центрСтолешницы, базаZ + 300, {
      габариты: { ш: длинаСтолешницы, г: 600, в: 38 },
      подъём: 900,
      цвет: '#e8e4dc',
      материал: 'Столешница камень',
    }),
  );

  // --- мойка и варочная панель на столешнице ---
  добавить(сделать('sink-flush-780', столНачало + 1100, базаZ + 300, { подъём: 938 }));
  добавить(сделать('hob-580', столКонец - 500, базаZ + 300, { подъём: 938 }));

  // --- навесные шкафы (начинаем ПОСЛЕ холодильника, иначе они с ним пересекаются) ---
  const ширинаХолодильника = модульПоИд('fridge-600')?.габариты.ш ?? 600;
  let верхX = -к.длина / 2 + 150 + ширинаХолодильника + 20;
  for (let i = 0; i < 3; i++) {
    const опр = модульПоИд('wall-600');
    if (!опр) break;
    добавить(
      сделать('wall-600', верхX + опр.габариты.ш / 2, базаZ + опр.габариты.г / 2, {
        подъём: 1500,
        цвет: ФАСАДЫ.find((ф) => ф.название.toLowerCase().includes('бел'))?.цвет,
      }),
    );
    верхX += опр.габариты.ш;
  }
  добавить(сделать('hood-dome-600', верхX + 300, базаZ + 250, { подъём: 1600 }));

  // --- окно на левой стене ---
  добавить(
    сделать('window-2-1600', -к.длина / 2 + к.толщина_стен / 2, 500, { подъём: 900, поворот: 90 }),
  );

  // --- обеденная зона ---
  добавить(сделать('table-6-1800', 0, 700));
  const стулья: [number, number][] = [
    [-600, 350],
    [0, 350],
    [600, 350],
    [-600, 1050],
    [0, 1050],
    [600, 1050],
  ];
  for (const [сx, сz] of стулья) добавить(сделать('chair-dining', сx, сz, { поворот: сz < 700 ? 0 : 180 }));

  добавить(сделать('light-pendant-3', 0, 700, { подъём: 1900 }));
  добавить(
    сделать('plant-900', -к.длина / 2 + 700, к.ширина / 2 - 700, {
      габариты: { ш: 500, г: 500, в: 1100 },
    }),
  );
  добавить(сделать('rug-2000x1400', 0, 700));

  проект.объекты = объекты;
  проект.изменён = new Date().toISOString();
  return проект;
}
