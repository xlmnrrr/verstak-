import { describe, expect, it } from 'vitest';
import { автоПроёмы, квартираПоСетке } from './квартира';

describe('квартира по сетке: как в мастере', () => {
  it('три закрашенных помещения дают план с общими стенами и дверями', () => {
    const клетки = [
      [1, 1, 2, 2, 2],
      [1, 1, 2, 2, 2],
      [3, 3, 3, 0, 0],
    ];
    const р = квартираПоСетке({ клетка: 600, клетки, комнаты: { 1: { тип: 'прихожая' }, 2: { тип: 'кухня' }, 3: { тип: 'ванная' } }, проёмы: автоПроёмы(клетки, 600) });
    expect(р.ошибки).toEqual([]);
    expect(р.помещения).toHaveLength(3);
    expect(р.связи.length).toBeGreaterThanOrEqual(2);
    const двери = р.помещения.flatMap((п) => п.отметки.filter((о) => о.вид === 'дверь'));
    expect(двери.length).toBeGreaterThanOrEqual(2);
  });

  it('пустая сетка — ошибка, а не пустой проект', () => {
    expect(квартираПоСетке({ клетка: 500, клетки: [[0, 0]], комнаты: {} }).ошибки.length).toBeGreaterThan(0);
  });
});
