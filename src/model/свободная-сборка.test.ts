import { describe, expect, it } from 'vitest';
import { таблицаСпецификации, htmlЧертежа } from '../export/форматы';
import { изделиеПоИд } from './каталог';
import { новоеПомещение, прямоугольник } from './помещение';
import { новыйПроектV2, новыйЭкземпляр } from './проект';
import { пометкаПересечений, проверитьВлезает } from './проверка';
import { записатьПроект, разобратьФайл } from './файл';

const комната = () => новыйПроектV2('т', новоеПомещение('п1', 'кухня', 'Кухня', прямоугольник(3600, 2800)));
const тумба = () => изделиеПоИд('тумба-ящики-600')!;

describe('«Свободная сборка»: настройка проекта', () => {
  it('по умолчанию выключена и в файл не пишется; включённая сохраняется и читается рядом с сеткой', () => {
    const п = комната();
    expect(п.настройки.свободная_сборка).toBeUndefined();
    const выкл = разобратьФайл(записатьПроект(п));
    expect(выкл.ок).toBe(true);
    expect(выкл.проект!.настройки.свободная_сборка).toBeFalsy();

    п.настройки = { ...п.настройки, свободная_сборка: true, шаг_сетки: 10 };
    const вкл = разобратьФайл(записатьПроект(п));
    expect(вкл.ок, JSON.stringify(вкл.ошибки)).toBe(true);
    expect(вкл.проект!.настройки.свободная_сборка).toBe(true);
    expect(вкл.проект!.настройки.шаг_сетки).toBe(10);
  });

  it('старый файл без поля открывается как раньше (режим выключен)', () => {
    const п = комната();
    const json = JSON.parse(записатьПроект(п));
    delete json.настройки.свободная_сборка;
    const р = разобратьФайл(JSON.stringify(json));
    expect(р.ок).toBe(true);
    expect(!!р.проект!.настройки.свободная_сборка).toBe(false);
  });
});

describe('пометка «есть пересечения» в спецификации и чертеже', () => {
  const сПересечением = (свободно: boolean) => {
    const п = комната();
    п.настройки = { ...п.настройки, свободная_сборка: свободно };
    п.объекты.push({ ...новыйЭкземпляр(тумба(), 'п1'), id: 'а', позиция: [0, 0, -1000] }, { ...новыйЭкземпляр(тумба(), 'п1'), id: 'б', позиция: [100, 0, -1000] });
    return п;
  };

  it('чистый проект: пометки нет, спецификация без лишней строки', () => {
    const п = комната();
    п.объекты.push({ ...новыйЭкземпляр(тумба(), 'п1'), id: 'а', позиция: [0, 0, -1000] });
    expect(пометкаПересечений(п)).toBeNull();
    const т = таблицаСпецификации(п);
    expect(т.some((р) => String(р[1]).startsWith('ПРИМЕЧАНИЕ'))).toBe(false);
    expect(htmlЧертежа(п, { заказ: '', клиент: '', дизайнер: '' })).not.toContain('ПРИМЕЧАНИЕ');
  });

  it('пересечение: одна пара считается один раз, пометка есть в спецификации и в чертеже', () => {
    const п = сПересечением(false);
    expect(проверитьВлезает(п).filter((x) => x.вид === 'пересечение').length).toBe(2);
    expect(пометкаПересечений(п)).toBe('Есть пересечения: 1 пара предметов');
    expect(таблицаСпецификации(п).at(-1)![1]).toContain('Есть пересечения: 1 пара предметов');
    expect(htmlЧертежа(п, { заказ: '', клиент: '', дизайнер: '' })).toContain('ПРИМЕЧАНИЕ: Есть пересечения: 1 пара предметов');
  });

  it('при включённой свободной сборке в пометке сказано об этом', () => {
    const п = сПересечением(true);
    expect(пометкаПересечений(п)).toContain('включена свободная сборка');
    // данные не теряются: проверка видит пересечение независимо от режима
    expect(проверитьВлезает(п).length).toBeGreaterThan(0);
  });
});
