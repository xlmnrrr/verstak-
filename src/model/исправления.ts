/**
 * Исправления в один клик для замечаний об открывании («Переставить петли», «Дать зазор 150 мм»).
 * Предлагаются только те, что на самом деле снимают конфликт и не создают новых пересечений или выступов за стену:
 * кнопка, которая не помогает, не показывается. Чистые функции: возвращают новый экземпляр, проект не меняют.
 */
import { изделиеПоИд } from './каталог';
import { конфликтыЭкземпляра, препятствияПомещения } from './открывание';
import { зазоры, кратен90 } from './привязка';
import { проверитьВлезает } from './проверка';
import { слитьРаскладку } from './раскладка';
import type { ПроектV2, Экземпляр } from './типы';

/** Зазор до мешающего предмета или стены, который даём одним кликом: хватает на створку, открытую на 110° */
export const ЗАЗОР_ОТКРЫВАНИЯ_ММ = 150;

export interface Исправление {
  вид: 'петли' | 'зазор';
  /** подпись кнопки */
  подпись: string;
  /** подсказка: что именно будет сделано */
  описание: string;
  /** экземпляр после исправления */
  результат: Экземпляр;
  /** сообщение после применения */
  итог: string;
}

const нарушений = (п: ПроектV2, id: string) => проверитьВлезает(п, new Set([id])).length;

/** Экземпляр заменён в копии проекта (для проверки «ничего не сломали») */
const сЗаменой = (п: ПроектV2, э: Экземпляр): ПроектV2 => ({ ...п, объекты: п.объекты.map((о) => (о.id === э.id ? э : о)) });

/**
 * Исправления для конфликта открывания экземпляра: сначала считаем, сколько конфликтов у него сейчас, и берём
 * только варианты, после которых их строго меньше, а новых пересечений и выступов за стену не появилось.
 */
export function исправленияОткрывания(п: ПроектV2, id: string): Исправление[] {
  const э = п.объекты.find((о) => о.id === id);
  const изд = э ? изделиеПоИд(э.изделие) : undefined;
  const пом = э ? п.помещения.find((x) => x.id === э.помещение) : undefined;
  if (!э || !изд || !пом) return [];
  const препятствия = препятствияПомещения(п, пом, э.помещение);
  const было = конфликтыЭкземпляра(э, препятствия).length;
  if (!было) return [];
  const нарушенийБыло = нарушений(п, id);
  const помогает = (э2: Экземпляр) => конфликтыЭкземпляра(э2, препятствия).length < было && нарушений(сЗаменой(п, э2), id) <= нарушенийБыло;
  const итог: Исправление[] = [];

  // 1. петли на другую сторону (одна сторона: «слева» ↔ «справа»; попарные, верхние и нижние переставлять нечего)
  const петли = слитьРаскладку(изд.раскладка, э.раскладка).фасад.петли;
  if (петли === 'слева' || петли === 'справа') {
    const новые = петли === 'слева' ? 'справа' : 'слева';
    const э2: Экземпляр = { ...э, раскладка: { ...э.раскладка, фасад: { ...э.раскладка?.фасад, петли: новые } } };
    if (помогает(э2)) итог.push({ вид: 'петли', подпись: 'Переставить петли', описание: `Петли ${петли} → ${новые}: створка откроется в другую сторону`, результат: э2, итог: `Петли переставлены: теперь ${новые}` });
  }

  // 2. сдвинуть от мешающего так, чтобы до него осталось 150 мм (только вдоль ширины, у кратных 90°)
  if (кратен90(э.поворот)) {
    const з = зазоры(п, э);
    const ось: 'x' | 'z' = Math.round(((э.поворот % 180) + 180) % 180) === 90 ? 'z' : 'x';
    const ключ = (плюс: boolean) => (ось === 'x' ? (плюс ? 'xПлюс' : 'xМинус') : плюс ? 'zПлюс' : 'zМинус') as 'xПлюс' | 'xМинус' | 'zПлюс' | 'zМинус';
    for (const вПлюс of [false, true]) {
      const мешающий = з[ключ(!вПлюс)];
      const свободно = з[ключ(вПлюс)];
      if (!мешающий) continue;
      const сдвиг = Math.round((ЗАЗОР_ОТКРЫВАНИЯ_ММ - мешающий.мм) * 2) / 2;
      if (сдвиг <= 0 || (свободно && свободно.мм < сдвиг)) continue;
      const знак = вПлюс ? 1 : -1;
      const позиция: Экземпляр['позиция'] = ось === 'x' ? [э.позиция[0] + знак * сдвиг, э.позиция[1], э.позиция[2]] : [э.позиция[0], э.позиция[1], э.позиция[2] + знак * сдвиг];
      const э2: Экземпляр = { ...э, позиция };
      if (помогает(э2)) {
        const от = мешающий.преграда.вид === 'стена' ? 'стены' : `«${мешающий.преграда.название}»`;
        итог.push({
          вид: 'зазор',
          подпись: `Дать зазор ${ЗАЗОР_ОТКРЫВАНИЯ_ММ} мм`,
          описание: `Сдвинуть на ${сдвиг} мм от ${от}: до ${мешающий.преграда.вид === 'стена' ? 'неё' : 'него'} останется ${ЗАЗОР_ОТКРЫВАНИЯ_ММ} мм`,
          результат: э2,
          итог: `Сдвинуто на ${сдвиг} мм: зазор до ${от} ${ЗАЗОР_ОТКРЫВАНИЯ_ММ} мм`,
        });
        break;
      }
    }
  }
  return итог;
}
