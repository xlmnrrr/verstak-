/**
 * A4: редактор отметок на стенах — поставить, подвинуть, изменить, удалить; границы стены и потолка;
 * подписи вида и высоты; запись в .kitchen и чтение; «Предложи планировку» учитывает поставленное.
 */
import { describe, expect, it } from 'vitest';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { новоеПомещение, прямоугольник } from './помещение';
import { новыйПроектV2 } from './проект';
import { записатьПроект, разобратьФайл } from './файл';
import { предложитьПланировки } from './планировщик';
import { коробаСтен } from './стены';
import { следУглы } from './проверка';
import { изделиеПоИд } from './каталог';
import {
  ВИДЫ_ОТМЕТОК,
  безОтметки,
  новаяОтметка,
  подписьОтметки,
  проверитьОтметку,
  сдвинутьОтметку,
  сИзменённойОтметкой,
  сОтметкой,
  строкаОтметки,
  точкаПодписи,
} from './отметки';

const кухня = () => новоеПомещение('п1', 'кухня', 'Кухня', прямоугольник(3600, 2800, false));

describe('отметки на стенах: правка', () => {
  it('поставить: размеры по умолчанию, посередине стены, новый id; подпись вида и высоты', () => {
    let п = кухня();
    const р = новаяОтметка(п, 'розетка', 0);
    expect(р).toMatchObject({ вид: 'розетка', стена: 0, ширина: 80, высота: 80, от_пола: 300, от_угла: 1760 });
    п = сОтметкой(п, р);
    const в = новаяОтметка(п, 'радиатор', 1, { от_угла: 300 });
    expect(в.id).not.toBe(р.id);
    expect(в.глубина).toBe(100);
    п = сОтметкой(п, в);
    expect(п.отметки).toHaveLength(2);
    expect(подписьОтметки(р)).toBe('Розетка · 300');
    expect(строкаОтметки(п, в)).toBe('Радиатор · правая стена · 300 от угла · 150 от пола · 800 × 500 × 100');
    for (const о of ВИДЫ_ОТМЕТОК) expect(проверитьОтметку(п, новаяОтметка(п, о.вид, 2)), о.вид).toEqual([]);
  });

  it('подвинуть и изменить — в границах стены и потолка; удалить', () => {
    let п = сОтметкой(кухня(), новаяОтметка(кухня(), 'щиток', 0, { от_угла: 100 }));
    const id = п.отметки[0].id;
    п = сдвинутьОтметку(п, id, -500);
    expect(п.отметки[0].от_угла).toBe(0);
    п = сдвинутьОтметку(п, id, 50);
    expect(п.отметки[0].от_угла).toBe(50);
    п = сИзменённойОтметкой(п, id, { от_угла: 5000 });
    expect(п.отметки[0].от_угла).toBe(3600 - 300);
    п = сИзменённойОтметкой(п, id, { от_пола: 2600 });
    expect(п.отметки[0].от_пола + п.отметки[0].высота).toBe(2700);
    п = сИзменённойОтметкой(п, id, { стена: 1, ширина: 5000 });
    expect(п.отметки[0].ширина).toBe(2800);
    expect(проверитьОтметку(п, п.отметки[0])).toEqual([]);
    п = безОтметки(п, id);
    expect(п.отметки).toEqual([]);
  });

  it('проверка с цифрами: за стену и выше потолка', () => {
    const п = кухня();
    const о = { ...новаяОтметка(п, 'окно', 0), от_угла: 3000, от_пола: 2000 };
    const т = проверитьОтметку(п, о);
    expect(т.some((x) => /выходит за стену на 600 мм — стена 3600 мм/.test(x))).toBe(true);
    expect(т.some((x) => /выше потолка на 700 мм — потолок 2700 мм/.test(x))).toBe(true);
  });

  it('в 3D: розетка — плитка на стене, окно — вырез в стене; подпись над отметкой, в комнате', () => {
    let п = сОтметкой(кухня(), новаяОтметка(кухня(), 'розетка', 0, { от_угла: 1000 }));
    п = сОтметкой(п, новаяОтметка(п, 'окно', 1));
    const к = коробаСтен(п);
    expect(к.плитки.some((x) => x.вид === 'розетка')).toBe(true);
    // правая стена разрезана окном: больше одного куска
    expect(к.стены.filter((с) => Math.abs(с.нормаль[0] + 1) < 1e-6).length).toBeGreaterThan(1);
    const т = точкаПодписи(п, п.отметки[0])!;
    expect(т[1]).toBeGreaterThan(300 + 80);
    expect(т[2]).toBeGreaterThan(0); // в комнате, не в стене (задняя стена z = 0, комната z > 0)
  });

  it('пишется в .kitchen и читается обратно; старый пример открывается', () => {
    let п = кухня();
    п = сОтметкой(п, новаяОтметка(п, 'вода', 0, { от_угла: 900 }));
    п = сОтметкой(п, новаяОтметка(п, 'наличник', 3));
    const р = разобратьФайл(записатьПроект(новыйПроектV2('т', п)));
    expect(р.ок).toBe(true);
    expect(р.проект!.помещения[0].отметки).toEqual(п.отметки);
    expect(разобратьФайл(readFileSync(join(process.cwd(), 'public/Библиотека/пример-проекта.kitchen'), 'utf8')).ок).toBe(true);
  });
});

describe('«Предложи планировку» учитывает отметки, поставленные редактором', () => {
  it('радиатор на задней стене: перед ним нет мебели у пола; вода — мойка рядом', () => {
    let п = кухня();
    п = сОтметкой(п, новаяОтметка(п, 'радиатор', 0, { от_угла: 1200, ширина: 1000 }));
    п = сОтметкой(п, новаяОтметка(п, 'вода', 1, { от_угла: 1500 }));
    const р = предложитьПланировки(новыйПроектV2('т', п));
    expect(р.варианты.length).toBeGreaterThan(0);
    for (const в of р.варианты) {
      expect(в.чисто, в.замечания.map((з) => з.текст).join(' | ')).toBe(true);
      expect(в.учтено.some((т) => т.startsWith('Радиатор 1000'))).toBe(true);
      for (const о of в.проект.объекты) {
        const изд = изделиеПоИд(о.изделие)!;
        if (изд.тип === 'проём' || о.позиция[1] > 200) continue;
        const у = следУглы(о.позиция, о.поворот, о.габариты.ш, о.габариты.г);
        const zMin = Math.min(...у.map((t) => t[1]));
        const x0 = Math.min(...у.map((t) => t[0]));
        const x1 = Math.max(...у.map((t) => t[0]));
        expect(zMin < 150 && x1 > 1210 && x0 < 2190, `${о.изделие} перед радиатором`).toBe(false);
      }
      const вода = в.учтено.find((т) => т.startsWith('Мойка в'));
      expect(вода).toBeDefined();
    }
  });
});
