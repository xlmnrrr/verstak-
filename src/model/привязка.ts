/**
 * Привязка и «умные» действия над расстановкой (этап 3): прилипание к стенам и соседям «без зазора», подсказки стыковки,
 * поиск ниши («остаток 437 мм: урезать до 437?»), зазоры для размерных линий, быстрые действия
 * («до потолка», «к соседу», «по центру», «в угол», «выровнять по фасаду»).
 * Чистая геометрия, мм, без three и React. Работает для поворотов, кратных 90° (шкафы вдоль стен); при других углах
 * привязка к объектам не включается, чтобы не ломать произвольные расстановки.
 */
import { изделиеПоИд } from './каталог';
import { высотаДляРендера, стены as рёбра, точкаВнутри } from './помещение';
import type { Экземпляр, Изделие, ПроектV2, Помещение } from './типы';

/** Типы изделий, к которым прилипают и о которые упираются (столешницы, декор, свет, проёмы и стулья не считаются) */
const ТВЁРДЫЕ = new Set<Изделие['тип']>(['корпус', 'техника', 'стол', 'мягкая']);
/** Сколько мм по высоте должно перекрываться, чтобы предметы считались «в одном ряду» */
const ПЕРЕКРЫТИЕ_ПО_ВЫСОТЕ = 10;
/** Допуск «вплотную» */
export const ВПЛОТНУЮ_ММ = 0.5;

export interface Преграда {
  id?: string;
  название: string;
  вид: 'стена' | 'сосед';
  x0: number;
  x1: number;
  z0: number;
  z1: number;
  y0: number;
  y1: number;
  /** у стены: внутренняя нормаль (в сторону комнаты) */
  внутрь?: [number, number];
}

/** Габарит экземпляра в плане (оси мира). Для углов не кратных 90° — описывающий прямоугольник */
export function прямоугольникЭкземпляра(э: Pick<Экземпляр, 'позиция' | 'поворот' | 'габариты'>) {
  const θ = (э.поворот * Math.PI) / 180;
  const c = Math.abs(Math.cos(θ));
  const s = Math.abs(Math.sin(θ));
  const hx = (э.габариты.ш * c + э.габариты.г * s) / 2;
  const hz = (э.габариты.ш * s + э.габариты.г * c) / 2;
  const [x, y, z] = э.позиция;
  return { x0: x - hx, x1: x + hx, z0: z - hz, z1: z + hz, y0: y, y1: y + э.габариты.в, cx: x, cz: z, hx, hz };
}

export const кратен90 = (поворот: number) => Math.abs(((поворот % 90) + 90) % 90) < 0.01 || Math.abs(((поворот % 90) + 90) % 90 - 90) < 0.01;

/** Преграды помещения для привязки: стены (прямые, вдоль осей) и твёрдые соседи; `кроме` — id, которые не считаются */
export function преградыДляПривязки(п: ПроектV2, помещениеId: string, кроме: ReadonlySet<string> | string = new Set()): Преграда[] {
  const искл = typeof кроме === 'string' ? new Set([кроме]) : кроме;
  const итог: Преграда[] = [];
  const пом = п.помещения.find((x) => x.id === помещениеId);
  if (пом) {
    const H = высотаДляРендера(пом);
    for (const с of рёбра(пом.контур)) {
      const вертикальная = Math.abs(с.направление[0]) < 1e-6;
      const горизонтальная = Math.abs(с.направление[1]) < 1e-6;
      if (!вертикальная && !горизонтальная) continue;
      итог.push({
        название: 'стена',
        вид: 'стена',
        x0: Math.min(с.а[0], с.б[0]),
        x1: Math.max(с.а[0], с.б[0]),
        z0: Math.min(с.а[1], с.б[1]),
        z1: Math.max(с.а[1], с.б[1]),
        y0: 0,
        y1: H,
        внутрь: [Math.round(с.нормаль[0]), Math.round(с.нормаль[1])],
      });
    }
  }
  for (const э of п.объекты) {
    if (э.помещение !== помещениеId || искл.has(э.id)) continue;
    const изд = изделиеПоИд(э.изделие);
    if (!изд || !ТВЁРДЫЕ.has(изд.тип)) continue;
    const р = прямоугольникЭкземпляра(э);
    итог.push({ id: э.id, название: э.название ?? изд.название, вид: 'сосед', x0: р.x0, x1: р.x1, z0: р.z0, z1: р.z1, y0: р.y0, y1: р.y1 });
  }
  return итог;
}

/* ------------------------------------------------------------------ привязка */

export interface Подсказка {
  ось: 'x' | 'z';
  /** координата линии стыка (мм) */
  линия: number;
  вид: 'стена' | 'сосед' | 'выравнивание';
  текст: string;
  сосед?: string;
  /** отрезок линии для рисования (оси мира, мм) */
  отрезок: [[number, number], [number, number]];
}

export interface ВходПривязки {
  /** центр изделия в плане (мм) */
  позиция: [number, number];
  ш: number;
  г: number;
  поворот: number;
  низ: number;
  верх: number;
}

export interface РезультатПривязки {
  позиция: [number, number];
  подсказки: Подсказка[];
}

const перекрытие = (a0: number, a1: number, b0: number, b1: number) => Math.min(a1, b1) - Math.max(a0, b0);

/**
 * Прилипание к стенам и соседям: каждая ось отдельно, ближайшая цель не дальше `порог` мм.
 * «Встык» (грань к грани без зазора) важнее выравнивания по одной линии.
 */
export function привязать(вход: ВходПривязки, преграды: readonly Преграда[], порог: number): РезультатПривязки {
  if (!кратен90(вход.поворот)) return { позиция: [...вход.позиция], подсказки: [] };
  const обмен = Math.round(((вход.поворот % 180) + 180) % 180) === 90;
  const hx = (обмен ? вход.г : вход.ш) / 2;
  const hz = (обмен ? вход.ш : вход.г) / 2;
  const поз: [number, number] = [вход.позиция[0], вход.позиция[1]];
  const подсказки: Подсказка[] = [];

  for (const ось of ['x', 'z'] as const) {
    const i = ось === 'x' ? 0 : 1;
    const полу = ось === 'x' ? hx : hz;
    const полуПоперёк = ось === 'x' ? hz : hx;
    const поперёк = ось === 'x' ? поз[1] : поз[0];
    let лучшая: { дельта: number; вид: Подсказка['вид']; преграда: Преграда; цель: number; вплотную: boolean } | null = null;
    for (const о of преграды) {
      if (перекрытие(вход.низ, вход.верх, о.y0, о.y1) <= ПЕРЕКРЫТИЕ_ПО_ВЫСОТЕ) continue;
      const a0 = ось === 'x' ? о.x0 : о.z0;
      const a1 = ось === 'x' ? о.x1 : о.z1;
      const l0 = ось === 'x' ? о.z0 : о.x0;
      const l1 = ось === 'x' ? о.z1 : о.x1;
      const вплотнуюПоперёк = перекрытие(поперёк - полуПоперёк, поперёк + полуПоперёк, l0, l1) > 0;
      const моя0 = поз[i] - полу;
      const моя1 = поз[i] + полу;
      const варианты: { цель: number; грань: number; вид: Подсказка['вид']; встык: boolean }[] = [];
      if (о.вид === 'стена') {
        if (!вплотнуюПоперёк || !о.внутрь) continue;
        const н = о.внутрь[i];
        // стена слева от изделия (нормаль +ось): прижимаем левую грань; справа (нормаль −ось): правую
        if (н > 0) варианты.push({ цель: a0, грань: моя0, вид: 'стена', встык: true });
        if (н < 0) варианты.push({ цель: a0, грань: моя1, вид: 'стена', встык: true });
      } else {
        if (вплотнуюПоперёк) {
          варианты.push({ цель: a1, грань: моя0, вид: 'сосед', встык: true });
          варианты.push({ цель: a0, грань: моя1, вид: 'сосед', встык: true });
        }
        // выравнивание по одной линии: только у близких по поперечной оси
        if (перекрытие(поперёк - полуПоперёк - порог * 4, поперёк + полуПоперёк + порог * 4, l0, l1) > 0) {
          варианты.push({ цель: a0, грань: моя0, вид: 'выравнивание', встык: false });
          варианты.push({ цель: a1, грань: моя1, вид: 'выравнивание', встык: false });
        }
      }
      for (const в of варианты) {
        const дельта = в.цель - в.грань;
        if (Math.abs(дельта) > порог) continue;
        const лучше =
          !лучшая ||
          (в.встык && !лучшая.вплотную) ||
          (в.встык === лучшая.вплотную && Math.abs(дельта) < Math.abs(лучшая.дельта) - 0.01);
        if (лучше) лучшая = { дельта, вид: в.вид, преграда: о, цель: в.цель, вплотную: в.встык };
      }
    }
    if (!лучшая) continue;
    поз[i] += лучшая.дельта;
    const л = ось === 'x' ? [поз[1] - hz, поз[1] + hz] : [поз[0] - hx, поз[0] + hx];
    const от = Math.min(л[0], ось === 'x' ? лучшая.преграда.z0 : лучшая.преграда.x0);
    const до = Math.max(л[1], ось === 'x' ? лучшая.преграда.z1 : лучшая.преграда.x1);
    подсказки.push({
      ось,
      линия: лучшая.цель,
      вид: лучшая.вид,
      сосед: лучшая.преграда.id,
      текст: лучшая.вид === 'стена' ? 'Вплотную к стене' : лучшая.вид === 'сосед' ? `Встык к «${лучшая.преграда.название}»` : `По одной линии с «${лучшая.преграда.название}»`,
      отрезок: ось === 'x' ? [[лучшая.цель, от], [лучшая.цель, до]] : [[от, лучшая.цель], [до, лучшая.цель]],
    });
  }
  return { позиция: поз, подсказки };
}

/* ------------------------------------------------------------------ ряд: зазоры и ниша */

export interface Просвет {
  /** расстояние до ближайшей преграды, мм (0 — вплотную) */
  мм: number;
  преграда: Преграда;
  /** координата грани преграды на оси */
  грань: number;
}

export interface Зазоры {
  /** по осям мира: минус и плюс по X, минус и плюс по Z */
  xМинус?: Просвет;
  xПлюс?: Просвет;
  zМинус?: Просвет;
  zПлюс?: Просвет;
  /** до потолка, мм (только если известна высота) */
  доПотолка?: number;
}

/** Ближайшие преграды по четырём направлениям от габарита (только для кратных 90°); дальше 3 м не ищем */
export function зазоры(п: ПроектV2, э: Экземпляр): Зазоры {
  const пом = п.помещения.find((x) => x.id === э.помещение);
  const р = прямоугольникЭкземпляра(э);
  const итог: Зазоры = {};
  if (пом) итог.доПотолка = Math.max(0, Math.round(высотаДляРендера(пом) - р.y1));
  if (!кратен90(э.поворот)) return итог;
  const преграды = преградыДляПривязки(п, э.помещение, э.id);
  const ищем = (ось: 'x' | 'z', плюс: boolean): Просвет | undefined => {
    let лучший: Просвет | undefined;
    for (const о of преграды) {
      if (перекрытие(р.y0, р.y1, о.y0, о.y1) <= ПЕРЕКРЫТИЕ_ПО_ВЫСОТЕ) continue;
      const a0 = ось === 'x' ? о.x0 : о.z0;
      const a1 = ось === 'x' ? о.x1 : о.z1;
      const l0 = ось === 'x' ? о.z0 : о.x0;
      const l1 = ось === 'x' ? о.z1 : о.x1;
      const моя0 = ось === 'x' ? р.x0 : р.z0;
      const моя1 = ось === 'x' ? р.x1 : р.z1;
      if (перекрытие(ось === 'x' ? р.z0 : р.x0, ось === 'x' ? р.z1 : р.x1, l0, l1) <= 0) continue;
      if (о.вид === 'стена' && о.внутрь) {
        const н = о.внутрь[ось === 'x' ? 0 : 1];
        // стена, на которую смотрим: её нормаль направлена к нам
        if (плюс ? н >= 0 : н <= 0) continue;
      }
      const мм = плюс ? a0 - моя1 : моя0 - a1;
      if (мм < -ВПЛОТНУЮ_ММ || мм > 3000) continue;
      if (!лучший || мм < лучший.мм) лучший = { мм: Math.max(0, Math.round(мм * 10) / 10), преграда: о, грань: плюс ? a0 : a1 };
    }
    return лучший;
  };
  итог.xМинус = ищем('x', false);
  итог.xПлюс = ищем('x', true);
  итог.zМинус = ищем('z', false);
  итог.zПлюс = ищем('z', true);
  return итог;
}

export interface Ниша {
  /** свободная ширина между преградами, мм */
  ширина: number;
  /** центр ниши по оси ширины изделия, мм (мир) */
  центр: number;
  ось: 'x' | 'z';
  слева: Преграда;
  справа: Преграда;
}

/**
 * Ниша для изделия: между двумя преградами по оси его ширины осталось меньше, чем ширина изделия, но не меньше минимальной.
 * Ищем от центра изделия: ближайшая преграда слева (грань не правее центра) и справа (не левее).
 */
export function найтиНишу(п: ПроектV2, э: Экземпляр, позиция?: [number, number]): Ниша | null {
  const н = окружение(п, э, позиция);
  const изд = изделиеПоИд(э.изделие);
  if (!н || !изд) return null;
  const мин = изд.границы.мин.ш;
  if (н.ширина >= э.габариты.ш - 1 || н.ширина < Math.max(мин, 100)) return null;
  return н;
}

/** Наибольший зазор, который предлагаем закрыть растяжением: больше — это уже не добор до стены, а свободное место */
export const МАКС_РАСТЯЖЕНИЕ_ММ = 300;

/**
 * Обратный случай ниши: изделие меньше проёма между преградами (зазор 3…300 мм, не больше максимума изделия) —
 * предложить растянуть до ширины проёма («Растянуть до 437»).
 */
export function найтиНишуШире(п: ПроектV2, э: Экземпляр, позиция?: [number, number]): Ниша | null {
  const н = окружение(п, э, позиция);
  const изд = изделиеПоИд(э.изделие);
  if (!н || !изд) return null;
  const запас = н.ширина - э.габариты.ш;
  if (запас < 3 || запас > МАКС_РАСТЯЖЕНИЕ_ММ || н.ширина > изд.границы.макс.ш) return null;
  return н;
}

/** Ближайшие преграды слева и справа по оси ширины изделия (в том же ряду) и ширина проёма между ними */
function окружение(п: ПроектV2, э: Экземпляр, позиция?: [number, number]): Ниша | null {
  const изд = изделиеПоИд(э.изделие);
  if (!изд || !кратен90(э.поворот)) return null;
  const эП = позиция ? { ...э, позиция: [позиция[0], э.позиция[1], позиция[1]] as Экземпляр['позиция'] } : э;
  const р = прямоугольникЭкземпляра(эП);
  const ось: 'x' | 'z' = Math.round(((э.поворот % 180) + 180) % 180) === 90 ? 'z' : 'x';
  const центр = ось === 'x' ? р.cx : р.cz;
  const глубина = ось === 'x' ? р.z1 - р.z0 : р.x1 - р.x0;
  let слева: { п: Преграда; грань: number } | null = null;
  let справа: { п: Преграда; грань: number } | null = null;
  for (const о of преградыДляПривязки(п, э.помещение, э.id)) {
    if (перекрытие(р.y0, р.y1, о.y0, о.y1) <= ПЕРЕКРЫТИЕ_ПО_ВЫСОТЕ) continue;
    const a0 = ось === 'x' ? о.x0 : о.z0;
    const a1 = ось === 'x' ? о.x1 : о.z1;
    const l0 = ось === 'x' ? о.z0 : о.x0;
    const l1 = ось === 'x' ? о.z1 : о.x1;
    // преграда должна быть в том же ряду: перекрывать не меньше трети глубины изделия
    if (перекрытие(ось === 'x' ? р.z0 : р.x0, ось === 'x' ? р.z1 : р.x1, l0, l1) < Math.min(глубина, 1000) / 3) continue;
    if (о.вид === 'стена') {
      const н = о.внутрь?.[ось === 'x' ? 0 : 1] ?? 0;
      if (н > 0 && a0 <= центр && (!слева || a0 > слева.грань)) слева = { п: о, грань: a0 };
      if (н < 0 && a0 >= центр && (!справа || a0 < справа.грань)) справа = { п: о, грань: a0 };
    } else {
      if (a1 <= центр && (!слева || a1 > слева.грань)) слева = { п: о, грань: a1 };
      if (a0 >= центр && (!справа || a0 < справа.грань)) справа = { п: о, грань: a0 };
    }
  }
  if (!слева || !справа) return null;
  const ширина = Math.round(справа.грань - слева.грань);
  return { ширина, центр: (слева.грань + справа.грань) / 2, ось, слева: слева.п, справа: справа.п };
}

/** Экземпляр, подогнанный по нише (урезан или растянут): ширина = ширина ниши, центр — центр ниши (встаёт без зазора) */
export function урезатьПоНише(э: Экземпляр, н: Ниша): Экземпляр {
  const позиция: Экземпляр['позиция'] = н.ось === 'x' ? [Math.round(н.центр * 2) / 2, э.позиция[1], э.позиция[2]] : [э.позиция[0], э.позиция[1], Math.round(н.центр * 2) / 2];
  return { ...э, габариты: { ...э.габариты, ш: н.ширина }, позиция };
}

/* ------------------------------------------------------------------ быстрые действия */

export type БыстроеДействие = 'потолок' | 'сосед' | 'центр' | 'угол' | 'фасад';
export type РезультатДействия = { экз: Экземпляр; текст: string } | { ошибка: string };

const ось90 = (э: Экземпляр): 'x' | 'z' => (Math.round(((э.поворот % 180) + 180) % 180) === 90 ? 'z' : 'x');
const сдвинутьПоОси = (э: Экземпляр, ось: 'x' | 'z', дельта: number): Экземпляр => ({
  ...э,
  позиция: ось === 'x' ? [Math.round((э.позиция[0] + дельта) * 2) / 2, э.позиция[1], э.позиция[2]] : [э.позиция[0], э.позиция[1], Math.round((э.позиция[2] + дельта) * 2) / 2],
});

/** «До потолка»: напольное тянется вверх (в пределах максимума изделия), навесное поднимается верхом к потолку */
export function доПотолка(п: ПроектV2, э: Экземпляр): РезультатДействия {
  const пом = п.помещения.find((x) => x.id === э.помещение);
  const изд = изделиеПоИд(э.изделие);
  if (!пом || !изд) return { ошибка: 'Не нашёл помещение или изделие' };
  const H = высотаДляРендера(пом);
  const навесное = изд.крепление === 'стена' || э.позиция[1] > 0;
  if (навесное) {
    const низ = Math.round(H - э.габариты.в);
    if (низ <= э.позиция[1]) return { ошибка: 'Верх уже у потолка или выше' };
    return { экз: { ...э, позиция: [э.позиция[0], низ, э.позиция[2]] }, текст: `Поднято до потолка: низ на ${низ} мм` };
  }
  const нужно = H - э.позиция[1];
  const макс = изд.границы.макс.в;
  if (нужно <= э.габариты.в) return { ошибка: 'Верх уже у потолка' };
  const высота = Math.min(нужно, макс);
  const остаток = нужно - высота;
  return {
    экз: { ...э, габариты: { ...э.габариты, в: Math.round(высота) } },
    текст: остаток > 0 ? `Растянуто до ${Math.round(высота)} мм (максимум изделия); до потолка осталось ${Math.round(остаток)} мм` : `Растянуто до потолка: высота ${Math.round(высота)} мм`,
  };
}

/** «К соседу»: сдвиг по оси ширины к ближайшей преграде (сосед или стена) вплотную */
export function кСоседу(п: ПроектV2, э: Экземпляр): РезультатДействия {
  if (!кратен90(э.поворот)) return { ошибка: 'Сначала поверните на 90° (угол должен быть кратен 90)' };
  const з = зазоры(п, э);
  const ось = ось90(э);
  const минус = ось === 'x' ? з.xМинус : з.zМинус;
  const плюс = ось === 'x' ? з.xПлюс : з.zПлюс;
  const варианты = [минус && { п: минус, знак: -1 }, плюс && { п: плюс, знак: 1 }].filter((в): в is { п: Просвет; знак: number } => !!в);
  if (!варианты.length) return { ошибка: 'Рядом по ряду нет ни соседа, ни стены' };
  варианты.sort((a, b) => a.п.мм - b.п.мм);
  const в = варианты[0];
  // ближайшая преграда уже вплотную: двигать некуда
  if (в.п.мм <= ВПЛОТНУЮ_ММ) return { ошибка: 'Уже вплотную' };
  return { экз: сдвинутьПоОси(э, ось, в.знак * в.п.мм), текст: `Придвинуто вплотную к ${в.п.преграда.вид === 'стена' ? 'стене' : `«${в.п.преграда.название}»`} (${Math.round(в.п.мм)} мм)` };
}

/** «По центру»: между ближайшими преградами слева и справа по оси ширины */
export function поЦентру(п: ПроектV2, э: Экземпляр): РезультатДействия {
  if (!кратен90(э.поворот)) return { ошибка: 'Сначала поверните на 90° (угол должен быть кратен 90)' };
  const з = зазоры(п, э);
  const ось = ось90(э);
  const минус = ось === 'x' ? з.xМинус : з.zМинус;
  const плюс = ось === 'x' ? з.xПлюс : з.zПлюс;
  if (!минус || !плюс) return { ошибка: 'Нужны преграды с обеих сторон (стена или сосед), чтобы встать между ними' };
  const общий = минус.мм + плюс.мм;
  const сдвиг = (плюс.мм - минус.мм) / 2;
  if (Math.abs(сдвиг) < 0.5) return { ошибка: 'Уже по центру' };
  return { экз: сдвинутьПоОси(э, ось, сдвиг), текст: `По центру: по ${Math.round(общий / 2)} мм с каждой стороны` };
}

/** «В угол»: к ближайшему выпуклому углу помещения вплотную к обеим стенам */
export function вУгол(п: ПроектV2, э: Экземпляр): РезультатДействия {
  const пом = п.помещения.find((x) => x.id === э.помещение);
  if (!пом) return { ошибка: 'Не нашёл помещение' };
  if (!кратен90(э.поворот)) return { ошибка: 'Сначала поверните на 90° (угол должен быть кратен 90)' };
  const р = прямоугольникЭкземпляра(э);
  const стены = рёбра(пом.контур);
  let лучший: { x: number; z: number; d: number } | null = null;
  for (let i = 0; i < стены.length; i++) {
    const а = стены[(i + стены.length - 1) % стены.length];
    const б = стены[i];
    // выпуклый угол: обе стены вдоль осей, нормали перпендикулярны и направлены внутрь
    if (Math.abs(а.нормаль[0] * б.нормаль[0] + а.нормаль[1] * б.нормаль[1]) > 1e-6) continue;
    const нx = Math.abs(а.нормаль[0]) > 0.5 ? а.нормаль[0] : б.нормаль[0];
    const нz = Math.abs(а.нормаль[1]) > 0.5 ? а.нормаль[1] : б.нормаль[1];
    if (Math.abs(нx) < 0.5 || Math.abs(нz) < 0.5) continue;
    const вершина = б.а;
    // вогнутый угол выреза Г или П не подходит: сдвинутая внутрь от вершины точка должна лежать в контуре
    if (!точкаВнутри(пом.контур, вершина[0] + Math.sign(нx) * 20, вершина[1] + Math.sign(нz) * 20)) continue;
    const x = вершина[0] + Math.sign(нx) * р.hx;
    const z = вершина[1] + Math.sign(нz) * р.hz;
    const d = Math.hypot(x - р.cx, z - р.cz);
    if (!лучший || d < лучший.d) лучший = { x, z, d };
  }
  if (!лучший) return { ошибка: 'Не нашёл подходящий угол комнаты' };
  if (лучший.d < 1) return { ошибка: 'Уже в углу' };
  return { экз: { ...э, позиция: [Math.round(лучший.x * 2) / 2, э.позиция[1], Math.round(лучший.z * 2) / 2] }, текст: 'Поставлено в ближайший угол вплотную к двум стенам' };
}

/** «Выровнять по фасаду»: передняя грань на линию фасада ближайшего соседа с тем же поворотом */
export function поФасаду(п: ПроектV2, э: Экземпляр): РезультатДействия {
  if (!кратен90(э.поворот)) return { ошибка: 'Сначала поверните на 90° (угол должен быть кратен 90)' };
  const θ = (э.поворот * Math.PI) / 180;
  // фасад смотрит в локальный +Z; при повороте на θ он смотрит в (−sin θ, cos θ) (геометрия.ts: при 90° — в −X)
  const фx = Math.round(-Math.sin(θ));
  const фz = Math.round(Math.cos(θ));
  const передняя = (о: Pick<Экземпляр, 'позиция' | 'габариты'>) => о.позиция[0] * фx + о.позиция[2] * фz + о.габариты.г / 2;
  const моя = передняя(э);
  const р = прямоугольникЭкземпляра(э);
  let лучший: { э: Экземпляр; d: number; цель: number } | null = null;
  for (const о of п.объекты) {
    if (о.id === э.id || о.помещение !== э.помещение || Math.round(((о.поворот % 360) + 360) % 360) !== Math.round(((э.поворот % 360) + 360) % 360)) continue;
    const изд = изделиеПоИд(о.изделие);
    if (!изд || !ТВЁРДЫЕ.has(изд.тип)) continue;
    const ро = прямоугольникЭкземпляра(о);
    if (перекрытие(р.y0, р.y1, ро.y0, ро.y1) <= ПЕРЕКРЫТИЕ_ПО_ВЫСОТЕ) continue;
    // сосед по ряду: расстояние между габаритами по оси ширины
    const вдольX = Math.abs(фz) === 1;
    const расст = вдольX ? Math.max(ро.x0 - р.x1, р.x0 - ро.x1, 0) : Math.max(ро.z0 - р.z1, р.z0 - ро.z1, 0);
    const поперёкПерекрытие = вдольX ? перекрытие(р.z0, р.z1, ро.z0 - 600, ро.z1 + 600) : перекрытие(р.x0, р.x1, ро.x0 - 600, ро.x1 + 600);
    if (расст > 2000 || поперёкПерекрытие <= 0) continue;
    if (!лучший || расст < лучший.d) лучший = { э: о, d: расст, цель: передняя(о) };
  }
  if (!лучший) return { ошибка: 'Рядом нет соседа с таким же поворотом, по фасаду которого можно выровнять' };
  const сдвиг = лучший.цель - моя;
  if (Math.abs(сдвиг) < 0.5) return { ошибка: 'Фасад уже на одной линии с соседом' };
  const название = лучший.э.название ?? изделиеПоИд(лучший.э.изделие)?.название ?? 'соседом';
  return {
    экз: { ...э, позиция: [Math.round((э.позиция[0] + фx * сдвиг) * 2) / 2, э.позиция[1], Math.round((э.позиция[2] + фz * сдвиг) * 2) / 2] },
    текст: `Фасад выровнен по «${название}» (${Math.round(Math.abs(сдвиг))} мм)`,
  };
}

