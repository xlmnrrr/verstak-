/**
 * Анализ стен помещения для планировщика и разбора (этап 7): что стоит на каждой стене и где ставить нельзя.
 * Отметки помещения (двери, окна, короба, щитки, радиаторы, ниши, вода, розетки) и предметы-проёмы
 * (окно и дверь из каталога, поставленные объектом) переводятся в «препятствия»: прямоугольник в плане
 * в осях стены (s — вдоль стены от её начала, t — от стены внутрь) и полоса высот.
 * Ряд мебели у стены i глубиной D занимает полосу t ∈ [0, D]; закрытые участки — проекции препятствий на эту полосу.
 * Чистая геометрия в мм, без three и DOM.
 */
import { изделиеПоИд } from './каталог';
import { стены as рёбра, высотаДляРендера, type Стена, type Точка } from './помещение';
import type { Отметка, Помещение, ПроектV2, Экземпляр } from './типы';

export interface СтенаПлана extends Стена {
  /** поворот изделия, фасад которого смотрит внутрь помещения от этой стены */
  поворот: number;
}

/** Препятствие в плане: прямоугольник в осях мира (углы) и полоса высот */
export interface Препятствие {
  вид: 'дверь' | 'арка' | 'окно' | 'короб' | 'щиток' | 'радиатор' | 'наличник' | 'предмет';
  /** стена, на которой отметка (для подписи) */
  стена: number;
  /** углы прямоугольника в плане, мм */
  углы: Точка[];
  y0: number;
  y1: number;
  /** запас вдоль стены, мм (двери и окна — 50, твёрдые препятствия — 10) */
  запас: number;
  подпись: string;
}

/** Точки «для заметок»: вода, розетки, щитки, технические ниши — их не закрывают молча */
export interface ТочкаСтены {
  вид: Отметка['вид'];
  стена: number;
  s0: number;
  s1: number;
  y0: number;
  y1: number;
  метки: string[];
  подпись: string;
}

export const нормУгол = (у: number) => Math.round(((у % 360) + 360) % 360);

/** Стены с поворотом «фасадом внутрь»: фронт(θ) = нормаль ⇒ θ = atan2(−nₓ, n_z) */
export function стеныПлана(пом: Помещение): СтенаПлана[] {
  return рёбра(пом.контур).map((с) => ({ ...с, поворот: нормУгол((Math.atan2(-с.нормаль[0], с.нормаль[1]) * 180) / Math.PI) }));
}

/** Точка мира по координатам стены */
export const точкаСтены = (с: Стена, s: number, t: number): Точка => [с.а[0] + с.направление[0] * s + с.нормаль[0] * t, с.а[1] + с.направление[1] * s + с.нормаль[1] * t];

/** Координаты стены для точки мира */
export const вОсиСтены = (с: Стена, p: Точка): [number, number] => {
  const dx = p[0] - с.а[0];
  const dz = p[1] - с.а[1];
  return [dx * с.направление[0] + dz * с.направление[1], dx * с.нормаль[0] + dz * с.нормаль[1]];
};

const прямоугольникСтены = (с: Стена, s0: number, s1: number, t0: number, t1: number): Точка[] => [
  точкаСтены(с, s0, t0),
  точкаСтены(с, s1, t0),
  точкаСтены(с, s1, t1),
  точкаСтены(с, s0, t1),
];

const НАЗВАНИЕ_СТЕНЫ = ['задняя', 'правая', 'передняя', 'левая'];
/** Подпись стены для текста: у прямоугольника — «задняя / правая / …», иначе номер */
export function имяСтены(пом: Помещение, i: number): string {
  return пом.контур.length === 4 ? `${НАЗВАНИЕ_СТЕНЫ[i]} стена` : `стена ${i + 1}`;
}

/** Предметы-проёмы (окно, дверь из каталога) как отметки на ближайшей стене */
export function проёмыИзПредметов(п: { объекты: Экземпляр[] }, пом: Помещение): Отметка[] {
  const ст = стеныПлана(пом);
  const итог: Отметка[] = [];
  for (const э of п.объекты) {
    if (э.помещение !== пом.id) continue;
    const изд = изделиеПоИд(э.изделие);
    if (!изд || изд.тип !== 'проём') continue;
    const ц: Точка = [э.позиция[0], э.позиция[2]];
    let лучшая: { i: number; s: number; t: number } | null = null;
    for (const с of ст) {
      const [s, t] = вОсиСтены(с, ц);
      if (s < -50 || s > с.длина + 50 || Math.abs(t) > 200) continue;
      if (!лучшая || Math.abs(t) < Math.abs(лучшая.t)) лучшая = { i: с.индекс, s, t };
    }
    if (!лучшая) continue;
    const окно = изд.id.startsWith('окно');
    итог.push({
      id: `предмет:${э.id}`,
      стена: лучшая.i,
      вид: окно ? 'окно' : 'дверь',
      от_угла: Math.round(лучшая.s - э.габариты.ш / 2),
      от_пола: Math.round(э.позиция[1]),
      ширина: э.габариты.ш,
      высота: э.габариты.в,
      заметка: э.название ?? изд.название,
    });
  }
  return итог;
}

/** Все отметки помещения вместе с предметами-проёмами */
export const отметкиСПредметами = (п: { объекты: Экземпляр[] }, пом: Помещение): Отметка[] => [...пом.отметки, ...проёмыИзПредметов(п, пом)];

function подписьОтметки(пом: Помещение, о: Отметка): string {
  const где = `${имяСтены(пом, о.стена)}, ${о.от_угла} мм от угла`;
  switch (о.вид) {
    case 'дверь':
      return `дверь ${о.ширина} мм (${где})`;
    case 'арка':
      return `арка ${о.ширина} мм (${где})`;
    case 'окно':
      return `окно ${о.ширина} мм, подоконник ${о.от_пола} (${где})`;
    case 'радиатор':
      return `радиатор ${о.ширина} мм (${где})`;
    case 'короб':
      return `короб ${о.ширина} × ${о.высота} на ${о.от_пола} от пола (${где})`;
    case 'щиток':
      return `щиток ${о.от_пола}–${о.от_пола + о.высота} (${где})`;
    case 'наличник':
      return `наличник ${о.ширина} мм (${где})`;
    default:
      return `${о.вид} (${где})`;
  }
}

/**
 * Препятствия помещения для расстановки. Дверь и арка закрывают стену и площадку перед собой (створка + 50 мм),
 * окно — полосу 100 мм у стены по своей высоте, радиатор — пол перед собой, короб, щиток и наличник — себя по высоте.
 */
export function препятствияРасстановки(п: { объекты: Экземпляр[] }, пом: Помещение, щитокПрепятствие = true): Препятствие[] {
  const ст = стеныПлана(пом);
  const H = высотаДляРендера(пом);
  const итог: Препятствие[] = [];
  for (const о of отметкиСПредметами(п, пом)) {
    const с = ст[о.стена];
    if (!с) continue;
    const s0 = о.от_угла;
    const s1 = о.от_угла + о.ширина;
    const подпись = подписьОтметки(пом, о);
    if (о.вид === 'дверь' || о.вид === 'арка') {
      const внутрь = о.вид === 'дверь' && о.открывание !== 'наружу';
      const глубина = внутрь ? о.ширина + 50 : 600;
      итог.push({ вид: о.вид, стена: о.стена, углы: прямоугольникСтены(с, s0 - 50, s1 + 50, -50, глубина), y0: 0, y1: H, запас: 0, подпись });
    } else if (о.вид === 'окно') {
      итог.push({ вид: 'окно', стена: о.стена, углы: прямоугольникСтены(с, s0 - 50, s1 + 50, -50, 100), y0: о.от_пола + 10, y1: о.от_пола + о.высота, запас: 0, подпись });
    } else if (о.вид === 'радиатор') {
      const г = о.глубина ?? 100;
      итог.push({ вид: 'радиатор', стена: о.стена, углы: прямоугольникСтены(с, s0 - 50, s1 + 50, -50, г + 50), y0: 0, y1: о.от_пола + о.высота + 50, запас: 0, подпись });
    } else if (о.вид === 'короб' || (о.вид === 'щиток' && щитокПрепятствие) || о.вид === 'наличник') {
      const г = о.глубина ?? (о.вид === 'короб' ? 300 : 12);
      const выс = о.вид === 'короб' && о.высота <= 0 ? H - о.от_пола : о.высота;
      итог.push({ вид: о.вид, стена: о.стена, углы: прямоугольникСтены(с, s0 - 10, s1 + 10, -50, г + 10), y0: о.от_пола, y1: о.от_пола + выс, запас: 0, подпись });
    }
  }
  return итог;
}

/** Точки, которые мебель может закрыть: вода, канализация, розетки, выключатели, щитки, технические ниши */
export function точкиПомещения(пом: Помещение): ТочкаСтены[] {
  return пом.отметки
    .filter((о) => ['вода', 'канализация', 'розетка', 'выключатель', 'щиток', 'ниша'].includes(о.вид))
    .map((о) => ({ вид: о.вид, стена: о.стена, s0: о.от_угла, s1: о.от_угла + о.ширина, y0: о.от_пола, y1: о.от_пола + о.высота, метки: о.метки ?? [], подпись: подписьОтметки(пом, о) }));
}

/** Закрытые участки полосы стены [t 0..D] в полосе высот [y0, y1]: интервалы s с причинами, слитые и отсортированные */
export function закрытыеУчастки(с: Стена, препятствия: Препятствие[], D: number, y0: number, y1: number): { s0: number; s1: number; причины: Препятствие[] }[] {
  const сырые: { s0: number; s1: number; п: Препятствие }[] = [];
  for (const пр of препятствия) {
    if (пр.y1 <= y0 + 1 || пр.y0 >= y1 - 1) continue;
    const оси = пр.углы.map((у) => вОсиСтены(с, у));
    const t0 = Math.min(...оси.map((о) => о[1]));
    const t1 = Math.max(...оси.map((о) => о[1]));
    if (t1 <= 1 || t0 >= D - 1) continue;
    const s0 = Math.min(...оси.map((о) => о[0]));
    const s1 = Math.max(...оси.map((о) => о[0]));
    if (s1 <= 0 || s0 >= с.длина) continue;
    сырые.push({ s0: Math.max(0, s0), s1: Math.min(с.длина, s1), п: пр });
  }
  сырые.sort((a, b) => a.s0 - b.s0);
  const итог: { s0: number; s1: number; причины: Препятствие[] }[] = [];
  for (const р of сырые) {
    const п = итог[итог.length - 1];
    if (п && р.s0 <= п.s1) {
      п.s1 = Math.max(п.s1, р.s1);
      п.причины.push(р.п);
    } else итог.push({ s0: р.s0, s1: р.s1, причины: [р.п] });
  }
  return итог;
}

/** Свободные отрезки стены [a, b] за вычетом закрытых участков */
export function свободныеОтрезки(a: number, b: number, закрыто: { s0: number; s1: number }[]): [number, number][] {
  const итог: [number, number][] = [];
  let x = a;
  for (const з of закрыто) {
    if (з.s1 <= x) continue;
    if (з.s0 >= b) break;
    if (з.s0 > x) итог.push([x, Math.min(з.s0, b)]);
    x = Math.max(x, з.s1);
  }
  if (x < b) итог.push([x, b]);
  return итог.filter(([p, q]) => q - p > 0.5);
}

/** Выпуклый угол 90° между стеной i и следующей: направление следующей совпадает с нормалью этой */
export function уголПрямой(ст: СтенаПлана[], i: number): boolean {
  const а = ст[i];
  const б = ст[(i + 1) % ст.length];
  return а.нормаль[0] * б.направление[0] + а.нормаль[1] * б.направление[1] > 0.999;
}

/** Расстояние от стены внутрь до противоположной стороны контура (по середине отрезка s) */
export function глубинаПеред(пом: Помещение, с: Стена, s: number): number {
  const о = точкаСтены(с, s, 1);
  let лучший = Infinity;
  const к = пом.контур;
  for (let i = 0; i < к.length; i++) {
    const a = к[i];
    const b = к[(i + 1) % к.length];
    // пересечение луча о + n·t с отрезком ab
    const ex = b[0] - a[0];
    const ez = b[1] - a[1];
    const den = с.нормаль[0] * ez - с.нормаль[1] * ex;
    if (Math.abs(den) < 1e-9) continue;
    const t = ((a[0] - о[0]) * ez - (a[1] - о[1]) * ex) / den;
    const u = ((a[0] - о[0]) * с.нормаль[1] - (a[1] - о[1]) * с.нормаль[0]) / den;
    if (t > 1 && u >= -1e-6 && u <= 1 + 1e-6) лучший = Math.min(лучший, t + 1);
  }
  return лучший;
}
