/**
 * Свободная правка стен: сдвиг стены, вырез угла (Г-образное помещение как на рисунке Макара), выступ и ниша, точка на стене,
 * удаление угла; отметки остаются на месте в комнате; площадь, периметр, стены без проёмов.
 */
import { describe, expect, it } from 'vitest';
import { новоеПомещение, прямоугольник, знаковаяПлощадь, стены } from './помещение';
import { выступ, обмерПомещения, ошибкаКонтура, передвинутьУгол, сдвинутьСтену, точкаНаСтене, удалитьУгол } from './контур-правка';
import { новаяОтметка, сОтметкой } from './отметки';

const комната = () => новоеПомещение('п1', 'кухня', 'Кухня', прямоугольник(3600, 2800, false));
const площадь = (к: [number, number][]) => Math.round(Math.abs(знаковаяПлощадь(к)) / 1e4) / 100;

describe('правка стен', () => {
  it('сдвиг стены внутрь и наружу: прямоугольник остаётся прямоугольником', () => {
    const р = сдвинутьСтену(комната(), 1, 400);
    expect(р.ошибка).toBeNull();
    expect(р.помещение.контур).toHaveLength(4);
    expect(площадь(р.помещение.контур)).toBeCloseTo(3.2 * 2.8, 2);
    const н = сдвинутьСтену(комната(), 0, -200);
    expect(площадь(н.помещение.контур)).toBeCloseTo(3.6 * 3.0, 2);
  });

  it('вырез угла (выступ от самого угла): Г-образное помещение из 6 стен, площадь меньше на вырез', () => {
    // левая стена (3) идёт от переднего угла к заднему: вырез у переднего угла 900 вдоль стены, 700 внутрь
    const р = выступ(комната(), 3, 0, 900, 700);
    expect(р.ошибка).toBeNull();
    expect(р.помещение.контур).toHaveLength(6);
    expect(площадь(р.помещение.контур)).toBeCloseTo(3.6 * 2.8 - 0.9 * 0.7, 2);
  });

  it('выступ посреди стены (короб) — 8 стен; ниша наружу — площадь больше', () => {
    const к = выступ(комната(), 0, 1200, 400, 300);
    expect(к.помещение.контур).toHaveLength(8);
    expect(площадь(к.помещение.контур)).toBeCloseTo(3.6 * 2.8 - 0.4 * 0.3, 2);
    const н = выступ(комната(), 0, 1200, 600, -250);
    expect(площадь(н.помещение.контур)).toBeCloseTo(3.6 * 2.8 + 0.6 * 0.25, 2);
  });

  it('точка на стене, её перемещение и удаление угла', () => {
    const т = точкаНаСтене(комната(), 2, 1800);
    expect(т.помещение.контур).toHaveLength(5);
    const ид = т.помещение.контур.findIndex((p) => p[0] === 1800);
    const у = передвинутьУгол(т.помещение, ид, 1800, 2400);
    expect(у.ошибка).toBeNull();
    expect(у.помещение.контур).toHaveLength(5);
    const назад = удалитьУгол(у.помещение, ид);
    expect(назад.помещение.контур).toHaveLength(4);
  });

  it('перекрученный контур и короткие стены — ошибка с цифрами, помещение прежнее', () => {
    const к = комната();
    const р = передвинутьУгол(к, 0, 1800, 3500);
    expect(р.ошибка).toMatch(/пересекаются/);
    expect(р.помещение).toBe(к);
    expect(ошибкаКонтура([[0, 0], [30, 0], [30, 30]])).toMatch(/короче 50 мм/);
  });

  it('отметки после правки остаются на месте в комнате (переносятся на новую стену)', () => {
    let п = комната();
    п = сОтметкой(п, новаяОтметка(п, 'розетка', 3, { от_угла: 2000 }));
    const р = выступ(п, 3, 0, 900, 700);
    const о = р.помещение.отметки[0];
    expect(о.вид).toBe('розетка');
    // левая стена была x = 0 от z = 2800 к z = 0; розетка в z = 800 − 40 … осталась на левой стене (x = 0)
    const стенаX = р.помещение.контур[о.стена][0];
    expect(стенаX).toBe(0);
  });

  it('стена не уезжает за соседнюю: соседняя не выворачивается, угол остаётся прямым', () => {
    const г = выступ(комната(), 3, 0, 900, 700).помещение;
    // стена выреза, параллельная левой (x = 700), — тянем наружу на 800: короткая соседняя (700) вывернулась бы
    const i = стены(г.контур).findIndex((с) => Math.abs(с.а[0] - 700) < 1 && Math.abs(с.направление[0]) < 1e-6);
    const р = сдвинутьСтену(г, i, -800);
    expect(р.ошибка).toMatch(/кончилась/);
    expect(р.помещение).toBe(г);
    const ок = сдвинутьСтену(г, i, -300);
    expect(ок.ошибка).toBeNull();
    for (const с of стены(ок.помещение.контур)) expect(Math.abs(с.направление[0]) < 1e-9 || Math.abs(с.направление[1]) < 1e-9).toBe(true);
  });

  it('обмер: пол, периметр, стены без проёмов', () => {
    let п = комната();
    п = сОтметкой(п, новаяОтметка(п, 'дверь', 2));
    const о = обмерПомещения(п);
    expect(о.полМ2).toBeCloseTo(10.08, 2);
    expect(о.периметрМ).toBeCloseTo(12.8, 2);
    expect(о.стеныМ2).toBeCloseTo(12.8 * 2.7 - 0.8 * 2.0, 2);
  });
});
