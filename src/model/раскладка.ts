/** Раскладка: слияние отличий, авто-полки (шаг 320, перестановка 32), ширины секций, число створок. */
import { зажать, кШагу, окр } from './геометрия';
import type { Раскладка, ЧастичнаяРаскладка, Секция, Фасад, КорпусРаскладки } from './типы';

export const ШАГ_ПОЛОК = 320;
export const ПЕРЕСТАНОВКА = 32;
export const ВЫСОТА_ЯЩИКА = 180;

export const фасадПоУмолчанию = (): Фасад => ({
  тип: 'нет',
  створок: 'авто',
  ящиков: 0,
  петли: 'слева',
  ручка: { вид: 'скоба', место: 'край' },
});

export const корпусПоУмолчанию = (): КорпусРаскладки => ({
  плита: 16,
  задник: 'ХДФ',
  цоколь: 0,
  ножки: 0,
  боковины: true,
});

export const секцияПоУмолчанию = (): Секция => ({
  ширина: 'доля',
  наполнение: { направление: 'снизу-вверх', число: 0, тип: 'регулируемая' },
});

/** Глубокая копия раскладки (JSON-данные) */
export const копияРаскладки = (р: Раскладка): Раскладка => JSON.parse(JSON.stringify(р));

/** Базовая раскладка изделия + отличия экземпляра. Исходные объекты не меняются. */
export function слитьРаскладку(база: Раскладка, отличия?: ЧастичнаяРаскладка): Раскладка {
  const итог = копияРаскладки(база);
  if (!отличия) return итог;
  if (отличия.корпус) Object.assign(итог.корпус, отличия.корпус);
  if (отличия.секции) итог.секции = JSON.parse(JSON.stringify(отличия.секции));
  if (отличия.фасад) {
    const { ручка, ...остальное } = отличия.фасад;
    Object.assign(итог.фасад, остальное);
    if (ручка) Object.assign(итог.фасад.ручка, ручка);
  }
  return итог;
}

/**
 * «Авто»: сколько полок влезает при шаге 320 мм.
 * Формула совпадает с v1 (`автоПолки`), чтобы числа старых проектов не менялись:
 * внутренняя высота = высота − цоколь − 2 плиты.
 */
export function автоПолки(высота: number, цоколь = 0, плита = 16): number {
  const внутренняя = высота - цоколь - плита * 2;
  if (внутренняя < 200) return 0;
  return Math.max(0, Math.floor(внутренняя / ШАГ_ПОЛОК) - 1);
}

/** Сколько полок в секции: число или авто. Для «слева-направо» авто считается по ширине секции. */
export function числоПолок(
  с: Секция,
  высота: number,
  цоколь: number,
  плита: number,
  ширинаСекции = 0,
): number {
  const ч = с.наполнение.число;
  if (typeof ч === 'number') return Math.max(0, Math.floor(ч));
  if (с.наполнение.направление === 'слева-направо') {
    const внутр = ширинаСекции - 0;
    return внутр < 200 ? 0 : Math.max(0, Math.floor(внутр / ШАГ_ПОЛОК) - 1);
  }
  return автоПолки(высота, цоколь, плита);
}

/** Ширины секций в мм: фиксированные остаются, «доля» делит остаток по весам. Сумма = доступная ширина. */
export function ширинысекций(секции: Секция[], доступно: number): number[] {
  const n = секции.length;
  if (!n) return [];
  const фикс = секции.map((с) => (typeof с.ширина === 'number' ? с.ширина : 0));
  let суммаФикс = фикс.reduce((a, b) => a + b, 0);
  const веса = секции.map((с) => (с.ширина === 'доля' ? (с.вес ?? 1) : 0));
  const суммаВесов = веса.reduce((a, b) => a + b, 0);

  // фиксированные не помещаются — сжимаем пропорционально
  if (суммаФикс > доступно || (суммаВесов === 0 && суммаФикс !== доступно)) {
    const к = доступно / (суммаФикс || 1);
    const шир = фикс.map((f) => f * к);
    return округлитьСумма(шир, доступно);
  }
  const остаток = доступно - суммаФикс;
  const шир = секции.map((_, i) => (веса[i] > 0 ? (остаток * веса[i]) / суммаВесов : фикс[i]));
  суммаФикс = 0;
  return округлитьСумма(шир, доступно);
}

/** Округлить до мм так, чтобы сумма осталась ровно `итого` (остаток — в последнюю секцию) */
function округлитьСумма(шир: number[], итого: number): number[] {
  const р = шир.map((w) => окр(w));
  const разница = окр(итого) - р.reduce((a, b) => a + b, 0);
  if (р.length) р[р.length - 1] += разница;
  return р;
}

/** Число створок распашного фасада: «авто» — одна до 600 мм, дальше по 600 мм на створку */
export function створокРаспашного(ш: number, заданo: number | 'авто'): number {
  if (typeof заданo === 'number') return Math.max(1, Math.floor(заданo));
  return ш <= 600 ? 1 : Math.ceil(ш / 600);
}

/** Число створок купе: «авто» — по 900 мм на створку, не меньше двух */
export function створокКупе(ш: number, заданo: number | 'авто'): number {
  if (typeof заданo === 'number') return Math.max(2, Math.floor(заданo));
  return Math.max(2, Math.ceil(ш / 900));
}

/** Позиции полок по высоте (центры, мм от низа изделия) внутри свободного промежутка [низ, верх] */
export function позицииПолок(n: number, низ: number, верх: number, толщина: number): number[] {
  if (n <= 0 || верх <= низ) return [];
  // больше, чем влезает вплотную (с зазором в одну плиту), не ставим
  n = Math.min(n, Math.floor((верх - низ) / (толщина * 2)));
  if (n <= 0) return [];
  const шаг = (верх - низ) / (n + 1);
  const рез: number[] = [];
  for (let i = 1; i <= n; i++) {
    // центр полки привязывается к перестановке 32 мм от нижней кромки промежутка
    let y = низ + кШагу(шаг * i, ПЕРЕСТАНОВКА);
    y = зажать(y, низ + толщина / 2, верх - толщина / 2);
    рез.push(y);
  }
  // привязка могла сблизить соседние полки: раздвигаем снизу вверх, потом прижимаем к верху
  for (let i = 1; i < n; i++) рез[i] = Math.max(рез[i], рез[i - 1] + толщина * 1.5);
  for (let i = n - 1; i >= 0; i--) {
    const предел = i === n - 1 ? верх - толщина / 2 : рез[i + 1] - толщина * 1.5;
    рез[i] = Math.min(рез[i], предел);
  }
  return рез;
}

/** Высота одного ящика: «авто» — заполнить свободное место (фасад «ящики») или стандартные 180 мм */
export function высотаЯщика(
  я: { число: number; высота: number | 'авто' },
  свободно: number,
  заполнять: boolean,
): number {
  const желаемая = я.высота === 'авто' ? (заполнять ? свободно / я.число : ВЫСОТА_ЯЩИКА) : я.высота;
  return Math.max(60, Math.min(желаемая, свободно / я.число));
}
