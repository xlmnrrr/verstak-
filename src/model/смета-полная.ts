/**
 * Полная смета (пожелание Макара 13.11.2026: «проработай смету прям хорошо, значения не только в мм, а и в см и м»).
 * Всё считается из тех же деталей и движений, что рисует 3D (`детали()`, `движенияИзделия()`), и из обмера помещения.
 * Цены — мастера: вводятся в окне «Смета» и помнятся на этом компьютере; пустая цена — строка без суммы.
 *
 * Нормы расхода (типовые, можно оспорить — тогда меняется константа и тест):
 *  - ЛДСП: лист 2750 × 1830, отход на раскрой 15 %, покупка целыми листами;
 *  - ХДФ: лист 2800 × 2070, отход 10 %;
 *  - кромка: +10 % на торцовку и запуск станка;
 *  - петли по высоте двери: до 900 — 2, до 1600 — 3, до 2000 — 4, выше — 5 (как рисует 3D);
 *  - полкодержатели — 4 на съёмную полку; ножки — 4 на модуль на ножках, 6 — шире 1000;
 *  - ламинат +7 % на подрезку, плинтус — периметр без дверных проёмов, багет натяжного потолка — периметр.
 */
import { детали } from './детали';
import { изделиеПоИд } from './каталог';
import { движенияИзделия } from './открывание';
import { слитьРаскладку } from './раскладка';
import { обмерПомещения } from './контур-правка';
import type { ПроектV2 } from './типы';

export const ЛИСТ_ЛДСП_М2 = (2750 * 1830) / 1e6;
export const ЛИСТ_ХДФ_М2 = (2800 * 2070) / 1e6;
export const ОТХОД_ЛДСП = 0.15;
export const ОТХОД_ХДФ = 0.1;
export const ЗАПАС_КРОМКИ = 0.1;
export const ЗАПАС_ПОЛА = 0.07;

/** Сколько петель на дверь высотой h, мм (то же правило рисует 3D: render/модели/фурнитура.ts) */
export const числоПетель = (h: number) => (h <= 900 ? 2 : h <= 1600 ? 3 : h <= 2000 ? 4 : 5);

export type ГруппаСметы = 'Плиты и кромка' | 'Фасады, стекло, столешница' | 'Фурнитура' | 'Свет и сантехника' | 'Помещение' | 'Работы';
export const ГРУППЫ_СМЕТЫ: ГруппаСметы[] = ['Плиты и кромка', 'Фасады, стекло, столешница', 'Фурнитура', 'Свет и сантехника', 'Помещение', 'Работы'];

export type ЕдиницаСметы = 'лист' | 'м²' | 'м' | 'шт' | 'пара' | 'компл';

export interface СтрокаСметы {
  группа: ГруппаСметы;
  /** ключ цены (помнится между проектами) */
  ключ: string;
  название: string;
  /** количество к покупке в своей единице (листы — целые, с отходом) */
  количество: number;
  единица: ЕдиницаСметы;
  /** для длин: сколько это в мм — окно показывает мм, см и м */
  мм?: number;
  /** как посчитано: «5,8 м² по деталям + 15 % отход» */
  пояснение: string;
}

export interface ИтогСметы {
  строки: СтрокаСметы[];
  изделий: number;
  деталей: number;
}

/** Строки сметы по проекту или одному помещению (без цен: цены прикладывает окно) */
export function полнаяСмета(п: ПроектV2, помещениеId?: string): ИтогСметы {
  const н = {
    корпусМ2: 0,
    фасадМ2: 0,
    хдфМ2: 0,
    кромка04: 0,
    кромка2: 0,
    столешницаМм: 0,
    стеклоМ2: 0,
    зеркалоМ2: 0,
    петли: 0,
    ручки: 0,
    направляющие: 0,
    газлифты: 0,
    купеДверей: 0,
    купеШиринаМм: 0,
    штангаМм: 0,
    полки: 0,
    ножки: 0,
    карусели: 0,
    модулей: 0,
    деталей: 0,
  };
  const штучные = new Map<string, { название: string; группа: ГруппаСметы; n: number }>();
  let изделий = 0;
  const объекты = п.объекты.filter((э) => !помещениеId || э.помещение === помещениеId);
  for (const э of объекты) {
    const изд = изделиеПоИд(э.изделие);
    if (!изд) continue;
    изделий++;
    // свет, сантехника, техника, декор — штуками
    if (изд.тип === 'свет' || изд.конструкция === 'сантехника' || изд.тип === 'техника') {
      const г: ГруппаСметы = 'Свет и сантехника';
      const ш = штучные.get(изд.id) ?? { название: изд.название, группа: г, n: 0 };
      ш.n++;
      штучные.set(изд.id, ш);
      if (изд.тип !== 'техника') continue;
    }
    if (изд.тип === 'проём' || изд.тип === 'декор') continue;
    const дет = детали(изд, э);
    н.деталей += дет.length;
    const корпусной = дет.some((д) => д.роль === 'боковина');
    if (корпусной) н.модулей++;
    for (const д of дет) {
      const [L, W, T] = д.размер;
      const м2 = (L * W) / 1e6;
      const к = д.кромка;
      const кромкаМм = (к.длина1 > 0 ? L : 0) + (к.длина2 > 0 ? L : 0) + (к.ширина1 > 0 ? W : 0) + (к.ширина2 > 0 ? W : 0);
      const толстая = Math.max(к.длина1, к.длина2, к.ширина1, к.ширина2) >= 1;
      switch (д.роль) {
        case 'задник':
        case 'ящик-дно':
          н.хдфМ2 += м2;
          break;
        case 'столешница':
          if (T > 30) н.столешницаМм += L;
          else н.корпусМ2 += м2;
          break;
        case 'стекло':
          н.стеклоМ2 += м2;
          break;
        case 'зеркало':
          н.зеркалоМ2 += м2;
          break;
        case 'штанга':
          н.штангаМм += L;
          break;
        case 'ручка':
          н.ручки++;
          break;
        case 'фасад':
        case 'ящик-фасад':
          if (д.форма !== 'плита') break;
          if (д.материал === 'стекло' || д.материал === 'зеркало') {
            if (д.материал === 'стекло') н.стеклоМ2 += м2;
            else н.зеркалоМ2 += м2;
            break;
          }
          н.фасадМ2 += м2;
          if (толстая) н.кромка2 += кромкаМм;
          else н.кромка04 += кромкаМм;
          break;
        case 'полка':
          н.полки++;
          н.корпусМ2 += м2;
          н.кромка04 += кромкаМм;
          break;
        case 'фурнитура':
        case 'техника':
        case 'объём':
        case 'проём':
          break;
        default:
          if (д.форма !== 'плита' || T > 30) break;
          н.корпусМ2 += м2;
          if (толстая) н.кромка2 += кромкаМм;
          else н.кромка04 += кромкаМм;
      }
    }
    // фурнитура по движениям: петли, направляющие, газлифты, купе
    for (const дв of движенияИзделия(изд, э)) {
      if (дв.вид === 'дверь') н.петли += числоПетель(дв.главная.объём[1]);
      else if (дв.вид === 'ящик') н.направляющие++;
      else if (дв.вид === 'подъёмник') н.газлифты += 2;
      else if (дв.вид === 'купе') {
        н.купеДверей++;
        н.купеШиринаМм = Math.max(н.купеШиринаМм, э.габариты.ш);
      }
    }
    const р = слитьРаскладку(изд.раскладка, э.раскладка);
    if (корпусной && (р.корпус.ножки ?? 0) > 0) н.ножки += э.габариты.ш > 1000 ? 6 : 4;
    if (изд.угловой) н.карусели++;
  }

  const с: СтрокаСметы[] = [];
  const доб = (группа: ГруппаСметы, ключ: string, название: string, количество: number, единица: ЕдиницаСметы, пояснение: string, мм?: number) => {
    if (количество > 0) с.push({ группа, ключ, название, количество, единица, пояснение, ...(мм !== undefined ? { мм } : {}) });
  };
  const дробь = (v: number, n = 2) => String(Math.round(v * 10 ** n) / 10 ** n).replace('.', ',');

  // плиты и кромка
  const листыЛДСП = Math.ceil(((н.корпусМ2 * (1 + ОТХОД_ЛДСП)) / ЛИСТ_ЛДСП_М2) * 100) / 100;
  доб('Плиты и кромка', 'лдсп-корпус', 'ЛДСП корпус 16 мм, лист 2750 × 1830', Math.ceil(листыЛДСП), 'лист', `${дробь(н.корпусМ2)} м² по деталям + ${ОТХОД_ЛДСП * 100} % отход = ${дробь(листыЛДСП)} листа`);
  const листыХДФ = (н.хдфМ2 * (1 + ОТХОД_ХДФ)) / ЛИСТ_ХДФ_М2;
  доб('Плиты и кромка', 'хдф', 'ХДФ задники и дно ящиков, лист 2800 × 2070', Math.ceil(листыХДФ), 'лист', `${дробь(н.хдфМ2)} м² + ${ОТХОД_ХДФ * 100} % = ${дробь(листыХДФ)} листа`);
  const к04 = н.кромка04 * (1 + ЗАПАС_КРОМКИ);
  доб('Плиты и кромка', 'кромка-04', 'Кромка ПВХ 0,4 мм', Math.ceil(к04 / 1000), 'м', `${дробь(н.кромка04 / 1000)} м по деталям + ${ЗАПАС_КРОМКИ * 100} %`, Math.round(к04));
  const к2 = н.кромка2 * (1 + ЗАПАС_КРОМКИ);
  доб('Плиты и кромка', 'кромка-2', 'Кромка ПВХ 2 мм', Math.ceil(к2 / 1000), 'м', `${дробь(н.кромка2 / 1000)} м по деталям + ${ЗАПАС_КРОМКИ * 100} %`, Math.round(к2));

  // фасады, стекло, столешница
  доб('Фасады, стекло, столешница', 'фасады', 'Фасады', Math.round(н.фасадМ2 * 100) / 100, 'м²', `фасады дверей и ящиков; в листы корпуса не входят — из ЛДСП это ≈ ${дробь((н.фасадМ2 * (1 + ОТХОД_ЛДСП)) / ЛИСТ_ЛДСП_М2)} листа с отходом`);
  доб('Фасады, стекло, столешница', 'столешница', 'Столешница 38 мм', Math.round(н.столешницаМм / 10) / 100, 'м', 'погонные метры по длине', Math.round(н.столешницаМм));
  доб('Фасады, стекло, столешница', 'стекло', 'Стекло', Math.round(н.стеклоМ2 * 100) / 100, 'м²', 'вставки, полки, перегородки');
  доб('Фасады, стекло, столешница', 'зеркало', 'Зеркало', Math.round(н.зеркалоМ2 * 100) / 100, 'м²', 'зеркальные фасады и вставки');

  // фурнитура
  доб('Фурнитура', 'петли', 'Петли мебельные с доводчиком', н.петли, 'шт', 'по высоте каждой двери: до 900 — 2, до 1600 — 3, до 2000 — 4, выше — 5');
  доб('Фурнитура', 'ручки', 'Ручки', н.ручки, 'шт', 'по одной на дверь и ящик, где ручка задана');
  доб('Фурнитура', 'направляющие', 'Направляющие ящиков', н.направляющие, 'пара', 'пара на ящик');
  доб('Фурнитура', 'газлифты', 'Газлифты (подъёмники)', н.газлифты, 'шт', 'два на подъёмный фасад или основание кровати');
  if (н.купеДверей) {
    доб('Фурнитура', 'купе-ролики', 'Ролики купе (комплект на дверь)', н.купеДверей, 'компл', 'верхние и нижние ролики, стопоры');
    доб('Фурнитура', 'купе-профиль', 'Направляющие купе, верх и низ', Math.ceil((н.купеШиринаМм * 2) / 1000), 'м', 'по ширине шкафа, две направляющие', н.купеШиринаМм * 2);
  }
  доб('Фурнитура', 'штанга', 'Штанга Ø25 с держателями', Math.ceil(н.штангаМм / 100) / 10, 'м', 'по длине штанг', Math.round(н.штангаМм));
  доб('Фурнитура', 'полкодержатели', 'Полкодержатели', н.полки * 4, 'шт', '4 на полку');
  доб('Фурнитура', 'ножки', 'Опоры регулируемые', н.ножки, 'шт', '4 на модуль на ножках, 6 — шире 1000 мм');
  доб('Фурнитура', 'карусели', 'Карусель 3/4 угловая', н.карусели, 'компл', 'угловые тумбы с каруселью');
  доб('Фурнитура', 'крепёж', 'Крепёж на модуль (конфирматы, шканты, евровинты)', н.модулей, 'компл', 'комплект на каждый корпус');

  // свет и сантехника — штуками
  for (const [ид, ш] of штучные) доб(ш.группа, `шт:${ид}`, ш.название, ш.n, 'шт', 'по проекту');

  // помещение: обмер с натяжным потолком, полом, стенами, плинтусом
  const помещения = п.помещения.filter((x) => !помещениеId || x.id === помещениеId);
  let пол = 0;
  let стены = 0;
  let периметр = 0;
  let плинтус = 0;
  let потолок = 0;
  let багет = 0;
  for (const пом of помещения) {
    const о = обмерПомещения(пом);
    пол += о.полМ2;
    стены += о.стеныМ2;
    периметр += о.периметрМ;
    const двери = пом.отметки.filter((x) => x.вид === 'дверь' || x.вид === 'арка').reduce((s, x) => s + x.ширина, 0) / 1000;
    плинтус += Math.max(0, о.периметрМ - двери);
    if (пом.натяжной_потолок) {
      потолок += о.полМ2;
      багет += о.периметрМ;
    }
  }
  доб('Помещение', 'пол', 'Напольное покрытие', Math.round(пол * (1 + ЗАПАС_ПОЛА) * 100) / 100, 'м²', `${дробь(пол)} м² пола + ${ЗАПАС_ПОЛА * 100} % на подрезку`);
  доб('Помещение', 'стены', 'Стены: обои или покраска', Math.round(стены * 100) / 100, 'м²', 'периметр × высота минус двери, окна и арки');
  доб('Помещение', 'плинтус', 'Плинтус', Math.ceil(плинтус * 10) / 10, 'м', 'периметр без дверных проёмов', Math.round(плинтус * 1000));
  доб('Помещение', 'потолок-натяжной', 'Натяжной потолок (полотно и монтаж)', Math.round(потолок * 100) / 100, 'м²', 'по площади пола');
  доб('Помещение', 'багет', 'Багет натяжного потолка', Math.ceil(багет * 10) / 10, 'м', 'по периметру', Math.round(багет * 1000));
  void периметр;

  // работы
  доб('Работы', 'сборка', 'Сборка и установка модуля', н.модулей, 'шт', 'каждый корпус');
  const светильников = [...штучные.entries()].filter(([ид]) => изделиеПоИд(ид)?.тип === 'свет').reduce((s, [, ш]) => s + ш.n, 0);
  доб('Работы', 'монтаж-света', 'Установка светильника', светильников, 'шт', 'врезка в полотно, подключение');

  return { строки: с, изделий, деталей: н.деталей };
}

/** Сумма строки по цене (нет цены — null) */
export const суммаСтроки = (с: СтрокаСметы, цена: number | undefined) => (цена && цена > 0 ? Math.round(с.количество * цена * 100) / 100 : null);
