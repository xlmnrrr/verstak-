const ТИП_ЗАГОЛОВОК: Record<ТипПланировки, string> = { линейная: 'Линейная', угловая: 'Угловая', 'П-образная': 'П-образная' };

function числа(п: ПроектV2, помId: string, з: Замечание[]): ЧислаВарианта {
  const с = смета(п, помId);
  const св = сводка(з);
  const столешница = п.объекты.filter((э) => э.помещение === помId && изделиеПоИд(э.изделие)?.тип === 'столешница' && !э.изделие.startsWith('подоконник')).reduce((s, э) => s + э.габариты.ш, 0);
  return {
    столешницаМ: м1(столешница / 1000),
    листов: м1(с.листов),
    кромкаМ: м1(с.кромкаМ),
    деталей: с.деталей,
    изделий: с.изделий,
    ошибок: св.ошибка,
    предупреждений: св.предупреждение,
    советов: св.совет,
    замечаний: з.length,
  };
}

const СЪЁМНЫЕ = new Set(['навесной-600', 'свободный-корпус', 'стеллаж-открытый-800']);
/** Что из прежней обстановки помещения переносится в вариант, если не мешает: стол, стулья, свет, декор, мягкая мебель */
const ПЕРЕНОСИМЫЕ = new Set<Изделие['тип']>(['стол', 'стул', 'свет', 'декор', 'мягкая']);

/**
 * Проект с вариантом в помещении: остаются проёмы-предметы (окна, двери) и переносимая обстановка (стол, стулья, свет,
 * декор), корпуса и техника заменяются вариантом. Затем цикл исправлений: петли и зазор из «Проверок»; навесной,
 * полки или перенесённый предмет, которые всё равно мешают, убираются с пометкой.
 */
function проектВарианта(к: Контекст, ставки: Ставка[], префикс: string, учтено: string[]): { п: ПроектV2; з: Замечание[] } {
  let п = копияПроекта(к.п);
  const перенесённые = new Set<string>();
  const оставить = п.объекты.filter((э) => {
    if (э.помещение !== к.пом.id) return true;
    const тип = изделиеПоИд(э.изделие)?.тип;
    if (тип && ПЕРЕНОСИМЫЕ.has(тип)) перенесённые.add(э.id);
    return тип === 'проём' || (!!тип && ПЕРЕНОСИМЫЕ.has(тип));
  });
  п.объекты = [...оставить, ...ставки.map((с, n) => вЭкземпляр(с, к.пом.id, `${префикс}-${n + 1}`))];
  // перенесённое, что стоит на месте нового ряда, убираем сразу (стол поверх тумб не двигаем — это решает мастер)
  const съёмный = (о: Экземпляр | undefined) => !!о && (СЪЁМНЫЕ.has(о.изделие) || перенесённые.has(о.id));
  let з = проверитьПроект(п).filter((x) => x.помещение === к.пом.id);
  for (let шаг = 0; шаг < 40 && з.length; шаг++) {
    let исправлено = false;
    for (const x of з) {
      if (x.правило !== 'открывание' || !x.id) continue;
      const и = исправленияОткрывания(п, x.id);
      const выбор = и.find((v) => v.вид === 'петли') ?? и[0];
      if (выбор) {
        п = { ...п, объекты: п.объекты.map((о) => (о.id === выбор.результат.id ? выбор.результат : о)) };
        исправлено = true;
        break;
      }
    }
    if (!исправлено) {
      // сначала перенесённая обстановка (стол, стулья), потом навесные и полки варианта
      const участники = з.flatMap((x) => [x.id, ...(x.с ?? [])]).map((id) => п.объекты.find((о) => о.id === id));
      const мешает = участники.find((о) => о && перенесённые.has(о.id)) ?? участники.find(съёмный);
      if (!мешает) break;
      const почему = з.find((x) => x.id === мешает.id || x.с?.includes(мешает.id))?.текст ?? 'мешал';
      учтено.push(`${мешает.название ?? изделиеПоИд(мешает.изделие)?.название ?? 'Модуль'} убран из варианта: ${почему.replace(/\.$/, '')}.`);
      п = { ...п, объекты: п.объекты.filter((о) => о.id !== мешает.id) };
    }
    з = проверитьПроект(п).filter((x) => x.помещение === к.пом.id);
  }
  return { п, з };
}

/** Заметки по точкам на стенах: вода, розетки и щитки за мебелью, технические ниши */
function заметкиТочек(к: Контекст, п: ПроектV2): string[] {
  const итог: string[] = [];
  const мебель = п.объекты.filter((э) => э.помещение === к.пом.id && ['корпус', 'техника'].includes(изделиеПоИд(э.изделие)?.тип ?? ''));
  for (const т of точкиПомещения(к.пом)) {
    const с = к.ст[т.стена];
    if (!с) continue;
    const середина = точкаСтены(с, (т.s0 + т.s1) / 2, 5);
    const за = мебель.find((э) => {
      const dx = середина[0] - э.позиция[0];
      const dz = середина[1] - э.позиция[2];
      const θ = (э.поворот * Math.PI) / 180;
      const lx = dx * Math.cos(θ) + dz * Math.sin(θ);
      const lz = -dx * Math.sin(θ) + dz * Math.cos(θ);
      return Math.abs(lx) <= э.габариты.ш / 2 && Math.abs(lz) <= э.габариты.г / 2 + 20 && т.y1 > э.позиция[1] && т.y0 < э.позиция[1] + э.габариты.в;
    });
    if (!за) continue;
    const имя = за.название ?? изделиеПоИд(за.изделие)?.название ?? 'модуль';
    if (т.вид === 'розетка' || т.вид === 'выключатель') итог.push(`${т.подпись[0].toUpperCase()}${т.подпись.slice(1)} — за «${имя}»: вырез ${Math.round(т.s1 - т.s0 + 20)} × ${Math.round(т.y1 - т.y0 + 20)} мм в задней стенке на ${т.y0} мм от пола.`);
    else if (т.вид === 'щиток') итог.push(`${т.подпись[0].toUpperCase()}${т.подпись.slice(1)} — внутри «${имя}»: в этой зоне без задника и полок, доступ через створку.`);
    else if (т.вид === 'ниша') итог.push(`${т.подпись[0].toUpperCase()}${т.подпись.slice(1)}${т.метки.includes('запретная-зона') ? ' — запретная зона' : ''}: закрыта «${имя}», нужен вырез или съёмная панель ${Math.round(т.s1 - т.s0)} × ${Math.round(т.y1 - т.y0)} мм.`);
    else if (т.вид === 'вода' || т.вид === 'канализация') итог.push(`${т.подпись[0].toUpperCase()}${т.подпись.slice(1)} — за «${имя}»: вырез в задней стенке под трубы.`);
  }
  return итог;
}

function заметкиПроёмов(к: Контекст): string[] {
  const итог: string[] = [];
  for (const пр of к.преп) {
    if (пр.вид === 'дверь' || пр.вид === 'арка') итог.push(`${пр.подпись[0].toUpperCase()}${пр.подпись.slice(1)}: стена и площадка открывания свободны.`);
    else if (пр.вид === 'окно') итог.push(`${пр.подпись[0].toUpperCase()}${пр.подпись.slice(1)}: высокие и навесные не перед окном.`);
    else if (пр.вид === 'радиатор') итог.push(`${пр.подпись[0].toUpperCase()}${пр.подпись.slice(1)}: перед ним мебели нет.`);
  }
  return итог;
}

/** Ниша — помещение уже 900 мм: в неё встаёт только один ряд */
export function назначениеПомещения(пом: Помещение): Назначение {
  const г = границыКонтура(пом.контур);
  if (Math.min(г.ш, г.г) <= 900) return 'ниша';
  return пом.тип === 'кухня' ? 'кухня' : 'хранение';
}

const БУКВЫ = ['А', 'Б', 'В', 'Г'];

/** Главная функция: 2–3 варианта для помещения проекта */
export function предложитьПланировки(п: ПроектV2, помещениеId?: string): ИтогПланировки {
  const пом = п.помещения.find((x) => x.id === помещениеId) ?? п.помещения[0];
  const к = контекст(п, пом);
  const назначение = назначениеПомещения(пом);
  const отказы: ОтказПланировки[] = [];
  const заготовки: { тип: ТипПланировки; заголовок: string; описание: string; ставки: Ставка[]; учтено: string[] }[] = [];

  if (назначение === 'кухня') {
    const стены = к.ст.map((с) => с.индекс).sort((a, b) => к.ст[b].длина - к.ст[a].длина);
    const подобрать = (тип: ТипПланировки, построить: (сПММ: boolean) => Кандидат[]) => {
      for (const сПММ of [true, false]) {
        const кандидаты = построить(сПММ).sort((a, b) => a.штраф - b.штраф);
        // первый, у которого после исправлений ноль замечаний; иначе лучший по штрафу
        let лучший: { к: Кандидат; з: number } | null = null;
        // сначала кандидаты с треугольником в норме; если таких нет — лучшие из остальных
        const хорошие = кандидаты.filter((x) => x.штраф < 5000);
        for (const кн of (хорошие.length ? хорошие : кандидаты).slice(0, 60)) {
          const пробное = проектВарианта(к, кн.ставки, 'проба', []);
          if (!лучший || пробное.з.length < лучший.з) лучший = { к: кн, з: пробное.з.length };
          if (!пробное.з.length) break;
        }
        if (лучший && (лучший.з === 0 || !сПММ)) {
          const т = оценкаТреугольника(лучший.к.ставки);
          const учтено = [...лучший.к.учтено];
          if (т.стороны.length) {
            учтено.push(
              т.линия
                ? `Рабочая линия: мойка, плита и холодильник в один ряд, между мойкой и плитой не меньше ${К.междуМойкойИПлитой} мм.`
                : `Треугольник: мойка — плита ${ммВм(т.стороны[0])}, плита — холодильник ${ммВм(т.стороны[1])}, холодильник — мойка ${ммВм(т.стороны[2])}, сумма ${ммВм(т.стороны.reduce((s, x) => s + x, 0))} (норма стороны 1,2–2,1 м, сумма 3,0–6,6 м).`,
            );
          }
          const в = доВоды(к, лучший.к.ставки);
          if (в !== null) учтено.push(`Мойка в ${Math.round(в)} мм от точки воды.`);
          if (!сПММ) учтено.push(`Посудомойка не встала: перед ней нужно ${НОРМЫ.передПосудомойкой} мм свободного места или длиннее ряд.`);
          заготовки.push({ тип, заголовок: `${ТИП_ЗАГОЛОВОК[тип]} кухня`, описание: лучший.к.описание, ставки: лучший.к.ставки, учтено });
          return;
        }
      }
      if (!заготовки.some((x) => x.тип === тип)) отказы.push({ тип: ТИП_ЗАГОЛОВОК[тип], причина: причинаОтказаКухни(к, тип) });
    };
    подобрать('линейная', (сПММ) => линейныеКандидаты(к, стены, сПММ));
    подобрать('угловая', (сПММ) => угловыеКандидаты(к, сПММ));
    подобрать('П-образная', (сПММ) => пКандидаты(к, сПММ));
  } else if (назначение === 'хранение') {
    хранение(к, заготовки, отказы);
  } else {
    ниша(к, заготовки, отказы);
  }

  const общие = заметкиПроёмов(к);
  const варианты: ВариантПланировки[] = заготовки.slice(0, 3).map((з, n) => {
    const буква = БУКВЫ[n];
    const учтено = [...общие, ...з.учтено];
    const { п: пв, з: замечания } = проектВарианта(к, з.ставки, `вар${буква}`, учтено);
    учтено.push(...заметкиТочек(к, пв));
    пв.название = `${п.название} — вариант ${буква}, ${з.тип}`;
    пв.изменён = new Date().toISOString();
    пв.прочее = { ...(пв.прочее ?? {}), вариант: { основа: п.название, буква, тип: з.тип, помещение: пом.id } };
    return {
      буква,
      тип: з.тип,
      заголовок: з.заголовок,
      описание: з.описание,
      проект: пв,
      помещение: пом.id,
      числа: числа(пв, пом.id, замечания),
      замечания,
      учтено,
      чисто: замечания.length === 0,
    };
  });
  return { назначение, помещение: пом.id, варианты, отказы };
}

function причинаОтказаКухни(к: Контекст, тип: ТипПланировки): string {
  const длины = к.ст.map((с) => Math.round(с.длина));
  if (тип === 'линейная') {
    const макс = Math.max(0, ...к.ст.map((с) => {
      const о = лучшийОтрезок(к, с.индекс);
      return о ? о[1] - о[0] : 0;
    }));
    return `нет свободной стены от ${600 + 600 + К.междуМойкойИПлитой + 600 + К.отПлиты} мм (холодильник, мойка, ${К.междуМойкойИПлитой} рабочей поверхности, плита, ${К.отПлиты} до стены): самый длинный свободный участок ${Math.round(макс)} мм.`;
  }
  if (тип === 'угловая') return `нет двух соседних стен под прямым углом со свободными участками от угла не короче 1800 мм (стены ${длины.join(' / ')} мм, двери и окна у углов) или ряды мешают друг другу.`;
  const ш = Math.min(...к.ст.map((с) => с.длина));
  return `между боковыми рядами должно остаться ${НОРМЫ.проход} мм прохода (${НОРМЫ.передХолодильником} перед холодильником): при ширине ${Math.round(ш)} мм и рядах по ${К.глубинаНиза} мм остаётся ${Math.round(ш - 2 * К.глубинаНиза)} мм.`;
}

/** Хранение в комнате: линейная (купе вдоль стены), угловая и П-образная (открытые системы) */
function хранение(к: Контекст, заготовки: { тип: ТипПланировки; заголовок: string; описание: string; ставки: Ставка[]; учтено: string[] }[], отказы: ОтказПланировки[]) {
  const h = Math.round(Math.min(2700, к.H - ЗАЗОР_ПОТОЛКА));
  const n = к.ст.length;
  // главная стена: длинная и без дверей
  const оценка = (i: number) => {
    const о = отрезки(к, i, 600, 0, h);
    return о.reduce((s, [a, b]) => s + (b - a), 0) + (i === 0 ? 1 : 0);
  };
  const главная = [...к.ст.keys()].sort((a, b) => оценка(b) - оценка(a))[0];
  const г0 = глубинаХранения(к, главная, false);
  // линейная
  {
    const учтено: string[] = [];
    if (г0 < 450) отказы.push({ тип: 'Линейная', причина: `перед стеной ${Math.round(глубинаПеред(к.пом, к.ст[главная], к.ст[главная].длина / 2))} мм: шкафу 450 и проходу ${НОРМЫ.проход} не хватает места.` });
    else {
      const наполнение: Наполнение = г0 >= 450 ? 'купе' : 'система';
      const ряд = рядХранения(к, главная, 0, к.ст[главная].длина, г0, h, наполнение, учтено);
      if (ряд) {
        учтено.push(`Проход перед шкафом ${Math.round(глубинаПеред(к.пом, к.ст[главная], к.ст[главная].длина / 2) - г0)} мм (норма ${НОРМЫ.проход}).`);
        заготовки.push({ тип: 'линейная', заголовок: `Линейная: ${названиеРяда(ряд)}`, описание: `${имяСтены(к.пом, главная)} ${Math.round(к.ст[главная].длина)} мм, глубина ${г0}, высота ${h}`, ставки: ряд, учтено });
      }
    }
  }
  // угловая и П: главная + соседние, открытые системы
  const следующая = (главная + 1) % n;
  const предыдущая = (главная + n - 1) % n;
  const гСистемы = Math.min(г0, 550);
  const бок = (i: number, отНачала: boolean, г: number, учтено: string[]): Ставка[] | null => {
    const с = к.ст[i];
    const a = отНачала ? гСистемы : 0;
    const b = отНачала ? с.длина : с.длина - гСистемы;
    return рядХранения(к, i, a, b, г, h, 'система', учтено);
  };
  if (гСистемы < 350) {
    отказы.push({ тип: 'Угловая', причина: `глубина системы меньше 350 мм при проходе ${НОРМЫ.проход}.` });
    отказы.push({ тип: 'П-образная', причина: `глубина системы меньше 350 мм при проходе ${НОРМЫ.проход}.` });
    return;
  }
  const сторонаУгловой = уголПрямой(к.ст, главная) ? следующая : уголПрямой(к.ст, предыдущая) ? предыдущая : null;
  if (сторонаУгловой === null) отказы.push({ тип: 'Угловая', причина: 'у главной стены нет прямого угла.' });
  else {
    const учтено: string[] = [];
    const перед = глубинаПеред(к.пом, к.ст[сторонаУгловой], к.ст[сторонаУгловой].длина / 2);
    const гБок = Math.min(гСистемы, Math.floor((перед - НОРМЫ.проход) / 10) * 10);
    const главный = рядХранения(к, главная, 0, к.ст[главная].длина, гСистемы, h, 'система', учтено);
    const боковой = гБок >= 350 ? бок(сторонаУгловой, сторонаУгловой === следующая, гБок, учтено) : null;
    if (главный && боковой) {
      учтено.push(`Угол: боковой ряд начинается за главным (${гСистемы} мм), без нахлёста.`);
      заготовки.push({ тип: 'угловая', заголовок: 'Угловая: открытая система', описание: `${имяСтены(к.пом, главная)} + ${имяСтены(к.пом, сторонаУгловой)}, глубина ${гСистемы} / ${гБок}, высота ${h}`, ставки: [...главный, ...боковой], учтено });
    } else отказы.push({ тип: 'Угловая', причина: `на соседней стене нет свободного участка от 300 мм (глубина ${гБок} мм при проходе ${НОРМЫ.проход}).` });
  }
  if (!уголПрямой(к.ст, главная) || !уголПрямой(к.ст, предыдущая)) отказы.push({ тип: 'П-образная', причина: 'у главной стены нет двух прямых углов.' });
  else {
    const учтено: string[] = [];
    const ширина = к.ст[главная].длина;
    const гБок = Math.min(гСистемы, Math.floor((ширина - НОРМЫ.проход) / 2 / 10) * 10);
    if (гБок < 300) отказы.push({ тип: 'П-образная', причина: `между боковыми рядами нужно ${НОРМЫ.проход} мм: при стене ${Math.round(ширина)} мм на ряды остаётся по ${Math.round((ширина - НОРМЫ.проход) / 2)} мм.` });
    else {
      const главный = рядХранения(к, главная, 0, ширина, гСистемы, h, 'система', учтено);
      const правый = бок(следующая, true, гБок, учтено);
      const левый = бок(предыдущая, false, гБок, учтено);
      if (главный && правый && левый) {
        учтено.push(`Проход между боковыми рядами ${Math.round(ширина - 2 * гБок)} мм (норма ${НОРМЫ.проход}).`);
        заготовки.push({ тип: 'П-образная', заголовок: 'П-образная: открытая система', описание: `${имяСтены(к.пом, предыдущая)} + ${имяСтены(к.пом, главная)} + ${имяСтены(к.пом, следующая)}, глубина ${гСистемы} / ${гБок}, высота ${h}`, ставки: [...главный, ...правый, ...левый], учтено });
      } else отказы.push({ тип: 'П-образная', причина: 'на боковой стене нет свободного участка от 300 мм (двери, наличники, короба).' });
    }
  }
}

/** Ниша: один ряд во всю ширину; варианты — разное наполнение */
function ниша(к: Контекст, заготовки: { тип: ТипПланировки; заголовок: string; описание: string; ставки: Ставка[]; учтено: string[] }[], отказы: ОтказПланировки[]) {
  const г = границыКонтура(к.пом.контур);
  // главная стена — самая длинная из двух длинных (задняя у ниши)
  const главная = [...к.ст.keys()].sort((a, b) => к.ст[b].длина - к.ст[a].длина || a - b)[0];
  const глубина = глубинаХранения(к, главная, true);
  const h = Math.round(Math.min(2700, к.H - ЗАЗОР_ПОТОЛКА));
  const длина = к.ст[главная].длина;
  const набор: Наполнение[] = длина >= 900 && глубина >= 450 ? ['купе', 'в-нишу', 'система'] : ['в-нишу', 'система'];
  const виденные = new Set<string>();
  for (const н of набор) {
    const учтено: string[] = [`Высота ${h} мм: ${ЗАЗОР_ПОТОЛКА} мм до потолка на сборку (шкаф ставят наклоном).`];
    const ряд = рядХранения(к, главная, 0, длина, глубина, h, н, учтено);
    if (!ряд) continue;
    const ключ = ряд.map((с) => `${с.изд}:${Math.round(с.s0)}`).join('|');
    if (виденные.has(ключ)) continue;
    виденные.add(ключ);
    заготовки.push({ тип: 'линейная', заголовок: `Линейная: ${названиеРяда(ряд)}`, описание: `${имяСтены(к.пом, главная)} ${Math.round(длина)} мм, глубина ${глубина}, высота ${h}`, ставки: ряд, учтено });
  }
  отказы.push({ тип: 'Угловая и П-образная', причина: `в нишу ${Math.round(г.ш)} × ${Math.round(г.г)} мм встаёт только один ряд: второй стене не хватает места на шкаф и проход ${НОРМЫ.проход} мм.` });
}
