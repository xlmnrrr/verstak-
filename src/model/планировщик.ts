function вЭкземпляр(с: Ставка, помещение: string, id: string): Экземпляр {
  const центр = точкаСтены(с.стена, (с.s0 + с.s1) / 2, (с.t0 ?? 0) + с.г / 2);
  const э: Экземпляр = {
    id,
    изделие: с.изд,
    помещение,
    позиция: [Math.round(центр[0] * 10) / 10, с.y, Math.round(центр[1] * 10) / 10],
    поворот: с.стена.поворот,
    габариты: { ш: Math.round((с.s1 - с.s0) * 10) / 10, г: с.г, в: с.в },
  };
  if (с.раскладка) э.раскладка = с.раскладка;
  if (с.материалы) э.материалы = с.материалы;
  if (с.название) э.название = с.название;
  return э;
}

/** Длина на куски не шире `макс` и не уже `мин` поровну (пусто, если длина меньше минимума) */
function куски(длина: number, мин: number, макс: number): number[] {
  if (длина < мин - 0.5) return [];
  const n = Math.max(1, Math.ceil(длина / макс - 1e-9));
  // целые миллиметры: остаток от деления — последнему куску (в цеху ширины целые)
  const ш = Math.floor(длина / n);
  return Array.from({ length: n }, (_, i) => (i < n - 1 ? ш : длина - ш * (n - 1)));
}

