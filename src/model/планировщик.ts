/**
 * Разложить слоты по отрезку [a, b] модулей: фиксированные — по 600, растяжки делят остаток по долям
 * (не меньше своего минимума; растяжка «0» исчезает целиком, если ей досталось меньше 150 мм).
 * Возвращает ставки или null, если не помещается.
 */
function разложить(р: Ряд, слоты: Слот[], к: Контекст): Ставка[] | null {
  const ставки = разложитьБезПроверки(р, слоты);
  if (!ставки) return null;
  // высокий холодильник не встаёт перед окном и под коробом: проверяем его полосу высот отдельно
  for (const с of ставки) {
    if (с.роль !== 'холодильник') continue;
    const закрыто = закрытыеУчастки(с.стена, к.преп, с.г, 0, с.в);
    if (закрыто.some((з) => з.s1 > с.s0 + 1 && з.s0 < с.s1 - 1)) return null;
  }
  return ставки;
}

function разложитьБезПроверки(р: Ряд, слоты: Слот[]): Ставка[] | null {
  const L = р.m1 - р.m0;
  const фикс = слоты.reduce((s, x) => s + (x.вид === 'растяжка' ? x.мин : ИД[x.вид].ш), 0);
  if (фикс > L + 0.5) return null;
  const растяжки = слоты.filter((x): x is Extract<Слот, { вид: 'растяжка' }> => x.вид === 'растяжка');
  const сумДоль = растяжки.reduce((s, x) => s + x.доля, 0) || 1;
  let остаток = L - фикс;
  const длины = new Map<Слот, number>();
  for (const x of растяжки) длины.set(x, x.мин + (остаток * x.доля) / сумДоль);
  // растяжки меньше 150 мм — отдаём соседней растяжке, чтобы не было щелей и «модулей» по 40 мм
  for (const x of растяжки) {
    const д = длины.get(x)!;
    if (д > 0.5 && д < 150) {
      const кому = растяжки.find((y) => y !== x && (длины.get(y) ?? 0) >= 150) ?? растяжки.find((y) => y !== x);
      if (!кому) return null;
      длины.set(кому, (длины.get(кому) ?? 0) + д);
      длины.set(x, 0);
    }
  }
  // целые миллиметры: все растяжки вниз до целого, остаток — последней ненулевой (ряд по-прежнему без щелей)
  const ненулевые = растяжки.filter((x) => (длины.get(x) ?? 0) > 0.5);
  if (ненулевые.length) {
    const последняя = ненулевые[ненулевые.length - 1];
    let сумма = 0;
    for (const x of ненулевые) {
      if (x === последняя) continue;
      const ц = Math.floor(длины.get(x)!);
      длины.set(x, ц);
      сумма += ц;
    }
    длины.set(последняя, Math.round((L - фикс + растяжки.reduce((s2, x) => s2 + x.мин, 0) - сумма) * 1000) / 1000);
  }
  остаток = 0;
  const итог: Ставка[] = [];
  let s = р.m0;
  for (const x of слоты) {
    if (x.вид === 'растяжка') {
      const д = длины.get(x) ?? 0;
      for (const ш of куски(д, 150, 600)) {
        итог.push(низ(р, s, s + ш, ш >= 300 ? 'тумба-ящики-600' : 'тумба-нижняя-400', 'ящики'));
        s += ш;
      }
      if (д > 0.5 && д < 150) s += д;
    } else {
      const и = ИД[x.вид];
      итог.push(низ(р, s, s + и.ш, и.изд, и.роль));
      s += и.ш;
    }
  }
  return итог;
}

function низ(р: Ряд, s0: number, s1: number, изд: string, роль: Ставка['роль']): Ставка {
  if (роль === 'холодильник') return { изд, стена: р.стена, s0, s1, г: К.холодильник.г, y: 0, в: К.холодильник.в, роль, название: 'Холодильник' };
  if (роль === 'посудомойка') return { изд, стена: р.стена, s0, s1, г: 550, y: 0, в: 820, роль, материалы: { фасад: ФАСАД_НИЗА } };
  return { изд, стена: р.стена, s0, s1, г: К.глубинаКорпуса, y: 0, в: К.высотаНиза, роль, материалы: { фасад: ФАСАД_НИЗА } };
}

/** Столешница, мойка, варочная и вытяжка по готовым модулям ряда */
function надстройка(к: Контекст, р: Ряд, модули: Ставка[]): Ставка[] {
  const итог: Ставка[] = [];
  // столешница — по ряду, но не над холодильником; длиннее 4000 — двумя кусками
  const холод = модули.filter((м) => м.роль === 'холодильник');
  let отрезкиСтол: [number, number][] = [[р.w0, р.w1]];
  for (const х of холод) отрезкиСтол = отрезкиСтол.flatMap(([a, b]) => свободныеОтрезки(a, b, [{ s0: х.s0, s1: х.s1 }]));
  for (const [a, b] of отрезкиСтол) {
    for (const [i, ш] of куски(b - a, 150, 4000).entries()) {
      const s0 = a + i * ш;
      итог.push({ изд: 'столешница-3000', стена: р.стена, s0, s1: s0 + ш, г: К.глубинаНиза, y: К.высотаНиза, в: К.столешница, роль: 'столешница', материалы: { столешница: СТОЛЕШНИЦА } });
    }
  }
  const верх = К.высотаНиза + К.столешница;
  for (const м of модули) {
    const ц = (м.s0 + м.s1) / 2;
    // мойка по ширине тумбы: у мойки 580 на тумбе 600 рядом с холодильником остаётся щель 10 мм — это замечание «щель в ряду»
    if (м.роль === 'мойка-тумба') итог.push({ изд: 'мойка-врезная-780', стена: р.стена, s0: м.s0, s1: м.s1, t0: 75, г: 450, y: верх, в: 200, роль: 'мойка', название: 'Мойка' });
    if (м.роль === 'плита-тумба') {
      итог.push({ изд: 'варочная-панель-580', стена: р.стена, s0: ц - 290, s1: ц + 290, t0: 45, г: 510, y: верх, в: 55, роль: 'варочная', название: 'Варочная панель' });
      const yВ = Math.max(верх + 650, Math.min(1600, к.H - 760 - 50));
      if (к.H - yВ >= 760) итог.push({ изд: 'вытяжка-купольная-600', стена: р.стена, s0: ц - 300, s1: ц + 300, г: 500, y: yВ, в: 750, роль: 'вытяжка', название: 'Вытяжка' });
    }
  }
  return итог;
}

/** Навесные над рядом: не над окном, не у вытяжки и холодильника (отступ 150), не в зоне двери; куски ≤ 600 (одна створка) */
function навесные(к: Контекст, р: Ряд, модули: Ставка[], надстр: Ставка[]): Ставка[] {
  if (к.H < К.низНавесных + К.высотаНавесных + 30) return [];
  const и = р.стена.индекс;
  const свобода = отрезки(к, и, К.глубинаНавесных, К.низНавесных, К.низНавесных + К.высотаНавесных);
  const исключить = [...модули.filter((м) => м.роль === 'холодильник'), ...надстр.filter((м) => м.роль === 'вытяжка')].map((м) => ({ s0: м.s0 - К.отступНавесныхОтВысоких, s1: м.s1 + К.отступНавесныхОтВысоких }));
  исключить.sort((a, b) => a.s0 - b.s0);
  const итог: Ставка[] = [];
  for (const [a, b] of свобода) {
    const a2 = Math.max(a, р.w0);
    const b2 = Math.min(b, р.w1);
    for (const [x, y] of свободныеОтрезки(a2, b2, исключить)) {
      let s = x;
      for (const ш of куски(y - x, 300, 600)) {
        итог.push({ изд: 'навесной-600', стена: р.стена, s0: s, s1: s + ш, г: К.глубинаНавесных, y: К.низНавесных, в: К.высотаНавесных, роль: 'навесной', материалы: { фасад: ФАСАД_ВЕРХА } });
        s += ш;
      }
    }
  }
  return итог;
}

/** Самый длинный свободный отрезок низа на стене */
function лучшийОтрезок(к: Контекст, i: number): [number, number] | null {
  const оо = отрезки(к, i, К.глубинаНиза, 0, ВЕРХ_НИЗА);
  if (!оо.length) return null;
  return оо.reduce((л, x) => (x[1] - x[0] > л[1] - л[0] ? x : л));
}

const центрРоли = (вс: Ставка[], роль: Ставка['роль']): Точка | null => {
  const м = вс.find((x) => x.роль === роль);
  return м ? точкаСтены(м.стена, (м.s0 + м.s1) / 2, (м.t0 ?? 0) + м.г / 2) : null;
};

/** Треугольник мойка — плита — холодильник: годится ли по нормам валидатора (или все в одну линию с зазором ≥ 400) */
function оценкаТреугольника(вс: Ставка[]): { годится: boolean; стороны: number[]; линия: boolean } {
  const м = центрРоли(вс, 'мойка');
  const п = центрРоли(вс, 'варочная');
  const х = центрРоли(вс, 'холодильник');
  if (!м || !п || !х) return { годится: false, стороны: [], линия: false };
  const d = (a: Точка, b: Точка) => Math.hypot(a[0] - b[0], a[1] - b[1]);
  const стороны = [d(м, п), d(п, х), d(х, м)];
  const площадь2 = Math.abs((п[0] - м[0]) * (х[1] - м[1]) - (х[0] - м[0]) * (п[1] - м[1]));
  const высота = площадь2 / Math.max(...стороны);
  if (высота < 400) return { годится: true, стороны, линия: true };
  const сумма = стороны.reduce((s, x) => s + x, 0);
  const годится = стороны.every((x) => x >= НОРМЫ.треугольникСторонаМин && x <= НОРМЫ.треугольникСторонаМакс) && сумма >= НОРМЫ.треугольникСуммаМин && сумма <= НОРМЫ.треугольникСуммаМакс;
  return { годится, стороны, линия: false };
}

/** Расстояние от мойки до ближайшей воды (мм) или null, если воды на плане нет */
function доВоды(к: Контекст, вс: Ставка[]): number | null {
  const м = вс.find((x) => x.роль === 'мойка-тумба');
  if (!м || !к.вода.length) return null;
  const ц = точкаСтены(м.стена, (м.s0 + м.s1) / 2, 0);
  return Math.min(...к.вода.map((в) => {
    const т = точкаСтены(к.ст[в.стена], в.s, 0);
    return Math.hypot(т[0] - ц[0], т[1] - ц[1]);
  }));
}

/** Кандидат кухни: все ставки и пояснение */
interface Кандидат {
  ставки: Ставка[];
  описание: string;
  учтено: string[];
  /** чем меньше, тем лучше (вода, треугольник) */
  штраф: number;
}

/** Модули плюс надстройка и навесные над главным рядом */
function собратьКухню(к: Контекст, ряды: { р: Ряд; модули: Ставка[] }[], главный: number): Ставка[] {
  const вс: Ставка[] = [];
  const надВсе: Ставка[] = [];
  for (const { р, модули } of ряды) {
    вс.push(...модули);
    const н = надстройка(к, р, модули);
    надВсе.push(...н);
    вс.push(...н);
  }
  const { р, модули } = ряды[главный];
  вс.push(...навесные(к, р, модули, надВсе.filter((x) => x.стена === р.стена)));
  return вс;
}

/** Штраф кандидата: треугольник не в норме — сразу в конец; дальше вода, потом длиннее ряд — лучше */
function штрафКухни(к: Контекст, вс: Ставка[], неЛиния = false): number {
  const т = оценкаТреугольника(вс);
  const в = доВоды(к, вс);
  const длина = вс.filter((с) => с.роль !== 'столешница' && с.роль !== 'мойка' && с.роль !== 'варочная' && с.роль !== 'вытяжка' && с.роль !== 'навесной').reduce((s, с) => s + (с.s1 - с.s0), 0);
  // угловая и П, где мойка, плита и холодильник всё равно в одну линию, — хуже: от такой лучше линейная
  return (т.годится ? 0 : 10000) + (в ?? 0) - длина * 0.1 + (неЛиния && т.линия ? 600 : 0);
}

const рС = (мин: number, доля: number): Слот => ({ вид: 'растяжка', мин, доля });
const СЛОТ_Х: Слот = { вид: 'Х' };
const СЛОТ_П: Слот = { вид: 'П' };
const слотыМойки = (сПММ: boolean): Слот[] => [{ вид: 'М' }, ...(сПММ ? [{ вид: 'Д' } as Слот] : [])];

/** Длины ряда для перебора: весь отрезок и укороченные (ряд не обязан занимать всю стену: так сходится треугольник, обходится радиатор) */
const длиныРяда = (полная: number, варианты: number[]) => [полная, ...варианты.filter((x) => x < полная - 1)];

/** Линейная: один ряд у стены, холодильник с краю, мойка ближе к воде, между мойкой и плитой ≥ 400 */
function линейныеКандидаты(к: Контекст, стены: number[], сПММ: boolean): Кандидат[] {
  const итог: Кандидат[] = [];
  for (const i of стены) {
    const о = лучшийОтрезок(к, i);
    if (!о) continue;
    for (const отступA of [0, 300, 600]) {
      for (const отступB of [0, 300, 600]) {
        const р: Ряд = { стена: к.ст[i], w0: о[0] + отступA, w1: о[1] - отступB, m0: о[0] + отступA, m1: о[1] - отступB };
        if (р.m1 - р.m0 < 2000) continue;
        for (const холодСлева of [true, false]) {
          const сХолодильником: Слот[] = [СЛОТ_Х, рС(0, 1), ...слотыМойки(сПММ), рС(К.междуМойкойИПлитой, 2), СЛОТ_П, рС(К.отПлиты, 1)];
          const слоты = холодСлева ? сХолодильником : [...сХолодильником].reverse();
          const модули = разложить(р, слоты, к);
          if (!модули) continue;
          const вс = собратьКухню(к, [{ р, модули }], 0);
          итог.push({ ставки: вс, описание: `${имяСтены(к.пом, i)}: ряд ${Math.round(р.w1 - р.w0)} мм`, учтено: [], штраф: штрафКухни(к, вс) });
        }
      }
    }
  }
  return итог;
}

type Предмет = 'М' | 'П';
/** Отступ у угла: не меньше 300 мм ящиков (дверца у угла упиралась бы в соседний ряд) */
const У_УГЛА = Math.max(300, К.отПлиты);
/** Рядом с угловой тумбой (низкая, под столешницей) хватает 150 мм: дверцы соседей на 110° её не задевают */
const У_ТУМБЫ = 150;

/** Мойка и плита в заданном порядке, между ними ≥ 400 рабочей поверхности */
function тело(предметы: Предмет[], сПММ: boolean): Слот[] {
  const с: Слот[] = [];
  предметы.forEach((x, k) => {
    if (k > 0) с.push(рС(К.междуМойкойИПлитой, 2));
    if (x === 'М') с.push(...слотыМойки(сПММ));
    else с.push(СЛОТ_П);
  });
  return с;
}

/** Ряд, который кончается у угла: [Х?][растяжка][мойка/плита][растяжка у угла]; плита не ближе 300 к холодильнику и стене */
function кУглу(предметы: Предмет[], холод: boolean, сПММ: boolean, доляУгла: number, уУгла = У_УГЛА): Слот[] {
  const перваяПлита = предметы[0] === 'П';
  const т = тело(предметы, сПММ);
  return [...(холод ? [СЛОТ_Х] : []), рС(перваяПлита ? К.отПлиты : 0, 1), ...т, рС(уУгла, доляУгла)];
}

/** Ряд, который начинается у угла: зеркально «к углу» (холодильник на дальнем, открытом конце) */
const отУгла = (предметы: Предмет[], холод: boolean, сПММ: boolean, доляУгла: number, уУгла = У_УГЛА): Слот[] => кУглу([...предметы].reverse(), холод, сПММ, доляУгла, уУгла).reverse();

/** Ряд между двумя углами (средняя стена П): [растяжка у угла][мойка/плита][растяжка у угла] */
const междуУглами = (предметы: Предмет[], сПММ: boolean, доляДо: number, доляПосле: number, уУгла = У_УГЛА): Слот[] => [рС(уУгла, доляДо), ...тело(предметы, сПММ), рС(уУгла, доляПосле)];

/** Как разложить мойку и плиту по стенам: каждое — на одну из стен; если на одной — оба порядка */
function раскладкиПредметов(стен: number): Предмет[][][] {
  const итог: Предмет[][][] = [];
  for (let м = 0; м < стен; м++) {
    for (let п = 0; п < стен; п++) {
      const по: Предмет[][] = Array.from({ length: стен }, () => []);
      if (м === п) {
        for (const порядок of [['М', 'П'], ['П', 'М']] as Предмет[][]) {
          const к = по.map((x) => [...x]);
          к[м] = порядок;
          итог.push(к);
        }
      } else {
        по[м].push('М');
        по[п].push('П');
        итог.push(по);
      }
    }
  }
  return итог;
}

/** Угловая тумба с каруселью в углу в конце стены `стена` (плечо «б» уходит вдоль следующей стены) */
function угловаяСтавка(стена: СтенаПлана, уг: number): Ставка {
  return {
    изд: уг >= 1000 ? 'тумба-угловая-карусель-1000' : 'тумба-угловая-карусель-900',
    стена,
    s0: стена.длина - уг,
    s1: стена.длина,
    г: уг,
    y: 0,
    в: К.высотаНиза,
    роль: 'угловой',
    материалы: { фасад: ФАСАД_НИЗА },
    название: 'Угловая тумба с каруселью',
  };
}

/** Угол: тумба с каруселью (основной вариант) или глухой квадрат под столешницей (если тумба не встаёт) */
const ВАРИАНТЫ_УГЛА = [К.угловой, 0];
/** Кандидаты с угловой тумбой идут раньше глухого угла: место в углу используется */
const БОНУС_УГЛОВОЙ = 500;

const текстУгла = (уг: number, два: boolean) =>
  уг
    ? `${два ? 'Углы' : 'Угол'}: угловая тумба ${уг} × ${уг} с каруселью 3/4, две створки на петлях у боковин; на 110° створки и дверцы соседей не задевают соседний ряд (проверено валидатором).`
    : `${два ? `Два угла ${К.угол} × ${К.угол} мм` : `Угол ${К.угол} × ${К.угол} мм`} под столешницей без модуля: угловая тумба ${К.угловой} × ${К.угловой} не встала; у угла ящики, дверцы соседей открываются на 110°.`;

/** Угловая: стены i и i+1 (угол в конце стены i). В углу — тумба с каруселью, иначе глухой квадрат 600 × 600. */
function угловыеКандидаты(к: Контекст, сПММ: boolean): Кандидат[] {
  const итог: Кандидат[] = [];
  const n = к.ст.length;
  for (let i = 0; i < n; i++) {
    if (!уголПрямой(к.ст, i)) continue;
    const j = (i + 1) % n;
    const A = к.ст[i];
    const B = к.ст[j];
    const оA = отрезокС(отрезки(к, i, К.глубинаНиза, 0, ВЕРХ_НИЗА), A.длина - 1);
    const оB = отрезокС(отрезки(к, j, К.глубинаНиза, 0, ВЕРХ_НИЗА), 1);
    if (!оA || !оB) continue;
    for (const уг of ВАРИАНТЫ_УГЛА) {
      // модули отступают от угла на тумбу (или на глухой квадрат); столешница B закрывает угол от 0, A — до L_A − 600
      const отступ = уг || К.угол;
      for (const дA of длиныРяда(A.длина - отступ - оA[0], [3000, 2400, 1800])) {
        for (const дB of длиныРяда(оB[1] - отступ, [3000, 2400, 1800])) {
          if (дA < 1200 || дB < 1200) continue;
          const рA: Ряд = { стена: A, w0: A.длина - отступ - дA, w1: A.длина - К.угол, m0: A.длина - отступ - дA, m1: A.длина - отступ };
          const рB: Ряд = { стена: B, w0: 0, w1: отступ + дB, m0: отступ, m1: отступ + дB };
          for (const [пA, пB] of раскладкиПредметов(2)) {
            for (const холодНаA of [true, false]) {
              for (const доляУгла of [0.5, 1, 3]) {
                const мA = разложить(рA, кУглу(пA, холодНаA, сПММ, доляУгла, уг ? У_ТУМБЫ : У_УГЛА), к);
                const мB = разложить(рB, отУгла(пB, !холодНаA, сПММ, доляУгла, уг ? У_ТУМБЫ : У_УГЛА), к);
                if (!мA || !мB) continue;
                if (уг) мA.push(угловаяСтавка(A, уг));
                const вс = собратьКухню(к, [{ р: рA, модули: мA }, { р: рB, модули: мB }], пA.includes('М') ? 0 : 1);
                итог.push({
                  ставки: вс,
                  описание: `${имяСтены(к.пом, i)} ${Math.round(рA.w1 - рA.w0)} мм + ${имяСтены(к.пом, j)} ${Math.round(рB.w1 - рB.w0)} мм`,
                  учтено: [текстУгла(уг, false)],
                  штраф: штрафКухни(к, вс, true) - (уг ? БОНУС_УГЛОВОЙ : 0),
                });
              }
            }
          }
        }
      }
    }
  }
  return итог;
}

/** П-образная: стены i−1, i, i+1; в обоих углах — тумбы с каруселью (или глухие углы под столешницей средней стены) */
function пКандидаты(к: Контекст, сПММ: boolean): Кандидат[] {
  const итог: Кандидат[] = [];
  const n = к.ст.length;
  if (n < 4) return итог;
  for (let i = 0; i < n; i++) {
    const h = (i + n - 1) % n;
    const j = (i + 1) % n;
    if (!уголПрямой(к.ст, h) || !уголПрямой(к.ст, i)) continue;
    const A = к.ст[h];
    const B = к.ст[i];
    const C = к.ст[j];
    const оA = отрезокС(отрезки(к, h, К.глубинаНиза, 0, ВЕРХ_НИЗА), A.длина - 1);
    const оB = отрезокС(отрезки(к, i, К.глубинаНиза, 0, ВЕРХ_НИЗА), B.длина / 2);
    const оC = отрезокС(отрезки(к, j, К.глубинаНиза, 0, ВЕРХ_НИЗА), 1);
    if (!оA || !оB || !оC || оB[0] > 1 || оB[1] < B.длина - 1) continue;
    for (const уг of ВАРИАНТЫ_УГЛА) {
      const отступ = уг || К.угол;
      const рB: Ряд = { стена: B, w0: 0, w1: B.длина, m0: отступ, m1: B.длина - отступ };
      if (рB.m1 - рB.m0 < (уг ? 900 : 1200)) continue;
      for (const дA of длиныРяда(A.длина - отступ - оA[0], [2400, 1800, 1200])) {
        for (const дC of длиныРяда(оC[1] - отступ, [2400, 1800, 1200])) {
          if (дA < 900 || дC < 900) continue;
          const рA: Ряд = { стена: A, w0: A.длина - отступ - дA, w1: A.длина - К.угол, m0: A.длина - отступ - дA, m1: A.длина - отступ };
          const рC: Ряд = { стена: C, w0: К.угол, w1: отступ + дC, m0: отступ, m1: отступ + дC };
          for (const [пA, пB, пC] of раскладкиПредметов(3)) {
            for (const холодНаA of [true, false]) {
              for (const [доляДо, доляПосле] of [[1, 1], [1, 3], [3, 1]]) {
                const мA = разложить(рA, кУглу(пA, холодНаA, сПММ, 1, уг ? У_ТУМБЫ : У_УГЛА), к);
                const мB = разложить(рB, междуУглами(пB, сПММ, доляДо, доляПосле, уг ? У_ТУМБЫ : У_УГЛА), к);
                const мC = разложить(рC, отУгла(пC, !холодНаA, сПММ, 1, уг ? У_ТУМБЫ : У_УГЛА), к);
                if (!мA || !мB || !мC) continue;
                if (уг) {
                  мA.push(угловаяСтавка(A, уг));
                  мB.push(угловаяСтавка(B, уг));
                }
                const главный = пA.includes('М') ? 0 : пB.includes('М') ? 1 : 2;
                const вс = собратьКухню(к, [{ р: рA, модули: мA }, { р: рB, модули: мB }, { р: рC, модули: мC }], главный);
                итог.push({
                  ставки: вс,
                  описание: `${имяСтены(к.пом, h)} ${Math.round(рA.w1 - рA.w0)} + ${имяСтены(к.пом, i)} ${Math.round(B.длина)} + ${имяСтены(к.пом, j)} ${Math.round(рC.w1 - рC.w0)} мм`,
                  учтено: [текстУгла(уг, true)],
                  штраф: штрафКухни(к, вс, true) - (уг ? БОНУС_УГЛОВОЙ : 0),
                });
              }
            }
          }
        }
      }
    }
  }
  return итог;
}

/* ------------------------------------------------------------------ хранение и ниши */

type Наполнение = 'система' | 'купе' | 'в-нишу';

const НАЗВАНИЕ_НАПОЛНЕНИЯ: Record<Наполнение, string> = { система: 'открытая система', купе: 'шкаф-купе', 'в-нишу': 'шкаф в нишу (купе без боковин)' };

/** Изделие для отрезка хранения шириной ш и глубиной г */
/** До потолка оставляем на сборку: шкаф поднимают наклоном */
const ЗАЗОР_ПОТОЛКА = 50;

/** Глубина, с которой встаёт продольная штанга (плечики 450 + запас): мельче — только полки */
const ГЛУБИНА_ШТАНГИ = 550;

/**
 * Секции ≈ 700 мм без ящиков (выдвинутый ящик у угла упирается в соседний ряд, в нише — в переднюю стену);
 * штанга через одну, если глубина позволяет, иначе везде полки.
 */
function секцииХранения(ш: number, г: number, h: number): ЧастичнаяРаскладка['секции'] {
  const n = Math.max(1, Math.round(ш / 700));
  const штанга = г >= ГЛУБИНА_ШТАНГИ;
  return Array.from({ length: n }, (_, k) => ({
    ширина: 'доля' as const,
    наполнение: штанга && k % 2 === 0
      ? { направление: 'снизу-вверх' as const, число: 1, тип: 'регулируемая' as const, штанга: { высота: Math.min(1900, h - 350) } }
      : { направление: 'снизу-вверх' as const, число: 'авто' as const, тип: 'регулируемая' as const },
  }));
}

function изделиеХранения(наполнение: Наполнение, ш: number, г: number, h: number): { изд: string; раскладка?: ЧастичнаяРаскладка } {
  const секции = секцииХранения(ш, г, h);
  if (наполнение === 'в-нишу' && ш >= 500 && г >= 300) return { изд: 'шкаф-в-нишу-1200', раскладка: { секции } };
  if (ш < 900 || (наполнение === 'купе' && г < 450)) {
    return г <= 500 ? { изд: 'стеллаж-открытый-800' } : { изд: 'свободный-корпус', раскладка: { фасад: { тип: 'нет' }, секции: [{ ширина: 'доля', наполнение: { направление: 'снизу-вверх', число: 'авто', тип: 'регулируемая' } }] } };
  }
  if (наполнение === 'купе') return { изд: ш >= 1800 ? 'шкаф-купе-2400' : 'шкаф-купе-1800', раскладка: { секции } };
  return { изд: 'гардеробная-система-1800', раскладка: { секции } };
}

/** Как назвать ряд хранения по самому широкому изделию в нём */
function названиеРяда(ставки: Ставка[]): string {
  const главное = ставки.filter((с) => с.роль === 'хранение').sort((a, b) => b.s1 - b.s0 - (a.s1 - a.s0))[0];
  if (!главное) return 'открытые полки';
  if (главное.изд.startsWith('шкаф-купе')) return НАЗВАНИЕ_НАПОЛНЕНИЯ.купе;
  if (главное.изд === 'шкаф-в-нишу-1200') return НАЗВАНИЕ_НАПОЛНЕНИЯ['в-нишу'];
  if (главное.изд === 'гардеробная-система-1800') return НАЗВАНИЕ_НАПОЛНЕНИЯ.система;
  return 'открытые полки';
}

function ограничить(изд: Изделие, ш: number, г: number, в: number) {
  const { мин, макс } = изд.границы;
  return { ш: Math.min(макс.ш, Math.max(мин.ш, ш)), г: Math.min(макс.г, Math.max(мин.г, г)), в: Math.min(макс.в, Math.max(мин.в, в)) };
}

/**
 * Ряд хранения у стены от a до b глубиной г и высотой h. Участки, закрытые препятствием не на всю высоту
 * (короб у пола, короб на стене), заполняются открытыми полками ниже и выше препятствия.
 */
function рядХранения(к: Контекст, i: number, a: number, b: number, г: number, h: number, наполнение: Наполнение, учтено: string[]): Ставка[] | null {
  const с = к.ст[i];
  const закрыто = закрытыеУчастки(с, к.преп, г, 0, h).filter((з) => з.s1 > a && з.s0 < b);
  const итог: Ставка[] = [];
  const полные = свободныеОтрезки(a, b, закрыто);
  for (const [x, y] of полные) {
    const ш = y - x;
    if (ш < 300) {
      if (ш >= 20) учтено.push(`${имяСтены(к.пом, i)}: щель ${Math.round(ш)} мм у препятствия — фальшпанель.`);
      continue;
    }
    const и = изделиеХранения(наполнение, ш, г, h);
    const изд = изделиеПоИд(и.изд)!;
    const кус = куски(ш, изд.границы.мин.ш, изд.границы.макс.ш);
    let s = x;
    for (const кш of кус) {
      const габ = ограничить(изд, кш, г, h);
      итог.push({ изд: и.изд, стена: с, s0: s, s1: s + габ.ш, г: габ.г, y: 0, в: габ.в, роль: 'хранение', раскладка: и.раскладка });
      s += кш;
    }
  }
  // участки под и над препятствиями, которые закрывают не всю высоту
  for (const з of закрыто) {
    const x = Math.max(a, з.s0);
    const y = Math.min(b, з.s1);
    if (y - x < 150) continue;
    const низП = Math.min(...з.причины.map((п) => п.y0));
    const верхП = Math.max(...з.причины.map((п) => п.y1));
    const чем = з.причины.map((п) => п.подпись).join(', ');
    const открытые = (y0: number, y1: number) =>
      итог.push({
        изд: 'свободный-корпус',
        стена: с,
        s0: x,
        s1: y,
        г: Math.min(г, 1000),
        y: y0,
        в: y1 - y0,
        роль: 'полки',
        название: 'Открытые полки',
        раскладка: { фасад: { тип: 'нет' }, корпус: { цоколь: 0, ножки: 0 }, секции: [{ ширина: 'доля', наполнение: { направление: 'снизу-вверх', число: 'авто', тип: 'регулируемая' } }] },
      });
    const части: string[] = [];
    if (низП >= 400) {
      открытые(0, Math.round(низП - 10));
      части.push(`под ним полки до ${Math.round(низП - 10)}`);
    }
    if (h - верхП >= 300) {
      открытые(Math.round(верхП + 10), h);
      части.push(`над ним полки с ${Math.round(верхП + 10)}`);
    }
    учтено.push(`${чем}: ${Math.round(y - x)} мм ряда обходят ${части.length ? `(${части.join(', ')})` : '(участок оставлен пустым)'}.`);
  }
  const мелко = `Глубина ${г} мм меньше ${ГЛУБИНА_ШТАНГИ}: продольная штанга не встаёт, внутри полки; для плечиков — выдвижная торцевая штанга.`;
  if (г < ГЛУБИНА_ШТАНГИ && итог.some((с) => с.роль === 'хранение') && !учтено.some((x) => x.startsWith(`Глубина ${г} мм`))) учтено.push(мелко);
  return итог.length ? итог : null;
}

function глубинаХранения(к: Контекст, i: number, ниша: boolean): number {
  const с = к.ст[i];
  const перед = глубинаПеред(к.пом, с, с.длина / 2);
  if (ниша) return Math.round(Math.min(перед, 900));
  return Math.min(600, Math.floor((перед - НОРМЫ.проход) / 10) * 10);
}

