function контекст(п: ПроектV2, пом: Помещение): Контекст {
  const ст = стеныПлана(пом);
  const вода = отметкиСПредметами(п, пом)
    .filter((о) => о.вид === 'вода' || о.вид === 'канализация')
    .map((о) => ({ стена: о.стена, s: о.от_угла + о.ширина / 2 }));
  // щиток на кухне — не закрываем мебелью; во встроенном шкафу (ниша, гардеробная) он внутри, доступ через створку — это заметка
  return { п, пом, ст, H: высотаДляРендера(пом), преп: препятствияРасстановки(п, пом, назначениеПомещения(пом) === 'кухня'), вода };
}

