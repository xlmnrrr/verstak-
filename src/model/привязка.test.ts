import { describe, expect, it } from 'vitest';
import { изделиеПоИд } from './каталог';
import { новоеПомещение, прямоугольник } from './помещение';
import { новыйПроектV2, новыйЭкземпляр } from './проект';
import { БЫСТРЫЕ, зазоры, найтиНишу, найтиНишуШире, преградыДляПривязки, привязать, прямоугольникЭкземпляра, урезатьПоНише } from './привязка';
import type { Экземпляр } from './типы';

// комната 3600 × 2800: стены x = ±1800, z = ±1400
const комната = () => новыйПроектV2('т', новоеПомещение('п1', 'кухня', 'Кухня', прямоугольник(3600, 2800)));
const тумба = (id: string, x: number, z: number, ш = 600, правка: Partial<Экземпляр> = {}): Экземпляр => {
  const и = изделиеПоИд('тумба-ящики-600')!;
  const э = новыйЭкземпляр(и, 'п1');
  return { ...э, id, габариты: { ...э.габариты, ш }, позиция: [x, 0, z], ...правка };
};
const вход = (э: Экземпляр) => ({ позиция: [э.позиция[0], э.позиция[2]] as [number, number], ш: э.габариты.ш, г: э.габариты.г, поворот: э.поворот, низ: э.позиция[1], верх: э.позиция[1] + э.габариты.в });

describe('привязка к стенам и соседям', () => {
  it('прилипает к стене вплотную, если до неё не дальше порога', () => {
    const п = комната();
    const э = тумба('а', -1800 + 300 + 20, 0);
    const р = привязать(вход(э), преградыДляПривязки(п, 'п1', 'а'), 35);
    expect(р.позиция[0]).toBeCloseTo(-1500, 5);
    expect(р.подсказки.some((x) => x.вид === 'стена' && x.ось === 'x')).toBe(true);
    expect(р.подсказки[0].текст).toContain('Вплотную к стене');
  });

  it('дальше порога — не трогает', () => {
    const п = комната();
    const э = тумба('а', -1800 + 300 + 60, 0);
    const р = привязать(вход(э), преградыДляПривязки(п, 'п1', 'а'), 35);
    expect(р.позиция[0]).toBe(-1440);
    expect(р.подсказки).toEqual([]);
  });

  it('встык к соседу без зазора, подсказка называет соседа', () => {
    const п = комната();
    const сосед = тумба('с', -600, -1100); // x от −900 до −300
    п.объекты.push(сосед);
    const э = тумба('а', -300 + 300 + 18, -1100); // 18 мм зазора справа от соседа
    const р = привязать(вход(э), преградыДляПривязки(п, 'п1', 'а'), 35);
    expect(р.позиция[0]).toBeCloseTo(0, 5);
    expect(прямоугольникЭкземпляра({ ...э, позиция: [р.позиция[0], 0, р.позиция[1]] }).x0).toBeCloseTo(сосед.позиция[0] + 300, 5);
    expect(р.подсказки.some((x) => x.вид === 'сосед' && x.текст.includes('Встык'))).toBe(true);
  });

  it('и к стене, и к соседу сразу: каждая ось отдельно', () => {
    const п = комната();
    п.объекты.push(тумба('с', -1500, -1100));
    const э = тумба('а', -1200 + 300 + 20, -1400 + 280 + 12, 600);
    const р = привязать(вход(э), преградыДляПривязки(п, 'п1', 'а'), 35);
    expect(р.позиция[0]).toBeCloseTo(-1200 + 300, 5); // x: к соседу (его правая грань −1200)
    expect(р.позиция[1]).toBeCloseTo(-1400 + 280, 5); // z: к задней стене
  });

  it('при повороте 90° учитывает обмен ширины и глубины', () => {
    const п = комната();
    const э = тумба('а', 0, 1400 - 300 - 15, 600, { поворот: 90 }); // ширина 600 вдоль z
    const р = привязать(вход(э), преградыДляПривязки(п, 'п1', 'а'), 35);
    expect(р.позиция[1]).toBeCloseTo(1400 - 300, 5);
  });

  it('произвольный угол: привязки к объектам нет', () => {
    const п = комната();
    const э = тумба('а', -1800 + 300 + 10, 0, 600, { поворот: 33 });
    const р = привязать(вход(э), преградыДляПривязки(п, 'п1', 'а'), 35);
    expect(р.позиция).toEqual([-1490, 0]);
    expect(р.подсказки).toEqual([]);
  });

  it('предметы на другой высоте (навесной над тумбой) не мешают: привязка идёт только по ряду', () => {
    const п = комната();
    п.объекты.push(тумба('с', -600, -1100));
    const э = { ...тумба('а', 20, -1100), позиция: [20, 1500, -1100] as [number, number, number] };
    const р = привязать(вход(э), преградыДляПривязки(п, 'п1', 'а'), 35);
    expect(р.позиция[0]).toBe(20);
  });
});

describe('ниша: «остаток N мм»', () => {
  const сНишой = () => {
    const п = комната();
    п.объекты.push(тумба('л', -1500, -1100), тумба('п', -463, -1100)); // между ними 437 мм: от −1200 до −763
    return п;
  };

  it('тумба 450 в ширине 437: предлагает урезать до 437 и встаёт без зазора', () => {
    const п = сНишой();
    const э = тумба('а', -981, -1100, 450);
    const н = найтиНишу(п, э);
    expect(н).not.toBeNull();
    expect(н!.ширина).toBe(437);
    expect(н!.ось).toBe('x');
    const после = урезатьПоНише(э, н!);
    expect(после.габариты.ш).toBe(437);
    const р = прямоугольникЭкземпляра(после);
    expect(р.x0).toBeCloseTo(-1200, 5);
    expect(р.x1).toBeCloseTo(-763, 5);
  });

  it('если помещается — предложения нет; если уже минимального — тоже', () => {
    const п = сНишой();
    expect(найтиНишу(п, тумба('а', -981, -1100, 437))).toBeNull();
    expect(найтиНишу(п, тумба('а', -981, -1100, 400))).toBeNull();
    const узко = комната();
    узко.объекты.push(тумба('л', -1500, -1100), тумба('п', -1200 + 60 + 300, -1100));
    // щель 60 мм: уже минимальной ширины изделия
    expect(найтиНишу(узко, тумба('а', -1200 + 30, -1100, 450))).toBeNull();
  });

  it('тумба 400 в проёме 437: предлагает растянуть до 437 без зазора; урезать в этом случае не предлагает', () => {
    const п = сНишой();
    const э = тумба('а', -981, -1100, 400);
    expect(найтиНишу(п, э)).toBeNull();
    const н = найтиНишуШире(п, э);
    expect(н?.ширина).toBe(437);
    const после = урезатьПоНише(э, н!);
    expect(после.габариты.ш).toBe(437);
    const р = прямоугольникЭкземпляра(после);
    expect(р.x0).toBeCloseTo(-1200, 5);
    expect(р.x1).toBeCloseTo(-763, 5);
  });

  it('растянуть: не предлагает при точном совпадении, при большом свободном месте и сверх максимума изделия', () => {
    const п = сНишой();
    expect(найтиНишуШире(п, тумба('а', -981, -1100, 437))).toBeNull();
    const просторно = комната();
    просторно.объекты.push(тумба('л', -1500, -1100), тумба('п', 100, -1100)); // проём больше 1000: это свободное место, не добор
    expect(найтиНишуШире(просторно, тумба('а', -600, -1100, 450))).toBeNull();
  });

  it('ниша между стеной и соседом тоже находится', () => {
    const п = комната();
    п.объекты.push(тумба('п', -1800 + 437 + 300, -1100)); // от −1363 до −763... левая стена −1800: щель 437? тумба 600 от −1363
    const э = тумба('а', -1581, -1100, 450);
    const н = найтиНишу(п, э);
    expect(н?.ширина).toBe(437);
    expect(н?.слева.вид).toBe('стена');
  });

  it('в другом ряду (напротив, по глубине) — не ниша', () => {
    const п = комната();
    п.объекты.push(тумба('л', -1500, 1100), тумба('п', -463, 1100));
    expect(найтиНишу(п, тумба('а', -981, -1100, 450))).toBeNull();
  });
});

describe('зазоры', () => {
  it('до соседа слева и стены справа в мм, потолок', () => {
    const п = комната();
    п.объекты.push(тумба('с', -600, -1100)); // правая грань −300
    const э = тумба('а', 200, -1100); // левая грань −100
    п.объекты.push(э);
    const з = зазоры(п, э);
    expect(з.xМинус?.мм).toBe(200);
    expect(з.xПлюс?.мм).toBe(1800 - 500); // стена x = 1800, моя правая грань 500
    expect(з.xПлюс?.преграда.вид).toBe('стена');
    expect(з.доПотолка).toBe(2700 - 720);
    expect(з.zМинус?.преграда.вид).toBe('стена');
  });

  it('вплотную даёт 0', () => {
    const п = комната();
    п.объекты.push(тумба('с', -600, -1100));
    const э = тумба('а', 0, -1100);
    expect(зазоры(п, э).xМинус?.мм).toBe(0);
  });
});

describe('быстрые действия', () => {
  const пенал = (id: string, x: number, z: number) => {
    const и = изделиеПоИд('пенал-кухонный-600')!;
    return { ...новыйЭкземпляр(и, 'п1'), id, позиция: [x, 0, z] as [number, number, number] };
  };

  it('«до потолка» тянет напольное вверх в пределах максимума, навесное поднимает', () => {
    const п = комната();
    const э = пенал('а', 0, -1100);
    const р = БЫСТРЫЕ.потолок(п, э);
    expect('экз' in р).toBe(true);
    if ('экз' in р) expect(р.экз.габариты.в).toBeLessThanOrEqual(2700);
    const навесной = { ...тумба('н', 0, -1100), позиция: [0, 1200, -1100] as [number, number, number], габариты: { ш: 600, г: 320, в: 700 } };
    const р2 = БЫСТРЫЕ.потолок(п, навесной);
    expect('экз' in р2 && р2.экз.позиция[1]).toBe(2000);
    const уже = { ...навесной, позиция: [0, 2000, -1100] as [number, number, number] };
    expect('ошибка' in БЫСТРЫЕ.потолок(п, уже)).toBe(true);
  });

  it('«к соседу» придвигает вплотную, повторно говорит «уже вплотную»', () => {
    const п = комната();
    п.объекты.push(тумба('с', -600, -1100)); // правая грань −300
    const э = тумба('а', 100, -1100); // левая грань −200: зазор 100, справа до стены 1800−400=1400
    const р = БЫСТРЫЕ.сосед(п, э);
    expect('экз' in р).toBe(true);
    if ('экз' in р) {
      expect(р.экз.позиция[0]).toBe(0);
      expect(р.текст).toContain('Придвинуто вплотную');
      expect('ошибка' in БЫСТРЫЕ.сосед(п, р.экз)).toBe(true);
    }
  });

  it('«по центру» между соседом и стеной', () => {
    const п = комната();
    п.объекты.push(тумба('с', -1500, -1100)); // правая грань −1200
    const э = тумба('а', 0, -1100); // между −1200 и стеной 1800: свободно 3000 − 600
    const р = БЫСТРЫЕ.центр(п, э);
    expect('экз' in р && р.экз.позиция[0]).toBe(300); // середина интервала −1200…1800 = 300
  });

  it('«в угол» — к ближайшему углу вплотную к обеим стенам', () => {
    const п = комната();
    const э = тумба('а', 1200, 900);
    const р = БЫСТРЫЕ.угол(п, э);
    expect('экз' in р).toBe(true);
    if ('экз' in р) {
      const р2 = прямоугольникЭкземпляра(р.экз);
      expect(р2.x1).toBeCloseTo(1800, 5);
      expect(р2.z1).toBeCloseTo(1400, 5);
    }
  });

  it('«в угол» в комнате Г не лезет в вогнутый угол выреза', () => {
    const п = новыйПроектV2('т', новоеПомещение('п1', 'кухня', 'Кухня', [[-2000, -1500], [2000, -1500], [2000, 0], [500, 0], [500, 1500], [-2000, 1500]]));
    const э = тумба('а', 300, 200); // рядом с вогнутым углом (500, 0)
    const р = БЫСТРЫЕ.угол(п, э);
    expect('экз' in р).toBe(true);
    if ('экз' in р) {
      const р2 = прямоугольникЭкземпляра(р.экз);
      // не в вогнутом углу: не пересекает вырез (x > 500 при z > 0)
      expect(р2.x1 <= 500 + 0.01 || р2.z1 <= 0 + 0.01).toBe(true);
    }
  });

  it('«выровнять по фасаду» — по ближайшему соседу с тем же поворотом', () => {
    const п = комната();
    const сосед = тумба('с', -600, -1100); // глубина 560: фасад на z = −1100 + 280 = −820
    п.объекты.push(сосед);
    const э = тумба('а', 100, -1000); // фасад на −720
    const р = БЫСТРЫЕ.фасад(п, э);
    expect('экз' in р && р.экз.позиция[2]).toBe(-1100);
    // сосед с другим поворотом не годится
    const п2 = комната();
    п2.объекты.push(тумба('с', -600, -1100, 600, { поворот: 180 }));
    expect('ошибка' in БЫСТРЫЕ.фасад(п2, э)).toBe(true);
  });

  it('при угле не кратном 90° действия по ряду просят повернуть', () => {
    const п = комната();
    const э = тумба('а', 0, 0, 600, { поворот: 20 });
    for (const д of ['сосед', 'центр', 'угол', 'фасад'] as const) {
      const р = БЫСТРЫЕ[д](п, э);
      expect('ошибка' in р && р.ошибка).toContain('90');
    }
  });
});
