/**
 * Чтение и запись .kitchen: определяет версию файла, проверяет, мигрирует v1, пишет v2.
 * Ошибки — по-русски и с путём до поля.
 */
import { z } from 'zod';
import { изделиеПоИд, СВОБОДНЫЙ_КОРПУС } from './каталог';
import { мигрироватьV1, ошибкиZod, type ОтчётМиграции } from './миграция';
import { проверитьПомещение } from './помещение';
import { настройкиПоУмолчанию } from './проект';
import { СХЕМА_V2, type Экземпляр, type ПроектV2, type Помещение } from './типы';

const Число = z.number().finite();
const Габ = z.object({ ш: Число.positive(), г: Число.positive(), в: Число.positive() });
const Тройка = z.tuple([Число, Число, Число]);
const Точка2 = z.tuple([Число, Число]);

const Наполнение = z.object({
  направление: z.enum(['снизу-вверх', 'слева-направо']),
  число: z.union([Число.min(0), z.literal('авто')]),
  тип: z.enum(['регулируемая', 'съёмная', 'стационарная']),
  ящики: z.object({ число: Число.min(0), высота: z.union([Число.positive(), z.literal('авто')]) }).optional(),
  штанга: z.object({ высота: Число.positive() }).optional(),
});
const Секция = z.object({
  ширина: z.union([Число.positive(), z.literal('доля')]),
  вес: Число.positive().optional(),
  наполнение: Наполнение,
});
const ТипФасада = z.enum(['нет', 'распашной', 'купе', 'ящики', 'подъёмник', 'push', 'зеркало', 'стекло']);
const ЧастичнаяРаскладка = z.object({
  корпус: z
    .object({
      плита: z.union([z.literal(16), z.literal(18)]).optional(),
      задник: z.enum(['есть', 'нет', 'ХДФ']).optional(),
      цоколь: Число.min(0).optional(),
      ножки: Число.min(0).optional(),
      крыша: Число.positive().optional(),
      боковины: z.boolean().optional(),
    })
    .optional(),
  секции: z.array(Секция).min(1).optional(),
  фасад: z
    .object({
      тип: ТипФасада.optional(),
      створок: z.union([Число.positive(), z.literal('авто')]).optional(),
      ящиков: Число.min(0).optional(),
      петли: z.enum(['слева', 'справа', 'попарно', 'сверху', 'снизу']).optional(),
      ручка: z
        .object({
          вид: z.enum(['скоба', 'рейлинг', 'кнопка', 'профиль', 'нет']).optional(),
          место: z.enum(['верх', 'низ', 'середина', 'край']).optional(),
        })
        .optional(),
    })
    .optional(),
});
const Материалы = z.record(z.string(), z.string());

const ЭкземплярZ = z.looseObject({
  id: z.string().min(1),
  изделие: z.string().min(1),
  помещение: z.string().min(1),
  название: z.string().optional(),
  позиция: Тройка,
  поворот: Число,
  габариты: Габ,
  раскладка: ЧастичнаяРаскладка.optional(),
  материалы: Материалы.optional(),
  материал_описание: z.string().optional(),
  открыт: z.boolean().optional(),
  открыто: z.array(z.string()).optional(),
  угол_открывания: Число.optional(),
  метки: z.array(z.string()).optional(),
});

const Отметка = z.object({
  id: z.string().min(1),
  стена: Число.int().min(0),
  вид: z.string(),
  от_угла: Число,
  от_пола: Число,
  ширина: Число.positive(),
  высота: Число.positive(),
  глубина: Число.optional(),
  ведёт_в: z.string().optional(),
  связь: z.string().optional(),
  метки: z.array(z.string()).optional(),
  заметка: z.string().optional(),
  петля: z.enum(['слева', 'справа']).optional(),
  открывание: z.enum(['внутрь', 'наружу']).optional(),
  открыта: z.boolean().optional(),
});

const ПомещениеZ = z.looseObject({
  id: z.string().min(1),
  тип: z.string(),
  название: z.string(),
  контур: z.array(Точка2).min(3, 'в контуре должно быть не меньше трёх точек'),
  высота: z.union([Число.min(1000, 'высота стен должна быть не меньше 1000 мм'), z.literal('неизвестна')]),
  толщина_стен: Число.min(0),
  смещение: Точка2,
  отметки: z.array(Отметка),
  отделка: z.object({ стены: z.string(), пол: z.string(), потолок: z.string().optional() }),
  мебель_высота: Число.min(300, 'высота мебели должна быть не меньше 300 мм').optional(),
  метки: z.array(z.string()).optional(),
});

const Связь = z.object({
  id: z.string(),
  а: z.string(),
  б: z.string(),
  стена_а: Число,
  стена_б: Число,
  участок: z.tuple([Точка2, Точка2]),
});

const НастройкиZ = z.looseObject({
  тема: z.enum(['система', 'мастерская', 'калька']).optional(),
  фон: z.string().optional(),
  шаг_сетки: Число.positive().optional(),
  толщина_плиты: z.union([z.literal(16), z.literal(18)]).optional(),
  качество: z.enum(['авто', 'высокое', 'среднее', 'слабый ноутбук']).optional(),
  режим_обзора: z.enum(['сверху', 'прогулка']).optional(),
  свободная_сборка: z.boolean().optional(),
});

export const СхемаV2Z = z.looseObject({
  schemaVersion: z.number(),
  название: z.string().min(1),
  создан: z.string(),
  изменён: z.string(),
  помещения: z.array(ПомещениеZ).min(1, 'нужно хотя бы одно помещение'),
  связи: z.array(Связь).optional(),
  объекты: z.array(ЭкземплярZ),
  настройки: НастройкиZ.optional(),
});

const ВЕРХ_V2 = ['schemaVersion', 'название', 'создан', 'изменён', 'помещения', 'связи', 'объекты', 'настройки'];
const ПОМ_V2 = ['id', 'тип', 'название', 'контур', 'высота', 'толщина_стен', 'смещение', 'отметки', 'отделка', 'мебель_высота', 'метки'];
const ЭКЗ_V2 = ['id', 'изделие', 'помещение', 'название', 'позиция', 'поворот', 'габариты', 'раскладка', 'материалы', 'материал_описание', 'открыт', 'открыто', 'угол_открывания', 'метки'];

const лишние = (о: Record<string, unknown>, известные: string[]) =>
  Object.fromEntries(Object.entries(о).filter(([к]) => !известные.includes(к)));

export interface РезультатОткрытия {
  ок: boolean;
  проект?: ПроектV2;
  /** версия файла, из которой открыли */
  из?: number;
  /** отчёт миграции, если файл был v1 */
  отчёт?: ОтчётМиграции;
  ошибки: string[];
  предупреждения: string[];
}

function разобратьV2(данные: unknown): РезультатОткрытия {
  const р = СхемаV2Z.safeParse(данные);
  if (!р.success) return { ок: false, ошибки: ошибкиZod(р.error), предупреждения: [] };
  const д = р.data as Record<string, unknown> & {
    schemaVersion: number;
    помещения: Record<string, unknown>[];
    объекты: Record<string, unknown>[];
    настройки?: Record<string, unknown>;
  };
  const предупреждения: string[] = [];
  if (д.schemaVersion > СХЕМА_V2) {
    предупреждения.push(`Файл новее приложения (schemaVersion ${д.schemaVersion} против ${СХЕМА_V2}). Часть полей может не читаться.`);
  }

  const разделить = <T>(о: Record<string, unknown>, известные: string[]): T => {
    const прочее = лишние(о, известные);
    const основа = Object.fromEntries(Object.entries(о).filter(([к]) => известные.includes(к)));
    return (Object.keys(прочее).length ? { ...основа, прочее } : основа) as T;
  };
  const помещения = д.помещения.map((п) => разделить<Помещение>(п, ПОМ_V2));
  const idПомещений = new Set(помещения.map((п) => п.id));
  const объекты: Экземпляр[] = д.объекты.map((о) => {
    const экз = разделить<Экземпляр>(о, ЭКЗ_V2);
    if (!изделиеПоИд(экз.изделие)) {
      предупреждения.push(`Объект ${экз.id}: изделие «${экз.изделие}» не найдено в каталоге — показано свободным корпусом.`);
      экз.метки = [...(экз.метки ?? []), `было:изделие:${экз.изделие}`];
      экз.изделие = СВОБОДНЫЙ_КОРПУС;
    }
    if (!idПомещений.has(экз.помещение)) {
      предупреждения.push(`Объект ${экз.id}: помещения «${экз.помещение}» нет в проекте — перенесён в «${помещения[0].название}».`);
      экз.помещение = помещения[0].id;
    }
    return экз;
  });
  for (const п of помещения) предупреждения.push(...проверитьПомещение(п));

  const проект: ПроектV2 = {
    schemaVersion: 2,
    название: д.название as string,
    создан: д.создан as string,
    изменён: д.изменён as string,
    помещения,
    связи: (д.связи as ПроектV2['связи']) ?? [],
    объекты,
    настройки: { ...настройкиПоУмолчанию(), ...((д.настройки ?? {}) as object) },
  };
  const прочее = лишние(д, ВЕРХ_V2);
  if (Object.keys(прочее).length) проект.прочее = прочее;
  if (!объекты.length) предупреждения.push('В проекте нет ни одного объекта.');
  return { ок: true, проект, из: 2, ошибки: [], предупреждения };
}

/** Разобрать текст файла .kitchen любой версии в проект v2 */
export function разобратьФайл(текст: string): РезультатОткрытия {
  let данные: unknown;
  try {
    данные = JSON.parse(текст);
  } catch (e) {
    return { ок: false, ошибки: [`Это не JSON: ${(e as Error).message}`], предупреждения: [] };
  }
  if (typeof данные !== 'object' || данные === null || Array.isArray(данные)) {
    return { ок: false, ошибки: ['Файл должен быть объектом JSON (в фигурных скобках)'], предупреждения: [] };
  }
  const версия = (данные as { schemaVersion?: unknown }).schemaVersion;
  if (typeof версия !== 'number') {
    return { ок: false, ошибки: ['schemaVersion: поле обязательно (нужно: число, 1 или 2)'], предупреждения: [] };
  }
  if (версия <= 1) {
    const м = мигрироватьV1(данные);
    if (!м.ок || !м.проект) return { ок: false, из: 1, отчёт: м.отчёт, ошибки: м.ошибки, предупреждения: [] };
    const предупреждения = [...м.отчёт.заметки];
    if (м.отчёт.потери.length) предупреждения.push(`Миграция: ${м.отчёт.потери.length} расхождений с исходным файлом, подробности в отчёте.`);
    return { ок: true, проект: м.проект, из: 1, отчёт: м.отчёт, ошибки: [], предупреждения };
  }
  return разобратьV2(данные);
}

/** Текст файла v2: неизвестные поля возвращаются на свои места */
export function записатьПроект(п: ПроектV2): string {
  const вернуть = <T extends { прочее?: Record<string, unknown> }>(о: T): Record<string, unknown> => {
    const { прочее, ...остальное } = о;
    return { ...(прочее ?? {}), ...остальное };
  };
  const итог = {
    ...(п.прочее ?? {}),
    schemaVersion: 2,
    название: п.название,
    создан: п.создан,
    изменён: п.изменён,
    помещения: п.помещения.map(вернуть),
    связи: п.связи,
    объекты: п.объекты.map(вернуть),
    настройки: п.настройки,
  };
  return JSON.stringify(итог, null, 2);
}
