import { describe, expect, it } from 'vitest';
import { изделиеПоИд } from './каталог';
import { исправленияОткрывания, ЗАЗОР_ОТКРЫВАНИЯ_ММ } from './исправления';
import { конфликтыПомещения } from './открывание';
import { новоеПомещение, прямоугольник } from './помещение';
import { новыйПроектV2, новыйЭкземпляр } from './проект';
import { проверитьВлезает } from './проверка';
import type { Экземпляр } from './типы';

const комната = () => новыйПроектV2('т', новоеПомещение('п1', 'кухня', 'Кухня', прямоугольник(3600, 2800)));
/** навесной 600 в заднем ряду; задел у левой стены: петля у стены на 110° упирается в стену */
const угловой = (петли: 'слева' | 'справа', x: number, id = 'ш'): Экземпляр => ({
  ...новыйЭкземпляр(изделиеПоИд('навесной-600')!, 'п1'),
  id,
  габариты: { ш: 600, г: 320, в: 720 },
  позиция: [x, 1400, -1400 + 160 + 1],
  раскладка: { фасад: { тип: 'распашной' as const, створок: 1, петли } },
});

describe('исправления конфликта открывания (кнопки в «Проверках»)', () => {
  it('у боковой стены петля слева на 110° упирается: «Переставить петли» снимает конфликт', () => {
    const п = комната();
    п.объекты.push(угловой('слева', -1800 + 300 + 1));
    expect(конфликтыПомещения(п, 'п1').length).toBe(1);
    const и = исправленияОткрывания(п, 'ш');
    const петли = и.find((x) => x.вид === 'петли');
    expect(петли?.подпись).toBe('Переставить петли');
    expect(петли!.результат.раскладка?.фасад?.петли).toBe('справа');
    const после = { ...п, объекты: [петли!.результат] };
    expect(конфликтыПомещения(после, 'п1')).toEqual([]);
  });

  it('«Дать зазор 150 мм» сдвигает от стены так, чтобы до неё осталось 150 мм, и только если это действительно помогает', () => {
    const п = комната();
    п.объекты.push(угловой('слева', -1800 + 300 + 1));
    const з = исправленияОткрывания(п, 'ш').find((x) => x.вид === 'зазор');
    // створка шириной ~600 на 110° выходит за плоскость петли на ~190 мм: 150 мм не хватает, кнопку честно не показываем
    expect(з).toBeUndefined();
    // уже на 110° с шириной 450 створка выходит на ~140 мм: зазор 150 снимает конфликт
    const узкий = комната();
    узкий.объекты.push({ ...угловой('слева', -1800 + 225 + 1), габариты: { ш: 450, г: 320, в: 720 } });
    expect(конфликтыПомещения(узкий, 'п1').length).toBe(1);
    const и = исправленияОткрывания(узкий, 'ш');
    const зазор = и.find((x) => x.вид === 'зазор');
    expect(зазор?.подпись).toBe(`Дать зазор ${ЗАЗОР_ОТКРЫВАНИЯ_ММ} мм`);
    const после = { ...узкий, объекты: [зазор!.результат] };
    expect(конфликтыПомещения(после, 'п1')).toEqual([]);
    // от стены осталось ровно 150 мм
    expect(зазор!.результат.позиция[0] - 225 - -1800).toBeCloseTo(ЗАЗОР_ОТКРЫВАНИЯ_ММ, 0);
    expect(проверитьВлезает(после).length).toBe(0);
  });

  it('нет конфликта — нет кнопок; нечего переставлять (попарные петли) — кнопки петель нет', () => {
    const п = комната();
    п.объекты.push(угловой('справа', -1800 + 300 + 1));
    expect(исправленияОткрывания(п, 'ш')).toEqual([]);
    const попарно = комната();
    попарно.объекты.push({ ...угловой('слева', -1800 + 300 + 1), раскладка: { фасад: { тип: 'распашной' as const, створок: 2, петли: 'попарно' as const } } });
    expect(исправленияОткрывания(попарно, 'ш').some((x) => x.вид === 'петли')).toBe(false);
  });

  it('исправление не двигает предмет в соседа или за стену', () => {
    const п = комната();
    // шкаф зажат между стеной и соседом: сдвигать некуда
    п.объекты.push(угловой('слева', -1800 + 300 + 1), угловой('справа', -1800 + 600 + 300 + 2, 'сосед'));
    for (const и of исправленияОткрывания(п, 'ш')) {
      expect(проверитьВлезает({ ...п, объекты: п.объекты.map((о) => (о.id === 'ш' ? и.результат : о)) }, new Set(['ш'])).length).toBe(0);
    }
  });
});
