/**
 * Этап 7: «Предложи планировку». Помещения заказчика, обычные кухни и кухня с дверью, окном, радиатором и водой:
 * варианты есть, у каждого числа, ни один не нарушает нормы валидатора, проект варианта пишется и читается файлом.
 */
import { describe, expect, it } from 'vitest';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { предложитьПланировки, назначениеПомещения } from './планировщик';
import { помещенияЗаказчика } from './каталог/помещения-заказчика';
import { новыйПроектV2, копияПроекта } from './проект';
import { новоеПомещение, прямоугольник, точкаВнутри } from './помещение';
import { разобратьФайл, записатьПроект } from './файл';
import { проверитьПроект } from './валидатор';
import { изделиеПоИд } from './каталог';
import { следУглы } from './проверка';
import type { ПроектV2 } from './типы';

const демо = (): ПроектV2 => разобратьФайл(readFileSync(join(process.cwd(), 'public/Библиотека/пример-проекта.kitchen'), 'utf8')).проект!;

function кухняСОтметками(): ПроектV2 {
  const к = новоеПомещение('п1', 'кухня', 'Кухня', прямоугольник(3200, 2600, false));
  к.отметки = [
    { id: 'д', стена: 2, вид: 'дверь', от_угла: 300, от_пола: 0, ширина: 800, высота: 2000 },
    { id: 'о', стена: 1, вид: 'окно', от_угла: 700, от_пола: 900, ширина: 1200, высота: 1400 },
    { id: 'р', стена: 1, вид: 'радиатор', от_угла: 800, от_пола: 150, ширина: 1000, высота: 500 },
    { id: 'в', стена: 0, вид: 'вода', от_угла: 1500, от_пола: 500, ширина: 50, высота: 50 },
  ];
  return новыйПроектV2('Кухня с отметками', к);
}

/** Общие требования к любому варианту */
function проверитьВариант(в: ReturnType<typeof предложитьПланировки>['варианты'][number]) {
  expect(в.чисто, `${в.заголовок}: ${в.замечания.map((з) => з.текст).join(' | ')}`).toBe(true);
  expect(проверитьПроект(в.проект).filter((з) => з.помещение === в.помещение)).toEqual([]);
  const ч = в.числа;
  for (const к of ['столешницаМ', 'листов', 'кромкаМ', 'деталей', 'изделий', 'замечаний'] as const) expect(Number.isFinite(ч[к]), к).toBe(true);
  expect(ч.листов).toBeGreaterThan(0);
  expect(ч.деталей).toBeGreaterThan(0);
  expect(ч.замечаний).toBe(0);
  // id уникальны, изделия из каталога, габариты целые и в границах
  const ids = в.проект.объекты.map((о) => о.id);
  expect(new Set(ids).size).toBe(ids.length);
  const пом = в.проект.помещения.find((x) => x.id === в.помещение)!;
  for (const о of в.проект.объекты.filter((x) => x.помещение === в.помещение)) {
    const изд = изделиеПоИд(о.изделие)!;
    expect(изд, о.изделие).toBeDefined();
    for (const к of ['ш', 'г', 'в'] as const) {
      expect(Number.isInteger(о.габариты[к]), `${о.изделие}.${к} = ${о.габариты[к]}`).toBe(true);
      expect(о.габариты[к]).toBeGreaterThanOrEqual(изд.границы.мин[к]);
      expect(о.габариты[к]).toBeLessThanOrEqual(изд.границы.макс[к]);
    }
    for (const у of следУглы(о.позиция, о.поворот, о.габариты.ш - 4, о.габариты.г - 4)) expect(точкаВнутри(пом.контур, у[0], у[1]), `${о.изделие} внутри помещения`).toBe(true);
  }
  // файл варианта пишется и открывается тем же
  const р = разобратьФайл(записатьПроект(в.проект));
  expect(р.ок).toBe(true);
  expect(р.проект!.объекты.length).toBe(в.проект.объекты.length);
  expect((р.проект!.прочее?.вариант as { буква: string }).буква).toBe(в.буква);
  expect(в.учтено.length).toBeGreaterThan(0);
}

describe('«Предложи планировку» на помещениях заказчика', () => {
  it('гардеробная кв. 160 (1910 × 1430): три варианта — линейная, угловая, П-образная, все без замечаний', () => {
    const пом = помещенияЗаказчика()[1];
    const р = предложитьПланировки(новыйПроектV2('Гардеробная', пом));
    expect(р.назначение).toBe('хранение');
    expect(р.варианты.map((в) => в.тип)).toEqual(['линейная', 'угловая', 'П-образная']);
    for (const в of р.варианты) проверитьВариант(в);
    // наличник на левой стене обойдён, проход между боковыми рядами ≥ 900
    const п = р.варианты[2];
    expect(п.учтено.some((т) => т.includes('наличник 445'))).toBe(true);
    expect(п.учтено.some((т) => /Проход между боковыми рядами (\d+)/.test(т) && Number(/(\d+) мм/.exec(т)![1]) >= 900)).toBe(true);
    // розетка за системой — вырез в задней стенке
    expect(р.варианты[0].учтено.some((т) => т.startsWith('Розетка') && т.includes('вырез'))).toBe(true);
  });

  it('ниши заказчика: только линейные варианты, все без замечаний; отказ угловой и П с числами', () => {
    for (const пом of помещенияЗаказчика().filter((x) => x.id !== 'кв160-гардеробная')) {
      const р = предложитьПланировки(новыйПроектV2(пом.название, пом));
      expect(р.назначение, пом.название).toBe('ниша');
      expect(р.варианты.length, пом.название).toBeGreaterThanOrEqual(1);
      for (const в of р.варианты) {
        expect(в.тип).toBe('линейная');
        проверитьВариант(в);
      }
      expect(р.отказы[0].причина).toMatch(/\d+ × \d+ мм/);
    }
  });

  it('ниша кв. 160 под купе: короб 507 × 608 обойдён полками под и над ним, техническая ниша — заметкой', () => {
    const пом = помещенияЗаказчика()[0];
    const р = предложитьПланировки(новыйПроектV2('Ниша', пом));
    expect(р.варианты).toHaveLength(3);
    const в = р.варианты[0];
    expect(в.учтено.some((т) => т.startsWith('короб 507 × 608') && т.includes('под ним полки до 980') && т.includes('над ним полки с 1608'))).toBe(true);
    expect(в.учтено.some((т) => т.includes('запретная зона') && т.includes('120 × 460'))).toBe(true);
    // высота до потолка минус 50 на сборку
    expect(в.проект.объекты.find((о) => о.изделие.startsWith('шкаф-купе'))!.габариты.в).toBe(2650);
  });

  it('прихожая кв. 281: щитки внутри шкафа — заметкой, короб у пола обойдён полками сверху', () => {
    const пом = помещенияЗаказчика()[3];
    const р = предложитьПланировки(новыйПроектV2('Прихожая', пом));
    const учтено = р.варианты.flatMap((в) => в.учтено).join('\n');
    expect(учтено).toMatch(/короб 510 × 820.*над ним полки с 830/);
    expect(учтено).toMatch(/Щиток .* без задника и полок, доступ через створку/);
  });
});

describe('«Предложи планировку» на кухнях', () => {
  it('кухня 3600 × 2800 и демо 4200 × 3000: линейная, угловая, П-образная без замечаний', () => {
    for (const п of [новыйПроектV2('Кухня'), демо()]) {
      const р = предложитьПланировки(п);
      expect(р.назначение).toBe('кухня');
      expect(р.варианты.map((в) => в.тип)).toEqual(['линейная', 'угловая', 'П-образная']);
      for (const в of р.варианты) {
        проверитьВариант(в);
        expect(в.числа.столешницаМ).toBeGreaterThan(1.5);
        const ид = в.проект.объекты.map((о) => о.изделие);
        for (const нужно of ['холодильник', 'тумба-под-мойку', 'мойка', 'варочная', 'столешница']) expect(ид.some((x) => x.startsWith(нужно)), нужно).toBe(true);
      }
      // треугольник или рабочая линия — с цифрами
      expect(р.варианты[1].учтено.some((т) => т.startsWith('Треугольник') || т.startsWith('Рабочая линия'))).toBe(true);
    }
  });

  it('в демо стол и стулья переносятся в линейный вариант, а там, где мешают проходу, убираются с пометкой', () => {
    const р = предложитьПланировки(демо());
    expect(р.варианты[0].проект.объекты.some((о) => о.изделие.startsWith('стол-обеденный'))).toBe(true);
    const сУбранным = р.варианты.find((в) => в.учтено.some((т) => т.includes('убран из варианта')));
    expect(сУбранным).toBeDefined();
  });

  it('кухня с дверью, окном, радиатором и водой: ничего перед дверью и радиатором, мойка у воды', () => {
    const р = предложитьПланировки(кухняСОтметками());
    expect(р.варианты).toHaveLength(3);
    for (const в of р.варианты) {
      проверитьВариант(в);
      // радиатор: правая стена (x = 3200), z 750…1850 — перед ним (x > 3000) ни одного корпуса у пола
      for (const о of в.проект.объекты) {
        const изд = изделиеПоИд(о.изделие)!;
        if (изд.тип === 'проём' || о.позиция[1] > 200) continue;
        const у = следУглы(о.позиция, о.поворот, о.габариты.ш, о.габариты.г);
        const xMax = Math.max(...у.map((t) => t[0]));
        const z0 = Math.min(...у.map((t) => t[1]));
        const z1 = Math.max(...у.map((t) => t[1]));
        expect(xMax > 3060 && z1 > 760 && z0 < 1840, `${о.изделие} перед радиатором`).toBe(false);
      }
      const вода = в.учтено.find((т) => т.startsWith('Мойка в'));
      expect(вода).toBeDefined();
      expect(Number(/Мойка в (\d+) мм/.exec(вода!)![1])).toBeLessThanOrEqual(1000);
      expect(в.учтено.some((т) => т.startsWith('Дверь 800'))).toBe(true);
      expect(в.учтено.some((т) => т.startsWith('Радиатор 1000'))).toBe(true);
    }
  });

  it('маленькая кухня 2400 × 1800: линейная не встаёт — отказ с миллиметрами, остальные без замечаний', () => {
    const р = предложитьПланировки(новыйПроектV2('Малая', новоеПомещение('п1', 'кухня', 'Кухня', прямоугольник(2400, 1800))));
    const отказ = р.отказы.find((о) => о.тип === 'Линейная');
    expect(отказ?.причина).toMatch(/2500 мм.*2400 мм/);
    for (const в of р.варианты) проверитьВариант(в);
  });

  it('исходный проект не меняется, расчёт укладывается в 2 секунды на помещение', () => {
    const п = демо();
    const было = JSON.stringify(копияПроекта(п));
    const t = performance.now();
    предложитьПланировки(п);
    expect(performance.now() - t).toBeLessThan(2000);
    expect(JSON.stringify(п)).toBe(было);
  });

  it('назначение: ниша уже 900 мм, кухня, остальное — хранение', () => {
    expect(назначениеПомещения(помещенияЗаказчика()[0])).toBe('ниша');
    expect(назначениеПомещения(новоеПомещение('к', 'кухня', 'К', прямоугольник(3000, 2500)))).toBe('кухня');
    expect(назначениеПомещения(новоеПомещение('с', 'спальня', 'С', прямоугольник(3500, 3000)))).toBe('хранение');
  });
});
