/**
 * Полная смета: листы с отходом целыми, петли по высоте дверей, направляющие по ящикам, светильники и натяжной потолок,
 * обмер помещения; единицы мм / см / м.
 */
import { describe, expect, it } from 'vitest';
import { новоеПомещение, прямоугольник } from './помещение';
import { новыйПроектV2, новыйЭкземпляр } from './проект';
import { изделиеПоИд } from './каталог';
import { полнаяСмета, суммаСтроки, числоПетель } from './смета-полная';
import { движенияИзделия } from './открывание';
import { НАТЯЖНОЙ_ПО_УМОЛЧАНИЮ } from './потолок';
import { длина, всеЕдиницы, площадьМ2 } from './единицы';
import type { ПроектV2 } from './типы';

function проект(): ПроектV2 {
  const пом = { ...новоеПомещение('п1', 'спальня', 'Спальня', прямоугольник(3600, 2800, false)), натяжной_потолок: НАТЯЖНОЙ_ПО_УМОЛЧАНИЮ };
  const п = новыйПроектV2('Смета', пом);
  const шкаф = новыйЭкземпляр(изделиеПоИд('шкаф-распашной-900')!, 'п1', [600, 0, 400]);
  const тумба = новыйЭкземпляр(изделиеПоИд('тумба-ящики-600')!, 'п1', [1800, 0, 400]);
  const спот = изделиеПоИд('светильник-точечный-gx53')!;
  const споты = [0, 1, 2].map((i) => новыйЭкземпляр(спот, 'п1', [900 + i * 900, 2638, 1400]));
  return { ...п, объекты: [шкаф, тумба, ...споты] };
}

const строка = (с: ReturnType<typeof полнаяСмета>, ключ: string) => с.строки.find((x) => x.ключ === ключ);

describe('полная смета', () => {
  it('листы ЛДСП и ХДФ — целыми, с отходом; кромка с запасом', () => {
    const с = полнаяСмета(проект());
    const л = строка(с, 'лдсп-корпус')!;
    expect(Number.isInteger(л.количество)).toBe(true);
    expect(л.количество).toBeGreaterThanOrEqual(1);
    expect(л.пояснение).toMatch(/15 % отход/);
    expect(строка(с, 'хдф')!.количество).toBeGreaterThanOrEqual(1);
    expect(строка(с, 'кромка-04')?.мм ?? строка(с, 'кромка-2')?.мм).toBeGreaterThan(0);
  });

  it('петли — по высоте каждой двери (то же правило, что рисует 3D), направляющие — пара на ящик', () => {
    const п = проект();
    const с = полнаяСмета(п);
    let петли = 0;
    let ящики = 0;
    for (const э of п.объекты) {
      for (const д of движенияИзделия(изделиеПоИд(э.изделие)!, э)) {
        if (д.вид === 'дверь') петли += числоПетель(д.главная.объём[1]);
        if (д.вид === 'ящик') ящики++;
      }
    }
    expect(петли).toBeGreaterThan(0);
    expect(строка(с, 'петли')!.количество).toBe(петли);
    expect(строка(с, 'направляющие')!.количество).toBe(ящики);
    expect(строка(с, 'полкодержатели')!.количество % 4).toBe(0);
  });

  it('свет и натяжной потолок: штуки светильников, площадь полотна, багет, монтаж', () => {
    const с = полнаяСмета(проект());
    expect(строка(с, 'шт:светильник-точечный-gx53')!.количество).toBe(3);
    expect(строка(с, 'потолок-натяжной')!.количество).toBeCloseTo(10.08, 2);
    expect(строка(с, 'багет')!.мм).toBe(12800);
    expect(строка(с, 'монтаж-света')!.количество).toBe(3);
    expect(строка(с, 'пол')!.количество).toBeCloseTo(10.08 * 1.07, 2);
  });

  it('сумма строки — только с ценой', () => {
    const с = полнаяСмета(проект());
    const л = строка(с, 'лдсп-корпус')!;
    expect(суммаСтроки(л, undefined)).toBeNull();
    expect(суммаСтроки(л, 3500)).toBe(л.количество * 3500);
  });
});

describe('единицы', () => {
  it('мм, см, м с запятой', () => {
    expect(длина(275, 'мм')).toBe('275 мм');
    expect(длина(275, 'см')).toBe('27,5 см');
    expect(длина(275, 'м')).toBe('0,275 м');
    expect(длина(2700, 'м')).toBe('2,7 м');
    expect(всеЕдиницы(12800)).toBe('12800 мм · 1280 см · 12,8 м');
    expect(площадьМ2(10.08)).toBe('10,08 м²');
  });
});
