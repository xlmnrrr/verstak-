import { describe, expect, it } from 'vitest';
import { изделиеПоИд } from './каталог';
import { контурГ, контурП, новоеПомещение, прямоугольник } from './помещение';
import { новыйПроектV2, новыйЭкземпляр } from './проект';
import { следУглы, выступЗаКонтур, проверитьВлезает, найтиМесто, глубинаПересечения } from './проверка';
import { коробаСтен } from './стены';

const проектКомнаты = (ш = 3600, г = 2800) => новыйПроектV2('т', новоеПомещение('п1', 'кухня', 'Кухня', прямоугольник(ш, г)));
const тумба = () => {
  const и = изделиеПоИд('тумба-ящики-600');
  if (!и) throw new Error('нет изделия для теста');
  return и;
};

describe('влезает', () => {
  it('след у стены не считается ошибкой, за стеной — считается', () => {
    const п = проектКомнаты();
    const контур = п.помещения[0].контур;
    expect(выступЗаКонтур(контур, следУглы([0, 0, -1100], 0, 600, 600))).toBe(0);
    expect(выступЗаКонтур(контур, следУглы([0, 0, -1300], 0, 600, 600))).toBe(200);
  });

  it('модуль шире комнаты помечается и даёт цифру', () => {
    const п = проектКомнаты(1000, 2800);
    const э = { ...новыйЭкземпляр(тумба(), 'п1'), габариты: { ш: 1400, г: 600, в: 720 } };
    п.объекты.push(э);
    const пр = проверитьВлезает(п);
    expect(пр.some((x) => x.id === э.id && x.вид === 'вне-помещения' && x.мм >= 200)).toBe(true);
  });

  it('вырез Г: шкаф поперёк выреза не влезает', () => {
    const к = контурГ(4000, 3000, 1500, 1200).map(([x, z]) => [x, z] as [number, number]);
    expect(выступЗаКонтур(к, следУглы([3000, 0, 2300], 0, 1500, 600))).toBeGreaterThan(0);
    expect(выступЗаКонтур(к, следУглы([1000, 0, 1000], 0, 600, 600))).toBe(0);
  });

  it('два корпуса друг в друге — пересечение; встык — нет', () => {
    const п = проектКомнаты();
    const а = { ...новыйЭкземпляр(тумба(), 'п1'), позиция: [0, 0, -1000] as [number, number, number] };
    const б = { ...новыйЭкземпляр(тумба(), 'п1'), позиция: [100, 0, -1000] as [number, number, number] };
    п.объекты.push(а, б);
    expect(проверитьВлезает(п).filter((x) => x.вид === 'пересечение').length).toBe(2);
    б.позиция = [а.габариты.ш, 0, -1000];
    expect(проверитьВлезает(п).filter((x) => x.вид === 'пересечение').length).toBe(0);
  });

  it('выше стен', () => {
    const п = проектКомнаты();
    const э = { ...новыйЭкземпляр(тумба(), 'п1'), позиция: [0, 2500, -1000] as [number, number, number] };
    п.объекты.push(э);
    expect(проверитьВлезает(п).some((x) => x.вид === 'выше-стен')).toBe(true);
  });

  it('SAT: касание не пересечение', () => {
    const а = следУглы([0, 0, 0], 0, 600, 600);
    const б = следУглы([600, 0, 0], 0, 600, 600);
    expect(глубинаПересечения(а, б)).toBe(0);
  });
});

describe('поиск места для новой тумбы', () => {
  it('у задней стены лицом в комнату, внутри контура, не в стене', () => {
    const п = проектКомнаты();
    const изд = тумба();
    const м = найтиМесто(п, 'п1', изд.габариты, 0)!;
    expect(м).not.toBeNull();
    expect(выступЗаКонтур(п.помещения[0].контур, следУглы(м.позиция, м.поворот, изд.габариты.ш, изд.габариты.г))).toBe(0);
  });

  it('когда задняя стена занята, встаёт на другую стену и не пересекает соседей', () => {
    const п = проектКомнаты();
    const изд = тумба();
    for (let i = 0; i < 12; i++) {
      const м = найтиМесто(п, 'п1', изд.габариты, 0);
      expect(м, `шаг ${i}`).not.toBeNull();
      const э = { ...новыйЭкземпляр(изд, 'п1', м!.позиция), поворот: м!.поворот };
      п.объекты.push(э);
    }
    expect(проверитьВлезает(п)).toEqual([]);
  });

  it('в Г и П-помещении ставит внутрь контура', () => {
    for (const контур of [контурГ(4000, 3000, 1500, 1200), контурП(4500, 3200, 1500, 1000)]) {
      const п = новыйПроектV2('т', новоеПомещение('п1', 'кухня', 'К', контур));
      const изд = тумба();
      for (let i = 0; i < 8; i++) {
        const м = найтиМесто(п, 'п1', изд.габариты, 0)!;
        expect(м).not.toBeNull();
        п.объекты.push({ ...новыйЭкземпляр(изд, 'п1', м.позиция), поворот: м.поворот });
      }
      expect(проверитьВлезает(п)).toEqual([]);
    }
  });

  it('модуль шире комнаты — места нет', () => {
    const п = проектКомнаты(1000, 1000);
    expect(найтиМесто(п, 'п1', { ш: 1400, г: 600, в: 720 }, 0)).toBeNull();
  });
});

describe('стены из контура', () => {
  it('прямоугольник: четыре стены без щелей, углы закрыты', () => {
    const п = новоеПомещение('п', 'кухня', 'К', прямоугольник(4000, 3000));
    const { стены } = коробаСтен(п);
    expect(стены).toHaveLength(4);
    const суммаДлин = стены.reduce((s, c) => s + c.размер[0], 0);
    // по периметру внешнего контура: 2·(4000+200) + 2·(3000+200) = 14800
    expect(Math.round(суммаДлин)).toBe(14800);
  });

  it('Г (6 точек): шесть стен, вогнутый угол укорочен', () => {
    const п = новоеПомещение('п', 'кухня', 'К', контурГ(4000, 3000, 1500, 1200));
    const { стены } = коробаСтен(п);
    expect(стены).toHaveLength(6);
    // периметр внутреннего контура 14200; выпуклых углов 5, вогнутый 1: +5·100·... = внешний периметр
    const внутр = 4000 + 3000 + 1800 + 1500 + 1200 + 2500;
    const сумма = стены.reduce((s, c) => s + c.размер[0], 0);
    expect(Math.round(сумма)).toBe(внутр + 2 * 100 * (5 - 1) );
  });

  it('П (8 точек): восемь стен', () => {
    const п = новоеПомещение('п', 'кухня', 'К', контурП(4500, 3200, 1500, 1000));
    expect(коробаСтен(п).стены).toHaveLength(8);
  });

  it('дверь режет стену: над проёмом остаётся перемычка', () => {
    const п = новоеПомещение('п', 'кухня', 'К', прямоугольник(4000, 3000));
    п.отметки.push({ id: 'д', стена: 0, вид: 'дверь', от_угла: 1000, от_пола: 0, ширина: 900, высота: 2100 });
    const { стены } = коробаСтен(п);
    const перемычка = стены.filter((c) => Math.abs(c.размер[0] - 900) < 1 && Math.abs(c.размер[1] - 600) < 1);
    expect(перемычка).toHaveLength(1);
    expect(стены.length).toBe(4 + 2);
  });
});
