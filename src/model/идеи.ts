/** Проект из идеи: комната по размерам идеи, предметы на местах, «свободная сборка» включена */
export function проектИдеи(идея: Идея): ПроектV2 {
  const контур = прямоугольник(идея.ширина, идея.глубина);
  const пом = новоеПомещение('п1', идея.тип, идея.название.split(':')[0], контур, 2700);
  пом.отметки = идея.отметки.map((о, i) => ({ id: `о${i}`, ...о }));
  const п = новыйПроектV2(идея.название, пом);
  п.настройки.свободная_сборка = true;
  const xs = контур.map((т) => т[0]);
  const zs = контур.map((т) => т[1]);
  const cx = (Math.min(...xs) + Math.max(...xs)) / 2;
  const cz = (Math.min(...zs) + Math.max(...zs)) / 2;
  let n = 0;
  for (const [id, x, z, поворот, y, мат] of идея.предметы) {
    const изд = изделиеПоИд(id);
    if (!изд) continue;
    const э = новыйЭкземпляр(изд, пом.id, [cx + x, y ?? (изд.крепление === 'стена' ? (изд.подъём ?? 1500) : 0), cz + z], `идея${n++}`);
    э.поворот = поворот;
    if (id === 'столешница-3000' && идея.id === 'кухня-студия') э.габариты = { ...э.габариты, ш: 3200 };
    if (id === 'ковёр-2000' && идея.id === 'кухня-студия') э.габариты = { ...э.габариты, ш: 2300, г: 1700 };
    if (id === 'шторы-с-тюлем-2000') э.габариты = { ...э.габариты, ш: 2100 };
    if (мат) э.материалы = мат as Материалы;
    п.объекты.push(э);
  }
  return п;
}
