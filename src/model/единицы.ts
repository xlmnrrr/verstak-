/**
 * Единицы показа (пожелание Макара 13.11.2026): значения не только в мм, но и в см и м.
 * Данные всегда хранятся в мм; показ — в выбранной единице, рядом — остальные. Запятая — десятичный знак.
 */
export type Единица = 'мм' | 'см' | 'м';

const число = (v: number, знаков: number) => {
  const т = (Math.round(v * 10 ** знаков) / 10 ** знаков).toFixed(знаков).replace(/\.?0+$/, '');
  return т.replace('.', ',');
};

/** «275 мм», «27,5 см», «0,275 м» */
export function длина(мм: number, е: Единица = 'мм'): string {
  if (е === 'см') return `${число(мм / 10, 1)} см`;
  if (е === 'м') return `${число(мм / 1000, 3)} м`;
  return `${Math.round(мм)} мм`;
}

/** Все три: «275 мм · 27,5 см · 0,275 м» */
export const всеЕдиницы = (мм: number) => `${длина(мм, 'мм')} · ${длина(мм, 'см')} · ${длина(мм, 'м')}`;

/** Площадь из мм² в м²: «10,08 м²» */
export const площадьМ2 = (м2: number) => `${число(м2, 2)} м²`;
