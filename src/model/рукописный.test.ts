/**
 * Этап 7: проект, написанный руками в блокноте, открывается. Образец — public/Библиотека/проект-руками.kitchen
 * (три предмета), он же — пример в схема-проекта.md. Таблица изделий в схеме сверяется с каталогом;
 * пересобрать её: SCHEMA_TABLE=1 npx vitest run src/model/рукописный.test.ts
 */
import { describe, expect, it } from 'vitest';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { разобратьФайл } from './файл';
import { проверитьПроект } from './валидатор';
import { КАТАЛОГ_V2 } from './каталог';
import { детали } from './детали';
import { изделиеПоИд } from './каталог';

const БИБЛИОТЕКА = join(process.cwd(), 'public', 'Библиотека');
const СХЕМА = join(БИБЛИОТЕКА, 'схема-проекта.md');
const РУКАМИ = join(БИБЛИОТЕКА, 'проект-руками.kitchen');
const НАЧАЛО = '<!-- ТАБЛИЦА-ИЗДЕЛИЙ';
const КОНЕЦ = '<!-- /ТАБЛИЦА-ИЗДЕЛИЙ -->';

function таблица(): string {
  const строки = ['| id | Что | Вид, крепление | Ш × Г × В | Мин | Макс |', '|---|---|---|---|---|---|'];
  const г = (x: { ш: number; г: number; в: number }) => `${x.ш} × ${x.г} × ${x.в}`;
  for (const и of КАТАЛОГ_V2) строки.push(`| \`${и.id}\` | ${и.название} | ${и.тип}, ${и.крепление}${и.подъём ? ` (низ ${и.подъём})` : ''} | ${г(и.габариты)} | ${г(и.границы.мин)} | ${г(и.границы.макс)} |`);
  return строки.join('\n');
}

describe('проект руками (схема для блокнота)', () => {
  const текст = readFileSync(РУКАМИ, 'utf8');

  it('проект-руками.kitchen открывается без ошибок и предупреждений: три предмета, все изделия из каталога', () => {
    const р = разобратьФайл(текст);
    expect(р.ошибки).toEqual([]);
    expect(р.ок).toBe(true);
    expect(р.предупреждения).toEqual([]);
    expect(р.проект!.объекты).toHaveLength(3);
    for (const э of р.проект!.объекты) {
      const изд = изделиеПоИд(э.изделие);
      expect(изд, э.изделие).toBeDefined();
      // детали строятся: предмет действительно рисуется в 3D
      expect(детали(изд!, э).length).toBeGreaterThan(0);
    }
    // материал из библиотеки и раскладка по умолчанию дошли до экземпляра
    expect(р.проект!.объекты[1].материалы?.фасад).toBe('дуб-натуральный');
    // настройки, которых нет в файле, подставлены
    expect(р.проект!.настройки.шаг_сетки).toBe(50);
  });

  it('у проекта руками нет замечаний валидатора (нормы соблюдены: проходы у кровати, дверь, стены)', () => {
    const з = проверитьПроект(разобратьФайл(текст).проект!);
    expect(з.map((x) => x.текст)).toEqual([]);
  });

  it('пример в схема-проекта.md — тот же файл, и он открывается', () => {
    const md = readFileSync(СХЕМА, 'utf8');
    const блок = /```json\n([\s\S]*?)\n```/.exec(md.replace(/\r\n/g, '\n'));
    expect(блок).not.toBeNull();
    const изСхемы = JSON.parse(блок![1]);
    expect(изСхемы).toEqual(JSON.parse(текст));
    expect(разобратьФайл(блок![1]).ок).toBe(true);
  });

  it('ошибка в рукописном файле объясняется с путём до поля', () => {
    const сломан = JSON.parse(текст);
    сломан.объекты[0].габариты.ш = '1800';
    const р = разобратьФайл(JSON.stringify(сломан));
    expect(р.ок).toBe(false);
    expect(р.ошибки.join(' ')).toMatch(/объекты\.0\.габариты\.ш/);
    const безЗапятой = текст.replace('"поворот": 0,', '"поворот": 0');
    expect(разобратьФайл(безЗапятой).ошибки[0]).toMatch(/Это не JSON/);
  });

  it('таблица изделий в схеме совпадает с каталогом (id, габариты, границы)', () => {
    const md = readFileSync(СХЕМА, 'utf8');
    const н = md.indexOf(НАЧАЛО);
    const к = md.indexOf(КОНЕЦ);
    expect(н).toBeGreaterThan(0);
    expect(к).toBeGreaterThan(н);
    const перваяСтрока = md.indexOf('\n', н) + 1;
    if (process.env.SCHEMA_TABLE) {
      writeFileSync(СХЕМА, md.slice(0, перваяСтрока) + таблица() + '\n' + md.slice(к), 'utf8');
      return;
    }
    expect(md.slice(перваяСтрока, к).replace(/\r\n/g, '\n').trim()).toBe(таблица());
  });
});
