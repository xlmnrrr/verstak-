/** Подпись отметки на сцене и плане: тип и высота от пола — «Розетка · 300» */
export const подписьОтметки = (о: Pick<Отметка, 'вид' | 'от_пола'>): string => `${описаниеВида(о.вид).название} · ${Math.round(о.от_пола)}`;

/** Полная строка для списка: «Розетка · задняя стена · 340 от угла · 250 от пола · 80 × 80» */
export function строкаОтметки(пом: Помещение, о: Отметка): string {
  return `${описаниеВида(о.вид).название} · ${имяСтены(пом, о.стена)} · ${Math.round(о.от_угла)} от угла · ${Math.round(о.от_пола)} от пола · ${Math.round(о.ширина)} × ${Math.round(о.высота)}${о.глубина ? ` × ${Math.round(о.глубина)}` : ''}`;
}

/** Длина стены помещения, мм */
export const длинаСтены = (пом: Помещение, стена: number): number => рёбра(пом.контур)[стена]?.длина ?? 0;

/**
 * Что не так с отметкой: выходит за стену, выше потолка, нулевой размер. Пусто — всё в порядке.
 * Тексты с цифрами, как в «Проверках».
 */
export function проверитьОтметку(пом: Помещение, о: Отметка): string[] {
  const итог: string[] = [];
  const L = длинаСтены(пом, о.стена);
  const H = высотаДляРендера(пом);
  const имя = описаниеВида(о.вид).название;
  if (!L) итог.push(`${имя}: стены ${о.стена + 1} нет в помещении.`);
  if (о.ширина <= 0 || о.высота <= 0) итог.push(`${имя}: ширина и высота должны быть больше нуля.`);
  if (о.от_угла < 0) итог.push(`${имя}: отступ от угла ${Math.round(о.от_угла)} мм — меньше нуля.`);
  if (L && о.от_угла + о.ширина > L + 0.5) итог.push(`${имя}: выходит за стену на ${Math.round(о.от_угла + о.ширина - L)} мм — стена ${Math.round(L)} мм, отступ ${Math.round(о.от_угла)} + ширина ${Math.round(о.ширина)}.`);
  if (о.от_пола < 0) итог.push(`${имя}: высота от пола ${Math.round(о.от_пола)} мм — меньше нуля.`);
  if (о.от_пола + о.высота > H + 0.5) итог.push(`${имя}: выше потолка на ${Math.round(о.от_пола + о.высота - H)} мм — потолок ${H} мм.`);
  return итог;
}

/** Поставить отметку в границы стены и потолка (размеры урезаются, если не помещаются) */
export function вГраницы(пом: Помещение, о: Отметка): Отметка {
  const L = длинаСтены(пом, о.стена);
  const H = высотаДляРендера(пом);
  const ширина = Math.max(10, Math.min(Math.round(о.ширина), Math.max(10, L)));
  const высота = Math.max(10, Math.min(Math.round(о.высота), H));
  const от_угла = Math.max(0, Math.min(Math.round(о.от_угла), Math.max(0, L - ширина)));
  const от_пола = Math.max(0, Math.min(Math.round(о.от_пола), H - высота));
  const р: Отметка = { ...о, ширина, высота, от_угла, от_пола };
  if (о.глубина !== undefined) р.глубина = Math.max(1, Math.round(о.глубина));
  return р;
}

/** Новый id отметки, которого нет в помещении: «о1», «о2»… */
export function новыйИдОтметки(пом: Помещение): string {
  const есть = new Set(пом.отметки.map((о) => о.id));
  for (let i = пом.отметки.length + 1; ; i++) if (!есть.has(`о${i}`)) return `о${i}`;
}

/** Отметка с размерами по умолчанию для вида: посередине стены (или с заданным отступом), сразу в границах */
export function новаяОтметка(пом: Помещение, вид: ВидОтметки, стена: number, поля: Partial<Pick<Отметка, 'от_угла' | 'от_пола' | 'ширина' | 'высота' | 'глубина'>> = {}): Отметка {
  const о = описаниеВида(вид);
  const L = длинаСтены(пом, стена);
  const ширина = поля.ширина ?? о.ширина;
  const черновик: Отметка = {
    id: новыйИдОтметки(пом),
    стена,
    вид,
    от_угла: поля.от_угла ?? Math.round((L - ширина) / 2),
    от_пола: поля.от_пола ?? о.от_пола,
    ширина,
    высота: поля.высота ?? (вид === 'короб' ? высотаДляРендера(пом) : о.высота),
  };
  const глубина = поля.глубина ?? о.глубина;
  if (глубина !== undefined && !о.проём && вид !== 'ниша') черновик.глубина = глубина;
  if (вид === 'ниша') черновик.глубина = поля.глубина ?? о.глубина;
  return вГраницы(пом, черновик);
}

/* ------------------------------------------------------------------ правки помещения (для команды истории) */

export const сОтметкой = (пом: Помещение, о: Отметка): Помещение => ({ ...пом, отметки: [...пом.отметки, вГраницы(пом, о)] });

export const сИзменённойОтметкой = (пом: Помещение, id: string, патч: Partial<Omit<Отметка, 'id'>>): Помещение => ({
  ...пом,
  отметки: пом.отметки.map((о) => (о.id === id ? вГраницы(пом, { ...о, ...патч }) : о)),
});

export const безОтметки = (пом: Помещение, id: string): Помещение => ({ ...пом, отметки: пом.отметки.filter((о) => о.id !== id) });

/** Подвинуть вдоль стены на Δ мм (в границах стены) */
export const сдвинутьОтметку = (пом: Помещение, id: string, Δ: number): Помещение => {
  const о = пом.отметки.find((x) => x.id === id);
  return о ? сИзменённойОтметкой(пом, id, { от_угла: о.от_угла + Δ }) : пом;
};

/**
 * Точка подписи отметки в осях помещения (мм): середина отметки на высоте её верха, чуть в комнату от стены.
 * Подпись видна над розеткой, а не внутри стены.
 */
export function точкаПодписи(пом: Помещение, о: Отметка): [number, number, number] | null {
  const с = рёбра(пом.контур)[о.стена];
  if (!с) return null;
  const s = о.от_угла + о.ширина / 2;
  const t = (о.глубина ?? 0) + 40;
  const y = Math.min(высотаДляРендера(пом) - 40, о.от_пола + Math.min(о.высота, 2400) + 60);
  return [с.а[0] + с.направление[0] * s + с.нормаль[0] * t, y, с.а[1] + с.направление[1] * s + с.нормаль[1] * t];
}
