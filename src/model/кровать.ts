/**
 * Эталон 3 (проход 1): кровать с подъёмным механизмом. Оси изделия как у всех: X — ширина, Y — высота, Z — глубина;
 * изголовье — сзади (−Z), ноги — спереди (+Z). Размеры типовые (матрас 1600 × 2000).
 *
 * В деталировку идут плиты: царги (боковины), спинка-основа изголовья, дно бельевого ящика, цоколь.
 * Фурнитура (в деталировку не идёт): рама основания из профиля 40 × 25, ламели берёзы 53 × 8, два газлифта.
 * Подвижная группа «подъёмник-0»: рама с ламелями (и матрас в рендере) поднимается у изножья на 45° вокруг оси у изголовья.
 * Матрас, мягкая обивка изголовья и подушки — только рендер (render/модели/кровать.ts).
 */
import type { Вектор3, Габариты, Деталь, Изделие, Кромка } from './типы';
import { кромкаНаГрани } from './угловой';

const кр0 = (): Кромка => ({ длина1: 0, длина2: 0, ширина1: 0, ширина2: 0 });
const ок = (v: number) => Math.round(v * 100) / 100;

function плита(роль: Деталь['роль'], x0: number, x1: number, y0: number, y1: number, z0: number, z1: number, материал: Деталь['материал'], кромка: (о: Вектор3) => Кромка, доп: Partial<Деталь> = {}): Деталь {
  const о: Вектор3 = [x1 - x0, y1 - y0, z1 - z0];
  const размер = [...о].sort((a, b) => b - a) as Вектор3;
  return {
    роль,
    размер: [ок(размер[0]), ок(размер[1]), ок(размер[2])],
    кромка: кромка(о),
    материал,
    локально: { центр: [ок((x0 + x1) / 2), ок((y0 + y1) / 2), ок((z0 + z1) / 2)], объём: [ок(о[0]), ок(о[1]), ок(о[2])] },
    форма: 'плита',
    ...доп,
  };
}

export const ГРУППА_ПОДЪЁМНИКА = 'подъёмник-0';
/** Угол подъёма основания, градусы */
export const УГОЛ_ПОДЪЁМА = 45;

/** Размеры кровати по габаритам: толщина изголовья, высота царг, рама, матрас */
export function размерыКровати(габ: Габариты) {
  const W = габ.ш;
  const G = габ.г;
  const H = габ.в;
  const t = 16;
  const изголовье = Math.min(110, Math.max(70, Math.round(G * 0.05)));
  const цоколь = 40;
  const верхЦарги = Math.min(380, Math.max(260, H * 0.36));
  const zГ = -G / 2 + изголовье; // передняя плоскость изголовья
  const zН = G / 2; // изножье
  // рама основания внутри царг, верх рамы на 8 мм ниже верха царг (ламели вровень)
  const рама = { x0: -W / 2 + t + 4, x1: W / 2 - t - 4, z0: zГ + t + 4, z1: zН - t - 4, yВерх: верхЦарги - 8, h: 25, ш: 40 };
  const матрас = { ш: W - 2 * t - 10, г: zН - zГ - 2 * t - 10, в: Math.min(240, Math.max(160, H * 0.21)) };
  return { W, G, H, t, изголовье, цоколь, верхЦарги, zГ, zН, рама, матрас };
}

const крЛицо = (ось: number, знак: 1 | -1) => (о: Вектор3) => кромкаНаГрани(о, ось, знак, 2);
const МЕТАЛЛ = { цвет: '#1e1f22', шер: 0.5, мет: 0.65 };
const БЕРЁЗА = { цвет: '#d9bd8f', шер: 0.62, мет: 0 };
const ХРОМ = { цвет: '#e3e6ea', шер: 0.15, мет: 1 };

/** Детали кровати с подъёмником в осях изделия */
export function деталиКроватиПодъёмной(изд: Изделие, габ: Габариты): Деталь[] {
  const р = размерыКровати(габ);
  const { W, t, цоколь, верхЦарги, zГ, zН, рама, H } = р;
  const G = габ.г;
  const д: Деталь[] = [];
  const п = { подвижная: { группа: ГРУППА_ПОДЪЁМНИКА } };

  // изголовье-основа (ЛДСП), по всей ширине; мягкая обивка — в рендере на его лицевой стороне
  д.push(плита('спинка', -W / 2, W / 2, 0, H, -G / 2, -G / 2 + t * 2, 'фасад', крЛицо(1, 1)));
  // царги: две боковины и изножье, кромка по верху и лицу
  for (const s of [-1, 1]) д.push(плита('боковина', s > 0 ? W / 2 - t : -W / 2, s > 0 ? W / 2 : -W / 2 + t, цоколь, верхЦарги, zГ, zН - t, 'фасад', крЛицо(1, 1)));
  д.push(плита('боковина', -W / 2, W / 2, цоколь, верхЦарги, zН - t, zН, 'фасад', крЛицо(1, 1)));
  // задняя стенка ящика у изголовья
  д.push(плита('перегородка', -W / 2 + t, W / 2 - t, цоколь, верхЦарги - 30, zГ, zГ + t, 'корпус', крЛицо(1, 1)));
  // дно бельевого ящика
  д.push(плита('дно', -W / 2 + t, W / 2 - t, цоколь, цоколь + t, zГ + t, zН - t, 'корпус', кр0));
  // цоколь утоплен на 30 мм
  for (const s of [-1, 1]) д.push(плита('цоколь', s > 0 ? W / 2 - 30 - t : -W / 2 + 30, s > 0 ? W / 2 - 30 : -W / 2 + 30 + t, 0, цоколь, zГ + 30, zН - 30, 'корпус', кр0));
  д.push(плита('цоколь', -W / 2 + 30, W / 2 - 30, 0, цоколь, zН - 30 - t, zН - 30, 'корпус', кр0));

  // рама основания (группа подъёмника): профиль 40 × 25
  const y1 = рама.yВерх;
  const y0 = y1 - рама.h;
  const рамаЧасть = (x0: number, x1: number, z0: number, z1: number) => ({ ...плита('фурнитура', x0, x1, y0, y1, z0, z1, 'ручки', кр0), литерал: МЕТАЛЛ, ...п });
  д.push(рамаЧасть(рама.x0, рама.x0 + рама.ш, рама.z0, рама.z1));
  д.push(рамаЧасть(рама.x1 - рама.ш, рама.x1, рама.z0, рама.z1));
  д.push(рамаЧасть(рама.x0 + рама.ш, рама.x1 - рама.ш, рама.z0, рама.z0 + рама.ш));
  д.push(рамаЧасть(рама.x0 + рама.ш, рама.x1 - рама.ш, рама.z1 - рама.ш, рама.z1));
  // средняя продольная балка у широких кроватей
  if (W > 1300) д.push(рамаЧасть(-рама.ш / 2, рама.ш / 2, рама.z0 + рама.ш, рама.z1 - рама.ш));
  // ламели берёзы 53 × 8 поперёк рамы с шагом ~75 мм, на держателях поверх рамы
  const L = рама.z1 - рама.z0 - 60;
  const n = Math.max(6, Math.round(L / 75));
  for (let i = 0; i < n; i++) {
    const z = рама.z0 + 30 + (L * (i + 0.5)) / n;
    д.push({ ...плита('фурнитура', рама.x0 + 6, рама.x1 - 6, y1, y1 + 8, z - 26.5, z + 26.5, 'ручки', кр0), литерал: БЕРЁЗА, ...п });
  }
  // газлифты: корпус в ящике у царги (стоит), шток к раме (едет с рамой)
  for (const s of [-1, 1]) {
    const x = s * (W / 2 - t - 40);
    const zЦ = zГ + 260;
    д.push({ ...плита('фурнитура', x - 11, x + 11, цоколь + 60, цоколь + 82, zЦ - 160, zЦ + 160, 'ручки', кр0), форма: 'цилиндр', ось: 'z', литерал: МЕТАЛЛ });
    д.push({ ...плита('фурнитура', x - 5, x + 5, y0 - 20, y0 - 10, zЦ + 150, zЦ + 330, 'ручки', кр0), форма: 'цилиндр', ось: 'z', литерал: ХРОМ, ...п });
  }
  return д;
}

/** Положение главной части подъёмника (рама) — для движения и проверок */
export function рамаПодъёмника(габ: Габариты): { центр: Вектор3; объём: Вектор3 } {
  const { рама } = размерыКровати(габ);
  return {
    центр: [(рама.x0 + рама.x1) / 2, рама.yВерх - рама.h / 2 + 4, (рама.z0 + рама.z1) / 2],
    объём: [рама.x1 - рама.x0, рама.h + 8, рама.z1 - рама.z0],
  };
}
