import type { Деталь, Изделие, Положение, Помещение, СторонаПетель, Экземпляр, Вектор3, ВидОткрывания } from './типы';

export type Точка2 = [number, number];

/** Распашные двери и люки открываются на этот угол по умолчанию; параметр изделия и экземпляра (`угол_открывания`) */
export const УГОЛ_ДВЕРИ = 100;
/** Конфликты считаются на максимуме: реальная петля открывается дальше, чем нарисованная дверь */
export const УГОЛ_КОНФЛИКТА = 110;
/** Откидные вниз и подъёмники открываются ровно на 90° (дальше физически не бывает) */
const УГОЛ_ОТКИДНОЙ = 90;
export const УГОЛ_ДВЕРИ_МИН = 45;
export const УГОЛ_ДВЕРИ_МАКС = 135;

/**
 * Угол для проверки конфликтов: если угол задан явно (на экземпляре или изделии), считаем на нём; иначе на максимуме 110°,
 * потому что реальная петля открывается дальше нарисованных 100°. Дверь у боковой стены можно «успокоить», задав ей 90°.
 */
export function конфликтныйУгол(изд: Pick<Изделие, 'угол_открывания'>, экз: Pick<Экземпляр, 'угол_открывания'>): number {
  const явный = экз.угол_открывания ?? изд.угол_открывания;
  const у = уголОткрывания(изд, экз);
  return явный === undefined ? Math.max(у, УГОЛ_КОНФЛИКТА) : у;
}

/** Угол открывания распашных дверей: экземпляр, затем изделие, затем 100° */
export function уголОткрывания(изд: Pick<Изделие, 'угол_открывания'>, экз: Pick<Экземпляр, 'угол_открывания'>): number {
  const у = экз.угол_открывания ?? изд.угол_открывания ?? УГОЛ_ДВЕРИ;
  return Math.min(УГОЛ_ДВЕРИ_МАКС, Math.max(УГОЛ_ДВЕРИ_МИН, у));
}
/** Ящик выдвигается на эту долю глубины */
export const ВЫДВИЖЕНИЕ_ЯЩИКА = 0.8;
/** Перекрытие по высоте меньше этого (мм) не считается */
export const МИН_ПЕРЕКРЫТИЕ_ПО_ВЫСОТЕ = 1;
/** Меньше этого «не хватает» не показываем (шум округления) */
export const ДОПУСК_НЕ_ХВАТАЕТ = 4;
/** Касание стены или соседа без зазора не считается помехой */
const ЗАЗОР_КАСАНИЯ = 1.5;

/* ------------------------------------------------------------------ типы */

export type Кинематика =
  | { вид: 'поворот'; ось: Вектор3; опора: Вектор3; /** градусы со знаком вокруг +ось при полном открытии */ угол: number; /** угол для проверки конфликтов (не меньше 110° у распашных) */ конфликт?: number }
  | { вид: 'сдвиг'; вектор: Вектор3 };

export interface Движение {
  группа: string;
  вид: ВидОткрывания;
  /** «дверца 1», «ящик 2», «створка 3» … — для сообщений по-русски */
  подпись: string;
  кинематика: Кинематика;
  /** единичный вектор «наружу» (x, z) в осях изделия */
  фронт: Точка2;
  /** главная деталь группы (дверь, фасад ящика, створка) в закрытом положении */
  главная: Положение;
  /** габарит всей группы (все детали) в закрытом положении */
  часть: Положение;
}

/** Поза части: поворот вокруг опоры (матрица 3×3 по строкам) и затем сдвиг, оси изделия */
export interface Поза {
  сдвиг: Вектор3;
  R?: number[];
  опора?: Вектор3;
}

/* ------------------------------------------------------------------ вектора и матрицы */

/** Поворот на `градусы` вокруг единичной оси (Родриг), 3×3 по строкам */
export function матрицаПоворота(ось: Вектор3, градусы: number): number[] {
  const [x, y, z] = ось;
  const р = (градусы * Math.PI) / 180;
  const c = Math.cos(р);
  const s = Math.sin(р);
  const t = 1 - c;
  return [t * x * x + c, t * x * y - s * z, t * x * z + s * y, t * x * y + s * z, t * y * y + c, t * y * z - s * x, t * x * z - s * y, t * y * z + s * x, t * z * z + c];
}

const крест = (a: Вектор3, b: Вектор3): Вектор3 => [a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0]];
const скаляр = (a: Вектор3, b: Вектор3) => a[0] * b[0] + a[1] * b[1] + a[2] * b[2];

/** Поза части при доле открытия 0…1 */
export function позаДвижения(д: Движение, доля: number): Поза {
  const k = д.кинематика;
  if (k.вид === 'сдвиг') return { сдвиг: [k.вектор[0] * доля + 0, k.вектор[1] * доля + 0, k.вектор[2] * доля + 0] };
  if (доля <= 0) return { сдвиг: [0, 0, 0] };
  return { сдвиг: [0, 0, 0], R: матрицаПоворота(k.ось, k.угол * доля), опора: k.опора };
}

/* ------------------------------------------------------------------ движения изделия */

const ГЛАВНЫЕ_РОЛИ = new Set(['фасад', 'стекло', 'зеркало', 'ящик-фасад', 'техника']);

function объединение(д: Деталь[]): Положение {
  let x0 = Infinity,
    x1 = -Infinity,
    y0 = Infinity,
    y1 = -Infinity,
    z0 = Infinity,
    z1 = -Infinity;
  for (const x of д) {
    const [cx, cy, cz] = x.локально.центр;
    const [ox, oy, oz] = x.локально.объём;
    x0 = Math.min(x0, cx - ox / 2);
    x1 = Math.max(x1, cx + ox / 2);
    y0 = Math.min(y0, cy - oy / 2);
    y1 = Math.max(y1, cy + oy / 2);
    z0 = Math.min(z0, cz - oz / 2);
    z1 = Math.max(z1, cz + oz / 2);
  }
  return { центр: [(x0 + x1) / 2, (y0 + y1) / 2, (z0 + z1) / 2], объём: [x1 - x0, y1 - y0, z1 - z0] };
}

/** Поворот блока составного изделия по префиксу группы «имя/…» */
function поворотБлока(изд: Изделие, группа: string): number {
  const и = группа.indexOf('/');
  if (и < 0) return 0;
  return изд.состав?.find((б) => б.имя === группа.slice(0, и))?.поворот ?? 0;
}

const фронтБлока = (поворот: number): Точка2 => {
  const [x, z] = повернутьТочку(0, 1, поворот);
  return [Math.round(x), Math.round(z)];
};
const правоБлока = (поворот: number): Точка2 => {
  const [x, z] = повернутьТочку(1, 0, поворот);
  return [Math.round(x), Math.round(z)];
};

/** Размер положения вдоль горизонтального единичного вектора осей */
const вдоль = (о: Вектор3, в: Точка2) => Math.abs(в[0]) * о[0] + Math.abs(в[1]) * о[2];

/**
 * Дверь на петлях. `сторона` — где петля, глядя на фасад: слева, справа, сверху, снизу.
 * Свободный край поворачивается к наблюдателю на УГОЛ_ДВЕРИ.
 */
function кинематикаДвери(г: Положение, сторона: СторонаПетель, фронт: Точка2, право: Точка2, угол = УГОЛ_ОТКИДНОЙ, уголКонфликта?: number): Кинематика {
  const [cx, cy, cz] = г.центр;
  const w = вдоль(г.объём, право);
  const h = г.объём[1];
  const f: Вектор3 = [фронт[0], 0, фронт[1]];
  const r: Вектор3 = [право[0], 0, право[1]];
  if (сторона === 'сверху' || сторона === 'снизу') {
    const вверх = сторона === 'сверху';
    const опора: Вектор3 = [cx, вверх ? cy + h / 2 : cy - h / 2, cz];
    const u: Вектор3 = [0, вверх ? -1 : 1, 0];
    const знак = Math.sign(скаляр(r, крест(u, f))) || 1;
    return { вид: 'поворот', ось: r, опора, угол: знак * угол };
  }
  const слева = сторона !== 'справа';
  const опора: Вектор3 = [cx + (слева ? -1 : 1) * (право[0] * w) / 2, cy, cz + (слева ? -1 : 1) * (право[1] * w) / 2];
  const u: Вектор3 = [(слева ? 1 : -1) * r[0], 0, (слева ? 1 : -1) * r[2]];
  const ось: Вектор3 = [0, 1, 0];
  const знак = Math.sign(скаляр(ось, крест(u, f))) || 1;
  return { вид: 'поворот', ось, опора, угол: знак * угол, конфликт: уголКонфликта ?? Math.max(угол, УГОЛ_КОНФЛИКТА) };
}

const _кэш = new Map<string, Движение[]>();

export const ключДвижений = (изд: Изделие, экз: Экземпляр) =>
  `${изд.id}|${экз.габариты.ш}x${экз.габариты.г}x${экз.габариты.в}|${экз.угол_открывания ?? ''}|${экз.раскладка ? JSON.stringify(экз.раскладка) : ''}`;

export function сбросКэшаДвижений() {
  _кэш.clear();
}

/** Что открывается у изделия и как. Результат кэшируется по изделию, габаритам и раскладке. */
export function движенияИзделия(изд: Изделие, экз: Экземпляр): Движение[] {
  const ключ = ключДвижений(изд, экз);
  const в = _кэш.get(ключ);
  if (в) return в;
  const р = построитьДвижения(изд, экз);
  _кэш.set(ключ, р);
  if (_кэш.size > 1000) _кэш.delete(_кэш.keys().next().value as string);
  return р;
}

function построитьДвижения(изд: Изделие, экз: Экземпляр): Движение[] {
  const уголДвери = уголОткрывания(изд, экз);
  const конфликтДвери = конфликтныйУгол(изд, экз);
  const раскладка = слитьРаскладку(изд.раскладка, экз.раскладка);
  const петли = раскладка.фасад.петли;
  if (изд.тип === 'техника') return движенияТехники(изд, экз, петли);
  if (изд.тип !== 'корпус' && !изд.состав?.length) return [];

  const д = детали(изд, экз);
  const группы = new Map<string, Деталь[]>();
  for (const x of д) {
    const г = x.подвижная?.группа;
    if (!г) continue;
    const список = группы.get(г) ?? [];
    список.push(x);
    группы.set(г, список);
  }
  const итог: Движение[] = [];
  const число = (шаблон: RegExp) => [...группы.keys()].filter((к) => шаблон.test(к)).length;
  const этаж = new Map<string, number>();

  for (const [группа, части] of группы) {
    const главная = части.find((x) => ГЛАВНЫЕ_РОЛИ.has(x.роль));
    if (!главная) continue;
    const поворот = поворотБлока(изд, группа);
    const фронт = фронтБлока(поворот);
    const право = правоБлока(поворот);
    const g = главная.локально;
    const часть = объединение(части);
    let m: RegExpMatchArray | null;

    if ((m = группа.match(/ящик-(\d+)-(\d+)$/))) {
      const боковины = части.filter((x) => x.роль === 'ящик-бок');
      const глубина = боковины.length ? Math.max(...боковины.map((x) => вдоль(x.локально.объём, фронт))) : 400;
      const секций = число(/ящик-\d+-0$/);
      const k = Number(m[2]);
      const i = Number(m[1]);
      итог.push({
        группа,
        вид: 'ящик',
        подпись: секций > 1 ? `ящик ${k + 1} (секция ${i + 1})` : `ящик ${k + 1}`,
        кинематика: { вид: 'сдвиг', вектор: [фронт[0] * глубина * ВЫДВИЖЕНИЕ_ЯЩИКА, 0, фронт[1] * глубина * ВЫДВИЖЕНИЕ_ЯЩИКА] },
        фронт,
        главная: g,
        часть: объединение(части),
      });
    } else if ((m = группа.match(/купе-(\d+)$/))) {
      const i = Number(m[1]);
      const w = вдоль(g.объём, право);
      // створки заднего ряда уезжают за переднюю; передние стоят на месте, клик по ним двигает соседнюю (группаДляКлика)
      if (i % 2 === 0) continue;
      const сдвиг = w - 40;
      итог.push({
        группа,
        вид: 'купе',
        подпись: `створка ${i + 1}`,
        кинематика: { вид: 'сдвиг', вектор: [-право[0] * сдвиг, 0, -право[1] * сдвиг] },
        фронт,
        главная: g,
        часть,
      });
    } else if ((m = группа.match(/(дверь|подъёмник)-(\d+)$/))) {
      const i = Number(m[2]);
      const подъёмник = m[1] === 'подъёмник';
      const сторона: СторонаПетель = подъёмник ? 'сверху' : петли === 'попарно' ? (i % 2 === 0 ? 'слева' : 'справа') : петли;
      const шаблон = подъёмник ? /подъёмник-\d+$/ : /дверь-\d+$/;
      const n = число(шаблон);
      этаж.set(m[1], n);
      итог.push({
        группа,
        вид: подъёмник ? 'подъёмник' : 'дверь',
        подпись: подъёмник ? (n > 1 ? `подъёмник ${i + 1}` : 'подъёмник') : n > 1 ? `дверца ${i + 1}` : 'дверца',
        кинематика: кинематикаДвери(g, сторона, фронт, право, подъёмник ? УГОЛ_ОТКИДНОЙ : уголДвери, конфликтДвери),
        фронт,
        главная: g,
        часть,
      });
    }
  }
  return итог.sort((a, b) => a.группа.localeCompare(b.группа, 'ru', { numeric: true }));
}

function движенияТехники(изд: Изделие, экз: Экземпляр, петли: СторонаПетель): Движение[] {
  const уголДвери = уголОткрывания(изд, экз);
  const конфликтДвери = конфликтныйУгол(изд, экз);
  const вид = видТехники(изд);
  const части = частиТехники(изд, экз.габариты, петли);
  const группы = new Map<string, Деталь[]>();
  for (const x of части) {
    const г = x.подвижная?.группа;
    if (!г) continue;
    const список = группы.get(г) ?? [];
    список.push(x);
    группы.set(г, список);
  }
  const фронт: Точка2 = [0, 1];
  const право: Точка2 = [1, 0];
  const итог: Движение[] = [];
  const числоДверей = [...группы.keys()].filter((к) => к.startsWith('дверь-')).length;
  for (const [группа, список] of группы) {
    // главная деталь — самая большая по площади лицевой стороны
    const главная = [...список].sort((a, b) => b.локально.объём[0] * b.локально.объём[1] - a.локально.объём[0] * a.локально.объём[1])[0];
    const g = главная.локально;
    const часть = объединение(список);
    const подпись = подписьТехники(вид, группа, числоДверей);
    const индекс = Number(группа.split('-').pop()) || 0;
    let кин: Кинематика;
    if (группа === 'козырёк') {
      кин = { вид: 'сдвиг', вектор: [0, 0, 180] };
    } else if (вид === 'плита' || вид === 'духовка' || вид === 'посудомойка') {
      кин = кинематикаДвери(g, 'снизу', фронт, право);
    } else if (вид === 'холодильник' && вариантХолодильника(изд.id, экз.габариты.ш, экз.габариты.в) === 'бок-о-бок') {
      кин = кинематикаДвери(g, индекс === 0 ? 'слева' : 'справа', фронт, право, уголДвери, конфликтДвери);
    } else if (вид === 'холодильник') {
      кин = кинематикаДвери(g, петли === 'попарно' ? (индекс % 2 === 0 ? 'слева' : 'справа') : петли === 'справа' ? 'справа' : 'слева', фронт, право, уголДвери, конфликтДвери);
    } else if (группа === 'люк') {
      // люк стиральной машины: петля у края круга, по умолчанию слева
      кин = кинематикаДвери(g, петли === 'справа' ? 'справа' : 'слева', фронт, право, уголДвери, конфликтДвери);
    } else {
      // микроволновка и морозильник: петля с выбранной стороны
      кин = кинематикаДвери(g, петли === 'справа' ? 'справа' : 'слева', фронт, право, уголДвери, конфликтДвери);
    }
    итог.push({ группа, вид: 'техника', подпись, кинематика: кин, фронт, главная: g, часть });
  }
  return итог.sort((a, b) => a.группа.localeCompare(b.группа, 'ru', { numeric: true }));
}

export const группыОткрывания = (д: Движение[]) => д.map((x) => x.группа);

/* ------------------------------------------------------------------ состояние «открыто» */

/** Какие группы сейчас открыты (по полям `открыт` и `открыто`) */
export function открытыеГруппы(движения: Движение[], экз: Pick<Экземпляр, 'открыт' | 'открыто'>): Set<string> {
  if (экз.открыт) return new Set(движения.map((x) => x.группа));
  const есть = new Set(движения.map((x) => x.группа));
  return new Set((экз.открыто ?? []).filter((г) => есть.has(г)));
}

/** Экземпляр с заданным набором открытых групп: все → `открыт: true`, ни одной → без полей */
export function сОткрытымиГруппами(экз: Экземпляр, движения: Движение[], набор: Set<string>): Экземпляр {
  const н: Экземпляр = { ...экз };
  delete н.открыт;
  delete н.открыто;
  if (!движения.length || !набор.size) return н;
  if (движения.every((д) => набор.has(д.группа))) {
    н.открыт = true;
    return н;
  }
  н.открыто = движения.filter((д) => набор.has(д.группа)).map((д) => д.группа);
  return н;
}

/**
 * Куда попадает клик по группе: купе — передняя створка двигает заднюю соседнюю (передняя стоит на месте),
 * остальное — сама группа. Нет такой группы — null.
 */
export function группаДляКлика(движения: Движение[], группа: string): string | null {
  if (движения.some((д) => д.группа === группа)) return группа;
  const m = группа.match(/^(.*купе-)(\d+)$/);
  if (m) {
    const i = Number(m[2]);
    for (const к of [`${m[1]}${i + 1}`, `${m[1]}${i - 1}`]) if (движения.some((д) => д.группа === к)) return к;
  }
  return null;
}

/** Переключить одну группу; возвращает новый экземпляр (или тот же, если открывать нечего) */
export function переключитьГруппу(экз: Экземпляр, движения: Движение[], группа: string): Экземпляр {
  const цель = группаДляКлика(движения, группа);
  if (!цель) return экз;
  const набор = открытыеГруппы(движения, экз);
  if (набор.has(цель)) набор.delete(цель);
  else набор.add(цель);
  return сОткрытымиГруппами(экз, движения, набор);
}

/** Открыть всё или закрыть всё */
export function открытьВсеГруппы(экз: Экземпляр, движения: Движение[], открыть: boolean): Экземпляр {
  return сОткрытымиГруппами(экз, движения, открыть ? new Set(движения.map((д) => д.группа)) : new Set());
}

/** Есть ли у изделия что открывать */
export const открываетсяЛи = (изд: Изделие, экз: Экземпляр) => движенияИзделия(изд, экз).length > 0;

