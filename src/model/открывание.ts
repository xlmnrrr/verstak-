/**
 * Открывание (этап 2): одна функция на изделие — что открывается и как. Её читают и 3D (поза в долях 0…1),
 * и проверки (развёртка в плане, конфликты со стеной и соседями с цифрой «не хватает N мм»).
 * Чистая геометрия, мм, оси изделия: X — ширина, Y — высота, Z — глубина, фасад в +Z. Без three и React.
 *
 * Виды движения: поворот вокруг оси (дверь на петлях, откидная вниз, подъёмник, люк) и сдвиг (ящик, купе, козырёк).
 * Все распашные части открываются на 90°.
 */
