export interface Развёртка {
  группа: string;
  подпись: string;
  вид: ВидОткрывания;
  /** высотный диапазон, мм от низа изделия */
  y0: number;
  y1: number;
  /** требуемый вылет, мм (длина двери от петли, глубина выдвижения ящика, вылет откидной) */
  S: number;
  /** выпуклая фигура в плане (оси изделия, мм) при вылете s ∈ [0, S] */
  фигура(s: number): Точка2[];
}

const ШАГ_ДУГИ = 7.5;

function прямоугольник(a: Точка2, l0: number, l1: number, f: Точка2, g0: number, g1: number): Точка2[] {
  const т = (l: number, g: number): Точка2 => [a[0] * l + f[0] * g, a[1] * l + f[1] * g];
  return [т(l0, g0), т(l1, g0), т(l1, g1), т(l0, g1)];
}

/** Развёртка группы в плане; для купе (ничего не выступает наружу) — null */
export function развёртка(д: Движение): Развёртка | null {
  const k = д.кинематика;
  const [cx, cy, cz] = д.главная.центр;
  const f = д.фронт;
  const y0 = cy - д.главная.объём[1] / 2;
  const y1 = cy + д.главная.объём[1] / 2;
  const переднийКрай = (cx * f[0] + cz * f[1]) + вдоль(д.главная.объём, f) / 2;

  if (k.вид === 'сдвиг') {
    const вперёд = k.вектор[0] * f[0] + k.вектор[2] * f[1];
    if (вперёд < 1) return null;
    const a: Точка2 = [-f[1], f[0]];
    const середина = cx * a[0] + cz * a[1];
    const полу = Math.abs(a[0]) * д.часть.объём[0] / 2 + Math.abs(a[1]) * д.часть.объём[2] / 2;
    const yМин = д.часть.центр[1] - д.часть.объём[1] / 2;
    const yМакс = д.часть.центр[1] + д.часть.объём[1] / 2;
    return {
      группа: д.группа,
      подпись: д.подпись,
      вид: д.вид,
      y0: yМин,
      y1: yМакс,
      S: вперёд,
      фигура: (s) => прямоугольник(a, середина - полу, середина + полу, f, переднийКрай, переднийКрай + s),
    };
  }

  const [ox, oy, oz] = k.опора;
  const вертикальнаяОсь = Math.abs(k.ось[1]) > 0.5;
  const угол = Math.abs(вертикальнаяОсь ? (k.конфликт ?? k.угол) : k.угол);
  if (вертикальнаяОсь) {
    // створка на вертикальной петле: веер от петли
    const dx = cx - ox;
    const dz = cz - oz;
    const w2 = Math.hypot(dx, dz);
    if (w2 < 1) return null;
    const u: Точка2 = [dx / w2, dz / w2];
    // вылет считается от плоскости фасада: начало веера сдвинуто с оси петли на половину толщины двери вперёд
    const п = вдоль(д.главная.объём, f) / 2;
    const hx = ox + f[0] * п;
    const hz = oz + f[1] * п;
    return {
      группа: д.группа,
      подпись: д.подпись,
      вид: д.вид,
      y0,
      y1,
      S: 2 * w2,
      фигура: (s) => {
        const точки: Точка2[] = [[hx, hz]];
        const шагов = Math.max(2, Math.ceil(угол / ШАГ_ДУГИ));
        for (let i = 0; i <= шагов; i++) {
          const ψ = ((угол * i) / шагов * Math.PI) / 180;
          const c = Math.cos(ψ);
          const sn = Math.sin(ψ);
          точки.push([hx + s * (u[0] * c + f[0] * sn), hz + s * (u[1] * c + f[1] * sn)]);
        }
        return точки;
      },
    };
  }
  // откидная: вниз (духовка, посудомойка) или вверх (подъёмник); вперёд выступает не дальше длины двери
  const L = 2 * Math.hypot(cy - oy, 0.0001 + Math.hypot(cx - ox, cz - oz));
  const вперёд = L * Math.sin((Math.min(угол, 90) * Math.PI) / 180);
  const a: Точка2 = [Math.abs(k.ось[0]) > 0.5 ? 1 : 0, Math.abs(k.ось[2]) > 0.5 ? 1 : 0];
  const середина = cx * a[0] + cz * a[1];
  const полу = вдоль(д.главная.объём, a) / 2;
  return {
    группа: д.группа,
    подпись: д.подпись,
    вид: д.вид,
    y0,
    y1,
    S: вперёд,
    фигура: (s) => прямоугольник(a, середина - полу, середина + полу, f, переднийКрай, переднийКрай + s),
  };
}

export const развёрткиИзделия = (изд: Изделие, экз: Экземпляр): Развёртка[] =>
  движенияИзделия(изд, экз)
    .map(развёртка)
    .filter((x): x is Развёртка => !!x);

