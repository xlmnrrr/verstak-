/**
 * Техника: из какого набора частей она состоит и какие из них открываются (этап 2).
 * Корпус, дверь, ручка — отдельные `Деталь`, подвижные помечены `подвижная.группа`.
 * Чистая геометрия, мм, оси изделия: X — ширина, Y — высота, Z — глубина, фасад в +Z.
 * Эти части видит только рендер и проверка открывания; деталировка и смета их не берут (форма «модель»).
 */
import { деталь, кр0 } from './детали';
import type { Габариты, Деталь, Изделие, СторонаПетель } from './типы';

export type ВидТехники =
  | 'холодильник'
  | 'морозильник'
  | 'плита'
  | 'духовка'
  | 'микроволновка'
  | 'посудомойка'
  | 'стиральная'
  | 'вытяжка-купольная'
  | 'вытяжка-встроенная'
  | 'прочее';

export function видТехники(изд: Pick<Изделие, 'id' | 'тип'>): ВидТехники {
  const id = изд.id;
  if (id.startsWith('холодильник')) return 'холодильник';
  if (id.startsWith('морозильник')) return 'морозильник';
  if (id.startsWith('плита-')) return 'плита';
  if (id.startsWith('духовка')) return 'духовка';
  if (id.startsWith('микроволновка')) return 'микроволновка';
  if (id.startsWith('посудомойка')) return 'посудомойка';
  if (id.startsWith('стиральная')) return 'стиральная';
  if (id.startsWith('вытяжка-купольная')) return 'вытяжка-купольная';
  if (id.startsWith('вытяжка-встроенная') || id.startsWith('вытяжка-встраиваемая')) return 'вытяжка-встроенная';
  return 'прочее';
}

/** Вид холодильника: из id (однодверный, двухдверный, side-by-side, встроенный), иначе по габаритам */
export type ВариантХолодильника = 'одна' | 'две' | 'бок-о-бок' | 'встроенный';

export function вариантХолодильника(id: string, ш: number, в: number): ВариантХолодильника {
  if (id.includes('однодверн')) return 'одна';
  if (id.includes('двухдверн')) return 'две';
  if (id.includes('side-by-side')) return 'бок-о-бок';
  if (id.includes('встроенн')) return 'встроенный';
  if (ш >= 750) return 'бок-о-бок';
  return в < 1200 ? 'одна' : 'две';
}

/** Встраиваемая техника: дверь закрыта фасадом шкафа */
const встраиваемая = (id: string) => id.includes('встраиваем') || id.includes('встроенн');

const СЕРЫЙ = { цвет: '#c9ced3', шер: 0.4, мет: 0.3 };
const РУЧКА = { цвет: '#8b9198', шер: 0.3, мет: 0.8 };
const ТЁМНЫЙ = { цвет: '#1b1d21', шер: 0.25, мет: 0.1 };
const ПАНЕЛЬ = { цвет: '#2a2d32', шер: 0.35, мет: 0.2 };
const СТЕКЛО_ЛЮКА = { цвет: '#243038', шер: 0.08, мет: 0.1 };

type Литерал = NonNullable<Деталь['литерал']>;

/** Часть техники: плита (центр, объём) со своим материалом, при желании — в подвижной группе */
function часть(центр: [number, number, number], объём: [number, number, number], мат: Литерал | 'техника' | 'фасад', группа?: string): Деталь {
  return {
    ...деталь('техника', центр, объём, typeof мат === 'string' ? мат : 'техника', кр0(), { форма: 'плита', ...(группа ? { подвижная: { группа } } : {}) }),
    ...(typeof мат === 'string' ? {} : { литерал: мат }),
  };
}

function цилиндрZ(центр: [number, number, number], d: number, длина: number, лит: Литерал, группа?: string): Деталь {
  return {
    ...деталь('техника', центр, [d, d, длина], 'техника', кр0(), { форма: 'цилиндр', ось: 'z', ...(группа ? { подвижная: { группа } } : {}) }),
    литерал: лит,
  };
}

/** Вертикальная ручка холодильника или микроволновки у свободного края двери */
function ручкаВертикальная(xКрая: number, сторонаПетель: 'слева' | 'справа', yЦентр: number, длина: number, zПереда: number, группа: string): Деталь {
  const x = сторонаПетель === 'слева' ? xКрая - 40 : xКрая + 40;
  return часть([x, yЦентр, zПереда + 12], [18, длина, 24], РУЧКА, группа);
}

/** Сторона петли для i-й двери: «попарно» — каждая дверь в свою сторону */
function сторона(петли: СторонаПетель, i: number): 'слева' | 'справа' {
  if (петли === 'справа') return 'справа';
  if (петли === 'попарно') return i % 2 === 0 ? 'слева' : 'справа';
  return 'слева';
}

/** Названия групп техники (подпись для сообщений — в открывание.ts) */
export const ГРУППЫ_ТЕХНИКИ = {
  дверь: (i: number) => `дверь-${i}`,
  люк: 'люк',
  козырёк: 'козырёк',
} as const;

/**
 * Части техники для рисунка и открывания. Для «прочего» (варочная панель, мойка) — корпус с передней панелью и ручкой,
 * ничего не открывается. `петли` берётся из раскладки экземпляра.
 */
export function частиТехники(изд: Pick<Изделие, 'id' | 'тип'>, габ: Габариты, петли: СторонаПетель): Деталь[] {
  const { ш: W, г: D, в: H } = габ;
  const вид = видТехники(изд);
  const z0 = D / 2;
  const д: Деталь[] = [];

  switch (вид) {
    case 'холодильник': {
      const вариант = вариантХолодильника(изд.id, W, H);
      // встроенный: двери под фасадом шкафа (тоньше, цвет фасада)
      const фасадом = вариант === 'встроенный';
      const толщ = фасадом ? 24 : 56;
      const zД = z0 - толщ / 2;
      const матДвери: Литерал | 'фасад' = фасадом ? 'фасад' : СЕРЫЙ;
      д.push(часть([0, H / 2, -толщ / 2], [W, H, D - толщ], 'техника'));
      const зазор = 4;
      if (вариант === 'бок-о-бок') {
        // двухстворчатый (side-by-side): каждая дверь открывается наружу в свою сторону
        const w = (W - 2 * 2 - зазор) / 2;
        for (let i = 0; i < 2; i++) {
          const x = -W / 2 + 2 + w / 2 + i * (w + зазор);
          const г = ГРУППЫ_ТЕХНИКИ.дверь(i);
          д.push(часть([x, H / 2, zД], [w, H - 6, толщ], матДвери, г));
          const крайX = i === 0 ? x + w / 2 : x - w / 2;
          д.push(ручкаВертикальная(крайX, i === 0 ? 'слева' : 'справа', H * 0.5, Math.min(600, H * 0.4), z0, г));
        }
      } else if (вариант === 'одна') {
        const г = ГРУППЫ_ТЕХНИКИ.дверь(0);
        д.push(часть([0, H / 2, zД], [W - 4, H - 6, толщ], матДвери, г));
        const с = сторона(петли, 0);
        д.push(ручкаВертикальная(с === 'слева' ? W / 2 - 2 : -W / 2 + 2, с, H * 0.6, Math.min(400, H * 0.4), z0, г));
      } else {
        // верхняя (холодильная) и нижняя (морозильная) двери
        const hНиз = Math.round(H * 0.34);
        const hВерх = H - hНиз - зазор;
        const двери: { yЦентр: number; h: number }[] = [
          { yЦентр: hНиз + зазор + hВерх / 2, h: hВерх },
          { yЦентр: hНиз / 2, h: hНиз },
        ];
        двери.forEach((дв, i) => {
          const г = ГРУППЫ_ТЕХНИКИ.дверь(i);
          д.push(часть([0, дв.yЦентр, zД], [W - 4, дв.h - 4, толщ], матДвери, г));
          const с = сторона(петли, i);
          const yР = i === 0 ? дв.yЦентр - дв.h * 0.35 : дв.yЦентр + дв.h * 0.1;
          д.push(ручкаВертикальная(с === 'слева' ? W / 2 - 2 : -W / 2 + 2, с, yР, Math.min(450, дв.h * 0.6), z0, г));
        });
      }
      return д;
    }
    case 'морозильник': {
      const толщ = 48;
      const zД = z0 - толщ / 2;
      д.push(часть([0, H / 2, -толщ / 2], [W, H, D - толщ], 'техника'));
      const г = ГРУППЫ_ТЕХНИКИ.дверь(0);
      д.push(часть([0, H / 2, zД], [W - 4, H - 6, толщ], СЕРЫЙ, г));
      const с = сторона(петли, 0);
      д.push(ручкаВертикальная(с === 'слева' ? W / 2 - 2 : -W / 2 + 2, с, H * 0.62, Math.min(300, H * 0.4), z0, г));
      return д;
    }
    case 'плита': {
      // духовка внизу, панель управления над дверью, варочная поверхность сверху
      const толщ = 40;
      д.push(часть([0, H / 2, -толщ / 2], [W, H, D - толщ], 'техника'));
      д.push(часть([0, H - 4, 0], [W - 20, 8, D - 20], ТЁМНЫЙ));
      const hДв = Math.round(H * 0.5);
      const yДв = 60 + hДв / 2;
      const г = ГРУППЫ_ТЕХНИКИ.дверь(0);
      д.push(часть([0, yДв, z0 - толщ / 2], [W - 20, hДв, толщ], СЕРЫЙ, г));
      д.push(часть([0, yДв + hДв / 2 - 40, z0 + 20], [W * 0.7, 18, 24], РУЧКА, г));
      д.push(часть([0, H - 110, z0 - 15], [W - 20, 140, 30], ПАНЕЛЬ));
      return д;
    }
    case 'духовка': {
      const толщ = 36;
      д.push(часть([0, H / 2, -толщ / 2], [W, H, D - толщ], 'техника'));
      const hПанели = 72;
      const hДв = H - hПанели - 6;
      const г = ГРУППЫ_ТЕХНИКИ.дверь(0);
      д.push(часть([0, 3 + hДв / 2, z0 - толщ / 2], [W - 8, hДв, толщ], СТЕКЛО_ЛЮКА, г));
      д.push(часть([0, 3 + hДв - 36, z0 + 22], [W * 0.62, 16, 24], РУЧКА, г));
      д.push(часть([0, H - hПанели / 2, z0 - 15], [W - 8, hПанели - 4, 30], ПАНЕЛЬ));
      return д;
    }
    case 'микроволновка': {
      const толщ = 30;
      д.push(часть([0, H / 2, -толщ / 2], [W, H, D - толщ], 'техника'));
      const панель = Math.min(120, W * 0.25);
      const wДв = W - панель - 16;
      const сторонаДв = сторона(петли, 0);
      const xДв = сторонаДв === 'слева' ? -W / 2 + 8 + wДв / 2 : W / 2 - 8 - wДв / 2;
      const xПанели = сторонаДв === 'слева' ? W / 2 - 8 - панель / 2 : -W / 2 + 8 + панель / 2;
      const г = ГРУППЫ_ТЕХНИКИ.дверь(0);
      д.push(часть([xДв, H / 2, z0 - толщ / 2], [wДв, H - 16, толщ], СТЕКЛО_ЛЮКА, г));
      д.push(ручкаВертикальная(сторонаДв === 'слева' ? xДв + wДв / 2 : xДв - wДв / 2, сторонаДв, H / 2, H * 0.55, z0 - 6, г));
      д.push(часть([xПанели, H / 2, z0 - 12], [панель, H - 16, 24], ПАНЕЛЬ));
      return д;
    }
    case 'посудомойка': {
      const толщ = 24;
      д.push(часть([0, H / 2, -толщ / 2], [W, H, D - толщ], 'техника'));
      const г = ГРУППЫ_ТЕХНИКИ.дверь(0);
      д.push(часть([0, H / 2, z0 - толщ / 2], [W - 4, H - 4, толщ], встраиваемая(изд.id) ? 'фасад' : СЕРЫЙ, г));
      д.push(часть([0, H - 70, z0 + 12], [W * 0.62, 16, 24], РУЧКА, г));
      return д;
    }
    case 'стиральная': {
      // встраиваемая: люк неподвижен под дверью с фасадом шкафа; обычная: люк с ручкой открывается сам
      const встр = встраиваемая(изд.id);
      const толщ = встр ? 19 : 30;
      д.push(часть([0, H / 2, -толщ / 2], [W, H, D - толщ], 'техника'));
      д.push(часть([0, H - 55, z0 - 15 - (встр ? 20 : 0)], [W - 6, 100, 30], ПАНЕЛЬ));
      const d = Math.round(Math.min(W, H) * 0.56);
      const yЛюка = (H - 110) / 2;
      const zЛюка = z0 - (встр ? 28 : 0);
      д.push(цилиндрZ([0, yЛюка, zЛюка - 8], d + 36, 16, СЕРЫЙ));
      const с = сторона(петли, 0);
      if (встр) {
        д.push(цилиндрZ([0, yЛюка, zЛюка + 8], d, 30, СТЕКЛО_ЛЮКА));
        const г = ГРУППЫ_ТЕХНИКИ.дверь(0);
        д.push(часть([0, H / 2, z0 - толщ / 2], [W - 4, H - 4, толщ], 'фасад', г));
        д.push(ручкаВертикальная(с === 'слева' ? W / 2 - 2 : -W / 2 + 2, с, H * 0.5, Math.min(300, H * 0.35), z0, г));
      } else {
        д.push(цилиндрZ([0, yЛюка, zЛюка + 8], d, 30, СТЕКЛО_ЛЮКА, ГРУППЫ_ТЕХНИКИ.люк));
        д.push(часть([с === 'слева' ? d / 2 - 30 : -d / 2 + 30, yЛюка, zЛюка + 28], [14, d * 0.3, 14], РУЧКА, ГРУППЫ_ТЕХНИКИ.люк));
      }
      return д;
    }
    case 'вытяжка-купольная': {
      // козырёк внизу выдвигается вперёд, купол и труба неподвижны
      const hКозырька = 70;
      д.push(часть([0, hКозырька + (H - hКозырька) / 2, 0], [W, H - hКозырька, D], 'техника'));
      д.push(часть([0, hКозырька / 2, -40], [W - 60, hКозырька - 6, D - 100], СЕРЫЙ, ГРУППЫ_ТЕХНИКИ.козырёк));
      д.push(часть([0, hКозырька - 4, z0 - 62], [W * 0.5, 12, 14], РУЧКА, ГРУППЫ_ТЕХНИКИ.козырёк));
      return д;
    }
    case 'вытяжка-встроенная': {
      const hКозырька = Math.min(60, H * 0.35);
      д.push(часть([0, hКозырька + (H - hКозырька) / 2, 0], [W, H - hКозырька, D], 'техника'));
      д.push(часть([0, hКозырька / 2, -30], [W - 40, hКозырька - 4, D - 60], СЕРЫЙ, ГРУППЫ_ТЕХНИКИ.козырёк));
      return д;
    }
    default: {
      // варочная панель, мойка: корпус, передняя панель и ручка; ничего не открывается
      д.push(часть([0, H / 2, 0], [W, H, D], 'техника'));
      д.push(часть([0, H / 2, z0 + 5], [W - 20, Math.max(10, H - 40), 20], СЕРЫЙ));
      д.push(часть([W / 2 - 60, H * 0.55, z0 + 20], [20, H * 0.55, 30], РУЧКА));
      return д;
    }
  }
}

/** Подпись группы для сообщений */
export function подписьТехники(вид: ВидТехники, группа: string, число: number): string {
  if (группа === ГРУППЫ_ТЕХНИКИ.люк) return 'люк стиральной машины';
  if (группа === ГРУППЫ_ТЕХНИКИ.козырёк) return 'козырёк вытяжки';
  const i = Number(группа.split('-').pop() ?? 0);
  switch (вид) {
    case 'холодильник':
      return число > 1 ? `дверь холодильника ${i + 1}` : 'дверь холодильника';
    case 'морозильник':
      return 'дверь морозильника';
    case 'стиральная':
      return 'дверь-фасад стиральной машины';
    case 'плита':
    case 'духовка':
      return 'дверца духовки';
    case 'микроволновка':
      return 'дверца микроволновки';
    case 'посудомойка':
      return 'дверь посудомойки';
    default:
      return 'дверь';
  }
}
