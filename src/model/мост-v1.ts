/**
 * Мост v2 ↔ v1 для старого рендера (живёт до 1А-2, пока на сцене стоит Furniture.tsx из v1).
 * Старый рендер и панели понимают плоские объекты v1; здесь модель v2 переводится в них,
 * а правки из панелей (патчи v1) — обратно в экземпляры v2.
 */
import { границыКонтура, высотаДляРендера } from './помещение';
import { изделиеПоИд } from './каталог';
import { полокМакс } from './детали';
import { слитьРаскладку, автоПолки } from './раскладка';
import type { Dims, Facade, Kind, Obj, Project, Room } from '../types';
import type { ЧастичнаяРаскладка, Экземпляр, ПроектV2, Помещение, Изделие, ТипФасада } from './типы';

const ФАСАД_V2_В_V1: Record<ТипФасада, Facade> = {
  нет: 'нет',
  распашной: 'распашной',
  купе: 'распашной',
  ящики: 'ящики',
  подъёмник: 'распашной',
  push: 'push',
  зеркало: 'зеркало',
  стекло: 'распашной',
};

/** вид v1 для изделия без связи со старым каталогом */
function видV1(изд: Изделие): Kind {
  if (изд.v1) return изд.v1.вид as Kind;
  switch (изд.тип) {
    case 'корпус':
      return изд.крепление === 'стена' ? 'навесной' : 'корпус';
    case 'мягкая':
    case 'свет':
    case 'декор':
      return 'декор';
    default:
      return изд.тип as Kind;
  }
}

const метка = (м: string[] | undefined, префикс: string) => м?.find((x) => x.startsWith(префикс));
const числоИзМетки = (м: string[] | undefined, префикс: string) => {
  const р = метка(м, префикс);
  if (!р) return undefined;
  const н = Number(р.slice(префикс.length));
  return Number.isFinite(н) ? н : undefined;
};

/** Смещение мира помещения относительно «центра габарита» (v1 строит комнату вокруг нуля) */
export const смещениеМоста = (п: Помещение): [number, number] => границыКонтура(п.контур).центр;

export function вКомнатуV1(п: Помещение, п2: ПроектV2): Room {
  const г = границыКонтура(п.контур);
  const форма = п.контур.length === 6 ? 'Г' : п.контур.length === 8 ? 'П' : 'прямоугольник';
  return {
    длина: Math.round(г.ш),
    ширина: Math.round(г.г),
    высота_стен: высотаДляРендера(п),
    толщина_стен: п.толщина_стен,
    форма,
    обои: п.отделка.стены,
    пол: п.отделка.пол,
    фон: п2.настройки.фон,
  };
}

export function вОбъектV1(экз: Экземпляр, смещение: [number, number] = [0, 0]): Obj {
  const изд = изделиеПоИд(экз.изделие);
  const р = изд ? слитьРаскладку(изд.раскладка, экз.раскладка) : undefined;
  const фасад = р ? ФАСАД_V2_В_V1[р.фасад.тип] : 'нет';
  const петли = р?.фасад.петли;
  const наклонX = числоИзМетки(экз.метки, 'наклон:X=');
  const наклонZ = числоИзМетки(экз.метки, 'наклон:Z=');
  const вид = (метка(экз.метки, 'вид:')?.slice(4) as Kind | undefined) ?? (изд ? видV1(изд) : 'корпус');
  const о: Obj = {
    id: экз.id,
    модуль: изд?.v1?.модуль ?? 'свободный',
    название: экз.название ?? изд?.название,
    позиция: [экз.позиция[0] - смещение[0], экз.позиция[1], экз.позиция[2] - смещение[1]],
    поворот: экз.поворот,
    габариты: { ...экз.габариты },
    подъём: экз.позиция[1],
    цвет: экз.материалы?.фасад ?? изд?.материалы.фасад,
    материал: экз.материал_описание ?? изд?.материал_описание,
    ящиков: р?.фасад.ящиков ?? 0,
    полок: изд ? полокМакс(изд, экз) : 0,
    цоколь: р?.корпус.цоколь ?? 0,
    ножки: р?.корпус.ножки ?? 0,
    вид,
    фасад,
  };
  if (петли) о.петли = петли === 'попарно' ? 'слева' : петли;
  if (экз.открыт || экз.открыто?.length) о.открыт = true;
  if (наклонX !== undefined) о.наклон_X = наклонX;
  if (наклонZ !== undefined) о.наклон_Z = наклонZ;
  return о;
}

export function вПроектV1(п: ПроектV2, помещениеId?: string): { проект: Project; смещение: [number, number]; помещение: string } {
  const пом = п.помещения.find((x) => x.id === помещениеId) ?? п.помещения[0];
  const смещение = смещениеМоста(пом);
  return {
    проект: {
      schemaVersion: 1,
      название: п.название,
      создан: п.создан,
      изменён: п.изменён,
      комната: вКомнатуV1(пом, п),
      объекты: п.объекты.filter((о) => о.помещение === пом.id).map((о) => вОбъектV1(о, смещение)),
      настройки: {
        шаг_сетки: п.настройки.шаг_сетки,
        толщина_плиты: п.настройки.толщина_плиты,
        режим_обзора: п.настройки.режим_обзора,
        тема: п.настройки.тема === 'калька' ? 'светлая' : 'тёмная',
      },
    },
    смещение,
    помещение: пом.id,
  };
}

/**
 * Перенести правку из панели/сцены (патч объекта v1) в экземпляр v2.
 * Возвращает новый экземпляр; исходный не меняется.
 */
export function патчV1вЭкземпляр(
  экз: Экземпляр,
  патч: Partial<Obj>,
  смещение: [number, number] = [0, 0],
): Экземпляр {
  const изд = изделиеПоИд(экз.изделие);
  const н: Экземпляр = { ...экз };
  const р: ЧастичнаяРаскладка = JSON.parse(JSON.stringify(экз.раскладка ?? {}));
  let раскладкаМенялась = false;

  if (патч.позиция) {
    н.позиция = [патч.позиция[0] + смещение[0], патч.подъём !== undefined ? патч.подъём : патч.позиция[1], патч.позиция[2] + смещение[1]];
  } else if (патч.подъём !== undefined) {
    н.позиция = [экз.позиция[0], патч.подъём, экз.позиция[2]];
  }
  if (патч.поворот !== undefined) н.поворот = патч.поворот;
  if (патч.габариты) н.габариты = { ...патч.габариты };
  if (патч.название !== undefined) н.название = патч.название === изд?.название ? undefined : патч.название;
  if (патч.открыт !== undefined) {
    if (патч.открыт) н.открыт = true;
    else delete н.открыт;
    delete н.открыто;
  }
  if (патч.цвет !== undefined) {
    н.материалы = { ...(экз.материалы ?? {}), фасад: патч.цвет };
  }
  if (патч.материал !== undefined) н.материал_описание = патч.материал;

  if (патч.наклон_X !== undefined || патч.наклон_Z !== undefined) {
    const м = (экз.метки ?? []).filter((x) => !x.startsWith('наклон:'));
    const x = патч.наклон_X ?? числоИзМетки(экз.метки, 'наклон:X=') ?? 0;
    const z = патч.наклон_Z ?? числоИзМетки(экз.метки, 'наклон:Z=') ?? 0;
    if (x) м.push(`наклон:X=${x}`);
    if (z) м.push(`наклон:Z=${z}`);
    if (м.length) н.метки = м;
    else delete н.метки;
  }

  if (патч.петли !== undefined) {
    р.фасад = { ...(р.фасад ?? {}), петли: патч.петли };
    раскладкаМенялась = true;
  }
  if (патч.ящиков !== undefined) {
    р.фасад = { ...(р.фасад ?? {}), ящиков: патч.ящиков };
    раскладкаМенялась = true;
  }
  if (патч.цоколь !== undefined) {
    р.корпус = { ...(р.корпус ?? {}), цоколь: патч.цоколь };
    раскладкаМенялась = true;
  }
  if (патч.ножки !== undefined) {
    р.корпус = { ...(р.корпус ?? {}), ножки: патч.ножки };
    раскладкаМенялась = true;
  }
  if (патч.фасад !== undefined) {
    р.фасад = { ...(р.фасад ?? {}), тип: патч.фасад as ТипФасада };
    раскладкаМенялась = true;
  }
  if (патч.полок !== undefined && изд) {
    const база = слитьРаскладку(изд.раскладка, р);
    р.секции = база.секции.map((с) => (с.наполнение.направление === 'снизу-вверх' ? { ...с, наполнение: { ...с.наполнение, число: патч.полок! } } : с));
    раскладкаМенялась = true;
  }
  if (раскладкаМенялась) н.раскладка = р;
  return н;
}

