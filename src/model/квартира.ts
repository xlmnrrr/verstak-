/**
 * Квартира по сетке (логика мастера, без интерфейса).
 * Пользователь «закрашивает» клетки номерами помещений; здесь из них собираются
 * помещения-контуры, общие стены (связи) и проёмы-переходы между помещениями.
 *
 * Сетка: ряд r — по оси Z (вниз), столбец c — по оси X (вправо). Линии сетки — оси стен.
 * Внутренний контур помещения = граница клеток, сдвинутая внутрь на половину толщины стены.
 * Контур у помещения задан в его собственных осях (начало — центр габарита), `смещение` — положение
 * этого начала на плане квартиры.
 */
import { границыКонтура, знаковаяПлощадь, стены, type Точка } from './помещение';
import type { Отметка, ВидОтметки, Помещение, Связь, ТипПомещения } from './типы';
import { пустаяОтделка } from './помещение';

export type Сторона = 'с' | 'ю' | 'в' | 'з';

export interface ПроёмПоСетке {
  /** клетка [ряд, столбец], у стороны которой стоит проём */
  клетка: [number, number];
  /** с — север (вверх, −Z), ю — юг, в — восток (+X), з — запад */
  сторона: Сторона;
  вид: Extract<ВидОтметки, 'дверь' | 'арка' | 'окно'>;
  ширина?: number;
  высота?: number;
  от_пола?: number;
}

export interface ОписаниеКомнаты {
  тип: ТипПомещения;
  название?: string;
  высота?: number | 'неизвестна';
  толщина_стен?: number;
}

export interface ЗадачаСетки {
  /** размер клетки, мм (например 500) */
  клетка: number;
  /** клетки[ряд][столбец]: номер помещения (1, 2, …) или 0 — пусто */
  клетки: number[][];
  комнаты: Record<number, ОписаниеКомнаты>;
  проёмы?: ПроёмПоСетке[];
  /** толщина стен по умолчанию, мм */
  толщина_стен?: number;
}

export interface РезультатСетки {
  помещения: Помещение[];
  связи: Связь[];
  ошибки: string[];
  предупреждения: string[];
}

/** Удобная запись сетки текстом: цифра — номер помещения, «.» или пробел — пусто */
export function клеткиИзТекста(строки: string[]): number[][] {
  return строки.map((с) => [...с].map((ч) => (ч >= '0' && ч <= '9' ? Number(ч) : 0)));
}

const ЗАГЛАВНОЕ = (с: string) => с.charAt(0).toUpperCase() + с.slice(1);
const ключТочки = (x: number, z: number) => `${x},${z}`;

interface Ребро {
  от: Точка;
  до: Точка;
}

/** Границы группы клеток → один замкнутый контур в единицах сетки (по часовой) или ошибка */
function контурГруппы(клетки: [number, number][]): { контур?: Точка[]; ошибка?: string } {
  const есть = new Set(клетки.map(([r, c]) => `${r},${c}`));
  const содержит = (r: number, c: number) => есть.has(`${r},${c}`);
  const рёбра: Ребро[] = [];
  for (const [r, c] of клетки) {
    if (!содержит(r - 1, c)) рёбра.push({ от: [c, r], до: [c + 1, r] });
    if (!содержит(r, c + 1)) рёбра.push({ от: [c + 1, r], до: [c + 1, r + 1] });
    if (!содержит(r + 1, c)) рёбра.push({ от: [c + 1, r + 1], до: [c, r + 1] });
    if (!содержит(r, c - 1)) рёбра.push({ от: [c, r + 1], до: [c, r] });
  }
  const исходящие = new Map<string, Ребро[]>();
  for (const р of рёбра) {
    const к = ключТочки(р.от[0], р.от[1]);
    исходящие.set(к, [...(исходящие.get(к) ?? []), р]);
  }
  for (const список of исходящие.values()) {
    if (список.length > 1) return { ошибка: 'помещение касается само себя углом' };
  }
  const использовано = new Set<Ребро>();
  const петли: Точка[][] = [];
  for (const старт of рёбра) {
    if (использовано.has(старт)) continue;
    const петля: Точка[] = [];
    let р: Ребро | undefined = старт;
    while (р && !использовано.has(р)) {
      использовано.add(р);
      петля.push(р.от);
      р = исходящие.get(ключТочки(р.до[0], р.до[1]))?.[0];
    }
    петли.push(петля);
  }
  if (петли.length !== 1) return { ошибка: 'внутри помещения есть «дырка» (другое помещение или пустота), такое пока не поддерживается' };

  // убрать лишние точки на прямых
  const п = петли[0];
  const вершины = п.filter((т, i) => {
    const а = п[(i + п.length - 1) % п.length];
    const б = п[(i + 1) % п.length];
    return !((а[0] === т[0] && т[0] === б[0]) || (а[1] === т[1] && т[1] === б[1]));
  });
  return { контур: вершины };
}

/** Сдвиг контура внутрь на d (для прямоугольных контуров: смещение вершины = d × сумма внутренних нормалей) */
function сдвинутьВнутрь(к: Точка[], d: number): Точка[] {
  const ст = стены(к);
  return к.map((т, i) => {
    const пред = ст[(i + к.length - 1) % к.length];
    const след = ст[i];
    return [т[0] + (пред.нормаль[0] + след.нормаль[0]) * d, т[1] + (пред.нормаль[1] + след.нормаль[1]) * d] as Точка;
  });
}

const ВЕКТОР_СТОРОНЫ: Record<Сторона, [number, number]> = { с: [-1, 0], ю: [1, 0], в: [0, 1], з: [0, -1] };

function ребройСтороны(r: number, c: number, с: Сторона): { от: Точка; до: Точка; середина: Точка } {
  // координаты точек сетки: [x=столбец, z=ряд]
  const [x0, z0] = [c, r];
  let от: Точка;
  let до: Точка;
  if (с === 'с') {
    от = [x0, z0];
    до = [x0 + 1, z0];
  } else if (с === 'ю') {
    от = [x0, z0 + 1];
    до = [x0 + 1, z0 + 1];
  } else if (с === 'з') {
    от = [x0, z0];
    до = [x0, z0 + 1];
  } else {
    от = [x0 + 1, z0];
    до = [x0 + 1, z0 + 1];
  }
  return { от, до, середина: [(от[0] + до[0]) / 2, (от[1] + до[1]) / 2] };
}

/** Индекс ребра контура (в единицах сетки), содержащего заданную точку */
function реброСТочкой(контур: Точка[], x: number, z: number): number {
  for (let i = 0; i < контур.length; i++) {
    const а = контур[i];
    const б = контур[(i + 1) % контур.length];
    const минX = Math.min(а[0], б[0]);
    const максX = Math.max(а[0], б[0]);
    const минZ = Math.min(а[1], б[1]);
    const максZ = Math.max(а[1], б[1]);
    const вертикаль = а[0] === б[0];
    if (вертикаль && x === а[0] && z >= минZ && z <= максZ) return i;
    if (!вертикаль && z === а[1] && x >= минX && x <= максX) return i;
  }
  return -1;
}

const ПО_УМОЛЧАНИЮ: Record<'дверь' | 'арка' | 'окно', { ш: number; в: number; пол: number }> = {
  дверь: { ш: 900, в: 2050, пол: 0 },
  арка: { ш: 1000, в: 2200, пол: 0 },
  окно: { ш: 1400, в: 1400, пол: 900 },
};

export function квартираПоСетке(задача: ЗадачаСетки): РезультатСетки {
  const ошибки: string[] = [];
  const предупреждения: string[] = [];
  const { клетка, клетки, комнаты } = задача;
  const толщинаОбщая = задача.толщина_стен ?? 100;

  if (!(клетка >= 300)) ошибки.push('Клетка меньше 300 мм: стены и проёмы не поместятся');
  const рядов = клетки.length;
  const столбцов = Math.max(0, ...клетки.map((р) => р.length));
  const номер = (r: number, c: number) => (r >= 0 && r < рядов && c >= 0 && c < (клетки[r]?.length ?? 0) ? клетки[r][c] : 0);

  // 1. группы
  const группы = new Map<number, [number, number][]>();
  for (let r = 0; r < рядов; r++) {
    for (let c = 0; c < столбцов; c++) {
      const н = номер(r, c);
      if (!н) continue;
      группы.set(н, [...(группы.get(н) ?? []), [r, c]]);
    }
  }
  if (группы.size === 0) ошибки.push('Не закрашено ни одной клетки');

  const порядок = [...группы.keys()].sort((a, b) => a - b);
  const названияИспользованные = new Map<string, number>();
  const данные = new Map<number, { id: string; контурСетки: Точка[]; контурПлана: Точка[]; t: number }>();

  for (const н of порядок) {
    const оп = комнаты[н];
    if (!оп) {
      ошибки.push(`Для номера ${н} не задан тип помещения`);
      continue;
    }
    const кл = группы.get(н)!;
    // связность по сторонам
    const видели = new Set<string>([`${кл[0][0]},${кл[0][1]}`]);
    const очередь = [кл[0]];
    while (очередь.length) {
      const [r, c] = очередь.pop()!;
      for (const [dr, dc] of [[-1, 0], [1, 0], [0, -1], [0, 1]]) {
        const ключ = `${r + dr},${c + dc}`;
        if (номер(r + dr, c + dc) === н && !видели.has(ключ)) {
          видели.add(ключ);
          очередь.push([r + dr, c + dc]);
        }
      }
    }
    const имя = оп.название ?? ЗАГЛАВНОЕ(оп.тип);
    if (видели.size !== кл.length) {
      ошибки.push(`Помещение ${н} («${имя}»): клетки не соединены сторонами, разделите на два помещения`);
      continue;
    }
    const { контур, ошибка } = контурГруппы(кл);
    if (!контур) {
      ошибки.push(`Помещение ${н} («${имя}»): ${ошибка}`);
      continue;
    }
    const t = оп.толщина_стен ?? толщинаОбщая;
    const контурПлана = сдвинутьВнутрь(контур.map(([x, z]) => [x * клетка, z * клетка] as Точка), t / 2);
    // стена тоньше клетки — иначе сдвиг сломает контур
    if (t >= клетка) ошибки.push(`Помещение ${н}: толщина стены ${t} мм не меньше клетки ${клетка} мм`);
    данные.set(н, { id: `п${н}`, контурСетки: контур, контурПлана, t });
    названияИспользованные.set(имя, (названияИспользованные.get(имя) ?? 0) + 1);
  }

  // имена: повторяющиеся получают номер
  const счёт = new Map<string, number>();
  const помещения: Помещение[] = [];
  const шт = new Map<number, Помещение>();
  for (const н of порядок) {
    const д = данные.get(н);
    const оп = комнаты[н];
    if (!д || !оп) continue;
    const базовое = оп.название ?? ЗАГЛАВНОЕ(оп.тип);
    const сколько = названияИспользованные.get(базовое) ?? 1;
    const k = (счёт.get(базовое) ?? 0) + 1;
    счёт.set(базовое, k);
    const название = сколько > 1 && !оп.название ? `${базовое} ${k}` : базовое;
    const гр = границыКонтура(д.контурПлана);
    const контур = д.контурПлана.map(([x, z]) => [x - гр.центр[0], z - гр.центр[1]] as Точка);
    const п: Помещение = {
      id: д.id,
      тип: оп.тип,
      название,
      контур,
      высота: оп.высота ?? 2700,
      толщина_стен: д.t,
      смещение: [гр.центр[0], гр.центр[1]],
      отметки: [],
      отделка: пустаяОтделка(),
    };
    if (знаковаяПлощадь(контур) <= 0) ошибки.push(`«${название}»: контур получился вырожденным`);
    помещения.push(п);
    шт.set(н, п);
  }

  // 2. общие стены: единичные рёбра между разными помещениями
  interface Единичное {
    а: number;
    б: number;
    горизонтально: boolean;
    линия: number;
    от: number;
    до: number;
  }
  const единичные: Единичное[] = [];
  for (let r = 0; r < рядов; r++) {
    for (let c = 0; c < столбцов; c++) {
      const н = номер(r, c);
      if (!н) continue;
      const юг = номер(r + 1, c);
      if (юг && юг !== н) единичные.push({ а: Math.min(н, юг), б: Math.max(н, юг), горизонтально: true, линия: r + 1, от: c, до: c + 1 });
      const восток = номер(r, c + 1);
      if (восток && восток !== н) единичные.push({ а: Math.min(н, восток), б: Math.max(н, восток), горизонтально: false, линия: c + 1, от: r, до: r + 1 });
    }
  }
  единичные.sort((a, b) => a.а - b.а || a.б - b.б || Number(b.горизонтально) - Number(a.горизонтально) || a.линия - b.линия || a.от - b.от);
  interface Участок {
    а: number;
    б: number;
    горизонтально: boolean;
    линия: number;
    от: number;
    до: number;
  }
  const участки: Участок[] = [];
  for (const е of единичные) {
    const пред = участки[участки.length - 1];
    if (пред && пред.а === е.а && пред.б === е.б && пред.горизонтально === е.горизонтально && пред.линия === е.линия && пред.до === е.от) {
      пред.до = е.до;
    } else участки.push({ ...е });
  }

  const связи: Связь[] = [];
  const точка = (у: Участок, т: number): Точка => (у.горизонтально ? [т * клетка, у.линия * клетка] : [у.линия * клетка, т * клетка]);
  for (const у of участки) {
    const да = данные.get(у.а);
    const дб = данные.get(у.б);
    if (!да || !дб) continue;
    const середина = (у.от + у.до) / 2;
    const [mx, mz] = у.горизонтально ? [середина, у.линия] : [у.линия, середина];
    const стенаА = реброСТочкой(да.контурСетки, mx, mz);
    const стенаБ = реброСТочкой(дб.контурСетки, mx, mz);
    связи.push({
      id: `с${связи.length + 1}`,
      а: да.id,
      б: дб.id,
      стена_а: стенаА,
      стена_б: стенаБ,
      участок: [точка(у, у.от), точка(у, у.до)],
    });
    if (стенаА < 0 || стенаБ < 0) ошибки.push(`Общая стена помещений ${у.а} и ${у.б}: не найдено ребро контура`);
  }

  // 3. проёмы
  let счётчикОтметок = 0;
  for (const п of задача.проёмы ?? []) {
    const [r, c] = п.клетка;
    const н = номер(r, c);
    if (!н) {
      ошибки.push(`Проём в клетке [${r}, ${c}]: клетка не закрашена`);
      continue;
    }
    const д = ПО_УМОЛЧАНИЮ[п.вид];
    const ширина = п.ширина ?? д.ш;
    const высота = п.высота ?? д.в;
    const отПола = п.от_пола ?? д.пол;
    const [dr, dc] = ВЕКТОР_СТОРОНЫ[п.сторона];
    const сосед = номер(r + dr, c + dc);
    const ребро = ребройСтороны(r, c, п.сторона);

    if (п.вид === 'окно' && сосед && сосед !== н) {
      ошибки.push(`Окно в клетке [${r}, ${c}] стоит между помещениями: окно возможно только в наружной стене`);
      continue;
    }

    const вычислить = (номерКомнаты: number, ведёт: number | null): { пом: Помещение; отметка: Отметка } | { ошибка: string } | null => {
      const дан = данные.get(номерКомнаты);
      const пом = шт.get(номерКомнаты);
      if (!дан || !пом) return null;
      const индекс = реброСТочкой(дан.контурСетки, ребро.середина[0], ребро.середина[1]);
      if (индекс < 0) return { ошибка: 'не найдена стена' };
      // положение центра проёма вдоль стены: проекция точки оси стены на сдвинутое ребро
      const ст = стены(дан.контурПлана)[индекс];
      const серединаМм: Точка = [ребро.середина[0] * клетка, ребро.середина[1] * клетка];
      const внутрь: Точка = [серединаМм[0] + ст.нормаль[0] * (дан.t / 2), серединаМм[1] + ст.нормаль[1] * (дан.t / 2)];
      const вдоль = (внутрь[0] - ст.а[0]) * ст.направление[0] + (внутрь[1] - ст.а[1]) * ст.направление[1];
      const от = Math.round(вдоль - ширина / 2);
      if (от < 0 || от + ширина > ст.длина + 0.5) {
        return {
          ошибка: `${п.вид} шириной ${ширина} мм не помещается на стене «${пом.название}» (стена ${Math.round(ст.длина)} мм, проём займёт ${от}…${от + ширина})`,
        };
      }
      const отметка: Отметка = { id: '', стена: индекс, вид: п.вид, от_угла: от, от_пола: отПола, ширина, высота };
      if (ведёт !== null) {
        const другой = шт.get(ведёт);
        if (другой) отметка.ведёт_в = другой.id;
      }
      return { пом, отметка };
    };

    const стороны = сосед && сосед !== н ? [вычислить(н, сосед), вычислить(сосед, н)] : [вычислить(н, null)];
    const сбой = стороны.find((с) => с && 'ошибка' in с) as { ошибка: string } | undefined;
    if (сбой) {
      ошибки.push(`Проём в клетке [${r}, ${c}]: ${сбой.ошибка}`);
      continue;
    }
    const готовые = стороны.filter((с): с is { пом: Помещение; отметка: Отметка } => !!с && 'пом' in с);
    for (const { пом, отметка } of готовые) {
      отметка.id = `о${++счётчикОтметок}`;
      пом.отметки.push(отметка);
    }
    if (сосед && сосед !== н && готовые.length === 2) {
      const a = шт.get(н)?.id;
      const б = шт.get(сосед)?.id;
      const [mx, mz] = [ребро.середина[0] * клетка, ребро.середина[1] * клетка];
      const связь = связи.find((с) => {
        if (!((с.а === a && с.б === б) || (с.а === б && с.б === a))) return false;
        const [[x1, z1], [x2, z2]] = с.участок;
        return mx >= Math.min(x1, x2) && mx <= Math.max(x1, x2) && mz >= Math.min(z1, z2) && mz <= Math.max(z1, z2);
      });
      if (связь) for (const { отметка } of готовые) отметка.связь = связь.id;
    }
  }

  // 4. проверка: все отметки внутри своих стен
  for (const п of помещения) {
    const ст = стены(п.контур);
    for (const о of п.отметки) {
      const с = ст[о.стена];
      if (о.от_угла < 0 || о.от_угла + о.ширина > с.длина) {
        предупреждения.push(`«${п.название}»: ${о.вид} почти у угла (стена ${Math.round(с.длина)} мм), проверьте положение`);
      }
    }
  }

  return { помещения, связи, ошибки, предупреждения };
}

/** Дверь в первой общей стене каждой пары соседних помещений */
export function автоПроёмы(клетки: number[][], клетка = 500): ПроёмПоСетке[] {
  const ширина = Math.max(400, Math.min(900, клетка - 150));
  const пары = new Set<string>();
  const р: ПроёмПоСетке[] = [];
  for (let r = 0; r < клетки.length; r++) {
    for (let c = 0; c < клетки[r].length; c++) {
      const а = клетки[r][c];
      if (!а) continue;
      const проверить = (б: number, сторона: 'в' | 'ю') => {
        if (!б || б === а) return;
        const к = [Math.min(а, б), Math.max(а, б)].join('-');
        if (пары.has(к)) return;
        пары.add(к);
        р.push({ клетка: [r, c], сторона, вид: "дверь", ширина });
      };
      проверить(клетки[r][c + 1] ?? 0, 'в');
      проверить(клетки[r + 1]?.[c] ?? 0, 'ю');
    }
  }
  return р;
}

