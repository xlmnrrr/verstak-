/**
 * Помещения: контуры-многоугольники, стены, отметки на стенах (проёмы, ниши, розетки, вода, щитки).
 * Контур — внутренний, по часовой стрелке при взгляде сверху (X вправо, Z вниз), в мм.
 */
import type { Отметка, Помещение, ТипПомещения, Вектор3 } from './типы';

export type Точка = [number, number];

export const прямоугольник = (ш: number, г: number, центр = true): Точка[] => {
  const x0 = центр ? -ш / 2 : 0;
  const z0 = центр ? -г / 2 : 0;
  return [
    [x0, z0],
    [x0 + ш, z0],
    [x0 + ш, z0 + г],
    [x0, z0 + г],
  ];
};

/** Г-образный контур: общий прямоугольник ш×г, из правого переднего угла вырезан вырез в×д */
export function контурГ(ш: number, г: number, вырезШ: number, вырезГ: number): Точка[] {
  return [
    [0, 0],
    [ш, 0],
    [ш, г - вырезГ],
    [ш - вырезШ, г - вырезГ],
    [ш - вырезШ, г],
    [0, г],
  ];
}

/** П-образный контур: ш×г с вырезом по центру переднего края */
export function контурП(ш: number, г: number, вырезШ: number, вырезГ: number): Точка[] {
  const x0 = (ш - вырезШ) / 2;
  return [
    [0, 0],
    [ш, 0],
    [ш, г],
    [x0 + вырезШ, г],
    [x0 + вырезШ, г - вырезГ],
    [x0, г - вырезГ],
    [x0, г],
    [0, г],
  ];
}

/** Знаковая площадь (формула шнуровки). В системе «Z вниз» контур по часовой даёт положительную. */
export function знаковаяПлощадь(к: Точка[]): number {
  let s = 0;
  for (let i = 0; i < к.length; i++) {
    const [x1, z1] = к[i];
    const [x2, z2] = к[(i + 1) % к.length];
    s += x1 * z2 - x2 * z1;
  }
  return s / 2;
}

export const площадьМм2 = (к: Точка[]) => Math.abs(знаковаяПлощадь(к));
export const площадьМ2 = (к: Точка[]) => площадьМм2(к) / 1_000_000;

export function границыКонтура(к: Точка[]) {
  const xs = к.map((p) => p[0]);
  const zs = к.map((p) => p[1]);
  const x0 = Math.min(...xs);
  const x1 = Math.max(...xs);
  const z0 = Math.min(...zs);
  const z1 = Math.max(...zs);
  return { x0, x1, z0, z1, ш: x1 - x0, г: z1 - z0, центр: [(x0 + x1) / 2, (z0 + z1) / 2] as Точка };
}

export interface Стена {
  индекс: number;
  а: Точка;
  б: Точка;
  длина: number;
  /** единичный вектор вдоль стены */
  направление: Точка;
  /** единичная нормаль внутрь помещения */
  нормаль: Точка;
}

/** Рёбра контура как стены. Нормаль внутрь — справа от направления (контур по часовой, Z вниз). */
export function стены(к: Точка[]): Стена[] {
  const ориентация = знаковаяПлощадь(к) >= 0 ? 1 : -1;
  return к.map((а, i) => {
    const б = к[(i + 1) % к.length];
    const dx = б[0] - а[0];
    const dz = б[1] - а[1];
    const длина = Math.hypot(dx, dz);
    const н: Точка = длина ? [dx / длина, dz / длина] : [0, 0];
    return {
      индекс: i,
      а,
      б,
      длина,
      направление: н,
      нормаль: [-н[1] * ориентация, н[0] * ориентация],
    };
  });
}

/** Точка внутри контура (чётно-нечётное правило) */
export function точкаВнутри(к: Точка[], x: number, z: number): boolean {
  let внутри = false;
  for (let i = 0, j = к.length - 1; i < к.length; j = i++) {
    const [xi, zi] = к[i];
    const [xj, zj] = к[j];
    if (zi > z !== zj > z && x < ((xj - xi) * (z - zi)) / (zj - zi) + xi) внутри = !внутри;
  }
  return внутри;
}

function отрезкиПересекаются(a: Точка, b: Точка, c: Точка, d: Точка): boolean {
  const о = (p: Точка, q: Точка, r: Точка) => (q[0] - p[0]) * (r[1] - p[1]) - (q[1] - p[1]) * (r[0] - p[0]);
  const o1 = о(a, b, c);
  const o2 = о(a, b, d);
  const o3 = о(c, d, a);
  const o4 = о(c, d, b);
  return o1 * o2 < 0 && o3 * o4 < 0;
}

/** Пересекает ли контур сам себя (несмежные рёбра) */
export function самопересечение(к: Точка[]): boolean {
  const n = к.length;
  for (let i = 0; i < n; i++) {
    for (let j = i + 2; j < n; j++) {
      if (i === 0 && j === n - 1) continue;
      if (отрезкиПересекаются(к[i], к[(i + 1) % n], к[j], к[(j + 1) % n])) return true;
    }
  }
  return false;
}

/** Положение отметки в мире помещения: центр на стене, вдоль стены, нормаль */
export function отметкаВПлане(п: Помещение, о: Отметка) {
  const с = стены(п.контур)[о.стена];
  if (!с) return null;
  const середина = о.от_угла + о.ширина / 2;
  const центр: Вектор3 = [
    с.а[0] + с.направление[0] * середина,
    о.от_пола + о.высота / 2,
    с.а[1] + с.направление[1] * середина,
  ];
  return { центр, стена: с, середина };
}

/** Проверка помещения: возвращает человекопонятные проблемы (пусто — всё в порядке) */
export function проверитьПомещение(п: Помещение): string[] {
  const п_: string[] = [];
  if (п.контур.length < 3) {
    п_.push(`«${п.название}»: в контуре меньше трёх точек`);
    return п_;
  }
  if (самопересечение(п.контур)) п_.push(`«${п.название}»: контур пересекает сам себя`);
  if (знаковаяПлощадь(п.контур) < 0) п_.push(`«${п.название}»: контур задан против часовой стрелки`);
  // ниши под шкаф тоже помещения, поэтому порог низкий: ловим только вырожденные контуры
  if (площадьМ2(п.контур) < 0.25) п_.push(`«${п.название}»: площадь меньше 0,25 м²`);
  const ст = стены(п.контур);
  for (const о of п.отметки) {
    const с = ст[о.стена];
    if (!с) {
      п_.push(`«${п.название}»: отметка «${о.вид}» ссылается на несуществующую стену ${о.стена}`);
      continue;
    }
    if (о.от_угла < 0 || о.от_угла + о.ширина > с.длина + 0.5) {
      п_.push(`«${п.название}»: ${о.вид} выходит за стену ${о.стена} (стена ${Math.round(с.длина)} мм, отметка ${о.от_угла}…${о.от_угла + о.ширина})`);
    }
    if (typeof п.высота === 'number' && о.от_пола + о.высота > п.высота + 0.5 && (о.вид === 'дверь' || о.вид === 'окно' || о.вид === 'арка')) {
      п_.push(`«${п.название}»: ${о.вид} выше стены`);
    }
  }
  return п_;
}

export const пустаяОтделка = () => ({ стены: '#cbb79a', пол: '#8a6a4b' });

export function новоеПомещение(
  id: string,
  тип: ТипПомещения,
  название: string,
  контур: Точка[],
  высота: number | 'неизвестна' = 2700,
): Помещение {
  return {
    id,
    тип,
    название,
    контур,
    высота,
    толщина_стен: 100,
    смещение: [0, 0],
    отметки: [],
    отделка: пустаяОтделка(),
  };
}

