/**
 * Модель v2 «Верстака»: изделие → раскладка → экземпляр → детали.
 * Чистый TypeScript: без three, react, zustand и DOM (проверяет архитектура.test.ts).
 *
 * Все размеры — целые миллиметры. Оси изделия (локальные): X — ширина, Y — высота (от пола),
 * Z — глубина; фасад смотрит в +Z; начало — центр низа изделия.
 * Поворот экземпляра — градусы вокруг вертикали, по часовой стрелке при взгляде сверху
 * (как в v1: фасад при 90° смотрит в −X).
 */

export type Вектор3 = [number, number, number];

/** ш — ширина (X), г — глубина (Z), в — высота (Y) */
export interface Габариты {
  ш: number;
  г: number;
  в: number;
}

export type ТипПомещения =
  | 'кухня'
  | 'спальня'
  | 'гостиная'
  | 'детская'
  | 'кабинет'
  | 'прихожая'
  | 'гардеробная'
  | 'ванная'
  | 'санузел'
  | 'коридор'
  | 'кладовая'
  | 'лоджия';

