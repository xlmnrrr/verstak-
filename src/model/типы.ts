export type ВидИзделия =
  | 'корпус'
  | 'столешница'
  | 'техника'
  | 'мягкая'
  | 'стол'
  | 'стул'
  | 'свет'
  | 'декор'
  | 'проём';

export type Крепление = 'пол' | 'стена' | 'потолок' | 'ниша';

/* ------------------------------------------------------------------ раскладка */

export type ТипФасада = 'нет' | 'распашной' | 'купе' | 'ящики' | 'подъёмник' | 'push' | 'зеркало' | 'стекло';
export type СторонаПетель = 'слева' | 'справа' | 'попарно' | 'сверху' | 'снизу';
export type ВидРучки = 'скоба' | 'рейлинг' | 'кнопка' | 'профиль' | 'нет';
export type МестоРучки = 'верх' | 'низ' | 'середина' | 'край';
export type ТипПолки = 'регулируемая' | 'съёмная' | 'стационарная';
export type НаправлениеПолок = 'снизу-вверх' | 'слева-направо';

export interface Ручка {
  вид: ВидРучки;
  место: МестоРучки;
}

export interface Фасад {
  тип: ТипФасада;
  /** число створок; 'авто' — по ширине (см. раскладка.ts) */
  створок: number | 'авто';
  /** число ящиков для типа «ящики» (в остальных случаях только хранится) */
  ящиков: number;
  петли: СторонаПетель;
  ручка: Ручка;
}

export interface КорпусРаскладки {
  плита: 16 | 18;
  задник: 'есть' | 'нет' | 'ХДФ';
  /** высота цоколя, мм; 0 — без цоколя */
  цоколь: number;
  /** высота ножек, мм (поднимают корпус, если цоколя нет) */
  ножки: number;
  /** толщина крыши, если не равна плите (например 20) */
  крыша?: number;
  /** false — корпус без боковин (в нишу: стены ниши работают как боковины) */
  боковины: boolean;
}

export interface Наполнение {
  направление: НаправлениеПолок;
  /** число полок (или перегородок при «слева-направо»); 'авто' — шаг 320, перестановка 32 */
  число: number | 'авто';
  тип: ТипПолки;
  ящики?: { число: number; высота: number | 'авто' };
  /** штанга: высота оси над полом изделия, мм */
  штанга?: { высота: number };
}

export interface Секция {
  /** мм или 'доля' — тянется пропорционально `вес` */
  ширина: number | 'доля';
  вес?: number;
  наполнение: Наполнение;
}

export interface Раскладка {
  корпус: КорпусРаскладки;
  /** слева направо */
  секции: Секция[];
  фасад: Фасад;
}

/** Отличия экземпляра от изделия. Секции, если указаны, заменяют секции изделия целиком. */
export interface ЧастичнаяРаскладка {
  корпус?: Partial<КорпусРаскладки>;
  секции?: Секция[];
  фасад?: Partial<Omit<Фасад, 'ручка'>> & { ручка?: Partial<Ручка> };
}

/** Ключи материалов: цвет `#rrggbb` или id материала из библиотеки (этап 5) */
export type КлючМатериала = 'корпус' | 'фасад' | 'столешница' | 'ручки' | 'стекло' | 'задник' | 'цоколь' | 'техника';
export type Материалы = Partial<Record<КлючМатериала, string>>;

/* ------------------------------------------------------------------ изделие */

export type Выражение = number | { ш?: number; г?: number; в?: number; плюс?: number };

/** Блок составного изделия (угловой шкаф, Г-образная тумба) */
export interface Блок {
  имя: string;
  /** центр низа блока относительно центра низа изделия */
  смещение: [Выражение, Выражение, Выражение];
  /** 0 | 90 | 180 | 270 */
  поворот: 0 | 90 | 180 | 270;
  габариты: { ш: Выражение; г: Выражение; в: Выражение };
  раскладка?: ЧастичнаяРаскладка;
}

export type ВидОткрывания = 'дверь' | 'ящик' | 'купе' | 'подъёмник' | 'техника';

export interface Изделие {
  id: string;
  название: string;
  помещения: ТипПомещения[];
  категория: string;
  тип: ВидИзделия;
  габариты: Габариты;
  границы: { мин: Габариты; макс: Габариты };
  крепление: Крепление;
  /** для навесных: высота низа по умолчанию */
  подъём?: number;
  раскладка: Раскладка;
  материалы: Материалы;
  /** название материала словами (в v1 — поле «материал»), например «ЛДСП 16 мм» */
  материал_описание?: string;
  /** составное изделие: детали строятся по блокам, а не по общей раскладке */
  состав?: Блок[];
  /** этап 2: какие части открываются */
  открывание?: ВидОткрывания[];
  /** на сколько градусов открываются распашные двери и люки; по умолчанию 100, конфликты считаются на максимуме 110 */
  угол_открывания?: number;
  /**
   * Угловой модуль Г-формы (кухня): угол помещения — справа сзади в осях изделия, плечо вдоль задней стены по ширине
   * и плечо вдоль правой стены по глубине; `плечо` — глубина каждого плеча вместе с фасадом.
   * Свободный угол спереди слева: следы для проверок — два прямоугольника, а не габарит.
   */
  угловой?: { плечо: number; карусель: 'три-четверти' | 'нет'; дверцы: boolean };
  источник?: { лист: string; достоверность: 'точно' | 'спорно' | 'нечитаемо'; заметка?: string };
  /** связь со старым каталогом v1 (мост для старого рендера, уйдёт в 1А-2) */
  v1?: { модуль: string; вид: string };
  заметка?: string;
}

/* ------------------------------------------------------------------ экземпляр */

export interface Экземпляр {
  id: string;
  изделие: string;
  помещение: string;
  название?: string;
  /** X и Z — центр, Y — низ, мм, в осях помещения */
  позиция: Вектор3;
  поворот: number;
  габариты: Габариты;
  раскладка?: ЧастичнаяРаскладка;
  материалы?: Материалы;
  /** название материала словами (в v1 — поле «материал») */
  материал_описание?: string;
  открыт?: boolean;
  /** открыты по отдельности: имена подвижных групп (этап 2); `открыт: true` означает «все открыты» */
  открыто?: string[];
  /** свой угол открывания распашных дверей экземпляра, градусы (вместо угла изделия) */
  угол_открывания?: number;
  /** 'уточнить-высоту', 'было:<модуль v1>', 'наклон:X=5' … */
  метки?: string[];
  /** неизвестные поля из файла — пишутся обратно при сохранении */
  прочее?: Record<string, unknown>;
}

