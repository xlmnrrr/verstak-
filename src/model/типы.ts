/**
 * Кромка в осях деталировки. Знак: «длинаN» — грани с нормалью вдоль оси ширины, «ширинаN» — с нормалью вдоль оси длины;
 * N = 1 — плюс-сторона оси, N = 2 — минус-сторона (оси ранжируются по размеру; рендер переводит в 6 бит граней).
 */
export interface Кромка {
  длина1: number;
  длина2: number;
  ширина1: number;
  ширина2: number;
}

/** Положение детали в осях изделия: центр и размеры по осям X, Y, Z */
export interface Положение {
  центр: Вектор3;
  объём: Вектор3;
}

export interface Деталь {
  роль: РольДетали;
  /** для деталировки: [длина, ширина, толщина], мм, по убыванию */
  размер: Вектор3;
  кромка: Кромка;
  материал: КлючМатериала | 'зеркало' | 'техника';
  локально: Положение;
  форма: 'плита' | 'цилиндр' | 'модель';
  /** ось цилиндра (штанга) */
  ось?: 'x' | 'y' | 'z';
  /**
   * Профиль цилиндра с вертикальной осью: 'сектор270' — диск без четверти (вырез спереди слева, −X и +Z),
   * 'обод270' — бортик по дуге того же диска. Полка «карусель 3/4» углового модуля.
   */
  профиль?: 'сектор270' | 'обод270';
  /** двери и ящики: группа для открывания (этап 2) */
  подвижная?: { группа: string };
  /** готовый материал (техника): цвет, шероховатость, металличность; вместо ключа `материал` */
  литерал?: { цвет: string; шер: number; мет: number };
}

