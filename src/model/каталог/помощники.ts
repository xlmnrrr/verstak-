/** Короткие конструкторы изделий: описание в одну-две строки → полное `Изделие`. */
import {
  корпусПоУмолчанию,
  фасадПоУмолчанию,
} from '../раскладка';
import type {
  Блок,
  Габариты,
  Изделие,
  Крепление,
  Материалы,
  Наполнение,
  Раскладка,
  Секция,
  ТипПомещения,
  ТипПолки,
  ТипФасада,
  ВидИзделия,
  ВидРучки,
  МестоРучки,
  СторонаПетель,
} from '../типы';

export type Три = [number, number, number];

export interface СекцияОп {
  /** вес доли (по умолчанию 1) */
  вес?: number;
  /** фиксированная ширина, мм (вместо веса) */
  ширина?: number;
  полки?: number | 'авто';
  /** вертикальные перегородки вместо горизонтальных полок */
  перегородки?: boolean;
  ящики?: number | { число: number; высота?: number | 'авто' };
  штанга?: number;
  тип?: ТипПолки;
}

export interface Описание {
  id: string;
  название: string;
  категория: string;
  помещения: ТипПомещения[];
  тип?: ВидИзделия;
  габ: Три;
  мин?: Три;
  макс?: Три;
  крепление?: Крепление;
  подъём?: number;
  цоколь?: number;
  ножки?: number;
  плита?: 16 | 18;
  задник?: 'есть' | 'нет' | 'ХДФ';
  крыша?: number;
  боковины?: boolean;
  /** число полок в единственной секции (если нет `секции`) */
  полки?: number | 'авто';
  ящиков?: number;
  секции?: СекцияОп[];
  фасад?: ТипФасада;
  створок?: number | 'авто';
  петли?: СторонаПетель;
  ручка?: ВидРучки;
  местоРучки?: МестоРучки;
  цвет?: string;
  описаниеМатериала?: string;
  материалы?: Материалы;
  состав?: Блок[];
  источник?: Изделие['источник'];
  v1?: Изделие['v1'];
  заметка?: string;
}

const габ = ([ш, г, в]: Три): Габариты => ({ ш, г, в });

function секция(с: СекцияОп | undefined, запасПолок: number | 'авто'): Секция {
  const н: Наполнение = {
    направление: с?.перегородки ? 'слева-направо' : 'снизу-вверх',
    число: с?.полки ?? запасПолок,
    тип: с?.тип ?? 'регулируемая',
  };
  if (с?.ящики) {
    н.ящики =
      typeof с.ящики === 'number'
        ? { число: с.ящики, высота: 'авто' }
        : { число: с.ящики.число, высота: с.ящики.высота ?? 'авто' };
  }
  if (с?.штанга) н.штанга = { высота: с.штанга };
  return с?.ширина !== undefined
    ? { ширина: с.ширина, наполнение: н }
    : { ширина: 'доля', вес: с?.вес ?? 1, наполнение: н };
}

export function раскладкаИз(о: Описание): Раскладка {
  const фас = фасадПоУмолчанию();
  фас.тип = о.фасад ?? 'нет';
  фас.ящиков = о.ящиков ?? 0;
  if (о.створок !== undefined) фас.створок = о.створок;
  if (о.петли) фас.петли = о.петли;
  фас.ручка.вид = о.ручка ?? (фас.тип === 'push' || фас.тип === 'зеркало' || фас.тип === 'купе' ? 'нет' : 'скоба');
  if (о.местоРучки) фас.ручка.место = о.местоРучки;

  const корпус = корпусПоУмолчанию();
  if (о.плита) корпус.плита = о.плита;
  if (о.задник) корпус.задник = о.задник;
  if (о.цоколь !== undefined) корпус.цоколь = о.цоколь;
  if (о.ножки !== undefined) корпус.ножки = о.ножки;
  if (о.крыша !== undefined) корпус.крыша = о.крыша;
  if (о.боковины !== undefined) корпус.боковины = о.боковины;

  const секции = (о.секции ?? [{}]).map((с) => секция(с, о.полки ?? 0));
  return { корпус, секции, фасад: фас };
}

/** Собрать изделие из короткого описания */
export function изделие(о: Описание): Изделие {
  const тип = о.тип ?? 'корпус';
  const мин = о.мин ?? ([Math.round(о.габ[0] * 0.5), Math.round(о.габ[1] * 0.6), Math.round(о.габ[2] * 0.5)] as Три);
  const макс = о.макс ?? ([Math.round(о.габ[0] * 2), Math.round(о.габ[1] * 1.5), Math.round(о.габ[2] * 1.2)] as Три);
  const материалы: Материалы = { ...(о.цвет ? { фасад: о.цвет } : {}), ...(о.материалы ?? {}) };
  const р: Изделие = {
    id: о.id,
    название: о.название,
    помещения: о.помещения,
    категория: о.категория,
    тип,
    габариты: габ(о.габ),
    границы: { мин: габ(мин), макс: габ(макс) },
    крепление: о.крепление ?? 'пол',
    раскладка: раскладкаИз(о),
    материалы,
  };
  if (о.описаниеМатериала) р.материал_описание = о.описаниеМатериала;
  if (о.подъём !== undefined) р.подъём = о.подъём;
  if (о.состав) р.состав = о.состав;
  if (о.источник) р.источник = о.источник;
  if (о.v1) р.v1 = о.v1;
  if (о.заметка) р.заметка = о.заметка;
  return р;
}
