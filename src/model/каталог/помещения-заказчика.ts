export interface СпорныйРазмер {
  помещение: string;
  что: string;
  заметка: string;
}

/** Всё, что помечено «уточнить»: для списка «требует подтверждения» */
export function спорныеОтметки(помещения: Помещение[]): СпорныйРазмер[] {
  const р: СпорныйРазмер[] = [];
  for (const п of помещения) {
    if (п.метки?.includes(УТОЧНИТЬ) || п.метки?.some((м) => м.startsWith('спорно'))) {
      const высота = typeof п.высота === 'number' ? `высота принята ${п.высота} мм` : 'высота неизвестна';
      р.push({ помещение: п.название, что: `помещение: ${п.метки.join(', ')}`, заметка: п.мебель_высота ? `${высота}; мебель ${п.мебель_высота} мм по замеру, до потолка — вариант` : высота });
    }
    for (const о of п.отметки) {
      if (о.метки?.includes(УТОЧНИТЬ)) р.push({ помещение: п.название, что: `${о.вид} (${о.метки.filter((м) => м !== УТОЧНИТЬ).join(', ') || 'размеры'})`, заметка: о.заметка ?? '' });
    }
  }
  return р;
}
