/**
 * Свободная правка стен (пожелание Макара 13.11.2026, «как в Симс»): сдвинуть стену, передвинуть угол, поставить точку
 * на стене, удалить точку, сделать выступ или вырезать угол (короб, колонна, ниша наружу). Чистая геометрия в мм.
 * После правки контур упрощается (совпадающие и лежащие на одной прямой точки убираются), отметки на стенах
 * переносятся на ближайшую стену нового контура по своему центру — проёмы и розетки остаются на месте в комнате.
 * Мебель не двигается: её координаты в осях помещения не зависят от контура.
 */
import { знаковаяПлощадь, стены, высотаДляРендера, type Точка } from './помещение';
import type { Отметка, Помещение } from './типы';

const ε = 0.5;
const округл = (p: Точка): Точка => [Math.round(p[0] * 10) / 10, Math.round(p[1] * 10) / 10];

/** Убрать совпадающие соседние точки и точки, лежащие на прямой между соседями */
export function упроститьКонтур(к: Точка[]): Точка[] {
  let т = к.map(округл);
  for (let шаг = 0; шаг < 4; шаг++) {
    const n = т.length;
    const р: Точка[] = [];
    for (let i = 0; i < n; i++) {
      const a = т[(i + n - 1) % n];
      const b = т[i];
      const c = т[(i + 1) % n];
      if (Math.hypot(b[0] - a[0], b[1] - a[1]) < ε) continue;
      const крест = (b[0] - a[0]) * (c[1] - b[1]) - (b[1] - a[1]) * (c[0] - b[0]);
      const дл = Math.hypot(b[0] - a[0], b[1] - a[1]) * Math.hypot(c[0] - b[0], c[1] - b[1]);
      if (дл > 0 && Math.abs(крест) / дл < 1e-6) continue;
      р.push(b);
    }
    if (р.length === т.length) break;
    т = р;
  }
  return т;
}

/** Пересекаются ли отрезки (без общих концов) */
function пересечение(a: Точка, b: Точка, c: Точка, d: Точка): boolean {
  const о = (p: Точка, q: Точка, r: Точка) => Math.sign((q[0] - p[0]) * (r[1] - p[1]) - (q[1] - p[1]) * (r[0] - p[0]));
  return о(a, b, c) * о(a, b, d) < 0 && о(c, d, a) * о(c, d, b) < 0;
}

/** Ошибка контура словами или null: не меньше трёх стен, стены не короче 50 мм, без самопересечений, площадь больше нуля */
export function ошибкаКонтура(к: Точка[]): string | null {
  if (к.length < 3) return 'В помещении должно остаться не меньше трёх стен.';
  for (const с of стены(к)) if (с.длина < 50) return `Стена ${с.индекс + 1} короче 50 мм (${Math.round(с.длина)} мм) — так не построить.`;
  const n = к.length;
  for (let i = 0; i < n; i++) {
    for (let j = i + 2; j < n; j++) {
      if (i === 0 && j === n - 1) continue;
      if (пересечение(к[i], к[(i + 1) % n], к[j], к[(j + 1) % n])) return `Стены ${i + 1} и ${j + 1} пересекаются — контур не должен перекручиваться.`;
    }
  }
  if (Math.abs(знаковаяПлощадь(к)) < 1e4) return 'У помещения не осталось площади.';
  return null;
}

/** Перенести отметки на ближайшую стену нового контура по их центру (на высоте не влияет) */
export function перенестиОтметки(старый: Точка[], новый: Точка[], отметки: Отметка[]): Отметка[] {
  const ст = стены(старый);
  const нв = стены(новый);
  return отметки.flatMap((о) => {
    const с = ст[о.стена];
    if (!с) return [о];
    const s = о.от_угла + о.ширина / 2;
    const p: Точка = [с.а[0] + с.направление[0] * s, с.а[1] + с.направление[1] * s];
    let лучшая: { i: number; s: number; d: number } | null = null;
    for (const w of нв) {
      const t = Math.max(0, Math.min(w.длина, (p[0] - w.а[0]) * w.направление[0] + (p[1] - w.а[1]) * w.направление[1]));
      const d = Math.hypot(w.а[0] + w.направление[0] * t - p[0], w.а[1] + w.направление[1] * t - p[1]);
      if (!лучшая || d < лучшая.d) лучшая = { i: w.индекс, s: t, d };
    }
    if (!лучшая) return [];
    const w = нв[лучшая.i];
    const ширина = Math.min(о.ширина, w.длина);
    const от_угла = Math.max(0, Math.min(w.длина - ширина, лучшая.s - ширина / 2));
    return [{ ...о, стена: лучшая.i, от_угла: Math.round(от_угла), ширина: Math.round(ширина) }];
  });
}

export interface ИтогПравки {
  помещение: Помещение;
  ошибка: string | null;
}

/** Применить новый контур: упростить, проверить, перенести отметки. При ошибке помещение прежнее */
export function сКонтуром(пом: Помещение, контур: Точка[]): ИтогПравки {
  const к = упроститьКонтур(контур);
  const ошибка = ошибкаКонтура(к);
  if (ошибка) return { помещение: пом, ошибка };
  return { помещение: { ...пом, контур: к, отметки: перенестиОтметки(пом.контур, к, пом.отметки) }, ошибка: null };
}

/** Пересечение двух прямых (точка + направление) */
function прямые(p: Точка, u: Точка, q: Точка, v: Точка): Точка | null {
  const з = u[0] * v[1] - u[1] * v[0];
  if (Math.abs(з) < 1e-9) return null;
  const t = ((q[0] - p[0]) * v[1] - (q[1] - p[1]) * v[0]) / з;
  return [p[0] + u[0] * t, p[1] + u[1] * t];
}

/**
 * Сдвинуть стену i на Δ мм по нормали: + внутрь помещения, − наружу. Соседние стены сохраняют направление
 * (концы — на пересечении прямых), поэтому прямоугольник остаётся прямоугольником, Г — Г.
 */
export function сдвинутьСтену(пом: Помещение, i: number, Δ: number): ИтогПравки {
  const к = пом.контур;
  const n = к.length;
  const с = стены(к);
  const w = с[i];
  if (!w) return { помещение: пом, ошибка: 'Нет такой стены.' };
  const пред = с[(i + n - 1) % n];
  const след = с[(i + 1) % n];
  const p: Точка = [w.а[0] + w.нормаль[0] * Δ, w.а[1] + w.нормаль[1] * Δ];
  const a = прямые(пред.а, пред.направление, p, w.направление) ?? p;
  const b = прямые(след.а, след.направление, p, w.направление) ?? [p[0] + w.направление[0] * w.длина, p[1] + w.направление[1] * w.длина];
  // соседние стены не должны вывернуться (стать «отрицательной» длины) — иначе угол превращается в зигзаг
  const нач = к[(i + n - 1) % n];
  const кон = к[(i + 2) % n];
  const нп = [a[0] - нач[0], a[1] - нач[1]];
  const нс = [кон[0] - b[0], кон[1] - b[1]];
  if (нп[0] * пред.направление[0] + нп[1] * пред.направление[1] < 50) return { помещение: пом, ошибка: `Дальше не сдвинуть: стена ${((i + n - 1) % n) + 1} кончилась. Нужен выступ — поставьте точку на стене.` };
  if (нс[0] * след.направление[0] + нс[1] * след.направление[1] < 50) return { помещение: пом, ошибка: `Дальше не сдвинуть: стена ${((i + 1) % n) + 1} кончилась. Нужен выступ — поставьте точку на стене.` };
  const нов = к.map((x) => [...x] as Точка);
  нов[i] = a;
  нов[(i + 1) % n] = b;
  return сКонтуром(пом, нов);
}

/** Передвинуть угол k в точку (мм, оси помещения) */
export function передвинутьУгол(пом: Помещение, k: number, x: number, z: number): ИтогПравки {
  const нов = пом.контур.map((p, i) => (i === k ? ([x, z] as Точка) : ([...p] as Точка)));
  return сКонтуром(пом, нов);
}

/** Поставить точку на стене i на расстоянии s от её начала (потом её можно тянуть) */
export function точкаНаСтене(пом: Помещение, i: number, s: number): ИтогПравки {
  const w = стены(пом.контур)[i];
  if (!w || s < 50 || s > w.длина - 50) return { помещение: пом, ошибка: 'Точка должна быть не ближе 50 мм к углу.' };
  const p: Точка = [w.а[0] + w.направление[0] * s, w.а[1] + w.направление[1] * s];
  const нов = [...пом.контур.slice(0, i + 1), p, ...пом.контур.slice(i + 1)] as Точка[];
  // без упрощения: новая точка лежит на прямой и иначе сразу пропала бы
  const ошибка = ошибкаКонтура(нов);
  return ошибка ? { помещение: пом, ошибка } : { помещение: { ...пом, контур: нов.map(округл), отметки: перенестиОтметки(пом.контур, нов, пом.отметки) }, ошибка: null };
}

/** Удалить угол k (соседние стены соединятся прямой) */
export function удалитьУгол(пом: Помещение, k: number): ИтогПравки {
  return сКонтуром(пом, пом.контур.filter((_, i) => i !== k));
}

/**
 * Выступ на стене i: участок [от_угла, от_угла + ширина] уходит внутрь помещения на глубину (короб, колонна, вырез угла);
 * отрицательная глубина — наружу (ниша, эркер). От угла 0 или до конца стены — вырезается угол (Г-образное помещение).
 */
export function выступ(пом: Помещение, i: number, от_угла: number, ширина: number, глубина: number): ИтогПравки {
  const w = стены(пом.контур)[i];
  if (!w) return { помещение: пом, ошибка: 'Нет такой стены.' };
  const s0 = Math.max(0, Math.min(w.длина, от_угла));
  const s1 = Math.max(s0, Math.min(w.длина, от_угла + ширина));
  if (s1 - s0 < 50) return { помещение: пом, ошибка: 'Ширина выступа — не меньше 50 мм.' };
  if (Math.abs(глубина) < 10) return { помещение: пом, ошибка: 'Глубина выступа — не меньше 10 мм.' };
  const т = (s: number, d: number): Точка => [w.а[0] + w.направление[0] * s + w.нормаль[0] * d, w.а[1] + w.направление[1] * s + w.нормаль[1] * d];
  const вставка: Точка[] = [т(s0, 0), т(s0, глубина), т(s1, глубина), т(s1, 0)];
  const к = пом.контур;
  let нов: Точка[] = [...к.slice(0, i + 1), ...вставка, ...к.slice(i + 1)] as Точка[];
  // вырез угла: выступ от самого угла по прямоугольнику — угол помещения уходит, соседняя стена укорачивается
  if (s0 < ε) {
    const n = к.length;
    const пред = стены(к)[(i + n - 1) % n];
    const перп = Math.abs(пред.направление[0] * w.нормаль[0] + пред.направление[1] * w.нормаль[1]) > 0.999;
    if (перп) нов = нов.filter((_, j) => j !== i);
  }
  return сКонтуром(пом, нов);
}

/** Площадь пола (м²), периметр (м), площадь стен без проёмов (м²) — для окна «Помещение» и сметы */
export function обмерПомещения(пом: Помещение): { полМ2: number; периметрМ: number; стеныМ2: number; проёмыМ2: number; высотаМ: number } {
  const H = высотаДляРендера(пом);
  const периметр = стены(пом.контур).reduce((s, с) => s + с.длина, 0);
  const проёмы = пом.отметки.filter((о) => о.вид === 'дверь' || о.вид === 'окно' || о.вид === 'арка').reduce((s, о) => s + о.ширина * о.высота, 0);
  return {
    полМ2: Math.abs(знаковаяПлощадь(пом.контур)) / 1e6,
    периметрМ: периметр / 1000,
    стеныМ2: Math.max(0, периметр * H - проёмы) / 1e6,
    проёмыМ2: проёмы / 1e6,
    высотаМ: H / 1000,
  };
}
