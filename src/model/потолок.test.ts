/**
 * Натяжной потолок и точечные светильники: уровень полотна, сетка по контуру (прямоугольник и Г), сохранение в .kitchen,
 * модель светильника (кольцо, светящаяся линза), «До потолка» — до полотна.
 */
import { describe, expect, it } from 'vitest';
import { новоеПомещение, прямоугольник, точкаВнутри } from './помещение';
import { доСтены, сеткаСветильников, уровеньПотолка, НАТЯЖНОЙ_ПО_УМОЛЧАНИЮ } from './потолок';
import { выступ } from './контур-правка';
import { новыйПроектV2, новыйЭкземпляр } from './проект';
import { записатьПроект, разобратьФайл } from './файл';
import { изделиеПоИд } from './каталог';
import { доПотолка } from './привязка';
import { примитивыСветильника } from '../render/модели/светильники';

const комната = () => новоеПомещение('п1', 'кухня', 'Кухня', прямоугольник(3600, 2800, false));

describe('натяжной потолок', () => {
  it('уровень: без полотна — перекрытие, с полотном — минус опуск', () => {
    const п = комната();
    expect(уровеньПотолка(п)).toBe(2700);
    expect(уровеньПотолка({ ...п, натяжной_потолок: НАТЯЖНОЙ_ПО_УМОЛЧАНИЮ })).toBe(2650);
    expect(уровеньПотолка({ ...п, натяжной_потолок: { ...НАТЯЖНОЙ_ПО_УМОЛЧАНИЮ, опуск: 5 } })).toBe(2680);
  });

  it('сетка в прямоугольнике 3600 × 2800, шаг 1000, от стен 500: 4 × 3 точки, все не ближе 500 к стене', () => {
    const п = комната();
    const т = сеткаСветильников(п, 1000, 500);
    expect(т).toHaveLength(12);
    for (const [x, z] of т) expect(доСтены(п.контур, x, z)).toBeGreaterThanOrEqual(499);
  });

  it('сетка в Г-образном помещении: точек меньше, ни одной в вырезе', () => {
    const р = выступ(комната(), 3, 0, 1800, 1600);
    expect(р.ошибка).toBeNull();
    const т = сеткаСветильников(р.помещение, 1000, 500);
    expect(т.length).toBeGreaterThan(3);
    expect(т.length).toBeLessThan(12);
    for (const [x, z] of т) expect(точкаВнутри(р.помещение.контур, x, z)).toBe(true);
  });

  it('сохраняется в .kitchen и открывается обратно', () => {
    const п = { ...комната(), натяжной_потолок: { фактура: 'глянец' as const, цвет: '#efe6d2', опуск: 60 } };
    const проект = новыйПроектV2('Потолок', п);
    const р = разобратьФайл(записатьПроект(проект));
    expect(р.ок).toBe(true);
    expect(р.проект?.помещения[0].натяжной_потолок).toEqual({ фактура: 'глянец', цвет: '#efe6d2', опуск: 60 });
  });

  it('«До потолка» под натяжным потолком тянет навесной шкаф до полотна', () => {
    const п = { ...комната(), натяжной_потолок: НАТЯЖНОЙ_ПО_УМОЛЧАНИЮ };
    const проект = новыйПроектV2('Потолок', п);
    const изд = изделиеПоИд('навесной-подъёмник-800')!;
    const э = новыйЭкземпляр(изд, 'п1', [1000, 1500, 200]);
    const р = доПотолка({ ...проект, объекты: [э] }, э);
    expect('экз' in р && р.экз.позиция[1]).toBe(2650 - э.габариты.в);
  });
});

describe('точечные светильники', () => {
  it('в каталоге три вида, крепление к потолку, тип «свет»', () => {
    for (const ид of ['светильник-точечный-gx53', 'светильник-точечный-led-85', 'светильник-накладной-цилиндр']) {
      const изд = изделиеПоИд(ид);
      expect(изд?.крепление).toBe('потолок');
      expect(изд?.тип).toBe('свет');
      expect(изд?.конструкция).toBe('светильник');
    }
  });

  it('модель: кольцо в цвет отделки и светящаяся линза, всё в габарите', () => {
    for (const [вариант, габ] of [['gx53', { ш: 106, г: 106, в: 12 }], ['led', { ш: 85, г: 85, в: 8 }], ['цилиндр', { ш: 80, г: 80, в: 100 }]] as const) {
      const ч = примитивыСветильника(вариант, габ, 'чёрный');
      expect(ч.some((x) => x.модель?.класс === 'лампа')).toBe(true);
      expect(ч.some((x) => x.модель?.класс === 'металл-чёрный')).toBe(true);
      for (const x of ч) {
        expect(x.t[1] + x.размер[1] / 2).toBeLessThanOrEqual(габ.в + 0.01);
        expect(Math.max(x.размер[0], x.размер[2])).toBeLessThanOrEqual(габ.ш * 1.05);
      }
    }
  });
});
