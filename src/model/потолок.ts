/**
 * Натяжной потолок и точечные светильники (пожелание Макара 13.11.2026: «натяжные потолки по нажатию и круглые лампочки,
 * которые можно ставить самому где хочется»).
 * Размеры типовые: опуск полотна под светильники GX53 — 50 мм (без светильников хватает 30, под накладные — 30…40);
 * светильник от стены — не ближе 200 мм (полотно крепится в багет у стены), шаг сетки ~1 м — ровный свет без пятен.
 * Мебель «до потолка» под натяжным потолком ставится до полотна, стены остаются полной высоты (полотно ниже их верха).
 */
import { высотаДляРендера, стены, точкаВнутри, границыКонтура, type Точка } from './помещение';
import type { Помещение } from './типы';

export type ФактураПотолка = 'мат' | 'сатин' | 'глянец';

export interface НатяжнойПотолок {
  фактура: ФактураПотолка;
  /** цвет полотна, #rrggbb */
  цвет: string;
  /** насколько полотно ниже перекрытия, мм */
  опуск: number;
}

export const НАТЯЖНОЙ_ПО_УМОЛЧАНИЮ: НатяжнойПотолок = { фактура: 'мат', цвет: '#f5f4f0', опуск: 50 };
export const ОПУСК_МИН = 20;
export const ОПУСК_МАКС = 400;
/** Светильник от стены не ближе, мм (размеры типовые) */
export const ОТ_СТЕНЫ_МИН = 200;

export const ФАКТУРЫ: [ФактураПотолка, string, string][] = [
  ['мат', 'Матовый', 'как побелка, без бликов'],
  ['сатин', 'Сатиновый', 'мягкий перламутровый отблеск'],
  ['глянец', 'Глянцевый', 'отражает комнату и свет'],
];

/** Уровень потолка в помещении, мм от пола: полотно натяжного или перекрытие */
export function уровеньПотолка(пом: Помещение): number {
  const H = высотаДляРендера(пом);
  const н = пом.натяжной_потолок;
  return н ? Math.max(1000, H - Math.max(ОПУСК_МИН, Math.min(ОПУСК_МАКС, н.опуск))) : H;
}

/** Расстояние от точки до ближайшей стены контура, мм */
export function доСтены(к: Точка[], x: number, z: number): number {
  let м = Infinity;
  for (const с of стены(к)) {
    const t = Math.max(0, Math.min(с.длина, (x - с.а[0]) * с.направление[0] + (z - с.а[1]) * с.направление[1]));
    м = Math.min(м, Math.hypot(с.а[0] + с.направление[0] * t - x, с.а[1] + с.направление[1] * t - z));
  }
  return м;
}

/**
 * Сетка светильников по контуру: ряды с шагом `шаг`, крайние — на `отступ` от стен; в Г-образном и любом другом контуре
 * точка берётся, только если она внутри и не ближе `отступ` к стене. Сетка центрируется в габарите помещения.
 */
export function сеткаСветильников(пом: Помещение, шаг = 1000, отступ = 500): Точка[] {
  const к = пом.контур;
  const г = границыКонтура(к);
  const ш = Math.max(300, шаг);
  const о = Math.max(ОТ_СТЕНЫ_МИН, отступ);
  const ряд = (от: number, до: number) => {
    const L = до - от - 2 * о;
    if (L < 0) return [(от + до) / 2];
    const n = Math.max(1, Math.round(L / ш) + 1);
    if (n === 1) return [(от + до) / 2];
    const s = L / (n - 1);
    return Array.from({ length: n }, (_, i) => от + о + i * s);
  };
  const итог: Точка[] = [];
  for (const z of ряд(г.z0, г.z1)) {
    for (const x of ряд(г.x0, г.x1)) {
      if (!точкаВнутри(к, x, z)) continue;
      if (доСтены(к, x, z) < о - 1) continue;
      итог.push([Math.round(x), Math.round(z)]);
    }
  }
  return итог;
}
