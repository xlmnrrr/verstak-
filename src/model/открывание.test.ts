const экз = (id: string, правка: Partial<Экземпляр> = {}) => ({ ...новыйЭкземпляр(изделиеПоИд(id)!, 'п1'), ...правка });
const дв = (id: string, правка: Partial<Экземпляр> = {}) => {
  const э = экз(id, правка);
  return движенияИзделия(изделиеПоИд(id)!, э);
};
const применить = (R: number[], v: number[]) => [R[0] * v[0] + R[1] * v[1] + R[2] * v[2], R[3] * v[0] + R[4] * v[1] + R[5] * v[2], R[6] * v[0] + R[7] * v[1] + R[8] * v[2]];
const около = (a: number, b: number, d = 1) => Math.abs(a - b) <= d;

describe('матрица поворота', () => {
  it('90° вокруг +Y переводит +X в −Z, вокруг +X переводит +Y в +Z', () => {
    expect(применить(матрицаПоворота([0, 1, 0], 90), [1, 0, 0]).map(Math.round)).toEqual([0, 0, -1]);
    expect(применить(матрицаПоворота([1, 0, 0], 90), [0, 1, 0]).map(Math.round)).toEqual([0, 0, 1]);
  });
});

describe('открывание: что открывается', () => {
  it('техника из списка открывается (и закрытая поза — тождество)', () => {
    const ожидание: Record<string, number> = {
      'холодильник-600': 2, // верхняя и нижняя двери
      'морозильник-600': 1,
      'плита-600': 1,
      'духовка-600': 1,
      'микроволновка-500': 1,
      'посудомойка-600': 1,
      'стиральная-машина-600': 1,
      'вытяжка-купольная-600': 1,
      'вытяжка-встроенная-600': 1,
    };
    for (const [id, n] of Object.entries(ожидание)) {
      const д = дв(id);
      expect(д.length, id).toBe(n);
      for (const x of д) {
        expect(x.вид).toBe('техника');
        const закрыта = позаДвижения(x, 0);
        expect(закрыта.R, `${id} закрыта`).toBeUndefined();
        expect(закрыта.сдвиг).toEqual([0, 0, 0]);
        const открыта = позаДвижения(x, 1);
        const двигается = !!открыта.R || открыта.сдвиг.some((v) => Math.abs(v) > 1);
        expect(двигается, `${id}/${x.группа}`).toBe(true);
      }
    }
  });

  it('варочная панель и мойка ничего не открывают', () => {
    for (const id of ['варочная-панель-580', 'мойка-накладная-800', 'мойка-врезная-780']) expect(дв(id), id).toEqual([]);
  });

  it('широкий холодильник: две двери, каждая наружу в свою сторону', () => {
    const э = экз('холодильник-600', { габариты: { ш: 900, г: 650, в: 1850 } });
    const д = движенияИзделия(изделиеПоИд('холодильник-600')!, э);
    expect(д.length).toBe(2);
    const [л, п] = д.map((x) => (x.кинематика.вид === 'поворот' ? x.кинематика : null));
    expect(л!.опора[0]).toBeLessThan(0);
    expect(п!.опора[0]).toBeGreaterThan(0);
    // свободный край уходит вперёд (+Z) у обеих дверей
    for (const x of д) {
      const k = x.кинематика;
      if (k.вид !== 'поворот') throw new Error('поворот');
      const R = матрицаПоворота(k.ось, k.угол);
      const край = [x.главная.центр[0] - k.опора[0], 0, x.главная.центр[2] - k.опора[2]];
      expect(применить(R, край)[2], x.группа).toBeGreaterThan(край[2] + 100);
    }
  });

  it('невысокий холодильник — одна дверь', () => {
    const э = экз('холодильник-600', { габариты: { ш: 600, г: 650, в: 850 } });
    expect(движенияИзделия(изделиеПоИд('холодильник-600')!, э).length).toBe(1);
  });

  it('духовка и посудомойка открываются вниз-вперёд вокруг нижней кромки', () => {
    for (const id of ['духовка-600', 'плита-600', 'посудомойка-600']) {
      const [x] = дв(id);
      const k = x.кинематика;
      if (k.вид !== 'поворот') throw new Error('поворот');
      expect(k.опора[1], id).toBeLessThan(x.главная.центр[1]);
      const центрПосле = применить(матрицаПоворота(k.ось, k.угол), [0, x.главная.центр[1] - k.опора[1], 0]);
      expect(центрПосле[2], id).toBeGreaterThan(x.главная.объём[1] / 2 - 2);
      expect(Math.abs(центрПосле[1]), id).toBeLessThan(2);
    }
  });

  it('каждый корпус каталога с фасадом открывает ровно свои группы, помеченные в детали()', () => {
    for (const изд of КАТАЛОГ_V2.filter((и) => и.тип === 'корпус')) {
      const э = новыйЭкземпляр(изд, 'п1');
      const д = движенияИзделия(изд, э);
      const имена = new Set(д.map((x) => x.группа));
      expect(имена.size, изд.id).toBe(д.length);
      for (const x of д) {
        for (const v of [...x.главная.центр, ...x.главная.объём]) expect(Number.isFinite(v), `${изд.id}/${x.группа}`).toBe(true);
        const закрыто = позаДвижения(x, 0);
        expect(закрыто.сдвиг).toEqual([0, 0, 0]);
      }
    }
  });
});

describe('открывание: распашные, ящики, купе, подъёмник', () => {
  const найти = (предикат: (и: (typeof КАТАЛОГ_V2)[number]) => boolean) => КАТАЛОГ_V2.find(предикат)!;

  it('петли слева, справа и попарно: свободный край идёт вперёд', () => {
    const изд = изделиеПоИд('навесной-600')!;
    for (const петли of ['слева', 'справа', 'попарно'] as const) {
      const э = { ...новыйЭкземпляр(изд, 'п1'), габариты: { ш: 800, г: 320, в: 720 }, раскладка: { фасад: { петли, тип: 'распашной' as const, створок: 2 } } };
      const д = движенияИзделия(изд, э);
      expect(д.length, петли).toBe(2);
      for (const [i, x] of д.entries()) {
        const k = x.кинематика;
        if (k.вид !== 'поворот') throw new Error('поворот');
        // петля слева: опора на левом краю двери (центр.x − w/2), справа — на правом
        const w = x.главная.объём[0];
        const сторона = петли === 'попарно' ? (i % 2 === 0 ? 'слева' : 'справа') : петли;
        expect(около(k.опора[0], x.главная.центр[0] + (сторона === 'слева' ? -w / 2 : w / 2)), `${петли} ${x.группа}`).toBe(true);
        const край = [x.главная.центр[0] - k.опора[0], 0, 0];
        expect(применить(матрицаПоворота(k.ось, k.угол), край)[2], `${петли} ${x.группа}`).toBeGreaterThan(w / 2 - 2);
      }
    }
  });

  it('ящики выдвигаются на 80% глубины вперёд', () => {
    const изд = изделиеПоИд('тумба-ящики-600')!;
    const д = движенияИзделия(изд, новыйЭкземпляр(изд, 'п1'));
    expect(д.length).toBeGreaterThan(1);
    for (const x of д) {
      expect(x.вид).toBe('ящик');
      const k = x.кинематика;
      if (k.вид !== 'сдвиг') throw new Error('сдвиг');
      expect(k.вектор[2]).toBeGreaterThan(200);
      expect(k.вектор[0]).toBe(0);
    }
  });

  it('купе: створки заднего ряда уезжают, клик по передней двигает соседнюю', () => {
    const изд = найти((и) => и.раскладка.фасад.тип === 'купе' && и.тип === 'корпус');
    const э = новыйЭкземпляр(изд, 'п1');
    const д = движенияИзделия(изд, э);
    expect(д.length).toBeGreaterThanOrEqual(1);
    const группы = д.map((x) => x.группа);
    expect(группы.every((г) => /купе-\d+$/.test(г))).toBe(true);
    // клик по створке 0 открывает створку 1
    expect(группаДляКлика(д, 'купе-0')).toBe('купе-1');
    const после = переключитьГруппу(э, д, 'купе-0');
    expect(открытыеГруппы(д, после).has('купе-1')).toBe(true);
    // двинулась только та, что в заднем ряду, и вбок
    for (const x of д) {
      const k = x.кинематика;
      if (k.вид !== 'сдвиг') throw new Error('сдвиг');
      expect(k.вектор[2]).toBeCloseTo(0);
      expect(Math.abs(k.вектор[0])).toBeGreaterThan(100);
    }
  });

  it('подъёмник поднимается вокруг верхней кромки', () => {
    const изд = найти((и) => и.раскладка.фасад.тип === 'подъёмник');
    const [x] = движенияИзделия(изд, новыйЭкземпляр(изд, 'п1'));
    expect(x.вид).toBe('подъёмник');
    const k = x.кинематика;
    if (k.вид !== 'поворот') throw new Error('поворот');
    expect(k.опора[1]).toBeGreaterThan(x.главная.центр[1]);
    const низПосле = применить(матрицаПоворота(k.ось, k.угол), [0, -x.главная.объём[1], 0]);
    expect(низПосле[2]).toBeGreaterThan(x.главная.объём[1] - 4);
  });

  it('угловой шкаф: двери повёрнутого блока поворачиваются вокруг своей петли, а не вокруг оси X', () => {
    const изд = КАТАЛОГ_V2.find((и) => и.состав && и.состав.some((б) => б.поворот === 90 || б.поворот === 270) && и.раскладка.фасад.тип === 'распашной')
      ?? КАТАЛОГ_V2.find((и) => и.состав && и.состав.some((б) => б.поворот !== 0));
    expect(изд).toBeDefined();
    const э = новыйЭкземпляр(изд!, 'п1');
    const д = движенияИзделия(изд!, э);
    for (const x of д.filter((m) => m.вид === 'дверь')) {
      const k = x.кинематика;
      if (k.вид !== 'поворот') throw new Error('поворот');
      const R = матрицаПоворота(k.ось, k.угол);
      const w = Math.max(x.главная.объём[0], x.главная.объём[2]);
      const вектор = [x.главная.центр[0] - k.опора[0], 0, x.главная.центр[2] - k.опора[2]];
      const после = применить(R, вектор);
      // дверь осталась на высоте и отошла от плоскости по нормали на половину ширины
      expect(Math.abs(после[1])).toBeLessThan(1);
      const сдвигНаружу = после[0] * x.фронт[0] + после[2] * x.фронт[1];
      expect(сдвигНаружу, x.группа).toBeGreaterThan(w / 2 - 3);
    }
  });
});

