/**
 * Угловой модуль Г-формы (A1, проход 1): тумба 900 × 900 или 1000 × 1000 с каруселью 3/4.
 *
 * Оси изделия как у всех: X — ширина, Y — высота, Z — глубина, фасад в +Z, начало — центр низа.
 * Угол помещения — справа сзади (x = +ш/2, z = −г/2). Плечо «а» идёт вдоль задней стены во всю ширину,
 * плечо «б» — вдоль правой стены во всю глубину. Спереди слева — свободный угол комнаты.
 *
 * Створки: «а» на плоскости z = −г/2 + плечо (смотрит в +Z), петля у левой боковины;
 * «б» на плоскости x = ш/2 − плечо (смотрит в −X), петля у передней боковины. На 110° обе уходят
 * за свои боковины, над фасадами соседей, и не задевают соседний ряд (проверяет валидатор).
 * Карусель 3/4: диск без четверти, вырез к створкам; центр отнесён на 30 мм вглубь от стыка створок.
 */
import { повернутьТочку } from './геометрия';
import type { Вектор3, Габариты, Деталь, Изделие, Кромка, Раскладка, Экземпляр } from './типы';

type Т2 = [number, number];

/** Кромка на одной грани плиты: ось грани (0 X, 1 Y, 2 Z) и знак */
export function кромкаНаГрани(объём: Вектор3, ось: number, знак: 1 | -1, мм: number): Кромка {
  const к: Кромка = { длина1: 0, длина2: 0, ширина1: 0, ширина2: 0 };
  const индексы = [0, 1, 2].sort((a, b) => объём[b] - объём[a] || a - b);
  const [длина, ширина] = индексы;
  if (ось === ширина) к[знак > 0 ? 'длина1' : 'длина2'] = мм;
  else if (ось === длина) к[знак > 0 ? 'ширина1' : 'ширина2'] = мм;
  return к;
}

const крВся = (мм: number): Кромка => ({ длина1: мм, длина2: мм, ширина1: мм, ширина2: мм });
const кр0 = (): Кромка => ({ длина1: 0, длина2: 0, ширина1: 0, ширина2: 0 });
const ок = (v: number) => Math.round(v * 100) / 100;

function д(роль: Деталь['роль'], ц: Вектор3, о: Вектор3, материал: Деталь['материал'], кромка: Кромка, доп: Partial<Деталь> = {}): Деталь {
  const размер = [...о].sort((a, b) => b - a) as Вектор3;
  return {
    роль,
    размер: [ок(размер[0]), ок(размер[1]), ок(размер[2])],
    кромка,
    материал,
    локально: { центр: [ок(ц[0]), ок(ц[1]), ок(ц[2])], объём: [ок(о[0]), ок(о[1]), ок(о[2])] },
    форма: 'плита',
    ...доп,
  };
}

/** Плита по границам: [x0, x1] × [y0, y1] × [z0, z1] */
function плита(роль: Деталь['роль'], x0: number, x1: number, y0: number, y1: number, z0: number, z1: number, материал: Деталь['материал'], кромка: (о: Вектор3) => Кромка, доп: Partial<Деталь> = {}): Деталь {
  const о: Вектор3 = [x1 - x0, y1 - y0, z1 - z0];
  return д(роль, [(x0 + x1) / 2, (y0 + y1) / 2, (z0 + z1) / 2], о, материал, кромка(о), доп);
}

/** Размеры корпуса углового модуля из габаритов и раскладки */
export function размерыУглового(изд: Pick<Изделие, 'угловой'>, габ: Габариты, р: Раскладка) {
  const W = габ.ш;
  const G = габ.г;
  const H = габ.в;
  const D = Math.max(300, Math.min(изд.угловой?.плечо ?? 560, Math.min(W, G) - 150));
  const t = р.корпус.плита;
  const дверцы = !!изд.угловой?.дверцы && р.фасад.тип !== 'нет';
  const tф = дверцы ? t : 0;
  const Dk = D - tф;
  const tз = р.корпус.задник === 'нет' ? 0 : р.корпус.задник === 'ХДФ' ? 4 : 8;
  const запас = Math.max(0, H - 3 * t - 20);
  const цоколь = Math.min(р.корпус.цоколь, запас);
  const ножки = Math.min(р.корпус.ножки, запас);
  const низ = Math.max(цоколь, ножки);
  const y0 = цоколь > 0 ? 0 : ножки;
  const tК = р.корпус.крыша ?? t;
  const xL = -W / 2;
  const xR = W / 2;
  const zB = -G / 2;
  const zF = G / 2;
  return { W, G, H, D, t, tф, Dk, tз, цоколь, низ, y0, tК, xL, xR, zB, zF, xc: xR - Dk, zc: zB + Dk, дверцы };
}

/** Детали углового модуля в осях изделия */
export function деталиУглового(изд: Изделие, экз: Pick<Экземпляр, 'габариты'>, р: Раскладка): Деталь[] {
  const р0 = размерыУглового(изд, экз.габариты, р);
  const { H, D, t, tф, tз, цоколь, низ, y0, tК, xL, xR, zB, zF, xc, zc, дверцы } = р0;
  const итог: Деталь[] = [];
  const кр = (ось: number, знак: 1 | -1) => (о: Вектор3) => кромкаНаГрани(о, ось, знак, 0.4);

  // боковины: левая (торец плеча «а») и передняя (торец плеча «б»)
  итог.push(плита('боковина', xL, xL + t, y0, H, zB, zc, 'корпус', кр(2, 1)));
  итог.push(плита('боковина', xc, xR, y0, H, zF - t, zF, 'корпус', кр(0, -1)));
  // дно и крыша — Г из двух плит: плечо «а» во всю ширину, плечо «б» от фасада «а» до передней боковины
  for (const [роль, ya, yb] of [['дно', низ, низ + t], ['крыша', H - tК, H]] as const) {
    итог.push(плита(роль, xL + t, xR - tз, ya, yb, zB + tз, zc, 'корпус', кр(2, 1)));
    итог.push(плита(роль, xc, xR - tз, ya, yb, zc, zF - t, 'корпус', кр(0, -1)));
  }
  // задние стенки ХДФ по обеим стенам помещения
  if (tз > 0) {
    итог.push(плита('задник', xL + t, xR, низ, H, zB, zB + tз, 'задник', кр0));
    итог.push(плита('задник', xR - tз, xR, низ, H, zB + tз, zF - t, 'задник', кр0));
  }
  // цоколь: две планки на 50 мм глубже фасадов
  if (цоколь > 0) {
    итог.push(плита('цоколь', xL + t, xc + 50 + t, 0, цоколь, zc - 50 - t, zc - 50, 'корпус', кр(2, 1)));
    итог.push(плита('цоколь', xc + 50, xc + 50 + t, 0, цоколь, zc - 50, zF - t, 'корпус', кр(0, -1)));
  }

  // карусель 3/4: две полки-диска с бортиком на стойке
  const yb = низ + t;
  const yt = H - tК;
  if (изд.угловой?.карусель === 'три-четверти' && yt - yb > 120) {
    const cx = xc + 30;
    const cz = zc - 30;
    const геом = Math.min(cx - (xL + t), zF - t - cz, xR - tз - cx, cz - (zB + tз)) - 15;
    const R = Math.max(100, Math.min(геом, (Math.min(р0.W, р0.G) - 170) / 2));
    const ПОЛКА = { цвет: '#e7e4de', шер: 0.42, мет: 0 };
    const ХРОМ = { цвет: '#d9dce0', шер: 0.16, мет: 1 };
    const уровни = [yb + 25, yb + Math.round((yt - yb) * 0.52)];
    for (const y of уровни) {
      итог.push(д('фурнитура', [cx, y + 3, cz], [2 * R, 6, 2 * R], 'ручки', кр0(), { форма: 'цилиндр', ось: 'y', профиль: 'сектор270', литерал: ПОЛКА }));
      итог.push(д('фурнитура', [cx, y + 6 + 18, cz], [2 * R, 36, 2 * R], 'ручки', кр0(), { форма: 'цилиндр', ось: 'y', профиль: 'обод270', литерал: ХРОМ }));
    }
    итог.push(д('фурнитура', [cx, (yb + yt) / 2, cz], [25, yt - yb, 25], 'ручки', кр0(), { форма: 'цилиндр', ось: 'y', литерал: ХРОМ }));
  }

  // створки и ручки
  if (дверцы) {
    const yН = (низ > 0 ? низ : 0) + 1.5;
    const yВ = H - 1.5;
    const hF = yВ - yН;
    const вид = р.фасад.ручка.вид;
    const длинаРучки = вид === 'кнопка' ? 20 : Math.min(hF * 0.3, вид === 'рейлинг' ? 600 : 160);
    const высотаРучки = вид === 'кнопка' ? 20 : длинаРучки;
    const yРучки = Math.max(yН + высотаРучки / 2 + 10, yВ - высотаРучки / 2 - 80);
    const xСтыка = xR - D; // наружная плоскость створки «б»

    const а = { группа: 'плечо-а/дверь-0' };
    итог.push(плита('фасад', xL + 1.5, xСтыка - 2, yН, yВ, zc, zc + tф, 'фасад', () => крВся(2), { подвижная: а }));
    const б = { группа: 'плечо-б/дверь-0' };
    итог.push(плита('фасад', xСтыка, xc, yН, yВ, zc, zF - 1.5, 'фасад', () => крВся(2), { подвижная: б }));

    if (вид !== 'нет' && вид !== 'профиль') {
      const ш = вид === 'кнопка' ? 20 : 14;
      // «а»: у свободного края (у стыка), «б»: дальше от стыка, чтобы ручки не сходились в углу
      const xa = xСтыка - 2 - 28 - ш / 2;
      итог.push(д('ручка', [xa, yРучки, zc + tф + 5], [ш, высотаРучки, 22], 'ручки', кр0(), { подвижная: а }));
      const zб = zc + tф + 60 + ш / 2;
      итог.push(д('ручка', [xСтыка - 5, yРучки, zб], [22, высотаРучки, ш], 'ручки', кр0(), { подвижная: б }));
    }
  }
  return итог;
}

/** Следы плеч в осях изделия (прямоугольники по часовой): для препятствий и проходов */
export function следыПлеч(изд: Pick<Изделие, 'угловой'>, габ: Габариты): Т2[][] {
  const W = габ.ш;
  const G = габ.г;
  const D = Math.max(300, Math.min(изд.угловой?.плечо ?? 560, Math.min(W, G) - 150));
  const xL = -W / 2;
  const xR = W / 2;
  const zB = -G / 2;
  const zF = G / 2;
  const прям = (x0: number, x1: number, z0: number, z1: number): Т2[] => [[x0, z0], [x1, z0], [x1, z1], [x0, z1]];
  return [прям(xL, xR, zB, zB + D), прям(xR - D, xR, zB + D, zF)];
}

/** Следы плеч в осях помещения */
export function следыПлечВМире(изд: Pick<Изделие, 'угловой'>, экз: Pick<Экземпляр, 'позиция' | 'поворот' | 'габариты'>, срез = 0): Т2[][] {
  return следыПлеч(изд, экз.габариты).map((п) => {
    const [x0, z0] = п[0];
    const [x1, z1] = п[2];
    const r: Т2[] = [[x0 + срез, z0 + срез], [x1 - срез, z0 + срез], [x1 - срез, z1 - срез], [x0 + срез, z1 - срез]];
    return r.map(([x, z]) => {
      const [rx, rz] = повернутьТочку(x, z, экз.поворот);
      return [экз.позиция[0] + rx, экз.позиция[2] + rz] as Т2;
    });
  });
}

/**
 * Следы экземпляра для проверок в осях помещения: у углового — два плеча, у остальных — габарит.
 * `углы` — функция габаритного следа (из проверка.ts, чтобы не было круговых импортов).
 */
export function следыЭкземпляра(
  изд: Pick<Изделие, 'угловой'> | undefined,
  э: Pick<Экземпляр, 'позиция' | 'поворот' | 'габариты'>,
  углы: (позиция: Вектор3, поворот: number, ш: number, г: number) => Т2[],
  срез = 0,
): Т2[][] {
  if (изд?.угловой) return следыПлечВМире(изд, э, срез);
  return [углы(э.позиция, э.поворот, Math.max(1, э.габариты.ш - 2 * срез), Math.max(1, э.габариты.г - 2 * срез))];
}

/**
 * Лицевые стороны плеч в осях изделия: середина фасада и нормаль (куда смотрит).
 * Проход меряется от них, а не от габарита: габарит углового модуля включает свободный угол комнаты.
 */
export function фасадыПлеч(изд: Pick<Изделие, 'угловой'>, габ: Габариты): { середина: Т2; нормаль: Т2; ширина: number }[] {
  const W = габ.ш;
  const G = габ.г;
  const D = Math.max(300, Math.min(изд.угловой?.плечо ?? 560, Math.min(W, G) - 150));
  return [
    { середина: [(-W / 2 + W / 2 - D) / 2, -G / 2 + D], нормаль: [0, 1], ширина: W - D },
    { середина: [W / 2 - D, (-G / 2 + D + G / 2) / 2], нормаль: [-1, 0], ширина: G - D },
  ];
}
