/**
 * Вырезы в столешнице под врезную мойку (чаша мойки) и варочную панель. Столешница в деталировке остаётся одной плитой
 * (вырез делают в цеху), а в 3D плита режется на куски вокруг выреза, чтобы мойка и панель были видны «в» столешнице.
 * Чистый TS: координаты — мм в осях столешницы (X — ширина, Z — глубина, центр в нуле).
 */
import { изделиеПоИд } from './каталог';
import type { Экземпляр } from './типы';

export interface Вырез {
  x0: number;
  x1: number;
  z0: number;
  z1: number;
}

/** Насколько вырез меньше габарита вставки: борт мойки лежит на столешнице, у варочной панели — рамка */
const ОТСТУП_ВРЕЗКИ: [string, number][] = [
  ['чаша-мойки', 28],
  ['мойка-врезная', 26],
  ['варочная-', 6],
];

const рад = (г: number) => (г * Math.PI) / 180;

export const этоСтолешница = (id: string) => id.startsWith('столешница');

/** Вырезы одной столешницы по врезным изделиям того же помещения (верх вставки на уровне верха столешницы) */
export function вырезыСтолешницы(стол: Экземпляр, объекты: readonly Экземпляр[]): Вырез[] {
  const W = стол.габариты.ш;
  const D = стол.габариты.г;
  const верхСтола = стол.позиция[1] + стол.габариты.в;
  const θ = рад(стол.поворот);
  const c = Math.cos(θ);
  const s = Math.sin(θ);
  const итог: Вырез[] = [];
  for (const о of объекты) {
    if (о.id === стол.id || о.помещение !== стол.помещение) continue;
    const отступ = ОТСТУП_ВРЕЗКИ.find(([п]) => о.изделие.startsWith(п))?.[1];
    if (отступ === undefined || !изделиеПоИд(о.изделие)) continue;
    // верх вставки — на уровне верха столешницы (допуск 60 мм)
    if (Math.abs(о.позиция[1] + о.габариты.в - верхСтола) > 60) continue;
    // относительный поворот должен быть кратен 90°
    const Δ = ((((о.поворот - стол.поворот) % 360) + 360) % 360);
    const кратен = [0, 90, 180, 270, 360].some((к) => Math.abs(Δ - к) < 0.5);
    if (!кратен) continue;
    const обмен = Math.abs(Δ - 90) < 0.5 || Math.abs(Δ - 270) < 0.5;
    const w = (обмен ? о.габариты.г : о.габариты.ш) - 2 * отступ;
    const g = (обмен ? о.габариты.ш : о.габариты.г) - 2 * отступ;
    if (w < 40 || g < 40) continue;
    // центр вставки в осях столешницы: обратное вращение вокруг вертикали
    const dx = о.позиция[0] - стол.позиция[0];
    const dz = о.позиция[2] - стол.позиция[2];
    const lx = c * dx + s * dz;
    const lz = -s * dx + c * dz;
    const вырез: Вырез = { x0: Math.max(-W / 2 + 1, lx - w / 2), x1: Math.min(W / 2 - 1, lx + w / 2), z0: Math.max(-D / 2 + 1, lz - g / 2), z1: Math.min(D / 2 - 1, lz + g / 2) };
    if (вырез.x1 - вырез.x0 < 40 || вырез.z1 - вырез.z0 < 40) continue;
    // вставка должна почти целиком лежать на столешнице: иначе это не врезка, а соседство
    if ((вырез.x1 - вырез.x0) * (вырез.z1 - вырез.z0) < 0.7 * w * g) continue;
    итог.push(вырез);
  }
  итог.sort((a, b) => a.x0 - b.x0);
  // вырезы, пересекающиеся по X с предыдущим, пропускаем (режем полосами вдоль X)
  const чистые: Вырез[] = [];
  for (const в of итог) if (!чистые.length || в.x0 >= чистые[чистые.length - 1].x1 - 0.5) чистые.push(в);
  return чистые;
}

/** Плита столешницы W × D, разрезанная вокруг вырезов: прямоугольники [x0, x1, z0, z1] (мм, оси столешницы) */
export function кускиСтолешницы(W: number, D: number, вырезы: readonly Вырез[]): [number, number, number, number][] {
  if (!вырезы.length) return [[-W / 2, W / 2, -D / 2, D / 2]];
  const куски: [number, number, number, number][] = [];
  let x = -W / 2;
  const добавить = (x0: number, x1: number, z0: number, z1: number) => {
    if (x1 - x0 > 0.5 && z1 - z0 > 0.5) куски.push([x0, x1, z0, z1]);
  };
  for (const в of вырезы) {
    добавить(x, в.x0, -D / 2, D / 2);
    добавить(в.x0, в.x1, -D / 2, в.z0);
    добавить(в.x0, в.x1, в.z1, D / 2);
    x = в.x1;
  }
  добавить(x, W / 2, -D / 2, D / 2);
  return куски;
}

/** Подпись набора вырезов (чтобы пересобирать столешницу только при изменении) */
export const ключВырезов = (в: readonly Вырез[]) => в.map((x) => [x.x0, x.x1, x.z0, x.z1].map((v) => Math.round(v)).join(',')).join(';');
