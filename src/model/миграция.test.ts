import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import { собратьДемо } from '../lib/демо';
import { КАТАЛОГ as КАТАЛОГ_V1 } from '../data/modules';
import type { Project } from '../types';
import { разобратьФайл, записатьПроект } from './файл';
import { мигрироватьV1 } from './миграция';
import { вПроектV1, патчV1вЭкземпляр, вОбъектV1 } from './мост-v1';
import { детали } from './детали';
import { изделиеПоИд } from './каталог';

const КОРЕНЬ = process.cwd();

function файлы(папка: string): string[] {
  const п = join(КОРЕНЬ, папка);
  if (!existsSync(п)) return [];
  return readdirSync(п).filter((ф) => ф.endsWith('.kitchen')).map((ф) => join(п, ф));
}

const ВСЕ_ФАЙЛЫ = [
  ...файлы('public/Библиотека'),
  ...файлы('Проекты'),
  ...файлы('Бэкапы'),
];

describe('миграция v1 → v2 на реальных файлах', () => {
  it('нашлись файлы для проверки', () => {
    expect(ВСЕ_ФАЙЛЫ.length).toBeGreaterThan(0);
    expect(ВСЕ_ФАЙЛЫ.some((ф) => ф.includes('пример-проекта'))).toBe(true);
  });

  for (const файл of ВСЕ_ФАЙЛЫ) {
    it(`открывается без потерь: ${файл.replace(КОРЕНЬ, '.')}`, () => {
      const текст = readFileSync(файл, 'utf8');
      const р = разобратьФайл(текст);
      expect(р.ошибки).toEqual([]);
      expect(р.ок).toBe(true);
      expect(р.из).toBe(1);
      expect(р.отчёт!.потери).toEqual([]);
      expect(р.отчёт!.свободных).toEqual([]);
      const исходный = JSON.parse(текст) as Project;
      expect(р.проект!.объекты.length).toBe(исходный.объекты.length);
      // запись v2 → чтение v2 даёт тот же проект
      const v2 = записатьПроект(р.проект!);
      const снова = разобратьФайл(v2);
      expect(снова.ок).toBe(true);
      expect(снова.из).toBe(2);
      expect(снова.проект).toEqual(р.проект);
      expect(JSON.parse(v2).schemaVersion).toBe(2);
    });
  }

  it('пример-проекта.kitchen: числа, помещение, позиции, свободных нет', () => {
    const текст = readFileSync(join(КОРЕНЬ, 'public/Библиотека/пример-проекта.kitchen'), 'utf8');
    const исходный = JSON.parse(текст) as Project;
    const р = мигрироватьV1(исходный);
    expect(р.ок).toBe(true);
    const п = р.проект!;
    expect(п.помещения.length).toBe(1);
    expect(п.помещения[0].контур).toEqual([[-2100, -1500], [2100, -1500], [2100, 1500], [-2100, 1500]]);
    expect(п.помещения[0].высота).toBe(2700);
    expect(п.объекты.length).toBe(исходный.объекты.length);
    исходный.объекты.forEach((о, i) => {
      expect(п.объекты[i].позиция[0]).toBe(о.позиция[0]);
      expect(п.объекты[i].позиция[2]).toBe(о.позиция[2]);
      expect(п.объекты[i].габариты).toEqual(о.габариты);
      expect(п.объекты[i].поворот).toBe(о.поворот);
    });
    // из v1 в v2 в отличиях остаются только реальные отличия: у стандартной тумбы раскладки нет
    const тумба = п.объекты.find((о) => о.изделие === 'тумба-нижняя-400')!;
    expect(тумба.раскладка).toBeUndefined();
  });

  it('детали каждого перенесённого объекта строятся и лежат внутри габарита', () => {
    const текст = readFileSync(join(КОРЕНЬ, 'public/Библиотека/пример-проекта.kitchen'), 'utf8');
    const п = разобратьФайл(текст).проект!;
    for (const экз of п.объекты) {
      const изд = изделиеПоИд(экз.изделие)!;
      const д = детали(изд, экз);
      expect(д.length, экз.изделие).toBeGreaterThan(0);
    }
  });
});

describe('миграция v1 → v2 на синтетических файлах', () => {
  const демо = () => JSON.parse(JSON.stringify(собратьДемо())) as Project;

  it('демо-кухня из кода: без потерь', () => {
    const р = мигрироватьV1(демо());
    expect(р.ок).toBe(true);
    expect(р.отчёт.потери).toEqual([]);
    expect(р.отчёт.перенесено).toBe(демо().объекты.length);
  });

  it('каждый из 57 модулей v1 в одиночку переносится без потерь', () => {
    for (const м of КАТАЛОГ_V1) {
      const проект = демо();
      проект.объекты = [
        {
          id: 'x1',
          модуль: м.id,
          название: м.название,
          позиция: [100, м.крепление === 'навесное' ? (м.подъём_по_умолчанию ?? 1500) : 0, 200],
          поворот: 90,
          габариты: { ...м.габариты },
          подъём: м.крепление === 'навесное' ? (м.подъём_по_умолчанию ?? 1500) : 0,
          цвет: м.цвет,
          материал: м.материал,
          ящиков: м.ящиков ?? 0,
          полок: м.полки === 'авто' ? undefined : (м.полки ?? 0),
          цоколь: м.цоколь ?? 0,
          ножки: м.ножки ?? 0,
          вид: м.вид,
          фасад: м.фасад ?? 'нет',
        },
      ];
      const р = мигрироватьV1(проект);
      expect(р.ок, `${м.id}: ${р.ошибки.join('; ')}`).toBe(true);
      // полок «авто» в v1 хранилось числом; тестируем и числом
      expect(р.отчёт.потери.filter((x) => !x.includes('полок')), м.id).toEqual([]);
    }
  });

  it('правки v1 с нестандартными значениями сохраняются как отличия раскладки', () => {
    const проект = демо();
    const тумба = проект.объекты.find((о) => о.модуль === 'cabinet-base-400')!;
    Object.assign(тумба, { полок: 3, цоколь: 150, ножки: 20, ящиков: 2, фасад: 'push', петли: 'справа', цвет: '#112233', габариты: { ш: 500, г: 600, в: 800 }, наклон_X: 5, открыт: true });
    const р = мигрироватьV1(проект);
    expect(р.отчёт.потери).toEqual([]);
    const экз = р.проект!.объекты.find((о) => о.id === тумба.id)!;
    expect(экз.раскладка?.корпус).toEqual({ цоколь: 150, ножки: 20 });
    expect(экз.раскладка?.фасад?.тип).toBe('push');
    expect(экз.раскладка?.фасад?.петли).toBe('справа');
    expect(экз.метки).toContain('наклон:X=5');
    expect(экз.открыт).toBe(true);
    expect(экз.материалы?.фасад).toBe('#112233');
  });

  it('незнакомый модуль не пропадает: свободный корпус, метка «было:…», строка в отчёте', () => {
    const проект = демо();
    const исходноеЧисло = проект.объекты.length;
    проект.объекты.push({
      id: 'неизвестный-1',
      модуль: 'diva-123',
      название: 'Странный диван',
      позиция: [0, 0, 0],
      поворот: 0,
      габариты: { ш: 777, г: 555, в: 444 },
    });
    const р = мигрироватьV1(проект);
    expect(р.ок).toBe(true);
    expect(р.проект!.объекты.length).toBe(исходноеЧисло + 1);
    const экз = р.проект!.объекты.find((о) => о.id === 'неизвестный-1')!;
    expect(экз.изделие).toBe('свободный-корпус');
    expect(экз.метки).toContain('было:diva-123');
    expect(экз.название).toBe('Странный диван');
    expect(экз.габариты).toEqual({ ш: 777, г: 555, в: 444 });
    expect(р.отчёт.свободных).toEqual([{ id: 'неизвестный-1', было: 'diva-123' }]);
    expect(р.отчёт.заметки.join(' ')).toMatch(/свободными корпусами/);
  });

  it('лишние поля на всех уровнях сохраняются и возвращаются при записи', () => {
    const проект = демо() as Project & Record<string, unknown>;
    (проект as Record<string, unknown>).моё_поле = { важное: [1, 2, 3] };
    (проект.комната as unknown as Record<string, unknown>).окно_на_юг = true;
    (проект.объекты[0] as unknown as Record<string, unknown>).заметка_мастера = 'заказчик просил ручку «кнопка»';
    (проект.настройки as Record<string, unknown>).любимая_настройка = 7;
    const текст = JSON.stringify(проект);
    const р = разобратьФайл(текст);
    expect(р.ок).toBe(true);
    expect(р.отчёт!.лишнихПолей.length).toBe(4);
    const записано = JSON.parse(записатьПроект(р.проект!));
    expect(записано.моё_поле).toEqual({ важное: [1, 2, 3] });
    expect(записано.помещения[0].окно_на_юг).toBe(true);
    expect(записано.объекты[0].заметка_мастера).toBe('заказчик просил ручку «кнопка»');
    expect(записано.настройки_v1).toEqual({ любимая_настройка: 7 });
    // и снова читается как v2 с теми же полями
    const снова = разобратьФайл(JSON.stringify(записано));
    expect(снова.ок).toBe(true);
    expect(снова.проект!.объекты[0].прочее).toEqual({ заметка_мастера: 'заказчик просил ручку «кнопка»' });
  });

  it('форма комнаты Г из v1 не теряется молча: заметка и метка', () => {
    const проект = демо();
    проект.комната.форма = 'Г';
    const р = мигрироватьV1(проект);
    expect(р.проект!.помещения[0].метки).toEqual(['было:форма Г']);
    expect(р.отчёт.заметки.join(' ')).toMatch(/Форма комнаты «Г»/);
  });

  it('тема, шаг сетки и фон переезжают в настройки v2', () => {
    const проект = демо();
    проект.настройки = { шаг_сетки: 100, толщина_плиты: 18, режим_обзора: 'прогулка', тема: 'светлая' };
    проект.комната.фон = '#223344';
    const р = мигрироватьV1(проект);
    expect(р.проект!.настройки).toMatchObject({ шаг_сетки: 100, толщина_плиты: 18, режим_обзора: 'прогулка', тема: 'калька', фон: '#223344' });
  });
});

describe('ошибки файла говорят по-русски', () => {
  it('не JSON, не объект, нет версии, битое поле v1 и v2', () => {
    expect(разобратьФайл('{ это не json').ошибки[0]).toMatch(/Это не JSON/);
    expect(разобратьФайл('[1,2]').ошибки[0]).toMatch(/объектом JSON/);
    expect(разобратьФайл('{}').ошибки[0]).toMatch(/schemaVersion/);
    const плохойV1 = разобратьФайл(JSON.stringify({ schemaVersion: 1, название: 'X', создан: '', изменён: '', комната: { длина: 100 }, объекты: [] }));
    expect(плохойV1.ок).toBe(false);
    expect(плохойV1.ошибки.join(' ')).toMatch(/комната\.длина: длина комнаты должна быть не меньше 500 мм/);
    const плохойV2 = разобратьФайл(JSON.stringify({ schemaVersion: 2, название: 'X', создан: '', изменён: '', помещения: [], объекты: [] }));
    expect(плохойV2.ок).toBe(false);
    expect(плохойV2.ошибки.join(' ')).toMatch(/нужно хотя бы одно помещение/);
  });

  it('файл новее приложения открывается с предупреждением', () => {
    const р = мигрироватьV1(JSON.parse(readFileSync(join(КОРЕНЬ, 'public/Библиотека/пример-проекта.kitchen'), 'utf8')));
    const v2 = JSON.parse(записатьПроект(р.проект!));
    v2.schemaVersion = 3;
    const открыт = разобратьФайл(JSON.stringify(v2));
    expect(открыт.ок).toBe(true);
    expect(открыт.предупреждения.join(' ')).toMatch(/новее приложения/);
  });

  it('v2: неизвестное изделие и неизвестное помещение чинятся с предупреждением', () => {
    const р = мигрироватьV1(JSON.parse(readFileSync(join(КОРЕНЬ, 'public/Библиотека/пример-проекта.kitchen'), 'utf8')));
    const v2 = JSON.parse(записатьПроект(р.проект!));
    v2.объекты[0].изделие = 'нет-такого';
    v2.объекты[1].помещение = 'п999';
    const открыт = разобратьФайл(JSON.stringify(v2));
    expect(открыт.ок).toBe(true);
    expect(открыт.проект!.объекты[0].изделие).toBe('свободный-корпус');
    expect(открыт.проект!.объекты[0].метки).toContain('было:изделие:нет-такого');
    expect(открыт.проект!.объекты[1].помещение).toBe('п1');
    expect(открыт.предупреждения.length).toBeGreaterThanOrEqual(2);
  });
});

describe('мост v2 → v1 для старого рендера', () => {
  it('проекция проекта v1 → v2 → v1 даёт те же объекты и комнату', () => {
    const исходный = JSON.parse(readFileSync(join(КОРЕНЬ, 'public/Библиотека/пример-проекта.kitchen'), 'utf8')) as Project;
    const р = мигрироватьV1(исходный).проект!;
    const { проект: v1 } = вПроектV1(р);
    expect(v1.комната).toMatchObject({ длина: 4200, ширина: 3000, высота_стен: 2700, толщина_стен: 100, форма: 'прямоугольник' });
    expect(v1.объекты.map((о) => о.id)).toEqual(исходный.объекты.map((о) => о.id));
    expect(v1.объекты.map((о) => о.модуль)).toEqual(исходный.объекты.map((о) => о.модуль));
  });

  it('правка из панели (патч v1) переходит в экземпляр v2 и обратно без искажений', () => {
    const р = мигрироватьV1(JSON.parse(readFileSync(join(КОРЕНЬ, 'public/Библиотека/пример-проекта.kitchen'), 'utf8'))).проект!;
    const экз = р.объекты.find((о) => о.изделие === 'тумба-нижняя-400')!;
    const н = патчV1вЭкземпляр(экз, { позиция: [123, 0, -456], поворот: 90, цоколь: 150, полок: 2, цвет: '#abcdef', открыт: true, наклон_Z: 3 });
    const о = вОбъектV1(н);
    expect(о.позиция).toEqual([123, 0, -456]);
    expect(о.поворот).toBe(90);
    expect(о.цоколь).toBe(150);
    expect(о.полок).toBe(2);
    expect(о.цвет).toBe('#abcdef');
    expect(о.открыт).toBe(true);
    expect(о.наклон_Z).toBe(3);
    // исходный экземпляр не тронут
    expect(экз.раскладка).toBeUndefined();
  });

  it('смещение моста: комната не в нуле показывается вокруг нуля и возвращается обратно', () => {
    const р = мигрироватьV1(JSON.parse(readFileSync(join(КОРЕНЬ, 'public/Библиотека/пример-проекта.kitchen'), 'utf8'))).проект!;
    // сдвигаем контур так, чтобы центр габарита был в (1000, 500)
    р.помещения[0].контур = р.помещения[0].контур.map(([x, z]) => [x + 1000, z + 500] as [number, number]);
    р.объекты = р.объекты.map((о) => ({ ...о, позиция: [о.позиция[0] + 1000, о.позиция[1], о.позиция[2] + 500] as [number, number, number] }));
    const { проект: v1, смещение } = вПроектV1(р);
    expect(смещение).toEqual([1000, 500]);
    expect(v1.объекты[0].позиция).toEqual([р.объекты[0].позиция[0] - 1000, р.объекты[0].позиция[1], р.объекты[0].позиция[2] - 500]);
    const н = патчV1вЭкземпляр(р.объекты[0], { позиция: v1.объекты[0].позиция }, смещение);
    expect(н.позиция).toEqual(р.объекты[0].позиция);
  });
});

describe('отчёт о прогоне (по запросу)', () => {
  it.runIf(process.env.MIGRATION_REPORT === '1')('пишет docs/миграция-отчёт.md', () => {
    const строки: string[] = [];
    let ок = 0;
    for (const файл of ВСЕ_ФАЙЛЫ) {
      const текст = readFileSync(файл, 'utf8');
      const р = разобратьФайл(текст);
      const имя = файл.replace(КОРЕНЬ, '.').replace(/\\/g, '/');
      if (!р.ок) {
        строки.push(`| \`${имя}\` | **не открылся** | ${р.ошибки.join('; ')} |`);
        continue;
      }
      const о = р.отчёт!;
      const итог = о.потери.length ? `потери: ${о.потери.length}` : 'без потерь';
      if (!о.потери.length) ок++;
      строки.push(`| \`${имя}\` | ${итог} | объектов ${о.объектов} → ${о.перенесено}; свободных корпусов ${о.свободных.length}; лишних полей ${о.лишнихПолей.length}; заметок ${о.заметки.length}${о.потери.length ? '; ' + о.потери.slice(0, 3).join('; ') : ''} |`);
    }
    const текст = [
      '# Отчёт прогона миграции v1 → v2',
      '',
      `Прогон: ${new Date().toISOString().slice(0, 16).replace('T', ' ')}. Файлов: ${ВСЕ_ФАЙЛЫ.length}, без потерь: ${ок}.`,
      'Команда: `MIGRATION_REPORT=1 npx vitest run src/model/миграция.test.ts` (в PowerShell: `$env:MIGRATION_REPORT=1`).',
      '',
      '| Файл | Итог | Что с ним стало |',
      '|---|---|---|',
      ...строки,
      '',
    ].join('\n');
    mkdirSync(join(КОРЕНЬ, 'docs'), { recursive: true });
    writeFileSync(join(КОРЕНЬ, 'docs', 'миграция-отчёт.md'), текст, 'utf8');
    expect(ок).toBe(ВСЕ_ФАЙЛЫ.length);
  });
});
