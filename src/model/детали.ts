/**
 * детали(): изделие + раскладка + габариты → список деталей в осях изделия.
 * Одна функция кормит 3D, деталировку, кромку и смету, поэтому они сходятся по построению.
 *
 * Оси изделия: X — ширина, Y — высота от пола, Z — глубина, фасад смотрит в +Z, начало — центр низа.
 * Поворот экземпляра в `детали()` НЕ участвует: раскладка живёт в локальных осях, поэтому
 * полки не могут «перевернуться» (мировое положение даёт вМире() из геометрия.ts).
 */
