import { describe, expect, it } from 'vitest';
import { изделиеПоИд } from './каталог';
import { новыйЭкземпляр } from './проект';
import { ключВырезов, кускиСтолешницы, вырезыСтолешницы } from './вырезы';

const экз = (id: string, позиция: [number, number, number], поворот = 0) => ({ ...новыйЭкземпляр(изделиеПоИд(id)!, 'п1', позиция, id + позиция.join('_')), поворот });

describe('вырезы в столешнице под мойку и варочную панель', () => {
  const стол = экз('столешница-3000', [0, 720, 0]);

  it('чаша мойки на уровне столешницы режет вырез', () => {
    const чаша = экз('чаша-мойки-500', [-500, 558, 0]);
    const в = вырезыСтолешницы(стол, [стол, чаша]);
    expect(в).toHaveLength(1);
    expect(в[0].x1 - в[0].x0).toBeCloseTo(500 - 56, 0);
    expect(в[0].z1 - в[0].z0).toBeCloseTo(450 - 56, 0);
  });

  it('мойка и варочная панель дают два выреза, плита делится на куски без наложений и потери площади', () => {
    const чаша = экз('чаша-мойки-500', [-600, 558, 0]);
    const варочная = экз('варочная-панель-580', [700, 758 - 55, 0]);
    const в = вырезыСтолешницы(стол, [стол, чаша, варочная]);
    expect(в).toHaveLength(2);
    const куски = кускиСтолешницы(3000, 600, в);
    const площадь = куски.reduce((a, [x0, x1, z0, z1]) => a + (x1 - x0) * (z1 - z0), 0);
    const вырезано = в.reduce((a, x) => a + (x.x1 - x.x0) * (x.z1 - x.z0), 0);
    expect(площадь).toBeCloseTo(3000 * 600 - вырезано, 0);
  });

  it('предмет не на уровне столешницы и накладная мойка вырез не режут', () => {
    expect(вырезыСтолешницы(стол, [стол, экз('чаша-мойки-500', [0, 100, 0])])).toHaveLength(0);
    expect(вырезыСтолешницы(стол, [стол, экз('мойка-накладная-800', [0, 758, 0])])).toHaveLength(0);
  });

  it('поворот стола и мойки учитывается; повёрнутая на 45° не режет', () => {
    const стол90 = экз('столешница-3000', [0, 720, 0], 90);
    // мойка стоит в мировых осях на (0, −500): в осях стола, повёрнутого на 90°, это сдвиг по X
    const чаша = экз('чаша-мойки-500', [0, 558, -500], 90);
    const в = вырезыСтолешницы(стол90, [стол90, чаша]);
    expect(в).toHaveLength(1);
    expect(Math.abs((в[0].x0 + в[0].x1) / 2)).toBeCloseTo(500, 0);
    expect(вырезыСтолешницы(стол, [стол, экз('чаша-мойки-500', [0, 558, 0], 45)])).toHaveLength(0);
  });

  it('ключ вырезов стабилен', () => {
    expect(ключВырезов([{ x0: 0.4, x1: 10.2, z0: -5, z1: 5 }])).toBe('0,10,-5,5');
  });
});
