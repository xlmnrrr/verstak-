import { describe, expect, it } from 'vitest';
import { контурГ, контурП, новоеПомещение, отметкаВПлане, площадьМ2, прямоугольник, проверитьПомещение, самопересечение, стены, точкаВнутри } from './помещение';

describe('контуры помещений', () => {
  it('прямоугольник, Г и П: число вершин и площадь', () => {
    expect(прямоугольник(4200, 3000).length).toBe(4);
    expect(площадьМ2(прямоугольник(4200, 3000))).toBeCloseTo(12.6);
    const г = контурГ(4000, 3000, 1500, 1000);
    expect(г.length).toBe(6);
    expect(площадьМ2(г)).toBeCloseTo(12 - 1.5);
    const п = контурП(5000, 3000, 2000, 1000);
    expect(п.length).toBe(8);
    expect(площадьМ2(п)).toBeCloseTo(15 - 2);
  });

  it('нормали стен смотрят внутрь', () => {
    for (const к of [прямоугольник(4000, 3000), контурГ(4000, 3000, 1500, 1000), контурП(5000, 3000, 2000, 1000)]) {
      for (const с of стены(к)) {
        const середина = [(с.а[0] + с.б[0]) / 2, (с.а[1] + с.б[1]) / 2];
        const внутри = точкаВнутри(к, середина[0] + с.нормаль[0] * 10, середина[1] + с.нормаль[1] * 10);
        expect(внутри, `стена ${с.индекс}`).toBe(true);
      }
    }
  });

  it('самопересечение находится, обычные контуры чисты', () => {
    expect(самопересечение(прямоугольник(1000, 1000))).toBe(false);
    expect(самопересечение(контурГ(4000, 3000, 1500, 1000))).toBe(false);
    expect(самопересечение([[0, 0], [1000, 1000], [1000, 0], [0, 1000]])).toBe(true);
  });

  it('отметка на стене: положение и проверка выхода за стену', () => {
    const п = новоеПомещение('п1', 'кухня', 'Кухня', прямоугольник(4000, 3000, false));
    п.отметки.push({ id: 'о1', стена: 0, вид: 'дверь', от_угла: 500, от_пола: 0, ширина: 900, высота: 2050 });
    const м = отметкаВПлане(п, п.отметки[0])!;
    expect(м.центр[0]).toBe(950);
    expect(м.центр[2]).toBe(0);
    expect(проверитьПомещение(п)).toEqual([]);
    п.отметки.push({ id: 'о2', стена: 1, вид: 'окно', от_угла: 2800, от_пола: 900, ширина: 1400, высота: 1400 });
    expect(проверитьПомещение(п).join(' ')).toMatch(/выходит за стену 1/);
  });
});

describe('помещения заказчика (замеры листов 09–16)', async () => {
  const { помещенияЗаказчика, спорныеОтметки } = await import('./каталог/помещения-заказчика');

  it('пять помещений проходят проверку: контуры по часовой, отметки на стенах не выходят за стены', () => {
    const п = помещенияЗаказчика();
    expect(п.length).toBe(5);
    for (const x of п) expect(проверитьПомещение(x), x.название).toEqual([]);
  });

  it('решения Макара от 11.11 внесены и помечены «уточнить»', () => {
    const п = помещенияЗаказчика();
    const спальня = п.find((x) => x.id === 'кв281-спальня')!;
    expect(спальня.высота).toBe(2700);
    expect(спальня.метки).toContain('спорно:высота');
    const ванная = п.find((x) => x.id === 'кв281-ванная')!;
    expect(ванная.высота).toBe(2700);
    expect(ванная.метки).toContain('спорно:высота');
    const купе = п.find((x) => x.id === 'кв160-купе')!;
    const технический = купе.отметки.find((о) => о.метки?.includes('технический'))!;
    expect(технический.метки).toContain('запретная-зона');
    expect(названиеСтены(технический.стена)).toBe('левая');
    const короб = купе.отметки.find((о) => о.метки?.includes('без-дверки'))!;
    expect([короб.ширина, короб.высота, короб.от_пола]).toEqual([507, 608, 990]);
    const прихожая = п.find((x) => x.id === 'кв281-прихожая')!;
    const препятствие = прихожая.отметки.find((о) => о.метки?.includes('препятствие'))!;
    expect([препятствие.ширина, препятствие.высота, препятствие.от_угла]).toEqual([510, 820, 100]);
    expect(спорныеОтметки(п).length).toBeGreaterThanOrEqual(10);
  });
});

function названиеСтены(i: number) {
  return ['задняя', 'правая', 'передняя', 'левая'][i];
}

