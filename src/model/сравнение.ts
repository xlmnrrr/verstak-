/**
 * Сравнение двух проектов (этап 7): список отличий с числами — метры столешницы, листы, детали, кромка,
 * замечания валидатора; какие предметы добавлены, убраны, изменены; что стало лучше и что хуже.
 * «А» — было (до), «Б» — стало (после). Чистая логика, мм.
 */
import { изделиеПоИд } from './каталог';
import { проверитьПроект, сводка, type Замечание } from './валидатор';
import { смета } from './смета';
import type { ПроектV2, Экземпляр } from './типы';

export interface СтрокаЧисел {
  что: string;
  ед: string;
  а: number;
  б: number;
  /** б − а */
  разница: number;
  /** какое направление лучше: меньше (листы, замечания) или больше (столешница) */
  лучше: 'меньше' | 'больше' | 'нейтрально';
  /** итог для этой строки: 'а', 'б' или null (поровну / нейтрально) */
  победитель: 'а' | 'б' | null;
}

export interface Сравнение {
  а: string;
  б: string;
  числа: СтрокаЧисел[];
  добавлено: string[];
  убрано: string[];
  изменено: string[];
  /** замечания, которые ушли в Б и появились в Б */
  ушлиЗамечания: string[];
  новыеЗамечания: string[];
  лучше: string[];
  хуже: string[];
}

const имя = (э: Экземпляр) => э.название ?? изделиеПоИд(э.изделие)?.название ?? э.изделие;
const ч1 = (v: number) => Math.round(v * 10) / 10;
const ф = (v: number) => String(ч1(v)).replace('.', ',');
const знак = (v: number) => (v > 0 ? `+${ф(v)}` : ф(v));

function показатели(п: ПроектV2, помещение?: string) {
  const с = смета(п, помещение);
  const з = проверитьПроект(п).filter((x) => !помещение || x.помещение === помещение);
  const св = сводка(з);
  const объекты = п.объекты.filter((э) => !помещение || э.помещение === помещение);
  const столешница = объекты.filter((э) => изделиеПоИд(э.изделие)?.тип === 'столешница' && !э.изделие.startsWith('подоконник')).reduce((s, э) => s + э.габариты.ш, 0);
  // фронт хранения: сумма ширин корпусов (сколько метров шкафов и тумб вдоль стен)
  const корпуса = объекты.filter((э) => изделиеПоИд(э.изделие)?.тип === 'корпус').reduce((s, э) => s + э.габариты.ш, 0);
  return { с, з, св, столешница, корпуса, объекты };
}

/** Пары предметов А ↔ Б: сначала по id, потом по изделию и ближайшему месту (до 1,5 м) */
function пары(а: Экземпляр[], б: Экземпляр[]) {
  const пары: [Экземпляр, Экземпляр][] = [];
  const свободныеБ = new Map(б.map((э) => [э.id, э]));
  const безПары: Экземпляр[] = [];
  for (const э of а) {
    const т = свободныеБ.get(э.id);
    if (т && т.изделие === э.изделие) {
      пары.push([э, т]);
      свободныеБ.delete(э.id);
    } else безПары.push(э);
  }
  const остатокА: Экземпляр[] = [];
  for (const э of безПары) {
    let лучший: Экземпляр | null = null;
    let д = 1500;
    for (const т of свободныеБ.values()) {
      if (т.изделие !== э.изделие) continue;
      const r = Math.hypot(т.позиция[0] - э.позиция[0], т.позиция[2] - э.позиция[2]);
      if (r < д) {
        д = r;
        лучший = т;
      }
    }
    if (лучший) {
      пары.push([э, лучший]);
      свободныеБ.delete(лучший.id);
    } else остатокА.push(э);
  }
  return { пары, убрано: остатокА, добавлено: [...свободныеБ.values()] };
}

function отличияПары(a: Экземпляр, b: Экземпляр): string | null {
  const ч: string[] = [];
  for (const [к, слово] of [['ш', 'ширина'], ['г', 'глубина'], ['в', 'высота']] as const) {
    if (Math.abs(a.габариты[к] - b.габариты[к]) >= 1) ч.push(`${слово} ${a.габариты[к]} → ${b.габариты[к]} (${знак(b.габариты[к] - a.габариты[к])})`);
  }
  const сдвиг = Math.hypot(b.позиция[0] - a.позиция[0], b.позиция[2] - a.позиция[2]);
  if (сдвиг >= 10) ч.push(`сдвинут на ${Math.round(сдвиг)} мм`);
  if (Math.abs(b.позиция[1] - a.позиция[1]) >= 10) ч.push(`низ ${a.позиция[1]} → ${b.позиция[1]}`);
  if (Math.abs(((b.поворот - a.поворот) % 360 + 360) % 360) >= 1) ч.push(`поворот ${a.поворот}° → ${b.поворот}°`);
  if (JSON.stringify(a.материалы ?? {}) !== JSON.stringify(b.материалы ?? {})) ч.push('материалы');
  if (JSON.stringify(a.раскладка ?? {}) !== JSON.stringify(b.раскладка ?? {})) ч.push('наполнение или фасад');
  return ч.length ? `${имя(b)}: ${ч.join(', ')}` : null;
}

/** Помещение для сравнения: с тем же id, иначе первое */
const помещениеВ = (п: ПроектV2, id?: string) => (id && п.помещения.some((x) => x.id === id) ? id : п.помещения[0]?.id);

export function сравнитьПроекты(а: ПроектV2, б: ПроектV2, помещение?: string): Сравнение {
  const помА = помещениеВ(а, помещение);
  const помБ = помещениеВ(б, помещение ?? помА);
  const А = показатели(а, помА);
  const Б = показатели(б, помБ);
  const строка = (что: string, ед: string, va: number, vb: number, лучше: СтрокаЧисел['лучше']): СтрокаЧисел => {
    const разница = ч1(vb - va);
    const победитель = лучше === 'нейтрально' || Math.abs(разница) < 0.05 ? null : (лучше === 'меньше') === разница < 0 ? 'б' : 'а';
    return { что, ед, а: ч1(va), б: ч1(vb), разница, лучше, победитель };
  };
  const числа: СтрокаЧисел[] = [
    строка('Изделий', 'шт', А.с.изделий, Б.с.изделий, 'нейтрально'),
    строка('Фронт шкафов и тумб', 'м', А.корпуса / 1000, Б.корпуса / 1000, 'больше'),
    строка('Столешница', 'м', А.столешница / 1000, Б.столешница / 1000, 'больше'),
    строка('Листов ЛДСП', 'лист', А.с.листов, Б.с.листов, 'меньше'),
    строка('Кромка', 'м', А.с.кромкаМ, Б.с.кромкаМ, 'меньше'),
    строка('Деталей', 'шт', А.с.деталей, Б.с.деталей, 'меньше'),
    строка('ХДФ', 'м²', А.с.хдфМ2, Б.с.хдфМ2, 'меньше'),
    строка('Ошибок', 'шт', А.св.ошибка, Б.св.ошибка, 'меньше'),
    строка('Предупреждений', 'шт', А.св.предупреждение, Б.св.предупреждение, 'меньше'),
    строка('Советов', 'шт', А.св.совет, Б.св.совет, 'меньше'),
  ];
  const { пары: пп, убрано, добавлено } = пары(А.объекты, Б.объекты);
  const изменено = пп.map(([x, y]) => отличияПары(x, y)).filter((x): x is string => !!x);
  const текст = (з: Замечание) => з.текст;
  const textsА = new Set(А.з.map(текст));
  const textsБ = new Set(Б.з.map(текст));
  const ушли = [...textsА].filter((т) => !textsБ.has(т));
  const новые = [...textsБ].filter((т) => !textsА.has(т));

  const лучше: string[] = [];
  const хуже: string[] = [];
  const подпись = (с: СтрокаЧисел) => `${с.что}: ${ф(с.а)} → ${ф(с.б)} ${с.ед} (${знак(с.разница)})`;
  for (const с of числа) {
    if (!с.победитель) continue;
    const почему = с.что === 'Листов ЛДСП' || с.что === 'Кромка' || с.что === 'Деталей' || с.что === 'ХДФ' ? (с.победитель === 'б' ? ' — дешевле и быстрее в цеху' : ' — дороже и дольше в цеху') : с.что === 'Столешница' ? (с.победитель === 'б' ? ' — больше рабочей поверхности' : ' — меньше рабочей поверхности') : с.что === 'Фронт шкафов и тумб' ? (с.победитель === 'б' ? ' — больше места хранения' : ' — меньше места хранения') : '';
    (с.победитель === 'б' ? лучше : хуже).push(`${подпись(с)}${почему}`);
  }
  for (const т of ушли) лучше.push(`Ушло замечание: ${т}`);
  for (const т of новые) хуже.push(`Появилось замечание: ${т}`);

  const подписьПредмета = (э: Экземпляр) => {
    const габ = `${э.габариты.ш}×${э.габариты.г}×${э.габариты.в}`;
    return имя(э).includes(габ) ? имя(э) : `${имя(э)}, ${габ}`;
  };
  return {
    а: а.название,
    б: б.название,
    числа,
    добавлено: добавлено.map(подписьПредмета),
    убрано: убрано.map(подписьПредмета),
    изменено,
    ушлиЗамечания: ушли,
    новыеЗамечания: новые,
    лучше,
    хуже,
  };
}

/** Сравнение текстом (Markdown) */
export function сравнениеТекстом(с: Сравнение): string {
  const стр = [`# Сравнение: «${с.а}» → «${с.б}»`, '', '| Что | Было (А) | Стало (Б) | Разница |', '|---|---:|---:|---:|'];
  for (const x of с.числа) стр.push(`| ${x.что}, ${x.ед} | ${ф(x.а)} | ${ф(x.б)} | ${x.разница ? знак(x.разница) : '0'} |`);
  const список = (заголовок: string, xs: string[]) => {
    стр.push('', `## ${заголовок} (${xs.length})`);
    if (!xs.length) стр.push('', 'Нет.');
    else стр.push('', ...xs.map((x) => `- ${x}`));
  };
  список('Лучше в Б', с.лучше);
  список('Хуже в Б', с.хуже);
  список('Добавлено', с.добавлено);
  список('Убрано', с.убрано);
  список('Изменено', с.изменено);
  return стр.join('\n') + '\n';
}
