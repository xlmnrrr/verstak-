/**
 * A2: нормы проходов по типу помещения — кухня 900, гардеробная и кладовая 700 (перед открытыми полками 600),
 * прихожая и коридор 800. Валидатор, разбор и «Предложи планировку» берут одну и ту же норму.
 */
import { describe, expect, it } from 'vitest';
import { изделиеПоИд } from './каталог';
import { помещенияЗаказчика } from './каталог/помещения-заказчика';
import { новоеПомещение, прямоугольник } from './помещение';
import { новыйПроектV2, новыйЭкземпляр } from './проект';
import { НОРМЫ, нормаПрохода, проверитьПроект } from './валидатор';
import { разобратьПроект } from './разбор';
import { предложитьПланировки } from './планировщик';
import { детали } from './детали';
import type { ПроектV2, ТипПомещения } from './типы';

describe('нормы проходов по типу помещения', () => {
  it('таблица: кухня 900, гардеробная и кладовая 700 / 600 перед открытыми, прихожая и коридор 800, остальные 900', () => {
    const ож: [ТипПомещения, boolean, number][] = [
      ['кухня', false, 900], ['кухня', true, 900],
      ['гардеробная', false, 700], ['гардеробная', true, 600],
      ['кладовая', false, 700], ['кладовая', true, 600],
      ['прихожая', false, 800], ['прихожая', true, 800],
      ['коридор', false, 800], ['спальня', false, 900],
    ];
    for (const [тип, откр, мм] of ож) expect(нормаПрохода(тип, откр), `${тип} ${откр}`).toBe(мм);
    expect(НОРМЫ.проход).toBe(900);
  });

  /** Помещение 2000 × D: шкаф у задней стены глубиной г, проход до передней стены D − г */
  function комната(тип: ТипПомещения, D: number, изделие: string, г: number): ПроектV2 {
    const п = новыйПроектV2('т', новоеПомещение('п1', тип, 'П', прямоугольник(2000, D)));
    const изд = изделиеПоИд(изделие)!;
    п.объекты.push({ ...новыйЭкземпляр(изд, 'п1'), id: 'ш', позиция: [0, 0, -D / 2 + г / 2], поворот: 0, габариты: { ш: 1800, г, в: 2200 } });
    return п;
  }
  const проходы = (п: ПроектV2) => проверитьПроект(п).filter((з) => з.правило === 'проход');

  it('гардеробная: перед купе 650 мм — мало (норма 700), перед открытой системой 650 — хватает (норма 600)', () => {
    const купе = проходы(комната('гардеробная', 1250, 'шкаф-купе-1800', 600));
    expect(купе).toHaveLength(1);
    expect(купе[0].мм).toBe(50);
    expect(купе[0].текст).toMatch(/нужно не меньше 700 мм \(гардеробная\)/);
    expect(проходы(комната('гардеробная', 1250, 'гардеробная-система-1800', 600))).toEqual([]);
    expect(проходы(комната('гардеробная', 1150, 'гардеробная-система-1800', 600))[0]?.мм).toBe(50);
  });

  it('кладовая — как гардеробная; прихожая — 800; спальня проход не проверяет (там место у кровати)', () => {
    expect(проходы(комната('кладовая', 1290, 'шкаф-купе-1800', 600))[0]?.мм).toBe(10);
    expect(проходы(комната('прихожая', 1350, 'шкаф-купе-1800', 600))[0]?.мм).toBe(50);
    expect(проходы(комната('прихожая', 1400, 'шкаф-купе-1800', 600))).toEqual([]);
    expect(проходы(комната('спальня', 1000, 'шкаф-купе-1800', 600))).toEqual([]);
  });

  it('разбор называет норму помещения: «останется 700 мм» в гардеробной', () => {
    const р = разобратьПроект(комната('гардеробная', 1250, 'шкаф-купе-1800', 600));
    const пункт = р.пункты.find((x) => x.заголовок === 'Узкий проход')!;
    expect(пункт.предлагаю).toMatch(/останется 700 мм/);
    expect(пункт.почему).toMatch(/гардеробная/);
  });

  it('гардеробная кв. 160: глубина 600, продольная штанга внутри корпуса, три варианта без замечаний', () => {
    const р = предложитьПланировки(новыйПроектV2('Гардеробная', помещенияЗаказчика()[1]));
    expect(р.варианты.map((в) => в.тип)).toEqual(['линейная', 'угловая', 'П-образная']);
    for (const в of р.варианты) {
      expect(в.чисто, в.замечания.map((з) => з.текст).join(' | ')).toBe(true);
      const хранение = в.проект.объекты.filter((о) => о.помещение === в.помещение && о.габариты.в > 1500);
      expect(хранение.length).toBeGreaterThan(0);
      for (const о of хранение) expect(о.габариты.г, о.изделие).toBe(600);
      // штанга есть и лежит внутри корпуса по глубине
      const сШтангой = хранение.filter((о) => о.раскладка?.секции?.some((с) => с.наполнение.штанга));
      expect(сШтангой.length, в.тип).toBeGreaterThan(0);
      for (const о of сШтангой) {
        const штанги = детали(изделиеПоИд(о.изделие)!, о).filter((д) => д.роль === 'штанга');
        expect(штанги.length).toBeGreaterThan(0);
        for (const ш of штанги) {
          expect(Math.abs(ш.локально.центр[2]) + 12.5).toBeLessThanOrEqual(о.габариты.г / 2);
          expect(ш.локально.объём[0]).toBeGreaterThan(300);
        }
      }
      expect(в.учтено.some((т) => т.includes('штанга не встаёт'))).toBe(false);
    }
    expect(р.варианты[0].учтено.some((т) => /норма 700 мм — гардеробная/.test(т))).toBe(true);
  });
});
