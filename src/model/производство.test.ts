import { describe, expect, it } from 'vitest';
import { КАТАЛОГ_V2 } from './каталог';
import { новыйПроектV2, новыйЭкземпляр } from './проект';
import { смета } from './смета';
import { деталировка, деталиЭкземпляра, расход, спецификация } from './производство';
import { примитивыЭкземпляра } from '../render/примитивы';

const ключРазмера = (a: number[]) => [...a].map((v) => Math.round(v)).sort((x, y) => y - x).join('x');

describe('деталировка сходится с 3D', () => {
  it('для каждого корпусного изделия каталога плиты деталировки = плиты в 3D (без ручек, стекла и зеркал)', () => {
    let проверено = 0;
    for (const изд of КАТАЛОГ_V2.filter((и) => ['корпус', 'стол', 'стул', 'мягкая', 'столешница'].includes(и.тип))) {
      const э = новыйЭкземпляр(изд, 'п1');
      const из = деталиЭкземпляра(э).map((с) => ключРазмера([с.длина, с.ширина, с.толщина])).sort();
      const в3d = примитивыЭкземпляра(изд, э)
        .примитивы.filter((п) => п.форма === 'плита' && п.мат !== 'ручки' && п.мат !== 'зеркало')
        .map((п) => ключРазмера(п.размер))
        .sort();
      // в 3D сидения и спинки мягкой мебели и ножки — тоже плиты; в деталировке они есть по ролям
      expect(из.length, изд.id).toBeGreaterThan(0);
      expect(из, изд.id).toEqual(в3d);
      проверено++;
    }
    expect(проверено).toBeGreaterThan(40);
  });
});

describe('выгрузка не режет листы и не теряет детали', () => {
  const п = новыйПроектV2('т');
  const тумба = КАТАЛОГ_V2.find((и) => и.id === 'тумба-ящики-600')!;
  for (let i = 0; i < 3; i++) п.объекты.push({ ...новыйЭкземпляр(тумба, 'п1'), id: `т${i}` });

  it('спецификация объединяет одинаковые изделия', () => {
    const с = спецификация(п);
    expect(с).toHaveLength(1);
    expect(с[0].количество).toBe(3);
  });

  it('число деталей в деталировке равно сумме по экземплярам; расход листов согласован со сметой', () => {
    const строки = деталировка(п);
    const всего = строки.reduce((s, r) => s + r.количество, 0);
    expect(всего).toBe(п.объекты.reduce((s, э) => s + деталиЭкземпляра(э).length, 0));
    const р = расход(строки);
    const см = смета(п);
    expect(р.плитМ2).toBeCloseTo(см.плитМ2, 2);
    expect(Object.values(р.листов).reduce((a, b) => a + b, 0)).toBeCloseTo(см.листов, 2);
    expect(р.кромкаВсегоМ).toBeCloseTo(см.кромкаМ, 1);
    expect(р.хдфМ2).toBeCloseTo(см.хдфМ2, 2);
  });

  it('ни одна деталь не превышает размер листа 2750 × 1830 (иначе не раскроить)', () => {
    for (const r of деталировка(п)) expect(Math.max(r.длина, r.ширина)).toBeLessThanOrEqual(2750);
  });
});
