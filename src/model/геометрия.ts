/** Геометрия без three.js: положение деталей в мире, площади, углы. Все числа — мм. */
import type { Вектор3, Положение } from './типы';

export const окр = (v: number) => Math.round(v);
export const зажать = (v: number, мин: number, макс: number) => Math.min(макс, Math.max(мин, v));
export const радианы = (г: number) => (г * Math.PI) / 180;

/** Привязка к шагу (перестановка полок — 32 мм) */
export const кШагу = (v: number, шаг: number) => Math.round(v / шаг) * шаг;

/** Одинаковые ли числа с допуском (мм) */
export const равны = (a: number, b: number, допуск = 0.5) => Math.abs(a - b) <= допуск;

/**
 * Повернуть точку локальных осей изделия вокруг вертикали.
 * Положительный угол — по часовой стрелке при взгляде сверху:
 * при 90° локальная ось +Z (фасад) смотрит в −X.
 */
export function повернутьТочку(x: number, z: number, угол: number): [number, number] {
  const р = радианы(угол);
  const c = Math.cos(р);
  const s = Math.sin(р);
  return [x * c - z * s, x * s + z * c];
}

export interface ПоложениеВМире {
  центр: Вектор3;
  /** размеры по осям детали (не по осям мира) */
  объём: Вектор3;
  /** поворот вокруг вертикали, градусы */
  угол: number;
  /** описывающий параллелепипед в осях мира: размеры по X, Y, Z */
  габарит: Вектор3;
}

/** Положение детали в осях помещения: сдвиг к позиции экземпляра + поворот */
export function вМире(п: Положение, позиция: Вектор3, поворот: number): ПоложениеВМире {
  const [x, y, z] = п.центр;
  const [rx, rz] = повернутьТочку(x, z, поворот);
  const р = радианы(поворот);
  const ac = Math.abs(Math.cos(р));
  const as = Math.abs(Math.sin(р));
  const [dx, dy, dz] = п.объём;
  return {
    центр: [позиция[0] + rx, позиция[1] + y, позиция[2] + rz],
    объём: [dx, dy, dz],
    угол: поворот,
    габарит: [dx * ac + dz * as, dy, dx * as + dz * ac],
  };
}

export const площадьПлиты = (размер: Вектор3) => размер[0] * размер[1];

/** Пересекаются ли два параллелепипеда (по внутренности, с допуском мм) */
export function пересекаются(a: Положение, b: Положение, допуск = 0.5): boolean {
  for (let i = 0; i < 3; i++) {
    const перекрытие = (a.объём[i] + b.объём[i]) / 2 - Math.abs(a.центр[i] - b.центр[i]);
    if (перекрытие <= допуск) return false;
  }
  return true;
}
