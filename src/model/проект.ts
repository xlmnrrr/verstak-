import type { Габариты, Изделие, Настройки, Помещение, ПроектV2, Экземпляр, Вектор3 } from './типы';

let счётчик = 0;
export const новыйИд = (префикс = 'о') => `${префикс}-${Date.now().toString(36)}-${(счётчик++).toString(36)}`;

export const настройкиПоУмолчанию = (): Настройки => ({
  тема: 'система',
  фон: '#171a1f',
  шаг_сетки: 50,
  толщина_плиты: 16,
  качество: 'авто',
  режим_обзора: 'сверху',
});

export function новыйПроектV2(название: string, помещение?: Помещение): ПроектV2 {
  const сейчас = new Date().toISOString();
  return {
    schemaVersion: 2,
    название,
    создан: сейчас,
    изменён: сейчас,
    помещения: [помещение ?? новоеПомещение('п1', 'кухня', 'Кухня', прямоугольник(3600, 2800))],
    связи: [],
    объекты: [],
    настройки: настройкиПоУмолчанию(),
  };
}

export const копияПроекта = (п: ПроектV2): ПроектV2 => JSON.parse(JSON.stringify(п));

/** Помещение проекта по id (первое, если id не найден) */
export const помещениеПоИд = (п: ПроектV2, id?: string): Помещение | undefined =>
  п.помещения.find((x) => x.id === id) ?? п.помещения[0];

export interface РезультатОграничения {
  габариты: Габариты;
  /** что пришлось подрезать до физических пределов (40…12 000 мм) */
  подрезано: string[];
  /** что вышло за обычный ряд изделия (это не запрет, а подсказка мастеру) */
  вне: string[];
}

/** Физические пределы любого размера, мм: тоньше двух плит корпус не собрать, длиннее 12 м — опечатка */
export const РАЗМЕР_МИН = 40;
export const РАЗМЕР_МАКС = 12000;

/**
 * Свободные размеры (решение Макара 13.11.2026): любой объект — любого размера. Запрет только физический (40…12 000 мм);
 * границы изделия из каталога теперь подсказка: «вне обычного ряда» — словами, без подрезки.
 */
export function ограничитьГабариты(изд: Изделие, габ: Габариты): РезультатОграничения {
  const { мин, макс } = изд.границы;
  const н: Габариты = {
    ш: Math.round(зажать(габ.ш, РАЗМЕР_МИН, РАЗМЕР_МАКС)),
    г: Math.round(зажать(габ.г, РАЗМЕР_МИН, РАЗМЕР_МАКС)),
    в: Math.round(зажать(габ.в, РАЗМЕР_МИН, РАЗМЕР_МАКС)),
  };
  const подрезано: string[] = [];
  const вне: string[] = [];
  const имя = { ш: 'ширина', г: 'глубина', в: 'высота' } as const;
  for (const к of ['ш', 'г', 'в'] as const) {
    if (н[к] !== Math.round(габ[к])) подрезано.push(`${имя[к]} → ${н[к]} мм (возможно ${РАЗМЕР_МИН}…${РАЗМЕР_МАКС})`);
    else if (н[к] < мин[к] || н[к] > макс[к]) вне.push(`${имя[к]} ${н[к]} мм (обычно ${мин[к]}…${макс[к]})`);
  }
  return { габариты: н, подрезано, вне };
}

/** Новый экземпляр изделия с заводскими габаритами. Отличий от изделия нет. */
export function новыйЭкземпляр(
  изд: Изделие,
  помещение: string,
  позиция?: Вектор3,
  id = новыйИд(),
): Экземпляр {
  const y = изд.крепление === 'стена' ? (изд.подъём ?? 1500) : 0;
  return {
    id,
    изделие: изд.id,
    помещение,
    позиция: позиция ?? [0, y, 0],
    поворот: 0,
    габариты: { ...изд.габариты },
  };
}

/** Раскладка экземпляра целиком (изделие + отличия) */
export function раскладкаЭкземпляра(экз: Экземпляр) {
  const изд = изделиеПоИд(экз.изделие);
  return изд ? слитьРаскладку(изд.раскладка, экз.раскладка) : undefined;
}

