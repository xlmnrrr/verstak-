/** Проект v2: создание, копирование, экземпляры из изделий, границы размеров. */
import { зажать } from './геометрия';
import { изделиеПоИд } from './каталог';
import { новоеПомещение, прямоугольник, высотаДляРендера } from './помещение';
import { слитьРаскладку } from './раскладка';
import type { Габариты, Изделие, Настройки, Помещение, ПроектV2, Экземпляр, Вектор3 } from './типы';

let счётчик = 0;
export const новыйИд = (префикс = 'о') => `${префикс}-${Date.now().toString(36)}-${(счётчик++).toString(36)}`;

export const настройкиПоУмолчанию = (): Настройки => ({
  тема: 'система',
  фон: '#171a1f',
  шаг_сетки: 50,
  толщина_плиты: 16,
  качество: 'авто',
  режим_обзора: 'сверху',
});

export function новыйПроектV2(название: string, помещение?: Помещение): ПроектV2 {
  const сейчас = new Date().toISOString();
  return {
    schemaVersion: 2,
    название,
    создан: сейчас,
    изменён: сейчас,
    помещения: [помещение ?? новоеПомещение('п1', 'кухня', 'Кухня', прямоугольник(3600, 2800))],
    связи: [],
    объекты: [],
    настройки: настройкиПоУмолчанию(),
  };
}

export const копияПроекта = (п: ПроектV2): ПроектV2 => JSON.parse(JSON.stringify(п));

/** Помещение проекта по id (первое, если id не найден) */
export const помещениеПоИд = (п: ПроектV2, id?: string): Помещение | undefined =>
  п.помещения.find((x) => x.id === id) ?? п.помещения[0];

export interface РезультатОграничения {
  габариты: Габариты;
  подрезано: string[];
}

/** Привести габариты к границам изделия (мин…макс). Что подрезано — словами. */
export function ограничитьГабариты(изд: Изделие, габ: Габариты): РезультатОграничения {
  const { мин, макс } = изд.границы;
  const н: Габариты = {
    ш: Math.round(зажать(габ.ш, мин.ш, макс.ш)),
    г: Math.round(зажать(габ.г, мин.г, макс.г)),
    в: Math.round(зажать(габ.в, мин.в, макс.в)),
  };
  const подрезано: string[] = [];
  if (н.ш !== габ.ш) подрезано.push(`ширина → ${н.ш} мм (допустимо ${мин.ш}…${макс.ш})`);
  if (н.г !== габ.г) подрезано.push(`глубина → ${н.г} мм (допустимо ${мин.г}…${макс.г})`);
  if (н.в !== габ.в) подрезано.push(`высота → ${н.в} мм (допустимо ${мин.в}…${макс.в})`);
  return { габариты: н, подрезано };
}

/** Новый экземпляр изделия с заводскими габаритами. Отличий от изделия нет. */
export function новыйЭкземпляр(
  изд: Изделие,
  помещение: string,
  позиция?: Вектор3,
  id = новыйИд(),
): Экземпляр {
  const y = изд.крепление === 'стена' ? (изд.подъём ?? 1500) : 0;
  return {
    id,
    изделие: изд.id,
    помещение,
    позиция: позиция ?? [0, y, 0],
    поворот: 0,
    габариты: { ...изд.габариты },
  };
}

/** Раскладка экземпляра целиком (изделие + отличия) */
export function раскладкаЭкземпляра(экз: Экземпляр) {
  const изд = изделиеПоИд(экз.изделие);
  return изд ? слитьРаскладку(изд.раскладка, экз.раскладка) : undefined;
}

