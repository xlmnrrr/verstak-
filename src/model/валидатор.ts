/* ------------------------------------------------------------------ 1. помещение и соседи */

function размерыИСоседи(п: ПроектV2): Замечание[] {
  const итог: Замечание[] = [];
  const экз = new Map(п.объекты.map((э) => [э.id, э]));
  const пом = new Map(п.помещения.map((x) => [x.id, x]));
  for (const пр of проверитьВлезает(п)) {
    const э = экз.get(пр.id);
    if (!э) continue;
    const к = пом.get(э.помещение);
    const имя = имяЭкз(э);
    if (пр.вид === 'вне-помещения' && к) {
      const θ = (э.поворот * Math.PI) / 180;
      const осьШ: Точка2 = [Math.cos(θ), Math.sin(θ)];
      const осьГ = фронт(э.поворот);
      const центр: Точка2 = [э.позиция[0], э.позиция[2]];
      const хШ = хорда(к.контур, центр, осьШ);
      const хГ = хорда(к.контур, центр, осьГ);
      let текст = `${имя}: выступает за стену на ${пр.мм} мм`;
      let мм = пр.мм;
      if (хШ !== null && э.габариты.ш > хШ + 2) {
        мм = Math.round(э.габариты.ш - хШ);
        текст = `${имя}: не влезает по ширине — между стенами ${Math.round(хШ)} мм, нужно ${э.габариты.ш}, не хватает ${мм} мм`;
      } else if (хГ !== null && э.габариты.г > хГ + 2) {
        мм = Math.round(э.габариты.г - хГ);
        текст = `${имя}: не влезает по глубине — между стенами ${Math.round(хГ)} мм, нужно ${э.габариты.г}, не хватает ${мм} мм`;
      }
      итог.push(замечание({ правило: 'вне-помещения', важность: 'ошибка', помещение: э.помещение, id: э.id, мм, текст }));
    } else if (пр.вид === 'выше-стен' && к) {
      const H = высотаДляРендера(к);
      итог.push(
        замечание({
          правило: 'выше-потолка',
          важность: 'ошибка',
          помещение: э.помещение,
          id: э.id,
          мм: пр.мм,
          текст: `${имя}: выше потолка на ${пр.мм} мм — потолок ${H} мм, верх изделия ${H + пр.мм} мм`,
        }),
      );
    } else if (пр.вид === 'пересечение' && пр.с && э.id < пр.с) {
      const с = экз.get(пр.с);
      итог.push(
        замечание({
          правило: 'пересечение',
          важность: 'ошибка',
          помещение: э.помещение,
          id: э.id,
          с: [пр.с],
          мм: пр.мм,
          текст: `${имя} пересекается с «${с ? имяЭкз(с) : 'соседом'}» на ${пр.мм} мм`,
        }),
      );
    }
  }
  return итог;
}

/* ------------------------------------------------------------------ 2. проёмы и короба */

function проёмы(п: ПроектV2): Замечание[] {
  const итог: Замечание[] = [];
  for (const пом of п.помещения) {
    const ст = рёбра(пом.контур);
    const тела = п.объекты.filter((э) => э.помещение === пом.id).map(тело).filter((т): т is Тело => !!т && ТВЁРДЫЕ.has(т.изд.тип));
    for (const о of пом.отметки) {
      if (о.вид !== 'дверь' && о.вид !== 'арка' && о.вид !== 'окно') continue;
      const с = ст[о.стена];
      if (!с) continue;
      for (const т of тела) {
        const s = т.след.map((q) => (q[0] - с.а[0]) * с.направление[0] + (q[1] - с.а[1]) * с.направление[1]);
        const h = т.след.map((q) => (q[0] - с.а[0]) * с.нормаль[0] + (q[1] - с.а[1]) * с.нормаль[1]);
        if (Math.min(...h) > 60 || Math.max(...h) < -пом.толщина_стен) continue; // не у этой стены
        const ов = перекрытие(Math.min(...s), Math.max(...s), о.от_угла, о.от_угла + о.ширина);
        if (ов <= 10) continue;
        if (перекрытие(т.y0, т.y1, о.от_пола, о.от_пола + о.высота) <= 10) continue;
        const мм = Math.round(Math.min(ов, о.ширина));
        const имя = имяЭкз(т.э);
        if (о.вид === 'окно') {
          итог.push(
            замечание({
              правило: 'проём',
              важность: 'предупреждение',
              помещение: пом.id,
              id: т.э.id,
              мм,
              текст: `${имя} закрывает окно: перекрывает ${мм} мм из ${о.ширина} мм по ширине, высота изделия ${Math.round(т.y1)} мм, подоконник ${о.от_пола} мм`,
            }),
          );
        } else {
          итог.push(
            замечание({
              правило: 'проём',
              важность: 'ошибка',
              помещение: пом.id,
              id: т.э.id,
              мм,
              текст: `${имя} загораживает ${о.вид === 'арка' ? 'арку' : 'дверь'}: перекрывает ${мм} мм из ${о.ширина} мм проёма`,
            }),
          );
        }
      }
    }
    // короба и щитки на стенах — препятствия
    const преп = препятствияПомещения(п, пом, пом.id).filter((x) => x.вид === 'короб' && (x.название === 'короб' || x.название === 'щиток'));
    for (const т of тела) {
      for (const к of преп) {
        if (перекрытие(т.y0, т.y1, к.y0, к.y1) <= 10) continue;
        const г = глубинаПересечения(т.след, к.поли as Точка[]);
        if (г > 10) {
          итог.push(
            замечание({
              правило: 'короб',
              важность: 'ошибка',
              помещение: пом.id,
              id: т.э.id,
              мм: Math.round(г),
              текст: `${имяЭкз(т.э)} пересекается с ${к.название === 'щиток' ? 'щитком' : 'коробом'} на стене на ${Math.round(г)} мм`,
            }),
          );
        }
      }
    }
  }
  return итог;
}

/* ------------------------------------------------------------------ 3. суммы секций */

function секции(п: ПроектV2): Замечание[] {
  const итог: Замечание[] = [];
  for (const э of п.объекты) {
    const изд = изделиеПоИд(э.изделие);
    if (!изд || изд.тип !== 'корпус' || изд.состав?.length) continue;
    const р = слитьРаскладку(изд.раскладка, э.раскладка);
    const n = р.секции.length;
    if (n < 2) continue;
    const t = р.корпус.плита;
    const внутр = э.габариты.ш - (р.корпус.боковины ? 2 * t : 0) - (n - 1) * t;
    const фикс = р.секции.reduce((s, c) => s + (typeof c.ширина === 'number' ? c.ширина : 0), 0);
    if (!р.секции.some((c) => typeof c.ширина === 'number')) continue;
    // ширины секций по расчёту модели: сжатие означает, что заданные секции не помещаются
    const расчёт = ширинысекций(р.секции, внутр);
    if (фикс <= внутр + 1) continue; // меньше — модель растянет секции по пропорции, это не ошибка
    const мм = Math.abs(Math.round(фикс - внутр));
    const задано = р.секции.filter((c) => typeof c.ширина === 'number').map((c) => c.ширина).join(' + ');
    итог.push(
      замечание({
        правило: 'секции',
        важность: 'предупреждение',
        помещение: э.помещение,
        id: э.id,
        мм,
        текст: `${имяЭкз(э)}: секции ${задано} = ${Math.round(фикс)} мм шире корпуса — внутри ${Math.round(внутр)} мм, не хватает ${мм} мм (секции сжаты до ${расчёт.join(' + ')})`,
      }),
    );
  }
  return итог;
}

/* ------------------------------------------------------------------ 4. открывание */

function открывание(п: ПроектV2): Замечание[] {
  const итог: Замечание[] = [];
  for (const пом of п.помещения) {
    const экз = new Map(п.объекты.map((э) => [э.id, э]));
    for (const к of конфликтыПомещения(п, пом.id)) {
      const э = экз.get(к.id);
      if (!э) continue;
      итог.push(
        замечание({
          правило: 'открывание',
          важность: 'предупреждение',
          помещение: пом.id,
          id: э.id,
          с: к.мешаетId ? [к.мешаетId] : undefined,
          мм: к.мм,
          группа: к.группа,
          текст: `${имяЭкз(э)}:${к.текст[0].toLowerCase()}${к.текст.slice(1)}`,
        }),
      );
    }
    итог.push(...дверьКомнаты(п, пом));
  }
  return итог;
}

/** Створка двери комнаты в плане при угле α: сектор от петли */
function сектор(петля: Точка2, вдоль: Точка2, внутрь: Точка2, ширина: number, α: number): Точка2[] {
  const шаги = Math.max(2, Math.ceil(α / 10));
  const р: Точка2[] = [петля];
  for (let i = 0; i <= шаги; i++) {
    const a = ((α * i) / шаги) * (Math.PI / 180);
    р.push([петля[0] + (вдоль[0] * Math.cos(a) + внутрь[0] * Math.sin(a)) * ширина, петля[1] + (вдоль[1] * Math.cos(a) + внутрь[1] * Math.sin(a)) * ширина]);
  }
  return р;
}

function дверьКомнаты(п: ПроектV2, пом: Помещение): Замечание[] {
  const итог: Замечание[] = [];
  const ст = рёбра(пом.контур).map((с) => ({ индекс: с.индекс, а: с.а as Точка2, направление: с.направление as Точка2, нормаль: с.нормаль as Точка2 }));
  const тела = п.объекты.filter((э) => э.помещение === пом.id).map(тело).filter((т): т is Тело => !!т && ТВЁРДЫЕ.has(т.изд.тип));
  for (const д of двериКомнаты(пом, ст)) {
    if (д.наружу) continue; // створка уходит в соседнее помещение
    const преп = тела.filter((т) => перекрытие(т.y0, т.y1, д.от_пола, д.от_пола + д.высота) > 10);
    if (!преп.length) continue;
    // сектор — выпуклый многоугольник; вместо SAT по всему сектору проверяем по углам
    const мешает = (α: number) => {
      const фигура = сектор(д.петля, д.вдоль, д.внутрь, д.ширина - 5, α);
      return преп.find((т) => т.следы.some((ч) => многоугольникиПересекаются(фигура, ч as Точка2[])));
    };
    const полный = мешает(УГОЛ_ДВЕРИ_КОМНАТЫ);
    if (!полный) continue;
    let lo = 0;
    let hi = УГОЛ_ДВЕРИ_КОМНАТЫ;
    for (let i = 0; i < 14; i++) {
      const mid = (lo + hi) / 2;
      if (мешает(mid)) hi = mid;
      else lo = mid;
    }
    const угол = Math.floor(lo);
    итог.push(
      замечание({
        правило: 'дверь-комнаты',
        важность: 'предупреждение',
        помещение: пом.id,
        id: полный.э.id,
        мм: УГОЛ_ДВЕРИ_КОМНАТЫ - угол,
        текст: `Дверь комнаты «${пом.название}» открывается только на ${угол}° из ${УГОЛ_ДВЕРИ_КОМНАТЫ}°: мешает «${имяЭкз(полный.э)}»`,
      }),
    );
  }
  return итог;
}

/* ------------------------------------------------------------------ 5. проходы и место перед техникой */

/** Расстояние от точки по лучу до ближайшей преграды: стены или твёрдого предмета в полосе высот [150..1200] */
function просветВпереди(пом: Помещение, тела: Тело[], источник: Тело): { мм: number; чем: Тело | null } | null {
  // угловой модуль: просвет — от лицевой стороны плеча «а», а не от габарита (в габарите свободный угол комнаты)
  const лицо = источник.изд.угловой ? фасадыПлеч(источник.изд, источник.э.габариты)[0] : null;
  const f = лицо ? (повернутьТочку(лицо.нормаль[0], лицо.нормаль[1], источник.э.поворот) as Точка2) : фронт(источник.э.поворот);
  const местно = лицо ? повернутьТочку(лицо.середина[0], лицо.середина[1], источник.э.поворот) : null;
  const о: Точка2 = местно
    ? [источник.э.позиция[0] + местно[0], источник.э.позиция[2] + местно[1]]
    : [источник.э.позиция[0] + f[0] * (источник.э.габариты.г / 2), источник.э.позиция[2] + f[1] * (источник.э.габариты.г / 2)];
  let лучший: { мм: number; чем: Тело | null } | null = null;
  const ст = лучДоКонтура(о, f, пом.контур);
  if (ст !== null) лучший = { мм: ст, чем: null };
  for (const т of тела) {
    if (т === источник || т.э.id === источник.э.id) continue;
    if (!ТВЁРДЫЕ.has(т.изд.тип)) continue;
    if (!(т.y0 < 1200 && т.y1 > 150)) continue;
    const t = лучВТело(о, f, т);
    if (t !== null && (лучший === null || t < лучший.мм)) лучший = { мм: t, чем: т };
  }
  return лучший;
}

function проходы(п: ПроектV2): Замечание[] {
  const итог: Замечание[] = [];
  for (const пом of п.помещения) {
    if (!С_ПРОХОДОМ.has(пом.тип)) continue;
    const тела = п.объекты.filter((э) => э.помещение === пом.id).map(тело).filter((т): т is Тело => !!т);
    const группы = new Map<string, { т: Тело; мм: number; чем: Тело | null; норма: number; число: number; особая: boolean }>();
    for (const т of тела) {
      if (т.изд.тип !== 'корпус' && т.изд.тип !== 'техника') continue;
      if (т.изд.крепление === 'стена' || т.изд.крепление === 'потолок') continue;
      if (т.y0 > 300 || т.э.габариты.в < 600) continue;
      const холодильник = начинается(т.э, 'холодильник', 'морозильник');
      const посудомойка = начинается(т.э, 'посудомойка');
      const открытые = т.изд.тип === 'корпус' && слитьРаскладку(т.изд.раскладка, т.э.раскладка).фасад.тип === 'нет';
      const норма = холодильник ? НОРМЫ.передХолодильником : посудомойка ? НОРМЫ.передПосудомойкой : нормаПрохода(пом.тип, открытые);
      const р = просветВпереди(пом, тела, т);
      if (!р || р.мм < 50 || р.мм >= норма - 1) continue; // вплотную: закрытый угол, не проход
      const ключ = холодильник || посудомойка ? `т:${т.э.id}` : р.чем ? `${[((т.э.поворот % 360) + 360) % 360, ((р.чем.э.поворот % 360) + 360) % 360].sort().join('~')}` : `${((т.э.поворот % 360) + 360) % 360}|стена`;
      const есть = группы.get(ключ);
      if (!есть) группы.set(ключ, { т, мм: Math.round(р.мм), чем: р.чем, норма, число: 1, особая: холодильник || посудомойка });
      else {
        есть.число++;
        if (р.мм < есть.мм) Object.assign(есть, { т, мм: Math.round(р.мм), чем: р.чем });
      }
    }
    for (const г of группы.values()) {
      const мм = Math.round(г.норма - г.мм);
      const кем = г.чем ? `«${имяЭкз(г.чем.э)}»` : 'стены';
      if (г.особая) {
        итог.push(
          замечание({
            правило: 'перед-техникой',
            важность: 'предупреждение',
            помещение: пом.id,
            id: г.т.э.id,
            с: г.чем ? [г.чем.э.id] : undefined,
            мм,
            текст: `Перед «${имяЭкз(г.т.э)}» свободно ${г.мм} мм до ${кем}: чтобы открыть ${начинается(г.т.э, 'посудомойка') ? 'посудомойку и встать рядом' : 'дверцу и пройти'}, нужно не меньше ${г.норма} мм, не хватает ${мм} мм`,
          }),
        );
      } else {
        итог.push(
          замечание({
            правило: 'проход',
            важность: 'предупреждение',
            помещение: пом.id,
            id: г.т.э.id,
            с: г.чем ? [г.чем.э.id] : undefined,
            мм,
            текст: `Проход перед «${имяЭкз(г.т.э)}»${г.число > 1 ? ` (и ещё ${г.число - 1} в ряду)` : ''} — ${г.мм} мм до ${кем}, нужно не меньше ${г.норма} мм${пом.тип === 'кухня' ? '' : ` (${пом.тип})`}, не хватает ${мм} мм`,
          }),
        );
      }
    }
  }
  return итог;
}

/* ------------------------------------------------------------------ 6. зазоры в ряду */

function зазорыВРяду(п: ПроектV2): Замечание[] {
  const итог: Замечание[] = [];
  for (const пом of п.помещения) {
    const тела = п.объекты
      .filter((э) => э.помещение === пом.id)
      .map(тело)
      .filter((т): т is Тело => !!т && (т.изд.тип === 'корпус' || т.изд.тип === 'техника') && т.изд.крепление !== 'потолок');
    for (let i = 0; i < тела.length; i++) {
      for (let j = i + 1; j < тела.length; j++) {
        const a = тела[i];
        const b = тела[j];
        if (Math.abs(a.э.поворот - b.э.поворот) % 360 > 0.01) continue;
        if (a.э.поворот % 90 !== 0) continue;
        if (перекрытие(a.y0, a.y1, b.y0, b.y1) <= 100) continue;
        const вдоль = Math.abs(фронт(a.э.поворот)[0]) > 0.5 ? 'z' : 'x'; // ряд идёт вдоль этой оси
        const [a0, a1, b0, b1, c0, c1, d0, d1] =
          вдоль === 'x'
            ? [a.ящик.x0, a.ящик.x1, b.ящик.x0, b.ящик.x1, a.ящик.z0, a.ящик.z1, b.ящик.z0, b.ящик.z1]
            : [a.ящик.z0, a.ящик.z1, b.ящик.z0, b.ящик.z1, a.ящик.x0, a.ящик.x1, b.ящик.x0, b.ящик.x1];
        if (перекрытие(c0, c1, d0, d1) < Math.min(c1 - c0, d1 - d0) * 0.5) continue; // не в одном ряду
        const зазор = Math.max(b0 - a1, a0 - b1);
        if (зазор < НОРМЫ.зазорЩельМин || зазор > НОРМЫ.зазорЩельМакс) continue;
        const мм = Math.round(зазор);
        итог.push(
          замечание({
            правило: 'зазор',
            важность: 'совет',
            помещение: пом.id,
            id: a.э.id,
            с: [b.э.id],
            мм,
            текст: `Щель ${мм} мм между «${имяЭкз(a.э)}» и «${имяЭкз(b.э)}»: слишком мала для фальшпанели и велика для стыка — сдвиньте вплотную или поставьте панель`,
          }),
        );
      }
    }
  }
  return итог;
}

/* ------------------------------------------------------------------ 7. эргономика кухни */

function кухня(п: ПроектV2): Замечание[] {
  const итог: Замечание[] = [];
  for (const пом of п.помещения) {
    if (пом.тип !== 'кухня') continue;
    const тела = п.объекты.filter((э) => э.помещение === пом.id).map(тело).filter((т): т is Тело => !!т);
    итог.push(...треугольник(пом, тела), ...рабочаяВысота(пом, тела), ...фартук(пом, тела));
  }
  return итог;
}

function найти(тела: Тело[], ...префиксы: string[]): Тело | undefined {
  for (const пр of префиксы) {
    const т = тела.find((x) => x.э.изделие.startsWith(пр));
    if (т) return т;
  }
  return undefined;
}

function треугольник(пом: Помещение, тела: Тело[]): Замечание[] {
  const мойка = найти(тела, 'мойка', 'тумба-под-мойку');
  const плита = найти(тела, 'плита', 'варочная', 'тумба-под-плиту');
  const холод = найти(тела, 'холодильник');
  const есть = [мойка, плита, холод].filter(Boolean).length;
  if (есть === 0) return [];
  const опорный = мойка ?? плита ?? холод!;
  if (есть < 3) {
    const нет = [!мойка && 'мойки', !плита && 'плиты', !холод && 'холодильника'].filter(Boolean).join(', ');
    return [замечание({ правило: 'треугольник', важность: 'совет', помещение: пом.id, id: опорный.э.id, текст: `Рабочий треугольник не построить: нет ${нет}` })];
  }
  const ц = (т: Тело): Точка2 => [т.э.позиция[0], т.э.позиция[2]];
  const d = (a: Тело, b: Тело) => Math.hypot(ц(a)[0] - ц(b)[0], ц(a)[1] - ц(b)[1]);
  const [aм, bм, cм] = [мойка!, плита!, холод!];
  const стороны = [
    { имя: 'мойка — плита', v: d(aм, bм) },
    { имя: 'плита — холодильник', v: d(bм, cм) },
    { имя: 'холодильник — мойка', v: d(cм, aм) },
  ];
  // высота наименьшей «вершины» над линией двух других: если все три в одну линию, треугольника нет — есть рабочая линия
  const площадь2 = Math.abs((ц(bм)[0] - ц(aм)[0]) * (ц(cм)[1] - ц(aм)[1]) - (ц(cм)[0] - ц(aм)[0]) * (ц(bм)[1] - ц(aм)[1]));
  const самая = Math.max(...стороны.map((s) => s.v));
  const высота = самая > 0 ? площадь2 / самая : 0;
  if (высота < 400) {
    // в одну линию: проверяем свободную поверхность между мойкой и плитой
    const зазор = Math.round(расстояниеЯщиков(aм.ящик, bм.ящик));
    if (зазор < НОРМЫ.междуМойкойИПлитой) {
      return [
        замечание({
          правило: 'треугольник',
          важность: 'совет',
          помещение: пом.id,
          id: aм.э.id,
          с: [bм.э.id],
          мм: НОРМЫ.междуМойкойИПлитой - зазор,
          текст: `Мойка и плита в одной линии, между ними ${зазор} мм рабочей поверхности — нужно не меньше ${НОРМЫ.междуМойкойИПлитой} мм, не хватает ${НОРМЫ.междуМойкойИПлитой - зазор} мм`,
        }),
      ];
    }
    return [];
  }
  const плохие = стороны.filter((s) => s.v < НОРМЫ.треугольникСторонаМин || s.v > НОРМЫ.треугольникСторонаМакс);
  const сумма = стороны.reduce((s, x) => s + x.v, 0);
  const части = плохие.map((s) => `${s.имя} ${м(s.v)} (нужно ${м(НОРМЫ.треугольникСторонаМин)}–${м(НОРМЫ.треугольникСторонаМакс)})`);
  if (сумма < НОРМЫ.треугольникСуммаМин || сумма > НОРМЫ.треугольникСуммаМакс) части.push(`сумма сторон ${м(сумма)} (нужно ${м(НОРМЫ.треугольникСуммаМин)}–${м(НОРМЫ.треугольникСуммаМакс)})`);
  if (!части.length) return [];
  return [замечание({ правило: 'треугольник', важность: 'совет', помещение: пом.id, id: aм.э.id, текст: `Рабочий треугольник: ${части.join('; ')}` })];
}

/**
 * Высота рабочей поверхности. Это совет: норма 850–900 мм ставится для роста пользователя, а у мастера свои чертежи.
 * Одна запись на ряд: столешницы одной высоты, стоящие вплотную (щель до 100 мм), считаются одним рядом, а не каждая отдельно.
 */
const РЯД_СВЯЗЬ_ММ = 100;
function рабочаяВысота(пом: Помещение, тела: Тело[]): Замечание[] {
  const поверхности = тела.filter((т) => т.изд.тип === 'столешница' && т.изд.крепление === 'пол' && !т.изд.id.startsWith('подоконник'));
  const вНорме = (верх: number) => верх >= НОРМЫ.рабочаяВысотаМин - НОРМЫ.допускВысоты && верх <= НОРМЫ.рабочаяВысотаМакс + НОРМЫ.допускВысоты;
  const плохие = поверхности.filter((т) => !вНорме(Math.round(т.y1)));
  // ряды: общая высота верха и касание в плане (union-find)
  const родитель = плохие.map((_, i) => i);
  const корень = (i: number): number => (родитель[i] === i ? i : (родитель[i] = корень(родитель[i])));
  for (let i = 0; i < плохие.length; i++) {
    for (let j = i + 1; j < плохие.length; j++) {
      const a = плохие[i];
      const b = плохие[j];
      if (Math.abs(a.y1 - b.y1) > 3) continue;
      const щельX = Math.max(b.ящик.x0 - a.ящик.x1, a.ящик.x0 - b.ящик.x1);
      const щельZ = Math.max(b.ящик.z0 - a.ящик.z1, a.ящик.z0 - b.ящик.z1);
      if (Math.max(щельX, щельZ) <= РЯД_СВЯЗЬ_ММ) родитель[корень(j)] = корень(i);
    }
  }
  const ряды = new Map<number, Тело[]>();
  плохие.forEach((т, i) => ряды.set(корень(i), [...(ряды.get(корень(i)) ?? []), т]));
  const итог: Замечание[] = [];
  for (const ряд of ряды.values()) {
    const т = ряд[0];
    const верх = Math.round(т.y1);
    const хуже = верх > НОРМЫ.рабочаяВысотаМакс ? верх - НОРМЫ.рабочаяВысотаМакс : НОРМЫ.рабочаяВысотаМин - верх;
    // низ столешницы на 720 — высота нижних тумб по чертежам мастера (в каталоге 720): норму 850 тут не навязываем, а напоминаем
    const поЧертежам = Math.abs(т.y0 - 720) <= 5 ? ` По вашим чертежам высота 720, норма ${НОРМЫ.рабочаяВысотаМин}.` : '';
    итог.push(
      замечание({
        правило: 'рабочая-высота',
        важность: 'совет',
        помещение: пом.id,
        id: т.э.id,
        с: ряд.length > 1 ? ряд.slice(1).map((x) => x.э.id) : undefined,
        мм: хуже,
        текст: `Рабочая поверхность «${имяЭкз(т.э)}»${ряд.length > 1 ? ` и ещё ${ряд.length - 1} в ряду` : ''} на высоте ${верх} мм, нужно ${НОРМЫ.рабочаяВысотаМин}–${НОРМЫ.рабочаяВысотаМакс} мм (${верх > НОРМЫ.рабочаяВысотаМакс ? 'выше' : 'ниже'} на ${хуже} мм).${поЧертежам}`,
      }),
    );
  }
  return итог;
}

function фартук(пом: Помещение, тела: Тело[]): Замечание[] {
  const итог: Замечание[] = [];
  const низы = тела.filter((т) => (т.изд.тип === 'столешница' || т.изд.тип === 'корпус' || т.изд.тип === 'техника') && т.изд.крепление !== 'стена' && т.изд.крепление !== 'потолок' && !т.изд.id.startsWith('подоконник'));
  const группы = new Map<string, { т: Тело; мм: number; число: number; верх: number }>();
  for (const в of тела) {
    if (в.изд.тип !== 'корпус' || в.изд.крепление !== 'стена' || в.изд.id.includes('вытяжк')) continue;
    if (в.y0 < 900 || в.y0 > 1800) continue;
    let верх = -1;
    for (const н of низы) {
      if (н.y1 > в.y0 - 100) continue; // высокий пенал, холодильник — не поверхность под шкафом
      if (н.изд.тип !== 'столешница' && н.y0 > 150) continue; // мойка, варочная панель и техника на столешнице — не поверхность
      if (перекрытие(н.ящик.x0, н.ящик.x1, в.ящик.x0, в.ящик.x1) <= 50 || перекрытие(н.ящик.z0, н.ящик.z1, в.ящик.z0, в.ящик.z1) <= 20) continue;
      if (н.y1 > верх) верх = н.y1;
    }
    if (верх < 0) continue;
    const мм = Math.round(в.y0 - верх);
    if (мм >= НОРМЫ.фартукМин - НОРМЫ.допускВысоты && мм <= НОРМЫ.фартукМакс + НОРМЫ.допускВысоты) continue;
    const ключ = String(мм);
    const есть = группы.get(ключ);
    if (есть) есть.число++;
    else группы.set(ключ, { т: в, мм, число: 1, верх });
  }
  for (const г of группы.values()) {
    итог.push(
      замечание({
        правило: 'фартук',
        важность: 'совет',
        помещение: пом.id,
        id: г.т.э.id,
        мм: г.мм < НОРМЫ.фартукМин ? НОРМЫ.фартукМин - г.мм : г.мм - НОРМЫ.фартукМакс,
        текст: `Фартук под «${имяЭкз(г.т.э)}»${г.число > 1 ? ` (и ещё ${г.число - 1})` : ''} — ${г.мм} мм от поверхности до низа шкафа, нужно ${НОРМЫ.фартукМин}–${НОРМЫ.фартукМакс} мм`,
      }),
    );
  }
  return итог;
}

/* ------------------------------------------------------------------ 8. эргономика комнат */

function комнаты(п: ПроектV2): Замечание[] {
  const итог: Замечание[] = [];
  for (const пом of п.помещения) {
    const тела = п.объекты.filter((э) => э.помещение === пом.id).map(тело).filter((т): т is Тело => !!т);
    for (const т of тела) {
      if (начинается(т.э, 'кровать')) итог.push(...уКровати(пом, тела, т));
      if (начинается(т.э, 'стол-письменный') && Math.abs(т.э.габариты.в - НОРМЫ.письменныйСтол) > 20) {
        итог.push(
          замечание({
            правило: 'письменный-стол',
            важность: 'совет',
            помещение: пом.id,
            id: т.э.id,
            мм: Math.abs(т.э.габариты.в - НОРМЫ.письменныйСтол),
            текст: `Письменный стол «${имяЭкз(т.э)}» высотой ${т.э.габариты.в} мм, нужно ${НОРМЫ.письменныйСтол} мм (${т.э.габариты.в > НОРМЫ.письменныйСтол ? 'выше' : 'ниже'} на ${Math.abs(т.э.габариты.в - НОРМЫ.письменныйСтол)} мм)`,
          }),
        );
      }
      // барный стул и табурет в каталоге нарисованы по шаблону обычного стула (сиденье не на своей высоте): им норма 450 не подходит
      if (т.изд.тип === 'стул' && !т.изд.id.includes('барный') && !т.изд.id.startsWith('табурет')) {
        const сиденье = детали(т.изд, т.э).filter((д) => д.роль === 'сиденье');
        if (сиденье.length) {
          const верх = Math.round(Math.max(...сиденье.map((д) => д.локально.центр[1] + д.локально.объём[1] / 2)));
          if (Math.abs(верх - НОРМЫ.сиденье) > 30) {
            итог.push(
              замечание({
                правило: 'сиденье',
                важность: 'совет',
                помещение: пом.id,
                id: т.э.id,
                мм: Math.abs(верх - НОРМЫ.сиденье),
                текст: `Сиденье «${имяЭкз(т.э)}» на высоте ${верх} мм, нужно ${НОРМЫ.сиденье} мм (${верх > НОРМЫ.сиденье ? 'выше' : 'ниже'} на ${Math.abs(верх - НОРМЫ.сиденье)} мм)`,
              }),
            );
          }
        }
      }
    }
    // диван против телевизора
    for (const д of тела.filter((x) => начинается(x.э, 'диван'))) {
      for (const тв of тела.filter((x) => начинается(x.э, 'тв-тумба'))) {
        const f = фронт(д.э.поворот);
        const вx = тв.э.позиция[0] - д.э.позиция[0];
        const вz = тв.э.позиция[2] - д.э.позиция[2];
        const л = Math.hypot(вx, вz) || 1;
        if ((f[0] * вx + f[1] * вz) / л < 0.5) continue; // диван смотрит не на ТВ
        const расст = Math.round(расстояниеЯщиков(д.ящик, тв.ящик));
        if (расст >= НОРМЫ.диванТвМин && расст <= НОРМЫ.диванТвМакс) continue;
        const мм = расст < НОРМЫ.диванТвМин ? НОРМЫ.диванТвМин - расст : расст - НОРМЫ.диванТвМакс;
        итог.push(
          замечание({
            правило: 'диван-тв',
            важность: 'совет',
            помещение: пом.id,
            id: д.э.id,
            с: [тв.э.id],
            мм,
            текст: `От дивана до ТВ-тумбы ${расст} мм, смотреть удобно с ${НОРМЫ.диванТвМин}–${НОРМЫ.диванТвМакс} мм (${расст < НОРМЫ.диванТвМин ? 'ближе' : 'дальше'} на ${мм} мм)`,
          }),
        );
      }
    }
  }
  return итог;
}

/** Свободное место у боковых сторон и в ногах кровати */
function уКровати(пом: Помещение, тела: Тело[], к: Тело): Замечание[] {
  const f = фронт(к.э.поворот);
  const право: Точка2 = [-f[1], f[0]]; // не важно, какая из боковых «левая»: подписываем «с одной стороны»
  const г = к.э.габариты.г;
  const ш = к.э.габариты.ш;
  const ц: Точка2 = [к.э.позиция[0], к.э.позиция[2]];
  // изголовье — задняя сторона (−f), ноги — фасад (+f); боковые — ±право
  const стороны: { имя: string; д: Точка2; точки: Точка2[] }[] = [
    { имя: 'с одной стороны', д: право, точки: [-0.25, 0, 0.25].map((k) => [ц[0] + право[0] * ш / 2 + f[0] * г * k, ц[1] + право[1] * ш / 2 + f[1] * г * k] as Точка2) },
    { имя: 'с другой стороны', д: [-право[0], -право[1]], точки: [-0.25, 0, 0.25].map((k) => [ц[0] - право[0] * ш / 2 + f[0] * г * k, ц[1] - право[1] * ш / 2 + f[1] * г * k] as Точка2) },
    { имя: 'в ногах', д: f, точки: [-0.25, 0, 0.25].map((k) => [ц[0] + f[0] * г / 2 + право[0] * ш * k, ц[1] + f[1] * г / 2 + право[1] * ш * k] as Точка2) },
  ];
  const итог: Замечание[] = [];
  const заменять = тела.filter((x) => x !== к && ТВЁРДЫЕ.has(x.изд.тип) && !начинается(x.э, 'тумба-прикроватная') && x.y0 < 700 && x.y1 > 200);
  const стороныОценка = стороны.map((с) => {
    let мин = Infinity;
    let чем: Тело | null = null;
    let упёрлась = 0;
    for (const о of с.точки) {
      let лучший = лучДоКонтура(о, с.д, пом.контур) ?? Infinity;
      let ктоТ: Тело | null = null;
      for (const т of заменять) {
        const t = лучВТело(о, с.д, т);
        if (t !== null && t < лучший) {
          лучший = t;
          ктоТ = т;
        }
      }
      if (лучший <= 50) упёрлась++;
      if (лучший < мин) {
        мин = лучший;
        чем = ктоТ;
      }
    }
    return { ...с, мин, чем, упёртаВСтену: упёрлась === с.точки.length };
  });
  // боковая сторона у стены — нормально (кровать «к стене»); обе боковые закрыты — а это уже ошибка
  for (const с of стороныОценка) {
    if (с.упёртаВСтену || с.мин >= НОРМЫ.уКровати || !isFinite(с.мин)) continue;
    const мм = Math.round(НОРМЫ.уКровати - с.мин);
    итог.push(
      замечание({
        правило: 'у-кровати',
        важность: 'предупреждение',
        помещение: пом.id,
        id: к.э.id,
        с: с.чем ? [с.чем.э.id] : undefined,
        мм,
        текст: `У кровати «${имяЭкз(к.э)}» ${с.имя} свободно ${Math.round(с.мин)} мм до ${с.чем ? `«${имяЭкз(с.чем.э)}»` : 'стены'}, нужно не меньше ${НОРМЫ.уКровати} мм, не хватает ${мм} мм`,
      }),
    );
  }
  return итог;
}

/* ------------------------------------------------------------------ итог */

const ВЕС: Record<Важность, number> = { ошибка: 0, предупреждение: 1, совет: 2 };

/** Полная проверка проекта. Сначала ошибки, потом предупреждения, потом советы; внутри — в порядке появления в проекте. */
export function проверитьПроект(п: ПроектV2): Замечание[] {
  const все = [...размерыИСоседи(п), ...проёмы(п), ...секции(п), ...открывание(п), ...проходы(п), ...зазорыВРяду(п), ...кухня(п), ...комнаты(п)];
  const порядок = new Map(п.объекты.map((э, i) => [э.id, i]));
  // одинаковые ключи (две дверцы одного холодильника) различаем номером: ключ нужен списку и переходам
  const видели = new Map<string, number>();
  for (const з of все) {
    const было = видели.get(з.ключ) ?? 0;
    видели.set(з.ключ, было + 1);
    if (было) з.ключ = `${з.ключ}#${было + 1}`;
  }
  return все
    .map((з, i) => ({ з, i }))
    .sort((a, b) => ВЕС[a.з.важность] - ВЕС[b.з.важность] || (порядок.get(a.з.id ?? '') ?? 0) - (порядок.get(b.з.id ?? '') ?? 0) || a.i - b.i)
    .map((x) => x.з);
}

/** Сколько замечаний каждой важности */
export function сводка(з: Замечание[]): Record<Важность, number> {
  return { ошибка: з.filter((x) => x.важность === 'ошибка').length, предупреждение: з.filter((x) => x.важность === 'предупреждение').length, совет: з.filter((x) => x.важность === 'совет').length };
}
