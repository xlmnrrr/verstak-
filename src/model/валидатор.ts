/** Единичный вектор «куда смотрит фасад» в плане: локальная +Z при повороте θ */
export const фронт = (поворот: number): Точка2 => {
  const θ = (поворот * Math.PI) / 180;
  return [-Math.sin(θ), Math.cos(θ)];
};

/** Луч в выпуклый многоугольник (Сайрус—Бек): расстояние до входа или null */
export function лучВМногоугольник(о: Точка2, d: Точка2, поли: Точка2[]): number | null {
  let s = 0;
  for (let i = 0; i < поли.length; i++) {
    const a = поли[i];
    const b = поли[(i + 1) % поли.length];
    s += a[0] * b[1] - b[0] * a[1];
  }
  const знак = s >= 0 ? 1 : -1;
  let t0 = 0;
  let t1 = Infinity;
  for (let i = 0; i < поли.length; i++) {
    const a = поли[i];
    const b = поли[(i + 1) % поли.length];
    const ex = b[0] - a[0];
    const ez = b[1] - a[1];
    const nx = ez * знак;
    const nz = -ex * знак; // наружу
    const denom = nx * d[0] + nz * d[1];
    const num = nx * (a[0] - о[0]) + nz * (a[1] - о[1]);
    if (Math.abs(denom) < 1e-9) {
      if (num < 0) return null; // параллельно и снаружи
      continue;
    }
    const t = num / denom;
    if (denom < 0) t0 = Math.max(t0, t);
    else t1 = Math.min(t1, t);
    if (t0 > t1) return null;
  }
  return t0;
}

/** Ближайшее пересечение луча с контуром помещения (стенами) */
export function лучДоКонтура(о: Точка2, d: Точка2, контур: Точка[]): number | null {
  let лучший: number | null = null;
  for (let i = 0; i < контур.length; i++) {
    const a = контур[i];
    const b = контур[(i + 1) % контур.length];
    const ex = b[0] - a[0];
    const ez = b[1] - a[1];
    const denom = d[0] * ez - d[1] * ex;
    if (Math.abs(denom) < 1e-9) continue;
    const t = ((a[0] - о[0]) * ez - (a[1] - о[1]) * ex) / denom;
    const u = ((a[0] - о[0]) * d[1] - (a[1] - о[1]) * d[0]) / denom;
    if (t > 1e-6 && u >= -1e-9 && u <= 1 + 1e-9 && (лучший === null || t < лучший)) лучший = t;
  }
  return лучший;
}

/** Расстояние между стенами вдоль направления через точку (хорда контура); null — точка вне контура */
export function хорда(контур: Точка[], о: Точка2, d: Точка2): number | null {
  if (!точкаВнутри(контур, о[0], о[1])) return null;
  const вперёд = лучДоКонтура(о, d, контур);
  const назад = лучДоКонтура(о, [-d[0], -d[1]], контур);
  if (вперёд === null || назад === null) return null;
  return вперёд + назад;
}

interface Ящик {
  x0: number;
  x1: number;
  z0: number;
  z1: number;
}
const ящик = (след: Точка[]): Ящик => ({
  x0: Math.min(...след.map((p) => p[0])),
  x1: Math.max(...след.map((p) => p[0])),
  z0: Math.min(...след.map((p) => p[1])),
  z1: Math.max(...след.map((p) => p[1])),
});
/** Расстояние между двумя прямоугольниками по осям (0 — касаются или перекрываются) */
const расстояниеЯщиков = (a: Ящик, b: Ящик) => Math.hypot(Math.max(0, b.x0 - a.x1, a.x0 - b.x1), Math.max(0, b.z0 - a.z1, a.z0 - b.z1));
const перекрытие = (a0: number, a1: number, b0: number, b1: number) => Math.min(a1, b1) - Math.max(a0, b0);

interface Тело {
  э: Экземпляр;
  изд: Изделие;
  /** габаритный след */
  след: Точка[];
  /** выпуклые части следа: у углового модуля — два плеча, у остальных — габарит */
  следы: Точка[][];
  y0: number;
  y1: number;
  ящик: Ящик;
}
const тело = (э: Экземпляр): Тело | null => {
  const изд = изделиеПоИд(э.изделие);
  if (!изд) return null;
  const след = следУглы(э.позиция, э.поворот, э.габариты.ш, э.габариты.г);
  const следы = следыЭкземпляра(изд, э, () => след as Точка2[]) as Точка[][];
  return { э, изд, след, следы, y0: э.позиция[1], y1: э.позиция[1] + э.габариты.в, ящик: ящик(след) };
};

/** Луч до тела: ближайшая из его выпуклых частей */
const лучВТело = (о: Точка2, d: Точка2, т: Тело): number | null => {
  let л: number | null = null;
  for (const ч of т.следы) {
    const t = лучВМногоугольник(о, d, ч as Точка2[]);
    if (t !== null && (л === null || t < л)) л = t;
  }
  return л;
};

