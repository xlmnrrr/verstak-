/**
 * Эталон 3: кровать с подъёмным механизмом. Деталировка (плиты без фурнитуры), подъём основания на 45° у изножья,
 * в плане ничего не выступает (дверцы соседей и проходы не страдают), рендер: матрас и подушки едут с основанием.
 */
import { describe, expect, it } from 'vitest';
import { изделиеПоИд } from './каталог';
import { детали } from './детали';
import { движенияИзделия, позаДвижения, конфликтыПомещения, развёртка } from './открывание';
import { деталиЭкземпляра } from './производство';
import { новоеПомещение, прямоугольник } from './помещение';
import { новыйПроектV2, новыйЭкземпляр } from './проект';
import { проверитьПроект } from './валидатор';
import { примитивыЭкземпляра, примитивыВПозе } from '../render/примитивы';

const изд = () => изделиеПоИд('кровать-подъёмная-1600')!;
const экз = () => ({ ...новыйЭкземпляр(изд(), 'п1'), id: 'к' });

describe('кровать с подъёмным механизмом', () => {
  it('в деталировке — царги, спинка-основа, перегородка, дно ящика, цоколь; рама, ламели и газлифты — фурнитура', () => {
    const строки = деталиЭкземпляра(экз());
    const сколько = (роль: string) => строки.filter((с) => с.роль === роль).reduce((s, с) => s + с.количество, 0);
    expect(сколько('боковина')).toBe(3);
    expect(сколько('спинка')).toBe(1);
    expect(сколько('дно')).toBe(1);
    expect(сколько('цоколь')).toBe(3);
    expect(строки.some((с) => с.роль === 'фурнитура')).toBe(false);
    const д = детали(изд(), экз());
    // ламели берёзы: по одной на ~75 мм длины рамы
    expect(д.filter((x) => x.роль === 'фурнитура' && x.литерал?.цвет === '#d9bd8f').length).toBeGreaterThan(20);
  });

  it('основание поднимается у изножья на 45° вокруг оси у изголовья; в плане ничего не выступает', () => {
    const дв = движенияИзделия(изд(), экз());
    expect(дв).toHaveLength(1);
    const д = дв[0];
    expect(д.группа).toBe('подъёмник-0');
    expect(развёртка(д)).toBeNull();
    const поза = позаДвижения(д, 1);
    // точка изножья рамы поднимается, точка у оси — нет
    const к = д.кинематика;
    if (к.вид !== 'поворот') throw new Error('ожидался поворот');
    const R = поза.R!;
    const о = поза.опора!;
    const точка = (p: [number, number, number]) => {
      const v = [p[0] - о[0], p[1] - о[1], p[2] - о[2]];
      return [о[0] + R[0] * v[0] + R[1] * v[1] + R[2] * v[2], о[1] + R[3] * v[0] + R[4] * v[1] + R[5] * v[2], о[2] + R[6] * v[0] + R[7] * v[1] + R[8] * v[2]];
    };
    const z1 = д.главная.центр[2] + д.главная.объём[2] / 2;
    const y = д.главная.центр[1];
    const L = z1 - о[2];
    expect(точка([0, y, z1])[1] - y).toBeCloseTo(L * Math.sin(Math.PI / 4), -1);
    expect(точка([0, о[1], о[2]])[1]).toBeCloseTo(о[1], 3);
  });

  it('у стены спальни: ни конфликтов открывания, ни замечаний валидатора', () => {
    const п = новыйПроектV2('с', новоеПомещение('п1', 'спальня', 'Спальня', прямоугольник(3600, 3400)));
    п.объекты.push({ ...экз(), позиция: [0, 0, -1700 + 1060], поворот: 0 });
    expect(конфликтыПомещения(п, 'п1')).toEqual([]);
    expect(проверитьПроект(п).map((з) => з.текст)).toEqual([]);
  });

  it('рендер: матрас стёганой тканью и подушки (гладкая ткань, без рисунка) едут с основанием, изголовье — рогожка', () => {
    const р = примитивыЭкземпляра(изд(), экз(), true);
    const м = р.примитивы.filter((x) => x.форма === 'модель');
    const матрас = м.find((x) => x.модель!.класс === 'ткань-стёганая')!;
    expect(матрас.группа).toBe('подъёмник-0');
    const подушки = м.filter((x) => x.модель!.класс === 'ткань');
    expect(подушки.length).toBeGreaterThanOrEqual(3);
    expect(подушки.every((x) => x.группа === 'подъёмник-0')).toBe(true);
    expect(м.some((x) => x.модель!.геом.startsWith('gltf:'))).toBe(false);
    expect(м.some((x) => x.модель!.класс === 'рогожка' && !x.группа)).toBe(true);
    // поза «открыто»: матрас поднимается
    const открыто = примитивыВПозе(р, new Map([['подъёмник-0', 1]])).примитивы.find((x) => x.модель?.класс === 'ткань-стёганая')!;
    expect(открыто.t[1]).toBeGreaterThan(матрас.t[1] + 300);
  });
});

describe('духовка и фурнитура моделями (эталоны 1 и 2)', () => {
  it('духовка: панель из нержавейки, тёмное стекло двери, ручка и стойки в группе двери; вблизи — решётка и лампа', () => {
    const д = изделиеПоИд('духовка-600')!;
    const э = новыйЭкземпляр(д, 'п1');
    const вдали = примитивыЭкземпляра(д, э, false).примитивы.filter((x) => x.форма === 'модель');
    const вблизи = примитивыЭкземпляра(д, э, true).примитивы.filter((x) => x.форма === 'модель');
    expect(вдали.some((x) => x.модель!.класс === 'нержавейка' && !x.группа)).toBe(true);
    expect(вдали.filter((x) => x.модель!.класс === 'стекло-тёмное' && x.группа === 'дверь-0').length).toBeGreaterThan(0);
    expect(вдали.filter((x) => x.модель!.класс === 'нержавейка-пруток' && x.группа === 'дверь-0').length).toBeGreaterThanOrEqual(3);
    expect(вдали.some((x) => x.модель!.класс === 'лампа')).toBe(false);
    expect(вблизи.some((x) => x.модель!.класс === 'лампа')).toBe(true);
    expect(вблизи.filter((x) => x.модель!.класс === 'хром').length).toBeGreaterThan(10);
  });

  it('распашной шкаф: ручки — пруток на двух стойках; вблизи — по 5 петель на дверь выше 2000 (2117) и полкодержатели', () => {
    const ш = изделиеПоИд('шкаф-распашной-900')!;
    const э = новыйЭкземпляр(ш, 'п1');
    const р = примитивыЭкземпляра(ш, э, true).примитивы.filter((x) => x.форма === 'модель');
    const ручки = р.filter((x) => x.модель!.класс === 'нержавейка-пруток' && x.модель!.геом.startsWith('пруток:12,'));
    expect(ручки).toHaveLength(2);
    const чашки = р.filter((x) => x.модель!.геом.startsWith('пруток:35,'));
    expect(чашки).toHaveLength(10);
    // чашки едут с дверью, планки стоят на боковине
    expect(чашки.every((x) => x.группа?.startsWith('дверь-'))).toBe(true);
    expect(р.filter((x) => x.модель!.геом.startsWith('пруток:6,14')).length).toBeGreaterThanOrEqual(8);
    // вдали петель нет
    expect(примитивыЭкземпляра(ш, э, false).примитивы.some((x) => x.модель?.геом.startsWith('пруток:35,'))).toBe(false);
  });
});
