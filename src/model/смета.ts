/**
 * Живая смета: из тех же деталей, что рисует 3D и считает деталировка (`детали()`), поэтому цифры сходятся по построению.
 * Листы считаются по площади плит ЛДСП (без отхода) на лист 2750 × 1830; кромка — сумма длин кромленых сторон.
 */
import { детали } from './детали';
import { изделиеПоИд } from './каталог';
import type { ПроектV2 } from './типы';

export const ЛИСТ_ММ = { длина: 2750, ширина: 1830 };
const ПЛИТНЫЕ = new Set(['боковина', 'дно', 'крыша', 'полка', 'перегородка', 'цоколь', 'фасад', 'ящик-фасад', 'ящик-бок', 'ящик-перед', 'ящик-зад']);

export interface Смета {
  изделий: number;
  деталей: number;
  /** площадь плит ЛДСП, м² */
  плитМ2: number;
  /** листы ЛДСП 2750 × 1830, дробное число */
  листов: number;
  /** кромка, м */
  кромкаМ: number;
  /** ХДФ (задники и дно ящиков), м² */
  хдфМ2: number;
}

export function смета(п: ПроектV2, помещениеId?: string): Смета {
  const р: Смета = { изделий: 0, деталей: 0, плитМ2: 0, листов: 0, кромкаМ: 0, хдфМ2: 0 };
  for (const э of п.объекты) {
    if (помещениеId && э.помещение !== помещениеId) continue;
    const изд = изделиеПоИд(э.изделие);
    if (!изд) continue;
    р.изделий++;
    for (const д of детали(изд, э)) {
      р.деталей++;
      const [длина, ширина, толщина] = д.размер;
      if (д.роль === 'задник' || д.роль === 'ящик-дно') {
        р.хдфМ2 += (длина * ширина) / 1e6;
        continue;
      }
      if (!ПЛИТНЫЕ.has(д.роль) || д.форма !== 'плита' || толщина > 30) continue;
      р.плитМ2 += (длина * ширина) / 1e6;
      const к = д.кромка;
      р.кромкаМ += ((к.длина1 > 0 ? длина : 0) + (к.длина2 > 0 ? длина : 0) + (к.ширина1 > 0 ? ширина : 0) + (к.ширина2 > 0 ? ширина : 0)) / 1000;
    }
  }
  р.листов = р.плитМ2 / ((ЛИСТ_ММ.длина * ЛИСТ_ММ.ширина) / 1e6);
  return р;
}

/** «3,2 листа» с правильным склонением */
export function подписьЛистов(л: number): string {
  const ц = Math.round(л * 10) / 10;
  const цел = Math.abs(ц - Math.round(ц)) < 0.05;
  const н = цел ? Math.round(ц) : ц;
  const текст = String(н).replace('.', ',');
  if (!цел) return `${текст} листа`;
  const m10 = н % 10;
  const m100 = н % 100;
  const слово = m10 === 1 && m100 !== 11 ? 'лист' : m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14) ? 'листа' : 'листов';
  return `${текст} ${слово}`;
}
