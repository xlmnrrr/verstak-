/**
 * Миграция .kitchen v1 → v2.
 * Принцип: ничего не теряется молча. Незнакомый модуль становится «свободным корпусом» с пометкой,
 * незнакомые поля сохраняются в `прочее`, а в конце миграция сама сверяет результат с исходником
 * через мост v2 → v1 и перечисляет расхождения в `потери` (должен быть пустым).
 */
import { z } from 'zod';
import { СхемаПроекта } from '../lib/schema';
import type { Obj, Project } from '../types';
import { изделиеПоИд, ТАБЛИЦА_V1, СВОБОДНЫЙ_КОРПУС } from './каталог';
import { вОбъектV1, смещениеМоста } from './мост-v1';
import { высотаДляРендера, прямоугольник } from './помещение';
import { настройкиПоУмолчанию } from './проект';
import { полокМакс } from './детали';
import { слитьРаскладку } from './раскладка';
import type { Изделие, ПроектV2, Помещение, ТипФасада, Экземпляр, ЧастичнаяРаскладка } from './типы';

export interface ОтчётМиграции {
  из: number;
  объектов: number;
  перенесено: number;
  /** модули, которых нет в каталоге: стали свободными корпусами */
  свободных: { id: string; было: string }[];
  /** поля файла, которых схема не знает: сохранены в `прочее` */
  лишнихПолей: string[];
  /** что изменилось по смыслу, но не потеряно */
  заметки: string[];
  /** расхождения «исходник ↔ результат»: должен быть пустым */
  потери: string[];
}

export interface РезультатМиграции {
  ок: boolean;
  проект?: ПроектV2;
  отчёт: ОтчётМиграции;
  ошибки: string[];
}

const ИЗВЕСТНЫЕ_ВЕРХ = ['schemaVersion', 'название', 'создан', 'изменён', 'комната', 'объекты', 'настройки'];
const ИЗВЕСТНЫЕ_КОМНАТА = ['длина', 'ширина', 'высота_стен', 'толщина_стен', 'форма', 'обои', 'пол', 'фон'];
const ИЗВЕСТНЫЕ_ОБЪЕКТ = [
  'id', 'модуль', 'название', 'позиция', 'поворот', 'наклон_X', 'наклон_Z', 'открыт', 'петли', 'габариты',
  'подъём', 'цвет', 'материал', 'ящиков', 'полок', 'цоколь', 'ножки', 'вид', 'фасад',
];
const ИЗВЕСТНЫЕ_НАСТРОЙКИ = ['шаг_сетки', 'толщина_плиты', 'режим_обзора', 'тема'];

const ТИПЫ_РУС: Record<string, string> = {
  string: 'строка',
  number: 'число',
  boolean: 'да/нет',
  object: 'объект',
  array: 'список',
  undefined: 'ничего',
  null: 'пусто',
};

/** Ошибки zod человеческим языком, с путём до поля */
export function ошибкиZod(ошибка: z.ZodError): string[] {
  return ошибка.issues.map((i) => {
    const путь = i.path.length ? i.path.join('.') : '(корень файла)';
    let текст = i.message;
    if (i.code === 'invalid_type') {
      const ожидалось = ТИПЫ_РУС[(i as { expected?: string }).expected ?? ''] ?? (i as { expected?: string }).expected;
      текст = текст.includes('received undefined') ? `поле обязательно (нужно: ${ожидалось})` : `нужно: ${ожидалось}`;
    }
    return `${путь}: ${текст}`;
  });
}

const лишниеКлючи = (объект: Record<string, unknown>, известные: string[]) =>
  Object.fromEntries(Object.entries(объект).filter(([к]) => !известные.includes(к)));

function экземплярИзV1(о: Obj, сырой: Record<string, unknown>, отчёт: ОтчётМиграции): Экземпляр {
  const идИзделия = ТАБЛИЦА_V1[о.модуль];
  const известный = !!идИзделия;
  const изд: Изделие = изделиеПоИд(идИзделия ?? СВОБОДНЫЙ_КОРПУС)!;
  const экз: Экземпляр = {
    id: о.id,
    изделие: изд.id,
    помещение: 'п1',
    позиция: [о.позиция[0], о.подъём && о.подъём > 0 ? о.подъём : о.позиция[1], о.позиция[2]],
    поворот: о.поворот,
    габариты: { ...о.габариты },
  };
  const метки: string[] = [];

  if (!известный) {
    метки.push(`было:${о.модуль}`);
    отчёт.свободных.push({ id: о.id, было: о.модуль });
  }
  if (о.название !== undefined && о.название !== изд.название) экз.название = о.название;
  if (о.открыт) экз.открыт = true;
  if (о.наклон_X) метки.push(`наклон:X=${о.наклон_X}`);
  if (о.наклон_Z) метки.push(`наклон:Z=${о.наклон_Z}`);
  if (о.вид !== undefined && о.вид !== (изд.v1?.вид ?? 'корпус')) метки.push(`вид:${о.вид}`);
  if (о.цвет !== undefined && о.цвет !== изд.материалы.фасад) экз.материалы = { фасад: о.цвет };
  if (о.материал !== undefined && о.материал !== изд.материал_описание) экз.материал_описание = о.материал;

  // отличия раскладки — только то, что не совпадает с изделием
  const р: ЧастичнаяРаскладка = {};
  const базовая = изд.раскладка;
  if (о.цоколь !== undefined && о.цоколь !== базовая.корпус.цоколь) р.корпус = { ...(р.корпус ?? {}), цоколь: о.цоколь };
  if (о.ножки !== undefined && о.ножки !== базовая.корпус.ножки) р.корпус = { ...(р.корпус ?? {}), ножки: о.ножки };
  if (о.фасад !== undefined && о.фасад !== базовая.фасад.тип) р.фасад = { ...(р.фасад ?? {}), тип: о.фасад as ТипФасада };
  if (о.петли !== undefined && о.петли !== базовая.фасад.петли) р.фасад = { ...(р.фасад ?? {}), петли: о.петли };
  if (о.ящиков !== undefined && о.ящиков !== базовая.фасад.ящиков) р.фасад = { ...(р.фасад ?? {}), ящиков: о.ящиков };
  if (Object.keys(р).length) экз.раскладка = р;

  // полки: сравниваем с тем, что получилось бы у изделия при этих габаритах, цоколе и фасаде
  if (о.полок !== undefined) {
    const текущее = полокМакс(изд, экз);
    if (текущее !== о.полок) {
      const сл = слитьРаскладку(изд.раскладка, экз.раскладка);
      экз.раскладка = {
        ...(экз.раскладка ?? {}),
        секции: сл.секции.map((с) =>
          с.наполнение.направление === 'снизу-вверх' ? { ...с, наполнение: { ...с.наполнение, число: о.полок! } } : с,
        ),
      };
    }
  }

  if (метки.length) экз.метки = метки;
  const лишнее = лишниеКлючи(сырой, ИЗВЕСТНЫЕ_ОБЪЕКТ);
  if (Object.keys(лишнее).length) {
    экз.прочее = лишнее;
    отчёт.лишнихПолей.push(...Object.keys(лишнее).map((к) => `объекты[${о.id}].${к}`));
  }
  return экз;
}

/** Совместимость v1: тема */
const ТЕМА = (т?: string) => (т === 'светлая' ? 'калька' : 'мастерская');

/** Сверка исходного v1 с мостом v2 → v1; возвращает расхождения словами */
export function сверитьСИсходником(исходный: Project, результат: ПроектV2): string[] {
  const потери: string[] = [];
  if (результат.объекты.length !== исходный.объекты.length) {
    потери.push(`число объектов: было ${исходный.объекты.length}, стало ${результат.объекты.length}`);
  }
  const пом = результат.помещения[0];
  const смещение = смещениеМоста(пом);
  результат.объекты.forEach((экз, i) => {
    const был = исходный.объекты[i];
    if (!был) return;
    const стал = вОбъектV1(экз, смещение);
    const где = `объект ${был.id}`;
    const сравнить = (поле: string, a: unknown, b: unknown) => {
      if (JSON.stringify(a) !== JSON.stringify(b)) потери.push(`${где}: ${поле} было ${JSON.stringify(a)}, стало ${JSON.stringify(b)}`);
    };
    сравнить('id', был.id, стал.id);
    const эффективнаяY = был.подъём && был.подъём > 0 ? был.подъём : был.позиция[1];
    сравнить('позиция', [был.позиция[0], эффективнаяY, был.позиция[2]], стал.позиция);
    сравнить('поворот', был.поворот, стал.поворот);
    сравнить('габариты', был.габариты, стал.габариты);
    сравнить('цвет', был.цвет, стал.цвет);
    сравнить('материал', был.материал, стал.материал);
    сравнить('ящиков', был.ящиков ?? 0, стал.ящиков ?? 0);
    сравнить('полок', был.полок ?? 0, стал.полок ?? 0);
    сравнить('цоколь', был.цоколь ?? 0, стал.цоколь ?? 0);
    сравнить('ножки', был.ножки ?? 0, стал.ножки ?? 0);
    сравнить('фасад', был.фасад ?? 'нет', стал.фасад ?? 'нет');
    сравнить('вид', был.вид ?? 'корпус', стал.вид ?? 'корпус');
    сравнить('петли', был.петли ?? 'слева', стал.петли ?? 'слева');
    сравнить('открыт', !!был.открыт, !!стал.открыт);
    сравнить('наклон_X', был.наклон_X ?? 0, стал.наклон_X ?? 0);
    сравнить('наклон_Z', был.наклон_Z ?? 0, стал.наклон_Z ?? 0);
    if (был.название !== undefined) сравнить('название', был.название, стал.название);
    if (изделиеПоИд(экз.изделие) && !экз.метки?.some((м) => м.startsWith('было:'))) {
      сравнить('модуль', был.модуль, стал.модуль);
    }
  });
  const к = исходный.комната;
  const к2 = результат.помещения[0];
  const высота = высотаДляРендера(к2);
  if (высота !== к.высота_стен) потери.push(`высота стен: было ${к.высота_стен}, стало ${высота}`);
  if (к2.отделка.стены !== к.обои) потери.push(`обои: было ${к.обои}, стало ${к2.отделка.стены}`);
  if (к2.отделка.пол !== к.пол) потери.push(`пол: было ${к.пол}, стало ${к2.отделка.пол}`);
  if (к2.толщина_стен !== к.толщина_стен) потери.push(`толщина стен: было ${к.толщина_стен}, стало ${к2.толщина_стен}`);
  return потери;
}

/** Миграция разобранного JSON v1 */
export function мигрироватьV1(сырой: unknown): РезультатМиграции {
  const отчёт: ОтчётМиграции = { из: 1, объектов: 0, перенесено: 0, свободных: [], лишнихПолей: [], заметки: [], потери: [] };
  const разбор = СхемаПроекта.safeParse(сырой);
  if (!разбор.success) return { ок: false, отчёт, ошибки: ошибкиZod(разбор.error) };

  const в1 = разбор.data as unknown as Project;
  const корень = сырой as Record<string, unknown>;
  const сырыеОбъекты = (корень.объекты as Record<string, unknown>[]) ?? [];
  const сырКомната = (корень.комната as Record<string, unknown>) ?? {};
  const к = в1.комната;
  отчёт.объектов = в1.объекты.length;

  const помещение: Помещение = {
    id: 'п1',
    тип: 'кухня',
    название: 'Помещение',
    контур: прямоугольник(к.длина, к.ширина),
    высота: к.высота_стен,
    толщина_стен: к.толщина_стен,
    смещение: [0, 0],
    отметки: [],
    отделка: { стены: к.обои, пол: к.пол },
  };
  if (к.форма !== 'прямоугольник') {
    помещение.метки = [`было:форма ${к.форма}`];
    отчёт.заметки.push(`Форма комнаты «${к.форма}» в v1 рисовалась прямоугольником; перенесён прямоугольник ${к.длина}×${к.ширина}. Контур можно поправить в мастере помещения.`);
  }
  const лишнееКомнаты = лишниеКлючи(сырКомната, ИЗВЕСТНЫЕ_КОМНАТА);
  if (Object.keys(лишнееКомнаты).length) {
    помещение.прочее = лишнееКомнаты;
    отчёт.лишнихПолей.push(...Object.keys(лишнееКомнаты).map((к2) => `комната.${к2}`));
  }

  const объекты = в1.объекты.map((о, i) => экземплярИзV1(о, сырыеОбъекты[i] ?? {}, отчёт));
  отчёт.перенесено = объекты.length;

  const настр = настройкиПоУмолчанию();
  настр.шаг_сетки = в1.настройки?.шаг_сетки ?? настр.шаг_сетки;
  const плита = в1.настройки?.толщина_плиты;
  if (плита === 16 || плита === 18) настр.толщина_плиты = плита;
  else if (плита !== undefined) отчёт.заметки.push(`Толщина плиты ${плита} мм не 16 и не 18; принято 16 мм.`);
  настр.режим_обзора = в1.настройки?.режим_обзора ?? 'сверху';
  настр.тема = в1.настройки?.тема ? ТЕМА(в1.настройки.тема) : 'система';
  if (к.фон) настр.фон = к.фон;

  const проект: ПроектV2 = {
    schemaVersion: 2,
    название: в1.название,
    создан: в1.создан,
    изменён: в1.изменён,
    помещения: [помещение],
    связи: [],
    объекты,
    настройки: настр,
  };
  const лишнее = лишниеКлючи(корень, ИЗВЕСТНЫЕ_ВЕРХ);
  const лишнееНастройки = лишниеКлючи((корень.настройки as Record<string, unknown>) ?? {}, ИЗВЕСТНЫЕ_НАСТРОЙКИ);
  if (Object.keys(лишнее).length || Object.keys(лишнееНастройки).length) {
    проект.прочее = { ...лишнее, ...(Object.keys(лишнееНастройки).length ? { настройки_v1: лишнееНастройки } : {}) };
    отчёт.лишнихПолей.push(...Object.keys(лишнее), ...Object.keys(лишнееНастройки).map((н) => `настройки.${н}`));
  }

  if (отчёт.свободных.length) {
    отчёт.заметки.push(`${отчёт.свободных.length} объектов не узнаны и показаны свободными корпусами (метка «было:…»).`);
  }
  if (!в1.объекты.length) отчёт.заметки.push('В проекте нет ни одного объекта.');

  // самопроверка: результат ↔ исходник
  отчёт.потери = сверитьСИсходником(в1, проект);
  return { ок: true, проект, отчёт, ошибки: [] };
}
