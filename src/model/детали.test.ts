const экземпляр = (изд: Изделие, габ?: Габариты, поворот = 0): Экземпляр => ({
  ...новыйЭкземпляр(изд, 'п1', [0, 0, 0], 'т'),
  габариты: габ ?? { ...изд.габариты },
  поворот,
});

/** Деталь целиком внутри габарита; ручки могут выступать вперёд до ВЫСТУП_РУЧКИ */
function вГабарите(д: Деталь, г: Габариты): string | null {
  const [cx, cy, cz] = д.локально.центр;
  const [dx, dy, dz] = д.локально.объём;
  const e = 0.01;
  const выступ = д.роль === 'ручка' ? ВЫСТУП_РУЧКИ : 0;
  if (cx - dx / 2 < -г.ш / 2 - e || cx + dx / 2 > г.ш / 2 + e) return `X ${cx - dx / 2}…${cx + dx / 2} вне ±${г.ш / 2}`;
  if (cy - dy / 2 < -e || cy + dy / 2 > г.в + e) return `Y ${cy - dy / 2}…${cy + dy / 2} вне 0…${г.в}`;
  if (cz - dz / 2 < -г.г / 2 - e || cz + dz / 2 > г.г / 2 + e + выступ) return `Z ${cz - dz / 2}…${cz + dz / 2} вне ±${г.г / 2}`;
  return null;
}

const размерыПроверки = (изд: Изделие): [string, Габариты][] => [
  ['заводской', изд.габариты],
  ['минимум', изд.границы.мин],
  ['максимум', изд.границы.макс],
  ['мин. ширина', { ...изд.габариты, ш: изд.границы.мин.ш }],
  ['макс. высота', { ...изд.габариты, в: изд.границы.макс.в }],
];

describe('каталог v2', () => {
  it('id уникальны, границы содержат заводские габариты', () => {
    const ид = new Set<string>();
    for (const и of КАТАЛОГ_V2) {
      expect(ид.has(и.id), `повтор id ${и.id}`).toBe(false);
      ид.add(и.id);
      const { мин, макс } = и.границы;
      for (const о of ['ш', 'г', 'в'] as const) {
        expect(и.габариты[о], `${и.id}: ${о} ниже минимума`).toBeGreaterThanOrEqual(мин[о]);
        expect(и.габариты[о], `${и.id}: ${о} выше максимума`).toBeLessThanOrEqual(макс[о]);
      }
    }
  });

  it('все 57 модулей v1 переходят в изделия v2 (таблица соответствия полна)', () => {
    expect(КАТАЛОГ_V1.length).toBe(57);
    for (const м of КАТАЛОГ_V1) {
      const id = ТАБЛИЦА_V1[м.id];
      expect(id, `нет изделия для ${м.id}`).toBeTruthy();
      const и = изделиеПоИд(id)!;
      expect(и, `изделие ${id} не найдено`).toBeTruthy();
      // габариты и границы перенесены без изменений (кроме углового шкафа, ставшего составным)
      if (м.id !== 'corner-1910-1430') {
        expect(и.габариты).toEqual(м.габариты);
        if (м.мин) expect(и.границы.мин).toEqual(м.мин);
        if (м.макс) expect(и.границы.макс).toEqual(м.макс);
      }
    }
  });

  it('в каталоге есть все виды шкафов из плана', () => {
    for (const id of [
      'шкаф-распашной-900', 'шкаф-купе-1800', 'шкаф-угловой-1910-1430', 'шкаф-в-нишу-1200',
      'перегородка-стеллаж-1800', 'гардеробная-система-1800', 'антресоль-1200', 'пенал-450', 'комод-900', 'стеллаж-открытый-800',
    ]) {
      expect(изделиеПоИд(id), id).toBeTruthy();
    }
  });
});

describe('детали(): каждое изделие', () => {
  for (const изд of КАТАЛОГ_V2) {
    it(`${изд.id}: детали внутри габарита на пяти размерах`, () => {
      for (const [имя, габ] of размерыПроверки(изд)) {
        const д = детали(изд, экземпляр(изд, габ));
        expect(д.length, `${изд.id}: нет деталей`).toBeGreaterThan(0);
        for (const деталь of д) {
          for (const v of [...деталь.локально.центр, ...деталь.локально.объём, ...деталь.размер]) {
            expect(Number.isFinite(v), `${изд.id}/${имя}/${деталь.роль}: нечисло`).toBe(true);
          }
          for (const v of деталь.локально.объём) expect(v, `${изд.id}/${имя}/${деталь.роль}: нулевой размер`).toBeGreaterThan(0);
          const ошибка = вГабарите(деталь, габ);
          expect(ошибка, `${изд.id} (${имя}, ${габ.ш}×${габ.г}×${габ.в}), ${деталь.роль}: ${ошибка}`).toBeNull();
        }
      }
    });
  }
});

describe('поворот не меняет раскладку', () => {
  const углы = [0, 90, 180, 270, 37];
  for (const изд of КАТАЛОГ_V2) {
    it(`${изд.id}: детали одинаковы при любом повороте`, () => {
      const база = JSON.stringify(детали(изд, экземпляр(изд)));
      for (const а of углы) expect(JSON.stringify(детали(изд, экземпляр(изд, undefined, а)))).toBe(база);
    });
  }

  it('полки остаются горизонтальными в мире при любом повороте', () => {
    const изд = изделиеПоИд('шкаф-распашной-900')!;
    for (const а of [0, 45, 90, 135, 180, 270, 315]) {
      const экз = экземпляр(изд, undefined, а);
      const полки = детали(изд, экз).filter((д) => д.роль === 'полка');
      expect(полки.length).toBeGreaterThan(0);
      for (const п of полки) {
        const м = вМире(п.локально, [1000, 0, -500], а);
        expect(м.объём[1], `толщина полки по вертикали при ${а}°`).toBe(16);
        expect(м.габарит[1]).toBe(16);
        expect(м.угол).toBe(а);
      }
    }
  });

  it('при 90° фасад смотрит в −X, при 180° — в −Z (как в v1)', () => {
    const изд = изделиеПоИд('шкаф-распашной-900')!;
    const фасад = детали(изд, экземпляр(изд)).find((д) => д.роль === 'фасад')!;
    const м90 = вМире({ центр: [0, 0, фасад.локально.центр[2]], объём: фасад.локально.объём }, [0, 0, 0], 90);
    expect(м90.центр[0]).toBeLessThan(0);
    expect(Math.abs(м90.центр[2])).toBeLessThan(1e-6);
    const м180 = вМире({ центр: [0, 0, фасад.локально.центр[2]], объём: фасад.локально.объём }, [0, 0, 0], 180);
    expect(м180.центр[2]).toBeLessThan(0);
  });
});

describe('полки', () => {
  it('авто-полки совпадают с формулой v1 на сетке высот и цоколей', () => {
    for (let в = 300; в <= 2700; в += 37) {
      for (const ц of [0, 40, 80, 100, 150]) {
        expect(автоПолки(в, ц, 16), `в=${в}, цоколь=${ц}`).toBe(автоПолкиV1(в, ц));
      }
    }
  });

  it('шаг 320 и перестановка 32: центры полок кратны 32 от низа и не ближе 1,5 плиты друг к другу', () => {
    const р = позицииПолок(5, 116, 2100, 16);
    expect(р.length).toBe(5);
    for (let i = 1; i < р.length; i++) expect(р[i] - р[i - 1]).toBeGreaterThanOrEqual(24);
    for (const y of р) expect((y - 116) % 32 === 0, `y=${y}`).toBe(true);
  });

  it('полок не больше, чем влезает вплотную', () => {
    expect(позицииПолок(50, 100, 400, 16).length).toBeLessThanOrEqual(9);
    expect(позицииПолок(3, 100, 100, 16)).toEqual([]);
  });

  it('полки не пересекаются между собой и лежат внутри корпуса (в секциях, на всех размерах)', () => {
    for (const изд of КАТАЛОГ_V2.filter((и) => и.тип === 'корпус')) {
      for (const [, габ] of размерыПроверки(изд)) {
        const полки = детали(изд, экземпляр(изд, габ)).filter((д) => д.роль === 'полка');
        for (let i = 0; i < полки.length; i++) {
          for (let j = i + 1; j < полки.length; j++) {
            const a = полки[i].локально;
            const b = полки[j].локально;
            const пересечение =
              Math.abs(a.центр[0] - b.центр[0]) < (a.объём[0] + b.объём[0]) / 2 - 0.5 &&
              Math.abs(a.центр[1] - b.центр[1]) < (a.объём[1] + b.объём[1]) / 2 - 0.5 &&
              Math.abs(a.центр[2] - b.центр[2]) < (a.объём[2] + b.объём[2]) / 2 - 0.5;
            expect(пересечение, `${изд.id}: полки ${i} и ${j} пересекаются`).toBe(false);
          }
        }
      }
    }
  });

  it('вертикальные перегородки (слева-направо) остаются вертикальными и внутри секции', () => {
    const изд = изделиеПоИд('перегородка-стеллаж-1800')!;
    const д = детали(изд, экземпляр(изд));
    const перегородки = д.filter((x) => x.роль === 'перегородка');
    // две межсекционные + две внутри средней секции
    expect(перегородки.length).toBe(4);
    for (const п of перегородки) {
      expect(п.локально.объём[0], 'толщина по X').toBe(16);
      expect(п.локально.объём[1]).toBeGreaterThan(1000);
    }
    expect(д.filter((x) => x.роль === 'полка').length).toBeGreaterThan(0);
  });

  it('изменённая высота пересчитывает «авто»-полки, фиксированное число остаётся', () => {
    const изд = изделиеПоИд('шкаф-распашной-900')!;
    const низкий = детали(изд, экземпляр(изд, { ...изд.габариты, в: 1200 })).filter((д) => д.роль === 'полка').length;
    const высокий = детали(изд, экземпляр(изд, { ...изд.габариты, в: 2700 })).filter((д) => д.роль === 'полка').length;
    expect(высокий).toBeGreaterThan(низкий);
    const экз = { ...экземпляр(изд), раскладка: { секции: [{ ширина: 'доля' as const, наполнение: { направление: 'снизу-вверх' as const, число: 2, тип: 'регулируемая' as const } }] } };
    expect(детали(изд, экз).filter((д) => д.роль === 'полка').length).toBe(2);
  });
});

describe('деталировка', () => {
  it('нижняя тумба 400: набор деталей и сумма площадей плит', () => {
    const изд = изделиеПоИд('тумба-нижняя-400')!;
    const д = детали(изд, экземпляр(изд));
    const по = (р: string) => д.filter((x) => x.роль === р);
    expect(по('боковина').length).toBe(2);
    expect(по('дно').length).toBe(1);
    expect(по('крыша').length).toBe(1);
    expect(по('задник').length).toBe(1);
    expect(по('цоколь').length).toBe(1);
    expect(по('полка').length).toBe(1);
    expect(по('фасад').length).toBe(1);
    // размеры детали: [длина, ширина, толщина] по убыванию
    for (const x of д) expect(x.размер[0]).toBeGreaterThanOrEqual(x.размер[1]);
    // боковина: высота 720 × глубина (560 − фасад 16), толщина 16
    const б = по('боковина')[0];
    expect(б.размер).toEqual([720, 544, 16]);
    // фасад 400 − 3 мм зазоров по высоте/ширине, толщина 16
    const ф = по('фасад')[0];
    expect(ф.размер[2]).toBe(16);
    expect(ф.размер[0]).toBeCloseTo(720 - 100 - 3, 5);
    expect(ф.размер[1]).toBeCloseTo(400 - 3, 5);
  });

  it('фасады с кромкой 2 мм по периметру, корпус — кромка по передней грани', () => {
    const изд = изделиеПоИд('тумба-нижняя-400')!;
    const д = детали(изд, экземпляр(изд));
    expect(д.find((x) => x.роль === 'фасад')!.кромка).toEqual({ длина1: 2, длина2: 2, ширина1: 2, ширина2: 2 });
    const б = д.find((x) => x.роль === 'боковина')!.кромка;
    expect(б.длина1 + б.длина2 + б.ширина1 + б.ширина2).toBeCloseTo(0.4);
    expect(д.find((x) => x.роль === 'задник')!.кромка).toEqual({ длина1: 0, длина2: 0, ширина1: 0, ширина2: 0 });
  });

  it('ящики: фасад, 2 боковины, передняя и задняя стенки, дно на каждый ящик', () => {
    const изд = изделиеПоИд('тумба-ящики-600')!;
    const д = детали(изд, экземпляр(изд));
    expect(д.filter((x) => x.роль === 'ящик-фасад').length).toBe(3);
    expect(д.filter((x) => x.роль === 'ящик-бок').length).toBe(6);
    expect(д.filter((x) => x.роль === 'ящик-перед').length).toBe(3);
    expect(д.filter((x) => x.роль === 'ящик-зад').length).toBe(3);
    expect(д.filter((x) => x.роль === 'ящик-дно').length).toBe(3);
    expect(д.filter((x) => x.роль === 'полка').length).toBe(0);
  });

  it('купе: створок по ширине, каждая в своей группе открывания', () => {
    const изд = изделиеПоИд('шкаф-купе-2400')!;
    const фасады = детали(изд, экземпляр(изд)).filter((д) => д.роль === 'фасад');
    expect(фасады.length).toBe(3);
    expect(new Set(фасады.map((д) => д.подвижная?.группа)).size).toBe(3);
  });

  it('шкаф в нишу: без боковин, ширина плит равна габариту', () => {
    const изд = изделиеПоИд('шкаф-в-нишу-1200')!;
    const д = детали(изд, экземпляр(изд));
    expect(д.filter((x) => x.роль === 'боковина').length).toBe(0);
    expect(д.find((x) => x.роль === 'крыша')!.локально.объём[0]).toBe(1200);
  });

  it('угловой шкаф: два блока, отвод повёрнут лицом в −X, плиты блоков не пересекаются', () => {
    const изд = изделиеПоИд('шкаф-угловой-1910-1430')!;
    const д = детали(изд, экземпляр(изд));
    const групп = new Set(д.filter((x) => x.подвижная).map((x) => x.подвижная!.группа.split('/')[0]));
    expect(групп.has('основной') || д.length > 0).toBe(true);
    const плиты = д.filter((x) => ['боковина', 'дно', 'крыша', 'перегородка'].includes(x.роль));
    // фасадов отвода нет (фасад «нет»), но проверим главное: основная часть и отвод заняли разные области
    const основнаяЗадняя = Math.min(...плиты.map((x) => x.локально.центр[2] - x.локально.объём[2] / 2));
    expect(основнаяЗадняя).toBeCloseTo(-1430 / 2, 5);
    const правая = Math.max(...плиты.map((x) => x.локально.центр[0] + x.локально.объём[0] / 2));
    expect(правая).toBeCloseTo(1910 / 2, 5);
    const вперёд = Math.max(...плиты.map((x) => x.локально.центр[2] + x.локально.объём[2] / 2));
    expect(вперёд).toBeCloseTo(1430 / 2, 5);
  });
});

describe('ширины секций', () => {
  it('сумма равна доступной, фиксированные не меняются', () => {
    const с = [
      { ширина: 400 as const, наполнение: { направление: 'снизу-вверх' as const, число: 0 as const, тип: 'регулируемая' as const } },
      { ширина: 'доля' as const, наполнение: { направление: 'снизу-вверх' as const, число: 0 as const, тип: 'регулируемая' as const } },
      { ширина: 'доля' as const, вес: 3, наполнение: { направление: 'снизу-вверх' as const, число: 0 as const, тип: 'регулируемая' as const } },
    ];
    const ш = ширинысекций(с, 1600);
    expect(ш[0]).toBe(400);
    expect(ш.reduce((a, b) => a + b, 0)).toBe(1600);
    expect(ш[2]).toBeCloseTo(ш[1] * 3, -1);
  });

  it('слитьРаскладку не меняет исходное изделие', () => {
    const изд = изделиеПоИд('тумба-нижняя-400')!;
    const до = JSON.stringify(изд.раскладка);
    const р = слитьРаскладку(изд.раскладка, { корпус: { цоколь: 150 }, фасад: { ручка: { вид: 'кнопка' } } });
    expect(р.корпус.цоколь).toBe(150);
    expect(р.фасад.ручка.вид).toBe('кнопка');
    expect(JSON.stringify(изд.раскладка)).toBe(до);
  });

  it('полокМакс для изделий v1 равен числу, которое хранил v1', () => {
    for (const м of КАТАЛОГ_V1) {
      const изд = изделиеПоИд(ТАБЛИЦА_V1[м.id])!;
      const ожидалось = м.полки === 'авто' ? автоПолкиV1(м.габариты.в, м.цоколь ?? 0) : (м.полки ?? 0);
      expect(полокМакс(изд, экземпляр(изд)), `${м.id}`).toBe(ожидалось);
    }
  });
});
