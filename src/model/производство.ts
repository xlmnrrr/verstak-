/**
 * Производство: спецификация модулей, деталировка (список деталей с размерами и кромкой), расход ЛДСП, ХДФ и кромки.
 * Всё считается из `детали()` — тех же деталей, что рисует 3D, поэтому цифры сходятся по построению (автотест производство.test.ts).
 */
import { детали } from './детали';
import { изделиеПоИд } from './каталог';
import type { КлючМатериала, ПроектV2, Экземпляр, Изделие } from './типы';
import { ЛИСТ_ММ } from './смета';

/** Роли, которые идут в деталировку как плиты */
export const РОЛИ_ДЕТАЛИРОВКИ = new Set([
  'боковина',
  'дно',
  'крыша',
  'полка',
  'перегородка',
  'задник',
  'цоколь',
  'фасад',
  'ящик-фасад',
  'ящик-бок',
  'ящик-перед',
  'ящик-зад',
  'ящик-дно',
  'столешница',
  'сиденье',
  'спинка',
  'ножка',
]);

export interface СтрокаСпецификации {
  изделие: string;
  название: string;
  помещение: string;
  ш: number;
  г: number;
  в: number;
  количество: number;
}

export interface СтрокаДеталировки {
  /** название изделия, к которому относится деталь */
  изделие: string;
  экземпляр: string;
  роль: string;
  длина: number;
  ширина: number;
  толщина: number;
  количество: number;
  материал: string;
  /** кромка, мм по сторонам: длина1, длина2, ширина1, ширина2 */
  кромка: [number, number, number, number];
}

export interface Расход {
  /** листы ЛДСП 2750 × 1830 без отхода, по толщине плиты */
  листов: Record<string, number>;
  плитМ2: number;
  хдфМ2: number;
  /** кромка, м, по толщине кромки (мм) */
  кромкаМ: Record<string, number>;
  кромкаВсегоМ: number;
  деталей: number;
}

const ИМЯ_МАТЕРИАЛА: Record<string, string> = {
  корпус: 'ЛДСП корпус',
  фасад: 'ЛДСП фасад',
  задник: 'ХДФ',
  столешница: 'Столешница',
  цоколь: 'ЛДСП цоколь',
  ручки: 'Ручки',
};

/** Название материала детали словами (из описания изделия или экземпляра, либо по ключу) */
function материалСловами(э: Экземпляр, изд: Изделие, ключ: string, толщина: number): string {
  const задан = э.материалы?.[ключ as КлючМатериала] ?? изд.материалы[ключ as КлючМатериала];
  const описание = э.материал_описание ?? изд.материал_описание;
  const база = ИМЯ_МАТЕРИАЛА[ключ] ?? ключ;
  const основа = ключ === 'корпус' || ключ === 'фасад' || ключ === 'цоколь' ? (описание ?? 'ЛДСП') : база;
  return `${основа}${задан ? ` (${задан})` : ''}, ${толщина} мм`;
}

const округл = (v: number) => Math.round(v * 10) / 10;

/** Детали одного экземпляра в виде строк деталировки (без объединения одинаковых) */
export function деталиЭкземпляра(э: Экземпляр): СтрокаДеталировки[] {
  const изд = изделиеПоИд(э.изделие);
  if (!изд) return [];
  const имя = э.название ?? изд.название;
  const р: СтрокаДеталировки[] = [];
  for (const д of детали(изд, э)) {
    if (д.форма !== 'плита' || !РОЛИ_ДЕТАЛИРОВКИ.has(д.роль)) continue;
    const [длина, ширина, толщина] = д.размер;
    р.push({
      изделие: имя,
      экземпляр: э.id,
      роль: д.роль,
      длина: округл(длина),
      ширина: округл(ширина),
      толщина: округл(толщина),
      количество: 1,
      материал: материалСловами(э, изд, д.материал, округл(толщина)),
      кромка: [д.кромка.длина1, д.кромка.длина2, д.кромка.ширина1, д.кромка.ширина2],
    });
  }
  return р;
}

/** Деталировка проекта (или помещения): одинаковые детали одного изделия объединены в одну строку с количеством */
export function деталировка(п: ПроектV2, помещениеId?: string): СтрокаДеталировки[] {
  const итог: СтрокаДеталировки[] = [];
  for (const э of п.объекты) {
    if (помещениеId && э.помещение !== помещениеId) continue;
    const строки = new Map<string, СтрокаДеталировки>();
    for (const с of деталиЭкземпляра(э)) {
      const ключ = `${с.роль}|${с.длина}|${с.ширина}|${с.толщина}|${с.материал}|${с.кромка.join(',')}`;
      const есть = строки.get(ключ);
      if (есть) есть.количество += 1;
      else строки.set(ключ, { ...с });
    }
    итог.push(...строки.values());
  }
  return итог;
}

/** Спецификация модулей: одинаковые изделия одного размера объединены */
export function спецификация(п: ПроектV2, помещениеId?: string): СтрокаСпецификации[] {
  const строки = new Map<string, СтрокаСпецификации>();
  for (const э of п.объекты) {
    if (помещениеId && э.помещение !== помещениеId) continue;
    const изд = изделиеПоИд(э.изделие);
    const ключ = `${э.изделие}|${э.габариты.ш}|${э.габариты.г}|${э.габариты.в}|${э.помещение}`;
    const есть = строки.get(ключ);
    if (есть) есть.количество += 1;
    else {
      строки.set(ключ, {
        изделие: э.изделие,
        название: э.название ?? изд?.название ?? э.изделие,
        помещение: п.помещения.find((x) => x.id === э.помещение)?.название ?? э.помещение,
        ш: э.габариты.ш,
        г: э.габариты.г,
        в: э.габариты.в,
        количество: 1,
      });
    }
  }
  return [...строки.values()];
}

/** Расход материалов по деталировке */
export function расход(строки: СтрокаДеталировки[]): Расход {
  const р: Расход = { листов: {}, плитМ2: 0, хдфМ2: 0, кромкаМ: {}, кромкаВсегоМ: 0, деталей: 0 };
  const площадьЛиста = (ЛИСТ_ММ.длина * ЛИСТ_ММ.ширина) / 1e6;
  const м2ПоТолщине: Record<string, number> = {};
  for (const с of строки) {
    р.деталей += с.количество;
    const м2 = (с.длина * с.ширина * с.количество) / 1e6;
    if (с.роль === 'задник' || с.роль === 'ящик-дно') {
      р.хдфМ2 += м2;
      continue;
    }
    if (с.роль === 'столешница' || с.толщина > 30) continue;
    р.плитМ2 += м2;
    м2ПоТолщине[String(с.толщина)] = (м2ПоТолщине[String(с.толщина)] ?? 0) + м2;
    const [д1, д2, ш1, ш2] = с.кромка;
    const метры = ((д1 > 0 ? с.длина : 0) + (д2 > 0 ? с.длина : 0) + (ш1 > 0 ? с.ширина : 0) + (ш2 > 0 ? с.ширина : 0)) * с.количество / 1000;
    for (const [толщ, мм] of [
      [д1, с.длина],
      [д2, с.длина],
      [ш1, с.ширина],
      [ш2, с.ширина],
    ]) {
      if (толщ > 0) р.кромкаМ[String(толщ)] = (р.кромкаМ[String(толщ)] ?? 0) + (мм * с.количество) / 1000;
    }
    р.кромкаВсегоМ += метры;
  }
  for (const [т, м2] of Object.entries(м2ПоТолщине)) р.листов[т] = м2 / площадьЛиста;
  return р;
}
