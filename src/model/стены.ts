/**
 * Стены помещения из контура и отметок (чистая геометрия, мм, без three).
 * Каждое ребро контура даёт стену толщиной `толщина_стен` снаружи внутреннего контура;
 * на выпуклых углах сегмент удлиняется, на вогнутых укорачивается — щелей нет.
 * Проёмы (дверь, окно, арка) режут стену, ниша оставляет тонкую заднюю часть.
 * Розетки, вода, щитки, короб — плитки на внутренней стороне стены.
 */
import { стены as рёбра, высотаДляРендера, type Точка } from './помещение';
import type { Отметка, Помещение } from './типы';

/** Параллелепипед стены. Локальные оси: X вдоль стены, Y вверх, Z — внутренняя нормаль. */
export interface КоробСтены {
  /** центр в осях помещения, мм */
  центр: [number, number, number];
  /** размеры по локальным осям: длина, высота, толщина */
  размер: [number, number, number];
  /** единичный вектор вдоль стены (x, z) */
  вдоль: Точка;
  /** внутренняя нормаль (x, z) */
  нормаль: Точка;
}

export interface Плитка {
  центр: [number, number, number];
  размер: [number, number, number];
  вдоль: Точка;
  нормаль: Точка;
  вид: Отметка['вид'];
}

const ПРОЁМЫ = new Set(['дверь', 'окно', 'арка']);

interface Вырез {
  s0: number;
  s1: number;
  y0: number;
  y1: number;
  /** оставить часть стены толщиной (мм) с внешней стороны; 0 — сквозной проём */
  остаток: number;
}

/** Диапазоны [a,b], оставшиеся от [0,H] после вычитания вырезов */
function твёрдое(H: number, вырезы: Вырез[]): [number, number][] {
  const р = вырезы.map((в) => [Math.max(0, в.y0), Math.min(H, в.y1)] as [number, number]).sort((a, b) => a[0] - b[0]);
  const итог: [number, number][] = [];
  let курсор = 0;
  for (const [a, b] of р) {
    if (a > курсор) итог.push([курсор, a]);
    курсор = Math.max(курсор, b);
  }
  if (курсор < H) итог.push([курсор, H]);
  return итог;
}

export function коробаСтен(п: Помещение): { стены: КоробСтены[]; плитки: Плитка[]; высота: number; высотаНеизвестна: boolean } {
  const H = высотаДляРендера(п);
  const T = п.толщина_стен;
  const р = рёбра(п.контур);
  const n = р.length;
  const стены: КоробСтены[] = [];
  const плитки: Плитка[] = [];

  for (let i = 0; i < n; i++) {
    const с = р[i];
    const пред = р[(i + n - 1) % n];
    const след = р[(i + 1) % n];
    if (с.длина < 1) continue;
    // выступ за углы: ext = −T·(oₚ·d)/(1 + oₚ·oᵢ), o — наружные нормали
    const удлинение = (соседДо: typeof с, соседКуда: typeof с, начало: boolean) => {
      const о1: Точка = [-соседДо.нормаль[0], -соседДо.нормаль[1]];
      const о2: Точка = [-соседКуда.нормаль[0], -соседКуда.нормаль[1]];
      const знам = 1 + о1[0] * о2[0] + о1[1] * о2[1];
      if (Math.abs(знам) < 1e-6) return 0;
      if (начало) return (-T * (о1[0] * с.направление[0] + о1[1] * с.направление[1])) / знам;
      return (T * (о2[0] * с.направление[0] + о2[1] * с.направление[1])) / знам;
    };
    const extA = удлинение(пред, с, true);
    const extB = удлинение(с, след, false);
    const s0 = -extA;
    const s1 = с.длина + extB;

    const вырезы: Вырез[] = [];
    for (const о of п.отметки) {
      if (о.стена !== i) continue;
      if (ПРОЁМЫ.has(о.вид)) {
        вырезы.push({ s0: о.от_угла, s1: о.от_угла + о.ширина, y0: о.от_пола, y1: о.от_пола + о.высота, остаток: 0 });
      } else if (о.вид === 'ниша') {
        const г = Math.min(о.глубина ?? T / 2, T - 10);
        вырезы.push({ s0: о.от_угла, s1: о.от_угла + о.ширина, y0: о.от_пола, y1: о.от_пола + о.высота, остаток: T - г });
      } else {
        const г = о.глубина ?? (о.вид === 'короб' ? 300 : 12);
        const середина = о.от_угла + о.ширина / 2;
        const высотаП = о.вид === 'короб' && о.высота <= 0 ? H : о.высота;
        плитки.push({
          вид: о.вид,
          центр: [
            с.а[0] + с.направление[0] * середина + с.нормаль[0] * (г / 2),
            о.от_пола + высотаП / 2,
            с.а[1] + с.направление[1] * середина + с.нормаль[1] * (г / 2),
          ],
          размер: [Math.max(10, о.ширина), Math.max(10, высотаП), г],
          вдоль: с.направление,
          нормаль: с.нормаль,
        });
      }
    }

    const точки = new Set<number>([s0, s1]);
    for (const в of вырезы) {
      точки.add(Math.min(s1, Math.max(s0, в.s0)));
      точки.add(Math.min(s1, Math.max(s0, в.s1)));
    }
    const ряд = [...точки].sort((a, b) => a - b);

    const добавить = (a: number, b: number, y0: number, y1: number, толщина: number) => {
      if (b - a < 0.5 || y1 - y0 < 0.5) return;
      const середина = (a + b) / 2;
      // толщина измеряется от наружной стороны: центр стены — на T/2 наружу от контура, остаток — ближе к наружной грани
      const сдвиг = -(T - толщина / 2);
      стены.push({
        центр: [
          с.а[0] + с.направление[0] * середина + с.нормаль[0] * сдвиг,
          (y0 + y1) / 2,
          с.а[1] + с.направление[1] * середина + с.нормаль[1] * сдвиг,
        ],
        размер: [b - a, y1 - y0, толщина],
        вдоль: с.направление,
        нормаль: с.нормаль,
      });
    };

    for (let k = 0; k + 1 < ряд.length; k++) {
      const a = ряд[k];
      const b = ряд[k + 1];
      const середина = (a + b) / 2;
      const покрывают = вырезы.filter((в) => в.s0 <= середина && в.s1 >= середина);
      if (!покрывают.length) {
        добавить(a, b, 0, H, T);
        continue;
      }
      // сквозные вырезы убирают материал полностью, ниши — оставляют заднюю часть
      const сквозные = покрывают.filter((в) => в.остаток === 0);
      for (const [y0, y1] of твёрдое(H, сквозные)) {
        const ниши = покрывают.filter((в) => в.остаток > 0 && в.y0 < y1 && в.y1 > y0);
        if (!ниши.length) {
          добавить(a, b, y0, y1, T);
          continue;
        }
        for (const [z0, z1] of твёрдое(y1, ниши.map((в) => ({ ...в, y0: Math.max(в.y0, y0), y1: Math.min(в.y1, y1) })))) {
          if (z1 > y0) добавить(a, b, Math.max(z0, y0), z1, T);
        }
        for (const н of ниши) добавить(a, b, Math.max(н.y0, y0), Math.min(н.y1, y1), н.остаток);
      }
    }
  }
  return { стены, плитки, высота: H, высотаНеизвестна: п.высота === 'неизвестна' };
}
