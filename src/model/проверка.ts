/**
 * Проверка «влезает» и поиск свободного места (чистая геометрия, мм, без three).
 * След экземпляра — прямоугольник габарита, повёрнутый на `поворот`. Допуск касания стены — 2 мм.
 */
import { повернутьТочку } from './геометрия';
import { высотаДляРендера, стены as рёбра, точкаВнутри, type Точка } from './помещение';
import type { Габариты, Изделие, Помещение, ПроектV2, Экземпляр, Вектор3 } from './типы';
import { изделиеПоИд } from './каталог';

export const ДОПУСК_СТЕНЫ = 2;
/** Пересечение корпусов меньше этой глубины не считается ошибкой */
export const ДОПУСК_ПЕРЕСЕЧЕНИЯ = 10;

export type ВидПроблемы = 'вне-помещения' | 'выше-стен' | 'пересечение';

export interface Проблема {
  /** id экземпляра */
  id: string;
  вид: ВидПроблемы;
  /** на сколько мм не влезает */
  мм: number;
  /** второй участник пересечения */
  с?: string;
  /** человеческий текст */
  текст: string;
}

/** Углы следа экземпляра в осях помещения (мм), порядок обхода сохраняется */
export function следУглы(позиция: Вектор3, поворот: number, ш: number, г: number): Точка[] {
  const углы: Точка[] = [
    [-ш / 2, -г / 2],
    [ш / 2, -г / 2],
    [ш / 2, г / 2],
    [-ш / 2, г / 2],
  ];
  return углы.map(([x, z]) => {
    const [rx, rz] = повернутьТочку(x, z, поворот);
    return [позиция[0] + rx, позиция[2] + rz] as Точка;
  });
}

function расстояниеДоОтрезка(p: Точка, a: Точка, b: Точка): number {
  const dx = b[0] - a[0];
  const dz = b[1] - a[1];
  const л2 = dx * dx + dz * dz;
  const t = л2 ? Math.max(0, Math.min(1, ((p[0] - a[0]) * dx + (p[1] - a[1]) * dz) / л2)) : 0;
  return Math.hypot(p[0] - (a[0] + t * dx), p[1] - (a[1] + t * dz));
}

function расстояниеДоКонтура(к: Точка[], p: Точка): number {
  let м = Infinity;
  for (let i = 0; i < к.length; i++) м = Math.min(м, расстояниеДоОтрезка(p, к[i], к[(i + 1) % к.length]));
  return м;
}

/** Точка внутри выпуклого четырёхугольника (углы по кругу) */
function внутриВыпуклого(следа: Точка[], p: Точка): boolean {
  let знак = 0;
  for (let i = 0; i < следа.length; i++) {
    const a = следа[i];
    const b = следа[(i + 1) % следа.length];
    const c = (b[0] - a[0]) * (p[1] - a[1]) - (b[1] - a[1]) * (p[0] - a[0]);
    if (Math.abs(c) < 1e-9) continue;
    const з = c > 0 ? 1 : -1;
    if (знак === 0) знак = з;
    else if (з !== знак) return false;
  }
  return true;
}

/**
 * На сколько мм след выступает за контур помещения (0 — влезает).
 * Углы вне контура дают расстояние до стены; вогнутый угол контура внутри следа (след перекрывает вырез Г/П) —
 * глубину вдавливания.
 */
export function выступЗаКонтур(контур: Точка[], след: Точка[]): number {
  let худший = 0;
  for (const у of след) {
    if (!точкаВнутри(контур, у[0], у[1])) худший = Math.max(худший, расстояниеДоКонтура(контур, у));
  }
  for (const в of контур) {
    if (внутриВыпуклого(след, в)) {
      let глубина = Infinity;
      for (let i = 0; i < след.length; i++) глубина = Math.min(глубина, расстояниеДоОтрезка(в, след[i], след[(i + 1) % след.length]));
      худший = Math.max(худший, глубина);
    }
  }
  return худший > ДОПУСК_СТЕНЫ ? Math.round(худший) : 0;
}

/** Глубина пересечения двух выпуклых четырёхугольников (SAT), 0 — не пересекаются */
export function глубинаПересечения(a: Точка[], b: Точка[]): number {
  let мин = Infinity;
  for (const фигура of [a, b]) {
    for (let i = 0; i < 4; i++) {
      const p = фигура[i];
      const q = фигура[(i + 1) % 4];
      let nx = -(q[1] - p[1]);
      let nz = q[0] - p[0];
      const л = Math.hypot(nx, nz) || 1;
      nx /= л;
      nz /= л;
      let a0 = Infinity;
      let a1 = -Infinity;
      let b0 = Infinity;
      let b1 = -Infinity;
      for (const t of a) {
        const d = t[0] * nx + t[1] * nz;
        a0 = Math.min(a0, d);
        a1 = Math.max(a1, d);
      }
      for (const t of b) {
        const d = t[0] * nx + t[1] * nz;
        b0 = Math.min(b0, d);
        b1 = Math.max(b1, d);
      }
      const перекрытие = Math.min(a1, b1) - Math.max(a0, b0);
      if (перекрытие <= 0) return 0;
      мин = Math.min(мин, перекрытие);
    }
  }
  return мин === Infinity ? 0 : мин;
}

const занимаетМесто = (тип: Изделие['тип'] | undefined) => !!тип && тип !== 'проём' && тип !== 'декор' && тип !== 'свет';
const жёсткое = (тип: Изделие['тип'] | undefined) => тип === 'корпус' || тип === 'техника';

/** Проверка проекта: что не влезает в помещение или в соседей */
/**
 * `только` — проверить лишь эти экземпляры (их выступы и пересечения со всеми остальными). Нужно на жесте:
 * двигается один объект, а полная проверка 200 модулей каждые 120 мс съедала кадр.
 */
export function проверитьВлезает(п: ПроектV2, только?: ReadonlySet<string>): Проблема[] {
  const итог: Проблема[] = [];
  const пом = new Map<string, Помещение>(п.помещения.map((x) => [x.id, x]));
  const следы = new Map<string, Точка[]>();
  const жёсткие: { э: Экземпляр; след: Точка[]; низ: number; верх: number; x0: number; x1: number; z0: number; z1: number }[] = [];

  for (const э of п.объекты) {
    const изд = изделиеПоИд(э.изделие);
    const к = пом.get(э.помещение);
    if (!к) continue;
    const след = следУглы(э.позиция, э.поворот, э.габариты.ш, э.габариты.г);
    следы.set(э.id, след);
    const тип = изд?.тип;
    if (тип === 'проём') continue;
    if (только && !только.has(э.id)) {
      // остальные нужны только как партнёры по пересечению
      if (жёсткое(тип)) {
        const xs = след.map((т) => т[0]);
        const zs = след.map((т) => т[1]);
        жёсткие.push({ э, след, низ: э.позиция[1], верх: э.позиция[1] + э.габариты.в, x0: Math.min(...xs), x1: Math.max(...xs), z0: Math.min(...zs), z1: Math.max(...zs) });
      }
      continue;
    }

    const выступ = выступЗаКонтур(к.контур, след);
    if (выступ > 0) {
      итог.push({ id: э.id, вид: 'вне-помещения', мм: выступ, текст: `Не влезает: выступает за стену на ${выступ} мм` });
    }
    const верх = э.позиция[1] + э.габариты.в;
    const стены = высотаДляРендера(к);
    if (тип !== 'свет' && верх > стены + ДОПУСК_СТЕНЫ) {
      итог.push({ id: э.id, вид: 'выше-стен', мм: Math.round(верх - стены), текст: `Выше стен на ${Math.round(верх - стены)} мм` });
    }
    if (жёсткое(тип)) {
      const xs = след.map((т) => т[0]);
      const zs = след.map((т) => т[1]);
      жёсткие.push({ э, след, низ: э.позиция[1], верх, x0: Math.min(...xs), x1: Math.max(...xs), z0: Math.min(...zs), z1: Math.max(...zs) });
    }
  }

  for (let i = 0; i < жёсткие.length; i++) {
    const a = жёсткие[i];
    const аВыбран = !только || только.has(a.э.id);
    for (let j = i + 1; j < жёсткие.length; j++) {
      const b = жёсткие[j];
      if (только && !аВыбран && !только.has(b.э.id)) continue;
      if (a.э.помещение !== b.э.помещение) continue;
      // быстрый отсев по описывающим прямоугольникам: большинство пар далеко друг от друга
      if (a.x1 <= b.x0 + ДОПУСК_ПЕРЕСЕЧЕНИЯ || b.x1 <= a.x0 + ДОПУСК_ПЕРЕСЕЧЕНИЯ || a.z1 <= b.z0 + ДОПУСК_ПЕРЕСЕЧЕНИЯ || b.z1 <= a.z0 + ДОПУСК_ПЕРЕСЕЧЕНИЯ) continue;
      const по_высоте = Math.min(a.верх, b.верх) - Math.max(a.низ, b.низ);
      if (по_высоте <= ДОПУСК_ПЕРЕСЕЧЕНИЯ) continue;
      const г = глубинаПересечения(a.след, b.след);
      const глубина = Math.min(г, по_высоте);
      if (глубина > ДОПУСК_ПЕРЕСЕЧЕНИЯ) {
        const мм = Math.round(глубина);
        итог.push({ id: a.э.id, вид: 'пересечение', мм, с: b.э.id, текст: `Пересекается с соседним на ${мм} мм` });
        итог.push({ id: b.э.id, вид: 'пересечение', мм, с: a.э.id, текст: `Пересекается с соседним на ${мм} мм` });
      }
    }
  }
  return итог;
}

/**
 * Пометка для чертежа и спецификации: есть ли в проекте пересечения предметов и выступы за стены.
 * Пары пересечений считаются один раз (в списке проблем каждая пара записана дважды). null — всё чисто.
 */
export function пометкаПересечений(п: ПроектV2): string | null {
  const пр = проверитьВлезает(п);
  if (!пр.length) return null;
  const пар = пр.filter((x) => x.вид === 'пересечение').length / 2;
  const выступов = пр.filter((x) => x.вид !== 'пересечение').length;
  const части: string[] = [];
  if (пар > 0) части.push(`есть пересечения: ${пар} ${пар % 10 === 1 && пар % 100 !== 11 ? 'пара' : пар % 10 >= 2 && пар % 10 <= 4 && (пар % 100 < 12 || пар % 100 > 14) ? 'пары' : 'пар'} предметов`);
  if (выступов > 0) части.push(`выступов за стены или выше стен: ${выступов}`);
  const текст = части.join('; ');
  return (текст[0].toUpperCase() + текст.slice(1)) + (п.настройки.свободная_сборка ? ' (включена свободная сборка)' : '');
}

/** Помещается ли след в контур (с допуском касания стены) */
export const следВнутри = (контур: Точка[], позиция: Вектор3, поворот: number, ш: number, г: number): boolean =>
  выступЗаКонтур(контур, следУглы(позиция, поворот, ш, г)) === 0;

export interface Место {
  позиция: Вектор3;
  поворот: number;
}

/**
 * Свободное место для нового изделия: вдоль стен по порядку (задняя стена первой), лицом в комнату,
 * без пересечения с уже стоящими. Нет места — null (вызывающий ставит в центр и предупреждает).
 */
export function найтиМесто(
  п: ПроектV2,
  помещениеId: string,
  габ: Габариты,
  низ: number,
  занимает = true,
): Место | null {
  const к = п.помещения.find((x) => x.id === помещениеId);
  if (!к) return null;
  const соседи = п.объекты
    .filter((о) => о.помещение === помещениеId && занимаетМесто(изделиеПоИд(о.изделие)?.тип))
    .map((о) => ({ след: следУглы(о.позиция, о.поворот, о.габариты.ш, о.габариты.г), низ: о.позиция[1], верх: о.позиция[1] + о.габариты.в }));

  const свободно = (позиция: Вектор3, поворот: number) => {
    const след = следУглы(позиция, поворот, габ.ш, габ.г);
    if (выступЗаКонтур(к.контур, след) > 0) return false;
    if (!занимает) return true;
    for (const с of соседи) {
      const по_высоте = Math.min(с.верх, низ + габ.в) - Math.max(с.низ, низ);
      if (по_высоте <= 1) continue;
      if (глубинаПересечения(с.след, след) > 1) return false;
    }
    return true;
  };

  const ст = рёбра(к.контур);
  const шаг = 50;
  for (const с of ст) {
    if (с.длина < габ.ш) continue;
    const поворот = ((Math.round((Math.atan2(-с.нормаль[0], с.нормаль[1]) * 180) / Math.PI) % 360) + 360) % 360;
    for (let t = габ.ш / 2; t <= с.длина - габ.ш / 2 + 0.01; t += шаг) {
      const x = с.а[0] + с.направление[0] * t + с.нормаль[0] * (габ.г / 2 + 1);
      const z = с.а[1] + с.направление[1] * t + с.нормаль[1] * (габ.г / 2 + 1);
      const позиция: Вектор3 = [Math.round(x), низ, Math.round(z)];
      if (свободно(позиция, поворот)) return { позиция, поворот };
    }
  }
  // середина комнаты, если у стен всё занято
  const xs = к.контур.map((p) => p[0]);
  const zs = к.контур.map((p) => p[1]);
  const x0 = Math.min(...xs);
  const x1 = Math.max(...xs);
  const z0 = Math.min(...zs);
  const z1 = Math.max(...zs);
  for (let z = z0 + габ.г / 2; z <= z1 - габ.г / 2; z += 100) {
    for (let x = x0 + габ.ш / 2; x <= x1 - габ.ш / 2; x += 100) {
      const позиция: Вектор3 = [Math.round(x), низ, Math.round(z)];
      if (свободно(позиция, 0)) return { позиция, поворот: 0 };
    }
  }
  return null;
}

/** Центр контура (в границах), чтобы поставить объект, которому не нашлось места */
export function центрПомещения(к: Помещение): Вектор3 {
  const xs = к.контур.map((p) => p[0]);
  const zs = к.контур.map((p) => p[1]);
  return [Math.round((Math.min(...xs) + Math.max(...xs)) / 2), 0, Math.round((Math.min(...zs) + Math.max(...zs)) / 2)];
}
