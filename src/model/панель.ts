/**
 * Панели и перегородки (пожелание Макара 13.11.2026): одна плита любого размера — перегородка, опора столешницы,
 * полка-панель, фальшпанель; стеклянная перегородка — стекло 8 мм в алюминиевом профиле. Тонкая сторона — та,
 * что меньше других: панель можно сделать и стоячей, и лежачей, просто поменяв габариты или повернув.
 * Плита идёт в деталировку (роль «перегородка», кромка по всем четырём торцам); стекло и профиль — нет (заказываются отдельно).
 */
import type { Вектор3, Габариты, Деталь, Изделие, Кромка } from './типы';

const ок = (v: number) => Math.round(v * 100) / 100;
const крВся = (мм: number): Кромка => ({ длина1: мм, длина2: мм, ширина1: мм, ширина2: мм });
const кр0 = (): Кромка => ({ длина1: 0, длина2: 0, ширина1: 0, ширина2: 0 });

function д(роль: Деталь['роль'], ц: Вектор3, о: Вектор3, материал: Деталь['материал'], кромка: Кромка, доп: Partial<Деталь> = {}): Деталь {
  const размер = [...о].sort((a, b) => b - a) as Вектор3;
  return { роль, размер: [ок(размер[0]), ок(размер[1]), ок(размер[2])], кромка, материал, локально: { центр: [ок(ц[0]), ок(ц[1]), ок(ц[2])], объём: [ок(о[0]), ок(о[1]), ок(о[2])] }, форма: 'плита', ...доп };
}

const АЛЮМИНИЙ = { цвет: '#c9ccd1', шер: 0.3, мет: 0.9 };

export function деталиПанели(изд: Изделие, габ: Габариты): Деталь[] {
  const { ш: W, г: G, в: H } = габ;
  const мат = изд.вариант === 'стекло' ? 'стекло' : изд.вариант === 'столешница' ? 'столешница' : изд.вариант === 'фасад' ? 'фасад' : 'корпус';
  if (мат !== 'стекло') return [д('перегородка', [0, H / 2, 0], [W, H, G], мат, крВся(мат === 'столешница' ? 1 : 2))];
  // стеклянная перегородка: профиль 20 мм по периметру большой грани, стекло 8 мм в пазу
  const тонкая = Math.min(W, G) === G ? 'z' : 'x';
  const п = Math.min(20, H / 4, (тонкая === 'z' ? W : G) / 4);
  const t = Math.min(8, Math.min(W, G));
  const итог: Деталь[] = [];
  if (тонкая === 'z') {
    итог.push(д('стекло', [0, H / 2, 0], [Math.max(1, W - п), Math.max(1, H - п), t], 'стекло', кр0()));
    for (const s of [-1, 1]) итог.push({ ...д('фурнитура', [0, H / 2 + s * (H / 2 - п / 2), 0], [W, п, G], 'ручки', кр0()), литерал: АЛЮМИНИЙ });
    for (const s of [-1, 1]) итог.push({ ...д('фурнитура', [s * (W / 2 - п / 2), H / 2, 0], [п, Math.max(1, H - 2 * п), G], 'ручки', кр0()), литерал: АЛЮМИНИЙ });
  } else {
    итог.push(д('стекло', [0, H / 2, 0], [t, Math.max(1, H - п), Math.max(1, G - п)], 'стекло', кр0()));
    for (const s of [-1, 1]) итог.push({ ...д('фурнитура', [0, H / 2 + s * (H / 2 - п / 2), 0], [W, п, G], 'ручки', кр0()), литерал: АЛЮМИНИЙ });
    for (const s of [-1, 1]) итог.push({ ...д('фурнитура', [0, H / 2, s * (G / 2 - п / 2)], [W, Math.max(1, H - 2 * п), п], 'ручки', кр0()), литерал: АЛЮМИНИЙ });
  }
  return итог;
}
