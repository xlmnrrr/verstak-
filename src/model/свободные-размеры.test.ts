/**
 * Пожелания Макара 13.11.2026: любой объект — любого размера (границы изделия — подсказка), угол открывания,
 * заданный в свойствах, доходит до 3D (баг: 90° в поле, а дверца открывалась на 100°).
 */
import { describe, expect, it } from 'vitest';
import { КАТАЛОГ_V2, изделиеПоИд } from './каталог';
import { детали } from './детали';
import { деталиЭкземпляра } from './производство';
import { новыйЭкземпляр, ограничитьГабариты, РАЗМЕР_МИН, РАЗМЕР_МАКС } from './проект';
import { примитивыЭкземпляра } from '../render/примитивы';

describe('свободные размеры', () => {
  it('пенал 600×2200: ширина 275 — без подрезки, только подсказка «обычно …»', () => {
    const изд = изделиеПоИд('пенал-кухонный-600') ?? КАТАЛОГ_V2.find((и) => и.id.startsWith('пенал'))!;
    const р = ограничитьГабариты(изд, { ш: 275, г: 398, в: 2181 });
    expect(р.габариты).toEqual({ ш: 275, г: 398, в: 2181 });
    expect(р.подрезано).toEqual([]);
    // за физические пределы — подрезка с цифрами
    const к = ограничитьГабариты(изд, { ш: 5, г: 99999, в: 2181 });
    expect(к.габариты.ш).toBe(РАЗМЕР_МИН);
    expect(к.габариты.г).toBe(РАЗМЕР_МАКС);
    expect(к.подрезано.length).toBe(2);
  });

  it('каждое изделие каталога при крайних размерах: детали конечные и неотрицательные, деталировка и 3D строятся', () => {
    const размеры = [
      { ш: РАЗМЕР_МИН, г: РАЗМЕР_МИН, в: РАЗМЕР_МИН },
      { ш: 275, г: 398, в: 2181 },
      { ш: 5000, г: 900, в: 3000 },
    ];
    for (const изд of КАТАЛОГ_V2) {
      for (const габ of размеры) {
        const э = { ...новыйЭкземпляр(изд, 'п1'), габариты: габ };
        const д = детали(изд, э);
        for (const x of д) {
          for (const v of [...x.размер, ...x.локально.объём, ...x.локально.центр]) expect(Number.isFinite(v), `${изд.id} ${JSON.stringify(габ)} ${x.роль}`).toBe(true);
          for (const v of x.локально.объём) expect(v, `${изд.id} ${JSON.stringify(габ)} ${x.роль}`).toBeGreaterThanOrEqual(0);
        }
        for (const с of деталиЭкземпляра(э)) expect(с.длина * с.ширина * с.толщина >= 0, изд.id).toBe(true);
        expect(() => примитивыЭкземпляра(изд, э, true)).not.toThrow();
      }
    }
  });
});

describe('угол открывания из свойств доходит до 3D', () => {
  it('сменили 100° → 90°: движение в рисуемом результате — 90°, без перезапуска', () => {
    const изд = изделиеПоИд('пенал-450')!;
    const э = новыйЭкземпляр(изд, 'п1');
    const угол = (x: typeof э) => {
      const к = примитивыЭкземпляра(изд, x).движения[0].кинематика;
      return к.вид === 'поворот' ? Math.abs(к.угол) : 0;
    };
    expect(угол(э)).toBe(100);
    expect(угол({ ...э, угол_открывания: 90 })).toBe(90);
    expect(угол({ ...э, угол_открывания: 120 })).toBe(120);
  });
});
