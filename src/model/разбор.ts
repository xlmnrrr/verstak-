const начинается = (э: Экземпляр, ...префиксы: string[]) => префиксы.some((x) => э.изделие.startsWith(x));

function неудобстваКухни(п: ПроектV2, пом: Помещение): ПунктРазбора[] {
  const итог: ПунктРазбора[] = [];
  const все = п.объекты.filter((э) => э.помещение === пом.id);
  const мойка = все.find((э) => начинается(э, 'мойка', 'тумба-под-мойку'));
  const тумбаМойки = все.find((э) => начинается(э, 'тумба-под-мойку')) ?? мойка;
  const варочная = все.find((э) => начинается(э, 'варочная', 'плита'));
  const холод = все.filter((э) => начинается(э, 'холодильник', 'морозильник'));
  const пмм = все.find((э) => начинается(э, 'посудомойка'));
  const вытяжка = все.find((э) => начинается(э, 'вытяжка'));
  const ст = стеныПлана(пом);
  const отметки = отметкиСПредметами(п, пом);
  const пункт = (п2: Omit<ПунктРазбора, 'раздел' | 'помещение'>) => итог.push({ ...п2, раздел: 'неудобно', помещение: пом.id });

  // 1. мойка далеко от воды
  const вода = отметки.filter((о) => о.вид === 'вода' || о.вид === 'канализация');
  if (тумбаМойки && вода.length) {
    const д = Math.min(...вода.map((о) => {
      const т = точкаСтены(ст[о.стена], о.от_угла + о.ширина / 2, 0);
      return Math.hypot(т[0] - тумбаМойки.позиция[0], т[1] - тумбаМойки.позиция[2]);
    }));
    if (д > 1500) {
      const перепад = Math.round((д / 1000) * 20);
      пункт({ важность: 'совет', заголовок: 'Мойка далеко от воды', что: `От ${кав(тумбаМойки)} до точки воды ${Math.round(д)} мм.`, предлагаю: `Перенести мойку ближе к воде: до 1500 мм не хватает ${Math.round(д - 1500)} мм.`, почему: `Слив идёт с уклоном 2 %: на ${(д / 1000).toFixed(1).replace('.', ',')} м это ${перепад} мм перепада под тумбой, длинный слив засоряется.`, предметы: [тумбаМойки.id], мм: Math.round(д - 1500) });
    }
  }
  // 2. посудомойка не у мойки
  if (пмм && тумбаМойки) {
    const г = зазорМежду(пмм, тумбаМойки);
    if (г > 600) пункт({ важность: 'совет', заголовок: 'Посудомойка далеко от мойки', что: `Между ${кав(пмм)} и ${кав(тумбаМойки)} ${Math.round(г)} мм.`, предлагаю: `Поставить посудомойку вплотную к тумбе мойки (сдвинуть на ${Math.round(г)} мм или поменять местами с соседним модулем).`, почему: 'Шланги и слив посудомойки короткие — её ставят рядом с мойкой; тарелки из мойки — сразу в машину.', предметы: [пмм.id, тумбаМойки.id], мм: Math.round(г) });
  }
  // 3. плита у стены или высокого и под окном
  if (варочная) {
    const з2 = кратен90(варочная.поворот) ? зазоры(п, варочная) : undefined;
    const ось = осьШ(варочная);
    const стороны = Math.abs(ось[0]) > 0.5 ? (['xМинус', 'xПлюс'] as const) : (['zМинус', 'zПлюс'] as const);
    for (const к of стороны) {
      const пр = з2?.[к];
      if (!пр || пр.мм >= 300) continue;
      if (пр.преграда.вид === 'сосед' && пр.преграда.y1 < 1000) continue; // низкий сосед — это рабочая поверхность
      const кто = пр.преграда.вид === 'стена' ? 'стены' : `«${пр.преграда.название}»`;
      пункт({ важность: 'совет', заголовок: 'Плита вплотную к стене или высокому', что: `От ${кав(варочная)} до ${кто} ${Math.round(пр.мм)} мм.`, предлагаю: `Отодвинуть варочную от ${кто} на ${Math.round(300 - пр.мм)} мм (до 300 мм).`, почему: 'Ручки кастрюль упираются, стена и боковина пенала греются и желтеют.', предметы: [варочная.id, ...(пр.преграда.id ? [пр.преграда.id] : [])], мм: Math.round(300 - пр.мм) });
    }
    for (const о of отметки.filter((x) => x.вид === 'окно')) {
      const [s, t] = вОсиСтены(ст[о.стена], центр(варочная));
      if (t > 900 || s < о.от_угла - 100 || s > о.от_угла + о.ширина + 100) continue;
      const сдвиг = Math.round(Math.min(s - (о.от_угла - 400), о.от_угла + о.ширина + 400 - s));
      пункт({ важность: 'совет', заголовок: 'Плита под окном', что: `${кав(варочная)} под окном (${имяСтены(пом, о.стена)}, ${о.от_угла}–${о.от_угла + о.ширина} мм).`, предлагаю: `Сдвинуть варочную вдоль стены на ${сдвиг} мм, чтобы до края окна было 300 мм, или поменять местами с мойкой.`, почему: 'Сквозняк гасит газ, занавеска и створка окна рядом с огнём — пожар.', предметы: [варочная.id], мм: сдвиг });
    }
    // вытяжка
    const верхВарочной = варочная.позиция[1] + варочная.габариты.в;
    if (!вытяжка) пункт({ важность: 'совет', заголовок: 'Нет вытяжки', что: `Над ${кав(варочная)} нет вытяжки.`, предлагаю: `Поставить вытяжку ${варочная.габариты.ш >= 700 ? 900 : 600} мм, низ на ${Math.round(верхВарочной + 700)} мм (700 мм над конфорками).`, почему: 'Без вытяжки жир оседает на навесных и потолке.', предметы: [варочная.id] });
    else {
      const над = Math.round(вытяжка.позиция[1] - верхВарочной);
      if (над < 650 || над > 850) {
        const цель = над < 650 ? 650 : 850;
        пункт({ важность: 'совет', заголовок: 'Высота вытяжки', что: `${кав(вытяжка)} на ${над} мм над конфорками.`, предлагаю: `${над < 650 ? 'Поднять' : 'Опустить'} вытяжку на ${Math.abs(цель - над)} мм (низ на ${Math.round(верхВарочной + цель)}).`, почему: 'Ниже 650 — греется и мешает, выше 850 — не тянет пар.', предметы: [вытяжка.id, варочная.id], мм: Math.abs(цель - над) });
      }
    }
  }
  // 4. холодильник рядом с плитой
  for (const х of холод) {
    if (!варочная) continue;
    const тумбаПлиты = все.find((э) => начинается(э, 'тумба-под-плиту', 'плита', 'духовка')) ?? варочная;
    const г = зазорМежду(х, тумбаПлиты);
    if (г < 300) пункт({ важность: 'совет', заголовок: 'Холодильник рядом с плитой', что: `Между ${кав(х)} и ${кав(тумбаПлиты)} ${Math.round(г)} мм.`, предлагаю: `Развести на ${Math.round(300 - г)} мм: поставить между ними модуль 300 мм или перенести холодильник в конец ряда.`, почему: 'Боковина холодильника греется от плиты — компрессор работает без остановки.', предметы: [х.id, тумбаПлиты.id], мм: Math.round(300 - г) });
  }
  // 5. нет посудомойки, хотя рядом с мойкой стоит тумба 450–600, которую можно заменить
  if (!пмм && тумбаМойки) {
    const сосед = все
      .filter((э) => э.id !== тумбаМойки.id && изделиеПоИд(э.изделие)?.тип === 'корпус' && изделиеПоИд(э.изделие)?.крепление === 'пол' && э.габариты.в <= 900 && э.габариты.ш >= 450 && э.габариты.ш <= 600)
      .map((э) => ({ э, г: зазорМежду(э, тумбаМойки) }))
      .filter((x) => x.г < 5)
      .sort((a, b) => b.э.габариты.ш - a.э.габариты.ш)[0];
    if (сосед) пункт({ важность: 'совет', заголовок: 'Нет посудомойки', что: `В кухне нет посудомойки; рядом с ${кав(тумбаМойки)} стоит ${кав(сосед.э)} ${сосед.э.габариты.ш} мм.`, предлагаю: `Поставить посудомойку ${сосед.э.габариты.ш >= 600 ? 600 : 450} мм вместо ${кав(сосед.э)}: место, вода и слив уже рядом.`, почему: 'Посудомойку ставят вплотную к мойке; позже встроить её без переделки ряда не получится.', предметы: [сосед.э.id, тумбаМойки.id] });
  }
  return итог;
}

/** Полки, створки, штанги, шкаф до потолка, щели у стен, розетки за корпусами */
function неудобстваХранения(п: ПроектV2, пом: Помещение): ПунктРазбора[] {
  const итог: ПунктРазбора[] = [];
  const H = высотаДляРендера(пом);
  const пункт = (п2: Omit<ПунктРазбора, 'раздел' | 'помещение'>) => итог.push({ ...п2, раздел: 'неудобно', помещение: пом.id });
  for (const э of п.объекты.filter((x) => x.помещение === пом.id)) {
    const изд = изделиеПоИд(э.изделие);
    if (!изд || (изд.тип !== 'корпус' && изд.тип !== 'техника')) continue;
    // щель или пустое место у стены — у корпусов и напольной техники
    if (кратен90(э.поворот) && изд.крепление === 'пол' && э.позиция[1] < 50) {
      const з2 = зазоры(п, э);
      const ось = осьШ(э);
      for (const к of Math.abs(ось[0]) > 0.5 ? (['xМинус', 'xПлюс'] as const) : (['zМинус', 'zПлюс'] as const)) {
        const пр = з2[к];
        if (!пр || пр.преграда.вид !== 'стена' || пр.мм < 3 || пр.мм > 450) continue;
        const мм = Math.round(пр.мм);
        if (мм <= 150) пункт({ важность: 'совет', заголовок: 'Щель у стены', что: `Между ${кав(э)} и стеной ${мм} мм.`, предлагаю: изд.тип === 'корпус' ? `Растянуть ${кав(э)} на ${мм} мм (ширина ${э.габариты.ш} → ${э.габариты.ш + мм}) или закрыть планкой ${мм} мм.` : `Закрыть щель планкой ${мм} мм или сдвинуть ${кав(э)} к стене (петли — от стены).`, почему: 'Щель у стены видна и собирает пыль; до 150 мм её закрывают корпусом или планкой.', предметы: [э.id], мм });
        else пункт({ важность: 'совет', заголовок: 'Пустое место у стены', что: `Между ${кав(э)} и стеной ${мм} мм пустого места.`, предлагаю: `Поставить в проём бутылочницу ${мм >= 300 ? Math.min(мм, 400) : мм} мм на всю высоту ряда или сдвинуть ${кав(э)} к стене на ${мм} мм${изд.тип === 'техника' ? ' (петли — от стены, тогда дверца откроется на 110°)' : ''}.`, почему: `${мм} мм у стены — это место под узкий модуль; пустой карман собирает мусор.`, предметы: [э.id], мм });
      }
    }
    if (изд.тип !== 'корпус') continue;
    const р = слитьРаскладку(изд.раскладка, э.раскладка);
    const дд = детали(изд, э);
    // полки длиннее 900 (16 мм) / 1000 (18 мм) прогибаются
    const предел = р.корпус.плита === 18 ? 1000 : 900;
    const длинные = дд.filter((д) => д.роль === 'полка' && д.размер[0] > предел + 1);
    if (длинные.length) {
      const L = Math.round(длинные[0].размер[0]);
      const куски = Math.ceil(L / предел);
      пункт({ важность: 'совет', заголовок: 'Длинные полки прогнутся', что: `${кав(э)}: ${длинные.length} ${скл(длинные.length, 'полка', 'полки', 'полок')} по ${L} мм при плите ${р.корпус.плита} мм.`, предлагаю: `Добавить ${куски - 1} ${скл(куски - 1, 'перегородку', 'перегородки', 'перегородок')}: полки станут по ${Math.round((L - (куски - 1) * р.корпус.плита) / куски)} мм.`, почему: `ЛДСП ${р.корпус.плита} мм длиннее ${предел} мм провисает под книгами и посудой за год.`, предметы: [э.id] });
    }
    // распашные створки шире 600
    if (р.фасад.тип === 'распашной' || р.фасад.тип === 'зеркало' || р.фасад.тип === 'стекло') {
      const широкие = дд.filter((д) => д.роль === 'фасад' && д.локально.объём[0] > 601);
      if (широкие.length) {
        const ш = Math.round(широкие[0].локально.объём[0]);
        const надо = Math.ceil(э.габариты.ш / 600);
        пункт({ важность: 'совет', заголовок: 'Широкие створки', что: `${кав(э)}: ${широкие.length} ${скл(широкие.length, 'створка', 'створки', 'створок')} по ${ш} мм.`, предлагаю: `${надо} ${скл(надо, 'створка', 'створки', 'створок')} по ${Math.round(э.габариты.ш / надо)} мм.`, почему: 'Створка шире 600 мм тяжела для двух петель и при открывании перегораживает проход.', предметы: [э.id] });
      }
    }
    // штанга в мелком шкафу
    if (р.секции.some((с) => с.наполнение.штанга) && э.габариты.г < 550) {
      пункт({ важность: 'совет', заголовок: 'Плечики не встанут', что: `${кав(э)}: штанга при глубине ${э.габариты.г} мм.`, предлагаю: `Глубина ${кав(э)} до 550 мм (+${550 - э.габариты.г}) или торцевая выдвижная штанга вместо продольной.`, почему: 'Плечики 450 мм плюс двери: продольной штанге нужна глубина корпуса от 550 мм.', предметы: [э.id], мм: 550 - э.габариты.г });
    }
    // высокий шкаф не до потолка
    if (изд.крепление !== 'стена' && э.габариты.в >= 1800) {
      const до = H - (э.позиция[1] + э.габариты.в);
      if (до > 100 && до < 450) пункт({ важность: 'совет', заголовок: 'Щель над шкафом', что: `Над ${кав(э)} до потолка ${Math.round(до)} мм.`, предлагаю: `Поднять ${кав(э)} до ${Math.round(H - 50)} мм (+${Math.round(до - 50)}) или закрыть планкой ${Math.round(до)} мм.`, почему: 'Узкая щель под потолком собирает пыль, а для антресоли мала; 50 мм оставляют на сборку наклоном.', предметы: [э.id], мм: Math.round(до - 50) });
    }
  }
  return итог;
}

/** Розетки, выключатели и вода за высокими корпусами */
function закрытыеТочки(п: ПроектV2, пом: Помещение): ПунктРазбора[] {
  const итог: ПунктРазбора[] = [];
  const ст = стеныПлана(пом);
  for (const о of пом.отметки) {
    if (!['розетка', 'выключатель', 'щиток'].includes(о.вид)) continue;
    const с = ст[о.стена];
    if (!с) continue;
    const т = точкаСтены(с, о.от_угла + о.ширина / 2, 10);
    const кто = п.объекты.find((э) => {
      if (э.помещение !== пом.id) return false;
      const изд = изделиеПоИд(э.изделие);
      if (!изд || (изд.тип !== 'корпус' && изд.тип !== 'техника')) return false;
      const dx = т[0] - э.позиция[0];
      const dz = т[1] - э.позиция[2];
      const θ = (э.поворот * Math.PI) / 180;
      const lx = dx * Math.cos(θ) + dz * Math.sin(θ);
      const lz = -dx * Math.sin(θ) + dz * Math.cos(θ);
      return Math.abs(lx) <= э.габариты.ш / 2 && Math.abs(lz) <= э.габариты.г / 2 + 20 && о.от_пола + о.высота > э.позиция[1] && о.от_пола < э.позиция[1] + э.габариты.в;
    });
    if (!кто) continue;
    const щиток = о.вид === 'щиток';
    итог.push({
      раздел: 'неудобно',
      важность: щиток ? 'предупреждение' : 'совет',
      заголовок: щиток ? 'Щиток внутри шкафа' : `${о.вид === 'розетка' ? 'Розетка' : 'Выключатель'} за корпусом`,
      что: `${о.вид[0].toUpperCase()}${о.вид.slice(1)} на ${о.от_пола} мм от пола (${имяСтены(пом, о.стена)}, ${о.от_угла} мм от угла) — за ${кав(кто)}.`,
      предлагаю: щиток ? `В зоне ${о.от_угла}–${о.от_угла + о.ширина} мм по стене и ${о.от_пола}–${о.от_пола + о.высота} по высоте — без задней стенки и полок, доступ через створку.` : `Вырез ${о.ширина + 20} × ${о.высота + 20} мм в задней стенке ${кав(кто)} на ${о.от_пола} мм от пола или перенести розетку на ${Math.round(кто.позиция[1] + кто.габариты.в + 100)} мм.`,
      почему: щиток ? 'К щитку электрик должен подойти без разборки шкафа.' : 'Розетка за корпусом без выреза не работает, а вилка упирается в заднюю стенку.',
      предметы: [кто.id],
      помещение: пом.id,
    });
  }
  return итог;
}


/** Полный разбор проекта: нормы (из валидатора) + неудобства, с предложениями в мм */
export function разобратьПроект(п: ПроектV2): Разбор {
  const замечания = проверитьПроект(п);
  const пункты: ПунктРазбора[] = [];
  for (const з of замечания) {
    const пр = предложитьПоЗамечанию(п, з);
    пункты.push({ ...пр, раздел: 'нормы', важность: з.важность, помещение: з.помещение });
  }
  for (const пом of п.помещения) {
    if (пом.тип === 'кухня') пункты.push(...неудобстваКухни(п, пом));
    пункты.push(...неудобстваХранения(п, пом), ...закрытыеТочки(п, пом));
  }
  const с = смета(п);
  const св = сводка(замечания);
  const столешница = п.объекты.filter((э) => изделиеПоИд(э.изделие)?.тип === 'столешница' && !э.изделие.startsWith('подоконник')).reduce((s, э) => s + э.габариты.ш, 0);
  const норм = пункты.filter((x) => x.раздел === 'нормы').length;
  const неуд = пункты.length - норм;
  return {
    проект: п.название,
    числа: { изделий: с.изделий, деталей: с.деталей, листов: Math.round(с.листов * 10) / 10, кромкаМ: Math.round(с.кромкаМ * 10) / 10, столешницаМ: Math.round(столешница / 100) / 10, ошибок: св.ошибка, предупреждений: св.предупреждение, советов: св.совет },
    пункты,
    итог: норм + неуд === 0 ? 'Нарушений норм и неудобств не найдено.' : `${норм} ${скл(норм, 'нарушение норм', 'нарушения норм', 'нарушений норм')}, ${неуд} ${скл(неуд, 'неудобство', 'неудобства', 'неудобств')}.`,
  };
}

/** Разбор текстом (Markdown): для «Сохранить отчёт» и чтобы отдать клиенту */
export function разборТекстом(р: Разбор, имяПомещения: (id: string) => string = (id) => id): string {
  const ч = р.числа;
  const стр: string[] = [
    `# Разбор проекта «${р.проект}»`,
    '',
    `Изделий ${ч.изделий}, деталей ${ч.деталей}, листов ЛДСП ${String(ч.листов).replace('.', ',')}, кромки ${String(ч.кромкаМ).replace('.', ',')} м, столешницы ${String(ч.столешницаМ).replace('.', ',')} м.`,
    `Замечаний валидатора: ошибок ${ч.ошибок}, предупреждений ${ч.предупреждений}, советов ${ч.советов}.`,
    '',
    `**Итог:** ${р.итог}`,
  ];
  for (const [раздел, заголовок] of [['нормы', 'Нарушает нормы'], ['неудобно', 'Неудобно']] as const) {
    const пп = р.пункты.filter((x) => x.раздел === раздел);
    стр.push('', `## ${заголовок} (${пп.length})`);
    if (!пп.length) стр.push('', 'Нет.');
    пп.forEach((x, i) => {
      стр.push('', `${i + 1}. **${x.заголовок}** (${x.важность}, ${имяПомещения(x.помещение)})`, `   - Что: ${x.что}`, `   - Предлагаю: ${x.предлагаю}`, `   - Почему: ${x.почему}`);
    });
  }
  return стр.join('\n') + '\n';
}
