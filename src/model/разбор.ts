const имя = (э: Экземпляр) => э.название ?? изделиеПоИд(э.изделие)?.название ?? 'Предмет';
const кав = (э: Экземпляр) => `«${имя(э)}»`;
const скл = (n: number, one: string, few: string, many: string) => {
  const m10 = n % 10;
  const m100 = n % 100;
  return m10 === 1 && m100 !== 11 ? one : m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14) ? few : many;
};

/** Ось ширины изделия в плане */
const осьШ = (э: Экземпляр): Точка => {
  const θ = (э.поворот * Math.PI) / 180;
  return [Math.cos(θ), Math.sin(θ)];
};
const центр = (э: Экземпляр): Точка => [э.позиция[0], э.позиция[2]];

/** Расстояние между габаритами двух предметов в плане (0 — касаются) */
function зазорМежду(a: Экземпляр, b: Экземпляр): number {
  const к = (э: Экземпляр) => {
    const θ = (э.поворот * Math.PI) / 180;
    const c = Math.abs(Math.cos(θ));
    const s = Math.abs(Math.sin(θ));
    const hx = (э.габариты.ш * c + э.габариты.г * s) / 2;
    const hz = (э.габариты.ш * s + э.габариты.г * c) / 2;
    return { x0: э.позиция[0] - hx, x1: э.позиция[0] + hx, z0: э.позиция[2] - hz, z1: э.позиция[2] + hz };
  };
  const p = к(a);
  const q = к(b);
  return Math.hypot(Math.max(0, q.x0 - p.x1, p.x0 - q.x1), Math.max(0, q.z0 - p.z1, p.z0 - q.z1));
}

