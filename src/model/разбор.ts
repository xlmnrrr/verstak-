      const изд = изделиеПоИд(э.изделие);
      const открытые = изд?.тип === 'корпус' && слитьРаскладку(изд.раскладка, э.раскладка).фасад.тип === 'нет';
      const норма = нормаПрохода(тип, открытые);
      const почему = тип === 'кухня' ? `Норма прохода на кухне ${норма} мм: двоим не разойтись, ящик не выдвинуть.` : `Норма прохода (${тип}${открытые ? ', перед открытыми полками' : ''}) ${норма} мм: встать перед шкафом, открыть створку и достать вещи.`;
      return { ...база, заголовок: 'Узкий проход', предлагаю: `Уменьшить глубину ряда напротив или ${кто} на ${мм} мм${с[0] ? ` (или убрать ${кав(с[0])})` : ''}: останется ${норма} мм.`, почему };
