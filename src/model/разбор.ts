      return { ...база, заголовок: `Мало места перед ${имя(э)}`, предлагаю: `Освободить ещё ${мм} мм перед ${кто}: сдвинуть ${с[0] ? кав(с[0]) : 'противоположный ряд'} или перенести технику на стену, где перед ней больше места.`, почему: 'Перед холодильником нужно 1000 мм, перед посудомойкой 1200 мм: открытая дверца плюс человек рядом.' };
