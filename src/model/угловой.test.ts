/**
 * A1: угловая тумба с каруселью 3/4. Детали внутри Г-формы, карусель не задевает створки, деталировка без фурнитуры;
 * открывание на 110° против соседнего ряда — валидатором; планировщик ставит тумбу в угол.
 */
import { describe, expect, it } from 'vitest';
import { изделиеПоИд } from './каталог';
import { детали } from './детали';
import { движенияИзделия, конфликтыПомещения } from './открывание';
import { новоеПомещение, прямоугольник } from './помещение';
import { новыйПроектV2, новыйЭкземпляр } from './проект';
import { проверитьПроект } from './валидатор';
import { проверитьВлезает } from './проверка';
import { деталировка } from './производство';
import { предложитьПланировки } from './планировщик';
import { следыПлеч } from './угловой';
import type { Экземпляр } from './типы';

const ИДЫ = ['тумба-угловая-карусель-900', 'тумба-угловая-карусель-1000', 'тумба-угловая-карусель-900-открытая', 'тумба-угловая-карусель-1000-открытая'];
const кухня = () => новыйПроектV2('к', новоеПомещение('п1', 'кухня', 'Кухня', прямоугольник(3600, 2800)));

/** Угловая тумба в правом заднем углу кухни 3600 × 2800 (оси от центра) */
const угол = (W = 900, id = 'тумба-угловая-карусель-900'): Экземпляр => ({
  ...новыйЭкземпляр(изделиеПоИд(id)!, 'п1'),
  id: 'угол',
  позиция: [1800 - W / 2, 0, -1400 + W / 2],
  поворот: 0,
  габариты: { ш: W, г: W, в: 820 },
});

/** Тумба 400 с одной дверцей: на задней стене (поворот 0) или на правой (поворот 90) */
function сосед(id: string, стена: 'задняя' | 'правая', отУгла: number, петли: 'слева' | 'справа'): Экземпляр {
  const э = новыйЭкземпляр(изделиеПоИд('тумба-нижняя-400')!, 'п1');
  const позиция: Экземпляр['позиция'] = стена === 'задняя' ? [1800 - отУгла - 200, 0, -1400 + 280] : [1800 - 280, 0, -1400 + отУгла + 200];
  return { ...э, id, позиция, поворот: стена === 'задняя' ? 0 : 90, габариты: { ш: 400, г: 560, в: 820 }, раскладка: { фасад: { тип: 'распашной', створок: 1, петли } } };
}

describe('угловая тумба с каруселью: детали', () => {
  it('все детали внутри Г-формы, ручки — не дальше 30 мм от фасада', () => {
    for (const id of ИДЫ) {
      const изд = изделиеПоИд(id)!;
      for (const W of [800, 900, 1000, 1200]) {
        const э = { ...угол(W, id), габариты: { ш: W, г: W, в: 820 } };
        const плечи = следыПлеч(изд, э.габариты);
        for (const д of детали(изд, э)) {
          const [cx, cy, cz] = д.локально.центр;
          const [ox, oy, oz] = д.локально.объём;
          expect(cy - oy / 2, `${id} ${д.роль} низ`).toBeGreaterThanOrEqual(-0.01);
          expect(cy + oy / 2, `${id} ${д.роль} верх`).toBeLessThanOrEqual(820.01);
          const выступ = д.роль === 'ручка' ? 30 : 0.01;
          // каждая точка детали в плане лежит в одном из плеч (с допуском выступа ручки):
          // у плиты — 4 угла, у диска 3/4 — точки дуги без выреза (−X, +Z)
          const точки: [number, number][] = д.профиль
            ? Array.from({ length: 28 }, (_, k) => (-Math.PI / 2 + (k / 27) * 1.5 * Math.PI)).map((φ) => [cx + (ox / 2) * Math.cos(φ), cz - (oz / 2) * Math.sin(φ)])
            : [[-1, -1], [1, -1], [1, 1], [-1, 1]].map(([sx, sz]) => [cx + (sx * ox) / 2, cz + (sz * oz) / 2]);
          for (const [x, z] of точки) {
            const внутри = плечи.some((п) => x >= п[0][0] - выступ && x <= п[2][0] + выступ && z >= п[0][1] - выступ && z <= п[2][1] + выступ);
            expect(внутри, `${id} ${W}: ${д.роль} (${Math.round(x)}, ${Math.round(z)}) вне плеч`).toBe(true);
          }
        }
      }
    }
  });

  it('карусель 3/4: две полки с бортиком и стойка; ⌀ 710 у 900 и 830 у 1000; вырез к створкам, полки не задевают створки', () => {
    for (const [W, ожидаем] of [[900, 710], [1000, 830]] as const) {
      const изд = изделиеПоИд(`тумба-угловая-карусель-${W}`)!;
      const д = детали(изд, угол(W, изд.id));
      const полки = д.filter((x) => x.профиль === 'сектор270');
      const ободы = д.filter((x) => x.профиль === 'обод270');
      expect(полки).toHaveLength(2);
      expect(ободы).toHaveLength(2);
      expect(Math.round(полки[0].локально.объём[0])).toBe(ожидаем);
      // центр карусели на 30 мм вглубь от стыка створок: вырез 3/4 не доходит до фасадов
      const створки = д.filter((x) => x.роль === 'фасад');
      expect(створки).toHaveLength(2);
      const [cx, , cz] = полки[0].локально.центр;
      const стыкА = Math.max(...створки.map((с) => с.локально.центр[2] - с.локально.объём[2] / 2));
      expect(cz).toBeLessThan(стыкА - 20);
      expect(cx).toBeGreaterThan(Math.min(...створки.map((с) => с.локально.центр[0] + с.локально.объём[0] / 2)) + 20);
    }
  });

  it('деталировка: плиты корпуса, створки и цоколь есть, карусель и стойка (фурнитура) — нет', () => {
    const п = кухня();
    п.объекты.push(угол());
    const строки = деталировка(п);
    expect(строки.some((с) => с.роль === 'фурнитура')).toBe(false);
    expect(строки.filter((с) => с.роль === 'фасад').reduce((s, с) => s + с.количество, 0)).toBe(2);
    expect(строки.filter((с) => с.роль === 'боковина').reduce((s, с) => s + с.количество, 0)).toBe(2);
  });

  it('открытая карусель: без створок и ручек, корпус на всю глубину плеча', () => {
    const изд = изделиеПоИд('тумба-угловая-карусель-900-открытая')!;
    const д = детали(изд, угол(900, изд.id));
    expect(д.some((x) => x.роль === 'фасад' || x.роль === 'ручка')).toBe(false);
    expect(движенияИзделия(изд, угол(900, изд.id))).toEqual([]);
  });

  it('створки: «а» на петле у левой боковины, «б» — у передней, обе на 110°', () => {
    const изд = изделиеПоИд('тумба-угловая-карусель-900')!;
    const дв = движенияИзделия(изд, угол());
    expect(дв.map((x) => x.группа).sort()).toEqual(['плечо-а/дверь-0', 'плечо-б/дверь-0']);
    const а = дв.find((x) => x.группа.startsWith('плечо-а'))!;
    const б = дв.find((x) => x.группа.startsWith('плечо-б'))!;
    // петля на краю створки: створка отступает от края корпуса на 1,5 мм
    expect(а.кинематика.вид === 'поворот' && а.кинематика.опора[0]).toBeCloseTo(-448.5, 1);
    expect(б.кинематика.вид === 'поворот' && б.кинематика.опора[2]).toBeCloseTo(448.5, 1);
    expect(а.фронт).toEqual([0, 1]);
    expect(б.фронт).toEqual([-1, 0]);
    for (const x of дв) expect(x.кинематика.вид === 'поворот' && x.кинематика.конфликт).toBe(110);
  });
});

describe('угловая тумба с каруселью: открывание против соседнего ряда (валидатор)', () => {
  it('тумба в углу и соседи с дверцами к углу и от угла: на 110° ничего не задевает, пересечений нет', () => {
    for (const пА of ['слева', 'справа'] as const) {
      for (const пБ of ['слева', 'справа'] as const) {
        const п = кухня();
        п.объекты.push(угол(), сосед('а', 'задняя', 900, пА), сосед('б', 'правая', 900, пБ));
        expect(конфликтыПомещения(п, 'п1'), `${пА}/${пБ}`).toEqual([]);
        expect(проверитьВлезает(п)).toEqual([]);
        expect(проверитьПроект(п).filter((з) => з.правило === 'открывание' || з.правило === 'пересечение')).toEqual([]);
      }
    }
  });

  it('для сравнения — пустой угол 600 × 600: дверцы соседей с петлёй у угла упираются в соседний ряд', () => {
    const п = кухня();
    п.объекты.push(сосед('а', 'задняя', 600, 'справа'), сосед('б', 'правая', 600, 'слева'));
    const к = конфликтыПомещения(п, 'п1');
    expect(к.length).toBeGreaterThan(0);
    expect(к[0].мешает).toMatch(/Тумба/);
  });

  it('стол в свободном углу комнаты рядом с тумбой — не пересечение (след — два плеча, а не квадрат 900)', () => {
    const п = кухня();
    const стол = { ...новыйЭкземпляр(изделиеПоИд('тумба-нижняя-400')!, 'п1'), id: 'т', позиция: [1800 - 560 - 160, 0, -1400 + 560 + 160] as Экземпляр['позиция'], поворот: 0, габариты: { ш: 300, г: 300, в: 820 } };
    п.объекты.push(угол(), стол);
    expect(проверитьВлезает(п)).toEqual([]);
  });
});

describe('«Предложи планировку»: в углу — тумба с каруселью', () => {
  it('кухня 3600 × 2800: в угловой — одна угловая тумба, в П-образной — две; варианты без замечаний', () => {
    const р = предложитьПланировки(кухня());
    const угловая = р.варианты.find((в) => в.тип === 'угловая')!;
    const п = р.варианты.find((в) => в.тип === 'П-образная')!;
    const сколько = (в: typeof угловая) => в.проект.объекты.filter((о) => о.изделие.startsWith('тумба-угловая-карусель')).length;
    expect(сколько(угловая)).toBe(1);
    expect(сколько(п)).toBe(2);
    for (const в of [угловая, п]) {
      expect(в.чисто, в.замечания.map((з) => з.текст).join(' | ')).toBe(true);
      expect(в.учтено.some((т) => т.includes('угловая тумба 900 × 900 с каруселью'))).toBe(true);
    }
  });
});
