/**
 * A3: высота мебели по замеру. Гардеробная кв. 160 — 2200 по замеру заказчика с пометкой «уточнить»;
 * «до потолка минус 50» — вариант по переключателю. Поле помещения пишется в .kitchen и читается обратно,
 * старые файлы без поля открываются как раньше.
 */
import { describe, expect, it } from 'vitest';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { помещенияЗаказчика, спорныеОтметки } from './каталог/помещения-заказчика';
import { новыйПроектV2 } from './проект';
import { предложитьПланировки } from './планировщик';
import { записатьПроект, разобратьФайл } from './файл';

const гардеробная = () => новыйПроектV2('Гардеробная', помещенияЗаказчика()[1]);

describe('высота мебели по замеру (A3)', () => {
  it('гардеробная кв. 160: по умолчанию 2200 по замеру, «уточнить», все варианты без замечаний', () => {
    const р = предложитьПланировки(гардеробная());
    expect(р.варианты).toHaveLength(3);
    for (const в of р.варианты) {
      expect(в.чисто).toBe(true);
      expect(в.описание).toMatch(/высота 2200/);
      expect(в.учтено[0]).toMatch(/^Высота 2200 мм — по замеру заказчика \(уточнить\); до потолка можно 2650 мм/);
      const высокие = в.проект.объекты.filter((о) => о.помещение === в.помещение && о.габариты.в > 1500);
      expect(высокие.length).toBeGreaterThan(0);
      for (const о of высокие) expect(о.габариты.в).toBe(2200);
    }
  });

  it('«до потолка» — вариант по переключателю: 2650 (потолок 2700 минус 50 на сборку)', () => {
    const р = предложитьПланировки(гардеробная(), undefined, { высота: 'до-потолка' });
    for (const в of р.варианты) {
      expect(в.чисто).toBe(true);
      expect(в.описание).toMatch(/высота 2650/);
      expect(в.учтено[0]).toMatch(/по замеру заказчика — 2200 мм \(уточнить\)/);
    }
  });

  it('помещение без замера — как раньше: до потолка минус 50 (ниша кв. 160 → 2650)', () => {
    const р = предложитьПланировки(новыйПроектV2('Ниша', помещенияЗаказчика()[0]));
    expect(р.варианты[0].учтено[0]).toBe('Высота 2650 мм: 50 мм до потолка на сборку (шкаф ставят наклоном).');
  });

  it('поле «мебель_высота» пишется в .kitchen и читается обратно; старый пример без поля открывается', () => {
    const п = гардеробная();
    const р = разобратьФайл(записатьПроект(п));
    expect(р.ок).toBe(true);
    expect(р.проект!.помещения[0].мебель_высота).toBe(2200);
    expect(р.проект!.помещения[0].прочее).toBeUndefined();
    const старый = разобратьФайл(readFileSync(join(process.cwd(), 'public/Библиотека/пример-проекта.kitchen'), 'utf8'));
    expect(старый.ок).toBe(true);
    expect(старый.проект!.помещения[0].мебель_высота).toBeUndefined();
    // меньше 300 — ошибка формата с русским текстом
    const плохой = JSON.parse(записатьПроект(п));
    плохой.помещения[0].мебель_высота = 100;
    const р2 = разобратьФайл(JSON.stringify(плохой));
    expect(р2.ок).toBe(false);
  });

  it('список «уточнить» называет высоту мебели по замеру', () => {
    const с = спорныеОтметки(помещенияЗаказчика()).find((x) => x.помещение === 'Кв. 160: гардеробная' && x.что.startsWith('помещение'))!;
    expect(с.что).toMatch(/мебель:2200 по замеру \(2100–2200\)/);
    expect(с.заметка).toMatch(/мебель 2200 мм по замеру, до потолка — вариант/);
  });
});
