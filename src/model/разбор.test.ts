/**
 * Этап 7: разбор проекта — нормы с конкретными предложениями в мм и неудобства по правилам мастера.
 */
import { describe, expect, it } from 'vitest';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { разобратьПроект, разборТекстом } from './разбор';
import { сравнитьПроекты, сравнениеТекстом } from './сравнение';
import { предложитьПланировки } from './планировщик';
import { разобратьФайл } from './файл';
import { новыйПроектV2, новыйЭкземпляр, копияПроекта } from './проект';
import { новоеПомещение, прямоугольник } from './помещение';
import { изделиеПоИд } from './каталог';
import type { ПроектV2 } from './типы';

const демо = (): ПроектV2 => разобратьФайл(readFileSync(join(process.cwd(), 'public/Библиотека/пример-проекта.kitchen'), 'utf8')).проект!;

describe('разбор проекта', () => {
  it('демо-кухня: норм не нарушает, два неудобства с миллиметрами — нет посудомойки и 320 мм у холодильника', () => {
    const р = разобратьПроект(демо());
    expect(р.числа).toMatchObject({ изделий: 23, ошибок: 0, предупреждений: 0, советов: 0 });
    expect(р.числа.листов).toBeCloseTo(2.6, 1);
    expect(р.пункты.filter((x) => x.раздел === 'нормы')).toEqual([]);
    const пмм = р.пункты.find((x) => x.заголовок === 'Нет посудомойки');
    expect(пмм?.предлагаю).toMatch(/посудомойку 600 мм вместо «Тумба с ящиками 600»/);
    const место = р.пункты.find((x) => x.заголовок === 'Пустое место у стены');
    expect(место?.что).toMatch(/Холодильник.*320 мм/);
    expect(место?.предлагаю).toMatch(/320 мм/);
    expect(р.итог).toBe('0 нарушений норм, 2 неудобства.');
  });

  it('нарушения норм: у каждого пункта предложение с числом, у пересечения — куда и на сколько сдвинуть', () => {
    const п = демо();
    // тумба с ящиками заезжает на соседа на 150 мм
    const т = п.объекты.find((о) => о.изделие === 'тумба-ящики-600')!;
    т.позиция = [т.позиция[0] + 150, т.позиция[1], т.позиция[2]];
    const р = разобратьПроект(п);
    const нормы = р.пункты.filter((x) => x.раздел === 'нормы');
    expect(нормы.length).toBeGreaterThan(0);
    for (const x of нормы) {
      expect(x.предлагаю, x.заголовок).toMatch(/\d/);
      expect(x.почему.length, x.заголовок).toBeGreaterThan(10);
      expect(x.предметы.length).toBeGreaterThan(0);
    }
    const пересечение = нормы.find((x) => x.что.includes('пересекается'));
    expect(пересечение?.предлагаю).toMatch(/(Сдвинуть .* (влево|вправо) на \d+ мм|Урезать .* на \d+ мм)/);
  });

  it('хранение: длинные полки, широкие створки, щель над шкафом — с цифрами', () => {
    const п = новыйПроектV2('Спальня', новоеПомещение('п1', 'спальня', 'Спальня', прямоугольник(3500, 3000, false)));
    const стеллаж = новыйЭкземпляр(изделиеПоИд('стеллаж-открытый-800')!, 'п1', [600, 0, 175], 'стеллаж');
    стеллаж.габариты = { ш: 1200, г: 350, в: 2200 };
    const шкаф = новыйЭкземпляр(изделиеПоИд('шкаф-распашной-900')!, 'п1', [2000, 0, 300], 'шкаф');
    шкаф.габариты = { ш: 1400, г: 600, в: 2400 };
    шкаф.раскладка = { фасад: { створок: 2 } };
    п.объекты = [стеллаж, шкаф];
    const р = разобратьПроект(п);
    const полки = р.пункты.find((x) => x.заголовок === 'Длинные полки прогнутся');
    expect(полки?.что).toMatch(/по 1166 мм при плите 16/);
    expect(полки?.предлагаю).toMatch(/1 перегородку: полки станут по 575 мм/);
    const створки = р.пункты.find((x) => x.заголовок === 'Широкие створки');
    expect(створки?.предлагаю).toMatch(/3 створки по 467 мм/);
    const щель = р.пункты.filter((x) => x.заголовок === 'Щель над шкафом');
    expect(щель.some((x) => x.что.includes('300 мм'))).toBe(true);
  });

  it('вариант планировки разбирается: числа сходятся с вариантом', () => {
    const в = предложитьПланировки(демо()).варианты[1];
    const р = разобратьПроект(в.проект);
    expect(р.числа.ошибок + р.числа.предупреждений + р.числа.советов).toBe(0);
    expect(р.числа.столешницаМ).toBeCloseTo(в.числа.столешницаМ, 1);
    expect(разборТекстом(р)).toMatch(/^# Разбор проекта «.*вариант Б, угловая»/);
  });
});

describe('сравнение двух проектов', () => {
  it('проект сам с собой: все разницы 0, списков нет', () => {
    const п = демо();
    const с = сравнитьПроекты(п, копияПроекта(п));
    expect(с.числа).toHaveLength(10);
    expect(с.числа.every((x) => x.разница === 0)).toBe(true);
    expect([...с.добавлено, ...с.убрано, ...с.изменено, ...с.лучше, ...с.хуже]).toEqual([]);
  });

  it('демо против линейного варианта: метры, листы, кромка, детали с разницей; что лучше, что хуже', () => {
    const а = демо();
    const в = предложитьПланировки(а).варианты[0];
    const с = сравнитьПроекты(а, в.проект);
    const стол = с.числа.find((x) => x.что === 'Столешница')!;
    expect(стол.а).toBeCloseTo(2.8, 1);
    expect(стол.б).toBeCloseTo(в.числа.столешницаМ, 1);
    expect(стол.победитель).toBe(стол.б > стол.а ? 'б' : 'а');
    expect(с.лучше.some((x) => x.startsWith('Столешница: 2,8 →'))).toBe(true);
    expect(с.хуже.some((x) => x.startsWith('Листов ЛДСП'))).toBe(true);
    expect(с.убрано.some((x) => x.startsWith('Плита'))).toBe(true);
    expect(с.изменено.some((x) => /сдвинут на \d+ мм/.test(x))).toBe(true);
    expect(сравнениеТекстом(с)).toMatch(/\| Столешница, м \| 2,8 \|/);
  });

  it('сдвиг и смена размера одного предмета видны в «Изменено» с миллиметрами; новое замечание — в «Хуже»', () => {
    const а = демо();
    const б = копияПроекта(а);
    const т = б.объекты.find((о) => о.изделие === 'тумба-ящики-600')!;
    т.позиция = [т.позиция[0] + 150, т.позиция[1], т.позиция[2]];
    т.габариты = { ...т.габариты, ш: 650 };
    const с = сравнитьПроекты(а, б);
    expect(с.изменено.some((x) => x.includes('ширина 600 → 650 (+50)') && x.includes('сдвинут на 150 мм'))).toBe(true);
    expect(с.хуже.some((x) => x.startsWith('Появилось замечание'))).toBe(true);
    expect(с.числа.find((x) => x.что === 'Ошибок')!.победитель).toBe('а');
  });
});
