import { memo, useMemo } from 'react';
import * as THREE from 'three';
import type { Obj } from '../types';
import { м } from '../lib/utils';

/** Процедурная деталь: корпус, техника, стол, стул, проём, декор.
 *  Строится кодом из примитивов по числам — поэтому любой размер перестраивается мгновенно. */

const ПЛИТА = 0.018; // 18 мм
const ЗАДНЯЯ = 0.008;

function Панель({
  р,
  ц,
  x = 0,
  y = 0,
  z = 0,
  зеркало = false,
}: {
  р: [number, number, number];
  ц: string;
  x?: number;
  y?: number;
  z?: number;
  зеркало?: boolean;
}) {
  return (
    <mesh position={[x, y, z]} castShadow receiveShadow>
      <boxGeometry args={р} />
      {зеркало ? (
        <meshStandardMaterial color="#cfe4ec" roughness={0.06} metalness={0.95} />
      ) : (
        <meshStandardMaterial color={ц} roughness={0.75} metalness={0.05} />
      )}
    </mesh>
  );
}

function ДетальВнутренняя({ obj }: { obj: Obj }) {
  const ш = м(obj.габариты.ш);
  const г = м(obj.габариты.г);
  const в = м(obj.габариты.в);
  const цоколь = м(obj.цоколь ?? 0);
  const ножки = м(obj.ножки ?? 0);

  const цветКорпуса = '#cfc7ba';
  const цветФасада = obj.цвет ?? '#c08a4a';
  const вид = obj.вид ?? 'корпус';

  const полки = useMemo(() => {
    const n = obj.полок ?? 0;
    if (n <= 0) return [];
    const низ = цоколь + ПЛИТА;
    const верх = в - ПЛИТА;
    const шаг = (верх - низ) / (n + 1);
    return Array.from({ length: n }, (_, i) => низ + шаг * (i + 1));
  }, [obj.полок, в, цоколь]);

  // --- Проёмы: окно и дверь ---
  if (вид === 'проём') {
    const брус = 0.06;
    return (
      <group>
        <Панель р={[ш, брус, г]} ц="#f3efe9" y={в - брус / 2} />
        <Панель р={[ш, брус, г]} ц="#f3efe9" y={брус / 2} />
        <Панель р={[брус, в, г]} ц="#f3efe9" x={-ш / 2 + брус / 2} y={в / 2} />
        <Панель р={[брус, в, г]} ц="#f3efe9" x={ш / 2 - брус / 2} y={в / 2} />
        <mesh position={[0, в / 2, 0]}>
          <boxGeometry args={[ш - брус * 2, в - брус * 2, 0.01]} />
          <meshPhysicalMaterial
            color="#bcd8e8"
            transparent
            opacity={0.28}
            roughness={0.05}
            metalness={0}
          />
        </mesh>
        <mesh position={[0, в / 2, 0]}>
          <boxGeometry args={[0.02, в - брус * 2, 0.03]} />
          <meshStandardMaterial color="#f3efe9" />
        </mesh>
      </group>
    );
  }

  // --- Декор: у каждого вида своя геометрия, иначе ковёр выглядит как растение ---
  if (вид === 'декор') {
    const ид = obj.модуль;

    // ковёр — плоский, на полу
    if (ид.startsWith('rug')) {
      return (
        <mesh position={[0, 0.006, 0]} receiveShadow>
          <boxGeometry args={[ш, 0.012, г]} />
          <meshStandardMaterial color={obj.цвет ?? '#8c5a4a'} roughness={1} />
        </mesh>
      );
    }

    // светильник — подвес или потолочная тарелка
    if (ид.startsWith('light')) {
      const подвес = ид.includes('pendant');
      return (
        <group>
          {подвес && (
            <mesh position={[0, в * 0.55, 0]}>
              <cylinderGeometry args={[0.008, 0.008, в * 0.9, 8]} />
              <meshStandardMaterial color="#4a4a4a" />
            </mesh>
          )}
          <mesh position={[0, в * 0.12, 0]} castShadow>
            <coneGeometry args={[ш * 0.5, в * 0.35, 20, 1, true]} />
            <meshStandardMaterial color={obj.цвет ?? '#2b2f36'} side={THREE.DoubleSide} />
          </mesh>
          <mesh position={[0, в * 0.06, 0]}>
            <sphereGeometry args={[0.06, 12, 10]} />
            <meshStandardMaterial color="#ffe6b0" emissive="#ffd27a" emissiveIntensity={1.4} />
          </mesh>
        </group>
      );
    }

    // мусорное ведро
    if (ид.startsWith('bin')) {
      return (
        <mesh position={[0, в / 2, 0]} castShadow>
          <cylinderGeometry args={[ш * 0.42, ш * 0.34, в, 16]} />
          <meshStandardMaterial color={obj.цвет ?? '#7b828b'} metalness={0.5} roughness={0.4} />
        </mesh>
      );
    }

    // зеркало настенное
    if (ид.startsWith('mirror')) {
      return (
        <mesh position={[0, в / 2, 0]} castShadow>
          <boxGeometry args={[ш, в, 0.04]} />
          <meshStandardMaterial color="#cfe4ec" roughness={0.05} metalness={0.95} />
        </mesh>
      );
    }

    // посуда — стопка
    if (ид.startsWith('dishes')) {
      return (
        <group>
          {[0, 1, 2].map((i) => (
            <mesh key={i} position={[0, 0.02 + i * 0.05, 0]} castShadow>
              <cylinderGeometry args={[ш * 0.4, ш * 0.4, 0.03, 16]} />
              <meshStandardMaterial color="#f2f0ec" roughness={0.4} />
            </mesh>
          ))}
        </group>
      );
    }

    // диван и кресло — корпус с сиденьем и спинкой
    if (ид.startsWith('sofa') || ид.startsWith('armchair')) {
      const сиденье = в * 0.45;
      return (
        <group>
          <Панель р={[ш, сиденье, г]} ц={obj.цвет ?? '#6b6f78'} y={сиденье / 2} />
          <Панель
            р={[ш, в - сиденье, г * 0.25]}
            ц={obj.цвет ?? '#6b6f78'}
            y={(в + сиденье) / 2}
            z={-г / 2 + г * 0.125}
          />
          <Панель р={[ш * 0.12, в * 0.35, г]} ц={obj.цвет ?? '#5f636b'} x={-ш / 2 + ш * 0.06} y={в * 0.62} />
          <Панель р={[ш * 0.12, в * 0.35, г]} ц={obj.цвет ?? '#5f636b'} x={ш / 2 - ш * 0.06} y={в * 0.62} />
        </group>
      );
    }

    // по умолчанию — растение
    return (
      <group>
        <mesh position={[0, в * 0.3, 0]} castShadow>
          <cylinderGeometry args={[ш * 0.3, ш * 0.22, в * 0.6, 16]} />
          <meshStandardMaterial color="#8d6b4b" roughness={0.9} />
        </mesh>
        <mesh position={[0, в * 0.78, 0]} castShadow>
          <sphereGeometry args={[ш * 0.45, 16, 12]} />
          <meshStandardMaterial color="#4f7a45" roughness={0.9} />
        </mesh>
      </group>
    );
  }

  // --- Техника ---
  if (вид === 'техника') {
    const корпус = obj.цвет ?? '#e8eaec';
    return (
      <group>
        <Панель р={[ш, в, г]} ц={корпус} x={0} y={в / 2} />
        <Панель р={[ш - 0.02, в - 0.04, 0.02]} ц={obj.цвет ? корпус : '#c9ced3'} z={г / 2 + 0.005} y={в / 2} />
        <Панель р={[0.02, в * 0.55, 0.03]} ц="#8b9198" x={ш / 2 - 0.06} z={г / 2 + 0.02} y={в * 0.55} />
      </group>
    );
  }

  // --- Стол ---
  if (вид === 'стол') {
    const толщина = 0.04;
    const ножка = 0.06;
    return (
      <group>
        <Панель р={[ш, толщина, г]} ц={цветФасада} y={в - толщина / 2} />
        {[
          [-1, -1],
          [1, -1],
          [-1, 1],
          [1, 1],
        ].map(([sx, sz], i) => (
          <Панель
            key={i}
            р={[ножка, в - толщина, ножка]}
            ц="#8a6a44"
            x={sx * (ш / 2 - ножка)}
            y={(в - толщина) / 2}
            z={sz * (г / 2 - ножка)}
          />
        ))}
      </group>
    );
  }

  // --- Стул / табурет ---
  if (вид === 'стул') {
    const сиденье = 0.045;
    const ножка = 0.04;
    const высотаСиденья = в * 0.55;
    return (
      <group>
        <Панель р={[ш, сиденье, г]} ц={цветФасада} y={высотаСиденья} />
        {[
          [-1, -1],
          [1, -1],
          [-1, 1],
          [1, 1],
        ].map(([sx, sz], i) => (
          <Панель
            key={i}
            р={[ножка, высотаСиденья, ножка]}
            ц="#7d5f3e"
            x={sx * (ш / 2 - ножка)}
            y={высотаСиденья / 2}
            z={sz * (г / 2 - ножка)}
          />
        ))}
        <Панель р={[ш, в - высотаСиденья, 0.03]} ц={цветФасада} y={(в + высотаСиденья) / 2} z={-г / 2 + 0.02} />
      </group>
    );
  }

  // --- Столешница ---
  if (вид === 'столешница') {
    return (
      <group>
        <Панель р={[ш, в, г]} ц={obj.цвет ?? '#e6e2da'} y={в / 2} />
      </group>
    );
  }

  // --- Корпус и навесной (по умолчанию) ---
  const нижняяПанель = цоколь > 0 ? цоколь : ножки > 0 ? ножки : 0;
  const высотаКорпуса = в - нижняяПанель;
  const фасадТолщина = 0.018;
  const зеркальный = obj.фасад === 'зеркало';
  const сЯщиками = obj.фасад === 'ящики';
  const дверцы = obj.фасад === 'нет' || сЯщиками ? 0 : Math.max(1, Math.round(ш / 0.6));
  const ширинаДверцы = (ш - 0.006) / Math.max(1, дверцы);
  const числоЯщиков = Math.max(1, obj.ящиков ?? 3);

  return (
    <group>
      {/* цоколь или ножки */}
      {цоколь > 0 && (
        <Панель
          р={[ш - 0.03, цоколь, г - 0.02]}
          ц="#5c5c5c"
          y={цоколь / 2}
        />
      )}
      {ножки > 0 &&
        [
          [-1, -1],
          [1, -1],
          [-1, 1],
          [1, 1],
        ].map(([sx, sz], i) => (
          <mesh
            key={i}
            position={[sx * (ш / 2 - 0.03), ножки / 2, sz * (г / 2 - 0.03)]}
            castShadow
          >
            <cylinderGeometry args={[0.02, 0.02, ножки, 10]} />
            <meshStandardMaterial color="#6b6b6b" metalness={0.6} roughness={0.4} />
          </mesh>
        ))}

      {/* корпус */}
      <Панель р={[ПЛИТА, высотаКорпуса, г]} ц={цветКорпуса} x={-ш / 2 + ПЛИТА / 2} y={нижняяПанель + высотаКорпуса / 2} />
      <Панель р={[ПЛИТА, высотаКорпуса, г]} ц={цветКорпуса} x={ш / 2 - ПЛИТА / 2} y={нижняяПанель + высотаКорпуса / 2} />
      <Панель р={[ш - ПЛИТА * 2, ПЛИТА, г]} ц={цветКорпуса} y={нижняяПанель + ПЛИТА / 2} />
      <Панель р={[ш - ПЛИТА * 2, ПЛИТА, г]} ц={цветКорпуса} y={в - ПЛИТА / 2} />
      <Панель р={[ш - ПЛИТА * 2, высотаКорпуса, ЗАДНЯЯ]} ц="#b7ad9d" z={-г / 2 + ЗАДНЯЯ / 2} y={нижняяПанель + высотаКорпуса / 2} />

      {/* полки */}
      {полки.map((y, i) => (
        <Панель key={i} р={[ш - ПЛИТА * 2, ПЛИТА, г - 0.02]} ц={цветКорпуса} y={y} />
      ))}

      {/* фасады-дверцы: петли слева / справа / сверху / снизу, дверца умеет открываться */}
      {дверцы > 0 &&
        Array.from({ length: дверцы }, (_, i) => {
          const левая = i < Math.ceil(дверцы / 2);
          const сторона = obj.петли ?? (левая ? 'слева' : 'справа');
          const xЦентр = -ш / 2 + 0.003 + ширинаДверцы * (i + 0.5);
          const yЦентр = нижняяПанель + высотаКорпуса / 2;
          const высотаПолотна = высотаКорпуса - 0.006;
          const угол = obj.открыт ? 1.75 : 0;
          const zПолотна = г / 2 + фасадТолщина / 2;

          let позицияГруппы: [number, number, number] = [xЦентр, yЦентр, zПолотна];
          let смещениеПолотна: [number, number] = [0, 0];
          let поворотДверцы: [number, number, number] = [0, 0, 0];

          if (сторона === 'слева') {
            позицияГруппы = [xЦентр - ширинаДверцы / 2, yЦентр, zПолотна];
            смещениеПолотна = [ширинаДверцы / 2, 0];
            поворотДверцы = [0, -угол, 0];
          } else if (сторона === 'справа') {
            позицияГруппы = [xЦентр + ширинаДверцы / 2, yЦентр, zПолотна];
            смещениеПолотна = [-ширинаДверцы / 2, 0];
            поворотДверцы = [0, угол, 0];
          } else if (сторона === 'сверху') {
            позицияГруппы = [xЦентр, yЦентр + высотаПолотна / 2, zПолотна];
            смещениеПолотна = [0, -высотаПолотна / 2];
            поворотДверцы = [-угол, 0, 0];
          } else {
            позицияГруппы = [xЦентр, yЦентр - высотаПолотна / 2, zПолотна];
            смещениеПолотна = [0, высотаПолотна / 2];
            поворотДверцы = [угол, 0, 0];
          }

          // ручка ставится с противоположной от петли стороны
          const ручкаX =
            смещениеПолотна[0] +
            (сторона === 'слева' ? ширинаДверцы / 2 - 0.05 : сторона === 'справа' ? -ширинаДверцы / 2 + 0.05 : 0);
          const ручкаY =
            смещениеПолотна[1] +
            (сторона === 'сверху' ? -высотаПолотна / 2 + 0.06 : сторона === 'снизу' ? высотаПолотна / 2 - 0.06 : 0);

          return (
            <group key={i} position={позицияГруппы} rotation={поворотДверцы}>
              <Панель
                р={[ширинаДверцы, высотаПолотна, фасадТолщина]}
                ц={цветФасада}
                зеркало={зеркальный}
                x={смещениеПолотна[0]}
                y={смещениеПолотна[1]}
              />
              {obj.фасад !== 'push' && (
                <mesh position={[ручкаX, ручкаY, фасадТолщина / 2 + 0.014]} castShadow>
                  <boxGeometry
                    args={
                      сторона === 'сверху' || сторона === 'снизу'
                        ? [0.18, 0.02, 0.02]
                        : [0.02, 0.16, 0.02]
                    }
                  />
                  <meshStandardMaterial color="#9a9a9a" metalness={0.8} roughness={0.3} />
                </mesh>
              )}
            </group>
          );
        })}

      {/* фасады-ящики: горизонтальные полотна с ручками */}
      {сЯщиками &&
        Array.from({ length: числоЯщиков }, (_, i) => {
          const высота = (высотаКорпуса - 0.008 * (числоЯщиков + 1)) / числоЯщиков;
          const y = нижняяПанель + 0.008 + высота * (i + 0.5) + 0.008 * i;
          return (
            <group key={i}>
              <Панель
                р={[ш - 0.006, высота, фасадТолщина]}
                ц={цветФасада}
                y={y}
                z={г / 2 + фасадТолщина / 2}
              />
              <mesh position={[0, y, г / 2 + фасадТолщина + 0.014]} castShadow>
                <boxGeometry args={[0.18, 0.02, 0.02]} />
                <meshStandardMaterial color="#9a9a9a" metalness={0.8} roughness={0.3} />
              </mesh>
            </group>
          );
        })}

    </group>
  );
}

/** Перерисовываем деталь только когда изменился сам объект */
export const Деталь = memo(ДетальВнутренняя, (a, b) => a.obj === b.obj);
