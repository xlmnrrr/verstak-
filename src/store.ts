import { create } from 'zustand';
import type { CameraMode, Dims, ModuleDef, Obj, Project, Room } from './types';
import { новый_проект, пустая_комната } from './types';
import { модульПоИд } from './data/modules';
import { новыйИд, автоПолки } from './lib/utils';
import * as хранилище from './lib/storage';

export type Экран = 'меню' | 'комната' | 'редактор' | 'проекты';
export type Инструмент = 'выбрать' | 'двигать' | 'крутить' | 'растянуть';

/** Функция снятия превью — регистрируется 3D-сценой */
let снятьПревью: (() => string | undefined) | null = null;
export const зарегистрироватьПревью = (fn: () => string | undefined) => {
  снятьПревью = fn;
};

export interface Состояние {
  экран: Экран;
  проект: Project;
  выбрано: string[];
  инструмент: Инструмент;
  обзор: CameraMode;
  шагСетки: number;
  сеткаВидна: boolean;
  прилипание: boolean;
  поиск: string;
  категория: string | null;
  /** Показывать окно подсказок (само скрывается через 10 секунд) */
  подсказкаВидна: boolean;
  /** Показывать правую панель «Конструктор» */
  панельВидна: boolean;
  сообщение: { текст: string; вид: 'инфо' | 'ошибка' } | null;
  занято: boolean;

  прошлое: Project[];
  будущее: Project[];

  // навигация
  наЭкран: (э: Экран) => void;
  создать: (название: string, комната: Room) => void;
  загрузить: (п: Project) => void;

  // инструменты
  выбрать: (ids: string[]) => void;
  добавитьКлик: (id: string) => void;
  выбратьИнструмент: (и: Инструмент) => void;
  установитьОбзор: (о: CameraMode) => void;
  установитьШаг: (ш: number) => void;
  переключитьСетку: () => void;
  переключитьПрилипание: () => void;
  установитьПоиск: (с: string) => void;
  установитьКатегорию: (к: string | null) => void;
  показатьПодсказку: () => void;
  скрытьПодсказку: () => void;
  переключитьПодсказку: () => void;
  переключитьПанель: () => void;
  сообщить: (текст: string, вид?: 'инфо' | 'ошибка') => void;
  закрытьСообщение: () => void;

  // объекты
  начатьИзменение: () => void;
  добавитьМодуль: (ид: string, позиция?: [number, number, number]) => string | null;
  обновитьОбъект: (ид: string, патч: Partial<Obj>) => void;
  обновитьГабариты: (ид: string, патч: Partial<Dims>) => void;
  удалитьВыбранное: () => void;
  копироватьВыбранное: () => void;
  сброситьРазмер: (ид: string) => void;
  обновитьКомнату: (патч: Partial<Room>) => void;

  // история
  отменить: () => void;
  вернуть: () => void;

  // файлы
  сохранить: () => Promise<void>;
  открыть: (имя: string) => Promise<void>;
  открытьФайл: () => Promise<void>;
  выгрузить: () => Promise<void>;
  удалить: (имя: string) => Promise<void>;
  показатьПапку: () => Promise<void>;
}

const копия = (п: Project): Project => JSON.parse(JSON.stringify(п));

export const useКухня = create<Состояние>((set, get) => ({
  экран: 'меню',
  проект: новый_проект('Новый проект', пустая_комната()),
  выбрано: [],
  инструмент: 'двигать',
  обзор: 'сверху',
  шагСетки: 50,
  сеткаВидна: true,
  прилипание: true,
  поиск: '',
  категория: null,
  подсказкаВидна: true,
  панельВидна: true,
  сообщение: null,
  занято: false,
  прошлое: [],
  будущее: [],

  наЭкран: (э) => set({ экран: э }),

  создать: (название, комната) =>
    set({
      проект: новый_проект(название, комната),
      выбрано: [],
      прошлое: [],
      будущее: [],
      экран: 'редактор',
      обзор: 'сверху',
    }),

  загрузить: (п) =>
    set({
      проект: п,
      выбрано: [],
      прошлое: [],
      будущее: [],
      экран: 'редактор',
      обзор: п.настройки?.режим_обзора ?? 'сверху',
      шагСетки: п.настройки?.шаг_сетки ?? 50,
    }),

  выбрать: (ids) => set({ выбрано: ids }),
  добавитьКлик: (id) => {
    const в = get().выбрано;
    set({ выбрано: в.includes(id) ? в.filter((x) => x !== id) : [...в, id] });
  },
  выбратьИнструмент: (и) => set({ инструмент: и }),
  установитьОбзор: (о) => set({ обзор: о }),
  установитьШаг: (ш) => set({ шагСетки: ш }),
  переключитьСетку: () => set({ сеткаВидна: !get().сеткаВидна }),
  переключитьПрилипание: () => set({ прилипание: !get().прилипание }),
  установитьПоиск: (с) => set({ поиск: с }),
  установитьКатегорию: (к) => set({ категория: к }),
  показатьПодсказку: () => set({ подсказкаВидна: true }),
  скрытьПодсказку: () => set({ подсказкаВидна: false }),
  переключитьПодсказку: () => set({ подсказкаВидна: !get().подсказкаВидна }),
  переключитьПанель: () => set({ панельВидна: !get().панельВидна }),
  сообщить: (текст, вид = 'инфо') => set({ сообщение: { текст, вид } }),
  закрытьСообщение: () => set({ сообщение: null }),

  начатьИзменение: () => {
    const { проект, прошлое } = get();
    set({ прошлое: [...прошлое.slice(-49), копия(проект)], будущее: [] });
  },

  добавитьМодуль: (ид, позиция) => {
    const опр = модульПоИд(ид);
    if (!опр) {
      get().сообщить(`Модуль «${ид}» не найден в каталоге`, 'ошибка');
      return null;
    }
    get().начатьИзменение();
    const { проект } = get();
    const к = проект.комната;
    const низ = опр.крепление === 'навесное' ? (опр.подъём_по_умолчанию ?? 1500) : 0;

    // Куда поставить: вдоль задней стены по центру, а если место занято — сдвигаем в сторону.
    const занято = (x: number, z: number) =>
      get().проект.объекты.some(
        (o) =>
          Math.abs(o.позиция[0] - x) < (o.габариты.ш + опр.габариты.ш) / 2 &&
          Math.abs(o.позиция[2] - z) < (o.габариты.г + опр.габариты.г) / 2,
      );
    let x = 0;
    let z = Math.round(-к.ширина / 2 + опр.габариты.г / 2);
    let попыток = 0;
    while (занято(x, z) && попыток < 60) {
      x += опр.габариты.ш + 20;
      if (x > к.длина / 2 - опр.габариты.ш / 2) {
        x = Math.round(-к.длина / 2 + опр.габариты.ш / 2);
        z += опр.габариты.г + 20;
      }
      попыток++;
    }
    if (попыток >= 60) {
      get().сообщить(
        `Свободного места для «${опр.название}» не нашлось — поставил в центр, подвинь мышкой`,
      );
      x = 0;
      z = 0;
    }

    const поз: [number, number, number] = позиция ?? [Math.round(x), низ, Math.round(z)];
    const полки =
      опр.полки === 'авто' ? автоПолки(опр.габариты.в, опр.цоколь ?? 0) : (опр.полки ?? 0);
    const объект: Obj = {
      id: новыйИд(),
      модуль: опр.id,
      название: опр.название,
      позиция: поз,
      поворот: 0,
      габариты: { ...опр.габариты },
      подъём: низ,
      цвет: опр.цвет,
      материал: опр.материал,
      ящиков: опр.ящиков ?? 0,
      полок: полки,
      цоколь: опр.цоколь ?? 0,
      ножки: опр.ножки ?? 0,
      вид: опр.вид,
      фасад: опр.фасад ?? 'нет',
    };
    set({
      проект: { ...проект, объекты: [...проект.объекты, объект], изменён: new Date().toISOString() },
      выбрано: [объект.id],
    });
    return объект.id;
  },

  обновитьОбъект: (ид, патч) => {
    const { проект } = get();
    set({
      проект: {
        ...проект,
        изменён: new Date().toISOString(),
        объекты: проект.объекты.map((o) => (o.id === ид ? { ...o, ...патч } : o)),
      },
    });
  },

  обновитьГабариты: (ид, патч) => {
    const { проект } = get();
    const был = проект.объекты.find((o) => o.id === ид);
    let подрезано: string[] = [];
    set({
      проект: {
        ...проект,
        изменён: new Date().toISOString(),
        объекты: проект.объекты.map((o) => {
          if (o.id !== ид) return o;
          const опр = модульПоИд(o.модуль);
          const новые: Dims = { ...o.габариты, ...патч };
          if (опр) {
            const мин = опр.мин ?? { ш: 50, г: 50, в: 50 };
            const макс = опр.макс ?? { ш: 4000, г: 1200, в: 3000 };
            const до = { ...новые };
            новые.ш = Math.min(макс.ш, Math.max(мин.ш, новые.ш));
            новые.г = Math.min(макс.г, Math.max(мин.г, новые.г));
            новые.в = Math.min(макс.в, Math.max(мин.в, новые.в));
            подрезано = [];
            if (новые.ш !== до.ш) подрезано.push(`ширина → ${новые.ш} мм (допустимо ${мин.ш}…${макс.ш})`);
            if (новые.г !== до.г) подрезано.push(`глубина → ${новые.г} мм (допустимо ${мин.г}…${макс.г})`);
            if (новые.в !== до.в) подрезано.push(`высота → ${новые.в} мм (допустимо ${мин.в}…${макс.в})`);
          }
          const полки = опр?.полки === 'авто' ? автоПолки(новые.в, o.цоколь ?? 0) : (o.полок ?? 0);
          return { ...o, габариты: новые, полок: полки };
        }),
      },
    });
    if (подрезано.length && был) {
      get().сообщить(`Размер ограничен: ${подрезано.join('; ')}`, 'ошибка');
    }
  },

  удалитьВыбранное: () => {
    const { проект, выбрано } = get();
    if (!выбрано.length) return;
    get().начатьИзменение();
    set({
      проект: { ...проект, объекты: проект.объекты.filter((o) => !выбрано.includes(o.id)) },
      выбрано: [],
    });
  },

  копироватьВыбранное: () => {
    const { проект, выбрано } = get();
    if (!выбрано.length) return;
    get().начатьИзменение();
    const новые = проект.объекты
      .filter((o) => выбрано.includes(o.id))
      .map((o) => ({
        ...o,
        id: новыйИд(),
        позиция: [o.позиция[0] + 100, o.позиция[1], o.позиция[2] + 100] as [number, number, number],
      }));
    set({
      проект: { ...проект, объекты: [...проект.объекты, ...новые] },
      выбрано: новые.map((o) => o.id),
    });
  },

  сброситьРазмер: (ид) => {
    const { проект } = get();
    const о = проект.объекты.find((x) => x.id === ид);
    if (!о) return;
    const опр = модульПоИд(о.модуль);
    if (!опр) return;
    get().начатьИзменение();
    get().обновитьГабариты(ид, { ...опр.габариты });
    get().сообщить(`Размер возвращён к стандартному: ${опр.габариты.ш}×${опр.габариты.г}×${опр.габариты.в}`);
  },

  обновитьКомнату: (патч) => {
    const { проект } = get();
    set({ проект: { ...проект, комната: { ...проект.комната, ...патч } } });
  },

  отменить: () => {
    const { прошлое, будущее, проект } = get();
    if (!прошлое.length) return;
    const пред = прошлое[прошлое.length - 1];
    set({
      прошлое: прошлое.slice(0, -1),
      будущее: [копия(проект), ...будущее].slice(0, 50),
      проект: пред,
      выбрано: [],
    });
  },

  вернуть: () => {
    const { прошлое, будущее, проект } = get();
    if (!будущее.length) return;
    const след = будущее[0];
    set({
      будущее: будущее.slice(1),
      прошлое: [...прошлое, копия(проект)],
      проект: след,
      выбрано: [],
    });
  },

  сохранить: async () => {
    const { проект } = get();
    set({ занято: true });
    try {
      const превью = снятьПревью?.();
      const имя = проект.название || 'Проект';
      const итог = await хранилище.сохранитьПроект({ ...проект, название: имя }, превью);
      if (итог.ок) get().сообщить(`Сохранено: ${имя}.kitchen${итог.путь ? ` → ${итог.путь}` : ''}`);
      else get().сообщить(`Не сохранено: ${итог.ошибка}`, 'ошибка');
    } finally {
      set({ занято: false });
    }
  },

  открыть: async (имя) => {
    set({ занято: true });
    try {
      const р = await хранилище.открытьПроект(имя);
      if (р.ок && р.проект) {
        get().загрузить(р.проект);
        if (р.предупреждения.length) get().сообщить(р.предупреждения.join(' '));
      } else {
        get().сообщить(`Не открылось. ${р.ошибки.slice(0, 4).join(' · ')}`, 'ошибка');
      }
    } finally {
      set({ занято: false });
    }
  },

  открытьФайл: async () => {
    set({ занято: true });
    try {
      const р = await хранилище.открытьИзФайла();
      if (р.ок && р.проект) {
        get().загрузить(р.проект);
        get().сообщить(`Открыт проект «${р.проект.название}»${р.предупреждения.length ? '. ' + р.предупреждения.join(' ') : ''}`);
      } else if (р.ошибки.length) {
        get().сообщить(`Файл не подошёл. ${р.ошибки.slice(0, 4).join(' · ')}`, 'ошибка');
      }
    } finally {
      set({ занято: false });
    }
  },

  выгрузить: async () => {
    const { проект } = get();
    const р = await хранилище.выгрузитьВФайл(проект);
    get().сообщить(р.ок ? `Файл сохранён: ${р.путь}` : 'Не удалось сохранить файл', р.ок ? 'инфо' : 'ошибка');
  },

  удалить: async (имя) => {
    await хранилище.удалитьПроект(имя);
    get().сообщить(`Удалён проект «${имя}»`);
  },

  показатьПапку: async () => {
    await хранилище.открытьПапкуПроектов();
  },
}));
