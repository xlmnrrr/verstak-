  /* ------------------------------------------------------------ проверка «влезает» */

  private запланироватьПроверку() {
    if (this.таймерПроверки || this.режим === 'обложка') return;
    this.таймерПроверки = window.setTimeout(() => {
      this.таймерПроверки = 0;
      if (this.освобождено) return;
      const с = useКухня.getState();
      // на жесте двигаются выбранные: проверяем только их, остальное берём из прошлой полной проверки
      let сырые: Проблема[];
      if (с.жест === 'идёт' && this.сырыеПроблемы && с.выбрано.length) {
        const движутся = new Set(с.выбрано);
        const прежние = this.сырыеПроблемы.filter((x) => !движутся.has(x.id) && !(x.с && движутся.has(x.с)));
        сырые = [...прежние, ...проверитьВлезает(с.проект2, движутся)];
      } else {
        сырые = проверитьВлезает(с.проект2);
      }
      this.сырыеПроблемы = сырые;
      const активные = new Map(с.проект2.объекты.filter((о) => о.помещение === с.помещениеАктивное).map((о) => [о.id, true]));
      this.проблемы = сырые.filter((x) => активные.has(x.id));
      const худшие = new Map<string, Проблема>();
      for (const п of this.проблемы) {
        const был = худшие.get(п.id);
        if (!был || п.мм > был.мм) худшие.set(п.id, п);
      }
      useКухня.setState({ проблем: худшие.size });
      this.пересчитатьОткрывание();
      // «Свободная сборка»: красных контуров и меток нет, список проблем остаётся в this.проблемы и в окне «Проверки»
      const тихо = !!с.проект2.настройки.свободная_сборка;
      // красный контур: не влезает или не открывается (счётчик «проблем» открывание не меняет)
      const краснЫе = new Set(тихо ? [] : [...худшие.keys(), ...this.конфликтыОткрывания.map((к) => к.id)]);
      const цели = [...краснЫе].map((id) => this.сборщик.запись(id)?.цель).filter((x) => !!x);
      this.контурПроблем.обновить(цели as NonNullable<(typeof цели)[number]>[]);
      // HTML-метки с цифрой
      const нужные = new Set(тихо ? [] : худшие.keys());
      for (const [id, эл] of this.метки) {
        if (!нужные.has(id)) {
          эл.remove();
          this.метки.delete(id);
        }
      }
      if (this.о.оверлей) {
        for (const [id, п] of тихо ? [] : худшие) {
          let эл = this.метки.get(id);
          if (!эл) {
            эл = document.createElement('div');
            эл.className = 'метка-влезает';
            this.о.оверлей.appendChild(эл);
            this.метки.set(id, эл);
          }
          эл.textContent = `⚠ ${п.мм} мм`;
          эл.title = п.текст;
          эл.dataset.вид = п.вид;
        }
      }
      this.попроситьКадр();
    }, 120);
  }

