  private синхронизировать(принудительно: boolean) {
    const с = useКухня.getState();
    const р = this.ссылки;
    const новыйПроект = с.открытий !== this.открытий;
    if (новыйПроект) {
      this.сырыеПроблемы = null;
      this.открытий = с.открытий;
      // открыли сохранённый проект: через 3 с (текстуры догрузились) обновляем его лист на обложке
      if (this.режим === 'редактор') {
        window.clearTimeout(this.таймерПревью);
        this.таймерПревью = window.setTimeout(() => void useКухня.getState().освежитьПревью(), 3000);
      }
      this.сборщик.сброс();
      this.lod.сброс();
      this.пол.обновить(undefined);
      р.о = undefined;
      р.п = undefined;
      this.ключОбласти = '';
      this.ключГраниц = '';
    }
    const изменилсяПроект = с.проект2.объекты !== р.о || с.проект2.помещения !== р.п || с.помещениеАктивное !== р.а || принудительно || новыйПроект;
    this.размерыГрязно = true;
    const свободная = !!с.проект2.настройки.свободная_сборка;
    if (свободная !== this.свободнаяБыла) {
      this.свободнаяБыла = свободная;
      this.запланироватьПроверку();
    }
    const изменилсяВид = с.выбрано !== р.в || с.инструмент !== р.и || с.обзор !== (р.ж as string);

    if (изменилсяПроект) {
      const было = р.о;
      р.о = с.проект2.объекты;
      р.п = с.проект2.помещения;
      р.а = с.помещениеАктивное;
      this.применитьПроект(с.проект2, с.помещениеАктивное, было === undefined);
    }
    const качество = с.проект2.настройки.качество;
    if (качество !== this.режимКачества) {
      this.режимКачества = качество;
      const имя: ИмяПрофиля = качество === 'авто' ? this.видеокарта.профиль : качество;
      this.применитьПрофиль(ПРОФИЛИ[имя], 'настройка');
    }
    const фонЭфф = this.эффективныйФон(с.проект2.настройки.фон);
    if (фонЭфф !== this.фонТекущий) this.установитьФон(фонЭфф);

    if (изменилсяПроект && this.последнийЧас !== null) this.обновитьЛампы();
    if (изменилсяПроект || изменилсяВид) {
      р.в = с.выбрано;
      р.и = с.инструмент;
      р.ж = с.обзор;
      this.обновитьВыделение();
    }
    if (с.обзор !== this.последнийОбзор) {
      this.последнийОбзор = с.обзор;
      this.камераОбзора.пресет(с.обзор);
    }
    this.обновитьПодписиОтметок();
    this.попроситьКадр();
  }

  /** Подписи отметок на стенах: только в редакторе и при открытом окне «Помещение»; выбранная — латунью */
