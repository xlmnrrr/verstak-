  private обновитьЛампы() {
    const час = this.последнийЧас;
    const ночь = час != null && (час >= 19 || час < 7.5);
    const с = useКухня.getState();
    const вКомнате = ночь ? с.проект2.объекты.filter((о) => о.помещение === с.помещениеАктивное && о.изделие.startsWith('светильник')) : [];
    const точечные = вКомнате.filter((о) => изделиеПоИд(о.изделие)?.конструкция === 'светильник');
    const светильники = вКомнате.filter((о) => !точечные.includes(о)).slice(0, 4);
    this.обновитьПрожекторы(точечные);
    while (this.лампы.length < светильники.length) {
      const л = new THREE.PointLight('#ffd9a0', 0, 7, 2);
      this.о.scene.add(л);
      this.лампы.push(л);
    }
    this.лампы.forEach((л, i) => {
      const о = светильники[i];
      л.visible = !!о;
      if (о) {
        л.position.set(о.позиция[0] / 1000, (о.позиция[1] + о.габариты.в * 0.9) / 1000, о.позиция[2] / 1000);
        л.intensity = 14;
      }
    });
  }

  /**
   * Вечером над каждым точечным светильником — прожектор вниз (до МАКС_ПРОЖЕКТОРОВ, без теней): пятна света на полу и
   * «арки» на стенах. Светильников больше — свет даёт каждый второй с удвоенной силой (общая освещённость та же).
   */
  private обновитьПрожекторы(точечные: { позиция: [number, number, number]; габариты: { ш: number; г: number; в: number }; изделие: string }[]) {
    const МАКС = 8;
    const шаг = точечные.length > МАКС ? Math.ceil(точечные.length / МАКС) : 1;
    const выбранные = точечные.filter((_, i) => i % шаг === 0).slice(0, МАКС);
    while (this.прожекторы.length < выбранные.length) {
      const л = new THREE.SpotLight('#ffd7a8', 0, 6.5, 1.0, 0.75, 2);
      this.о.scene.add(л, л.target);
      this.прожекторы.push(л);
    }
    this.прожекторы.forEach((л, i) => {
      const о = выбранные[i];
      л.visible = !!о;
      if (!о) return;
      const узкий = о.изделие.includes('цилиндр');
      const x = о.позиция[0] / 1000;
      const z = о.позиция[2] / 1000;
      const y = о.позиция[1] / 1000 - 0.005;
      л.position.set(x, y, z);
      л.target.position.set(x, 0, z);
      л.target.updateMatrixWorld();
      л.angle = узкий ? 0.5 : 1.0;
      л.penumbra = узкий ? 0.5 : 0.8;
      л.intensity = (узкий ? 9 : 6) * шаг;
    });
  }

  /** Обложка: медленный облёт камеры вокруг помещения (один постановочный момент приложения, §6 DESIGN.md) */
  private облёт(сейчас: number) {
    const о = this.камераОбзора.текущаяОбласть;
    const cx = (о.x0 + о.x1) / 2;
    const cz = (о.z0 + о.z1) / 2;
    const размер = Math.max(о.x1 - о.x0, о.z1 - о.z0, 2);
    const R = Math.min(размер * 0.72 + 1.3, размер / 2 + 2.8);
    const a = this.спокойствие || this.профиль.имя === 'слабый ноутбук' ? 0.55 : (сейчас / 1000) * 0.09 + 0.55;
    const px = cx + Math.sin(a) * R;
    const pz = cz + Math.cos(a) * R;
    const py = о.высота * 0.85 + размер * 0.2;
    const dx = cx - px;
    const dy = о.высота * 0.3 - py;
    const dz = cz - pz;
    this.камераОбзора.pos.set(px, py, pz);
    this.камераОбзора.yaw = Math.atan2(-dx, -dz);
    this.камераОбзора.pitch = Math.asin(dy / Math.hypot(dx, dy, dz));
    if (!this.спокойствие && this.профиль.имя !== 'слабый ноутбук' && !this.hidden) {
      if (this.профиль.имя === 'среднее') window.setTimeout(() => this.попроситьКадр(), 33);
      else this.попроситьКадр();
    }
  }

  /** Настоящая фаска вблизи: проверка, когда камера заметно сдвинулась (не чаще раза в 100 мс) */
  /** Для проверок: принудительно «настоящая» (все изделия с фаской) или «шейдер» (ни одного); 'авто' — по расстоянию */
  режимФаски: 'авто' | 'шейдер' | 'настоящая' = 'авто';
  private применённыйРежимФаски = 'авто';
  private числоФасок = 0;

  проверитьФаску(сейчас: number) {
    // доделываем перестройку, начатую в прошлых кадрах (бюджет — несколько миллисекунд на кадр)
    if (this.сборщик.фасокВОчереди) {
      this.сборщик.обработатьОчередьФасок(3);
      this.попроситьКадр();
    }
    // «Фото»: настоящая фаска у всех изделий (новые изделия добавляются в набор при следующей проверке)
    const режим = this.режимФаски === 'авто' && this.профиль.фото ? 'настоящая' : this.режимФаски;
    if (режим !== 'авто') {
      const все = режим === 'настоящая' ? this.сборщик.идыЭкземпляров() : [];
      if (this.применённыйРежимФаски !== режим || (режим === 'настоящая' && все.length !== this.числоФасок)) {
        this.применённыйРежимФаски = режим;
        this.числоФасок = все.length;
        this.сборщик.установитьФаски(new Set(все));
        this.попроситьКадр();
      }
      return;
    }
    if (this.применённыйРежимФаски !== 'авто') {
      this.применённыйРежимФаски = 'авто';
      this.lod.сброс();
      this.сборщик.установитьФаски(new Set());
    }
    if (this.профиль.фаскиМакс <= 0 || !this.lod.нужна(сейчас)) return;
    const { gl } = this.о;
    const высотаПикс = (gl.domElement.clientHeight || 800) * gl.getPixelRatio();
    const набор = this.lod.обновить(сейчас, высотаПикс, this.профиль.фаскиМакс);
    if (набор) {
      this.сборщик.установитьФаски(набор);
      this.попроситьКадр();
    }
  }

