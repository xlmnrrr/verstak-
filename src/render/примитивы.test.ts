import { describe, expect, it } from 'vitest';
import { КАТАЛОГ_V2, изделиеПоИд } from '../model/каталог';
import { новыйЭкземпляр } from '../model/проект';
import { битыКромки, примитивыВПозе, примитивыЭкземпляра, ключДеталей, МАКС_ДЕТАЛЕЙ } from './примитивы';

describe('кромка → биты граней', () => {
  it('боковина, дно и полка с передней кромкой получают грань +Z (бит 4)', () => {
    const изд = изделиеПоИд('тумба-ящики-600')!;
    const экз = новыйЭкземпляр(изд, 'п1');
    const р = примитивыЭкземпляра(изд, экз);
    // по ролям из детали(): боковины, дно, крыша
    const ПЛЮС_Z = 1 << 4;
    const плиты = р.примитивы.filter((п) => п.форма === 'плита' && (п.биты & 63) === ПЛЮС_Z);
    expect(плиты.length).toBeGreaterThanOrEqual(3);
  });

  it('длина1 — нормаль вдоль оси ширины, плюс-сторона', () => {
    // плита [600 по X, 16 по Y, 500 по Z]: длина по X, ширина по Z
    expect(битыКромки([600, 16, 500], { длина1: 0.4, длина2: 0, ширина1: 0, ширина2: 0 })).toBe(1 << 4);
    expect(битыКромки([600, 16, 500], { длина1: 0, длина2: 0.4, ширина1: 0, ширина2: 0 })).toBe(1 << 5);
    expect(битыКромки([600, 16, 500], { длина1: 0, длина2: 0, ширина1: 0.4, ширина2: 0 })).toBe(1 << 0);
  });
});

describe('примитивы изделий', () => {
  it('у каждого изделия каталога строится хотя бы один примитив, и все внутри разумных пределов', () => {
    for (const изд of КАТАЛОГ_V2) {
      const экз = новыйЭкземпляр(изд, 'п1');
      const р = примитивыЭкземпляра(изд, экз);
      expect(р.примитивы.length, изд.id).toBeGreaterThan(0);
      expect(р.примитивы.length, изд.id).toBeLessThan(MАКС_ДЕТАЛЕЙ_С_ЗАПАСОМ);
      for (const п of р.примитивы) {
        for (const v of [...п.размер, ...п.t]) expect(Number.isFinite(v), `${изд.id}: ${v}`).toBe(true);
        expect(п.размер.every((v) => v > 0)).toBe(true);
      }
    }
  });

  it('техника, проём и декор раскладываются на примитивы', () => {
    for (const [id, минимум] of [
      ['холодильник-600', 3],
      ['окно-1200', 6],
      ['растение-900', 2],
      ['посуда-декор', 3],
    ] as const) {
      const изд = изделиеПоИд(id)!;
      expect(примитивыЭкземпляра(изд, новыйЭкземпляр(изд, 'п1')).примитивы.length, id).toBeGreaterThanOrEqual(минимум);
    }
  });

  it('штанга — цилиндр, длина по оси X', () => {
    const изд = КАТАЛОГ_V2.find((и) => примитивыЭкземпляра(и, новыйЭкземпляр(и, 'п1')).примитивы.some((п) => п.форма === 'цилиндр' && п.мат === 'ручки'))!;
    expect(изд).toBeDefined();
    const ц = примитивыЭкземпляра(изд, новыйЭкземпляр(изд, 'п1')).примитивы.find((п) => п.форма === 'цилиндр' && п.мат === 'ручки')!;
    // Rz(−90°): локальная Y (длина) → ось X изделия
    expect(ц.R.map((v) => Math.round(v))).toEqual([0, 1, 0, -1, 0, 0, 0, 0, 1]);
  });

  it('поза «открыто» накладывается на закрытую сборку: ящики вперёд, двери поворачиваются, кэш общий', () => {
    const я = изделиеПоИд('тумба-ящики-600')!;
    const экз = новыйЭкземпляр(я, 'п1');
    // открытость не входит в ключ кэша: закрытая сборка одна на все позы
    expect(ключДеталей(я, экз)).toBe(ключДеталей(я, { ...экз, открыт: true }));
    const р = примитивыЭкземпляра(я, экз);
    expect(р.подвижные).toBe(true);
    const закрыто = примитивыВПозе(р, null);
    expect(закрыто.примитивы).toBe(р.примитивы);
    const доли = new Map(р.движения.map((д) => [д.группа, 1]));
    const открыто = примитивыВПозе(р, доли).примитивы;
    const maxZ = (м: typeof открыто) => Math.max(...м.map((п) => п.t[2]));
    expect(maxZ(открыто)).toBeGreaterThan(maxZ(р.примитивы) + 100);
    // на полпути — между закрытым и открытым
    const половина = примитивыВПозе(р, new Map(р.движения.map((д) => [д.группа, 0.5]))).примитивы;
    expect(maxZ(половина)).toBeGreaterThan(maxZ(р.примитивы) + 40);
    expect(maxZ(половина)).toBeLessThan(maxZ(открыто) - 40);

    const д = изделиеПоИд('навесной-600')!;
    const рд = примитивыЭкземпляра(д, новыйЭкземпляр(д, 'п1'));
    const дв = примитивыВПозе(рд, new Map(рд.движения.map((x) => [x.группа, 1]))).примитивы;
    expect(дв.some((п) => п.группа && Math.abs(п.R[2]) > 0.9)).toBe(true);
  });

  it('техника: дверь, ручка и панель — отдельные примитивы, подвижные несут группу', () => {
    const холод = изделиеПоИд('холодильник-600')!;
    const р = примитивыЭкземпляра(холод, новыйЭкземпляр(холод, 'п1'));
    expect(р.движения.length).toBe(2);
    for (const д of р.движения) expect(р.примитивы.filter((п) => п.группа === д.группа).length, д.группа).toBeGreaterThanOrEqual(2);
    expect(р.примитивы.some((п) => !п.группа)).toBe(true);
  });

  it('на 23 изделиях корпус в среднем около 15 деталей (оценка из рендер.md §9.2)', () => {
    const корпуса = КАТАЛОГ_V2.filter((и) => и.тип === 'корпус').slice(0, 23);
    const сред = корпуса.reduce((s, и) => s + примитивыЭкземпляра(и, новыйЭкземпляр(и, 'п1')).примитивы.length, 0) / корпуса.length;
    expect(сред).toBeGreaterThan(8);
    expect(сред).toBeLessThan(60);
  });
});

const MАКС_ДЕТАЛЕЙ_С_ЗАПАСОМ = МАКС_ДЕТАЛЕЙ + 200;
