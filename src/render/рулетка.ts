/**
 * Рулетка: клик по грани, клик по второй — расстояние в мм. Замеры держатся на сцене до очистки.
 * Режим включается кнопкой или клавишей M (useUI.рулетка); пока он включён, клик по сцене — замер, а не выбор.
 */
import type * as THREE from 'three';
import { useUI } from '../store/интерфейс';
import { useКухня } from '../store';
import { изделиеПоИд } from '../model/каталог';
import { коробаСтен } from '../model/стены';
import type { ЦельВыбора } from './выбор';
import { ближайшаяГрань, замерПоГраням, осиПоворота, type Грань, type Замер, type Коробка3 } from './рулетка-математика';
import { Отрезки, ПулПодписей, type Отрезок } from './отрезки';
import type { Луч, В3 } from './жесты-математика';

const ЦВЕТ_ЗАМЕРА: [number, number, number] = [0.3, 0.9, 0.75];
const ЦВЕТ_ГРАНИ: [number, number, number] = [0.94, 0.7, 0.16];

export class Рулетка {
  readonly замеры: Замер[] = [];
  private первая: Грань | null = null;
  private readonly отрезки: Отрезки;
  private readonly подписи: ПулПодписей;

  constructor(
    сцена: THREE.Object3D,
    оверлей: HTMLElement | null,
    private readonly цели: () => { цели: ЦельВыбора[]; ид: string[] },
  ) {
    this.отрезки = new Отрезки(сцена, 15);
    this.подписи = new ПулПодписей(оверлей, 'размер-метка рулетка');
  }

  get включена() {
    return useUI.getState().рулетка;
  }

  /** Коробки мира: части изделий и стены активного помещения (метры) */
  private коробки(): Коробка3[] {
    const итог: Коробка3[] = [];
    const { цели, ид } = this.цели();
    const п = useКухня.getState().проект2;
    цели.forEach((ц, k) => {
      const экз = п.объекты.find((о) => о.id === ид[k]);
      const имя = экз?.название ?? (экз ? изделиеПоИд(экз.изделие)?.название : undefined) ?? 'предмет';
      const оси = осиПоворота(ц.cos, ц.sin);
      for (let i = 0; i * 6 < ц.боксы.length; i++) {
        const b = ц.боксы;
        const lx = b[i * 6], ly = b[i * 6 + 1], lz = b[i * 6 + 2];
        итог.push({
          центр: [ц.позиция[0] + ц.cos * lx - ц.sin * lz, ц.позиция[1] + ly, ц.позиция[2] + ц.sin * lx + ц.cos * lz],
          полу: [b[i * 6 + 3], b[i * 6 + 4], b[i * 6 + 5]],
          оси,
          название: имя,
        });
      }
    });
    const с = useКухня.getState();
    const пом = п.помещения.find((x) => x.id === с.помещениеАктивное);
    if (пом) {
      for (const с2 of коробаСтен(пом).стены) {
        итог.push({
          центр: [с2.центр[0] / 1000, с2.центр[1] / 1000, с2.центр[2] / 1000],
          полу: [с2.размер[0] / 2000, с2.размер[1] / 2000, с2.размер[2] / 2000],
          оси: [[с2.вдоль[0], 0, с2.вдоль[1]], [0, 1, 0], [с2.нормаль[0], 0, с2.нормаль[1]]],
          название: 'стена',
        });
      }
    }
    return итог;
  }

  /** Клик в режиме рулетки: первая грань, вторая грань — замер */
  клик(луч: Луч) {
    const г = ближайшаяГрань(луч, this.коробки());
    if (!г) {
      useКухня.getState().сообщить('Рулетка: кликните по грани предмета, стены или пола');
      return;
    }
    if (!this.первая) {
      this.первая = г;
      useКухня.getState().сообщить(`Рулетка: первая грань («${г.название}»). Кликните вторую`);
    } else {
      const з = замерПоГраням(this.первая, г);
      this.замеры.push(з);
      this.первая = null;
      useКухня.getState().сообщить(`Замер: ${з.мм} мм${з.тип === 'по прямой' ? ' по прямой' : ''} («${з.из}» → «${з.до}»)`);
    }
    this.обновить();
  }

  /** Esc: снять первую грань, а если её нет — выйти из режима */
  отмена(): boolean {
    if (this.первая) {
      this.первая = null;
      this.обновить();
      return true;
    }
    return false;
  }

  убратьПоследний() {
    this.замеры.pop();
    this.первая = null;
    this.обновить();
  }

  очистить() {
    this.замеры.length = 0;
    this.первая = null;
    this.обновить();
  }

  /** Перерисовать линии и подписи; счётчик замеров — в UI-хранилище */
  обновить() {
    const л: Отрезок[] = [];
    const подписи: { точка: В3; текст: string; класс?: string }[] = [];
    for (const з of this.замеры) {
      л.push({ a: з.a, b: з.b, цвет: ЦВЕТ_ЗАМЕРА });
      // засечки на концах: маленький крест из трёх отрезков
      for (const p of [з.a, з.b]) {
        const k = 0.03;
        л.push({ a: [p[0] - k, p[1], p[2]], b: [p[0] + k, p[1], p[2]], цвет: ЦВЕТ_ЗАМЕРА }, { a: [p[0], p[1] - k, p[2]], b: [p[0], p[1] + k, p[2]], цвет: ЦВЕТ_ЗАМЕРА }, { a: [p[0], p[1], p[2] - k], b: [p[0], p[1], p[2] + k], цвет: ЦВЕТ_ЗАМЕРА });
      }
      подписи.push({ точка: [(з.a[0] + з.b[0]) / 2, (з.a[1] + з.b[1]) / 2, (з.a[2] + з.b[2]) / 2], текст: `${з.мм} мм` });
    }
    if (this.первая?.углы) {
      const у = this.первая.углы;
      for (let i = 0; i < 4; i++) л.push({ a: у[i], b: у[(i + 1) % 4], цвет: ЦВЕТ_ГРАНИ });
    }
    if (this.первая) {
      const p = this.первая.точка;
      const k = 0.04;
      л.push({ a: [p[0] - k, p[1], p[2]], b: [p[0] + k, p[1], p[2]], цвет: ЦВЕТ_ГРАНИ }, { a: [p[0], p[1] - k, p[2]], b: [p[0], p[1] + k, p[2]], цвет: ЦВЕТ_ГРАНИ }, { a: [p[0], p[1], p[2] - k], b: [p[0], p[1], p[2] + k], цвет: ЦВЕТ_ГРАНИ });
    }
    this.отрезки.задать(л);
    this.подписи.задать(подписи);
    useUI.setState({ замеровРулетки: this.замеры.length, рулеткаЖдётВторую: !!this.первая });
  }

  расставить(камера: THREE.Camera, r: DOMRect) {
    this.подписи.расставить(камера, r);
  }

  освободить() {
    this.отрезки.освободить();
    this.подписи.освободить();
  }
}
