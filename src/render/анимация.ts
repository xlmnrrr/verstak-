/**
 * Анимация открывания: доля 0…1 по каждой подвижной группе каждого владельца (экземпляр или дверь комнаты).
 * 180 мс с плавным стартом и торможением; считается только поза (transform), геометрия не меняется.
 * Класс чистый (время передаётся снаружи) — под vitest.
 */

export const ДЛИТЕЛЬНОСТЬ_МС = 180;

interface Состояние {
  текущая: number;
  от: number;
  цель: number;
  старт: number;
}

const плавно = (t: number) => t * t * (3 - 2 * t);

export interface ШагАнимации {
  /** у кого изменилась поза на этом шаге */
  изменились: Set<string>;
  /** у кого анимация закончилась именно сейчас */
  закончились: Set<string>;
}

export class Анимации {
  private readonly карта = new Map<string, Map<string, Состояние>>();
  private идут = 0;

  /** Хоть одна анимация ещё не закончена */
  get идёт() {
    return this.идут > 0;
  }

  /**
   * Задать, какие группы владельца должны быть открыты (1) или закрыты (0). Новые владельцы и `мгновенно` — без анимации.
   * Возвращает true, если запущена хотя бы одна анимация.
   */
  задать(владелец: string, цели: ReadonlyMap<string, number>, мгновенно: boolean, сейчас: number): boolean {
    let м = this.карта.get(владелец);
    if (!м) {
      м = new Map();
      this.карта.set(владелец, м);
      мгновенно = true;
    }
    let запущена = false;
    for (const [группа, цель] of цели) {
      let с = м.get(группа);
      if (!с) {
        м.set(группа, { текущая: цель, от: цель, цель, старт: сейчас });
        continue;
      }
      if (с.цель === цель) continue;
      const шла = с.текущая !== с.цель;
      if (мгновенно) {
        с.текущая = с.от = с.цель = цель;
        if (шла) this.идут--;
        continue;
      }
      if (!шла) this.идут++;
      с.от = с.текущая;
      с.цель = цель;
      с.старт = сейчас;
      запущена = true;
    }
    // группы, которых больше нет у изделия
    for (const группа of [...м.keys()]) {
      if (!цели.has(группа)) {
        const с = м.get(группа)!;
        if (с.текущая !== с.цель) this.идут--;
        м.delete(группа);
      }
    }
    return запущена;
  }

  /** Продвинуть все анимации до момента `сейчас` */
  шаг(сейчас: number): ШагАнимации {
    const изменились = new Set<string>();
    const закончились = new Set<string>();
    if (!this.идут) return { изменились, закончились };
    for (const [владелец, м] of this.карта) {
      for (const с of м.values()) {
        if (с.текущая === с.цель) continue;
        const t = Math.min(1, Math.max(0, (сейчас - с.старт) / ДЛИТЕЛЬНОСТЬ_МС));
        с.текущая = t >= 1 ? с.цель : с.от + (с.цель - с.от) * плавно(t);
        изменились.add(владелец);
        if (t >= 1) {
          this.идут--;
          закончились.add(владелец);
        }
      }
    }
    return { изменились, закончились };
  }

  /** Текущие доли владельца: только ненулевые; null — всё закрыто */
  доли(владелец: string): Map<string, number> | null {
    const м = this.карта.get(владелец);
    if (!м) return null;
    let р: Map<string, number> | null = null;
    for (const [г, с] of м) {
      if (с.текущая > 0) (р ??= new Map()).set(г, с.текущая);
    }
    return р;
  }

  /** Текущая доля одной группы */
  доля(владелец: string, группа: string): number {
    return this.карта.get(владелец)?.get(группа)?.текущая ?? 0;
  }

  /** Анимация владельца ещё идёт */
  идётУ(владелец: string): boolean {
    const м = this.карта.get(владелец);
    if (!м) return false;
    for (const с of м.values()) if (с.текущая !== с.цель) return true;
    return false;
  }

  удалить(владелец: string) {
    const м = this.карта.get(владелец);
    if (!м) return;
    for (const с of м.values()) if (с.текущая !== с.цель) this.идут--;
    this.карта.delete(владелец);
  }

  сбросить() {
    this.карта.clear();
    this.идут = 0;
  }
}
