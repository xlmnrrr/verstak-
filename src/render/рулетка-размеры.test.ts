import { describe, expect, it } from 'vitest';
import { изделиеПоИд } from '../model/каталог';
import { новоеПомещение, прямоугольник } from '../model/помещение';
import { зазоры } from '../model/привязка';
import { новыйПроектV2, новыйЭкземпляр } from '../model/проект';
import { ближайшаяГрань, граньКоробки, замерПоГраням, осиПоворота, type Коробка3 } from './рулетка-математика';
import { размерныеЭлементы } from './размеры-геометрия';

const единичная = (центр: [number, number, number], полу: [number, number, number]): Коробка3 => ({ центр, полу, оси: осиПоворота(1, 0) });

describe('рулетка: грани', () => {
  it('луч сверху вниз в крышку: нормаль вверх, точка на высоте, углы грани', () => {
    const к = единичная([0, 0.5, 0], [0.3, 0.5, 0.3]);
    const г = граньКоробки({ о: [0.1, 3, 0.1], н: [0, -1, 0] }, к)!;
    expect(г.нормаль).toEqual([0, 1, 0]);
    expect(г.точка[1]).toBeCloseTo(1, 9);
    expect(г.углы).toHaveLength(4);
    for (const у of г.углы!) expect(у[1]).toBeCloseTo(1, 9);
  });

  it('луч сбоку в боковую грань: нормаль к лучу; мимо коробки — null; начало внутри — null', () => {
    const к = единичная([0, 0.5, 0], [0.3, 0.5, 0.3]);
    const г = граньКоробки({ о: [-3, 0.5, 0], н: [1, 0, 0] }, к)!;
    expect(г.нормаль[0]).toBe(-1);
    expect(г.точка[0]).toBeCloseTo(-0.3, 9);
    expect(граньКоробки({ о: [-3, 5, 0], н: [1, 0, 0] }, к)).toBeNull();
    expect(граньКоробки({ о: [0, 0.5, 0], н: [1, 0, 0] }, к)).toBeNull();
  });

  it('повёрнутая коробка: грань повёрнута вместе с ней', () => {
    const θ = Math.PI / 4;
    const к: Коробка3 = { центр: [0, 0.5, 0], полу: [0.5, 0.5, 0.1], оси: осиПоворота(Math.cos(θ), Math.sin(θ)) };
    const г = граньКоробки({ о: [-3, 0.5, 0], н: [1, 0, 0] }, к)!;
    expect(Math.abs(г.нормаль[0])).toBeCloseTo(Math.SQRT1_2, 6);
    expect(Math.abs(г.нормаль[2])).toBeCloseTo(Math.SQRT1_2, 6);
  });

  it('ближайшая из нескольких и пол', () => {
    const а = единичная([0, 0.5, 0], [0.3, 0.5, 0.3]);
    const б = единичная([0, 0.5, 2], [0.3, 0.5, 0.3]);
    const г = ближайшаяГрань({ о: [0, 0.5, 5], н: [0, 0, -1] }, [а, б])!;
    expect(г.точка[2]).toBeCloseTo(2.3, 9);
    const пол = ближайшаяГрань({ о: [5, 2, 5], н: [0, -1, 0] }, [а, б])!;
    expect(пол.название).toBe('пол');
    expect(пол.точка[1]).toBe(0);
  });
});

describe('рулетка: замер', () => {
  it('две параллельные грани: расстояние между плоскостями вдоль нормали, мм', () => {
    const левый = единичная([0, 0.5, 0], [0.3, 0.5, 0.3]);
    const правый = единичная([1.437 + 0.3, 0.5, 0], [0.3, 0.5, 0.3]);
    const а = граньКоробки({ о: [-3, 0.4, 0.1], н: [1, 0, 0] }, левый)!;
    const б = граньКоробки({ о: [3, 0.7, -0.1], н: [-1, 0, 0] }, правый)!;
    const з = замерПоГраням(а, б);
    expect(з.тип).toBe('между гранями');
    expect(з.мм).toBe(2337); // от левой грани первой коробки (x = −0,3) до правой грани второй (x = 2,037): грани, по которым кликнули
    // отрезок строго вдоль нормали первой грани
    expect(з.a[1]).toBeCloseTo(з.b[1], 9);
    expect(з.a[2]).toBeCloseTo(з.b[2], 9);
  });

  it('пол и низ навесного (антипараллельные): высота', () => {
    const навесной = единичная([0, 1.5 + 0.36, 0], [0.3, 0.36, 0.16]); // низ на 1,5 м
    const пол = ближайшаяГрань({ о: [2, 2, 2], н: [0, -1, 0] }, [])!;
    const низ = граньКоробки({ о: [0, 0.2, 0], н: [0, 1, 0] }, навесной)!;
    expect(замерПоГраням(пол, низ).мм).toBe(1500);
  });

  it('непараллельные грани: по прямой между точками', () => {
    const а = единичная([0, 0.5, 0], [0.3, 0.5, 0.3]);
    const сверху = граньКоробки({ о: [0, 3, 0], н: [0, -1, 0] }, а)!;
    const сбоку = граньКоробки({ о: [3, 0.5, 0], н: [-1, 0, 0] }, а)!;
    const з = замерПоГраням(сверху, сбоку);
    expect(з.тип).toBe('по прямой');
    expect(з.мм).toBe(Math.round(Math.hypot(0.3, 0.5) * 1000));
  });
});

describe('размерные линии', () => {
  const комната = () => новыйПроектV2('т', новоеПомещение('п1', 'кухня', 'Кухня', прямоугольник(3600, 2800)));
  const тумба = (id: string, x: number, z: number) => ({ ...новыйЭкземпляр(изделиеПоИд('тумба-ящики-600')!, 'п1'), id, позиция: [x, 0, z] as [number, number, number] });

  it('ширина, глубина и высота подписаны числами изделия', () => {
    const э = тумба('а', 0, -1100);
    const { метки } = размерныеЭлементы(э, null, 2700);
    expect(метки.map((м) => м.текст)).toEqual([`${э.габариты.ш}`, `${э.габариты.г}`, `${э.габариты.в}`]);
  });

  it('зазоры: подпись с числом мм и линия к соседу; «вплотную» без линии; потолок', () => {
    const п = комната();
    const сосед = тумба('с', -600, -1100); // правая грань −300
    const э = тумба('а', 200, -1100); // левая грань −100: зазор 200
    п.объекты.push(сосед, э);
    const з = зазоры(п, э);
    const { метки, отрезки } = размерныеЭлементы(э, з, 2700);
    const зазорМетки = метки.filter((м) => м.вид === 'зазор').map((м) => м.текст);
    expect(зазорМетки).toContain('200');
    expect(метки.some((м) => м.вид === 'потолок' && м.текст === `до потолка ${2700 - э.габариты.в}`)).toBe(true);
    expect(отрезки.length).toBeGreaterThan(9);
    // вплотную
    const э2 = тумба('б', 0, -1100);
    п.объекты.push(э2);
    const м2 = размерныеЭлементы(э2, зазоры(п, э2), 2700).метки.filter((м) => м.вид === 'зазор').map((м) => м.текст);
    expect(м2).toContain('вплотную');
  });

  it('метры: координаты 1:1000, повёрнутое изделие поворачивает линии', () => {
    const э = { ...тумба('а', 1000, 2000), поворот: 90 };
    const { отрезки } = размерныеЭлементы(э, null, 2700);
    // линия ширины идёт перед изделием (при 90° фасад смотрит в −X): все её точки левее центра на глубину/2 + отступ
    const ширина = отрезки[0];
    expect(ширина.a[0]).toBeCloseTo((1000 - (э.габариты.г / 2 + 100)) / 1000, 6);
    expect(ширина.b[0]).toBeCloseTo((1000 - (э.габариты.г / 2 + 100)) / 1000, 6);
  });
});
