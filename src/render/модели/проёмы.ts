/**
 * Проёмы моделями (проход 2): окно с рамой, створками, стеклом, откосами и подоконником; дверь с коробкой, полотном, наличниками,
 * ручкой и петлями; арка с наличником. Один код на изделие каталога («окно-1200», «дверь-900») и на отметку помещения
 * (окно, дверь, арка в стене).
 * Оси: X — вдоль стены (центр проёма), Y — вверх от низа проёма, Z — поперёк: +Z в комнату, 0 — середина стены толщиной G.
 */
import type { Габариты, Изделие } from '../../model/типы';
import type { Примитив } from '../примитивы';
import { Y_В_X, брус, пруток, точёная } from './строитель';
import { оттенок } from './мебель';

const мм = Math.max;
const мин = Math.min;

/** Число створок по ширине окна: до 1000 — одна, до 2400 — две, дальше по 800 */
export const створокОкна = (W: number) => (W < 1000 ? 1 : W < 2400 ? 2 : Math.round(W / 800));

/** Окно: рама ПВХ, створки, стекло, ручки, откосы, подоконник, отлив */
export function примитивыОкна(W: number, H: number, G: number): Примитив[] {
  const р: Примитив[] = [];
  const профиль = 62;
  const глубина = мин(76, G * 0.76);
  const zР = -G / 2 + глубина / 2 + 22; // рама ближе к наружной стороне
  // рама: четыре профиля
  р.push(брус('пластик-светлый', [0, профиль / 2, zР], [W, профиль, глубина], 4));
  р.push(брус('пластик-светлый', [0, H - профиль / 2, zР], [W, профиль, глубина], 4));
  for (const s of [-1, 1]) р.push(брус('пластик-светлый', [s * (W / 2 - профиль / 2), H / 2, zР], [профиль, H - 2 * профиль + 4, глубина], 4));
  // створки
  const n = створокОкна(W);
  const wВн = W - 2 * профиль;
  const hВн = H - 2 * профиль;
  const wС = wВн / n;
  const пС = 52;
  const gС = глубина - 14;
  for (let i = 0; i < n; i++) {
    const x = -wВн / 2 + wС * (i + 0.5);
    const hS = hВн - 4;
    const wS = wС - 2;
    // рама створки
    р.push(брус('пластик-светлый', [x, профиль + пС / 2 + 2, zР + 6], [wS, пС, gС], 3));
    р.push(брус('пластик-светлый', [x, H - профиль - пС / 2 - 2, zР + 6], [wS, пС, gС], 3));
    for (const s of [-1, 1]) р.push(брус('пластик-светлый', [x + s * (wS / 2 - пС / 2), H / 2, zР + 6], [пС, hS - 2 * пС + 4, gС], 3));
    // стеклопакет
    р.push(брус('стекло-светлое', [x, H / 2, zР + 6], [wS - 2 * пС + 12, hS - 2 * пС + 12, 8], 0.5, { тень: false }));
    // ручка: оливка у середины высоты, на «замковой» стороне
    const правая = i % 2 === 0 ? 1 : -1;
    const xР = x + правая * (wS / 2 - пС / 2);
    р.push(брус('хром', [xР, H / 2 - 20, zР + 6 + gС / 2 + 6], [16, 50, 14], 4, { тень: false }));
    р.push(брус('хром', [xР, H / 2 - 40, zР + 6 + gС / 2 + 10], [14, 50, 10], 4, { тень: false }));
    // петли с противоположной стороны
    for (const dy of [0.2, 0.8]) р.push(пруток('никель', [x - правая * (wS / 2), профиль + hВн * dy, zР + 6 + gС / 2], 12, 34, 'y', undefined, 10));
  }
  // импосты между створками
  for (let i = 1; i < n; i++) р.push(брус('пластик-светлый', [-wВн / 2 + wС * i, H / 2, zР], [24, hВн, глубина - 6], 2));
  // откосы изнутри: потолочная и две боковые панели, окрашены
  const dО = G / 2 - (zР + глубина / 2) + 2;
  const zО = zР + глубина / 2 + dО / 2 - 2;
  р.push(брус('краска-белая', [0, H + 6, zО], [W + 28, 14, dО], 1, { тень: false }));
  for (const s of [-1, 1]) р.push(брус('краска-белая', [s * (W / 2 + 7), H / 2, zО], [14, H + 14, dО], 1, { тень: false }));
  // подоконник: плита с закруглённым вылетом в комнату, наружный отлив
  р.push(брус('эмаль-белая', [0, -14, zР + глубина / 2 + (G / 2 + 80 - (zР + глубина / 2)) / 2], [W + 160, 28, G / 2 + 80 - (zР + глубина / 2) + 0], 6));
  р.push(брус('металл-чёрный', [0, -8, -G / 2 - 12], [W + 20, 4, 70], 1));
  return р;
}

/** Коробка и наличники двери: проём W × H; без полотна (оно рисуется отдельно, оно открывается) */
export function примитивыКоробкиДвери(W: number, H: number, G: number, цвет: string): Примитив[] {
  const р: Примитив[] = [];
  const б = 34; // сечение коробки
  const к = { цвет };
  // коробка: два стояка и притолока во всю толщину стены
  for (const s of [-1, 1]) р.push(брус('краска-белая', [s * (W / 2 - б / 2 + 2), H / 2, 0], [б, H, G - 4], 2, к));
  р.push(брус('краска-белая', [0, H - б / 2 + 2, 0], [W, б, G - 4], 2, к));
  // наличники с двух сторон: Г-образная рамка шириной 70, толщиной 12
  const шН = 70;
  for (const z of [G / 2 + 5, -G / 2 - 5]) {
    for (const s of [-1, 1]) р.push(брус('краска-белая', [s * (W / 2 + шН / 2 - 4), H / 2 + 20, z], [шН, H + 40, 12], 3, { цвет: оттенок(цвет, 0.03) }));
    р.push(брус('краска-белая', [0, H + шН / 2 - 4, z], [W + 2 * шН - 8, шН, 12], 3, { цвет: оттенок(цвет, 0.03) }));
  }
  return р;
}

/** Полотно двери в своих осях: центр полотна в нуле, X — ширина, Y — высота, Z — толщина; ручка и петли на стороне +X (свободный край) */
export function примитивыПолотнаДвери(w: number, h: number, толщ: number, цвет: string): Примитив[] {
  const р: Примитив[] = [];
  const к = { цвет };
  const св = { цвет: оттенок(цвет, 0.05) };
  р.push(брус('краска-белая', [0, 0, 0], [w, h, толщ], 3, к));
  // филёнки: две пары вставок с рамкой (выпуклые на 3 мм, обе стороны)
  const отст = мин(95, w * 0.14);
  const hP = (h - 3 * отст) / 2;
  for (const z of [толщ / 2 + 1.5, -толщ / 2 - 1.5]) {
    for (const y of [-(отст / 2 + hP / 2), отст / 2 + hP / 2]) {
      р.push(брус('краска-белая', [0, y, z], [w - 2 * отст, hP, 4], 1.5, св));
      р.push(брус('краска-белая', [0, y, z], [w - 2 * отст - 26, hP - 26, 5], 1, оттенок(цвет, -0.035) ? { цвет: оттенок(цвет, -0.035) } : к));
    }
  }
  // ручка: розетка и рычаг, на высоте 1000 от пола (низ полотна ≈ −h/2)
  const yР = -h / 2 + 1000;
  for (const s of [-1, 1]) {
    const z = s * (толщ / 2 + 4);
    р.push(точёная('шайба', 'нержавейка-пруток', [w / 2 - 50, yР, z], 52, 8, 'z'));
    р.push(пруток('нержавейка-пруток', [w / 2 - 50 - 52, yР, z + s * 30], 16, 120, 'x', undefined, 14));
    р.push(пруток('нержавейка-пруток', [w / 2 - 50, yР, z + s * 16], 16, 30, 'z', undefined, 14));
  }
  // петли: три накладных на свободной по ручке — противоположной стороне (−X)
  for (const y of [0.12, 0.5, 0.88]) р.push(пруток('никель', [-w / 2 - 1, -h / 2 + h * y, 0], 14, 90, 'y', undefined, 12));
  return р;
}

/** Арка: наличник-обрамление проёма с двух сторон */
export function примитивыАрки(W: number, H: number, G: number, цвет = '#f3efe9'): Примитив[] {
  const р: Примитив[] = [];
  const шН = 60;
  for (const z of [G / 2 + 4, -G / 2 - 4]) {
    for (const s of [-1, 1]) р.push(брус('краска-белая', [s * (W / 2 + шН / 2 - 2), H / 2 + 10, z], [шН, H + 20, 10], 2, { цвет }));
    р.push(брус('краска-белая', [0, H + шН / 2 - 2, z], [W + 2 * шН - 4, шН, 10], 2, { цвет }));
  }
  return р;
}

/** Изделия каталога «Окна и двери»: окно целиком; дверь — коробка, закрытое полотно, наличники */
export function примитивыПроёма(изд: Pick<Изделие, 'id' | 'материалы'>, габ: Габариты): Примитив[] | null {
  const { ш: W, г: G, в: H } = габ;
  if (изд.id.startsWith('окно')) return примитивыОкна(W, H, G);
  if (изд.id.startsWith('дверь')) {
    const ц = изд.материалы.фасад?.startsWith('#') ? изд.материалы.фасад : '#ece8df';
    const wП = W - 70;
    const hП = H - 36;
    const полотно = примитивыПолотнаДвери(wП, hП, 40, ц).map((п) => ({ ...п, t: [п.t[0], п.t[1] + 18 + hП / 2, п.t[2]] as [number, number, number] }));
    return [...примитивыКоробкиДвери(W, H, G, ц), ...полотно];
  }
  return null;
}

