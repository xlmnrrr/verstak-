/**
 * Проход 2: ни одно изделие каталога не рисуется «коробкой вместо вещи». Проверка идёт по готовым примитивам рендера
 * (без three): у техники, мебели, декора, проёмов — настоящие части моделей; ручки корпусов — профилем, а не бруском.
 */
import { describe, expect, it } from 'vitest';
import { КАТАЛОГ_V2 } from '../../model/каталог';
import { новыйЭкземпляр } from '../../model/проект';
import { примитивыЭкземпляра } from '../примитивы';
import { геометрияМодели } from './геометрии-моделей';
import { треугольников } from './геометрии-моделей';

const МОДЕЛЬНЫЕ = new Set(['техника', 'мягкая', 'стул', 'проём', 'декор', 'свет', 'стол']);

describe('каталог: модели вместо коробок', () => {
  for (const изд of КАТАЛОГ_V2) {
    it(`${изд.id}: ${МОДЕЛЬНЫЕ.has(изд.тип) ? 'части моделей' : 'корпус с настоящей фурнитурой'}`, () => {
      const э = новыйЭкземпляр(изд, 'п1');
      const р = примитивыЭкземпляра(изд, э, true).примитивы;
      const модели = р.filter((п) => п.форма === 'модель');
      if (МОДЕЛЬНЫЕ.has(изд.тип) && изд.id !== 'свободный-корпус') {
        // минимум две части модели; для техники и мебели — заметно больше
        expect(модели.length, изд.id).toBeGreaterThanOrEqual(изд.тип === 'техника' || изд.тип === 'мягкая' || изд.тип === 'стул' ? 4 : 2);
        // старые заглушки: плита-коробка с материалом «техника» (общий цвет изделия) не допускается
        expect(р.filter((п) => п.форма === 'плита' && п.мат === 'техника').length, `${изд.id}: плита «техника»`).toBe(0);
      }
      if (изд.тип === 'корпус') {
        // ручка не бруском: плита с материалом «ручки» допустима только в деталировке, но в 3D её заменяет модель
        const ручкаБруском = р.filter((п) => п.форма === 'плита' && п.мат === 'ручки');
        expect(ручкаБруском.length, `${изд.id}: ручка-брусок`).toBe(0);
      }
      // у всех частей моделей строится геометрия (ключи валидны) и она не пустая
      const ключи = new Set(модели.map((п) => п.модель!.геом).filter((г) => !г.startsWith('gltf:')));
      for (const к of ключи) expect(треугольников(к), `${изд.id}: ${к}`).toBeGreaterThan(0);
    });
  }

  it('число треугольников одного изделия вблизи укладывается в бюджет docs/модели.md §5', () => {
    for (const изд of КАТАЛОГ_V2) {
      const э = новыйЭкземпляр(изд, 'п1');
      const р = примитивыЭкземпляра(изд, э, true).примитивы;
      let т = 0;
      for (const п of р) {
        if (п.форма === 'модель' && п.модель && !п.модель.геом.startsWith('gltf:')) т += треугольников(п.модель.геом);
        else if (п.форма === 'плита') т += 12;
        else т += 200;
      }
      // техника ≤ 20 тыс., кровать ≤ 15 тыс., остальное ≤ 12 тыс.: берём общий потолок 30 тыс. — выше значит, что-то построено неэкономно
      expect(т, `${изд.id}: ${т} треугольников`).toBeLessThan(30000);
    }
  });

  it('геометрии растения и шторы строятся детерминированно', () => {
    const a = геометрияМодели('крона:450,500,60');
    const b = геометрияМодели('крона:450,500,60');
    expect(a).toBe(b);
    expect(a.getAttribute('position').count).toBeGreaterThan(300);
  });
});
