/**
 * Фурнитура и конструктив корпусной мебели моделями (проход 2): направляющие ящиков, регулируемые ножки, цокольная планка,
 * профили купе (рамка створки, ролики, верхняя и нижняя направляющие), профиль-гола (ручка-«гривка»), газлифты подъёмников.
 * Работает по готовым деталям из `детали()` и не меняет деталировку: все эти вещи покупные.
 * Размеры — мм в осях изделия.
 */
import type { Вектор3 } from '../../model/типы';
import type { Примитив } from '../примитивы';
import { брус, пруток, точёная } from './строитель';

const мин = Math.min;

/**
 * Телескопические направляющие ящика: подвижная часть на боковине ящика, неподвижная — на боковине корпуса.
 * Бок ящика: центр и объём из `детали()`; `наружу` — знак стороны (+1 вправо, −1 влево).
 */
export function направляющиеЯщика(центр: Вектор3, объём: Вектор3, группа: string | undefined, наружу: number): Примитив[] {
  const [cx, cy, cz] = центр;
  const [ox, oy, oz] = объём;
  const L = мин(oz - 20, 500);
  const xВн = cx + наружу * (ox / 2 + 1.6);
  const xКорп = cx + наружу * (ox / 2 + 5);
  const y = cy - oy / 4;
  const опц = group(группа);
  return [
    // подвижная часть — на боковине ящика, едет вместе с ним
    брус('никель', [xВн, y, cz], [2.6, 14, L], 0.6, опц),
    // неподвижная — на боковине корпуса, чуть длиннее подвижной
    брус('никель', [xКорп, y, cz], [2.4, 20, L + 10], 0.6),
    // ролик на передней кромке подвижной части
    точёная('шайба', 'пластик', [xВн, y, cz + L / 2 - 8], 12, 4, 'x', опц),
  ];
}

const group = (г?: string) => (г ? { группа: г } : {});

/** Регулируемые ножки: четыре опоры у углов корпуса без цоколя (пластиковая тарелка, стальной винт, верхняя планка) */
export function ножкиКорпуса(W: number, D: number, высота: number): Примитив[] {
  const р: Примитив[] = [];
  const h = мин(высота, 200);
  for (const sx of [-1, 1]) {
    for (const sz of [-1, 1]) {
      const x = sx * (W / 2 - 55);
      const z = sz * (D / 2 - 70) + (sz > 0 ? 0 : 0);
      р.push(точёная('шайба', 'пластик', [x, 4, z], 50, 8, 'y'));
      р.push(пруток('хром', [x, h / 2, z], 14, мин(h, мин(h, 200)) - 6, 'y', undefined, 10));
      р.push(брус('пластик', [x, h - 3, z], [44, 6, 44], 1.5));
    }
  }
  return р;
}

/** Цокольная планка: резиновый уплотнитель по нижней кромке цоколя (спереди) */
export function планкаЦоколя(центр: Вектор3, объём: Вектор3): Примитив[] {
  const [cx, cy, cz] = центр;
  const [ox, oy, oz] = объём;
  return [брус('резина', [cx, cy - oy / 2 + 5, cz + oz / 2 + 1.2], [ox - 2, 10, 2.6], 0.8, { тень: false })];
}

/** Купе: алюминиевая рамка створки, вертикальная ручка-профиль, ролики; всё в группе створки */
export function профильКупе(центр: Вектор3, объём: Вектор3, группа: string, номер: number): Примитив[] {
  const [cx, cy, cz] = центр;
  const [ox, oy, oz] = объём;
  const п = 24; // сечение рамки
  const о = group(группа);
  const р: Примитив[] = [];
  // рамка по периметру створки (анодированный алюминий)
  р.push(брус('нержавейка', [cx, cy + oy / 2 - п / 2, cz], [ox, п, oz + 2], 1.2, о));
  р.push(брус('нержавейка', [cx, cy - oy / 2 + п / 2, cz], [ox, п, oz + 2], 1.2, о));
  for (const s of [-1, 1]) р.push(брус('нержавейка', [cx + s * (ox / 2 - п / 2), cy, cz], [п, oy - 2 * п + 2, oz + 2], 1.2, о));
  // ручка-профиль: у края, к которому створка едет (чётные — к правому, нечётные — к левому)
  const край = номер % 2 === 0 ? 1 : -1;
  р.push(брус('металл-чёрный', [cx + край * (ox / 2 - п - 6), cy, cz + oz / 2 + 4], [14, oy * 0.8, 10], 3, о));
  // ролики: два у нижней кромки, два у верхней (видны в зазоре, когда створка сдвинута)
  for (const s of [-1, 1]) {
    р.push(точёная('шайба', 'пластик', [cx + s * (ox / 2 - 70), cy - oy / 2 - 5, cz], 26, 12, 'z', о));
    р.push(точёная('шайба', 'пластик', [cx + s * (ox / 2 - 70), cy + oy / 2 + 5, cz], 26, 10, 'z', о));
  }
  return р;
}

/** Верхняя и нижняя направляющие купе (рельсы по всей ширине корпуса), неподвижные */
export function рельсыКупе(W: number, yНиз: number, yВерх: number, zЦентр: number, глубина: number): Примитив[] {
  return [
    брус('нержавейка', [0, yВерх + 6, zЦентр], [W - 2, 12, глубина], 1),
    брус('нержавейка', [0, yНиз - 4, zЦентр], [W - 2, 8, глубина], 1),
    // два жёлоба на нижнем рельсе для роликов
    брус('металл-чёрный', [0, yНиз, zЦентр + глубина * 0.2], [W - 8, 2.4, 6], 0.5, { тень: false }),
    брус('металл-чёрный', [0, yНиз, zЦентр - глубина * 0.2], [W - 8, 2.4, 6], 0.5, { тень: false }),
  ];
}

/** Профиль-гола (ручка-«гривка»): алюминиевый Г-образный профиль вдоль верхней кромки фасада ящика или длинного края двери */
export function профильГола(центр: Вектор3, объём: Вектор3, группа: string | undefined, вертикальный: boolean, знак = 1, снизу = false): Примитив[] {
  const [cx, cy, cz] = центр;
  const [ox, oy, oz] = объём;
  const о = group(группа);
  const зFront = cz + oz / 2;
  if (вертикальный) {
    // вдоль свободного края двери
    const x = cx + знак * (ox / 2 - 1);
    return [
      брус('нержавейка', [x, cy, зFront - 1], [18, oy - 4, 3], 0.8, о),
      брус('нержавейка', [x + знак * -7, cy, зFront - 10], [3, oy - 4, 20], 0.8, о),
    ];
  }
  const y = снизу ? cy - oy / 2 : cy + oy / 2;
  const к = снизу ? -1 : 1;
  return [
    брус('нержавейка', [cx, y - 8 * к, зFront + 1.4], [ox - 4, 16, 3], 0.8, о),
    брус('нержавейка', [cx, y + 1 * к, зFront - 8], [ox - 4, 3, 20], 0.8, о),
  ];
}

/** Газлифты подъёмного фасада: по одному у каждой боковины, цилиндр и шток (внутри корпуса, у верха) */
export function газлифты(W: number, yВерх: number, z: number): Примитив[] {
  const р: Примитив[] = [];
  for (const s of [-1, 1]) {
    const x = s * (W / 2 - 40);
    р.push(пруток('металл-чёрный', [x, yВерх - 90, z], 18, 150, 'z', undefined, 12));
    р.push(пруток('хром', [x, yВерх - 90, z + 120], 8, 110, 'z', undefined, 10));
    р.push(брус('никель', [x, yВерх - 90, z - 80], [10, 28, 14], 2));
  }
  return р;
}
