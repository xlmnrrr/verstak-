/** Диванная секция (прямая): основание, подлокотники, спинка, подушки; x0..x1 по ширине, z0..z1 по глубине (спинка у z0) */
function секцияДивана(
  c: Цвета,
  x0: number,
  x1: number,
  z0: number,
  z1: number,
  H: number,
  ножки: number,
  подлокотники: [boolean, boolean],
  hПод: number,
  вшПод: number,
  спинка = true,
): Примитив[] {
  const р: Примитив[] = [];
  const ткань = c.ткань;
  const W = x1 - x0;
  const D = z1 - z0;
  const cx = (x0 + x1) / 2;
  const cz = (z0 + z1) / 2;
  const hОсн = 190;
  const yОсн = ножки + hОсн / 2;
  const wПод = [подлокотники[0] ? вшПод : 0, подлокотники[1] ? вшПод : 0];
  const wВ = W - wПод[0] - wПод[1];
  const cxВ = x0 + wПод[0] + wВ / 2;
  // основание под сиденьем и спинка
  р.push(подушка('рогожка', [cxВ, yОсн, cz], [wВ, hОсн, D], 22, 0, { цвет: оттенок(ткань, -0.04) }));
  const dСп = спинка ? 230 : 0;
  const hСп = H - ножки - hОсн;
  if (спинка) р.push(подушка('рогожка', [cxВ, ножки + hОсн + hСп / 2 - 10, z0 + dСп / 2], [wВ, hСп - 20, dСп], 50, 12, { цвет: оттенок(ткань, -0.04) }));
  // подлокотники
  подлокотники.forEach((есть, i) => {
    if (!есть) return;
    const x = i === 0 ? x0 + вшПод / 2 : x1 - вшПод / 2;
    р.push(подушка('рогожка', [x, ножки + (hПод - ножки) / 2 + 30, cz], [вшПод, hПод - ножки - 10, D], 42, 14, { цвет: оттенок(ткань, -0.02) }));
  });
  // ножки: низкие конические, по углам
  for (const sx of [x0 + 70, x1 - 70]) for (const sz of [z0 + 70, z1 - 70]) р.push(точёная('ножка-конус', 'дерево', [sx, ножки / 2, sz], 54, ножки, 'y', { цвет: c.дерево }));
  // сиденья: по одной на ~900 мм
  const n = мм(1, Math.round(wВ / 900));
  const wС = wВ / n;
  const dС = D - dСп + 20;
  for (let i = 0; i < n; i++) {
    const x = cxВ - wВ / 2 + wС * (i + 0.5);
    р.push(подушка('рогожка', [x, ножки + hОсн + 70, z1 - dС / 2 + 6], [wС - 6, 140, dС - 4], 30, 18, { цвет: ткань }));
    if (!спинка) continue;
    // подушка спинки: опирается на сиденье и отклонена назад
    const hС = hСп - 140;
    р.push(подушка('рогожка', [x, ножки + hОсн + 140 + hС / 2 - 20, z0 + dСп + 62], [wС - 6, hС, 170], 46, 16, { цвет: ткань, R: Rx(-10) }));
  }
  return р;
}

function диван(габ: Габариты, c: Цвета, id: string): Примитив[] {
  const { ш: W, г: D, в: H } = габ;
  const ножки = мин(120, H * 0.16);
  const hПод = H * 0.78;
  const вшПод = мин(220, W * 0.1);
  const р = секцияДивана(c, -W / 2, W / 2, -D / 2, D / 2, H, ножки, [true, true], hПод, вшПод);
  // декоративные подушки — спокойные, в тон
  const dП = мин(480, (W - 2 * вшПод) * 0.28);
  const yП = ножки + 190 + 140 + dП * 0.55;
  for (const s of [-1, 1]) {
    р.push(подушка('ткань', [s * (W / 2 - вшПод - dП * 0.62), yП, -D / 2 + 400], [dП, dП, 140], 56, 28, { цвет: оттенок(c.ткань, s > 0 ? 0.28 : -0.22), R: умнож(Rx(-18), Ry(s * 12)) }));
  }
  void id;
  return р;
}

function умнож(a: number[], b: number[]): number[] {
  const р = new Array<number>(9).fill(0);
  for (let i = 0; i < 3; i++) for (let j = 0; j < 3; j++) for (let k = 0; k < 3; k++) р[i * 3 + j] += a[i * 3 + k] * b[k * 3 + j];
  return р;
}

/** Угловой диван: длинная секция вдоль задней стены и оттоманка (шезлонг) справа, обращённая вперёд */
function диванУгловой(габ: Габариты, c: Цвета): Примитив[] {
  const { ш: W, г: D, в: H } = габ;
  const ножки = мин(120, H * 0.16);
  const hПод = H * 0.78;
  const вшПод = 200;
  const dОсн = 980;
  const wШез = мин(1000, W * 0.36);
  const р: Примитив[] = [];
  // главная секция вдоль задней стены
  р.push(...секцияДивана(c, -W / 2, W / 2 - wШез, -D / 2, -D / 2 + dОсн, H, ножки, [true, false], hПод, вшПод));
  // шезлонг: опирается на правую стену, доходит вперёд до D
  р.push(...секцияДивана(c, W / 2 - wШез, W / 2, -D / 2 + dОсн, D / 2, H, ножки, [false, true], hПод, вшПод, false));
  // угловая «спинка» над шезлонгом не нужна: у шезлонга низкий подлокотник
  const dП = 440;
  р.push(подушка('ткань', [-W / 2 + вшПод + 300, ножки + 190 + 140 + dП * 0.55, -D / 2 + 400], [dП, dП, 140], 56, 28, { цвет: оттенок(c.ткань, 0.3), R: умнож(Rx(-18), Ry(12)) }));
  р.push(подушка('ткань', [W / 2 - wШез - 240, ножки + 190 + 140 + dП * 0.55, -D / 2 + 400], [dП, dП, 140], 56, 28, { цвет: оттенок(c.ткань, -0.22), R: умнож(Rx(-18), Ry(-12)) }));
  return р;
}

