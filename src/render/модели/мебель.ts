const мм = Math.max;
const мин = Math.min;

/** Оттенок цвета: k > 0 светлее (к белому), k < 0 темнее (к чёрному) */
export function оттенок(цвет: string | undefined, k: number, запасной = '#8a8d92'): string {
  const ц = (цвет ?? '').replace('#', '');
  const c = ц.length === 6 ? ц : запасной.replace('#', '');
  const ч = [0, 2, 4].map((i) => parseInt(c.slice(i, i + 2), 16));
  const м = ч.map((v) => Math.round(k >= 0 ? v + (255 - v) * k : v * (1 + k)));
  return '#' + м.map((v) => Math.max(0, Math.min(255, v)).toString(16).padStart(2, '0')).join('');
}

export interface Цвета {
  /** обивка и ткань (материал «фасад» изделия) */
  ткань: string;
  /** дерево ножек и рам (материал «корпус» или тёплый орех) */
  дерево: string;
}

export function цветаМебели(изд: Pick<Изделие, 'материалы'>, экзМат?: Partial<Record<string, string>>): Цвета {
  const ф = экзМат?.фасад ?? изд.материалы.фасад;
  const к = экзМат?.корпус ?? изд.материалы.корпус;
  return { ткань: ф && ф.startsWith('#') ? ф : '#8a8d92', дерево: к && к.startsWith('#') ? оттенок(к, -0.1) : '#9a7a52' };
}

