function ножкиСтола(габ: Габариты, c: Цвета, письменный: boolean): Примитив[] {
  const { ш: W, г: D, в: H } = габ;
  const верх = мин(30, H / 4);
  const о = мин(65, W / 4, D / 4);
  const hН = H - верх;
  const р: Примитив[] = [];
  for (const sx of [-1, 1]) for (const sz of [-1, 1]) р.push(точёная('ножка-конус', 'дерево', [sx * (W / 2 - о), hН / 2, sz * (D / 2 - о)], 62, hН, 'y', { цвет: c.дерево }));
  // царги: четыре планки под столешницей и угловые косынки
  const hЦ = 78;
  const yЦ = hН - hЦ / 2;
  for (const s of [-1, 1]) {
    р.push(брус('дерево', [0, yЦ, s * (D / 2 - о)], [W - 2 * о - 40, hЦ, 22], 4, { цвет: c.дерево }));
    р.push(брус('дерево', [s * (W / 2 - о), yЦ, 0], [22, hЦ, D - 2 * о - 40], 4, { цвет: c.дерево }));
  }
  for (const sx of [-1, 1]) for (const sz of [-1, 1]) р.push(брус('дерево', [sx * (W / 2 - о - 28), hН - 40, sz * (D / 2 - о - 28)], [60, 50, 60], 6, { цвет: c.дерево, R: Ry(45) }));
  if (письменный) {
    // ящик под столешницей справа: фасад и скоба
    const wЯ = мин(460, W * 0.32);
    const xЯ = W / 2 - о - 20 - wЯ / 2;
    р.push(брус('дерево', [xЯ, hН - 55, D / 2 - о - 10], [wЯ, 90, 20], 4, { цвет: оттенок(c.дерево, 0.04) }));
    р.push(пруток('нержавейка-пруток', [xЯ, hН - 55, D / 2 - о + 12], 10, мин(130, wЯ * 0.4), 'x', undefined, 12));
  }
  return р;
}

