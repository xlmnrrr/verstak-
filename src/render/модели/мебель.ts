/** Подушки, плед и матрас на кровати без подъёмника; X — ширина матраса, голова у −Z */
export function постель(W: number, G: number, yВерхОснования: number, c: Цвета, zГолова: number): Примитив[] {
  const wМ = W - 40;
  const lМ = G - 120;
  const hМ = 210;
  const yМ = yВерхОснования + hМ / 2 + 6;
  const zМ = zГолова + 20 + lМ / 2;
  const р: Примитив[] = [];
  р.push({ ...подушка('ткань-стёганая', [0, yМ, zМ], [wМ, hМ, lМ], 45, 10, { цвет: '#f1eee8' }), мат: { цвет: '#f1eee8', шер: 1, мет: 0 } });
  // две подушки у изголовья, одеяло-плед сложено у изножья
  const yП = yМ + hМ / 2 + 60;
  for (const s of [-1, 1]) р.push(подушка('ткань', [s * (wМ / 4 + 6), yП - 8, zГолова + 20 + 260], [мин(640, wМ / 2 - 40), 150, 400], 62, 36, { цвет: '#ece8e0', R: Rx(-7) }));
  р.push(подушка('ткань', [0, yМ + hМ / 2 + 10, zМ + lМ * 0.36], [wМ * 0.94, 20, 380], 9, 7, { цвет: оттенок(c.ткань, 0.1) }));
  return р;
}

function кроватьПростая(габ: Габариты, c: Цвета): Примитив[] {
  const { ш: W, г: G } = габ;
  const р = постель(W, G, 450, c, -G / 2 + 90);
  // мягкая обивка изголовья
  const hИ = 560;
  const yИ = габ.в - hИ / 2 - 20;
  р.push(подушка('рогожка', [0, yИ, -G / 2 + 70], [W - 40, hИ, 70], 28, 6, { цвет: c.ткань }));
  return р;
}

/* ============================================================== вход */

/** Модели мебели; null — вид не знаком */
export function примитивыМебели(изд: Pick<Изделие, 'id' | 'тип' | 'материалы'>, габ: Габариты, экзМат?: Partial<Record<string, string>>): Примитив[] | null {
  const c = цветаМебели(изд, экзМат);
  const id = изд.id;
  if (изд.тип === 'стул') {
    if (id.includes('барный')) return стулБарный(габ, c);
    if (id.startsWith('табурет')) return табурет(габ, c);
    return стулОбеденный(габ, c, id.includes('подлокотн'));
  }
  if (изд.тип === 'мягкая') {
    if (id.startsWith('пуф')) return пуф(габ, c);
    if (id.startsWith('кресло')) return кресло(габ, c);
    if (id.includes('угловой')) return диванУгловой(габ, c);
    return диван(габ, c, id);
  }
  if (id === 'банкетка-900') return банкетка(габ, c);
  return null;
}

/** Ножки и царги стола вместо четырёх брусков (столешница остаётся плитой деталировки) */
export function ножкиИзделия(изд: Pick<Изделие, 'id' | 'материалы'>, габ: Габариты, экзМат?: Partial<Record<string, string>>): Примитив[] {
  const c = цветаМебели(изд, экзМат);
  if (изд.id.startsWith('журнальный')) return журнальный(габ, c);
  return ножкиСтола(габ, c, изд.id.includes('письменный'));
}

/** Дополнения к корпусным изделиям (кровать без подъёмника) */
export function дополнениеКорпуса(изд: Pick<Изделие, 'id' | 'материалы'>, габ: Габариты, экзМат?: Partial<Record<string, string>>): Примитив[] {
  const c = цветаМебели(изд, экзМат);
  if (изд.id === 'кровать-1600') return кроватьПростая(габ, c);
  return [];
}

