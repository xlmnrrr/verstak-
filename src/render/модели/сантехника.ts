/**
 * Сантехника моделями (пожелание Макара 13.11.2026): смесители и чаши, чтобы собирать мойку и раковину из частей.
 * Размеры типовые, всё тянется за габариты (геометрия строится по размерам экземпляра).
 *  - смеситель кухонный: основание Ø52, корпус Ø40, рычаг сбоку-сверху, высокий излив-дуга («гусак»), аэратор;
 *  - смеситель для раковины: основание, корпус, плоский излив вперёд, рычаг сверху;
 *  - чаша кухонной мойки (нержавейка): борт-рамка, дно и стенки, выпуск Ø90 с сеткой;
 *  - раковина накладная керамическая: точёная чаша, донный клапан;
 *  - поддон душевой: керамическая плита с бортом и трапом.
 * Оси изделия: фасад в +Z (к человеку), смеситель стоит у задней стороны и тянется изливом вперёд.
 */
import type { Габариты, Вектор3 } from '../../model/типы';
import { ключ } from './геометрии-моделей';
import type { КлассМодели } from './материалы-моделей';
import type { Примитив } from '../примитивы';

const Е = [1, 0, 0, 0, 1, 0, 0, 0, 1];
const Y_В_X = [0, 1, 0, -1, 0, 0, 0, 0, 1];
const Y_В_Z = [1, 0, 0, 0, 0, -1, 0, 1, 0];
/** Дуга (тор в плоскости XY) → в плоскость YZ изделия: x' = −z, y' = y, z' = x */
const ДУГА_В_YZ = [0, 0, -1, 0, 1, 0, 1, 0, 0];
/** Рамка (выдавлена вдоль Z) → лёжа, нормаль вверх: x' = x, y' = z, z' = −y */
const Z_В_Y = [1, 0, 0, 0, 0, 1, 0, -1, 0];

const м = (геом: string, класс: КлассМодели, t: Вектор3, размер: Вектор3, R = Е, тень = true): Примитив => ({ форма: 'модель', модель: { геом, класс }, размер, t, R, мат: 'ручки', биты: 0, r: 0, тень });

export function примитивыСантехники(вариант: string, габ: Габариты, отделка: string | undefined): Примитив[] {
  const { ш: W, г: G, в: H } = габ;
  const металл: КлассМодели = отделка?.includes('чёрн') ? 'металл-чёрный' : отделка?.includes('нерж') ? 'нержавейка-пруток' : 'хром';
  const р: Примитив[] = [];
  switch (вариант) {
    case 'смеситель-кухонный': {
      // стоит у задней стороны габарита; излив — дуга вперёд на W/2 радиусом
      const z0 = -G / 2 + 30;
      const hК = Math.max(120, H * 0.48);
      р.push(м(ключ('точёная', 'кнопка', 54, 14), металл, [0, 7, z0], [54, 14, 54]));
      р.push(м(ключ('пруток', 40, hК, 32), металл, [0, 14 + hК / 2, z0], [40, hК, 40]));
      // рычаг: короткий брус вверх-назад
      р.push(м(ключ('брус', 14, 70, 14, 6), металл, [24, 14 + hК - 10, z0 - 10], [14, 70, 14]));
      // вертикальная труба излива и дуга
      const R = Math.max(60, Math.min(G - 60, H - hК) / 2);
      const hТр = Math.max(20, H - 14 - hК - R - 12);
      р.push(м(ключ('пруток', 24, hТр, 24), металл, [0, 14 + hК + hТр / 2, z0], [24, hТр, 24]));
      const yД = 14 + hК + hТр;
      р.push(м(ключ('дуга', 24, R, 180), металл, [0, yД, z0 + R], [24, R + 12, 2 * R + 24], ДУГА_В_YZ));
      // спуск к аэратору и аэратор
      р.push(м(ключ('пруток', 24, 50, 24), металл, [0, yД - 25, z0 + 2 * R], [24, 50, 24]));
      р.push(м(ключ('пруток', 22, 12, 20), 'никель', [0, yД - 56, z0 + 2 * R], [22, 12, 22]));
      break;
    }
    case 'смеситель-ванной': {
      const z0 = -G / 2 + 30;
      р.push(м(ключ('точёная', 'кнопка', 50, 12), металл, [0, 6, z0], [50, 12, 50]));
      const hК = Math.max(80, H - 40);
      р.push(м(ключ('пруток', 38, hК, 32), металл, [0, 12 + hК / 2, z0], [38, hК, 38]));
      const L = Math.max(60, G - 40);
      р.push(м(ключ('брус', 30, 22, L, 9), металл, [0, 12 + hК - 30, z0 + L / 2 + 6], [30, 22, L]));
      р.push(м(ключ('брус', 18, 12, 60, 5), металл, [0, 12 + hК + 6, z0 - 10], [18, 12, 60]));
      р.push(м(ключ('пруток', 18, 6, 20), 'никель', [0, 12 + hК - 44, z0 + L], [18, 6, 18]));
      break;
    }
    case 'чаша-мойки': {
      // врезная чаша из нержавейки: борт 20 мм лежит на столешнице (верх габарита), чаша уходит вниз на H
      const борт = Math.min(30, W / 6, G / 6);
      р.push(м(ключ('рамка', W, G, борт, 2), 'нержавейка', [0, H - 1, 0], [W, 2, G], Z_В_Y));
      const wЧ = W - 2 * борт;
      const gЧ = G - 2 * борт;
      const hЧ = H - 2;
      for (const s of [-1, 1]) {
        р.push(м(ключ('брус', 1.2, hЧ, gЧ, 0.5), 'нержавейка', [(s * wЧ) / 2, hЧ / 2, 0], [1.2, hЧ, gЧ]));
        р.push(м(ключ('брус', wЧ, hЧ, 1.2, 0.5), 'нержавейка', [0, hЧ / 2, (s * gЧ) / 2], [wЧ, hЧ, 1.2]));
      }
      р.push(м(ключ('брус', wЧ, 1.2, gЧ, 0.5), 'нержавейка', [0, 0.6, 0], [wЧ, 1.2, gЧ]));
      // выпуск Ø90 с сеткой-корзинкой
      р.push(м(ключ('пруток', 90, 3, 40), 'хром', [0, 2.5, Math.min(0, gЧ / 2 - 120)], [90, 3, 90], Е, false));
      р.push(м(ключ('пруток', 60, 2, 32), 'металл-чёрный', [0, 4, Math.min(0, gЧ / 2 - 120)], [60, 2, 60], Е, false));
      break;
    }
    case 'раковина-накладная': {
      // керамическая чаша-«тюльпан» на столешнице: точёная, стенка 8 мм
      const d = Math.min(W, G);
      р.push(м(ключ('точёная', 'чаша', d, H), 'керамика', [0, H / 2, 0], [d, H, d]));
      р.push(м(ключ('пруток', 40, 3, 32), 'хром', [0, 14, 0], [40, 3, 40], Е, false));
      break;
    }
    case 'поддон-душевой': {
      // керамическая плита с бортом и трапом посередине
      р.push(м(ключ('подушка', W, H, G, Math.min(12, H / 3), 0), 'керамика', [0, H / 2, 0], [W, H, G]));
      р.push(м(ключ('рамка', W - 40, G - 40, 26, 3), 'керамика', [0, H + 1, 0], [W - 40, 3, G - 40], Z_В_Y));
      р.push(м(ключ('пруток', 110, 2, 40), 'нержавейка', [0, H + 1, 0], [110, 2, 110], Е, false));
      break;
    }
  }
  return р;
}

export { Y_В_X, Y_В_Z };
