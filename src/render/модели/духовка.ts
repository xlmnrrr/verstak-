/**
 * Эталон 1 (проход 1): встраиваемая духовка моделью. Размеры типовые для ниши 600 (595 × 595 × 570), раскладка
 * совпадает с `model/техника.ts` (панель 72 мм, дверь 517 мм на петле снизу, толщина двери 36 мм), поэтому открывание,
 * развёртка и проверки не меняются: дверь — группа «дверь-0».
 *
 *  - панель управления: шлифованная нержавейка с двумя кнобами и окном дисплея (светится);
 *  - дверь: тёмное стекло с отражением (в «Фото» чуть пропускает — видна камера), рамка из нержавейки,
 *    ручка — пруток Ø20 на двух стойках, нижняя планка; изнутри — светлое внутреннее стекло;
 *  - камера: эмаль, крышка вентилятора, лампа, направляющие на трёх уровнях, решётка, резиновый уплотнитель;
 *  - корпус: тёмный металл (в нише не виден).
 * Вдали (LOD) внутренности камеры не рисуются: снаружи их не видно, а инстансов меньше.
 */
import type { Габариты, Вектор3 } from '../../model/типы';
import { ключ } from './геометрии-моделей';
import type { КлассМодели } from './материалы-моделей';
import type { Примитив } from '../примитивы';

const Е = [1, 0, 0, 0, 1, 0, 0, 0, 1];
const Y_В_X = [0, 1, 0, -1, 0, 0, 0, 0, 1];
const Y_В_Z = [1, 0, 0, 0, 0, -1, 0, 1, 0];
const ДВЕРЬ = 'дверь-0';

const м = (геом: string, класс: КлассМодели, t: Вектор3, размер: Вектор3, R = Е, группа?: string): Примитив => ({
  форма: 'модель',
  модель: { геом, класс },
  размер,
  t,
  R,
  мат: 'техника',
  биты: 0,
  r: 0,
  тень: true,
  ...(группа ? { группа } : {}),
});

/** Брус со скруглением r: размеры по осям изделия */
const брус = (класс: КлассМодели, t: Вектор3, [x, y, z]: Вектор3, r: number, группа?: string) => м(ключ('брус', x, y, z, r, 2), класс, t, [x, y, z], Е, группа);
/** Пруток вдоль оси изделия */
const пруток = (класс: КлассМодели, t: Вектор3, d: number, L: number, ось: 'x' | 'y' | 'z', группа?: string, сег = 16) =>
  м(ключ('пруток', d, L, сег), класс, t, ось === 'x' ? [L, d, d] : ось === 'y' ? [d, L, d] : [d, d, L], ось === 'x' ? Y_В_X : ось === 'z' ? Y_В_Z : Е, группа);

/** Плита (простая коробка) тёмного корпуса: в нише не видна, рисуется дешёвым инстансом плит */
const корпус = (t: Вектор3, размер: Вектор3): Примитив => ({ форма: 'плита', размер, t, R: Е, мат: { цвет: '#26282c', шер: 0.55, мет: 0.45 }, биты: 0, r: 0.5, тень: true });

export function примитивыДуховки(габ: Габариты, детально: boolean): Примитив[] {
  const { ш: W, г: D, в: H } = габ;
  const z0 = D / 2; // лицевая плоскость
  const hП = 72; // панель управления (как в model/техника.ts)
  const hД = H - hП - 6; // дверь
  const yД = 3 + hД / 2; // центр двери
  const толщД = 36;
  const р: Примитив[] = [];

  /* ---------------- панель управления */
  const yП = H - hП / 2;
  р.push(брус('нержавейка', [0, yП, z0 - 10], [W - 4, hП - 4, 20], 1.5));
  // окно дисплея и цифры
  р.push(брус('стекло-тёмное', [0, yП, z0 + 0.6], [128, 30, 2], 1));
  р.push(брус('дисплей', [0, yП, z0 + 1.8], [62, 12, 1], 0.3));
  // кнобы: юбка в панель, тело наружу
  for (const s of [-1, 1]) {
    р.push(м(ключ('точёная', 'кноб', 38, 24), 'нержавейка', [s * (W / 2 - 88), yП, z0 + 12], [38, 38, 24], Y_В_Z));
    // кольцо подсветки под кнобом (тонкая тёмная шайба)
    р.push(пруток('пластик', [s * (W / 2 - 88), yП, z0 + 0.6], 46, 1.4, 'z'));
  }

  /* ---------------- дверь (группа «дверь-0», петля снизу) */
  // наружное тёмное стекло во всю дверь
  р.push(брус('стекло-тёмное', [0, yД, z0 - 3], [W - 6, hД, 6], 2, ДВЕРЬ));
  // рамка двери из нержавейки (видна по торцам и сверху)
  р.push(брус('нержавейка', [0, yД, z0 - 6 - 14], [W - 6, hД, 28], 1.5, ДВЕРЬ));
  // нижняя планка
  р.push(брус('нержавейка', [0, 3 + 7, z0 + 0.5], [W - 6, 12, 7], 1, ДВЕРЬ));
  // внутреннее светлое стекло (видно, когда дверь открыта)
  р.push(брус('стекло-светлое', [0, yД + 10, z0 - толщД - 1.5], [W - 120, hД - 150, 3], 1, ДВЕРЬ));
  // ручка: пруток Ø20 на двух стойках, заглушки
  const yР = 3 + hД - 46;
  const LР = Math.min(480, W - 110);
  р.push(пруток('нержавейка-пруток', [0, yР, z0 + 44], 20, LР, 'x', ДВЕРЬ, 24));
  for (const s of [-1, 1]) {
    р.push(м(ключ('точёная', 'кнопка', 20, 6), 'нержавейка-пруток', [s * (LР / 2 + 2), yР, z0 + 44], [6, 20, 20], Y_В_X, ДВЕРЬ));
    р.push(брус('нержавейка-пруток', [s * (LР / 2 - 34), yР, z0 + 21], [16, 18, 42], 4, ДВЕРЬ));
  }

  /* ---------------- камера */
  const Wк = Math.min(470, W - 120);
  const Hк = Math.min(360, hД - 150);
  const Dк = Math.min(430, D - 120);
  const zФ = z0 - толщД - 6; // передняя плоскость камеры (за уплотнителем)
  const zЗ = zФ - Dк;
  const yН = yД - Hк / 2;
  const yВ = yД + Hк / 2;
  // стенки эмалью
  р.push(брус('эмаль', [0, yД, zЗ + 2], [Wк, Hк, 4], 1));
  for (const s of [-1, 1]) р.push(брус('эмаль', [s * (Wк / 2 - 2), yД, (zФ + zЗ) / 2], [4, Hк, Dк], 1));
  р.push(брус('эмаль', [0, yВ - 2, (zФ + zЗ) / 2], [Wк, 4, Dк], 1));
  р.push(брус('эмаль', [0, yН + 2, (zФ + zЗ) / 2], [Wк, 4, Dк], 1));
  // уплотнитель по проёму камеры
  р.push(м(ключ('рамка', Wк + 36, Hк + 36, 18, 8), 'резина', [0, yД, zФ + 4], [Wк + 36, Hк + 36, 8]));
  if (детально) {
    // крышка вентилятора на задней стенке и лампа в левом верхнем углу
    р.push(пруток('никель', [0, yД, zЗ + 6], Math.min(190, Hк - 60), 5, 'z', undefined, 40));
    р.push(пруток('лампа', [-Wк / 2 + 7, yВ - 45, zЗ + 70], 34, 8, 'x', undefined, 20));
    // направляющие на трёх уровнях
    for (const k of [1, 2, 3]) {
      const y = yН + (Hк * k) / 4;
      for (const s of [-1, 1]) р.push(пруток('хром', [s * (Wк / 2 - 8), y, (zФ + zЗ) / 2 + 10], 5, Dк - 40, 'z', undefined, 8));
    }
    // решётка на втором уровне: рамка и прутки
    const yР2 = yН + Hк / 2 + 6;
    const Lx = Wк - 22;
    const Lz = Dк - 50;
    const zЦ = (zФ + zЗ) / 2 + 5;
    for (const s of [-1, 1]) р.push(пруток('хром', [0, yР2, zЦ + (s * Lz) / 2], 5, Lx, 'x', undefined, 8));
    for (const s of [-1, 1]) р.push(пруток('хром', [(s * Lx) / 2, yР2, zЦ], 5, Lz, 'z', undefined, 8));
    for (let i = 1; i <= 9; i++) р.push(пруток('хром', [-Lx / 2 + (Lx * i) / 10, yР2, zЦ], 3, Lz, 'z', undefined, 6));
  }

  /* ---------------- корпус (в нише не виден) */
  const zК0 = -D / 2;
  const zК1 = zФ;
  р.push(корпус([0, H - hП / 2, (zК0 + z0 - 20) / 2], [W - 2, hП - 6, z0 - 20 - zК0]));
  for (const s of [-1, 1]) р.push(корпус([s * (W / 2 - 6), (H - hП) / 2, (zК0 + zК1) / 2], [12, H - hП, zК1 - zК0]));
  р.push(корпус([0, (yВ + H - hП) / 2, (zК0 + zК1) / 2], [W - 24, Math.max(4, H - hП - yВ), zК1 - zК0]));
  р.push(корпус([0, yН / 2, (zК0 + zК1) / 2], [W - 24, Math.max(4, yН), zК1 - zК0]));
  р.push(корпус([0, (H - hП) / 2, zК0 + 4], [W - 24, H - hП, 8]));
  return р;
}
