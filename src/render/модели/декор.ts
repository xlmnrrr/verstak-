/** Модели декора по id; null — не знаком (остаётся прежняя заглушка) */
export function примитивыДекора(изд: Pick<Изделие, 'id' | 'материалы'>, габ: Габариты, фасад: Ц): Примитив[] | null {
  const id = изд.id;
  const ц = фасад ?? изд.материалы.фасад;
  const н = примитивыНаполнения(id, габ);
  if (н) return н;
  if (id.startsWith('ковёр')) return ковёр(габ, цв(ц, '#8d7f6d'));
  if (id.startsWith('зеркало')) return зеркало(габ, ц, id.includes('напольное'));
  if (id.startsWith('картина')) return картина(габ, ц);
  if (id.startsWith('часы')) return часы(габ);
  if (id.startsWith('штор')) return шторы(габ, ц, id.includes('тюль'));
  if (id.startsWith('светильник-потолочный')) return светПотолочный(габ, ц);
  if (id.startsWith('светильник-подвес')) return светПодвес(габ, ц);
  if (id.startsWith('люстра')) return люстра(габ);
  if (id.startsWith('торшер')) return торшер(габ);
  if (id.startsWith('лампа-настольная')) return лампаНастольная(габ);
  if (id.startsWith('бра')) return бра(габ);
  if (id.startsWith('светильник-трековый')) return светТрековый(габ);
  if (id.startsWith('растение-малое')) return растение(габ, true);
  if (id.startsWith('растение')) return растение(габ, false);
  if (id.startsWith('ваза')) return ваза(габ, ц);
  if (id.startsWith('книги')) return книги(габ);
  if (id.startsWith('посуда')) return посуда(габ);
  if (id.startsWith('ведро')) return ведро(габ, ц);
  if (id.startsWith('телевизор')) return телевизор(габ);
  if (id.startsWith('радиатор')) return радиатор(габ);
  if (id.startsWith('кондиционер')) return кондиционер(габ);
  if (id.startsWith('ванна')) return ванна2(габ);
  if (id.startsWith('унитаз')) return унитаз(габ);
  if (id.startsWith('вешалка')) return вешалка(габ, ц);
  if (id.startsWith('полотенцесушитель')) return полотенцесушитель(габ);
  return null;
}
