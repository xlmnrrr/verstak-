  р.push(брус('металл-чёрный', [0, H - рам / 2, зад + G * 0.62], [W, рам, G * 0.9], 4));
  for (const s of [-1, 1]) р.push(брус('металл-чёрный', [s * (W / 2 - рам / 2), H / 2, зад + G * 0.62], [рам, H - 2 * рам + 2, G * 0.9], 4));
