function шторы(габ: Габариты, цвет: Ц, сТюлем: boolean): Примитив[] {
  const { ш: W, г: G, в: H } = габ;
  const р: Примитив[] = [];
  const зад = -G / 2;
  const ткань = цв(цвет, '#bdb4a4');
  // карниз: труба с кронштейнами и наконечниками
  const yК = H - 40;
  р.push(пруток('латунь', [0, yК, зад + 90], 22, W, 'x', undefined, 18));
  for (const s of [-1, 1]) {
    р.push(шар('латунь', [s * (W / 2 + 4), yК, зад + 90], 40));
    р.push(брус('латунь', [s * (W / 2 - 80), yК + 3, зад + 45], [12, 26, 90], 3));
  }
  // две створки штор со складками, собраны к краям; тюль — на втором карнизе ближе к окну
  const hШ = H - 70;
  const wЧ = W * 0.3;
  for (const s of [-1, 1]) {
    р.push(часть(ключ('штора', wЧ, hШ, 110, 26), 'штора', [s * (W / 2 - wЧ / 2 - 6), hШ / 2 + 4, зад + 100], [wЧ, hШ, 60], { цвет: ткань }));
    // подхват: лента на уровне 1/3 высоты
    р.push(брус('штора', [s * (W / 2 - wЧ * 0.5), hШ * 0.4, зад + 126], [wЧ * 0.7, 18, 12], 4, { цвет: оттенок(ткань, -0.2), тень: false }));
  }
  if (сТюлем) {
    р.push(часть(ключ('штора', W - 120, hШ, 80, 14), 'тюль', [0, hШ / 2 + 4, зад + 40], [W - 120, hШ, 30], { цвет: '#f4f1ea', тень: false }));
  }
  return р;
}

