/**
 * Фурнитура любого корпуса (docs/модели.md §1): ручки настоящим профилем и чашечные петли.
 * Работает по уже готовым деталям и движениям модели — `детали()` и деталировка не меняются.
 *
 *  - Ручка-деталь (брусок 160 × 14 × 22 из `детали()`) → скоба: круглый пруток Ø12 на двух стойках Ø10 с межосевым 128
 *    (типовой ряд 96 / 128 / 160 / 192 / 256 / 320), рейлинг — пруток Ø14 с заглушками, кнопка — точёная.
 *    Брусок вдоль X — горизонтальная ручка, вдоль Y — вертикальная. Ручка остаётся в своей подвижной группе.
 *  - Петля (только вблизи, LOD): на каждой распашной дверце чашка Ø35 в двери (едет с дверью),
 *    плечо и монтажная планка на боковине (стоят). Число по высоте двери: до 900 — 2, до 1600 — 3, до 2000 — 4, выше — 5.
 * Все размеры — мм в осях изделия; геометрии моделей — в метрах, ключи `геометрии-моделей.ts`.
 */
import type { Движение } from '../../model/открывание';
import type { Вектор3 } from '../../model/типы';
import { ключ } from './геометрии-моделей';
import type { КлассМодели } from './материалы-моделей';
import type { Примитив } from '../примитивы';

const Е = [1, 0, 0, 0, 1, 0, 0, 0, 1];
/** Поворот, переводящий ось Y геометрии в X изделия (Rz −90°) и в Z (Rx 90°) */
const Y_В_X = [0, 1, 0, -1, 0, 0, 0, 0, 1];
const Y_В_Z = [1, 0, 0, 0, 0, -1, 0, 1, 0];

function модель(геом: string, класс: КлассМодели, t: Вектор3, размер: Вектор3, R = Е, группа?: string): Примитив {
  return { форма: 'модель', модель: { геом, класс }, размер, t, R, мат: 'ручки', биты: 0, r: 0, тень: true, ...(группа ? { группа } : {}) };
}

/** Межосевое по длине бруска: ближайшее из типового ряда, не длиннее самой ручки */
const РЯД = [96, 128, 160, 192, 256, 320, 448, 640];
const межосевое = (длина: number) => РЯД.filter((x) => x <= длина + 30).pop() ?? 64;

/**
 * Ручка-скоба вместо бруска. Брусок: центр, объём (по осям изделия), фронт — ось выступа (+Z для фасада, −X / +X для
 * плеча углового модуля). Стойки уходят в фасад, пруток — на вылете 28 мм от фасада.
 */
export function ручкаМоделью(центр: Вектор3, объём: Вектор3, вид: 'скоба' | 'рейлинг' | 'кнопка', группа: string | undefined, фронт: [number, number] = [0, 1], класс: КлассМодели = 'нержавейка-пруток'): Примитив[] {
  const [ox, oy, oz] = объём;
  // ось выступа — куда смотрит фасад (у бокового плеча углового модуля — в −X)
  const ВЫСТ: 'x' | 'z' = Math.abs(фронт[0]) > 0.5 ? 'x' : 'z';
  const знак = Math.sign(ВЫСТ === 'x' ? фронт[0] : фронт[1]) || 1;
  const выступ = ВЫСТ === 'z' ? oz : ox;
  // база — плоскость фасада: брусок выступает на 16 мм наружу из 22 (6 мм — «в фасаде»)
  const база = (ВЫСТ === 'z' ? центр[2] : центр[0]) - знак * (выступ / 2 - 6);
  const вПлоскость = (d: number): Вектор3 => (ВЫСТ === 'z' ? [центр[0], центр[1], база + знак * d] : [база + знак * d, центр[1], центр[2]]);
  if (вид === 'кнопка') {
    const d = Math.min(ox, oy, oz === выступ ? oy : oz, 24);
    const t = вПлоскость(13);
    return [модель(ключ('точёная', 'кнопка', Math.max(16, d), 26), 'никель', t, [d, 26, d], ВЫСТ === 'z' ? Y_В_Z : Y_В_X, группа)];
  }
  // длинная ось ручки: вдоль X или Y (у бокового плеча — вдоль Z или Y)
  const плоскостьОси: ('x' | 'y' | 'z')[] = ВЫСТ === 'z' ? ['x', 'y'] : ['z', 'y'];
  const размерПо = (о: 'x' | 'y' | 'z') => (о === 'x' ? ox : о === 'y' ? oy : oz);
  const длинная = размерПо(плоскостьОси[0]) >= размерПо(плоскостьОси[1]) ? плоскостьОси[0] : плоскостьОси[1];
  const L = размерПо(длинная);
  const dП = вид === 'рейлинг' ? 14 : 12;
  const вылет = 30;
  const cc = вид === 'рейлинг' ? Math.max(64, L - 60) : межосевое(L);
  const длинаПрутка = вид === 'рейлинг' ? L : cc + 36;
  const R = длинная === 'x' ? Y_В_X : длинная === 'z' ? Y_В_Z : Е;
  const итог: Примитив[] = [];
  const ц = вПлоскость(вылет);
  итог.push(модель(ключ('пруток', dП, длинаПрутка, 20), класс, ц, длинная === 'x' ? [длинаПрутка, dП, dП] : длинная === 'y' ? [dП, длинаПрутка, dП] : [dП, dП, длинаПрутка], R, группа));
  // торцы прутка: скругление (кнопка-заглушка)
  for (const s of [-1, 1]) {
    const сдвиг = (s * длинаПрутка) / 2;
    const p: Вектор3 = [...ц];
    if (длинная === 'x') p[0] += сдвиг;
    else if (длинная === 'y') p[1] += сдвиг;
    else p[2] += сдвиг;
    итог.push(модель(ключ('точёная', 'кнопка', dП, 4), класс, p, [dП, 4, dП], R, группа));
  }
  // стойки: от фасада до прутка
  for (const s of [-1, 1]) {
    const сдвиг = (s * cc) / 2;
    const p = вПлоскость(вылет / 2);
    if (длинная === 'x') p[0] += сдвиг;
    else if (длинная === 'y') p[1] += сдвиг;
    else p[2] += сдвиг;
    итог.push(модель(ключ('пруток', 10, вылет, 14), класс, p, ВЫСТ === 'z' ? [10, 10, вылет] : [вылет, 10, 10], ВЫСТ === 'z' ? Y_В_Z : Y_В_X, группа));
  }
  return итог;
}

/** Сколько петель на двери высотой h, мм (правило мебельщиков, типовое) */
export const числоПетель = (h: number) => (h <= 900 ? 2 : h <= 1600 ? 3 : h <= 2000 ? 4 : 5);

/**
 * Чашечные петли распашной двери (только вблизи). Движение даёт ось петли (опору), фронт и саму дверь (главная часть).
 * Чашка Ø35 × 12 — во внутренней плоскости двери в 22 мм от края (центр), плечо 46 × 14 × 10 и планка 50 × 12 × 38
 * — на боковине, в 37 мм от её переднего края.
 */
export function петлиДвери(д: Движение): Примитив[] {
  const к = д.кинематика;
  if (к.вид !== 'поворот' || Math.abs(к.ось[1]) < 0.5) return [];
  const [cx, cy, cz] = д.главная.центр;
  const [ox, oy, oz] = д.главная.объём;
  const f = д.фронт;
  // толщина двери по фронту, ширина — поперёк
  const толщ = Math.abs(f[0]) * ox + Math.abs(f[1]) * oz;
  const h = oy;
  const опора = к.опора;
  // от оси петли к центру двери (в плане) — единичный вектор поперёк фронта
  let ux = cx - опора[0];
  let uz = cz - опора[2];
  const дл = Math.hypot(ux, uz) || 1;
  ux /= дл;
  uz /= дл;
  const итог: Примитив[] = [];
  const n = числоПетель(h);
  const y0 = cy - h / 2 + 100;
  const y1 = cy + h / 2 - 100;
  const внутр = (cx * f[0] + cz * f[1]) - толщ / 2; // внутренняя плоскость двери по фронту
  for (let i = 0; i < n; i++) {
    const y = y0 + ((y1 - y0) * i) / (n - 1);
    // чашка: 22 мм от кромки, утоплена на 11 из 12 мм, выступ 1 мм внутрь корпуса
    const вдоль = 22;
    const px = опора[0] + ux * вдоль;
    const pz = опора[2] + uz * вдоль;
    const глубЧашки = внутр - 1.5;
    const чашка: Вектор3 = [f[0] !== 0 ? глубЧашки * f[0] + (1 - Math.abs(f[0])) * px : px, y, f[1] !== 0 ? глубЧашки * f[1] + (1 - Math.abs(f[1])) * pz : pz];
    итог.push(модель(ключ('пруток', 35, 4, 24), 'никель', чашка, [35, 35, 4], Math.abs(f[1]) > 0.5 ? Y_В_Z : Y_В_X, д.группа));
    // плечо: от чашки вглубь корпуса на 46 мм, на 18 мм ближе к боковине; стоит на месте
    const вглубь = 30;
    const плечо: Вектор3 = [чашка[0] - f[0] * вглубь - ux * 6, y, чашка[2] - f[1] * вглубь - uz * 6];
    итог.push(модель(ключ('брус', Math.abs(f[1]) > 0.5 ? 14 : 46, 12, Math.abs(f[1]) > 0.5 ? 46 : 14, 2), 'никель', плечо, Math.abs(f[1]) > 0.5 ? [14, 12, 46] : [46, 12, 14]));
    // монтажная планка на боковине
    const планка: Вектор3 = [чашка[0] - f[0] * 50 - ux * 14, y, чашка[2] - f[1] * 50 - uz * 14];
    итог.push(модель(ключ('брус', Math.abs(f[1]) > 0.5 ? 8 : 38, 48, Math.abs(f[1]) > 0.5 ? 38 : 8, 1.5), 'никель', планка, Math.abs(f[1]) > 0.5 ? [8, 48, 38] : [38, 48, 8]));
  }
  return итог;
}

/**
 * Штанга: хромированная труба Ø25 во всю ширину секции и два держателя-фланца на концах (Ø44 × 6 на боковине,
 * стойка Ø10 до трубы). Деталь-цилиндр из `детали()` даёт центр, длину и ось.
 */
export function штангаМоделью(x: { локально: { центр: Вектор3; объём: Вектор3 }; ось?: 'x' | 'y' | 'z' }): Примитив[] {
  const [cx, cy, cz] = x.локально.центр;
  const [ox, oy, oz] = x.локально.объём;
  const ось = x.ось ?? 'x';
  const L = ось === 'x' ? ox : ось === 'z' ? oz : oy;
  const R = ось === 'x' ? Y_В_X : ось === 'z' ? Y_В_Z : Е;
  const итог: Примитив[] = [модель(ключ('пруток', 25, Math.max(10, L - 8), 24), 'хром', [cx, cy, cz], ось === 'x' ? [L, 25, 25] : [25, 25, L], R)];
  for (const s of [-1, 1]) {
    const p: Вектор3 = ось === 'x' ? [cx + (s * (L - 6)) / 2, cy, cz] : [cx, cy, cz + (s * (L - 6)) / 2];
    итог.push(модель(ключ('точёная', 'кнопка', 44, 6), 'хром', p, ось === 'x' ? [6, 44, 44] : [44, 44, 6], R));
  }
  return итог;
}

/** Полкодержатели: четыре штыря Ø5 с шляпкой под углами полки, у боковин (только вблизи) */
export function полкодержатели(центр: Вектор3, объём: Вектор3): Примитив[] {
  const [cx, cy, cz] = центр;
  const [ox, oy, oz] = объём;
  const итог: Примитив[] = [];
  const y = cy - oy / 2 - 3;
  for (const sx of [-1, 1]) {
    for (const sz of [-1, 1]) {
      const p: Вектор3 = [cx + sx * (ox / 2 - 4), y, cz + sz * (oz / 2 - 40)];
      итог.push(модель(ключ('пруток', 6, 14, 10), 'никель', p, [14, 6, 6], Y_В_X));
    }
  }
  return итог;
}
