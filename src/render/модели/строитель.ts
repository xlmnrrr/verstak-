/**
 * Общие помощники для моделей прохода 2 (docs/модели.md): короткие конструкторы частей — брус, пруток, точёная деталь,
 * подушка, рамка, пирамида, тор. Все размеры — мм в осях изделия (X — ширина, Y — высота от пола, Z — глубина, фасад в +Z),
 * центр части — `t`. Геометрии строит `геометрии-моделей.ts` по ключу; здесь только ключи и поворот.
 */
import type { Вектор3 } from '../../model/типы';
import { ключ } from './геометрии-моделей';
import type { КлассМодели } from './материалы-моделей';
import type { Примитив } from '../примитивы';

export const Е = [1, 0, 0, 0, 1, 0, 0, 0, 1];
/** Ось Y геометрии → X, Z изделия */
export const Y_В_X = [0, 1, 0, -1, 0, 0, 0, 0, 1];
export const Y_В_Z = [1, 0, 0, 0, 0, -1, 0, 1, 0];
/** Выдавленное вдоль Z (рамка) → лёжа, нормаль вверх */
export const Z_В_Y = [1, 0, 0, 0, 0, 1, 0, -1, 0];

const рад = (г: number) => (г * Math.PI) / 180;
/** Поворот вокруг оси на угол в градусах (3×3 по строкам) */
export function Rx(г: number): number[] {
  const c = Math.cos(рад(г));
  const s = Math.sin(рад(г));
  return [1, 0, 0, 0, c, -s, 0, s, c];
}
export function Ry(г: number): number[] {
  const c = Math.cos(рад(г));
  const s = Math.sin(рад(г));
  return [c, 0, s, 0, 1, 0, -s, 0, c];
}
export function Rz(г: number): number[] {
  const c = Math.cos(рад(г));
  const s = Math.sin(рад(г));
  return [c, -s, 0, s, c, 0, 0, 0, 1];
}
/** Произведение матриц a·b (сначала b, потом a) */
export function умн(a: number[], b: number[]): number[] {
  const р = new Array<number>(9).fill(0);
  for (let i = 0; i < 3; i++) for (let j = 0; j < 3; j++) for (let k = 0; k < 3; k++) р[i * 3 + j] += a[i * 3 + k] * b[k * 3 + j];
  return р;
}

export interface Опции {
  R?: number[];
  группа?: string;
  тень?: boolean;
  /** оттенок класса (цвет обивки, дерева); без него — цвет класса как есть */
  цвет?: string;
}

/** Часть модели: ключ геометрии, класс материала, центр, габарит (для выбора) */
export function часть(геом: string, класс: КлассМодели, t: Вектор3, размер: Вектор3, о: Опции = {}): Примитив {
  return {
    форма: 'модель',
    модель: { геом, класс },
    размер,
    t,
    R: о.R ?? Е,
    мат: о.цвет ? { цвет: о.цвет, шер: 1, мет: 0 } : 'ручки',
    биты: 0,
    r: 0,
    тень: о.тень ?? true,
    ...(о.группа ? { группа: о.группа } : {}),
  };
}

/** Брус со скруглением r (мм) вдоль осей изделия */
export const брус = (класс: КлассМодели, t: Вектор3, [x, y, z]: Вектор3, r: number, о: Опции = {}) =>
  часть(ключ('брус', Math.max(0.5, x), Math.max(0.5, y), Math.max(0.5, z), r, 2), класс, t, [x, y, z], о);

/** Пруток (цилиндр) диаметром d и длиной L вдоль оси изделия */
export const пруток = (класс: КлассМодели, t: Вектор3, d: number, L: number, ось: 'x' | 'y' | 'z', о: Опции = {}, сег = 16) =>
  часть(ключ('пруток', d, L, сег), класс, t, ось === 'x' ? [L, d, d] : ось === 'y' ? [d, L, d] : [d, d, L], { ...о, R: ось === 'x' ? Y_В_X : ось === 'z' ? Y_В_Z : Е });

/** Труба без торцов (внутренняя стенка бочки барабана) */
export const трубка = (класс: КлассМодели, t: Вектор3, d: number, L: number, ось: 'x' | 'y' | 'z', о: Опции = {}, сег = 32) =>
  часть(ключ('трубка', d, L, сег), класс, t, ось === 'x' ? [L, d, d] : ось === 'y' ? [d, L, d] : [d, d, L], { ...о, R: ось === 'x' ? Y_В_X : ось === 'z' ? Y_В_Z : Е });

/** Точёная деталь: профиль `вид` (геометрии-моделей.ts), диаметр d, высота h вдоль оси */
export const точёная = (вид: string, класс: КлассМодели, t: Вектор3, d: number, h: number, ось: 'x' | 'y' | 'z' = 'y', о: Опции = {}) =>
  часть(ключ('точёная', вид, d, h), класс, t, ось === 'x' ? [h, d, d] : ось === 'y' ? [d, h, d] : [d, d, h], { ...о, R: о.R ?? (ось === 'x' ? Y_В_X : ось === 'z' ? Y_В_Z : Е) });

/** Мягкая подушка (сиденье, матрас, валик) со скруглением r и выпуклостью верха b */
export const подушка = (класс: КлассМодели, t: Вектор3, [ш, в, г]: Вектор3, r: number, b: number, о: Опции = {}) =>
  часть(ключ('подушка', ш, в, г, r, b), класс, t, [ш, в, г], о);

/** Плоская рамка, лицом в +Z: наружный ш × в, полоса ш1, толщина г */
export const рамка = (класс: КлассМодели, t: Вектор3, ш: number, в: number, ш1: number, г: number, о: Опции = {}) =>
  часть(ключ('рамка', ш, в, ш1, г), класс, t, [ш, в, г], о);

/** Усечённая пирамида: низ ш1 × г1, верх ш2 × г2, высота в; ось Y */
export const пирамида = (класс: КлассМодели, t: Вектор3, ш1: number, г1: number, ш2: number, г2: number, в: number, о: Опции = {}, сдвигZ = 0) =>
  часть(ключ('пирамида', ш1, г1, ш2, г2, в, сдвигZ), класс, t, [Math.max(ш1, ш2), в, Math.max(г1, г2) + Math.abs(сдвигZ)], о);

/** Шар (диаметр d) */
export const шар = (класс: КлассМодели, t: Вектор3, d: number, о: Опции = {}) => часть(ключ('шар', d), класс, t, [d, d, d], о);

/** Тор: труба d по окружности радиуса R, лежит горизонтально (ось Y) */
export const тор = (класс: КлассМодели, t: Вектор3, d: number, R: number, о: Опции = {}) =>
  часть(ключ('дуга', d, R, 360), класс, t, [2 * R + d, d, 2 * R + d], { ...о, R: о.R ?? Rx(-90) });

/** Плита-короб для дешёвого дальнего плана (тёмный корпус в нише) */
export const коробка = (t: Вектор3, размер: Вектор3, цвет = '#26282c'): Примитив => ({ форма: 'плита', размер, t, R: Е, мат: { цвет, шер: 0.55, мет: 0.3 }, биты: 0, r: 0.5, тень: true });

/** Отделка техники по цвету изделия: светлая — белая эмаль, тёмная — чёрное стекло, остальное — нержавейка */
export function отделкаТехники(цвет: string | undefined): 'эмаль-белая' | 'стекло-тёмное' | 'нержавейка' {
  const ц = (цвет ?? '').replace('#', '');
  if (ц.length !== 6) return 'нержавейка';
  const r = parseInt(ц.slice(0, 2), 16);
  const g = parseInt(ц.slice(2, 4), 16);
  const b = parseInt(ц.slice(4, 6), 16);
  const л = (0.299 * r + 0.587 * g + 0.114 * b) / 255;
  const нас = (Math.max(r, g, b) - Math.min(r, g, b)) / 255;
  if (л < 0.28) return 'стекло-тёмное';
  if (л > 0.84 && нас < 0.08) return 'эмаль-белая';
  return 'нержавейка';
}
