/**
 * Техника моделями (проход 2, docs/модели.md): холодильники, морозильник, плита, варочные панели, микроволновка,
 * посудомойка, стиральная и сушильная машины, вытяжки, мойки, кофемашина, винный шкаф.
 * Раскладка и группы открывания совпадают с `model/техника.ts` (дверь-i, люк, козырёк): открывание, развёртка и проверки
 * не меняются. Вдали (LOD) — внешняя оболочка без внутренностей; вблизи (`детально`) корпус полый, внутри полки,
 * корзины, барабан, камера — то, что видно, когда дверь открыта.
 * Оси изделия: X — ширина, Y — высота от пола, Z — глубина, фасад в +Z; центр низа в нуле.
 */
