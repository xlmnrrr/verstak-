function кофемашина(габ: Габариты, отд: Отд): Примитив[] {
  const { ш: W, г: D, в: H } = габ;
  const z0 = D / 2;
  const к: КлассМодели = отд === 'эмаль-белая' ? 'эмаль-белая' : отд === 'нержавейка' ? 'нержавейка' : 'металл-чёрный';
  const р: Примитив[] = [];
  р.push(брус('металл-чёрный', [0, H / 2, -6], [W, H, D - 12], 4));
  // лицевое тёмное стекло и сенсорный экран
  р.push(брус('стекло-тёмное', [0, H / 2, z0 - 4], [W - 8, H - 8, 6], 3));
  р.push(брус('дисплей', [0, H - 70, z0 - 0.5], [W * 0.32, 52, 1], 1, { тень: false }));
  // блок выдачи: носик, поддон и решётка для чашек
  р.push(брус(к, [0, H * 0.58, z0 - 50], [70, 56, 80], 6));
  р.push(пруток('нержавейка-пруток', [-12, H * 0.58 - 36, z0 - 60], 8, 22, 'y'));
  р.push(пруток('нержавейка-пруток', [12, H * 0.58 - 36, z0 - 60], 8, 22, 'y'));
  р.push(брус('нержавейка', [0, H * 0.3, z0 - 80], [W - 140, 8, 130], 3));
  for (let i = 0; i < 9; i++) р.push(брус('металл-чёрный', [-W / 2 + 80 + (i * (W - 160)) / 8, H * 0.3 + 4.5, z0 - 80], [8, 1.5, 120], 0.5, { тень: false }));
  // ручка-вкладка с лотком
  р.push(брус('нержавейка-пруток', [0, 18, z0 - 4], [W * 0.5, 12, 6], 3));
  return р;
}

