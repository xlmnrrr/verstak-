/** Передняя панель-«фасад»: плита материала изделия (цвет фасада) — для встроенной техники под мебельным фасадом */
const плитаФасад = (t: Вектор3, размер: Вектор3, группа?: string): Примитив => ({ форма: 'плита', размер, t, R: Е, мат: 'фасад', биты: 0, r: 0.5, тень: true, ...(группа ? { группа } : {}) });

/** Вертикальная ручка на двух стойках у свободного края двери */
function ручкаСтойка(класс: КлассМодели, x: number, y: number, z0: number, L: number, группа: string, d = 15, вылет = 32): Примитив[] {
  return [
    пруток(класс, [x, y, z0 + вылет], d, L, 'y', { группа }, 20),
    брус(класс, [x, y - L / 2 + 25, z0 + вылет / 2], [d - 3, 14, вылет], 3, { группа }),
    брус(класс, [x, y + L / 2 - 25, z0 + вылет / 2], [d - 3, 14, вылет], 3, { группа }),
    точёная('кнопка', класс, [x, y - L / 2 - 1, z0 + вылет], d, 4, 'y', { группа }),
    точёная('кнопка', класс, [x, y + L / 2 + 1, z0 + вылет], d, 4, 'y', { группа }),
  ];
}
/** Горизонтальная ручка-рейлинг на двух стойках */
function ручкаГоризонт(класс: КлассМодели, x: number, y: number, z0: number, L: number, группа: string, d = 16, вылет = 34): Примитив[] {
  return [
    пруток(класс, [x, y, z0 + вылет], d, L, 'x', { группа }, 20),
    брус(класс, [x - L / 2 + 28, y, z0 + вылет / 2], [14, d - 3, вылет], 3, { группа }),
    брус(класс, [x + L / 2 - 28, y, z0 + вылет / 2], [14, d - 3, вылет], 3, { группа }),
    точёная('кнопка', класс, [x - L / 2 - 1, y, z0 + вылет], d, 4, 'x', { группа }),
    точёная('кнопка', класс, [x + L / 2 + 1, y, z0 + вылет], d, 4, 'x', { группа }),
  ];
}

/** Полая камера: пять плит (низ, верх, зад, два бока) толщины t по границам x0..x1, y0..y1, z0..z1 (передняя сторона открыта) */
function камера(класс: КлассМодели, x0: number, x1: number, y0: number, y1: number, z0: number, z1: number, t: number, r = 1): Примитив[] {
  const w = x1 - x0;
  const h = y1 - y0;
  const g = z1 - z0;
  const cx = (x0 + x1) / 2;
  const cy = (y0 + y1) / 2;
  const cz = (z0 + z1) / 2;
  return [
    брус(класс, [cx, cy, z0 + t / 2], [w, h, t], r),
    брус(класс, [x0 + t / 2, cy, cz], [t, h, g], r),
    брус(класс, [x1 - t / 2, cy, cz], [t, h, g], r),
    брус(класс, [cx, y1 - t / 2, cz], [w, t, g], r),
    брус(класс, [cx, y0 + t / 2, cz], [w, t, g], r),
  ];
}

/* ============================================================== холодильники */

function холодильник(id: string, габ: Габариты, петли: СторонаПетель, отд: Отд, детально: boolean): Примитив[] {
  const { ш: W, г: D, в: H } = габ;
  const z0 = D / 2;
  const вариант = вариантХолодильника(id, W, H);
  const встр = вариант === 'встроенный';
  const винный = id.startsWith('винный');
  const толщ = встр ? 24 : 56;
  const zД = z0 - толщ / 2;
  const зазор = 4;
  const р: Примитив[] = [];
  const классДвери: КлассМодели = винный ? 'металл-чёрный' : отд;
  const ручка: КлассМодели = 'нержавейка-пруток';

  // двери: центр по Y, высота, x, ширина, индекс
  const двери: { y: number; h: number; x: number; w: number }[] = [];
  if (вариант === 'бок-о-бок') {
    const w = (W - 4 - зазор) / 2;
    for (let i = 0; i < 2; i++) двери.push({ y: H / 2, h: H - 6, x: -W / 2 + 2 + w / 2 + i * (w + зазор), w });
  } else if (вариант === 'одна') {
    двери.push({ y: H / 2, h: H - 6, x: 0, w: W - 4 });
  } else {
    const hНиз = Math.round(H * 0.34);
    const hВерх = H - hНиз - зазор;
    двери.push({ y: hНиз + зазор + hВерх / 2, h: hВерх, x: 0, w: W - 4 });
    двери.push({ y: hНиз / 2, h: hНиз, x: 0, w: W - 4 });
  }

  /* ---------- корпус */
  const Dт = D - толщ;
  const zт = -толщ / 2;
  if (!детально || встр) {
    р.push(встр ? коробка([0, H / 2, zт], [W, H, Dт], '#cfd2d6') : брус(отд, [0, H / 2, zт], [W, H, Dт], 6));
  }
  if (детально) {
    // полый корпус: внешняя обшивка 3 мм и светлый пластиковый вкладыш; встроенный — только вкладыш
    if (!встр) {
      for (const s of [-1, 1]) р.push(брус(отд, [s * (W / 2 - 1.5), H / 2, zт], [3, H, Dт], 1));
      р.push(брус(отд, [0, H - 1.5, zт], [W, 3, Dт], 1));
    }
    const л = 22;
    р.push(...камера('пластик-светлый', -W / 2 + 4, W / 2 - 4, 40, H - 4, -D / 2 + 20, z0 - толщ, л, 2));
    // внутренний объём
    const x0 = -W / 2 + 4 + л;
    const x1 = W / 2 - 4 - л;
    const y0 = 40 + л;
    const y1 = H - 4 - л;
    const zз = -D / 2 + 20 + л;
    const zп = z0 - толщ - 4;
    const wв = x1 - x0;
    const gв = zп - zз;
    const cx = (x0 + x1) / 2;
    const cz = (zз + zп) / 2;
    // лампа-полоса под потолком камеры
    р.push(брус('лампа', [cx, y1 - 2, zп - 40], [wв - 80, 3, 14], 1, { тень: false }));
    const делитель = вариант === 'две' ? Math.round(H * 0.34) : 0;
    const полок = Math.max(2, Math.min(5, Math.floor((y1 - y0 - 260) / 190)));
    const yВерхНачало = делитель ? делитель + 8 + 130 : y0 + 150;
    if (вариант === 'бок-о-бок') {
      // две колонки: слева морозильная с ящиками, справа холодильная с полками
      р.push(брус('пластик-светлый', [0, (y0 + y1) / 2, cz], [14, y1 - y0, gв], 1));
      const wЛ = wв / 2 - 7;
      for (let k = 1; k <= 3; k++) р.push(...ящикМорозилки(-wв / 4 - 3.5, y0 + 20 + (k - 1) * ((y1 - y0 - 40) / 3) + 70, cz, wЛ - 16, 120, gв - 80));
      for (let k = 0; k < 5; k++) р.push(...полкаСтеклянная(wв / 4 + 3.5, y0 + 220 + k * 230, cz, wЛ - 10, gв - 60));
    } else {
      for (let k = 0; k < полок; k++) {
        const y = yВерхНачало + k * ((y1 - yВерхНачало - 40) / полок);
        р.push(...полкаСтеклянная(cx, y, cz, wв - 8, gв - 60));
      }
      // ящики для овощей и зелени внизу холодильной части
      if (вариант !== 'одна' || H > 1100) {
        const yЯ = (делитель ? делитель + 8 : y0) + 70;
        for (const s of [-1, 1]) р.push(...ящикМорозилки(cx + (s * wв) / 4, yЯ + 8, cz + 6, wв / 2 - 14, 120, gв - 90, true));
      } else {
        р.push(...ящикМорозилки(cx, y0 + 80, cz + 6, wв - 20, 120, gв - 90, true));
      }
      if (делитель) {
        // перегородка между камерами и два ящика морозилки
        р.push(брус('пластик-светлый', [cx, делитель + 4, cz], [wв + 2 * л, 8, gв], 1));
        for (let k = 0; k < 2; k++) р.push(...ящикМорозилки(cx, 20 + 8 + k * (делитель / 2 - 10) + 50, cz + 6, wв - 20, делитель / 2 - 50, gв - 90));
      }
    }
  }

  /* ---------- двери */
  двери.forEach((дв, i) => {
    const группа = ГРУППЫ_ТЕХНИКИ.дверь(i);
    const о: Опции = { группа };
    const w = дв.w;
    const h = дв.h;
    if (встр) {
      р.push(плитаФасад([дв.x, дв.y, zД], [w, h, толщ], группа));
    } else {
      р.push(брус(классДвери, [дв.x, дв.y, zД], [w, h, толщ], 5, о));
      if (винный) {
        // стеклянная дверь винного шкафа в рамке из чёрного металла
        р.push(брус('стекло-тёмное', [дв.x, дв.y, z0 - 3], [w - 36, h - 40, 4], 2, { группа, тень: false }));
      }
    }
    // изнутри: вкладыш с кармашками и уплотнитель
    if (детально) {
      const zВн = z0 - толщ + 1;
      р.push(брус('пластик-светлый', [дв.x, дв.y, zВн + 4], [w - 8, h - 8, 8], 3, о));
      р.push(рамка('резина', [дв.x, дв.y, zВн - 4], w - 14, h - 14, 16, 10, о));
      const nК = h > 900 ? 4 : 2;
      for (let k = 0; k < nК; k++) {
        const y = дв.y - h / 2 + 140 + k * ((h - 300) / (nК - 1 || 1));
        р.push(брус('стекло-светлое', [дв.x, y, zВн - 22], [w - 70, 3, 36], 1, { группа, тень: false }));
        р.push(брус('пластик-светлый', [дв.x, y + 8, zВн - 38], [w - 70, 16, 3], 1, о));
      }
    }
    // ручка: у свободного края двери
    const с = вариант === 'бок-о-бок' ? (i === 0 ? 'слева' : 'справа') : сторона(петли, i);
    const xКрая = дв.x + (с === 'слева' ? w / 2 : -w / 2);
    const xР = xКрая + (с === 'слева' ? -40 : 40);
    const LР = Math.min(i === 0 && вариант === 'две' ? 450 : 600, h * 0.5, 600);
    const yР = вариант === 'две' ? (i === 0 ? дв.y - h * 0.3 : дв.y + h * 0.1) : H * 0.52;
    if (!винный) р.push(...ручкаСтойка(ручка, xР, yР, z0, LР, группа));
    else р.push(...ручкаСтойка(ручка, xР, дв.y, z0, мм(200, h * 0.6), группа));
    // панель-дисплей на двери side-by-side
    if (вариант === 'бок-о-бок' && i === 0) {
      р.push(брус('стекло-тёмное', [дв.x, H * 0.62, z0 + 0.4], [150, 320, 2], 2, { группа }));
      р.push(брус('дисплей', [дв.x, H * 0.62 + 90, z0 + 1.6], [60, 22, 1], 0.3, { группа, тень: false }));
      р.push(точёная('кнопка', 'хром', [дв.x, H * 0.62 - 30, z0 + 2], 22, 3, 'z', { группа }));
    }
  });
  // винный шкаф: стеклянные полки с бутылками виден сквозь тёмное стекло только вблизи
  if (винный && детально) {
    const w = W - 60;
    const nП = 4;
    for (let k = 0; k < nП; k++) {
      const y = 120 + k * ((H - 200) / nП);
      р.push(брус('дерево', [0, y, 0], [w, 14, D - толщ - 60], 2, { цвет: '#b58b5c' }));
      for (let b = 0; b < Math.floor(w / 85); b++) {
        р.push(пруток('эмаль-белая', [-w / 2 + 48 + b * 85, y + 44, 0], 74, мм(120, D - толщ - 110), 'z', { цвет: ['#1f4a2b', '#2b3a1c', '#3a1d22'][(b + k) % 3] }, 14));
      }
    }
  }
  // цоколь-решётка
  if (!встр) р.push(брус('пластик', [0, 18, z0 - толщ + 8], [W - 30, 30, 10], 2, { тень: false }));
  return р;
}

/** Стеклянная полка с ободком */
function полкаСтеклянная(cx: number, y: number, cz: number, w: number, g: number): Примитив[] {
  return [
    брус('стекло-светлое', [cx, y, cz], [w, 5, g], 1, { тень: false }),
    брус('пластик-светлый', [cx, y + 3, cz + g / 2 - 3], [w, 12, 5], 1),
  ];
}

/** Ящик-контейнер: лоток из светлого стекла-пластика с передней стенкой */
function ящикМорозилки(cx: number, yНиз: number, cz: number, w: number, h: number, g: number, овощи = false): Примитив[] {
  const к: КлассМодели = овощи ? 'стекло-светлое' : 'пластик-светлый';
  return [
    брус(к, [cx, yНиз - h / 2 + 6, cz], [w, 6, g], 2, { тень: false }),
    брус(к, [cx, yНиз - h / 2 + h / 2 - 2, cz + g / 2 - 3], [w, h - 6, 6], 2, { тень: false }),
    брус(к, [cx - w / 2 + 3, yНиз - h / 2 + h / 2 - 2, cz], [6, h - 6, g], 2, { тень: false }),
    брус(к, [cx + w / 2 - 3, yНиз - h / 2 + h / 2 - 2, cz], [6, h - 6, g], 2, { тень: false }),
    брус('пластик-светлый', [cx, yНиз + h / 2 - 8, cz + g / 2 + 1], [w + 4, 14, 8], 2),
  ];
}

function морозильник(габ: Габариты, петли: СторонаПетель, отд: Отд, детально: boolean): Примитив[] {
  const { ш: W, г: D, в: H } = габ;
  const z0 = D / 2;
  const толщ = 48;
  const zД = z0 - толщ / 2;
  const группа = ГРУППЫ_ТЕХНИКИ.дверь(0);
  const о: Опции = { группа };
  const р: Примитив[] = [];
  const Dт = D - толщ;
  if (!детально) р.push(брус(отд, [0, H / 2, -толщ / 2], [W, H, Dт], 6));
  else {
    for (const s of [-1, 1]) р.push(брус(отд, [s * (W / 2 - 1.5), H / 2, -толщ / 2], [3, H, Dт], 1));
    р.push(брус(отд, [0, H - 1.5, -толщ / 2], [W, 3, Dт], 1));
    р.push(...камера('пластик-светлый', -W / 2 + 4, W / 2 - 4, 40, H - 4, -D / 2 + 20, z0 - толщ, 22, 2));
    // выдвижные ящики морозильной камеры: 3–5 по высоте
    const n = Math.max(2, Math.min(6, Math.round((H - 100) / 220)));
    const hЯ = (H - 110) / n;
    for (let k = 0; k < n; k++) р.push(...ящикМорозилки(0, 66 + (k + 1) * hЯ - 10, -толщ / 2 + 4, W - 70, hЯ - 22, Dт - 80));
  }
  р.push(брус(отд, [0, H / 2, zД], [W - 4, H - 6, толщ], 5, о));
  if (детально) {
    р.push(брус('пластик-светлый', [0, H / 2, z0 - толщ + 5], [W - 12, H - 14, 8], 3, о));
    р.push(рамка('резина', [0, H / 2, z0 - толщ - 3], W - 18, H - 22, 16, 10, о));
  }
  const с = сторона(петли, 0);
  const xР = с === 'слева' ? W / 2 - 2 - 40 : -W / 2 + 2 + 40;
  р.push(...ручкаСтойка('нержавейка-пруток', xР, H * 0.62, z0, Math.min(300, H * 0.4), группа));
  р.push(брус('пластик', [0, 18, z0 - толщ + 8], [W - 30, 30, 10], 2, { тень: false }));
  return р;
}

