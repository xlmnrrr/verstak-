/**
 * Модели техники для изделия; `null` — вид не знаком (остаётся прежняя коробочная техника).
 * Духовка и сантехника рисуются своими модулями.
 */
export function примитивыТехники2(изд: Pick<Изделие, 'id' | 'тип'>, габ: Габариты, петли: СторонаПетель, цвет: string | undefined, детально: boolean): Примитив[] | null {
  const вид = видТехники(изд);
  const отд = отделкаТехники(цвет);
  switch (вид) {
    case 'холодильник':
      return холодильник(изд.id, габ, петли, изд.id.startsWith('винный') ? 'нержавейка' : отд, детально);
    case 'морозильник':
      return морозильник(габ, петли, отд, детально);
    case 'плита':
      return плита(габ, отд, детально);
    case 'микроволновка':
      return микроволновка(габ, петли, отд, детально);
    case 'посудомойка':
      return посудомойка(изд.id, габ, отд, детально);
    case 'стиральная':
      return стиральная(изд.id, габ, петли, отд, детально);
    case 'вытяжка-купольная':
      return вытяжкаКупольная(габ, отд);
    case 'вытяжка-встроенная':
      return вытяжкаВстроенная(габ, отд);
    case 'прочее':
      if (изд.id.startsWith('варочная')) return варочная(изд.id, габ, детально);
      if (изд.id.startsWith('мойка-накладная')) return мойкаНакладная(габ);
      if (изд.id.startsWith('мойка-врезная')) return мойкаВрезная(габ);
      if (изд.id.startsWith('кофемашина')) return кофемашина(габ, отд);
      return null;
    default:
      return null;
  }
}

