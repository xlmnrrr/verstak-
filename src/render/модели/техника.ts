function мойкаНакладная(габ: Габариты): Примитив[] {
  const { ш: W, г: D, в: H } = габ;
  const р: Примитив[] = [];
  const t = 1.5;
  // внешний борт: рамка по периметру на высоте верха габарита
  р.push(рамка('нержавейка', [0, H - 10, 0], W, D, 26, 20, { R: Z_В_Y }));
  const wЧ = W * 0.62;
  const gЧ = D - 52;
  const xЧ = -W / 2 + 26 + wЧ / 2 - 12;
  // чаша: стенки и дно
  for (const s of [-1, 1]) {
    р.push(брус('нержавейка', [xЧ + (s * wЧ) / 2, H * 0.5, 0], [t, H - 14, gЧ], 0.6));
    р.push(брус('нержавейка', [xЧ, H * 0.5, (s * gЧ) / 2], [wЧ, H - 14, t], 0.6));
  }
  р.push(брус('нержавейка', [xЧ, 6, 0], [wЧ, t, gЧ], 0.6));
  // выпуск Ø90 с сеткой и перелив
  р.push(точёная('шайба', 'хром', [xЧ, 8, 0], 90, 3));
  р.push(точёная('шайба', 'металл-чёрный', [xЧ, 9.5, 0], 62, 2));
  р.push(брус('нержавейка-пруток', [xЧ, H - 42, gЧ / 2 - 4], [30, 10, 3], 2));
  // сушилка: крыло справа с рифлением, уклон к чаше (ряд лотков)
  const xС = W / 2 - (W - wЧ - 26) / 2 - 12;
  const wС = W - wЧ - 52;
  р.push(брус('нержавейка', [xС, H - 8, 0], [wС, 4, gЧ], 1));
  const nР = Math.max(4, Math.floor((gЧ - 80) / 28));
  for (let i = 0; i < nР; i++) р.push(брус('нержавейка-пруток', [xС, H - 4, -gЧ / 2 + 40 + (i * (gЧ - 80)) / (nР - 1)], [wС - 30, 4, 10], 2, { тень: false }));
  // отверстие под смеситель на борту
  р.push(точёная('шайба', 'хром', [xЧ, H - 0.5, -D / 2 + 13], 36, 2));
  return р;
}

