/**
 * Эталон 3 (проход 1): мягкие части кровати с подъёмником — только рендер (docs/модели.md §1).
 *  - матрас: «подушка» со скруглёнными рёбрами R 45 и лёгкой выпуклостью, стёганая ткань (Fabric008, sheen); едет с основанием;
 *  - мягкая обивка изголовья: «подушка» R 30 на лицевой стороне основы, рогожка (Fabric031); цвет — материал «фасад» изделия;
 *  - кант по периметру матраса (тонкая «подушка»), подушки — модель glTF Poly Haven (CC0), лежат на матрасе у изголовья.
 */
import { ГРУППА_ПОДЪЁМНИКА, размерыКровати } from '../../model/кровать';
import type { Габариты } from '../../model/типы';
import { ключ } from './геометрии-моделей';
import { Rx, подушка } from './строитель';
import type { Примитив } from '../примитивы';

const Е = [1, 0, 0, 0, 1, 0, 0, 0, 1];

export function примитивыКровати(габ: Габариты, цветОбивки: string, _детально: boolean): Примитив[] {
  const р = размерыКровати(габ);
  const { W, H, t, zГ, zН, рама, матрас } = р;
  const G = габ.г;
  const итог: Примитив[] = [];
  // матрас на ламелях
  const yМ = рама.yВерх + 8 + матрас.в / 2;
  const zМ = (zГ + t + zН - t) / 2;
  итог.push({ форма: 'модель', модель: { геом: ключ('подушка', матрас.ш, матрас.в, матрас.г, 45, 10), класс: 'ткань-стёганая' }, размер: [матрас.ш, матрас.в, матрас.г], t: [0, yМ, zМ], R: Е, мат: { цвет: '#f1eee8', шер: 1, мет: 0 }, биты: 0, r: 0, тень: true, группа: ГРУППА_ПОДЪЁМНИКА });
  // кант по середине высоты матраса (тонкая скруглённая полоса)
  итог.push({ форма: 'модель', модель: { геом: ключ('подушка', матрас.ш + 4, 14, матрас.г + 4, 7, 0), класс: 'рогожка' }, размер: [матрас.ш + 4, 14, матрас.г + 4], t: [0, yМ, zМ], R: Е, мат: { цвет: '#cfc8bb', шер: 1, мет: 0 }, биты: 0, r: 0, тень: false, группа: ГРУППА_ПОДЪЁМНИКА });
  // мягкое изголовье: от верха царги до верха основы, толщина 70 на лицевой стороне основы
  const hИ = H - р.верхЦарги + 60;
  const yИ = H - hИ / 2 - 10;
  const zИ = -G / 2 + t * 2 + 35;
  итог.push({ форма: 'модель', модель: { геом: ключ('подушка', W - 30, hИ, 70, 30, 6), класс: 'рогожка' }, размер: [W - 30, hИ, 70], t: [0, yИ, zИ], R: Е, мат: { цвет: цветОбивки, шер: 1, мет: 0 }, биты: 0, r: 0, тень: true });
  // подушки — две, спокойные, у изголовья; сложенный плед у изножья; едут с основанием
  const верхМ = yМ + матрас.в / 2;
  for (const sx of [-1, 1]) итог.push({ ...подушка('ткань', [sx * (матрас.ш / 4 + 6), верхМ + 62, zГ + t + 250], [Math.min(640, матрас.ш / 2 - 40), 150, 400], 62, 36, { цвет: '#ece8e0', R: Rx(-7), группа: ГРУППА_ПОДЪЁМНИКА }) });
  итог.push(подушка('ткань', [0, верхМ + 10, zМ + матрас.г * 0.34], [матрас.ш * 0.94, 20, 380], 9, 7, { цвет: цветОбивки, группа: ГРУППА_ПОДЪЁМНИКА }));
  return итог;
}
