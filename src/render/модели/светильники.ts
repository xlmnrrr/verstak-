/**
 * Точечные светильники моделями (Макар, 13.11.2026). Оси изделия: y = 0 — низ габарита, верх габарита — потолок.
 * Размеры типовые, всё тянется за габариты:
 *  - GX53: плоский фланец у потолка (3 мм), под ним корпус лампы ⌀0,74 и светящаяся опаловая линза;
 *  - LED-спот: тонкий борт 2 мм и рассеиватель вровень;
 *  - накладной цилиндр: корпус-труба, крышка у потолка, внизу утопленная на 14 мм лампа в тёмном отражателе.
 * Линза — класс «лампа» (светится; ночью над ней ещё и прожектор вниз — ядро.обновитьЛампы).
 */
import type { Габариты } from '../../model/типы';
import { ключ } from './геометрии-моделей';
import type { КлассМодели } from './материалы-моделей';
import type { Примитив } from '../примитивы';

const Е = [1, 0, 0, 0, 1, 0, 0, 0, 1];

const м = (геом: string, класс: КлассМодели, t: [number, number, number], размер: [number, number, number], тень = false): Примитив => ({ форма: 'модель', модель: { геом, класс }, размер, t, R: Е, мат: 'ручки', биты: 0, r: 0, тень });

/** Отделка кольца по названию материала «ручки» */
export function классКольца(отделка: string | undefined): КлассМодели {
  const о = (отделка ?? '').toLowerCase();
  if (о.includes('хром')) return 'хром';
  if (о.includes('чёрн') || о.includes('черн')) return 'металл-чёрный';
  if (о.includes('латун') || о.includes('золот')) return 'латунь';
  if (о.includes('никел') || о.includes('сатин')) return 'никель';
  return 'краска-белая';
}

export function примитивыСветильника(вариант: string, габ: Габариты, отделка: string | undefined): Примитив[] {
  const D = Math.min(габ.ш, габ.г);
  const H = Math.max(2, габ.в);
  const к = классКольца(отделка);
  const р: Примитив[] = [];
  switch (вариант) {
    case 'led': {
      const ф = Math.min(2, H);
      р.push(м(ключ('точёная', 'фланец', D, ф), к, [0, H - ф / 2, 0], [D, ф, D]));
      // рассеиватель чуть ниже борта (0,5 мм) — без мерцания граней
      р.push(м(ключ('пруток', D * 0.82, 1, 48), 'лампа', [0, H - ф - 0.2, 0], [D * 0.82, 1, D * 0.82]));
      break;
    }
    case 'цилиндр': {
      const кр = Math.min(4, H / 4);
      р.push(м(ключ('точёная', 'фланец', D * 1.04, кр), к, [0, H - кр / 2, 0], [D * 1.04, кр, D * 1.04]));
      const hТ = Math.max(4, H - кр - 14);
      // корпус: труба сверху до кольца-отражателя
      р.push(м(ключ('пруток', D, hТ, 48), к, [0, 14 + hТ / 2, 0], [D, hТ, D], true));
      // нижнее кольцо с отверстием: изнутри видно тёмный отражатель и утопленную лампу
      р.push(м(ключ('точёная', 'кольцо-84', D, 14), к, [0, 7, 0], [D, 14, D], true));
      р.push(м(ключ('пруток', D * 0.84, 2, 40), 'металл-чёрный', [0, 13, 0], [D * 0.84, 2, D * 0.84]));
      р.push(м(ключ('пруток', D * 0.5, 1, 32), 'лампа', [0, 11.5, 0], [D * 0.5, 1, D * 0.5]));
      break;
    }
    default: {
      // GX53
      const ф = Math.min(3, H / 3);
      р.push(м(ключ('точёная', 'фланец', D, ф), к, [0, H - ф / 2, 0], [D, ф, D]));
      const hК = Math.max(1, H - ф);
      р.push(м(ключ('точёная', 'линза', D * 0.74, hК), 'краска-белая', [0, hК / 2, 0], [D * 0.74, hК, D * 0.74]));
      р.push(м(ключ('пруток', D * 0.62, 1.2, 48), 'лампа', [0, 0.35, 0], [D * 0.62, 1.2, D * 0.62]));
    }
  }
  return р;
}
