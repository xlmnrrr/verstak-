/**
 * Наполнение корпусов моделями (проход 2): проволочная корзина, брючница, сушилка для посуды, мусорная система, лоток для приборов.
 * Ставятся внутрь корпуса как отдельные изделия (габарит — место в корпусе). Оси: фасад (передний край) в +Z.
 */
import type { Габариты } from '../../model/типы';
import type { Примитив } from '../примитивы';
import { брус, пруток, точёная } from './строитель';

const мин = Math.min;
const мм = Math.max;

function корзина(габ: Габариты): Примитив[] {
  const { ш: W, г: D, в: H } = габ;
  const р: Примитив[] = [];
  const d = 5;
  // каркас: верхний и нижний прямоугольные контуры, стойки по углам
  for (const y of [d / 2, H - d / 2]) {
    for (const s of [-1, 1]) {
      р.push(пруток('хром', [0, y, (s * (D - d)) / 2], d, W, 'x', undefined, 8));
      р.push(пруток('хром', [(s * (W - d)) / 2, y, 0], d, D, 'z', undefined, 8));
    }
  }
  for (const sx of [-1, 1]) for (const sz of [-1, 1]) р.push(пруток('хром', [(sx * (W - d)) / 2, H / 2, (sz * (D - d)) / 2], d, H, 'y', undefined, 8));
  // дно: сетка из прутков; борта — по два прутка
  const nX = мм(4, Math.floor(W / 50));
  const nZ = мм(4, Math.floor(D / 50));
  for (let i = 1; i < nX; i++) р.push(пруток('хром', [-W / 2 + (W * i) / nX, d / 2 + 4, 0], 3.5, D - 4, 'z', undefined, 6));
  for (let i = 1; i < nZ; i++) р.push(пруток('хром', [0, d / 2 + 4, -D / 2 + (D * i) / nZ], 3.5, W - 4, 'x', undefined, 6));
  for (const y of [H * 0.4, H * 0.72]) {
    for (const s of [-1, 1]) {
      р.push(пруток('хром', [(s * (W - d)) / 2, y, 0], 3.5, D, 'z', undefined, 6));
      р.push(пруток('хром', [0, y, (s * (D - d)) / 2], 3.5, W, 'x', undefined, 6));
    }
  }
  // направляющие по бокам
  for (const s of [-1, 1]) р.push(брус('никель', [(s * (W + 8)) / 2, H * 0.55, 0], [4, 16, D - 20], 1));
  return р;
}

function брючница(габ: Габариты): Примитив[] {
  const { ш: W, г: D, в: H } = габ;
  const р: Примитив[] = [];
  for (const s of [-1, 1]) {
    р.push(брус('нержавейка', [(s * (W - 14)) / 2, H / 2, 0], [14, H, D], 2));
    р.push(брус('никель', [(s * (W + 4)) / 2, H / 2, 0], [4, мин(H, 20), D - 30], 1));
  }
  // поперечные штанги-выдвижные, по 9 на всю глубину
  const n = мм(5, Math.floor(D / 45));
  for (let i = 0; i < n; i++) р.push(пруток('хром', [0, H / 2 + 6, -D / 2 + 30 + (i * (D - 60)) / (n - 1)], 10, W - 20, 'x', undefined, 10));
  р.push(брус('нержавейка', [0, H - 7, D / 2 - 4], [W - 4, 14, 8], 2));
  return р;
}

function сушилка(габ: Габариты): Примитив[] {
  const { ш: W, г: D, в: H } = габ;
  const р: Примитив[] = [];
  const d = 4;
  const hП = 30;
  // поддон
  р.push(брус('нержавейка', [0, hП / 2, 0], [W, hП, D], 3));
  // два яруса решёток: верхний — для тарелок (стойки через 30 мм), нижний — для чашек
  const яруса = [{ y: hП + 20, h: H * 0.4 }, { y: hП + H * 0.5, h: H * 0.34 }];
  for (const [k, я] of яруса.entries()) {
    for (const s of [-1, 1]) р.push(пруток('хром', [0, я.y, (s * (D - d)) / 2], d, W - 20, 'x', undefined, 8));
    for (const s of [-1, 1]) р.push(пруток('хром', [(s * (W - 20)) / 2, я.y, 0], d, D - d, 'z', undefined, 8));
    const n = мм(6, Math.floor((W - 40) / 28));
    for (let i = 0; i < n; i++) {
      const x = -W / 2 + 20 + (i * (W - 40)) / (n - 1);
      if (k === 0) р.push(пруток('хром', [x, я.y + я.h / 2, 0], d, я.h, 'y', undefined, 6));
      else р.push(пруток('хром', [x, я.y + 14, (i % 2 ? 1 : -1) * (D / 4)], d, 28, 'y', undefined, 6));
    }
  }
  // столовые приборы: лоток сбоку
  р.push(брус('пластик-светлый', [W / 2 - 50, hП + 40, D / 2 - 60], [80, 80, 100], 8));
  return р;
}

function мусорка(габ: Габариты): Примитив[] {
  const { ш: W, г: D, в: H } = габ;
  const р: Примитив[] = [];
  // основание-рама на направляющих, два бака с откидной крышкой
  р.push(брус('металл-чёрный', [0, 10, 0], [W, 20, D], 2));
  const n = 2;
  const w = (W - 30) / n;
  for (let i = 0; i < n; i++) {
    const x = -W / 2 + 15 + w * (i + 0.5) + (i ? 5 : -5) * 0;
    р.push(брус('пластик', [x, 20 + (H - 20) / 2, 0], [w - 10, H - 20, D - 40], 14));
    р.push(брус('пластик-светлый', [x, H - 6, 0], [w - 4, 12, D - 34], 8));
    р.push(точёная('шайба', 'хром', [x, H + 3, D / 2 - 45], 28, 6, 'y'));
  }
  for (const s of [-1, 1]) р.push(брус('никель', [(s * (W + 4)) / 2, 40, 0], [4, 28, D - 20], 1));
  return р;
}

function лоток(габ: Габариты): Примитив[] {
  const { ш: W, г: D, в: H } = габ;
  const р: Примитив[] = [];
  const t = 8;
  const бамбук = { цвет: '#d4b98a' };
  р.push(брус('дерево', [0, t / 2, 0], [W, t, D], 2, бамбук));
  for (const s of [-1, 1]) {
    р.push(брус('дерево', [(s * (W - t)) / 2, H / 2, 0], [t, H, D], 2, бамбук));
    р.push(брус('дерево', [0, H / 2, (s * (D - t)) / 2], [W, H, t], 2, бамбук));
  }
  // перегородки на ячейки: вилки, ножи, ложки
  р.push(брус('дерево', [-W * 0.18, H / 2, 0], [t, H, D - t], 2, бамбук));
  р.push(брус('дерево', [W * 0.18, H / 2, 0], [t, H, D - t], 2, бамбук));
  р.push(брус('дерево', [W * 0.34, H / 2, -D * 0.1], [W * 0.3, H, t], 2, бамбук));
  return р;
}

/** Модели наполнения по id; null — не знаком */
export function примитивыНаполнения(id: string, габ: Габариты): Примитив[] | null {
  if (id.startsWith('корзина')) return корзина(габ);
  if (id.startsWith('брючница')) return брючница(габ);
  if (id.startsWith('сушилка-посуды')) return сушилка(габ);
  if (id.startsWith('мусорная-система')) return мусорка(габ);
  if (id.startsWith('лоток-для-приборов')) return лоток(габ);
  return null;
}
