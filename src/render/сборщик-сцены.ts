/** Часть модели (форма «модель») в рамке base — 4×4 по столбцам, метры: итоговая запись слота; другие формы не рисуются */
function записьЧасти(base: ArrayLike<number>, п: Примитив): { ключ: string; запись: ЗаписьСлота } | null {
  if (п.форма !== 'модель' || !п.модель || п.модель.геом.startsWith('gltf:')) return null;
  const R = п.R;
  const m = new Float32Array(16);
  for (let i = 0; i < 3; i++) {
    for (let j = 0; j < 3; j++) {
      let c = 0;
      for (let k = 0; k < 3; k++) c += base[k * 4 + i] * R[k * 3 + j];
      m[j * 4 + i] = c;
    }
    m[12 + i] = base[12 + i] + (base[i] * п.t[0] + base[4 + i] * п.t[1] + base[8 + i] * п.t[2]) / 1000;
  }
  m[15] = 1;
  const цвет: [number, number, number] = typeof п.мат === 'string' ? [1, 1, 1] : цветИзСтроки(п.мат.цвет);
  return {
    ключ: `модель|${п.модель.геом}|${п.модель.класс}`,
    запись: { m, размер: [п.размер[0] / 1000, п.размер[1] / 1000, п.размер[2] / 1000], цвет, поверх: [1, 0, п.биты, п.r] },
  };
}

