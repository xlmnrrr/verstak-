import type { Изделие, КлючМатериала, Помещение, ПроектV2, Экземпляр } from '../model/типы';
import { Группа } from './группы';
import { type ФормаГеометрии } from './геометрии';
import { поверхность, умолчаниеПоверхности, цветИзСтроки, type НаборМатериалов } from './материалы';
import { примитивыЭкземпляра, type Примитив } from './примитивы';
import type { ЦельВыбора } from './выбор';
import { расстояниеДоОББ } from './выбор';
import type { Диапазон } from './слоты';
