/**
 * Рулетка: чистая математика граней. Луч против ориентированной коробки даёт грань (точка, нормаль, углы);
 * два клика — расстояние между гранями (если параллельны) или по прямой. Метры, простые массивы, без three.
 */
import { вычесть, длина, нормировать, скаляр, type Луч, type В3 } from './жесты-математика';

export interface Коробка3 {
  центр: В3;
  /** полуразмеры по осям */
  полу: В3;
  /** ортонормированные оси коробки в мире */
  оси: [В3, В3, В3];
  /** подпись для сообщений («стена», «Шкаф 600») */
  название?: string;
}

export interface Грань {
  точка: В3;
  /** единичная нормаль наружу, к лучу */
  нормаль: В3;
  t: number;
  /** четыре угла грани (для подсветки); у пола — null */
  углы: В3[] | null;
  название: string;
}

const комб = (ц: В3, a: В3, ka: number, b: В3, kb: number, c: В3, kc: number): В3 => [
  ц[0] + a[0] * ka + b[0] * kb + c[0] * kc,
  ц[1] + a[1] * ka + b[1] * kb + c[1] * kc,
  ц[2] + a[2] * ka + b[2] * kb + c[2] * kc,
];

/** Грань, в которую упирается луч (снаружи); null — мимо или начало луча внутри */
export function граньКоробки(луч: Луч, к: Коробка3): Грань | null {
  const д = вычесть(луч.о, к.центр);
  let tМин = -Infinity;
  let tМакс = Infinity;
  let ось = -1;
  let знак = 1;
  for (let i = 0; i < 3; i++) {
    const o = скаляр(д, к.оси[i]);
    const н = скаляр(луч.н, к.оси[i]);
    const h = к.полу[i];
    if (Math.abs(н) < 1e-12) {
      if (Math.abs(o) > h) return null;
      continue;
    }
    let t1 = (-h - o) / н;
    let t2 = (h - o) / н;
    let вход = -1; // знак стороны, через которую входит луч
    if (t1 > t2) {
      [t1, t2] = [t2, t1];
      вход = 1;
    }
    if (t1 > tМин) {
      tМин = t1;
      ось = i;
      знак = вход;
    }
    tМакс = Math.min(tМакс, t2);
    if (tМин > tМакс) return null;
  }
  if (ось < 0 || tМин < 0) return null;
  const точка: В3 = [луч.о[0] + луч.н[0] * tМин, луч.о[1] + луч.н[1] * tМин, луч.о[2] + луч.н[2] * tМин];
  const a = к.оси[ось];
  const нормаль: В3 = [a[0] * знак, a[1] * знак, a[2] * знак];
  const i1 = (ось + 1) % 3;
  const i2 = (ось + 2) % 3;
  const центрГрани: В3 = комб(к.центр, a, знак * к.полу[ось], к.оси[i1], 0, к.оси[i2], 0);
  const углы: В3[] = [
    комб(центрГрани, a, 0, к.оси[i1], к.полу[i1], к.оси[i2], к.полу[i2]),
    комб(центрГрани, a, 0, к.оси[i1], -к.полу[i1], к.оси[i2], к.полу[i2]),
    комб(центрГрани, a, 0, к.оси[i1], -к.полу[i1], к.оси[i2], -к.полу[i2]),
    комб(центрГрани, a, 0, к.оси[i1], к.полу[i1], к.оси[i2], -к.полу[i2]),
  ];
  return { точка, нормаль, t: tМин, углы, название: к.название ?? 'предмет' };
}

/** Ближайшая грань по лучу среди коробок и пола (плоскость y = 0) */
export function ближайшаяГрань(луч: Луч, коробки: readonly Коробка3[], пол = true): Грань | null {
  let лучшая: Грань | null = null;
  for (const к of коробки) {
    const г = граньКоробки(луч, к);
    if (г && (!лучшая || г.t < лучшая.t)) лучшая = г;
  }
  if (пол && луч.н[1] < -1e-9) {
    const t = -луч.о[1] / луч.н[1];
    if (t >= 0 && (!лучшая || t < лучшая.t)) {
      лучшая = { точка: [луч.о[0] + луч.н[0] * t, 0, луч.о[2] + луч.н[2] * t], нормаль: [0, 1, 0], t, углы: null, название: 'пол' };
    }
  }
  return лучшая;
}

export interface Замер {
  a: В3;
  b: В3;
  /** расстояние, мм */
  мм: number;
  /** между параллельными гранями (по нормали) или по прямой между точками */
  тип: 'между гранями' | 'по прямой';
  из: string;
  до: string;
}

/**
 * Замер по двум граням. Параллельные (в том числе противоположные) — расстояние между плоскостями вдоль нормали:
 * отрезок идёт от первой точки по нормали. Иначе — по прямой между точками клика.
 */
export function замерПоГраням(а: Грань, б: Грань): Замер {
  const параллельны = Math.abs(скаляр(а.нормаль, б.нормаль)) >= 0.985;
  if (параллельны) {
    const d = скаляр(а.нормаль, вычесть(б.точка, а.точка));
    const конец: В3 = [а.точка[0] + а.нормаль[0] * d, а.точка[1] + а.нормаль[1] * d, а.точка[2] + а.нормаль[2] * d];
    return { a: а.точка, b: конец, мм: Math.round(Math.abs(d) * 1000), тип: 'между гранями', из: а.название, до: б.название };
  }
  return { a: а.точка, b: б.точка, мм: Math.round(длина(вычесть(б.точка, а.точка)) * 1000), тип: 'по прямой', из: а.название, до: б.название };
}

/** Единичная ось из угла поворота вокруг вертикали (для коробок изделий): локальные X, Y, Z → мир */
export function осиПоворота(cos: number, sin: number): [В3, В3, В3] {
  return [[cos, 0, sin], [0, 1, 0], нормировать([-sin, 0, cos])];
}
