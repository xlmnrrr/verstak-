/**
 * Геометрия размерных линий у выделенного изделия: ширина, глубина, высота и зазоры до соседей, стен и потолка.
 * Чистые функции (мм на входе, метры на выходе), без three и DOM, поэтому под vitest.
 */
import type { Зазоры } from '../model/привязка';
import type { Экземпляр } from '../model/типы';
import type { В3 } from './жесты-математика';

export type ВидМетки = 'размер' | 'зазор' | 'потолок';

export interface ОтрезокСцены {
  a: В3;
  b: В3;
  цвет: [number, number, number];
}

export interface МеткаСцены {
  /** где стоит подпись, метры */
  точка: В3;
  текст: string;
  вид: ВидМетки;
}

export interface РазмерныеЭлементы {
  отрезки: ОтрезокСцены[];
  метки: МеткаСцены[];
}

const ЦВЕТ_РАЗМЕРА: [number, number, number] = [0.82, 0.86, 0.9];
const ЦВЕТ_ЗАЗОРА: [number, number, number] = [0.94, 0.7, 0.16];
const ЦВЕТ_ПОТОЛКА: [number, number, number] = [0.55, 0.78, 0.95];
/** Отступ размерных линий от изделия, мм */
export const ОТСТУП_ММ = 100;
const ЗАСЕЧКА_ММ = 40;

const м = (v: number) => v / 1000;

/** Локальная точка изделия → мировая (метры): поворот вокруг вертикали, как в рендере */
export function вМир(э: Pick<Экземпляр, 'позиция' | 'поворот'>, lx: number, ly: number, lz: number): В3 {
  const θ = (э.поворот * Math.PI) / 180;
  const c = Math.cos(θ);
  const s = Math.sin(θ);
  return [м(э.позиция[0] + lx * c - lz * s), м(э.позиция[1] + ly), м(э.позиция[2] + lx * s + lz * c)];
}

/** Линия с засечками на концах (поперёк: векторы в мм, мировые) */
function сЗасечками(a: В3, b: В3, поперёк: В3, цвет: [number, number, number]): ОтрезокСцены[] {
  const з = м(ЗАСЕЧКА_ММ);
  const т = (p: В3, k: number): ОтрезокСцены => ({ a: [p[0] - поперёк[0] * з * k, p[1] - поперёк[1] * з * k, p[2] - поперёк[2] * з * k], b: [p[0] + поперёк[0] * з * k, p[1] + поперёк[1] * з * k, p[2] + поперёк[2] * з * k], цвет });
  return [{ a, b, цвет }, т(a, 1), т(b, 1)];
}

export function размерныеЭлементы(э: Pick<Экземпляр, 'позиция' | 'поворот' | 'габариты'>, зазоры: Зазоры | null, высотаПомещения: number): РазмерныеЭлементы {
  const { ш, г, в } = э.габариты;
  const отрезки: ОтрезокСцены[] = [];
  const метки: МеткаСцены[] = [];
  const θ = (э.поворот * Math.PI) / 180;
  const ox: В3 = [Math.cos(θ), 0, Math.sin(θ)];
  const oz: В3 = [-Math.sin(θ), 0, Math.cos(θ)];

  // ширина: перед изделием у низа
  {
    const a = вМир(э, -ш / 2, 0, г / 2 + ОТСТУП_ММ);
    const b = вМир(э, ш / 2, 0, г / 2 + ОТСТУП_ММ);
    отрезки.push(...сЗасечками(a, b, oz, ЦВЕТ_РАЗМЕРА));
    метки.push({ точка: вМир(э, 0, 0, г / 2 + ОТСТУП_ММ), текст: `${Math.round(ш)}`, вид: 'размер' });
  }
  // глубина: сбоку у низа
  {
    const a = вМир(э, ш / 2 + ОТСТУП_ММ, 0, -г / 2);
    const b = вМир(э, ш / 2 + ОТСТУП_ММ, 0, г / 2);
    отрезки.push(...сЗасечками(a, b, ox, ЦВЕТ_РАЗМЕРА));
    метки.push({ точка: вМир(э, ш / 2 + ОТСТУП_ММ, 0, 0), текст: `${Math.round(г)}`, вид: 'размер' });
  }
  // высота: у переднего левого угла
  {
    const a = вМир(э, -ш / 2 - ОТСТУП_ММ, 0, г / 2);
    const b = вМир(э, -ш / 2 - ОТСТУП_ММ, в, г / 2);
    отрезки.push(...сЗасечками(a, b, ox, ЦВЕТ_РАЗМЕРА));
    метки.push({ точка: вМир(э, -ш / 2 - ОТСТУП_ММ, в / 2, г / 2), текст: `${Math.round(в)}`, вид: 'размер' });
  }

  if (зазоры) {
    const [x, y, z] = э.позиция;
    const θ90 = Math.abs(((э.поворот % 90) + 90) % 90) < 0.01;
    const c = Math.abs(Math.cos(θ));
    const s = Math.abs(Math.sin(θ));
    const hx = (ш * c + г * s) / 2;
    const hz = (ш * s + г * c) / 2;
    const середина = (a0: number, a1: number, b0: number, b1: number) => (Math.max(a0, b0) + Math.min(a1, b1)) / 2;
    if (θ90) {
      const напр: { з: Зазоры[keyof Зазоры]; ось: 'x' | 'z'; плюс: boolean }[] = [
        { з: зазоры.xМинус, ось: 'x', плюс: false },
        { з: зазоры.xПлюс, ось: 'x', плюс: true },
        { з: зазоры.zМинус, ось: 'z', плюс: false },
        { з: зазоры.zПлюс, ось: 'z', плюс: true },
      ];
      for (const н of напр) {
        const п = н.з;
        if (!п || typeof п === 'number') continue;
        const о = п.преграда;
        const yМ = середина(y, y + в, о.y0, о.y1);
        const мояГрань = н.ось === 'x' ? (н.плюс ? x + hx : x - hx) : н.плюс ? z + hz : z - hz;
        const латерально = н.ось === 'x' ? середина(z - hz, z + hz, о.z0, о.z1) : середина(x - hx, x + hx, о.x0, о.x1);
        const a: В3 = н.ось === 'x' ? [м(мояГрань), м(yМ), м(латерально)] : [м(латерально), м(yМ), м(мояГрань)];
        const b: В3 = н.ось === 'x' ? [м(п.грань), м(yМ), м(латерально)] : [м(латерально), м(yМ), м(п.грань)];
        const поперёк: В3 = н.ось === 'x' ? [0, 0, 1] : [1, 0, 0];
        if (п.мм > 0.5) отрезки.push(...сЗасечками(a, b, поперёк, ЦВЕТ_ЗАЗОРА));
        метки.push({ точка: [(a[0] + b[0]) / 2, a[1], (a[2] + b[2]) / 2], текст: п.мм <= 0.5 ? 'вплотную' : `${Math.round(п.мм)}`, вид: 'зазор' });
      }
    }
    if (typeof зазоры.доПотолка === 'number' && зазоры.доПотолка > 0) {
      const a: В3 = [м(x), м(y + в), м(z)];
      const b: В3 = [м(x), м(высотаПомещения), м(z)];
      отрезки.push(...сЗасечками(a, b, [1, 0, 0], ЦВЕТ_ПОТОЛКА));
      метки.push({ точка: [(a[0] + b[0]) / 2, (a[1] + b[1]) / 2, a[2]], текст: `до потолка ${зазоры.доПотолка}`, вид: 'потолок' });
    }
  }
  return { отрезки, метки };
}
