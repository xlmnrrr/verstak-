const ПОРЯДОК: ИмяПрофиля[] = ['высокое', 'среднее', 'слабый ноутбук'];
export const ступеньНиже = (п: ИмяПрофиля): ИмяПрофиля => ПОРЯДОК[Math.min(ПОРЯДОК.length - 1, ПОРЯДОК.indexOf(п) + 1)];
export const ступеньВыше = (п: ИмяПрофиля): ИмяПрофиля => ПОРЯДОК[Math.max(0, ПОРЯДОК.indexOf(п) - 1)];

export interface ОценкаВидеокарты {
  имя: string;
  профиль: ИмяПрофиля;
  программная: boolean;
}

/** Стартовый профиль по имени видеокарты (WEBGL_debug_renderer_info) */
export function профильПоВидеокарте(имя: string): ОценкаВидеокарты {
  const н = имя.toLowerCase();
  if (/swiftshader|basic render|llvmpipe|software|microsoft basic/.test(н)) return { имя, профиль: 'слабый ноутбук', программная: true };
  if (/nvidia|geforce|rtx|gtx|quadro/.test(н)) return { имя, профиль: 'высокое', программная: false };
  if (/radeon rx|radeon pro|amd radeon\(tm\) rx|rx \d/.test(н)) return { имя, профиль: 'высокое', программная: false };
  if (/iris|xe graphics|radeon\(tm\) graphics|radeon graphics|vega/.test(н)) return { имя, профиль: 'среднее', программная: false };
  if (/intel/.test(н) && /uhd|hd graphics|hd /.test(н)) return { имя, профиль: 'слабый ноутбук', программная: false };
  return { имя, профиль: 'среднее', программная: false };
}

/** Имя видеокарты из временного холста (без создания основного контекста) */
export function определитьВидеокарту(): string {
  try {
    const к = document.createElement('canvas');
    const gl = (к.getContext('webgl2') || к.getContext('webgl')) as WebGLRenderingContext | null;
    if (!gl) return 'нет WebGL';
    const ext = gl.getExtension('WEBGL_debug_renderer_info');
    const имя = ext ? String(gl.getParameter(ext.UNMASKED_RENDERER_WEBGL)) : String(gl.getParameter(gl.RENDERER));
    gl.getExtension('WEBGL_lose_context')?.loseContext();
    return имя;
  } catch {
    return 'неизвестно';
  }
}

/* ------------------------------------------------------------------ монитор кадров («авто») */

export interface ОпцииМонитора {
  /** интервал обновления экрана, мс */
  интервалЭкрана: number;
}

/**
 * Меряются только сплошные отрезки: кадры подряд с интервалом меньше 100 мс.
 * Вниз — медиана больше 22 мс (меньше 45 fps) 2 с подряд.
 * Вверх — 10 с сплошной работы без кадров длиннее 1,25 интервала экрана; не чаще раза в 60 с и не на ступень, с которой
 * спустились за последние 5 минут.
 */
export class МониторКадров {
  private окно: { t: number; д: number }[] = [];
  private последний = -1;
  private началоСплошного = -1;
  private длинныйВСплошном = false;
  private последнееПереключение = -Infinity;
  private спустилисьС: { имя: ИмяПрофиля; t: number } | null = null;

  constructor(
    private readonly опции: ОпцииМонитора = { интервалЭкрана: 1000 / 60 },
    public профиль: ИмяПрофиля = 'высокое',
  ) {}

  /** Вызывать на каждый отрисованный кадр: t — время кадра, мс. Возвращает новый профиль или null. */
  кадр(t: number): ИмяПрофиля | null {
    const д = this.последний < 0 ? -1 : t - this.последний;
    this.последний = t;
    if (д < 0 || д > 100) {
      this.окно = [];
      this.началоСплошного = t;
      this.длинныйВСплошном = false;
      return null;
    }
    if (this.началоСплошного < 0) this.началоСплошного = t;
    this.окно.push({ t, д });
    while (this.окно.length && t - this.окно[0].t > 2000) this.окно.shift();
    if (д > this.опции.интервалЭкрана * 1.25) this.длинныйВСплошном = true;

    // вниз
    if (this.окно.length >= 20 && t - this.окно[0].t >= 1900) {
      const с = [...this.окно].map((x) => x.д).sort((a, b) => a - b);
      const медиана = с[Math.floor(с.length / 2)];
      if (медиана > 22 && t - this.последнееПереключение > 2000) {
        const новый = ступеньНиже(this.профиль);
        if (новый !== this.профиль) return this.переключить(новый, t, true);
      }
    }
    // вверх
    if (!this.длинныйВСплошном && t - this.началоСплошного >= 10_000 && t - this.последнееПереключение >= 60_000) {
      const новый = ступеньВыше(this.профиль);
      if (новый !== this.профиль && !(this.спустилисьС && this.спустилисьС.имя === новый && t - this.спустилисьС.t < 300_000)) {
        return this.переключить(новый, t, false);
      }
    }
    return null;
  }

  private переключить(новый: ИмяПрофиля, t: number, вниз: boolean): ИмяПрофиля {
    if (вниз) this.спустилисьС = { имя: this.профиль, t };
    this.профиль = новый;
    this.последнееПереключение = t;
    this.окно = [];
    this.началоСплошного = t;
    this.длинныйВСплошном = false;
    return новый;
  }
}

/** Самопроверка при первом открытии: медиана интервала кадров больше 20 мс — на ступень ниже */
export function профильПослеСамопроверки(старт: ИмяПрофиля, интервалыМс: number[]): { профиль: ИмяПрофиля; медиана: number; годится: boolean } {
  if (интервалыМс.length < 20) return { профиль: старт, медиана: 0, годится: false };
  const с = [...интервалыМс].sort((a, b) => a - b);
  const медиана = с[Math.floor(с.length / 2)];
  // кадры по 100+ мс — окно скрыто или рисование троттлится: итог ненадёжен
  if (медиана > 100) return { профиль: старт, медиана, годится: false };
  return { профиль: медиана > 20 ? ступеньНиже(старт) : старт, медиана, годится: true };
}
