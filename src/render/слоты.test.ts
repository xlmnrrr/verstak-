import { describe, expect, it } from 'vitest';
import { Слоты } from './слоты';

describe('слоты инстансов', () => {
  it('выделяет подряд, освобождённое переиспользует', () => {
    const с = new Слоты(100);
    const a = с.выделить(10);
    const b = с.выделить(10);
    const c = с.выделить(10);
    expect([a, b, c]).toEqual([0, 10, 20]);
    с.освободить(b, 10);
    expect(с.верх).toBe(30);
    expect(с.выделить(4)).toBe(10);
    expect(с.выделить(6)).toBe(14);
    expect(с.занято).toBe(30);
  });

  it('дыра на самом верху опускает границу', () => {
    const с = new Слоты(100);
    const a = с.выделить(10);
    const b = с.выделить(10);
    с.освободить(b, 10);
    expect(с.верх).toBe(10);
    с.освободить(a, 10);
    expect(с.верх).toBe(0);
    expect(с.дыры).toEqual([]);
  });

  it('соседние дыры сливаются', () => {
    const с = new Слоты(100);
    const a = с.выделить(10);
    const b = с.выделить(10);
    с.выделить(10);
    с.освободить(a, 10);
    с.освободить(b, 10);
    expect(с.дыры).toEqual([{ начало: 0, число: 20 }]);
  });

  it('нет места — -1; ёмкость растёт степенью двойки с запасом', () => {
    const с = new Слоты(16);
    expect(с.выделить(16)).toBe(0);
    expect(с.выделить(1)).toBe(-1);
    expect(Слоты.ёмкостьДля(100)).toBe(256);
    expect(Слоты.ёмкостьДля(3000)).toBe(4096);
    expect(Слоты.ёмкостьДля(7600)).toBe(16384);
  });

  it('доля дыр считается от занятой области', () => {
    const с = new Слоты(100);
    const a = с.выделить(10);
    с.выделить(10);
    с.освободить(a, 10);
    expect(с.долиДыр).toBeCloseTo(0.5);
  });
});
