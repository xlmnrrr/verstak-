/** Выделение слотов в буфере инстансов: непрерывные диапазоны, список дыр, уплотнение. Чистая логика, без three. */

export interface Диапазон {
  начало: number;
  число: number;
}

export class Слоты {
  ёмкость: number;
  /** верхняя граница занятых слотов (mesh.count) */
  верх = 0;
  занято = 0;
  дыры: Диапазон[] = [];

  constructor(ёмкость: number) {
    this.ёмкость = ёмкость;
  }

  /** Первый подходящий диапазон из дыр, иначе в конец. -1 — места нет, нужен рост. */
  выделить(n: number): number {
    if (n <= 0) return this.верх;
    for (let i = 0; i < this.дыры.length; i++) {
      const д = this.дыры[i];
      if (д.число >= n) {
        const начало = д.начало;
        if (д.число === n) this.дыры.splice(i, 1);
        else {
          д.начало += n;
          д.число -= n;
        }
        this.занято += n;
        return начало;
      }
    }
    if (this.верх + n <= this.ёмкость) {
      const начало = this.верх;
      this.верх += n;
      this.занято += n;
      return начало;
    }
    return -1;
  }

  освободить(начало: number, n: number): void {
    if (n <= 0) return;
    this.занято -= n;
    this.дыры.push({ начало, число: n });
    this.дыры.sort((a, b) => a.начало - b.начало);
    // слить соседние
    const слито: Диапазон[] = [];
    for (const д of this.дыры) {
      const п = слито[слито.length - 1];
      if (п && п.начало + п.число === д.начало) п.число += д.число;
      else слито.push({ ...д });
    }
    this.дыры = слито;
    // дыра на самом верху — просто опускаем границу
    const последняя = this.дыры[this.дыры.length - 1];
    if (последняя && последняя.начало + последняя.число === this.верх) {
      this.верх = последняя.начало;
      this.дыры.pop();
    }
  }

  /** Доля дыр внутри занятой области */
  get долиДыр(): number {
    return this.верх ? (this.верх - this.занято) / this.верх : 0;
  }

  /** Ёмкость после роста: ближайшая степень двойки ≥ max(256, 1,25 × нужно) */
  static ёмкостьДля(нужно: number): number {
    let е = 256;
    while (е < нужно * 1.25) е *= 2;
    return е;
  }

  сбросить(): void {
    this.верх = 0;
    this.занято = 0;
    this.дыры = [];
  }
}
