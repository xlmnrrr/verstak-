export type ФормаПримитива = 'плита' | 'цилиндр' | 'сфера' | 'конус' | 'стекло' | 'сектор' | 'обод' | 'модель';

export interface ЛитералМатериала {
  цвет: string;
  шер: number;
  мет: number;
}

export interface Примитив {
  форма: ФормаПримитива;
  /** размеры по собственным осям: плита — по осям, цилиндр — (диаметр, длина, диаметр) */
  размер: Вектор3;
  /** центр в осях изделия */
  t: Вектор3;
  /** поворот: 3×3 по строкам, оси изделия → оси детали */
  R: number[];
  /** ключ материала модели, либо готовый материал */
  мат: string | ЛитералМатериала;
  /** биты кромки (6 бит, ±X ±Y ±Z в осях детали) + 64 для ЛДСП */
  биты: number;
  /** радиус фаски, мм */
  r: number;
  тень: boolean;
  /** подвижная группа (дверь, ящик, створка), если есть */
  группа?: string;
  /** часть модели (docs/модели.md): ключ геометрии в метрах и класс физического материала; размер — габарит для выбора */
  модель?: { геом: string; класс: КлассМодели };
}

export interface РезультатДеталей {
  примитивы: Примитив[];
  /** число деталей из `детали()` (до разбиения моделей) */
  деталей: number;
  /** габаритные коробки для выбора (закрытое положение): cx,cy,cz,hx,hy,hz в метрах, по оси изделия */
  боксы: Float32Array;
  /** что открывается у изделия */
  движения: Движение[];
  /** есть ли подвижные примитивы */
  подвижные: boolean;
  /** подпись для отладки: что обрезано */
  предупреждение?: string;
}

const ЕДИНИЧНАЯ = [1, 0, 0, 0, 1, 0, 0, 0, 1];
export const МАКС_ДЕТАЛЕЙ = 512;

/* ------------------------------------------------------------------ кромка → биты */

/**
 * Кромка в осях детали → 6 бит (±X ±Y ±Z). Правило: оси ранжируются по размеру (длина ≥ ширина ≥ толщина, при равенстве
 * первая по индексу); «длинаN» — грани с нормалью вдоль оси ширины, «ширинаN» — с нормалью вдоль оси длины;
 * N = 1 — плюс-сторона оси, N = 2 — минус-сторона.
 */
export function битыКромки(объём: Вектор3, к: Кромка): number {
  const индексы = [0, 1, 2].sort((a, b) => объём[b] - объём[a] || a - b);
  const [длина, ширина] = индексы;
  let биты = 0;
  const бит = (ось: number, плюс: boolean) => 1 << (ось * 2 + (плюс ? 0 : 1));
  if (к.длина1 > 0) биты |= бит(ширина, true);
  if (к.длина2 > 0) биты |= бит(ширина, false);
  if (к.ширина1 > 0) биты |= бит(длина, true);
  if (к.ширина2 > 0) биты |= бит(длина, false);
  return биты;
}

const радиусФаски = (к: Кромка) => {
  const макс = Math.max(к.длина1, к.длина2, к.ширина1, к.ширина2);
  return макс > 0 ? Math.min(2, Math.max(0.5, макс)) : 0.5;
};

const ЛДСП = new Set(['корпус', 'фасад', 'задник']);

/* ------------------------------------------------------------------ матрицы 3×3 */

const умножить = (a: number[], b: number[]): number[] => {
  const р = new Array(9).fill(0);
  for (let i = 0; i < 3; i++) for (let j = 0; j < 3; j++) for (let k = 0; k < 3; k++) р[i * 3 + j] += a[i * 3 + k] * b[k * 3 + j];
  return р;
};
const применить = (R: number[], v: Вектор3): Вектор3 => [
  R[0] * v[0] + R[1] * v[1] + R[2] * v[2],
  R[3] * v[0] + R[4] * v[1] + R[5] * v[2],
  R[6] * v[0] + R[7] * v[1] + R[8] * v[2],
];
/** Ось цилиндра по умолчанию — Y. Rz(−90°) для оси X, Rx(90°) для оси Z. */
const ПОВОРОТ_ОСИ: Record<string, number[]> = {
  x: [0, 1, 0, -1, 0, 0, 0, 0, 1],
  y: ЕДИНИЧНАЯ,
  z: [1, 0, 0, 0, 0, -1, 0, 1, 0],
};

/* ------------------------------------------------------------------ заглушки моделей */

const литерал = (цвет: string, шер = 0.75, мет = 0.05): ЛитералМатериала => ({ цвет, шер, мет });

const плитаЛ = (t: Вектор3, размер: Вектор3, мат: Примитив['мат'], тень = true): Примитив => ({
  форма: 'плита',
  размер,
  t,
  R: ЕДИНИЧНАЯ,
  мат,
  биты: 0,
  r: 0.5,
  тень,
});

export type ВидДекора = 'ковёр' | 'светильник' | 'ведро' | 'зеркало' | 'посуда' | 'растение';

export function видДекора(изд: Изделие): ВидДекора {
  const м = изд.v1?.модуль ?? '';
  const id = изд.id;
  if (м.startsWith('rug') || id.startsWith('ковёр')) return 'ковёр';
  if (м.startsWith('light') || id.startsWith('светильник')) return 'светильник';
  if (м.startsWith('bin') || id.startsWith('ведро')) return 'ведро';
  if (м.startsWith('mirror') || id.startsWith('зеркало')) return 'зеркало';
  if (м.startsWith('dishes') || id.startsWith('посуда')) return 'посуда';
  return 'растение';
}

/** Части техники из модели (корпус, дверь, ручка, панель) в примитивы */
function примитивыТехники(изд: Изделие, экз: Экземпляр, петли: string): Примитив[] {
  return частиТехники(изд, экз.габариты, петли as never).map((x) => {
    const мат: Примитив['мат'] = x.литерал ?? x.материал;
    const [dx, dy, dz] = x.локально.объём;
    if (x.форма === 'цилиндр') {
      const L = dz;
      const d = Math.max(dx, dy);
      return { форма: 'цилиндр' as const, размер: [d, L, d] as Вектор3, t: x.локально.центр, R: ПОВОРОТ_ОСИ.z, мат, биты: 0, r: 0, тень: true, группа: x.подвижная?.группа };
    }
    return { форма: 'плита' as const, размер: x.локально.объём, t: x.локально.центр, R: ЕДИНИЧНАЯ, мат, биты: 0, r: 0.5, тень: true, группа: x.подвижная?.группа };
  });
}

function заглушкаПроёма(д: Деталь): Примитив[] {
  const [ш, в, г] = д.локально.объём;
  const [cx, cy, cz] = д.локально.центр;
  const y0 = cy - в / 2;
  const брус = 60;
  const цвет = литерал('#f3efe9', 0.6, 0);
  return [
    плитаЛ([cx, y0 + в - брус / 2, cz], [ш, брус, г], цвет),
    плитаЛ([cx, y0 + брус / 2, cz], [ш, брус, г], цвет),
    плитаЛ([cx - ш / 2 + брус / 2, y0 + в / 2, cz], [брус, в, г], цвет),
    плитаЛ([cx + ш / 2 - брус / 2, y0 + в / 2, cz], [брус, в, г], цвет),
    { ...плитаЛ([cx, y0 + в / 2, cz], [Math.max(10, ш - брус * 2), Math.max(10, в - брус * 2), 10], 'стекло', false), форма: 'стекло' },
    плитаЛ([cx, y0 + в / 2, cz], [20, Math.max(10, в - брус * 2), 30], цвет),
  ];
}

const цилиндр = (t: Вектор3, d: number, L: number, мат: Примитив['мат'], тень = true): Примитив => ({
  форма: 'цилиндр',
  размер: [d, L, d],
  t,
  R: ЕДИНИЧНАЯ,
  мат,
  биты: 0,
  r: 0,
  тень,
});

function заглушкаДекора(д: Деталь, изд: Изделие): Примитив[] {
  const [ш, в, г] = д.локально.объём;
  const [cx, , cz] = д.локально.центр;
  const y0 = д.локально.центр[1] - в / 2;
  switch (видДекора(изд)) {
    case 'ковёр':
      return [плитаЛ([cx, y0 + 6, cz], [ш, 12, г], 'фасад', false)];
    case 'светильник': {
      const подвес = изд.id.includes('подвес');
      const р: Примитив[] = [];
      if (подвес) р.push(цилиндр([cx, y0 + в * 0.55, cz], 16, в * 0.9, литерал('#4a4a4a')));
      р.push({ форма: 'конус', размер: [ш, в * 0.35, ш], t: [cx, y0 + в * 0.12, cz], R: ЕДИНИЧНАЯ, мат: 'фасад', биты: 0, r: 0, тень: true });
      р.push({ форма: 'сфера', размер: [120, 120, 120], t: [cx, y0 + в * 0.06, cz], R: ЕДИНИЧНАЯ, мат: литерал('#ffe6b0', 0.4, 0), биты: 0, r: 0, тень: false });
      return р;
    }
    case 'ведро':
      return [цилиндр([cx, y0 + в / 2, cz], ш * 0.76, в, литерал('#7b828b', 0.4, 0.5))];
    case 'зеркало':
      return [плитаЛ([cx, y0 + в / 2, cz], [ш, в, 40], 'зеркало')];
    case 'посуда':
      return [0, 1, 2].map((i) => цилиндр([cx, y0 + 20 + i * 50, cz], ш * 0.8, 30, литерал('#f2f0ec', 0.4, 0)));
    default:
      return [
        цилиндр([cx, y0 + в * 0.3, cz], ш * 0.52, в * 0.6, литерал('#8d6b4b', 0.9, 0)),
        { форма: 'сфера', размер: [ш * 0.9, ш * 0.9, ш * 0.9], t: [cx, y0 + в * 0.78, cz], R: ЕДИНИЧНАЯ, мат: литерал('#4f7a45', 0.9, 0), биты: 0, r: 0, тень: true },
      ];
  }
}

/* ------------------------------------------------------------------ поза «открыто» */

function сПозой(п: Примитив, поза: Поза | undefined): Примитив {
  if (!поза) return п;
  let t = п.t;
  let R = п.R;
  if (поза.R && поза.опора) {
    const о = поза.опора;
    const d = применить(поза.R, [t[0] - о[0], t[1] - о[1], t[2] - о[2]]);
    t = [о[0] + d[0], о[1] + d[1], о[2] + d[2]];
    R = умножить(поза.R, R);
  }
  t = [t[0] + поза.сдвиг[0], t[1] + поза.сдвиг[1], t[2] + поза.сдвиг[2]];
  return { ...п, t, R };
}

/* ------------------------------------------------------------------ вход */

const _кэш = new Map<string, РезультатДеталей>();
const ПРЕДЕЛ_КЭША = 2000;

/** Ключ кэша: изделие, габариты, раскладка и угол открывания (движения кэшируются вместе с деталями — угол обязан быть в ключе) */
export const ключДеталей = (изд: Изделие, экз: Экземпляр): string =>
  `${изд.id}|${экз.габариты.ш}x${экз.габариты.г}x${экз.габариты.в}|${экз.раскладка ? JSON.stringify(экз.раскладка) : ''}|${экз.угол_открывания ?? ''}`;

export function сбросКэшаДеталей() {
  _кэш.clear();
}

/**
 * Примитивы экземпляра. `детально` — изделие в наборе «ближайших» (LOD, docs/модели.md §3): добавляются петли;
 * ручки профилем, техника моделью и мягкое рисуются всегда.
 */
export function примитивыЭкземпляра(изд: Изделие, экз: Экземпляр, детально = false): РезультатДеталей {
  const ключ = ключДеталей(изд, экз) + (детально ? '|д' : '');
  const в = _кэш.get(ключ);
  if (в) {
    _кэш.delete(ключ);
    _кэш.set(ключ, в);
    return в;
  }
  const р = построить(изд, экз, детально);
  _кэш.set(ключ, р);
  if (_кэш.size > ПРЕДЕЛ_КЭША) _кэш.delete(_кэш.keys().next().value as string);
  return р;
}

function боксыПримитивов(примитивы: Примитив[]): Float32Array {
  const боксы = new Float32Array(примитивы.length * 6);
  примитивы.forEach((п, i) => {
    const [a, b, c] = п.размер;
    // ось цилиндра уже в R: полуразмеры по осям изделия = |R|·полуразмеры детали
    const h = [a / 2, b / 2, c / 2];
    const R = п.R;
    for (let k = 0; k < 3; k++) {
      боксы[i * 6 + k] = п.t[k] / 1000;
      боксы[i * 6 + 3 + k] = (Math.abs(R[k * 3]) * h[0] + Math.abs(R[k * 3 + 1]) * h[1] + Math.abs(R[k * 3 + 2]) * h[2]) / 1000;
    }
  });
  return боксы;
}

/**
 * Примитивы экземпляра в позе: `доли` — группа → доля открытия 0…1. Пустая карта (или все нули) — закрытое положение,
 * возвращается тот же результат без копирования. Движения берутся из результата (закрытая сборка).
 */
export function примитивыВПозе(р: РезультатДеталей, доли: ReadonlyMap<string, number> | null): { примитивы: Примитив[]; боксы: Float32Array } {
  if (!доли || !доли.size || !р.подвижные) return { примитивы: р.примитивы, боксы: р.боксы };
  const позы = new Map<string, Поза>();
  for (const д of р.движения) {
    const d = доли.get(д.группа);
    if (d && d > 0) позы.set(д.группа, позаДвижения(д, d));
  }
  if (!позы.size) return { примитивы: р.примитивы, боксы: р.боксы };
  const примитивы = р.примитивы.map((п) => (п.группа ? сПозой(п, позы.get(п.группа)) : п));
  return { примитивы, боксы: боксыПримитивов(примитивы) };
}

/** Класс материала ручки по материалу «ручки» изделия: латунь, чёрный металл, иначе шлифованная нержавейка */
function классРучки(изд: Изделие, экз: Экземпляр): КлассМодели {
  const м = (экз.материалы?.ручки ?? изд.материалы.ручки ?? '').toLowerCase();
  if (м.includes('латун')) return 'латунь';
  if (м.includes('чёрн') || м.includes('черн') || м === '#1d1e20') return 'металл-чёрный';
  return 'нержавейка-пруток';
}

function построить(изд: Изделие, экз: Экземпляр, детально: boolean): РезультатДеталей {
  let д = детали(изд, экз);
  let предупреждение: string | undefined;
  if (д.length > МАКС_ДЕТАЛЕЙ) {
    предупреждение = `деталей ${д.length}, рисуются первые ${МАКС_ДЕТАЛЕЙ}`;
    д = д.slice(0, МАКС_ДЕТАЛЕЙ);
  }
  const раскладка = слитьРаскладку(изд.раскладка, экз.раскладка);
  const петли = раскладка.фасад.петли;
  const видРучки = раскладка.фасад.ручка.вид;
  const примитивы: Примитив[] = [];
  const движения = движенияИзделия(изд, экз);
  const фронтГруппы = new Map(движения.map((x) => [x.группа, x.фронт] as const));
  const классР = классРучки(изд, экз);

  for (const x of д) {
    const [dx, dy, dz] = x.локально.объём;
    if (dx < 0.5 || dy < 0.5 || dz < 0.5) continue;
    let части: Примитив[];
    if (x.форма === 'модель') {
      // эталон: встраиваемая духовка — модель со стеклом, панелью, ручкой и камерой (render/модели/духовка.ts)
      if (x.роль === 'техника' && видТехники(изд) === 'духовка') части = примитивыДуховки(экз.габариты, детально);
      // смесители, чаши, раковины, поддоны — модели по габаритам (render/модели/сантехника.ts)
      else if (изд.конструкция === 'сантехника') части = примитивыСантехники(изд.вариант ?? '', экз.габариты, экз.материалы?.ручки ?? изд.материалы.ручки);
      // точечные светильники в потолок (render/модели/светильники.ts)
      else if (изд.конструкция === 'светильник') части = примитивыСветильника(изд.вариант ?? '', экз.габариты, экз.материалы?.ручки ?? изд.материалы.ручки);
      else части = x.роль === 'техника' ? примитивыТехники(изд, экз, петли) : x.роль === 'проём' ? заглушкаПроёма(x) : заглушкаДекора(x, изд);
    } else if (x.форма === 'цилиндр' && x.роль === 'штанга') {
      // штанга: хромированная труба Ø25 с держателями на концах (docs/модели.md §1)
      части = штангаМоделью(x);
    } else if (x.форма === 'цилиндр') {
      const ось = x.ось ?? 'y';
      const L = ось === 'x' ? dx : ось === 'z' ? dz : dy;
      const диаметр = ось === 'x' ? Math.max(dy, dz) : ось === 'z' ? Math.max(dx, dy) : Math.max(dx, dz);
      // профиль 3/4 (карусель углового модуля) — только с вертикальной осью
      const форма: ФормаПримитива = x.профиль === 'сектор270' ? 'сектор' : x.профиль === 'обод270' ? 'обод' : 'цилиндр';
      части = [
        { форма, размер: [диаметр, L, диаметр], t: x.локально.центр, R: форма === 'цилиндр' ? ПОВОРОТ_ОСИ[ось] : ЕДИНИЧНАЯ, мат: x.литерал ?? x.материал, биты: 0, r: 0, тень: true },
      ];
    } else if (x.роль === 'фурнитура' && x.форма === 'плита') {
      // покупная фурнитура-брус (рама подъёмника, ламели): модель со скруглёнными рёбрами, в деталировку не идёт
      const металл = (x.литерал?.мет ?? 0) > 0.5;
      // светлый металл (алюминиевый профиль) — никель, тёмный (рама кровати) — чёрный металл
      const светлый = металл && parseInt((x.литерал?.цвет ?? '#000000').slice(1, 3), 16) > 0x80;
      const r = Math.min(металл ? 2 : 1.5, Math.min(dx, dy, dz) / 3);
      части = [{ форма: 'модель', модель: { геом: ключГеом('брус', dx, dy, dz, r, 2), класс: светлый ? 'никель' : металл ? 'металл-чёрный' : 'берёза' }, размер: [dx, dy, dz], t: x.локально.центр, R: ЕДИНИЧНАЯ, мат: 'ручки', биты: 0, r: 0, тень: true }];
    } else if (x.роль === 'ручка' && x.форма === 'плита' && (видРучки === 'скоба' || видРучки === 'рейлинг' || видРучки === 'кнопка')) {
      // ручка настоящим профилем: скоба на стойках, рейлинг, кнопка (docs/модели.md §1)
      части = ручкаМоделью(x.локально.центр, x.локально.объём, видРучки, x.подвижная?.группа, фронтГруппы.get(x.подвижная?.группа ?? '') ?? [0, 1], классР);
    } else {
      const стекло = x.материал === 'стекло';
      // ножки стола и стула — тёмное дерево, как в v1
      const мат: Примитив['мат'] = x.литерал ?? (x.роль === 'цоколь' ? 'цоколь' : x.роль === 'ножка' ? литерал(изд.тип === 'стул' ? '#7d5f3e' : '#8a6a44', 0.75, 0.05) : x.материал);
      части = [
        {
          форма: стекло ? 'стекло' : 'плита',
          размер: x.локально.объём,
          t: x.локально.центр,
          R: ЕДИНИЧНАЯ,
          мат,
          биты: стекло ? 0 : битыКромки(x.локально.объём, x.кромка) | (ЛДСП.has(x.материал) ? 64 : 0),
          r: радиусФаски(x.кромка),
          тень: !стекло,
        },
      ];
    }
    if (x.подвижная && x.форма !== 'модель') for (const ч of части) ч.группа = x.подвижная.группа;
    for (const ч of части) примитивы.push(ч);
  }

  // кровать с подъёмником: матрас, мягкое изголовье, подушки (только рендер)
  if (изд.конструкция === 'кровать-подъёмная') примитивы.push(...примитивыКровати(экз.габариты, экз.материалы?.фасад ?? изд.материалы.фасад ?? '#8a6f55', детально));
  // петли распашных дверей и полкодержатели — только вблизи (LOD)
  if (детально && изд.тип !== 'техника' && !изд.конструкция) {
    for (const дв of движения) if (дв.вид === 'дверь') примитивы.push(...петлиДвери(дв));
    for (const x of д) if (x.роль === 'полка') примитивы.push(...полкодержатели(x.локально.центр, x.локально.объём));
  }
  const группыДвижений = new Set(движения.map((д) => д.группа));
  // передние створки купе, не имеющие своего движения, всё равно знают группу (клик → группаДляКлика)
  return { примитивы, деталей: д.length, боксы: боксыПримитивов(примитивы), предупреждение, движения, подвижные: примитивы.some((п) => п.группа && (группыДвижений.has(п.группа) || /купе-\d+$/.test(п.группа))) };
}
