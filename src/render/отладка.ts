/**
 * window.__кухня — хук для автотестов и замера. Сохраняется из v1 (`gl`, `scene`, `camera`, `экраннаяТочка`, `стрелкаГизмо`)
 * плюс `стрелка(ось)` (основание и кончик настоящей стрелки в клиентских координатах) и `экземплярНаЭкране(id)`.
 */
import * as THREE from 'three';
import { useКухня } from '../store';
import type { Ядро } from './ядро';

export function вКлиентские(я: Ядро, gl: THREE.WebGLRenderer, scene: THREE.Scene, camera: THREE.PerspectiveCamera) {
  const w = window as unknown as Record<string, unknown>;

  const стрелка = (ось: 'X' | 'Y' | 'Z') => {
    я.стрелки.обновить(camera, gl.domElement.clientHeight || 800);
    const с = я.стрелки.стрелки.find((x) => x.ось === ось);
    if (!с) return null;
    return {
      id: с.id,
      основание: я.экраннаяТочка(...с.начало),
      кончик: я.экраннаяТочка(...с.кончик),
      началоМ: с.начало,
      кончикМ: с.кончик,
    };
  };

  w.__кухня = {
    camera,
    gl,
    scene,
    ядро: я,
    экраннаяТочка: (x: number, y: number, z: number) => я.экраннаяТочка(x, y, z),
    стрелка,
    /** совместимость со скриптом v1: «верх» — кончик стрелки */
    стрелкаГизмо: (имя: string) => {
      const с = стрелка(имя as 'X' | 'Y' | 'Z');
      return с ? { основание: с.основание, верх: с.кончик } : null;
    },
    экземплярНаЭкране: (id: string) => {
      const з = я.сборщик.запись(id);
      if (!з) return null;
      const ц = з.цель;
      return я.экраннаяТочка(ц.позиция[0], ц.позиция[1] + ц.полу[1], ц.позиция[2]);
    },
    статистика: () => ({
      draw_calls: gl.info.render.calls,
      треугольников: gl.info.render.triangles,
      кадров_gl: gl.info.render.frame,
      кадров_ядро: я.кадров,
      пересчётов_теней: я.тени.пересчётов,
      сборка_мс: +я.сборщик.сборкаМс.toFixed(1),
      профиль: я.профиль.имя,
      видеокарта: я.видеокарта.имя,
      msaa: я.msaa,
      dpr: gl.getPixelRatio(),
      карта_теней: я.тени.свет.shadow.mapSize.x,
      группы: я.сборщик.статистика(),
      геометрий: gl.info.memory.geometries,
      журнал: [...я.сборщик.журнал, ...я.журнал],
    }),
    проблемы: () => я.проблемы,
    /** поставить камеру для скриншотов и проверок: позиция в метрах, yaw и pitch в радианах */
    поставитьКамеру: (x: number, y: number, z: number, yaw: number, pitch: number) => {
      я.камераОбзора.pos.set(x, y, z);
      я.камераОбзора.yaw = yaw;
      я.камераОбзора.pitch = pitch;
      я.камераОбзора.кадр(0);
      я.попроситьКадр();
    },
    режимФаски: (р: 'авто' | 'шейдер' | 'настоящая') => {
      я.режимФаски = р;
      я.попроситьКадр();
    },
    самопроверкаГотова: я.самопроверкаГотова,
  };

  // мировые координаты объектов в метрах (для старого скрипта проверки интерфейса)
  const обновить = () => {
    const с = useКухня.getState();
    w.__проект_объекты = с.проект2.объекты.filter((о) => о.помещение === с.помещениеАктивное).map((о) => [о.позиция[0] / 1000, о.позиция[1] / 1000, о.позиция[2] / 1000]);
  };
  обновить();
  useКухня.subscribe(обновить);
}
