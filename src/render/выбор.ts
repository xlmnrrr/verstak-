/**
 * Выбор мышью без чтения пикселей и без встроенных лучей three. Две ступени:
 * 1) луч против габаритного параллелепипеда (OBB) каждого экземпляра;
 * 2) луч в локальных осях кандидата против коробок его деталей. Результат — экземпляр и деталь.
 * Чистая математика, метры.
 */
import type { Луч, В3 } from './жесты-математика';

export interface ЦельВыбора {
  /** позиция экземпляра (низ, центр), метры */
  позиция: В3;
  cos: number;
  sin: number;
  /** полуразмеры габарита по локальным осям: ш/2, в/2, г/2 */
  полу: В3;
  /** коробки деталей: cx,cy,cz,hx,hy,hz (метры, оси изделия) */
  боксы: Float32Array;
  /** подвижная группа каждой коробки (дверь, ящик, створка); нет — деталь корпуса */
  группы?: (string | undefined)[];
  /** охватывающая коробка с открытыми дверцами (cx,cy,cz,hx,hy,hz): первая ступень выбора, если шире габарита */
  охват?: number[];
}

/** Мир → локальные оси изделия: поворот на −θ, где θ — поворот экземпляра (три: rotation.y = −θ) */
export function вЛокальный(ц: ЦельВыбора, p: В3, вектор = false): В3 {
  const dx = vector(p[0], ц.позиция[0], вектор);
  const dy = vector(p[1], ц.позиция[1], вектор);
  const dz = vector(p[2], ц.позиция[2], вектор);
  return [ц.cos * dx + ц.sin * dz, dy, -ц.sin * dx + ц.cos * dz];
}
const vector = (a: number, b: number, вектор: boolean) => (вектор ? a : a - b);

/** Слэб-метод: расстояние вдоль луча до коробки (t ≥ 0) или null */
export function лучПротивКоробки(о: В3, н: В3, cx: number, cy: number, cz: number, hx: number, hy: number, hz: number): number | null {
  let tмин = 0;
  let tмакс = Infinity;
  const центр = [cx, cy, cz];
  const полу = [hx, hy, hz];
  for (let i = 0; i < 3; i++) {
    const d = н[i];
    const мин = центр[i] - полу[i] - о[i];
    const макс = центр[i] + полу[i] - о[i];
    if (Math.abs(d) < 1e-12) {
      if (мин > 0 || макс < 0) return null;
    } else {
      let a = мин / d;
      let b = макс / d;
      if (a > b) [a, b] = [b, a];
      tмин = Math.max(tмин, a);
      tмакс = Math.min(tмакс, b);
      if (tмин > tмакс) return null;
    }
  }
  return tмин;
}

export interface РезультатВыбора {
  индекс: number;
  t: number;
  /** индекс коробки детали (по порядку примитивов) */
  деталь: number;
}

/** Ближайшая цель под лучом: 1) OBB, 2) коробки деталей */
export function выбратьЦель(луч: Луч, цели: ЦельВыбора[]): РезультатВыбора | null {
  let лучший: РезультатВыбора | null = null;
  for (let k = 0; k < цели.length; k++) {
    const ц = цели[k];
    const о = вЛокальный(ц, луч.о);
    const н = вЛокальный(ц, луч.н, true);
    const ох = ц.охват;
    const t1 = ох ? лучПротивКоробки(о, н, ох[0], ох[1], ох[2], ох[3], ох[4], ох[5]) : лучПротивКоробки(о, н, 0, ц.полу[1], 0, ц.полу[0], ц.полу[1], ц.полу[2]);
    if (t1 === null) continue;
    if (лучший && t1 > лучший.t + 3) continue;
    // ступень 2: детали
    let tд = Infinity;
    let де = -1;
    const б = ц.боксы;
    for (let i = 0; i * 6 < б.length; i++) {
      const t = лучПротивКоробки(о, н, б[i * 6], б[i * 6 + 1], б[i * 6 + 2], б[i * 6 + 3], б[i * 6 + 4], б[i * 6 + 5]);
      if (t !== null && t < tд) {
        tд = t;
        де = i;
      }
    }
    if (де < 0) continue;
    if (!лучший || tд < лучший.t) лучший = { индекс: k, t: tд, деталь: де };
  }
  return лучший;
}

/** Расстояние от точки до ближайшей точки OBB (для отбора изделий под настоящую фаску), метры */
export function расстояниеДоОББ(ц: ЦельВыбора, p: В3): number {
  const л = вЛокальный(ц, p);
  const cy = ц.полу[1];
  const dx = Math.max(Math.abs(л[0]) - ц.полу[0], 0);
  const dy = Math.max(Math.abs(л[1] - cy) - ц.полу[1], 0);
  const dz = Math.max(Math.abs(л[2]) - ц.полу[2], 0);
  return Math.hypot(dx, dy, dz);
}
