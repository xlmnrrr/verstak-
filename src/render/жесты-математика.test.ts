import { describe, expect, it } from 'vitest';
import {
  позицияПоОси,
  пределПоВысоте,
  растяжение,
  смещениеПоОси,
  уголПоМыши,
  вычесть,
  нормировать,
  type В3,
  type Луч,
} from './жесты-математика';

/** Камера на расстоянии d под углами: высота над горизонтом (градусы) и азимут */
const камеры: { имя: string; поз: (ц: В3) => В3 }[] = [
  { имя: 'сбоку', поз: (ц) => [ц[0] + 4, ц[1] + 0.2, ц[2]] },
  { имя: '41° сверху', поз: (ц) => [ц[0], ц[1] + 4 * Math.sin(0.72), ц[2] + 4 * Math.cos(0.72)] },
  { имя: 'почти отвесно', поз: (ц) => [ц[0], ц[1] + 4 * Math.sin(1.48), ц[2] + 4 * Math.cos(1.48)] },
  { имя: 'снизу', поз: (ц) => [ц[0] + 1, ц[1] - 1, ц[2] + 3] },
  { имя: 'вдоль оси', поз: (ц) => [ц[0] + 0.001, ц[1] + 4, ц[2]] },
];

const лучЧерез = (камера: В3, цель: В3): Луч => ({ о: камера, н: нормировать(вычесть(цель, камера)) });

describe('тяга по оси: смещение не зависит от места захвата', () => {
  const начало: В3 = [1, 0.4, -0.5];
  const длинаСтрелки = 0.55;
  for (const к of камеры) {
    for (const доля of [0.1, 0.4, 0.6, 0.9]) {
      it(`${к.имя}, захват на ${доля * 100}% стрелки`, () => {
        const камера = к.поз(начало);
        const ось: В3 = [0, 1, 0];
        const захват: В3 = [начало[0], начало[1] + длинаСтрелки * доля, начало[2]];
        const d = 0.18;
        const цель: В3 = [захват[0], захват[1] + d, захват[2]];
        const смещение = смещениеПоОси({
          луч0: лучЧерез(камера, захват),
          луч1: лучЧерез(камера, цель),
          начало,
          ось,
          камера,
          экран: { dx: 0, dy: -60, ux: 0, uy: -1, метровНаПиксель: 0.003, вертикальная: true },
        });
        expect(Number.isFinite(смещение)).toBe(true);
        if (к.имя !== 'вдоль оси' && к.имя !== 'почти отвесно') expect(смещение).toBeCloseTo(d, 6);
        // в любом случае меняется только y: две другие координаты копируются побитно
        const старт: В3 = [-1120, 1500, 333];
        const н = позицияПоОси(старт, 1, смещение * 1000, 50, true, пределПоВысоте(2700, 720));
        expect(н[0]).toBe(старт[0]);
        expect(н[2]).toBe(старт[2]);
      });
    }
  }

  it('объект не по сетке с прилипанием: x и z не прыгают к шагу', () => {
    const н = позицияПоОси([-1120, 0, 333], 1, 120, 50, true);
    expect(н).toEqual([-1120, 100, 333]);
    const н2 = позицияПоОси([-1123, 0, 337], 0, 10, 50, true);
    expect(н2).toEqual([-1100, 0, 337]);
  });

  it('навесной на 1500 поднимается вверх, а не падает на пол', () => {
    const н = позицияПоОси([0, 1500, 0], 1, 200, 50, true, пределПоВысоте(2700, 720));
    expect(н[1]).toBe(1700);
    const потолок = позицияПоОси([0, 1500, 0], 1, 5000, 50, true, пределПоВысоте(2700, 720));
    expect(потолок[1]).toBe(1980);
    const пол = позицияПоОси([0, 1500, 0], 1, -5000, 50, true, пределПоВысоте(2700, 720));
    expect(пол[1]).toBe(0);
  });

  it('предел по высоте для объекта выше комнаты — ноль', () => {
    expect(пределПоВысоте(2400, 2600)).toEqual({ мин: 0, макс: 0 });
  });
});

describe('крутить и растянуть', () => {
  it('угол: 0,6° на пиксель, прилипание 15°, Shift 90°, обход через 360', () => {
    expect(уголПоМыши(0, 50, false, false)).toBe(30);
    expect(уголПоМыши(0, 50, true, false)).toBe(30);
    expect(уголПоМыши(0, 40, true, false)).toBe(30);
    expect(уголПоМыши(0, 40, true, true)).toBe(0);
    expect(уголПоМыши(0, 100, true, true)).toBe(90);
    expect(уголПоМыши(10, -50, false, false)).toBe(340);
  });

  it('растянуть + стороной: противоположная грань стоит на месте', () => {
    const р = растяжение(600, 100, 50, true, false, 300, 1200);
    expect(р).toEqual({ размер: 700, сдвиг: 50 });
    // грань −: центр − размер/2 = (0 + 50) − 700/2 = −300 = 0 − 600/2 ✓
  });

  it('границы изделия и симметричная тяга', () => {
    expect(растяжение(600, 9000, 50, true, false, 300, 1200).размер).toBe(1200);
    expect(растяжение(600, -9000, 50, true, false, 300, 1200).размер).toBe(300);
    expect(растяжение(600, 100, 50, true, true, 300, 1200)).toEqual({ размер: 800, сдвиг: 0 });
  });
});
