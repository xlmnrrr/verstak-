import { describe, expect, it } from 'vitest';
import { МониторКадров, профильПоВидеокарте, профильПослеСамопроверки, ПРОФИЛИ } from './качество';

describe('профиль по видеокарте', () => {
  it('GTX 1650 — высокое, Iris Xe — среднее, UHD — слабый, SwiftShader — слабый и программная', () => {
    expect(профильПоВидеокарте('ANGLE (NVIDIA, NVIDIA GeForce GTX 1650 Direct3D11 vs_5_0 ps_5_0, D3D11)').профиль).toBe('высокое');
    expect(профильПоВидеокарте('ANGLE (Intel, Intel(R) Iris(R) Xe Graphics)').профиль).toBe('среднее');
    expect(профильПоВидеокарте('ANGLE (Intel, Intel(R) UHD Graphics 620)').профиль).toBe('слабый ноутбук');
    const п = профильПоВидеокарте('ANGLE (Google, Vulkan 1.3.0 (SwiftShader Device (Subzero)), SwiftShader driver)');
    expect(п.профиль).toBe('слабый ноутбук');
    expect(п.программная).toBe(true);
  });

  it('тени включены во всех профилях: у каждого есть карта теней', () => {
    for (const п of Object.values(ПРОФИЛИ)) expect(п.карта).toBeGreaterThanOrEqual(1024);
  });
});

describe('самопроверка', () => {
  it('медленные кадры — ступень ниже, быстрые — прежний, скрытое окно — не судим', () => {
    expect(профильПослеСамопроверки('высокое', new Array(60).fill(25)).профиль).toBe('среднее');
    expect(профильПослеСамопроверки('высокое', new Array(60).fill(16.7)).профиль).toBe('высокое');
    expect(профильПослеСамопроверки('высокое', new Array(60).fill(500)).годится).toBe(false);
  });
});

describe('монитор кадров', () => {
  it('2 с кадров по 30 мс — вниз; паузы между отрезками не считаются', () => {
    const м = new МониторКадров({ интервалЭкрана: 16.7 }, 'высокое');
    let t = 1000;
    let итог = null;
    for (let i = 0; i < 100 && !итог; i++) {
      t += 30;
      итог = м.кадр(t);
    }
    expect(итог).toBe('среднее');

    const м2 = new МониторКадров({ интервалЭкрана: 16.7 }, 'высокое');
    t = 0;
    for (let i = 0; i < 50; i++) {
      t += 500; // одиночные кадры с паузами: не сплошной отрезок
      expect(м2.кадр(t)).toBeNull();
    }
  });

  it('вверх только после 10 с ровной работы и не на ступень, с которой спустились', () => {
    const м = new МониторКадров({ интервалЭкрана: 16.7 }, 'среднее');
    let t = 0;
    let итог = null;
    for (let i = 0; i < 1000 && !итог; i++) {
      t += 16.7;
      итог = м.кадр(t);
    }
    // 10 с, но с момента создания не прошло 60 с с последнего переключения? последнего не было → вверх
    expect(итог).toBe('высокое');
  });
});
