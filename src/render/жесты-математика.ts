/**
 * Чистые функции жестов: лучи, плоскости, смещение вдоль оси, прилипание. Без three и DOM (простые массивы).
 * Метры — для лучей и точек сцены, миллиметры — для позиций и размеров в модели.
 */
export type В3 = [number, number, number];

export interface Луч {
  о: В3;
  н: В3;
}

export const вычесть = (a: В3, b: В3): В3 => [a[0] - b[0], a[1] - b[1], a[2] - b[2]];
export const сложить = (a: В3, b: В3): В3 => [a[0] + b[0], a[1] + b[1], a[2] + b[2]];
export const масштаб = (a: В3, k: number): В3 => [a[0] * k, a[1] * k, a[2] * k];
export const скаляр = (a: В3, b: В3) => a[0] * b[0] + a[1] * b[1] + a[2] * b[2];
export const длина = (a: В3) => Math.hypot(a[0], a[1], a[2]);
export const нормировать = (a: В3): В3 => {
  const л = длина(a);
  return л > 1e-12 ? [a[0] / л, a[1] / л, a[2] / л] : [0, 0, 0];
};

/** Точка пересечения луча с плоскостью; null — луч параллелен или плоскость позади */
export function пересечениеСПлоскостью(л: Луч, точка: В3, нормаль: В3): В3 | null {
  const знам = скаляр(л.н, нормаль);
  if (Math.abs(знам) < 1e-9) return null;
  const t = скаляр(вычесть(точка, л.о), нормаль) / знам;
  if (t < 0) return null;
  return сложить(л.о, масштаб(л.н, t));
}

/** Порог «смотрим почти вдоль оси» (составляющая направления на камеру поперёк оси) */
export const ПОРОГ_ВДОЛЬ_ОСИ = 0.15;

export interface ЭкранныйЗапас {
  /** сдвиг мыши от нажатия, пиксели */
  dx: number;
  dy: number;
  /** единичное направление оси на экране (y вниз); [0,0] — ось проецируется в точку */
  ux: number;
  uy: number;
  /** сколько метров на пиксель на глубине объекта */
  метровНаПиксель: number;
  /** ось вертикальна: при вырожденной проекции тянем вверх-вниз */
  вертикальная: boolean;
}

export interface ВходОси {
  /** луч под курсором в момент нажатия и сейчас */
  луч0: Луч;
  луч1: Луч;
  /** начало оси (точка объекта) и единичное направление оси, метры */
  начало: В3;
  ось: В3;
  камера: В3;
  экран?: ЭкранныйЗапас;
}

/**
 * Смещение вдоль оси (метры). Плоскость содержит ось и повёрнута к камере; смещение — проекция на ось разности
 * точек курсора на этой плоскости. Место захвата на стрелке не важно, важна только разница.
 * Если смотрим почти вдоль оси — смещение из сдвига мыши по экранной проекции оси.
 */
export function смещениеПоОси(в: ВходОси): number {
  const к = нормировать(вычесть(в.камера, в.начало));
  const поперёк = вычесть(к, масштаб(в.ось, скаляр(к, в.ось)));
  const запасное = () => {
    const э = в.экран;
    if (!э) return 0;
    const л = Math.hypot(э.ux, э.uy);
    if (л > 0.3) return ((э.dx * э.ux + э.dy * э.uy) / л) * э.метровНаПиксель;
    return (э.вертикальная ? -э.dy : -э.dy) * э.метровНаПиксель;
  };
  if (длина(поперёк) < ПОРОГ_ВДОЛЬ_ОСИ) return запасное();
  const n = нормировать(поперёк);
  const q0 = пересечениеСПлоскостью(в.луч0, в.начало, n);
  const q1 = пересечениеСПлоскостью(в.луч1, в.начало, n);
  if (!q0 || !q1) return запасное();
  return скаляр(вычесть(q1, q0), в.ось);
}

/** Прилипание к шагу; шаг ≤ 0 — просто целые */
export const прилипнуть = (v: number, шаг: number): number => (шаг > 0 ? Math.round(v / шаг) * шаг : Math.round(v));

/**
 * Новая позиция при тяге по одной оси: стартовая, в которой заменена одна координата.
 * Две другие копируются как есть — без округления и без повторного ограничения.
 * Прилипание — только у тянущейся оси. Позиция в мм: [x, y (низ), z].
 */
export function позицияПоОси(
  старт: В3,
  ось: 0 | 1 | 2,
  смещениеМм: number,
  шаг: number,
  прилипание: boolean,
  предел?: { мин: number; макс: number },
): В3 {
  let v = старт[ось] + смещениеМм;
  if (прилипание && шаг > 0) v = прилипнуть(v, шаг);
  v = Math.round(v);
  if (предел) v = Math.max(предел.мин, Math.min(Math.max(предел.мин, предел.макс), v));
  const н: В3 = [старт[0], старт[1], старт[2]];
  н[ось] = v;
  return н;
}

/** Предел по высоте для тяги по Y: от 0 до высота помещения − высота объекта (мм) */
export const пределПоВысоте = (высотаПомещения: number, высотаОбъекта: number) => ({
  мин: 0,
  макс: Math.max(0, высотаПомещения - высотаОбъекта),
});

/**
 * Угол при «крутить»: 0,6° на пиксель вертикального сдвига мыши. С Shift — шаг 90°, с прилипанием — 15°.
 */
export function уголПоМыши(старт: number, dyПикс: number, прилипание: boolean, shift: boolean): number {
  const сырой = старт + dyПикс * 0.6;
  const шаг = shift ? 90 : прилипание ? 15 : 1;
  const в = Math.round(сырой / шаг) * шаг;
  return ((в % 360) + 360) % 360;
}

/**
 * «Растянуть» одной стороной: тянется + грань, противоположная стоит на месте. Размер и сдвиг центра вдоль локальной оси.
 * С Alt — симметрично (центр на месте). Возвращает новый размер и сдвиг центра в мм по локальной оси.
 */
export function растяжение(
  стартРазмер: number,
  смещениеМм: number,
  шаг: number,
  прилипание: boolean,
  симметрично: boolean,
  мин: number,
  макс: number,
): { размер: number; сдвиг: number } {
  let размер = стартРазмер + (симметрично ? 2 : 1) * смещениеМм;
  if (прилипание && шаг > 0) размер = прилипнуть(размер, шаг);
  размер = Math.round(Math.max(мин, Math.min(макс, размер)));
  const изменение = размер - стартРазмер;
  return { размер, сдвиг: симметрично ? 0 : изменение / 2 };
}
