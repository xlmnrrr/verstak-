import { describe, expect, it } from 'vitest';
import { Анимации, ДЛИТЕЛЬНОСТЬ_МС } from './анимация';

const цели = (о: Record<string, number>) => new Map(Object.entries(о));

describe('анимация открывания', () => {
  it('длится 150–200 мс', () => {
    expect(ДЛИТЕЛЬНОСТЬ_МС).toBeGreaterThanOrEqual(150);
    expect(ДЛИТЕЛЬНОСТЬ_МС).toBeLessThanOrEqual(200);
  });

  it('новый владелец появляется сразу в нужной позе, без анимации', () => {
    const а = new Анимации();
    expect(а.задать('э:1', цели({ 'дверь-0': 1 }), false, 0)).toBe(false);
    expect(а.идёт).toBe(false);
    expect(а.доля('э:1', 'дверь-0')).toBe(1);
    expect(а.доли('э:1')?.get('дверь-0')).toBe(1);
  });

  it('смена цели запускает анимацию: промежуточные доли монотонны, в конце ровно цель', () => {
    const а = new Анимации();
    а.задать('э:1', цели({ 'дверь-0': 0 }), false, 0);
    expect(а.доли('э:1')).toBeNull();
    expect(а.задать('э:1', цели({ 'дверь-0': 1 }), false, 100)).toBe(true);
    expect(а.идёт).toBe(true);
    let прошлая = 0;
    let закончилась = false;
    for (let t = 100; t <= 100 + ДЛИТЕЛЬНОСТЬ_МС + 20; t += 20) {
      const ш = а.шаг(t);
      const д = а.доля('э:1', 'дверь-0');
      expect(д).toBeGreaterThanOrEqual(прошлая);
      expect(д).toBeLessThanOrEqual(1);
      прошлая = д;
      if (ш.закончились.has('э:1')) закончилась = true;
    }
    expect(закончилась).toBe(true);
    expect(а.доля('э:1', 'дверь-0')).toBe(1);
    expect(а.идёт).toBe(false);
  });

  it('на середине времени доля около половины (плавный старт и торможение симметричны)', () => {
    const а = new Анимации();
    а.задать('э:1', цели({ г: 0 }), false, 0);
    а.задать('э:1', цели({ г: 1 }), false, 0);
    а.шаг(ДЛИТЕЛЬНОСТЬ_МС / 2);
    expect(а.доля('э:1', 'г')).toBeCloseTo(0.5, 2);
  });

  it('повторная смена цели посреди анимации разворачивает от текущей доли, без скачка', () => {
    const а = new Анимации();
    а.задать('э:1', цели({ г: 0 }), false, 0);
    а.задать('э:1', цели({ г: 1 }), false, 0);
    а.шаг(ДЛИТЕЛЬНОСТЬ_МС * 0.6);
    const середина = а.доля('э:1', 'г');
    expect(середина).toBeGreaterThan(0.3);
    а.задать('э:1', цели({ г: 0 }), false, ДЛИТЕЛЬНОСТЬ_МС * 0.6);
    а.шаг(ДЛИТЕЛЬНОСТЬ_МС * 0.6 + 1);
    expect(Math.abs(а.доля('э:1', 'г') - середина)).toBeLessThan(0.05);
    а.шаг(ДЛИТЕЛЬНОСТЬ_МС * 3);
    expect(а.доля('э:1', 'г')).toBe(0);
    expect(а.идёт).toBe(false);
  });

  it('мгновенно: без анимации, даже если цель сменилась', () => {
    const а = new Анимации();
    а.задать('э:1', цели({ г: 0 }), false, 0);
    expect(а.задать('э:1', цели({ г: 1 }), true, 5)).toBe(false);
    expect(а.идёт).toBe(false);
    expect(а.доля('э:1', 'г')).toBe(1);
  });

  it('счётчик идущих сходится к нулю: удаление владельца и сброс', () => {
    const а = new Анимации();
    а.задать('э:1', цели({ г: 0, к: 0 }), false, 0);
    а.задать('э:1', цели({ г: 1, к: 1 }), false, 0);
    expect(а.идёт).toBe(true);
    а.удалить('э:1');
    expect(а.идёт).toBe(false);
    а.задать('э:2', цели({ г: 0 }), false, 0);
    а.задать('э:2', цели({ г: 1 }), false, 0);
    а.сбросить();
    expect(а.идёт).toBe(false);
    expect(а.доли('э:2')).toBeNull();
  });

  it('группа, которой больше нет у изделия, не оставляет «вечной» анимации', () => {
    const а = new Анимации();
    а.задать('э:1', цели({ a: 0, b: 0 }), false, 0);
    а.задать('э:1', цели({ a: 1, b: 1 }), false, 0);
    а.задать('э:1', цели({ a: 1 }), false, 10);
    а.шаг(ДЛИТЕЛЬНОСТЬ_МС * 2);
    expect(а.идёт).toBe(false);
  });

  it('в простое шаг ничего не меняет', () => {
    const а = new Анимации();
    а.задать('э:1', цели({ г: 0 }), false, 0);
    const ш = а.шаг(1000);
    expect(ш.изменились.size).toBe(0);
    expect(ш.закончились.size).toBe(0);
  });
});
