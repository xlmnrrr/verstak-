import { describe, expect, it } from 'vitest';
import { выбратьЦель, расстояниеДоОББ, type ЦельВыбора } from './выбор';

const шкаф = (x: number, z: number, угол = 0): ЦельВыбора => {
  const θ = (угол * Math.PI) / 180;
  return {
    позиция: [x, 0, z],
    cos: Math.cos(θ),
    sin: Math.sin(θ),
    полу: [0.3, 0.36, 0.3],
    // боковина слева и справа, задник
    боксы: new Float32Array([-0.292, 0.36, 0, 0.008, 0.36, 0.3, 0.292, 0.36, 0, 0.008, 0.36, 0.3, 0, 0.36, -0.296, 0.3, 0.36, 0.004]),
  };
};

describe('выбор мышью', () => {
  it('луч сверху попадает в боковину, ближайший шкаф выигрывает', () => {
    const цели = [шкаф(0, 0), шкаф(0, 2)];
    const р = выбратьЦель({ о: [-0.292, 3, 0], н: [0, -1, 0] }, цели);
    expect(р?.индекс).toBe(0);
  });

  it('луч в пустое место между боковинами (нет деталей на пути) — не выбирает', () => {
    const цели = [шкаф(0, 0)];
    // сверху по центру: боковины и задник не на пути
    expect(выбратьЦель({ о: [0, 3, 0.1], н: [0, -1, 0] }, цели)).toBeNull();
  });

  it('поворот на 90°: фасадная ось смотрит в −X', () => {
    const ц = шкаф(0, 0, 90);
    // задник повернулся в +X: луч по оси X с положительной стороны попадает в задник раньше боковины
    const р = выбратьЦель({ о: [2, 0.36, 0], н: [-1, 0, 0] }, [ц]);
    expect(р?.деталь).toBe(2);
  });

  it('расстояние до OBB: внутри 0, снаружи по оси', () => {
    const ц = шкаф(1, 1);
    expect(расстояниеДоОББ(ц, [1, 0.3, 1])).toBeCloseTo(0);
    expect(расстояниеДоОББ(ц, [2, 0.3, 1])).toBeCloseTo(0.7);
  });
});
