function useСмета(): Смета {
  const [с, установить] = useState<Смета>(() => смета(useКухня.getState().проект2, useКухня.getState().помещениеАктивное));
  useEffect(() => {
    let таймер = 0;
    const пересчитать = () => {
      таймер = 0;
      const ст = useКухня.getState();
      установить(смета(ст.проект2, ст.помещениеАктивное));
    };
    // подписка без перерисовки на каждый шаг жеста: пересчёт через 250 мс после последней правки
    const отписка = useКухня.subscribe((ст, пр) => {
      if (ст.проект2.объекты === пр.проект2.объекты && ст.помещениеАктивное === пр.помещениеАктивное) return;
      if (таймер) clearTimeout(таймер);
      таймер = window.setTimeout(пересчитать, 250);
    });
    пересчитать();
    return () => {
      отписка();
      if (таймер) clearTimeout(таймер);
    };
  }, []);
  return с;
}

