/**
 * Подписка на store с ограничением частоты: на жесте (перетаскивание, растягивание) панель обновляется не чаще 10 раз в секунду,
 * иначе перерисовка панелей съедает кадр на слабом процессоре.
 */
function useКухняТротл<T>(выбор: (с: ReturnType<typeof useКухня.getState>) => T, мс = 100): T {
  const [значение, установить] = useState<T>(() => выбор(useКухня.getState()));
  useEffect(() => {
    let таймер = 0;
    let последний = 0;
    const применить = () => {
      таймер = 0;
      последний = performance.now();
      установить(() => выбор(useКухня.getState()));
    };
    const отписка = useКухня.subscribe(() => {
      // на жесте панели обновляются втрое реже: поля цифр успевают за мышью, а кадр не страдает
      const ост = (useКухня.getState().жест === 'идёт' ? мс * 3 : мс) - (performance.now() - последний);
      if (ост <= 0) {
        if (таймер) clearTimeout(таймер);
        применить();
      } else if (!таймер) таймер = window.setTimeout(применить, ост);
    });
    применить();
    return () => {
      отписка();
      if (таймер) clearTimeout(таймер);
    };
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [мс]);
  return значение;
}


/** Правка проекта одной записью истории: граница до, закрытие после (Ctrl+Z откатывает ровно её) */
function useПравка() {
  const начать = useКухня((s) => s.начатьИзменение);
  const закончить = useКухня((s) => s.завершитьИзменение);
  return <T,>(действие: () => T): T => {
    начать();
    const р = действие();
    закончить();
    return р;
  };
}

function Число({ подпись, значение, наИзменение, шаг = 10 }: { подпись: string; значение: number; наИзменение: (v: number) => void; шаг?: number }) {
  const [текст, установитьТекст] = useState(String(Math.round(значение)));
  useEffect(() => установитьТекст(String(Math.round(значение))), [значение]);
  const зафиксировать = () => {
    const ч = Number(текст.replace(',', '.'));
    // без изменения значения команда не создаётся: иначе пустая запись попадает в историю
    if (Number.isFinite(ч)) {
      if (Math.round(ч) !== Math.round(значение)) наИзменение(Math.round(ч));
    } else установитьТекст(String(Math.round(значение)));
  };
  return (
    <div className="поле">
      <label>{подпись}</label>
      <input
        type="number"
        step={шаг}
        value={текст}
        onChange={(e) => установитьТекст(e.target.value)}
        onBlur={зафиксировать}
        onKeyDown={(e) => {
          if (e.key === 'Enter') (e.target as HTMLInputElement).blur();
        }}
      />
    </div>
  );
}

