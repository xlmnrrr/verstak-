  const сохранить = useКухня((s) => s.сохранить);
  const выгрузить = useКухня((s) => s.выгрузить);
  const открытьФайл = useКухня((s) => s.открытьФайл);
  const наЭкран = useКухня((s) => s.наЭкран);
  const переименовать = useКухня((s) => s.переименовать);
