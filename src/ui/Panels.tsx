function Конструктор() {
  const поиск = useКухня((s) => s.поиск);
  const установитьПоиск = useКухня((s) => s.установитьПоиск);
  const категория = useКухня((s) => s.категория);
  const установитьКатегорию = useКухня((s) => s.установитьКатегорию);
  const добавитьМодуль = useКухня((s) => s.добавитьМодуль);

  const сл = поиск.trim().toLowerCase();
  const найдено = КАТАЛОГ.filter(
    (m) =>
      (!категория || m.категория === категория) &&
      (!сл || m.название.toLowerCase().includes(сл) || m.id.includes(сл)),
  );

  const группы = КАТЕГОРИИ.map((к) => ({ к, позиции: найдено.filter((m) => m.категория === к) })).filter(
    (г) => г.позиции.length,
  );

  return (
    <div>
      <input
        placeholder="Поиск: шкаф, холодильник, окно…"
        value={поиск}
        onChange={(e) => установитьПоиск(e.target.value)}
      />
      <div className="категории">
        <button className={!категория ? 'активна' : ''} onClick={() => установитьКатегорию(null)}>
          Всё
        </button>
        {КАТЕГОРИИ.map((к) => (
          <button key={к} className={категория === к ? 'активна' : ''} onClick={() => установитьКатегорию(к)}>
            {к}
          </button>
        ))}
      </div>

      {группы.length === 0 && <p style={{ color: 'var(--текст2)', fontSize: 13 }}>Ничего не найдено.</p>}

      {группы.map((г) => (
        <div key={г.к}>
          <div className="заголовок-группы">{г.к}</div>
          {г.позиции.map((м) => (
            <div className="позиция" key={м.id} onClick={() => добавитьМодуль(м.id)} title={м.заметка}>
              <div>
                <div className="имя">{м.название}</div>
                <div className="размер">
                  {м.габариты.ш} × {м.габариты.г} × {м.габариты.в} мм
                  {м.крепление === 'навесное' ? ' · навесной' : ''}
                </div>
              </div>
            </div>
          ))}
        </div>
      ))}
    </div>
  );
}

/* --------------------------- Числовое поле --------------------------- */

function Число({
  подпись,
  значение,
  наИзменение,
  шаг = 10,
}: {
  подпись: string;
  значение: number;
  наИзменение: (v: number) => void;
  шаг?: number;
}) {
  const [текст, установитьТекст] = useState(String(Math.round(значение)));
  useEffect(() => установитьТекст(String(Math.round(значение))), [значение]);

  const зафиксировать = () => {
    const ч = Number(текст.replace(',', '.'));
    if (Number.isFinite(ч)) наИзменение(Math.round(ч));
    else установитьТекст(String(Math.round(значение)));
  };

  return (
    <div className="поле">
      <label>{подпись}</label>
      <input
        type="number"
        step={шаг}
        value={текст}
        onChange={(e) => установитьТекст(e.target.value)}
        onBlur={зафиксировать}
        onKeyDown={(e) => {
          if (e.key === 'Enter') (e.target as HTMLInputElement).blur();
        }}
      />
    </div>
  );
}

/* ------------------------------ Свойства ----------------------------- */

function Свойства() {
  const проект = useКухня((s) => s.проект);
  const выбрано = useКухня((s) => s.выбрано);
  const обновитьОбъект = useКухня((s) => s.обновитьОбъект);
  const обновитьГабариты = useКухня((s) => s.обновитьГабариты);
  const сброситьРазмер = useКухня((s) => s.сброситьРазмер);
  const удалитьВыбранное = useКухня((s) => s.удалитьВыбранное);
  const копироватьВыбранное = useКухня((s) => s.копироватьВыбранное);
  const начатьИзменение = useКухня((s) => s.начатьИзменение);

  if (!выбрано.length)
    return (
      <p style={{ color: 'var(--текст2)', fontSize: 13, lineHeight: 1.6 }}>
        Ничего не выбрано. Нажми на модуль в комнате или добавь новый из «Конструктора».
        <br />
        <br />
        Shift+клик — выбрать несколько.
      </p>
    );

  if (выбрано.length > 1)
    return (
      <div>
        <div className="заголовок-группы">Выбрано объектов: {выбрано.length}</div>
        <button style={{ width: '100%', marginBottom: 8 }} onClick={копироватьВыбранное}>
          Дублировать
        </button>
        <button style={{ width: '100%' }} className="опасная" onClick={удалитьВыбранное}>
          Удалить выбранные
        </button>
      </div>
    );

  const о = проект.объекты.find((x) => x.id === выбрано[0]);
  if (!о) return null;

  const изменить = (патч: Partial<Obj>) => {
    начатьИзменение();
    обновитьОбъект(о.id, патч);
  };

  const навесной = (о.подъём ?? 0) > 0;

  return (
    <div>
      <div className="заголовок-группы">{о.название ?? о.модуль}</div>

      <div className="ряд">
        <Число
          подпись="Ширина, мм"
          значение={о.габариты.ш}
          наИзменение={(v) => {
            начатьИзменение();
            обновитьГабариты(о.id, { ш: v });
          }}
        />
        <Число
          подпись="Глубина, мм"
          значение={о.габариты.г}
          наИзменение={(v) => {
            начатьИзменение();
            обновитьГабариты(о.id, { г: v });
          }}
        />
      </div>
      <Число
        подпись="Высота, мм"
        значение={о.габариты.в}
        наИзменение={(v) => {
          начатьИзменение();
          обновитьГабариты(о.id, { в: v });
        }}
      />
      <button style={{ width: '100%', marginBottom: 12 }} onClick={() => сброситьРазмер(о.id)}>
        Вернуть стандартный размер
      </button>

      <div className="заголовок-группы">Положение</div>
      <div className="ряд">
        <Число подпись="X, мм" значение={о.позиция[0]} наИзменение={(v) => изменить({ позиция: [v, о.позиция[1], о.позиция[2]] })} />
        <Число подпись="Z, мм" значение={о.позиция[2]} наИзменение={(v) => изменить({ позиция: [о.позиция[0], о.позиция[1], v] })} />
      </div>
      <Число
        подпись={навесной ? 'Высота подвеса (низ), мм' : 'Высота над полом, мм'}
        значение={о.подъём && о.подъём > 0 ? о.подъём : о.позиция[1]}
        наИзменение={(v) => изменить({ подъём: v, позиция: [о.позиция[0], v, о.позиция[2]] })}
      />
      <div className="заголовок-группы">Поворот и наклон</div>
      <Число
        подпись="Поворот вокруг вертикали, °"
        шаг={15}
        значение={о.поворот}
        наИзменение={(v) => изменить({ поворот: ((v % 360) + 360) % 360 })}
      />
      <div className="ряд" style={{ marginBottom: 10 }}>
        <button onClick={() => изменить({ поворот: (о.поворот + 270) % 360 })}>⟲ 90° влево</button>
        <button onClick={() => изменить({ поворот: (о.поворот + 90) % 360 })}>90° вправо ⟳</button>
      </div>
      <div className="ряд">
        <Число
          подпись="Наклон вперёд-назад, °"
          шаг={15}
          значение={о.наклон_X ?? 0}
          наИзменение={(v) => изменить({ наклон_X: v })}
        />
        <Число
          подпись="Наклон влево-вправо, °"
          шаг={15}
          значение={о.наклон_Z ?? 0}
          наИзменение={(v) => изменить({ наклон_Z: v })}
        />
      </div>

      <div className="заголовок-группы">Дверцы</div>
      <div className="поле">
        <label>С какой стороны петли</label>
        <select
          value={о.петли ?? 'слева'}
          onChange={(e) => изменить({ петли: e.target.value as Obj['петли'] })}
        >
          <option value="слева">Слева — открывается вправо</option>
          <option value="справа">Справа — открывается влево</option>
          <option value="сверху">Сверху — открывается вверх</option>
          <option value="снизу">Снизу — открывается вниз</option>
        </select>
      </div>
      <button
        style={{ width: '100%', marginBottom: 12 }}
        className={о.открыт ? 'активна' : ''}
        onClick={() => изменить({ открыт: !о.открыт })}
      >
        {о.открыт ? 'Закрыть дверцы' : 'Открыть дверцы'}
      </button>

      <div className="заголовок-группы">Фасад и цвет</div>
      <div className="палитра" style={{ marginBottom: 12 }}>
        {ФАСАДЫ.map((ф) => (
          <button
            key={ф.id}
            title={ф.название}
            className={`цвет ${о.цвет === ф.цвет ? 'активна' : ''}`}
            style={{ background: ф.цвет }}
            onClick={() => {
              начатьИзменение();
              обновитьОбъект(о.id, { цвет: ф.цвет, материал: ф.название });
            }}
          />
        ))}
      </div>

      <div className="ряд">
        <Число подпись="Полок" шаг={1} значение={о.полок ?? 0} наИзменение={(v) => изменить({ полок: Math.max(0, v) })} />
        <Число подпись="Ящиков" шаг={1} значение={о.ящиков ?? 0} наИзменение={(v) => изменить({ ящиков: Math.max(0, v) })} />
      </div>
      <Число подпись="Цоколь, мм" значение={о.цоколь ?? 0} наИзменение={(v) => изменить({ цоколь: Math.max(0, v) })} />

      <div className="ряд" style={{ marginTop: 14 }}>
        <button onClick={копироватьВыбранное}>Дублировать</button>
        <button className="опасная" onClick={удалитьВыбранное}>
          Удалить
        </button>
      </div>
    </div>
  );
}

