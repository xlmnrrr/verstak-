/**
 * Мастер помещения: три способа — размеры цифрами, контур (прямоугольник, Г, П) и «квартира по сетке».
 * Плюс пять помещений заказчика одним кликом. Результат — проект v2, который открывается в редакторе.
 */
import { useMemo, useRef, useState } from 'react';
import { useКухня } from '../store';
import { ТИПЫ_ПОМЕЩЕНИЙ, type ТипПомещения, type ПроектV2 } from '../model/типы';
import { контурГ, контурП, новоеПомещение, прямоугольник, площадьМ2, границыКонтура } from '../model/помещение';
import { новыйПроектV2 } from '../model/проект';
import { квартираПоСетке, автоПроёмы } from '../model/квартира';
import { помещенияЗаказчика } from '../model/каталог/помещения-заказчика';
import { ОБОИ, ПОЛЫ } from '../data/materials';
import { Иконка } from './design/Иконки';

const ЗАГЛ = (с: string) => с.charAt(0).toUpperCase() + с.slice(1);
const ЦВЕТА_КЛЕТОК = ['#c9a45c', '#6f9bd1', '#8cc28a', '#d98a73', '#a98ad1', '#d1c06f', '#7fc4c0', '#c78fb0'];

function Число({ подпись, значение, наИзменение, мин, макс }: { подпись: string; значение: number; наИзменение: (v: number) => void; мин: number; макс: number }) {
  return (
    <div className="поле">
      <label>{подпись}</label>
      <input type="number" min={мин} max={макс} value={значение} onChange={(e) => наИзменение(Math.max(мин, Math.min(макс, Number(e.target.value) || мин)))} />
    </div>
  );
}

function собрать(название: string, контур: [number, number][], тип: ТипПомещения, высота: number, толщина: number, обои: string, пол: string): ПроектV2 {
  const пом = новоеПомещение('п1', тип, ЗАГЛ(тип), контур, высота);
  пом.толщина_стен = толщина;
  пом.отделка = { стены: обои, пол };
  return новыйПроектV2(название, пом);
}

/* ------------------------------------------------------------------ квартира по сетке */

interface Комната {
  н: number;
  тип: ТипПомещения;
}

function СеткаКвартиры({ создать }: { создать: (п: ПроектV2) => void }) {
  const [клетка, установитьКлетку] = useState(500);
  const [ш, установитьШ] = useState(10);
  const [в, установитьВ] = useState(7);
  const [клетки, установитьКлетки] = useState<number[][]>(() => Array.from({ length: 7 }, () => Array(10).fill(0)));
  const [комнаты, установитьКомнаты] = useState<Комната[]>([{ н: 1, тип: 'прихожая' }]);
  const [кисть, установитьКисть] = useState(1);
  const [ошибки, установитьОшибки] = useState<string[]>([]);
  const рисую = useRef(false);

  const изменитьРазмер = (нш: number, нв: number) => {
    установитьШ(нш);
    установитьВ(нв);
    установитьКлетки(Array.from({ length: нв }, (_, r) => Array.from({ length: нш }, (_, c) => клетки[r]?.[c] ?? 0)));
  };
  const покрасить = (r: number, c: number) => {
    установитьКлетки((к) => к.map((ряд, i) => (i === r ? ряд.map((v, j) => (j === c ? кисть : v)) : ряд)));
  };
  const добавить = (тип: ТипПомещения) => {
    const н = Math.max(0, ...комнаты.map((к) => к.н)) + 1;
    установитьКомнаты([...комнаты, { н, тип }]);
    установитьКисть(н);
  };
  const занято = клетки.flat().filter(Boolean).length;
  const цвет = (н: number) => (н ? ЦВЕТА_КЛЕТОК[(н - 1) % ЦВЕТА_КЛЕТОК.length] : 'transparent');

  const собратьПлан = () => {
    const использованные = [...new Set(клетки.flat().filter(Boolean))];
    const описание: Record<number, { тип: ТипПомещения }> = {};
    for (const к of комнаты) if (использованные.includes(к.н)) описание[к.н] = { тип: к.тип };
    const р = квартираПоСетке({ клетка, клетки, комнаты: описание, проёмы: автоПроёмы(клетки, клетка) });
    if (р.ошибки.length || !р.помещения.length) {
      установитьОшибки(р.ошибки.length ? р.ошибки : ['Закрасьте хотя бы одну клетку']);
      return;
    }
    установитьОшибки([]);
    const п = новыйПроектV2('Квартира', р.помещения[0]);
    п.помещения = р.помещения;
    п.связи = р.связи;
    создать(п);
  };

  return (
    <div className="мастер-сетка">
      <p className="подзаголовок">Выберите помещение и закрасьте клетки мышью. Из клеток соберётся план: общие стены и двери между соседними помещениями.</p>
      <div className="поля3">
        <div className="поле">
          <label>Клетка</label>
          <select value={клетка} onChange={(e) => установитьКлетку(Number(e.target.value))}>
            {[300, 500, 600, 1000].map((к) => (
              <option key={к} value={к}>
                {к} мм
              </option>
            ))}
          </select>
        </div>
        <Число подпись="Клеток по ширине" значение={ш} наИзменение={(v) => изменитьРазмер(v, в)} мин={3} макс={24} />
        <Число подпись="Клеток по глубине" значение={в} наИзменение={(v) => изменитьРазмер(ш, v)} мин={3} макс={18} />
      </div>
      <div className="кисти" role="group" aria-label="Помещения">
        {комнаты.map((к) => (
          <button key={к.н} type="button" className="чип" aria-pressed={кисть === к.н} onClick={() => установитьКисть(к.н)}>
            <i className="кубик" style={{ background: цвет(к.н) }} />
            {ЗАГЛ(к.тип)} {к.н}
          </button>
        ))}
        <button type="button" className="чип" aria-pressed={кисть === 0} onClick={() => установитьКисть(0)}>
          Стереть
        </button>
      </div>
      <div className="кисти" role="group" aria-label="Добавить помещение">
        {(['прихожая', 'гостиная', 'кухня', 'ванная', 'санузел', 'спальня'] as ТипПомещения[]).map((т) => (
          <button key={т} type="button" className="кн" onClick={() => добавить(т)}>
            <Иконка имя="плюс" размер={16} />
            {ЗАГЛ(т)}
          </button>
        ))}
      </div>
      <div className="сетка-клеток" style={{ gridTemplateColumns: `repeat(${ш}, 1fr)` }} onPointerLeave={() => (рисую.current = false)} onPointerUp={() => (рисую.current = false)}>
        {клетки.map((ряд, r) =>
          ряд.map((н, c) => (
            <button
              key={`${r}-${c}`}
              type="button"
              className="клетка"
              aria-label={`Клетка ${r + 1}:${c + 1}`}
              style={{ background: цвет(н) }}
              onPointerDown={() => {
                рисую.current = true;
                покрасить(r, c);
              }}
              onPointerEnter={() => рисую.current && покрасить(r, c)}
              onKeyDown={(e) => (e.key === 'Enter' || e.key === ' ') && покрасить(r, c)}
            />
          )),
        )}
      </div>
      {ошибки.length > 0 && (
        <div className="блок-ошибка" role="alert">
          <span>
            <b>План не собрался.</b> {ошибки.join(' ')}
          </span>
        </div>
      )}
      <div className="низ-мастера">
        <span className="плашка">
          Закрашено клеток: <b>{занято}</b> ({((занято * клетка * клетка) / 1e6).toFixed(1)} м²)
        </span>
        <button className="кн главная" type="button" disabled={!занято} onClick={собратьПлан}>
          Собрать квартиру
        </button>
      </div>
    </div>
  );
}

/* ------------------------------------------------------------------ мастер */

export function Мастер() {
  const загрузить = useКухня((с) => с.загрузить);
  const наЭкран = useКухня((с) => с.наЭкран);
  const [способ, установитьСпособ] = useState<'размеры' | 'контур' | 'сетка'>('размеры');
  const [название, установитьНазвание] = useState('Моя кухня');
  const [тип, установитьТип] = useState<ТипПомещения>('кухня');
  const [ш, установитьШ] = useState(3600);
  const [г, установитьГ] = useState(2800);
  const [в, установитьВ] = useState(2700);
  const [т, установитьТ] = useState(100);
  const [форма, установитьФорму] = useState<'прямоугольник' | 'Г' | 'П'>('Г');
  const [вырезШ, установитьВырезШ] = useState(1500);
  const [вырезГ, установитьВырезГ] = useState(1200);
  const [обои, установитьОбои] = useState(ОБОИ[0].цвет);
  const [пол, установитьПол] = useState(ПОЛЫ[0].цвет);

  const контур = useMemo(() => {
    if (способ === 'размеры' || форма === 'прямоугольник') return прямоугольник(ш, г);
    const вШ = Math.min(вырезШ, ш - 600);
    const вГ = Math.min(вырезГ, г - 600);
    return форма === 'Г' ? контурГ(ш, г, вШ, вГ) : контурП(ш, г, вШ, вГ);
  }, [способ, форма, ш, г, вырезШ, вырезГ]);

  const создать = () => загрузить(собрать(название.trim() || 'Новый проект', контур, тип, в, т, обои, пол));
  const границы = границыКонтура(контур);
  const мини = 160 / Math.max(границы.ш, границы.г);

  return (
    <div className="экран-прокрутка">
      <div className="мастер">
        <div className="мастер-шапка">
          <h2>Новое помещение</h2>
          <button className="кн тихая" type="button" onClick={() => наЭкран('меню')}>
            На обложку
          </button>
        </div>

        <section className="группа">
          <h3>Помещения заказчика — одним кликом</h3>
          <div className="кисти">
            {помещенияЗаказчика().map((п) => (
              <button key={п.id} type="button" className="чип" title={`${п.название}: ${площадьМ2(п.контур).toFixed(1)} м²`} onClick={() => загрузить(новыйПроектV2(п.название, п))}>
                {п.название}
              </button>
            ))}
          </div>
        </section>

        <div className="сегменты" role="tablist" aria-label="Способ задать помещение">
          {(
            [
              ['размеры', 'Размеры'],
              ['контур', 'Контур Г и П'],
              ['сетка', 'Квартира по сетке'],
            ] as const
          ).map(([ид, имя]) => (
            <button key={ид} type="button" role="tab" aria-pressed={способ === ид} aria-selected={способ === ид} onClick={() => установитьСпособ(ид)}>
              {имя}
            </button>
          ))}
        </div>

        {способ === 'сетка' ? (
          <СеткаКвартиры создать={загрузить} />
        ) : (
          <div className="мастер-форма">
            <div className="поля2">
              <div className="поле">
                <label>Название проекта</label>
                <input value={название} onChange={(e) => установитьНазвание(e.target.value)} />
              </div>
              <div className="поле">
                <label>Тип помещения</label>
                <select value={тип} onChange={(e) => установитьТип(e.target.value as ТипПомещения)}>
                  {ТИПЫ_ПОМЕЩЕНИЙ.map((x) => (
                    <option key={x} value={x}>
                      {ЗАГЛ(x)}
                    </option>
                  ))}
                </select>
              </div>
            </div>
            {способ === 'контур' && (
              <div className="сегменты" role="group" aria-label="Форма">
                {(['прямоугольник', 'Г', 'П'] as const).map((ф) => (
                  <button key={ф} type="button" aria-pressed={форма === ф} onClick={() => установитьФорму(ф)}>
                    {ф === 'прямоугольник' ? 'Прямоугольник' : `${ф}-образная`}
                  </button>
                ))}
              </div>
            )}
            <div className="поля2">
              <Число подпись="Длина, мм" значение={ш} наИзменение={установитьШ} мин={1000} макс={20000} />
              <Число подпись="Ширина, мм" значение={г} наИзменение={установитьГ} мин={1000} макс={20000} />
              {способ === 'контур' && форма !== 'прямоугольник' && (
                <>
                  <Число подпись="Вырез: ширина, мм" значение={вырезШ} наИзменение={установитьВырезШ} мин={300} макс={15000} />
                  <Число подпись="Вырез: глубина, мм" значение={вырезГ} наИзменение={установитьВырезГ} мин={300} макс={15000} />
                </>
              )}
              <Число подпись="Высота стен, мм" значение={в} наИзменение={установитьВ} мин={1500} макс={6000} />
              <Число подпись="Толщина стен, мм" значение={т} наИзменение={установитьТ} мин={0} макс={600} />
            </div>
            <div className="мастер-два">
              <div>
                <h3 className="мелкий">Обои</h3>
                <div className="палитра">
                  {ОБОИ.slice(0, 8).map((о) => (
                    <button key={о.id} type="button" title={о.название} aria-label={о.название} className={`цвет ${обои === о.цвет ? 'активна' : ''}`} style={{ background: о.цвет }} onClick={() => установитьОбои(о.цвет)} />
                  ))}
                </div>
                <h3 className="мелкий">Пол</h3>
                <div className="палитра">
                  {ПОЛЫ.slice(0, 8).map((о) => (
                    <button key={о.id} type="button" title={о.название} aria-label={о.название} className={`цвет ${пол === о.цвет ? 'активна' : ''}`} style={{ background: о.цвет }} onClick={() => установитьПол(о.цвет)} />
                  ))}
                </div>
              </div>
              <svg className="контур-мини" viewBox="-12 -12 184 184" aria-label="Контур помещения">
                <polygon points={контур.map(([x, z]) => `${(x - границы.x0) * мини},${(z - границы.z0) * мини}`).join(' ')} fill="none" stroke="var(--латунь)" strokeWidth="3" strokeLinejoin="round" />
              </svg>
            </div>
            <div className="низ-мастера">
              <span className="плашка">
                Площадь: <b>{площадьМ2(контур).toFixed(1)}</b> м²
              </span>
              <button className="кн главная" type="button" onClick={создать}>
                Создать и открыть
              </button>
            </div>
          </div>
        )}
      </div>
    </div>
  );
}
