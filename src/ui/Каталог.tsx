/**
 * Каталог (выезжает по P): поиск по названию и габаритам («шкаф 600»), категории, фильтр по помещению,
 * недавние и избранное, карточка изделия с габаритами.
 */
import { useMemo, useState } from 'react';
import { useКухня } from '../store';
import { useUI } from '../store/интерфейс';
import { КАТАЛОГ_V2, КАТЕГОРИИ_V2 } from '../model/каталог';
import type { Изделие, ТипПомещения } from '../model/типы';
import { Иконка, type ИмяИконки } from './design/Иконки';
import { ПодсказкаИзделия, ПревьюИзделия } from './Превью';

const ПОМЕЩЕНИЯ_ФИЛЬТР: ТипПомещения[] = ['кухня', 'спальня', 'гостиная', 'прихожая', 'гардеробная', 'ванная'];

export function значокИзделия(и: Изделие): ИмяИконки {
  if (и.крепление === 'стена') return 'полка';
  if (и.раскладка.фасад.тип === 'ящики') return 'ящик';
  if (и.раскладка.фасад.тип === 'купе') return 'купе';
  if (и.раскладка.фасад.тип === 'подъёмник') return 'подъёмник';
  if (и.тип === 'проём') return 'ниша';
  if (и.тип === 'техника') return 'слои';
  if (и.раскладка.секции.some((с) => с.наполнение.штанга)) return 'штанга';
  return 'каталог';
}

/** Поиск: каждое слово — в названии/категории; число — совпадает с началом любого из габаритов */
export function подходит(и: Изделие, запрос: string): boolean {
  const слова = запрос.trim().toLowerCase().split(/\s+/).filter(Boolean);
  const текст = `${и.название} ${и.категория}`.toLowerCase();
  return слова.every((с) => (/^\d+$/.test(с) ? [и.габариты.ш, и.габариты.г, и.габариты.в].some((v) => String(v).startsWith(с)) : текст.includes(с)));
}

function Карточка({
  и,
  звезда,
  переключить,
  добавить,
  наведение,
}: {
  и: Изделие;
  звезда: boolean;
  переключить: () => void;
  добавить: () => void;
  наведение: (к: { и: Изделие; x: number; y: number } | null) => void;
}) {
  const показать = (e: { currentTarget: HTMLElement }) => {
    const r = e.currentTarget.getBoundingClientRect();
    наведение({ и, x: r.right + 8, y: r.top - 24 });
  };
  return (
    <div className="позиция-ряд">
      <button
        className="позиция"
        type="button"
        onClick={добавить}
        onMouseEnter={показать}
        onMouseLeave={() => наведение(null)}
        onFocus={показать}
        onBlur={() => наведение(null)}
        aria-label={`${и.название}, ${и.габариты.ш} на ${и.габариты.г} на ${и.габариты.в} миллиметров`}
      >
        <ПревьюИзделия id={и.id} размер={44} запас={<Иконка имя={значокИзделия(и)} размер={20} />} />
        <span>
          <span className="имя">{и.название}</span>
          <br />
          <span className="размер">
            {и.габариты.ш} × {и.габариты.г} × {и.габариты.в} мм{и.крепление === 'стена' ? ' · навесной' : ''}
          </span>
        </span>
      </button>
      <button className="кн-и малая звезда" type="button" aria-pressed={звезда} aria-label={звезда ? 'Убрать из избранного' : 'В избранное'} title={звезда ? 'Убрать из избранного' : 'В избранное'} onClick={переключить}>
        <Иконка имя="звезда" размер={18} />
      </button>
    </div>
  );
}

export function Каталог() {
  const открыт = useКухня((s) => s.каталогОткрыт);
  const закрыть = useКухня((s) => s.переключитьКаталог);
  const поиск = useКухня((s) => s.поиск);
  const установитьПоиск = useКухня((s) => s.установитьПоиск);
  const категория = useКухня((s) => s.категория);
  const установитьКатегорию = useКухня((s) => s.установитьКатегорию);
  const добавитьМодуль = useКухня((s) => s.добавитьМодуль);
  const тип = useКухня((s) => s.проект2.помещения.find((п) => п.id === s.помещениеАктивное)?.тип);
  const { недавние, избранное, комнатаКат } = useUI();
  const ui = useUI();
  const [толькоИзбранное, установитьТолькоИзбранное] = useState(false);
  const [подсказка, установитьПодсказку] = useState<{ и: Изделие; x: number; y: number } | null>(null);

  const найдено = useMemo(
    () => КАТАЛОГ_V2.filter((и) => (!категория || и.категория === категория) && (!комнатаКат || и.помещения.includes(комнатаКат as ТипПомещения)) && (!толькоИзбранное || избранное.includes(и.id)) && подходит(и, поиск)),
    [категория, комнатаКат, поиск, избранное, толькоИзбранное],
  );
  const группы = useMemo(() => КАТЕГОРИИ_V2.map((к) => ({ к, поз: найдено.filter((и) => и.категория === к) })).filter((г) => г.поз.length), [найдено]);
  const недавниеИзделия = недавние.map((id) => КАТАЛОГ_V2.find((и) => и.id === id)).filter((и): и is Изделие => !!и);

  const добавить = (и: Изделие) => {
    добавитьМодуль(и.id);
    ui.добавитьНедавнее(и.id);
  };
  const ряд = (и: Изделие) => <Карточка key={и.id} и={и} звезда={избранное.includes(и.id)} переключить={() => ui.переключитьИзбранное(и.id)} добавить={() => добавить(и)} наведение={установитьПодсказку} />;

  return (
    <aside className={`выезд слева${открыт ? ' открыта' : ''}`} aria-label="Каталог изделий" aria-hidden={!открыт}>
      <div className="выезд-шапка">
        <div>
          <b>Каталог</b>
          <span>
            Найдено: {найдено.length}
            {тип ? ` · помещение: ${тип}` : ''}
          </span>
        </div>
        <button className="кн-и малая" type="button" title="Закрыть (P)" aria-label="Закрыть каталог" onClick={() => закрыть(false)}>
          <Иконка имя="закрыть" />
        </button>
      </div>
      <div className="каталог-поиск">
        <Иконка имя="поиск" />
        <input placeholder="Шкаф 600, тумба, окно…" value={поиск} onChange={(e) => установитьПоиск(e.target.value)} aria-label="Поиск по названию и размерам" />
      </div>
      <div className="чипы" role="group" aria-label="Помещение">
        <button className="чип" type="button" aria-pressed={!комнатаКат} onClick={() => ui.установить({ комнатаКат: null })}>
          Все помещения
        </button>
        {ПОМЕЩЕНИЯ_ФИЛЬТР.map((п) => (
          <button key={п} className="чип" type="button" aria-pressed={комнатаКат === п} onClick={() => ui.установить({ комнатаКат: комнатаКат === п ? null : п })}>
            {п[0].toUpperCase() + п.slice(1)}
          </button>
        ))}
        <button className="чип" type="button" aria-pressed={толькоИзбранное} onClick={() => установитьТолькоИзбранное(!толькоИзбранное)}>
          Избранное
        </button>
      </div>
      <div className="чипы" role="group" aria-label="Категория">
        <button className="чип" type="button" aria-pressed={!категория} onClick={() => установитьКатегорию(null)}>
          Все категории
        </button>
        {КАТЕГОРИИ_V2.map((к) => (
          <button key={к} className="чип" type="button" aria-pressed={категория === к} onClick={() => установитьКатегорию(категория === к ? null : к)}>
            {к}
          </button>
        ))}
      </div>
      <div className="выезд-тело">
        {недавниеИзделия.length > 0 && !поиск && !категория && (
          <div>
            <div className="заголовок-группы">Недавние</div>
            {недавниеИзделия.slice(0, 4).map(ряд)}
          </div>
        )}
        {группы.length === 0 && <p className="пусто-панель">Ничего не нашлось. Попробуйте «тумба 600», «шкаф» или «окно».</p>}
        {группы.map((г) => (
          <div key={г.к}>
            <div className="заголовок-группы">{г.к}</div>
            {г.поз.map(ряд)}
          </div>
        ))}
      </div>
      {подсказка && открыт && <ПодсказкаИзделия и={подсказка.и} x={подсказка.x} y={подсказка.y} />}
    </aside>
  );
}
