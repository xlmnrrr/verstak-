/**
 * Окно «Идеи от Claude»: готовые продуманные интерьеры (model/идеи.ts) — открываются как обычные проекты и правятся руками.
 * Для своей комнаты идею можно заказать у Claude в чате: он соберёт файл .kitchen по тем же приёмам.
 */
import { useКухня } from '../store';
import { useUI } from '../store/интерфейс';
import { ИДЕИ, проектИдеи } from '../model/идеи';
import { Иконка } from './design/Иконки';

export function Идеи({ закрыть }: { закрыть: () => void }) {
  const загрузить = useКухня((s) => s.загрузить);
  return (
    <div className="идеи">
      <p className="подсказка">
        Готовые интерьеры с продуманной расстановкой: открываются как обычный проект, дальше можно двигать, менять размеры и цвета. Нужна идея под вашу
        комнату — напишите Claude размеры и пожелания: он соберёт файл, который откроется здесь же («Открыть файл»).
      </p>
      <div className="идеи-список">
        {ИДЕИ.map((и) => (
          <article key={и.id} className="идея">
            <h4>{и.название}</h4>
            <p>{и.кратко}</p>
            <ul>
              {и.приёмы.map((п) => (
                <li key={п}>{п}</li>
              ))}
            </ul>
            <button
              type="button"
              className="кн главная"
              onClick={() => {
                загрузить(проектИдеи(и));
                useUI.getState().открытьОкно(null);
                закрыть();
              }}
            >
              <Иконка имя="пример" размер={16} />
              Открыть идею
            </button>
          </article>
        ))}
      </div>
    </div>
  );
}
