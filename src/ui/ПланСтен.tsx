/**
 * План стен в окне «Помещение» (пожелание Макара 13.11.2026, «как в Симс»): тянуть угол, тянуть стену, вырезать угол,
 * сделать выступ или нишу, поставить точку на стене, удалить угол. Пока тянешь — предпросмотр; отпустил — одна запись
 * истории (Ctrl+Z). Прилипание 10 мм и к линиям соседних углов. Длины стен — в выбранных единицах (мм / см / м),
 * площадь пола, периметр и стены без проёмов — под планом.
 */
import { useRef, useState } from 'react';
import { useКухня } from '../store';
import { useUI } from '../store/интерфейс';
import { стены as стеныКонтура, границыКонтура, type Точка } from '../model/помещение';
import { выступ, обмерПомещения, передвинутьУгол, сдвинутьСтену, точкаНаСтене, удалитьУгол, type ИтогПравки } from '../model/контур-правка';
import { длина, площадьМ2 } from '../model/единицы';
import type { Помещение } from '../model/типы';

type Тяга = { вид: 'угол'; k: number; старт: Точка } | { вид: 'стена'; i: number; старт: Точка };

const ШАГ = 10;
const кШагу = (v: number) => Math.round(v / ШАГ) * ШАГ;

export function ПланСтен() {
  const пом = useКухня((s) => s.проект2.помещения.find((п) => п.id === s.помещениеАктивное));
  const править = useКухня((s) => s.правитьПомещение);
  const сообщить = useКухня((s) => s.сообщить);
  const е = useUI((s) => s.единицы);
  const svg = useRef<SVGSVGElement>(null);
  const [тяга, задатьТягу] = useState<Тяга | null>(null);
  const [черновик, задатьЧерновик] = useState<Помещение | null>(null);
  const [стена, задатьСтену] = useState(0);
  const [угол, задатьУгол] = useState<number | null>(null);
  const [форма, задатьФорму] = useState({ от: 0, ширина: 600, глубина: 400 });
  if (!пом) return null;
  const вид = черновик ?? пом;
  const к = вид.контур;
  const ст = стеныКонтура(к);
  const г = границыКонтура(пом.контур);
  const поле = Math.max(г.ш, г.г) * 0.12 + 200;
  const шрифт = Math.max(г.ш, г.г) / 17;
  const выбрана = Math.min(стена, ст.length - 1);

  /** Точка мыши в мм осей помещения */
  const вМм = (e: React.PointerEvent): Точка => {
    const м = svg.current!.getScreenCTM()!.inverse();
    const p = new DOMPoint(e.clientX, e.clientY).matrixTransform(м);
    return [p.x, p.y];
  };
  const применить = (р: ИтогПравки, что: string) => {
    if (р.ошибка) сообщить(р.ошибка, 'ошибка');
    else править(пом.id, () => р.помещение, что);
  };
  const начать = (t: Тяга, e: React.PointerEvent) => {
    e.stopPropagation();
    (e.target as Element).setPointerCapture(e.pointerId);
    задатьТягу(t);
  };
  const двигать = (e: React.PointerEvent) => {
    if (!тяга) return;
    const p = вМм(e);
    if (тяга.вид === 'угол') {
      let [x, z] = [кШагу(p[0]), кШагу(p[1])];
      // прилипание к линиям соседних углов (прямые углы получаются сами)
      const n = пом.контур.length;
      for (const j of [(тяга.k + n - 1) % n, (тяга.k + 1) % n]) {
        const q = пом.контур[j];
        if (Math.abs(x - q[0]) < 60) x = q[0];
        if (Math.abs(z - q[1]) < 60) z = q[1];
      }
      // недопустимое положение не показываем: держится последнее правильное
      const р = передвинутьУгол(пом, тяга.k, x, z);
      if (!р.ошибка) задатьЧерновик(р.помещение);
    } else {
      const w = стеныКонтура(пом.контур)[тяга.i];
      const Δ = кШагу((p[0] - тяга.старт[0]) * w.нормаль[0] + (p[1] - тяга.старт[1]) * w.нормаль[1]);
      const р = сдвинутьСтену(пом, тяга.i, Δ);
      if (!р.ошибка) задатьЧерновик(р.помещение);
    }
  };
  const закончить = () => {
    if (тяга && черновик && черновик !== пом) {
      // проверка и запись: тот же расчёт ещё раз — с текстом ошибки, если отпустили в недопустимом месте
      править(пом.id, () => черновик, тяга.вид === 'угол' ? 'Передвинуть угол' : 'Сдвинуть стену');
    }
    задатьТягу(null);
    задатьЧерновик(null);
  };
  const о = обмерПомещения(вид);

  return (
    <div className="план-стен">
      <svg
        ref={svg}
        viewBox={`${г.x0 - поле} ${г.z0 - поле} ${г.ш + 2 * поле} ${г.г + 2 * поле}`}
        preserveAspectRatio="xMidYMid meet"
        onPointerMove={двигать}
        onPointerUp={закончить}
        onPointerCancel={закончить}
        aria-label="План стен: тяните угол или стену"
        role="img"
      >
        <polygon className="план-пол" points={к.map((p) => p.join(',')).join(' ')} />
        {ст.map((w) => {
          const b: Точка = [w.а[0] + w.направление[0] * w.длина, w.а[1] + w.направление[1] * w.длина];
          const ц: Точка = [(w.а[0] + b[0]) / 2 - w.нормаль[0] * шрифт * 1.2, (w.а[1] + b[1]) / 2 - w.нормаль[1] * шрифт * 1.2];
          return (
            <g key={w.индекс}>
              <line
                className={`план-стена${w.индекс === выбрана ? ' выбрана' : ''}`}
                x1={w.а[0]}
                y1={w.а[1]}
                x2={b[0]}
                y2={b[1]}
                strokeWidth={шрифт * 0.55}
                onPointerDown={(e) => {
                  задатьСтену(w.индекс);
                  задатьУгол(null);
                  начать({ вид: 'стена', i: w.индекс, старт: вМм(e) }, e);
                }}
                data-стена={w.индекс}
              />
              <text x={ц[0]} y={ц[1]} fontSize={шрифт} textAnchor="middle" dominantBaseline="middle" className="план-размер">
                {длина(w.длина, е)}
              </text>
            </g>
          );
        })}
        {к.map((p, k) => (
          <circle
            key={k}
            className={`план-угол${угол === k ? ' выбран' : ''}`}
            cx={p[0]}
            cy={p[1]}
            r={шрифт * 0.55}
            onPointerDown={(e) => {
              задатьУгол(k);
              начать({ вид: 'угол', k, старт: вМм(e) }, e);
            }}
            data-угол={k}
          />
        ))}
      </svg>
      <p className="подсказка-мелко">
        Тяните угол — он двигается с шагом 10 мм и прилипает к соседним; тяните стену — она сдвигается параллельно. Ctrl+Z отменяет.
      </p>
      <p className="обмер">
        Пол <b>{площадьМ2(о.полМ2)}</b> · периметр <b>{длина(о.периметрМ * 1000, 'м')}</b> · стены <b>{площадьМ2(о.стеныМ2)}</b> без проёмов · высота <b>{длина(о.высотаМ * 1000, е)}</b>
      </p>
      <div className="поля3">
        <label className="поле">
          <span>Стена</span>
          <select value={выбрана} onChange={(e) => задатьСтену(Number(e.target.value))} aria-label="Стена для выступа">
            {ст.map((w) => (
              <option key={w.индекс} value={w.индекс}>
                {w.индекс + 1} · {длина(w.длина, е)}
              </option>
            ))}
          </select>
        </label>
        <ЧислоМм подпись="От угла, мм" значение={форма.от} задать={(v) => задатьФорму({ ...форма, от: v })} />
        <ЧислоМм подпись="Ширина, мм" значение={форма.ширина} задать={(v) => задатьФорму({ ...форма, ширина: v })} />
        <ЧислоМм подпись="Глубина, мм (− наружу)" значение={форма.глубина} задать={(v) => задатьФорму({ ...форма, глубина: v })} />
      </div>
      <div className="ряд-кнопок">
        <button className="кн" type="button" onClick={() => применить(выступ(пом, выбрана, форма.от, форма.ширина, форма.глубина), форма.глубина >= 0 ? 'Выступ' : 'Ниша')} data-действие="выступ">
          {форма.глубина >= 0 ? 'Сделать выступ' : 'Сделать нишу'}
        </button>
        <button className="кн" type="button" onClick={() => применить(выступ(пом, выбрана, 0, форма.ширина, Math.abs(форма.глубина)), 'Вырезать угол')} data-действие="вырезать-угол" title="Угол в начале выбранной стены уходит внутрь на ширину × глубину">
          Вырезать угол
        </button>
        <button className="кн" type="button" onClick={() => применить(точкаНаСтене(пом, выбрана, (ст[выбрана]?.длина ?? 0) / 2), 'Точка на стене')} title="Новая точка посередине стены — её можно тянуть">
          Точка на стене
        </button>
        <button className="кн опасная" type="button" disabled={угол === null || к.length <= 3} onClick={() => угол !== null && (применить(удалитьУгол(пом, угол), 'Удалить угол'), задатьУгол(null))}>
          Удалить угол
        </button>
      </div>
    </div>
  );
}

function ЧислоМм({ подпись, значение, задать }: { подпись: string; значение: number; задать: (v: number) => void }) {
  return (
    <label className="поле">
      <span>{подпись}</span>
      <input type="number" step={10} value={значение} onChange={(e) => задать(Number(e.target.value) || 0)} />
    </label>
  );
}
