/**
 * История изменений: стек команд с «жестами».
 * Жест — это перетаскивание, растягивание или поворот мышью: много мелких команд одного объекта
 * склеиваются в одну запись, и Ctrl+Z откатывает жест целиком.
 *
 * Протокол старого интерфейса сохранён: начатьИзменение() = граница(). Команда после границы открывает
 * запись, следующие команды с тем же ключом сливаются в неё до новой границы. Команда без границы —
 * отдельная запись, поэтому отмена работает всегда, в том числе после правки цифрой.
 */
import type { ПроектV2 } from '../model/типы';
import { склеить, type Команда } from './команды';

export const ПРЕДЕЛ_ИСТОРИИ = 500;

export type РежимЖеста = 'нет' | 'ждём' | 'идёт';

export interface История {
  прошлое: Команда[];
  будущее: Команда[];
  жест: РежимЖеста;
}

export const пустаяИстория = (): История => ({ прошлое: [], будущее: [], жест: 'нет' });

/** Начало нового жеста: следующая команда откроет новую запись */
export const граница = (и: История): История => ({ ...и, жест: 'ждём' });

export function выполнить(п: ПроектV2, и: История, к: Команда): { проект: ПроектV2; история: История } {
  const новый = к.применить(п);
  const последняя = и.прошлое[и.прошлое.length - 1];

  if (и.жест === 'идёт' && последняя && к.ключ && последняя.ключ === к.ключ) {
    const прошлое = [...и.прошлое.slice(0, -1), склеить(последняя, к)];
    return { проект: новый, история: { прошлое, будущее: [], жест: 'идёт' } };
  }
  const прошлое = [...и.прошлое, к].slice(-ПРЕДЕЛ_ИСТОРИИ);
  return {
    проект: новый,
    история: { прошлое, будущее: [], жест: и.жест === 'ждём' || и.жест === 'идёт' ? 'идёт' : 'нет' },
  };
}

export function отменить(п: ПроектV2, и: История): { проект: ПроектV2; история: История } | null {
  const к = и.прошлое[и.прошлое.length - 1];
  if (!к) return null;
  return {
    проект: к.отменить(п),
    история: { прошлое: и.прошлое.slice(0, -1), будущее: [к, ...и.будущее].slice(0, ПРЕДЕЛ_ИСТОРИИ), жест: 'нет' },
  };
}

export function вернуть(п: ПроектV2, и: История): { проект: ПроектV2; история: История } | null {
  const к = и.будущее[0];
  if (!к) return null;
  return {
    проект: к.применить(п),
    история: { прошлое: [...и.прошлое, к], будущее: и.будущее.slice(1), жест: 'нет' },
  };
}
