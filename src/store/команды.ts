/**
 * Команды: все изменения проекта проходят через них. Команда умеет применить себя и отменить.
 * Чистые функции над ПроектV2, без zustand и three — поэтому под тестами.
 */
import type { Настройки, Помещение, ПроектV2, Экземпляр } from '../model/типы';

export interface Команда {
  /** что сделано — для подписи «Отменить: …» */
  название: string;
  /** одинаковый ключ в одном жесте склеивает команды в одну запись истории */
  ключ?: string;
  применить(п: ПроектV2): ПроектV2;
  отменить(п: ПроектV2): ПроектV2;
}

/** Склеить две подряд идущие команды в одну запись: применить a затем b; отменить b затем a */
export function склеить(a: Команда, b: Команда): Команда {
  return {
    название: a.название,
    ключ: a.ключ,
    применить: (п) => b.применить(a.применить(п)),
    отменить: (п) => a.отменить(b.отменить(п)),
  };
}

const заменитьОбъект = (п: ПроектV2, id: string, н: Экземпляр): ПроектV2 => ({
  ...п,
  объекты: п.объекты.map((о) => (о.id === id ? н : о)),
});

export function добавитьОбъекты(экз: Экземпляр[], название = 'Добавить'): Команда {
  const ids = new Set(экз.map((э) => э.id));
  return {
    название,
    применить: (п) => ({ ...п, объекты: [...п.объекты, ...экз] }),
    отменить: (п) => ({ ...п, объекты: п.объекты.filter((о) => !ids.has(о.id)) }),
  };
}

export function удалитьОбъекты(ids: string[], название = 'Удалить'): Команда {
  const набор = new Set(ids);
  let удалённые: { экз: Экземпляр; индекс: number }[] = [];
  return {
    название,
    применить: (п) => {
      удалённые = п.объекты.map((экз, индекс) => ({ экз, индекс })).filter((x) => набор.has(x.экз.id));
      return { ...п, объекты: п.объекты.filter((о) => !набор.has(о.id)) };
    },
    отменить: (п) => {
      const список = [...п.объекты];
      for (const { экз, индекс } of удалённые) список.splice(Math.min(индекс, список.length), 0, экз);
      return { ...п, объекты: список };
    },
  };
}

/** Изменить один объект. `изменение` получает текущий экземпляр и возвращает новый. */
export function изменитьОбъект(
  id: string,
  изменение: (э: Экземпляр) => Экземпляр,
  название = 'Изменить',
  ключ?: string,
): Команда {
  let было: Экземпляр | undefined;
  return {
    название,
    ключ: ключ ?? `объект:${id}`,
    применить: (п) => {
      const текущий = п.объекты.find((о) => о.id === id);
      if (!текущий) return п;
      было = текущий;
      return заменитьОбъект(п, id, изменение(текущий));
    },
    отменить: (п) => (было ? заменитьОбъект(п, id, было) : п),
  };
}

export function изменитьПомещение(
  id: string,
  изменение: (п: Помещение) => Помещение,
  название = 'Изменить помещение',
  ключ?: string,
): Команда {
  let было: Помещение | undefined;
  const заменить = (п: ПроектV2, н: Помещение): ПроектV2 => ({ ...п, помещения: п.помещения.map((x) => (x.id === id ? н : x)) });
  return {
    название,
    ключ: ключ ?? `помещение:${id}`,
    применить: (п) => {
      const текущее = п.помещения.find((x) => x.id === id);
      if (!текущее) return п;
      было = текущее;
      return заменить(п, изменение(текущее));
    },
    отменить: (п) => (было ? заменить(п, было) : п),
  };
}

export function переименоватьПроект(имя: string): Команда {
  let было = '';
  return {
    название: 'Переименовать проект',
    ключ: 'название',
    применить: (п) => {
      было = п.название;
      return { ...п, название: имя };
    },
    отменить: (п) => ({ ...п, название: было }),
  };
}

export function изменитьНастройки(патч: Partial<Настройки>, название = 'Изменить настройки'): Команда {
  let было: Настройки | undefined;
  return {
    название,
    ключ: 'настройки',
    применить: (п) => {
      было = п.настройки;
      return { ...п, настройки: { ...п.настройки, ...патч } };
    },
    отменить: (п) => (было ? { ...п, настройки: было } : п),
  };
}
