/**
 * Автосохранение раз в 60 секунд, только если есть несохранённые правки.
 * Пишется в отдельный файл Проекты\.автосохранение\<имя>.kitchen (основной файл не трогается).
 * При запуске находим автосохранения новее основного файла и предлагаем восстановить.
 */
import { записатьАвтосохранение, интервалАвтосохранения } from '../lib/storage';
import { useКухня } from './index';

let таймер: ReturnType<typeof setInterval> | null = null;

/** Один тик: записать, если экран редактора и есть несохранённые правки */
export async function тикАвтосохранения(): Promise<boolean> {
  const с = useКухня.getState();
  if (с.экран !== 'редактор' || !с.изменено) return false;
  const р = await записатьАвтосохранение(с.проект2);
  if (р.ок) useКухня.setState({ автосохранено: new Date().toISOString() });
  return р.ок;
}

/** Запустить таймер. Возвращает функцию остановки. */
export function запуститьАвтосохранение(): () => void {
  let остановлено = false;
  void интервалАвтосохранения().then((сек) => {
    if (остановлено) return;
    таймер = setInterval(() => void тикАвтосохранения(), сек * 1000);
  });
  return () => {
    остановлено = true;
    if (таймер) clearInterval(таймер);
    таймер = null;
  };
}
