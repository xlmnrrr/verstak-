/**
 * Состояние интерфейса, которое помнится между запусками (localStorage): первый запуск, свёрнутые свойства,
 * недавние и избранные изделия и материалы, открытый каталог, последняя вкладка помещения, автозапуск.
 * Тема хранится в основном хранилище (`тема`), фон сцены — в настройках проекта.
 */
import { create } from 'zustand';
import type { ПроектV2 } from '../model/типы';
import type { ИтогПланировки } from '../model/планировщик';

const КЛЮЧ = 'верстак:интерфейс';

export type Окно = null | 'проверки' | 'настройки' | 'справка' | 'экспорт' | 'тур' | 'проектировщик';

/** Вкладки окна «Проектировщик» (этап 7) */
export type ВкладкаПроектировщика = 'планировка' | 'разбор' | 'сравнение';

/** Проект для разбора, сравнения или шторки: из варианта планировки или из файла */
export interface ВнешнийПроект {
  проект: ПроектV2;
  имя: string;
}

/** «До / после»: слева текущий проект, справа — этот; доля — где шторка (0…1 по ширине сцены) */
export interface Шторка extends ВнешнийПроект {
  доля: number;
}

interface Сохраняемое {
  туркПройден: boolean;
  свёрнуты: boolean;
  недавние: string[];
  избранное: string[];
  избранныеМатериалы: string[];
  свойЦвета: string[];
  комнатаКат: string | null;
  последняяВкладка: string | null;
  автозапуск: boolean;
  акцент: string;
  заказ: string;
  клиент: string;
  дизайнер: string;
  /** размерные линии и зазоры у выделенного изделия */
  показатьРазмеры: boolean;
}

const умолчание: Сохраняемое = {
  туркПройден: false,
  свёрнуты: false,
  недавние: [],
  избранное: [],
  избранныеМатериалы: [],
  свойЦвета: [],
  комнатаКат: null,
  последняяВкладка: null,
  автозапуск: false,
  акцент: 'латунь',
  заказ: '',
  клиент: '',
  дизайнер: '',
  показатьРазмеры: true,
};

function читать(): Сохраняемое {
  try {
    return { ...умолчание, ...JSON.parse(localStorage.getItem(КЛЮЧ) ?? '{}') };
  } catch {
    return { ...умолчание };
  }
}

interface UI extends Сохраняемое {
  окно: Окно;
  планОткрыт: boolean;
  показатьКлиенту: boolean;
  /** рулетка включена: клик по грани — замер (не сохраняется между запусками) */
  рулетка: boolean;
  установитьРулетку: (в: boolean) => void;
  /** сколько замеров сейчас на сцене и ждёт ли рулетка вторую грань (для кнопок и подсказки) */
  замеровРулетки: number;
  рулеткаЖдётВторую: boolean;
  /** час суток 6…22; свет по времени включается ползунком */
  час: number;
  часВключён: boolean;
  установитьЧас: (ч: number | null) => void;
  установить: (п: Partial<Сохраняемое>) => void;
  открытьОкно: (о: Окно) => void;
  переключитьИзбранное: (ид: string) => void;
  переключитьИзбранныйМатериал: (ид: string) => void;
  добавитьНедавнее: (ид: string) => void;
  добавитьСвойЦвет: (ц: string) => void;
  переключитьПлан: (о?: boolean) => void;
  /* этап 7: проектировщик (не сохраняется между запусками) */
  вкладкаПроектировщика: ВкладкаПроектировщика;
  /** последний итог «Предложи планировку» (варианты живут, пока не закрыто приложение или не открыт другой проект) */
  планировка: ИтогПланировки | null;
  /** что разбираем: null — текущий проект */
  разборДля: ВнешнийПроект | null;
  /** с чем сравниваем текущий проект */
  сравнитьС: ВнешнийПроект | null;
  шторка: Шторка | null;
  открытьПроектировщик: (вкладка: ВкладкаПроектировщика, п?: { разборДля?: ВнешнийПроект | null; сравнитьС?: ВнешнийПроект | null }) => void;
  установитьШторку: (ш: Шторка | null) => void;
}

export const useUI = create<UI>((set, get) => {
  const сохранить = (п: Partial<Сохраняемое>) => {
    const { окно: _о, планОткрыт: _п, показатьКлиенту: _к, рулетка: _р, замеровРулетки: _з, рулеткаЖдётВторую: _в, планировка: _пл, разборДля: _рд, сравнитьС: _сс, шторка: _ш, ...остальное } = { ...get(), ...п } as UI;
    const чистое: Record<string, unknown> = {};
    for (const к of Object.keys(умолчание)) чистое[к] = (остальное as unknown as Record<string, unknown>)[к];
    try {
      // сливаем с тем, что уже лежит: часть полей (каталог) пишет основное хранилище
      const было = JSON.parse(localStorage.getItem(КЛЮЧ) ?? '{}');
      localStorage.setItem(КЛЮЧ, JSON.stringify({ ...было, ...чистое }));
    } catch {
      /* без сохранения работает до закрытия */
    }
  };
  const переключить = (список: string[], ид: string) => (список.includes(ид) ? список.filter((x) => x !== ид) : [ид, ...список]);
  return {
    ...читать(),
    окно: null,
    планОткрыт: false,
    показатьКлиенту: false,
    рулетка: false,
    установитьРулетку: (в) => set({ рулетка: в }),
    замеровРулетки: 0,
    рулеткаЖдётВторую: false,
    час: 14,
    часВключён: false,
    установитьЧас: (ч) => set(ч === null ? { часВключён: false } : { час: ч, часВключён: true }),
    установить: (п) => {
      сохранить(п);
      set(п);
    },
    открытьОкно: (окно) => set({ окно }),
    переключитьИзбранное: (ид) => get().установить({ избранное: переключить(get().избранное, ид) }),
    переключитьИзбранныйМатериал: (ид) => get().установить({ избранныеМатериалы: переключить(get().избранныеМатериалы, ид) }),
    добавитьНедавнее: (ид) => get().установить({ недавние: [ид, ...get().недавние.filter((x) => x !== ид)].slice(0, 8) }),
    добавитьСвойЦвет: (ц) => get().установить({ свойЦвета: [ц, ...get().свойЦвета.filter((x) => x !== ц)].slice(0, 12) }),
    переключитьПлан: (о) => set({ планОткрыт: о ?? !get().планОткрыт }),
    вкладкаПроектировщика: 'планировка',
    планировка: null,
    разборДля: null,
    сравнитьС: null,
    шторка: null,
    открытьПроектировщик: (вкладка, п = {}) => set({ окно: 'проектировщик', вкладкаПроектировщика: вкладка, ...п }),
    установитьШторку: (ш) => set({ шторка: ш }),
  };
});

if (typeof window !== "undefined") (window as unknown as Record<string, unknown>).__верстакUI ??= useUI;
