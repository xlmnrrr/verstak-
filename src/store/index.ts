export type ТемаИнтерфейса = 'система' | 'мастерская' | 'калька';
const КЛЮЧ_ТЕМЫ = 'верстак:тема';
function прочитатьТему(): ТемаИнтерфейса {
  try {
    const т = localStorage.getItem(КЛЮЧ_ТЕМЫ);
    if (т === 'мастерская' || т === 'калька' || т === 'система') return т;
  } catch {
    /* хранилище недоступно */
  }
  return 'система';
}

