/** Проекция v2 → v1 с повторным использованием неизменённых объектов (меньше перерисовок) */
const кэшОбъектов = new WeakMap<object, { смещение: string; obj: Obj }>();
function проекция(п2: ПроектV2, помещение: string) {
  const р = вПроектV1(п2, помещение, false);
  const пом = п2.помещения.find((x) => x.id === р.помещение)!;
  const ключСмещения = р.смещение.join(',');
  const объекты = п2.объекты
    .filter((о) => о.помещение === пом.id)
    .map((экз) => {
      const в = кэшОбъектов.get(экз);
      if (в && в.смещение === ключСмещения) return в.obj;
      const obj = вОбъектV1(экз, р.смещение);
      кэшОбъектов.set(экз, { смещение: ключСмещения, obj });
      return obj;
    });
  return { ...р, проект: { ...р.проект, объекты } };
}

/** После отмены и возврата выделение сохраняется у объектов, которые остались в проекте */
const оставитьСуществующие = (ids: string[], п: ПроектV2) => ids.filter((id) => п.объекты.some((о) => о.id === id));

const КОМНАТА_ПО_УМОЛЧАНИЮ = { длина: 3600, ширина: 2800, высота: 2700 };

function помещениеИзКомнаты(к: Room): Помещение {
  const п = новоеПомещение('п1', 'кухня', 'Кухня', прямоугольник(к.длина, к.ширина), к.высота_стен);
  п.толщина_стен = к.толщина_стен;
  п.отделка = { стены: к.обои, пол: к.пол };
  return п;
}

