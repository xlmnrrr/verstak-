import { describe, expect, it } from 'vitest';
import { изделиеПоИд } from '../model/каталог';
import { новыйПроектV2, новыйЭкземпляр } from '../model/проект';
import type { ПроектV2 } from '../model/типы';
import { добавитьОбъекты, изменитьОбъект, переименоватьПроект, удалитьОбъекты } from './команды';
import { выполнить, вернуть, граница, отменить, пустаяИстория, type История } from './история';

const тумба = () => новыйЭкземпляр(изделиеПоИд('тумба-нижняя-400')!, 'п1', [0, 0, 0], 'а');

function старт(): { п: ПроектV2; и: История } {
  return { п: новыйПроектV2('Тест'), и: пустаяИстория() };
}

describe('команды и история', () => {
  it('добавить → отменить → вернуть', () => {
    let { п, и } = старт();
    ({ проект: п, история: и } = выполнить(п, и, добавитьОбъекты([тумба()])));
    expect(п.объекты.length).toBe(1);
    const о = отменить(п, и)!;
    expect(о.проект.объекты.length).toBe(0);
    const в = вернуть(о.проект, о.история)!;
    expect(в.проект.объекты.length).toBe(1);
  });

  it('перетаскивание (много правок одного объекта в одном жесте) — одна запись истории', () => {
    let { п, и } = старт();
    ({ проект: п, история: и } = выполнить(п, и, добавитьОбъекты([тумба()])));
    и = граница(и); // pointerdown
    for (let x = 10; x <= 500; x += 10) {
      ({ проект: п, история: и } = выполнить(п, и, изменитьОбъект('а', (э) => ({ ...э, позиция: [x, 0, 0] }), 'Сдвинуть')));
    }
    expect(п.объекты[0].позиция[0]).toBe(500);
    expect(и.прошлое.length).toBe(2); // добавление + весь жест
    const о = отменить(п, и)!;
    expect(о.проект.объекты[0].позиция[0]).toBe(0); // откатился жест целиком
    const в = вернуть(о.проект, о.история)!;
    expect(в.проект.объекты[0].позиция[0]).toBe(500);
  });

  it('два жеста подряд — две записи', () => {
    let { п, и } = старт();
    ({ проект: п, история: и } = выполнить(п, и, добавитьОбъекты([тумба()])));
    for (const конец of [300, 700]) {
      и = граница(и);
      for (let x = 1; x <= 5; x++) {
        ({ проект: п, история: и } = выполнить(п, и, изменитьОбъект('а', (э) => ({ ...э, позиция: [(конец / 5) * x, 0, 0] }))));
      }
    }
    expect(и.прошлое.length).toBe(3);
    const о1 = отменить(п, и)!;
    expect(о1.проект.объекты[0].позиция[0]).toBe(300);
    const о2 = отменить(о1.проект, о1.история)!;
    expect(о2.проект.объекты[0].позиция[0]).toBe(0);
  });

  it('правка без границы (цифрой в поле) отменяется отдельно, а не склеивается с прошлой', () => {
    let { п, и } = старт();
    ({ проект: п, история: и } = выполнить(п, и, добавитьОбъекты([тумба()])));
    ({ проект: п, история: и } = выполнить(п, и, изменитьОбъект('а', (э) => ({ ...э, габариты: { ...э.габариты, ш: 500 } }))));
    ({ проект: п, история: и } = выполнить(п, и, изменитьОбъект('а', (э) => ({ ...э, габариты: { ...э.габариты, ш: 600 } }))));
    expect(и.прошлое.length).toBe(3);
    const о = отменить(п, и)!;
    expect(о.проект.объекты[0].габариты.ш).toBe(500);
  });

  it('удаление возвращает объект на прежнее место в списке', () => {
    let { п, и } = старт();
    const [a, б, в] = ['а', 'б', 'в'].map((id) => ({ ...тумба(), id }));
    ({ проект: п, история: и } = выполнить(п, и, добавитьОбъекты([a, б, в])));
    ({ проект: п, история: и } = выполнить(п, и, удалитьОбъекты(['б'])));
    expect(п.объекты.map((o) => o.id)).toEqual(['а', 'в']);
    const о = отменить(п, и)!;
    expect(о.проект.объекты.map((x) => x.id)).toEqual(['а', 'б', 'в']);
  });

  it('новая команда после отмены очищает «вернуть»', () => {
    let { п, и } = старт();
    ({ проект: п, история: и } = выполнить(п, и, добавитьОбъекты([тумба()])));
    const о = отменить(п, и)!;
    const н = выполнить(о.проект, о.история, переименоватьПроект('Другое'));
    expect(н.история.будущее.length).toBe(0);
    expect(вернуть(н.проект, н.история)).toBeNull();
  });

  it('отмена на пустой истории ничего не ломает', () => {
    const { п, и } = старт();
    expect(отменить(п, и)).toBeNull();
    expect(вернуть(п, и)).toBeNull();
  });

  it('500 объектов: история хранит команды, а не копии проекта (память не растёт копиями)', () => {
    let { п, и } = старт();
    const экз = Array.from({ length: 500 }, (_, i) => ({ ...тумба(), id: `о${i}`, позиция: [i, 0, 0] as [number, number, number] }));
    ({ проект: п, история: и } = выполнить(п, и, добавитьОбъекты(экз)));
    for (let k = 0; k < 100; k++) {
      и = граница(и);
      ({ проект: п, история: и } = выполнить(п, и, изменитьОбъект('о0', (э) => ({ ...э, поворот: k }))));
    }
    expect(и.прошлое.length).toBe(101);
    // запись — маленькая команда, а не копия проекта
    expect(JSON.stringify(п).length).toBeGreaterThan(50000);
    expect(JSON.stringify(и.прошлое[50]).length).toBeLessThan(200);
  });
});
