import { describe, expect, it } from 'vitest';
import { изделиеПоИд } from '../model/каталог';
import { новоеПомещение, прямоугольник } from '../model/помещение';
import { новыйПроектV2, новыйЭкземпляр } from '../model/проект';
import type { ПроектV2 } from '../model/типы';
import { htmlЧертежа } from './форматы';
import { ОБЛАСТЬ_ЛИСТА, МАСШТАБЫ, раскладкаЛистов, размерВида, svgВида, упаковать, видыСпереди, htmlЛистаВидов, type Размер } from './виды';

const комната = (ш = 4200, г = 3000, в = 2700): ПроектV2 => новыйПроектV2('т', новоеПомещение('к', 'кухня', 'Кухня', прямоугольник(ш, г), в));
let n = 0;
function поставить(п: ПроектV2, ид: string, x: number, z: number, поворот = 0, y?: number) {
  const изд = изделиеПоИд(ид);
  if (!изд) throw new Error('нет изделия ' + ид);
  const э = новыйЭкземпляр(изд, 'к', [x, y ?? (изд.крепление === 'стена' ? (изд.подъём ?? 1500) : 0), z], `в${n++}`);
  э.поворот = поворот;
  п.объекты.push(э);
  return э;
}

describe('виды спереди: какие предметы попадают на стену', () => {
  it('задняя стена: слева направо в порядке возрастания x, номера как на плане', () => {
    const п = комната();
    const а = поставить(п, 'тумба-ящики-600', -1000, -1220);
    const б = поставить(п, 'тумба-ящики-600', 1000, -1220);
    const виды = видыСпереди(п);
    expect(виды).toHaveLength(1);
    expect(виды[0].стена).toBe(0);
    expect(виды[0].предметы.map((x) => x.id)).toEqual([а.id, б.id]);
    expect(виды[0].предметы.map((x) => x.номер)).toEqual([1, 2]);
    expect(виды[0].предметы[0].x).toBeCloseTo(-1000 + 2100 - 300, 5); // 2100 — полдлины стены
    expect(виды[0].предметы[1].x).toBeGreaterThan(виды[0].предметы[0].x);
    expect(виды[0].длина).toBe(4200);
    expect(виды[0].высота).toBe(2700);
  });

  it('передняя стена: зритель смотрит наоборот, слева у него — большие x', () => {
    const п = комната();
    const а = поставить(п, 'тумба-ящики-600', -1000, 1220, 180);
    const б = поставить(п, 'тумба-ящики-600', 1000, 1220, 180);
    const виды = видыСпереди(п);
    expect(виды).toHaveLength(1);
    expect(виды[0].стена).toBe(2);
    // слева от зрителя (глядящего на переднюю стену) — предмет с бо́льшим x
    expect(виды[0].предметы.map((x) => x.id)).toEqual([б.id, а.id]);
  });

  it('предмет с фасадом не на зрителя и остров посреди комнаты на виды стен не попадают', () => {
    const п = комната();
    поставить(п, 'тумба-ящики-600', 0, -1220, 180); // спиной к комнате
    поставить(п, 'тумба-ящики-600', 0, 0); // остров
    expect(видыСпереди(п)).toHaveLength(0);
  });

  it('есть фасадные части с положением внутри предмета; навесной шкаф идёт на своей высоте', () => {
    const п = комната();
    поставить(п, 'тумба-ящики-600', -900, -1220);
    поставить(п, 'навесной-600', -900, -1240, 0, 1430);
    const в = видыСпереди(п)[0];
    const тумба = в.предметы.find((x) => x.y === 0)!;
    const навесной = в.предметы.find((x) => x.y === 1430)!;
    expect(тумба.части.length).toBeGreaterThan(0);
    for (const ч of тумба.части) {
      expect(ч.x).toBeGreaterThanOrEqual(тумба.x - 1);
      expect(ч.x + ч.ш).toBeLessThanOrEqual(тумба.x + тумба.ш + 1);
      expect(ч.y + ч.в).toBeLessThanOrEqual(тумба.y + тумба.в + 1);
    }
    expect(навесной.y).toBe(1430);
  });

  it('проёмы стены попадают в вид с тем же отсчётом слева', () => {
    const п = комната();
    п.помещения[0].отметки.push({ id: 'о', стена: 0, вид: 'окно', от_угла: 500, от_пола: 900, ширина: 1200, высота: 1400 });
    поставить(п, 'тумба-ящики-600', 1000, -1220);
    const в = видыСпереди(п)[0];
    expect(в.проёмы).toHaveLength(1);
    expect(в.проёмы[0]).toMatchObject({ вид: 'окно', x: 500, ш: 1200, y: 900, в: 1400 });
  });
});

describe('упаковка видов на лист без обрезки', () => {
  const внутри = (р: { x: number; y: number }, s: Размер) => р.x >= 0 && р.y >= 0 && р.x + s.ш <= ОБЛАСТЬ_ЛИСТА.ш + 1e-6 && р.y + s.в <= ОБЛАСТЬ_ЛИСТА.в + 1e-6;
  const пересекаются = (a: { x: number; y: number }, sa: Размер, b: { x: number; y: number }, sb: Размер) => a.x < b.x + sb.ш && b.x < a.x + sa.ш && a.y < b.y + sb.в && b.y < a.y + sa.в;

  it('на лист ставится несколько видов, ничего не вылезает и не перекрывается', () => {
    const размеры: Размер[] = [
      { ш: 120, в: 70 },
      { ш: 120, в: 70 },
      { ш: 120, в: 70 },
      { ш: 120, в: 70 },
      { ш: 250, в: 60 },
    ];
    const пл = упаковать(размеры)!;
    expect(пл).not.toBeNull();
    expect(пл).toHaveLength(размеры.length);
    пл.forEach((р, i) => expect(внутри(р, размеры[i]), `вид ${i} вылез`).toBe(true));
    for (let i = 0; i < пл.length; i++) for (let j = i + 1; j < пл.length; j++) if (пл[i].лист === пл[j].лист) expect(пересекаются(пл[i], размеры[i], пл[j], размеры[j]), `${i} и ${j} перекрываются`).toBe(false);
    // два вида в ряд и второй ряд на том же листе
    expect(пл.filter((р) => р.лист === 0).length).toBeGreaterThanOrEqual(3);
  });

  it('вид больше листа не режется — упаковка отказывается', () => {
    expect(упаковать([{ ш: ОБЛАСТЬ_ЛИСТА.ш + 1, в: 10 }])).toBeNull();
    expect(упаковать([{ ш: 10, в: ОБЛАСТЬ_ЛИСТА.в + 1 }])).toBeNull();
  });

  it('случайные наборы: каждый вид учтён один раз, в пределах листа, без перекрытий', () => {
    let семя = 7;
    const случ = () => ((семя = (семя * 1103515245 + 12345) & 0x7fffffff) / 0x7fffffff);
    for (let t = 0; t < 60; t++) {
      const размеры: Размер[] = Array.from({ length: 1 + Math.floor(случ() * 12) }, () => ({ ш: 40 + случ() * 220, в: 30 + случ() * 110 }));
      const пл = упаковать(размеры)!;
      expect(пл).toHaveLength(размеры.length);
      пл.forEach((р, i) => expect(внутри(р, размеры[i])).toBe(true));
      for (let i = 0; i < пл.length; i++) for (let j = i + 1; j < пл.length; j++) if (пл[i].лист === пл[j].лист) expect(пересекаются(пл[i], размеры[i], пл[j], размеры[j])).toBe(false);
    }
  });

  it('масштаб комплекта: самый крупный, при котором всё помещается; мелкие стены делят лист', () => {
    const п = комната(2400, 2400);
    поставить(п, 'тумба-ящики-600', -300, -920); // стена 0
    поставить(п, 'тумба-ящики-600', 920, -300, 90); // правая стена (фасад на комнату)
    const виды = видыСпереди(п);
    expect(виды.length).toBe(2);
    const р = раскладкаЛистов(виды)!;
    expect(МАСШТАБЫ).toContain(р.масштаб);
    expect(р.листы).toHaveLength(1); // два небольших вида на одном листе
    expect(р.листы[0]).toHaveLength(2);
    // более крупный масштаб, чем выбранный, уже не уместил бы вид или лишил бы смысла «несколько на лист»
    const крупнее = МАСШТАБЫ[МАСШТАБЫ.indexOf(р.масштаб as (typeof МАСШТАБЫ)[number]) - 1];
    if (крупнее) {
      const все = виды.map((в) => размерВида(в, крупнее));
      const пл = упаковать(все);
      expect(!пл || Math.max(...пл.map((x) => x.лист)) + 1 > Math.ceil(виды.length / 2)).toBe(true);
    }
  });

  it('большая кухня: виды без обрезки, на нескольких листах, подряд', () => {
    const п = комната(9000, 3000);
    for (let i = 0; i < 12; i++) поставить(п, 'тумба-ящики-600', -4200 + i * 600 + 300, -1220);
    const виды = видыСпереди(п);
    const р = раскладкаЛистов(виды)!;
    expect(р).not.toBeNull();
    const шир = размерВида(виды[0], р.масштаб).ш;
    expect(шир).toBeLessThanOrEqual(ОБЛАСТЬ_ЛИСТА.ш + 1e-6);
    expect(р.листы.flat()).toHaveLength(виды.length);
  });
});

describe('SVG и HTML чертежа', () => {
  it('SVG вида: числа конечные, номера предметов есть, размеры вида на бумаге в пределах листа', () => {
    const п = комната();
    поставить(п, 'тумба-ящики-600', -900, -1220);
    поставить(п, 'тумба-ящики-600', -300, -1220);
    const в = видыСпереди(п)[0];
    const р = раскладкаЛистов([в])!;
    const svg = svgВида(в, р.масштаб);
    expect(svg).not.toMatch(/NaN|undefined|Infinity/);
    expect(svg).toContain('>1</text>');
    expect(svg).toContain('>2</text>');
    expect(svg).toContain(`1:${р.масштаб}`);
    expect(svg).toMatch(/4\s200/); // общая длина стены (неразрывный пробел в числе)
    const { ш, в: выс } = размерВида(в, р.масштаб);
    expect(ш).toBeLessThanOrEqual(ОБЛАСТЬ_ЛИСТА.ш);
    expect(выс).toBeLessThanOrEqual(ОБЛАСТЬ_ЛИСТА.в);
  });

  it('чертёж: листы пронумерованы, виды спереди идут после планов, состав комплекта указан', () => {
    const п = комната();
    поставить(п, 'тумба-ящики-600', -900, -1220);
    const html = htmlЧертежа(п, { заказ: '1', клиент: 'К', дизайнер: 'Д' });
    expect(html).toContain('Лист 1. План');
    expect(html).toContain('Лист 2. Виды спереди, масштаб 1:');
    expect(html).toContain('Состав: лист 1 — план; лист 2 — виды спереди');
    expect(html.indexOf('Лист 2. Виды спереди')).toBeGreaterThan(html.indexOf('Лист 1. План'));
    expect(html.indexOf('Спецификация модулей')).toBeGreaterThan(html.indexOf('Лист 2. Виды спереди'));
  });

  it('без предметов у стен видов спереди нет, комплект прежний', () => {
    const п = комната();
    поставить(п, 'тумба-ящики-600', 0, 0);
    const html = htmlЧертежа(п, { заказ: '', клиент: '', дизайнер: '' });
    expect(html).not.toContain('Виды спереди, масштаб');
    expect(html).toContain('Лист 1. План');
  });

  it('htmlЛистаВидов кладёт каждый вид внутри области листа', () => {
    const п = комната();
    поставить(п, 'тумба-ящики-600', -900, -1220);
    const виды = видыСпереди(п);
    const р = раскладкаЛистов(виды)!;
    const html = htmlЛистаВидов(виды, р, 2, 0);
    for (const m of html.matchAll(/left:([\d.]+)mm;top:([\d.]+)mm;width:([\d.]+)mm;height:([\d.]+)mm/g)) {
      expect(Number(m[1]) + Number(m[3])).toBeLessThanOrEqual(ОБЛАСТЬ_ЛИСТА.ш + 1e-6);
      expect(Number(m[2]) + Number(m[4])).toBeLessThanOrEqual(ОБЛАСТЬ_ЛИСТА.в + 1e-6);
    }
  });
});
