/**
 * Производство 2.0: виды спереди (развёртки стен) для PDF-чертежа и упаковка нескольких видов на лист без обрезки.
 * Чистая геометрия и SVG-строки, без DOM. Размеры — миллиметры; «бумажные» размеры — миллиметры на листе A4.
 *
 * Вид спереди: зритель стоит в комнате лицом к стене. Предметы, у которых фасад смотрит на зрителя и спина у этой стены,
 * рисуются вместе с проёмами (дверь, окно, арка). Номера предметов совпадают с номерами на плане и в легенде.
 */
import { детали } from '../model/детали';
import { изделиеПоИд } from '../model/каталог';
import { высотаДляРендера, стены as рёбра } from '../model/помещение';
import type { Помещение, ПроектV2, Экземпляр } from '../model/типы';

/** Рабочая область листа A4 альбомной: поля, рамка, место под штамп и заголовок листа уже вычтены (мм на бумаге) */
export const ОБЛАСТЬ_ЛИСТА = { ш: 270, в: 146 } as const;
/** Поля вокруг одного вида на бумаге: слева — высотные размеры, снизу — цепочка размеров, сверху — заголовок */
const ПОЛЯ = { лево: 13, право: 4, верх: 7, низ: 17 } as const;
/** Зазор между видами на листе, мм бумаги */
export const ЗАЗОР_ВИДОВ = 5;
/** Допустимые масштабы 1:N по возрастанию N (крупный → мелкий) */
export const МАСШТАБЫ = [10, 15, 20, 25, 30, 40, 50, 75, 100] as const;

export interface ПредметВида {
  /** номер на плане */
  номер: number;
  id: string;
  название: string;
  /** левый край и ширина вдоль стены, мм (отсчёт от левого края стены для зрителя) */
  x: number;
  ш: number;
  y: number;
  в: number;
  /** фасадные части (дверцы, ящики, стёкла): левый край, низ, ширина, высота в тех же осях */
  части: { x: number; y: number; ш: number; в: number; роль: string }[];
}

export interface ПроёмВида {
  вид: 'дверь' | 'окно' | 'арка';
  x: number;
  ш: number;
  y: number;
  в: number;
}

export interface ВидСтены {
  ключ: string;
  помещение: string;
  названиеПомещения: string;
  /** номер стены (индекс ребра контура) и её длина, мм */
  стена: number;
  длина: number;
  высота: number;
  предметы: ПредметВида[];
  проёмы: ПроёмВида[];
}

const ФАСАДНЫЕ = new Set(['фасад', 'ящик-фасад', 'стекло', 'зеркало']);

const градусы = (поворот: number) => ((поворот % 360) + 360) % 360;

/** Виды спереди по стенам помещений: только стены, у которых стоят предметы */
export function видыСпереди(п: ПроектV2, помещениеId?: string): ВидСтены[] {
  const итог: ВидСтены[] = [];
  const помещения = помещениеId ? п.помещения.filter((x) => x.id === помещениеId) : п.помещения;
  for (const пом of помещения) итог.push(...видыПомещения(п, пом));
  return итог;
}

function видыПомещения(п: ПроектV2, пом: Помещение): ВидСтены[] {
  const H = высотаДляРендера(пом);
  const экземпляры: { э: Экземпляр; номер: number }[] = [];
  let номер = 0;
  for (const э of п.объекты) {
    if (э.помещение !== пом.id || изделиеПоИд(э.изделие)?.тип === 'проём') continue;
    номер++;
    экземпляры.push({ э, номер });
  }
  const итог: ВидСтены[] = [];
  for (const с of рёбра(пом.контур)) {
    if (с.длина < 300) continue;
    const n = с.нормаль;
    // зритель стоит в комнате лицом к стене: его правая рука
    const право: [number, number] = [n[1], -n[0]];
    const вправоПоСтене = право[0] * с.направление[0] + право[1] * с.направление[1] > 0;
    const предметы: ПредметВида[] = [];
    for (const { э, номер: ном } of экземпляры) {
      const θ = (градусы(э.поворот) * Math.PI) / 180;
      const фронт: [number, number] = [-Math.sin(θ), Math.cos(θ)];
      if (фронт[0] * n[0] + фронт[1] * n[1] < Math.cos((10 * Math.PI) / 180)) continue; // фасад смотрит не на зрителя
      const s = (э.позиция[0] - с.а[0]) * с.направление[0] + (э.позиция[2] - с.а[1]) * с.направление[1];
      const расстояние = (э.позиция[0] - с.а[0]) * n[0] + (э.позиция[2] - с.а[1]) * n[1] - э.габариты.г / 2;
      if (s < -50 || s > с.длина + 50 || расстояние > 250 || расстояние < -60) continue;
      const центрX = вправоПоСтене ? s : с.длина - s;
      const изд = изделиеПоИд(э.изделие);
      const части: ПредметВида['части'] = [];
      if (изд && (изд.тип === 'корпус' || изд.тип === 'стол')) {
        for (const д of детали(изд, э)) {
          if (!ФАСАДНЫЕ.has(д.роль)) continue;
          const ш = д.локально.объём[0];
          const в = д.локально.объём[1];
          if (ш < 20 || в < 20) continue;
          части.push({ x: центрX + д.локально.центр[0] - ш / 2, y: э.позиция[1] + д.локально.центр[1] - в / 2, ш, в, роль: д.роль });
        }
      }
      предметы.push({ номер: ном, id: э.id, название: э.название ?? изд?.название ?? э.изделие, x: центрX - э.габариты.ш / 2, ш: э.габариты.ш, y: э.позиция[1], в: э.габариты.в, части });
    }
    if (!предметы.length) continue;
    предметы.sort((a, b) => a.x - b.x);
    const проёмы: ПроёмВида[] = [];
    for (const о of пом.отметки) {
      if (о.стена !== с.индекс || (о.вид !== 'дверь' && о.вид !== 'окно' && о.вид !== 'арка')) continue;
      const левоПоСтене = о.от_угла;
      const x = вправоПоСтене ? левоПоСтене : с.длина - левоПоСтене - о.ширина;
      проёмы.push({ вид: о.вид, x, ш: о.ширина, y: о.от_пола, в: о.высота });
    }
    итог.push({ ключ: `${пом.id}:${с.индекс}`, помещение: пом.id, названиеПомещения: пом.название, стена: с.индекс, длина: с.длина, высота: H, предметы, проёмы });
  }
  return итог;
}

/* ------------------------------------------------------------------ размеры на бумаге и упаковка */

export interface Размер {
  ш: number;
  в: number;
}

/** Размер вида на бумаге при масштабе 1:s (с полями) */
export const размерВида = (в: ВидСтены, s: number): Размер => ({ ш: в.длина / s + ПОЛЯ.лево + ПОЛЯ.право, в: в.высота / s + ПОЛЯ.верх + ПОЛЯ.низ });

export interface Размещение {
  лист: number;
  x: number;
  y: number;
}

/**
 * Упаковка прямоугольников на листы «полками»: слева направо, новая полка, когда не хватает ширины, новый лист, когда не хватает высоты.
 * Ничего не обрезается: если прямоугольник больше листа, возвращается null.
 */
export function упаковать(размеры: Размер[], область: Размер = ОБЛАСТЬ_ЛИСТА, зазор = ЗАЗОР_ВИДОВ): Размещение[] | null {
  const итог: Размещение[] = [];
  let лист = 0;
  let x = 0;
  let y = 0;
  let высотаПолки = 0;
  for (const р of размеры) {
    if (р.ш > область.ш + 1e-6 || р.в > область.в + 1e-6) return null;
    if (x > 0 && x + р.ш > область.ш + 1e-6) {
      y += высотаПолки + зазор;
      x = 0;
      высотаПолки = 0;
    }
    if (y + р.в > область.в + 1e-6) {
      лист++;
      x = 0;
      y = 0;
      высотаПолки = 0;
    }
    итог.push({ лист, x, y });
    x += р.ш + зазор;
    высотаПолки = Math.max(высотаПолки, р.в);
  }
  return итог;
}

export interface РаскладкаЛистов {
  масштаб: number;
  /** по листам: индексы видов и их положение на листе (мм бумаги) */
  листы: { вид: number; x: number; y: number; ш: number; в: number }[][];
}

/**
 * Один масштаб на весь комплект: самый крупный из списка, при котором каждый вид помещается на лист целиком и всё умещается
 * не больше чем на половину числа видов листов (чтобы на листе стояло несколько видов). Не получается — просто самый крупный,
 * при котором каждый вид помещается. Масштаб мельче 1:100 не бывает: такой вид слишком мелкий, он остаётся на отдельном листе.
 */
export function раскладкаЛистов(виды: ВидСтены[], область: Размер = ОБЛАСТЬ_ЛИСТА): РаскладкаЛистов | null {
  if (!виды.length) return null;
  const цель = Math.max(1, Math.ceil(виды.length / 2));
  let запасной: РаскладкаЛистов | null = null;
  for (const s of МАСШТАБЫ) {
    const размеры = виды.map((в) => размерВида(в, s));
    const пл = упаковать(размеры, область);
    if (!пл) continue;
    const листов = Math.max(...пл.map((x) => x.лист)) + 1;
    const р: РаскладкаЛистов = { масштаб: s, листы: Array.from({ length: листов }, () => []) };
    пл.forEach((x, i) => р.листы[x.лист].push({ вид: i, x: x.x, y: x.y, ш: размеры[i].ш, в: размеры[i].в }));
    if (!запасной) запасной = р;
    if (листов <= цель) return р;
  }
  return запасной;
}

/* ------------------------------------------------------------------ SVG вида */

const экр = (t: string) => t.replace(/&/g, '&amp;').replace(/</g, '&lt;');
const мм = (v: number) => Math.round(v).toLocaleString('ru-RU');

/**
 * SVG одного вида на бумаге при масштабе 1:s. Размеры и подписи заданы в мм бумаги, поэтому их шрифт не зависит от масштаба.
 * Система координат svg — мм бумаги; по y вверх идёт высота над полом.
 */
export function svgВида(в: ВидСтены, s: number): string {
  const { ш, в: выс } = размерВида(в, s);
  const X = (v: number) => ПОЛЯ.лево + v / s;
  const Y = (v: number) => ПОЛЯ.верх + (в.высота - v) / s;
  const л: string[] = [];
  const f = 2.3; // шрифт размеров, мм бумаги
  // стена и пол
  л.push(`<rect x="${X(0)}" y="${Y(в.высота)}" width="${в.длина / s}" height="${в.высота / s}" fill="#f7f4ee" stroke="#142019" stroke-width="0.35"/>`);
  for (const п of в.проёмы) {
    const подпись = п.вид === 'окно' ? 'окно' : п.вид === 'арка' ? 'арка' : 'дверь';
    л.push(`<rect x="${X(п.x)}" y="${Y(п.y + п.в)}" width="${п.ш / s}" height="${п.в / s}" fill="${п.вид === 'окно' ? '#dfeaf2' : '#ece6da'}" stroke="#6a7a72" stroke-width="0.25" stroke-dasharray="1.6 1"/>`);
    л.push(`<text x="${X(п.x + п.ш / 2)}" y="${Y(п.y + п.в / 2)}" font-size="${f}" text-anchor="middle" fill="#5a6a62">${подпись}</text>`);
  }
  for (const р of в.предметы) {
    л.push(`<rect x="${X(р.x)}" y="${Y(р.y + р.в)}" width="${р.ш / s}" height="${р.в / s}" fill="#e9e1d0" stroke="#3a2f22" stroke-width="0.4"/>`);
    for (const ч of р.части) {
      л.push(`<rect x="${X(ч.x)}" y="${Y(ч.y + ч.в)}" width="${ч.ш / s}" height="${ч.в / s}" fill="${ч.роль === 'стекло' || ч.роль === 'зеркало' ? '#dbe8ee' : '#f1ead9'}" stroke="#7a6a55" stroke-width="0.2"/>`);
    }
    const размерШрифта = Math.min(f * 1.4, р.ш / s / 2.2, р.в / s / 1.6);
    if (размерШрифта >= 1.2) л.push(`<text x="${X(р.x + р.ш / 2)}" y="${Y(р.y + р.в / 2)}" font-size="${размерШрифта}" text-anchor="middle" dominant-baseline="central" fill="#142019" font-weight="700">${р.номер}</text>`);
  }
  // цепочка ширин и общая длина под стеной
  const yЦепь = Y(0) + 5;
  const yОбщая = Y(0) + 11;
  const засечка = (x: number, y: number) => `<line x1="${x}" y1="${y - 1.2}" x2="${x}" y2="${y + 1.2}" stroke="#174b8a" stroke-width="0.3"/>`;
  const края = [...new Set(в.предметы.flatMap((р) => [Math.round(р.x), Math.round(р.x + р.ш)]))].sort((a, b) => a - b);
  л.push(`<line x1="${X(края[0])}" y1="${yЦепь}" x2="${X(края[края.length - 1])}" y2="${yЦепь}" stroke="#174b8a" stroke-width="0.3"/>`);
  for (let i = 0; i < края.length; i++) {
    л.push(засечка(X(края[i]), yЦепь));
    if (i > 0) {
      const w = края[i] - края[i - 1];
      const шир = w / s;
      if (w > 0 && шир >= 5) л.push(`<text x="${X((края[i] + края[i - 1]) / 2)}" y="${yЦепь - 0.9}" font-size="${f * 0.9}" text-anchor="middle" fill="#174b8a">${мм(w)}</text>`);
    }
  }
  л.push(`<line x1="${X(0)}" y1="${yОбщая}" x2="${X(в.длина)}" y2="${yОбщая}" stroke="#174b8a" stroke-width="0.3"/>${засечка(X(0), yОбщая)}${засечка(X(в.длина), yОбщая)}`);
  л.push(`<text x="${X(в.длина / 2)}" y="${yОбщая - 0.9}" font-size="${f}" text-anchor="middle" fill="#174b8a">${мм(в.длина)}</text>`);
  // уровни по высоте слева: верхи и низы предметов и высота стены
  const уровни = [...new Set([0, в.высота, ...в.предметы.flatMap((р) => [Math.round(р.y), Math.round(р.y + р.в)])])].sort((a, b) => a - b);
  const подписи: number[] = [];
  let последний = -1e9;
  for (const у of уровни) {
    if ((у - последний) / s < f * 1.1 && подписи.length) continue; // не лепим подписи друг на друга
    подписи.push(у);
    последний = у;
  }
  for (const у of подписи) {
    л.push(`<line x1="${X(0) - 3}" y1="${Y(у)}" x2="${X(0)}" y2="${Y(у)}" stroke="#174b8a" stroke-width="0.3"/>`);
    л.push(`<text x="${X(0) - 3.6}" y="${Y(у)}" font-size="${f * 0.9}" text-anchor="end" dominant-baseline="central" fill="#174b8a">${мм(у)}</text>`);
  }
  // заголовок вида
  const заг = `${в.названиеПомещения}, стена ${в.стена + 1} · 1:${s}`;
  л.push(`<text x="${ПОЛЯ.лево}" y="4.6" font-size="3.4" font-weight="700" fill="#142019">${экр(заг)}</text>`);
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${ш} ${выс}" width="${ш}mm" height="${выс}mm" style="display:block;font-family:'Segoe UI',Arial,sans-serif">${л.join('')}</svg>`;
}

/** Содержимое листа видов (заголовок и полотно): блоки по заданному положению (мм бумаги от левого верхнего угла области листа) */
export function htmlЛистаВидов(виды: ВидСтены[], р: РаскладкаЛистов, номерЛиста: number, индексЛиста: number): string {
  const блоки = р.листы[индексЛиста]
    .map((б) => `<div class="вид" style="left:${б.x}mm;top:${б.y}mm;width:${б.ш}mm;height:${б.в}mm">${svgВида(виды[б.вид], р.масштаб)}</div>`)
    .join('');
  return `<h2>Лист ${номерЛиста}. Виды спереди, масштаб 1:${р.масштаб}</h2><div class="полотно" style="width:${ОБЛАСТЬ_ЛИСТА.ш}mm;height:${ОБЛАСТЬ_ЛИСТА.в}mm">${блоки}</div>`;
}

/** Ссылка на легенду: номера предметов совпадают с планом */
export const легендаВида = (в: ВидСтены): string => в.предметы.map((р) => `${р.номер} — ${экр(р.название)}`).join('; ');
