/**
 * Очистка имени проекта для файла Windows. Один источник правды: используют и Electron (main.mjs),
 * и окно приложения (через vite), и тесты.
 * Убирает запрещённые символы и разделители пути, служебные имена (CON, NUL, COM1…),
 * точки и пробелы по краям; длина не больше 80.
 */
const ЗАПРЕЩЕНО = /[\\/:*?"<>|\u0000-\u001f]/g;
const СЛУЖЕБНЫЕ = /^(con|prn|aux|nul|com[1-9]|lpt[1-9])$/i;

export function очиститьИмя(имя, запасное = 'Проект') {
  let н = String(имя ?? '')
    .normalize('NFC')
    .replace(ЗАПРЕЩЕНО, '_')
    .replace(/\.{2,}/g, '.')
    .replace(/^[\s.]+|[\s.]+$/g, '');
  if (н.length > 80) н = н.slice(0, 80).replace(/[\s.]+$/g, '');
  const безРасширения = н.split('.')[0];
  if (!н || СЛУЖЕБНЫЕ.test(безРасширения)) return запасное;
  return н;
}
