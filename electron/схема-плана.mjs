/**
 * План для листа на обложке, когда картинки-превью нет (проект написан руками, вариант планировки, превью не снялось):
 * контур первого помещения и следы предметов в нём. Числа — мм. v1: прямоугольник комнаты с началом в центре.
 * Общий для main.mjs (папка «Проекты») и браузерного режима разработки (src/lib/storage.ts).
 */
const ч = (v) => (typeof v === 'number' && Number.isFinite(v) ? Math.round(v) : 0);

const следы = (объекты, фильтр) =>
  (Array.isArray(объекты) ? объекты : [])
    .filter((о) => о && о.габариты && Array.isArray(о.позиция) && фильтр(о))
    .slice(0, 300)
    .map((о) => [ч(о.позиция[0]), ч(о.позиция[2]), ч(о.габариты.ш), ч(о.габариты.г), ч(о.поворот), ч(о.позиция[1]) > 1200 ? 1 : 0]);

export function схемаПлана(д, помещениеId) {
  if (!д || typeof д !== 'object') return undefined;
  if (Array.isArray(д.помещения) && д.помещения[0] && Array.isArray(д.помещения[0].контур)) {
    const пом = д.помещения.find((x) => x && x.id === помещениеId) ?? д.помещения[0];
    return {
      контур: пом.контур.slice(0, 64).map((т) => [ч(т?.[0]), ч(т?.[1])]),
      объекты: следы(д.объекты, (о) => о.помещение === пом.id),
    };
  }
  const к = д.комната;
  if (к && к.длина && к.ширина) {
    const x = ч(к.длина) / 2;
    const z = ч(к.ширина) / 2;
    return { контур: [[-x, -z], [x, -z], [x, z], [-x, z]], объекты: следы(д.объекты, () => true) };
  }
  return undefined;
}
