/**
 * Приёмка этапа 4 «Валидатор» в настоящем окне Electron: окно «Проверки» на демо (чисто) и на проблемном проекте (с цифрами),
 * фильтры, переход к объекту. Запуск: node scripts/проверка-4.cjs http://127.0.0.1:5274/ ; скриншоты — проверка\v2\4-*.png
 */
const path = require('node:path');
const fs = require('node:fs');
const { запуститьElectron, подключиться, слушатьКонсоль, пауза, открытьПример } = require('./электрон-общее.cjs');
const АДРЕС = process.argv[2] || 'http://127.0.0.1:5274/';
const корень = process.cwd();
const данные = path.join(корень, 'проверка', 'данные-4');
const снимки = path.join(корень, 'проверка', 'v2');
fs.mkdirSync(снимки, { recursive: true });
const итоги = [];
const проверка = (имя, ок, п = '') => {
  итоги.push({ имя, ок: !!ок, п });
  console.log(`${ок ? 'ОК ' : 'НЕТ'}  ${имя}${п ? ' — ' + п : ''}`);
};

(async () => {
  fs.rmSync(данные, { recursive: true, force: true });
  fs.mkdirSync(path.join(данные, 'Проекты'), { recursive: true });
  const процесс = запуститьElectron({ адрес: АДРЕС, данные, порт: 9384, доп: { VERSTAK_AUTOSAVE_SEC: '3600' } });
  const t0 = Date.now();
  try {
    const { браузер, стр } = await подключиться(АДРЕС, 9384);
    const к = слушатьКонсоль(стр);
    const S = (fn, ...а) => стр.evaluate(fn, ...а);
    await пауза(2500);
    await S(() => localStorage.setItem('верстак:интерфейс', JSON.stringify({ туркПройден: true, каталогОткрыт: false })));
    await стр.reload();
    await пауза(2000);

    const открытьПроверки = async () => {
      await S(() => document.querySelector('button[aria-label="Проверки"]')?.click());
      await пауза(500);
    };
    const текстОкна = () => S(() => document.querySelector('.модал.окно')?.innerText ?? '');
    const закрыть = async () => {
      await стр.keyboard.press('Escape');
      await пауза(300);
    };

    /* ---------- 1. демо: ни одного замечания ---------- */
    await открытьПример(стр);
    const объектовДемо = await S(() => window.__верстакStore.getState().проект2.объекты.length);
    await открытьПроверки();
    const т1 = await текстОкна();
    проверка('демо-кухня: окно «Проверки» пустое — «Всё в порядке»', /Всё в порядке/.test(т1) && !/Ошибки|Предупреждения|Советы/.test(т1), `объектов ${объектовДемо}`);
    await стр.screenshot({ path: path.join(снимки, '4-проверки-демо-чисто.png') });
    await закрыть();

    /* ---------- 2. проблемный проект ---------- */
    await S(() => {
      const с = window.__верстакStore.getState();
      с.создать('Проверки этапа 4', { длина: 3600, ширина: 2800, высота_стен: 2700, толщина_стен: 100, форма: 'прямоугольник', обои: '#d8cdb8', пол: '#a58865', фон: '#171a1f' });
      window.__верстакStore.getState().установитьОбзор('сверху');
    });
    await пауза(900);
    const добавить = (изд, x, z, y = 0) =>
      S(
        (и, x, z, y) => {
          const с = window.__верстакStore.getState();
          const ид = с.добавитьМодуль(и, [x, y, z]);
          window.__верстакStore.getState().выбрать([]);
          return ид;
        },
        изд,
        x,
        z,
        y,
      );
    const ид = {};
    ид.столешница = await добавить('столешница-3000', 0, -1100, 900);
    ид.навесной = await добавить('навесной-600', 0, -1240, 1250);
    ид.щельА = await добавить('тумба-ящики-600', -1200, -1120);
    ид.щельБ = await добавить('тумба-ящики-600', -580, -1120);
    ид.пересечениеА = await добавить('тумба-ящики-600', 600, -1120);
    ид.пересечениеБ = await добавить('тумба-ящики-600', 900, -1120);
    ид.напротив = await добавить('тумба-ящики-600', -580, 140); // напротив тумбы щельБ: между фасадами 700 мм
    ид.длинный = await добавить('шкаф-распашной-2843', 1500, 0); // повёрнут на 90°: вдоль комнаты 2800 мм, шкаф 2843
    // повороты задаём загрузкой проекта: команда поворота в store привязана к жесту
    await S((повороты) => {
      const с = window.__верстакStore.getState();
      const п = с.проект2;
      с.загрузить({ ...п, объекты: п.объекты.map((x) => (x.id in повороты ? { ...x, поворот: повороты[x.id] } : x)) });
    }, { [ид.напротив]: 180, [ид.длинный]: 90 });
    await пауза(800);
    await S(() => window.__кухня?.поставитьКамеру?.(0, 6.4, 3.4, 0, -1.1));
    await пауза(400);

    await открытьПроверки();
    const т2 = await текстОкна();
    проверка('есть три группы: Ошибки, Предупреждения, Советы', /Ошибки/.test(т2) && /Предупреждения/.test(т2) && /Советы/.test(т2));
    проверка('«не влезает» с цифрами: между стенами, нужно, не хватает', /не влезает по ширине — между стенами 2800 мм, нужно 2843, не хватает 43 мм/.test(т2) || /не влезает по ширине — между стенами \d+ мм, нужно 2843, не хватает \d+ мм/.test(т2), (т2.match(/[^\n]*не влезает[^\n]*/) || [''])[0].slice(0, 160));
    проверка('пересечение с цифрой в мм', /пересекается с .* на 300 мм/.test(т2));
    проверка('проход 700: «не хватает 200 мм»', /Проход перед .* — 700 мм до .*нужно не меньше 900 мм, не хватает 200 мм/.test(т2), (т2.match(/[^\n]*Проход перед[^\n]*/) || [''])[0].slice(0, 160));
    проверка('высота рабочей поверхности 938: выше на 38', /938 мм.*выше на 38 мм/.test(т2));
    проверка('щель 20 мм — совет', /Щель 20 мм/.test(т2));
    проверка('фартук — совет с нормой 550–600', /Фартук/.test(т2) && /550–600/.test(т2));
    await стр.screenshot({ path: path.join(снимки, '4-проверки-список.png') });

    // фильтр
    await S(() => [...document.querySelectorAll('.чип-проверок')].find((b) => b.textContent.startsWith('Ошибки'))?.click());
    await пауза(300);
    const т3 = await текстОкна();
    проверка('фильтр «Ошибки» скрывает остальное', /Ошибки/.test(т3) && !/Предупреждения\n/.test(т3.replace(/Предупреждения\s*\d+/, '')) && !/Щель 20/.test(т3));
    await стр.screenshot({ path: path.join(снимки, '4-проверки-фильтр.png') });
    await S(() => [...document.querySelectorAll('.чип-проверок')].find((b) => b.textContent.startsWith('Все'))?.click());
    await пауза(200);

    // переход к объекту
    const цельПерехода = await S(() => {
      const л = [...document.querySelectorAll('.замечание')].find((li) => /пересекается/.test(li.innerText));
      return l_ok(л);
      function l_ok(x) {
        if (!x) return null;
        x.querySelector('.позиция').click();
        return true;
      }
    });
    await пауза(500);
    const после = await S(() => ({ окно: !!document.querySelector('.модал.окно'), выбрано: window.__верстакStore.getState().выбрано }));
    проверка('клик по замечанию закрывает окно и выделяет объект', цельПерехода && !после.окно && после.выбрано.length === 1 && [ид.пересечениеА, ид.пересечениеБ].includes(после.выбрано[0]), JSON.stringify(после));
    await стр.screenshot({ path: path.join(снимки, '4-проверки-переход.png') });

    // светлая тема
    await S(() => document.documentElement.setAttribute('data-theme', 'light'));
    await открытьПроверки();
    await стр.screenshot({ path: path.join(снимки, '4-проверки-светлая.png') });
    const контраст = await S(() => {
      const ярк = (c) => {
        const [r, g, b] = c.match(/\d+(\.\d+)?/g).slice(0, 3).map(Number).map((v) => { v /= 255; return v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4; });
        return 0.2126 * r + 0.7152 * g + 0.0722 * b;
      };
      const к = (a, b) => { const x = ярк(a), y = ярк(b); return (Math.max(x, y) + 0.05) / (Math.min(x, y) + 0.05); };
      const ок = document.querySelector('.модал.окно');
      const фон = getComputedStyle(ок).backgroundColor;
      const el = [...ок.querySelectorAll('.размер, .имя, .чип-проверок, h4')];
      let мин = 99;
      for (const e of el) мин = Math.min(мин, к(getComputedStyle(e).color, фон));
      return +мин.toFixed(2);
    });
    проверка('контраст текста окна в светлой теме ≥ 4,5:1', контраст >= 4.5, `мин ${контраст}`);
    await закрыть();
    await S(() => document.documentElement.removeAttribute('data-theme'));

    /* ---------- 3. консоль ---------- */
    const ошибки = к.ошибки.filter((e) => !/favicon|ResizeObserver/.test(e));
    проверка('ошибок консоли и шейдеров нет', ошибки.length === 0 && к.шейдер.length === 0, ошибки.concat(к.шейдер).join(' | ').slice(0, 300));
    await браузер.disconnect();
  } catch (е) {
    проверка('сбой приёмки', false, е && е.message ? е.message : String(е));
  } finally {
    try {
      процесс.kill();
    } catch {
      /* окно уже закрыто */
    }
  }
  const ок = итоги.filter((x) => x.ок).length;
  console.log(`\nИтог: ${ок} из ${итоги.length}, ${((Date.now() - t0) / 1000).toFixed(0)} с`);
  process.exit(ок === итоги.length ? 0 : 1);
})();
