function взгляд(P, T) {
  const dx = T[0] - P[0];
  const dy = T[1] - P[1];
  const dz = T[2] - P[2];
  return [Math.atan2(-dx, -dz), Math.atan2(dy, Math.hypot(dx, dz))];
}

