function подготовить() {
  fs.rmSync(данные, { recursive: true, force: true });
  fs.mkdirSync(path.join(данные, 'Проекты'), { recursive: true });
  const исходный = path.join(корень, 'Проекты', 'Пример_ кухня из шаблонов.kitchen');
  fs.copyFileSync(исходный, path.join(данные, 'Проекты', 'Пример_ кухня из шаблонов.kitchen'));
}

/** Выполнить в странице код с доступом к store и моделям */
const вСтранице = (стр, fn, ...арг) =>
  стр.evaluate(
    async (код, арг2) => {
      const useКухня = window.__верстакStore ?? (await import('/src/store/index.ts')).useКухня;
      const модель = {
        проверка: await import('/src/model/проверка.ts'),
        помещение: await import('/src/model/помещение.ts'),
        проект: await import('/src/model/проект.ts'),
      };
      // eslint-disable-next-line no-new-func
      return new Function('useКухня', 'модель', 'арг', `return (${код})(useКухня, модель, ...арг)`)(useКухня, модель, арг2);
    },
    fn.toString(),
    арг,
  );

const ядро = (стр, fn, ...арг) => стр.evaluate((код, арг2) => new Function('к', 'арг', `return (${код})(к, ...арг)`)(window.__кухня, арг2), fn.toString(), арг);

async function новыйПроект(стр, ш, г, в = 2700) {
  await вСтранице(
    стр,
    (с, м, ш2, г2, в2) => {
      const п = м.проект.новыйПроектV2('Проверка', м.помещение.новоеПомещение('п1', 'кухня', 'Кухня', м.помещение.прямоугольник(ш2, г2), в2));
      с.getState().загрузить(п);
    },
    ш,
    г,
    в,
  );
  await пауза(700);
}

