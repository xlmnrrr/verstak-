/**
 * Приёмка этапа 1А-1 в настоящем окне Electron: миграция v1 → v2, сохранение, бэкап исходника,
 * корзина, автосохранение и восстановление после «убитого» процесса, история.
 *
 * Боевые данные не трогаются: приложение стартует с VERSTAK_DATA_DIR = проверка\данные-1А1.
 * Запуск (dev-сервер уже работает на 5274):  node scripts/проверка-1А1.cjs
 *   КУХНЯ_DEV_URL берётся из аргумента: node scripts/проверка-1А1.cjs http://127.0.0.1:5274/
 */
const path = require('node:path');
const fs = require('node:fs');
const { spawn } = require('node:child_process');

const PUPPETEER = 'C:\\Users\\makar\\.dsh\\profiles\\desktop\\node_modules\\puppeteer-core';
const puppeteer = require(PUPPETEER);
const electronExe = require('electron');

const АДРЕС = process.argv[2] || 'http://127.0.0.1:5274/';
const ПОРТ = 9333;
const корень = process.cwd();
const данные = path.join(корень, 'проверка', 'данные-1А1');
const пауза = (мс) => new Promise((r) => setTimeout(r, мс));

const результаты = [];
const проверка = (имя, ок, подробности = '') => {
  результаты.push({ имя, ок: !!ок, подробности });
  console.log(`${ок ? 'ОК ' : 'НЕТ'}  ${имя}${подробности ? ' — ' + подробности : ''}`);
};

function подготовить() {
  fs.rmSync(данные, { recursive: true, force: true });
  fs.mkdirSync(path.join(данные, 'Проекты'), { recursive: true });
  const исходный = path.join(корень, 'Проекты', 'Пример_ кухня из шаблонов.kitchen');
  const текст = fs.readFileSync(исходный);
  fs.writeFileSync(path.join(данные, 'Проекты', 'Пример_ кухня из шаблонов.kitchen'), текст);
  fs.writeFileSync(path.join(данные, 'Проекты', 'Удалить меня.kitchen'), текст);
  return текст;
}

function запуститьElectron() {
  const env = { ...process.env, VERSTAK_DATA_DIR: данные, VERSTAK_AUTOSAVE_SEC: '2' };
  delete env.ELECTRON_RUN_AS_NODE;
  env['КУХНЯ_DEV_URL'] = АДРЕС;
  const процесс = spawn(electronExe, ['.', `--remote-debugging-port=${ПОРТ}`], { cwd: корень, env, stdio: 'ignore' });
  return процесс;
}

async function подключиться() {
  for (let i = 0; i < 60; i++) {
    try {
      const браузер = await puppeteer.connect({ browserURL: `http://127.0.0.1:${ПОРТ}`, defaultViewport: null });
      const стр = (await браузер.pages()).find((p) => p.url().startsWith(АДРЕС));
      if (стр) return { браузер, стр };
      браузер.disconnect();
    } catch {
      /* ждём запуск */
    }
    await пауза(500);
  }
  throw new Error('не удалось подключиться к окну Electron');
}

const вСтранице = (стр, fn, ...арг) =>
  стр.evaluate(async (код, арг2) => {
    const { useКухня } = await import('/src/store/index.ts');
    // eslint-disable-next-line no-new-func
    return new Function('useКухня', 'арг', `return (${код})(useКухня, ...арг)`)(useКухня, арг2);
  }, fn.toString(), арг);

(async () => {
  const исходныйТекст = подготовить();
  const ошибкиСтраницы = [];

  /* ---------------------------------------------------------------- запуск 1 */
  let процесс = запуститьElectron();
  let { браузер, стр } = await подключиться();
  стр.on('pageerror', (e) => ошибкиСтраницы.push(e.message));
  стр.on('console', (м) => {
    if (м.type() === 'error') ошибкиСтраницы.push(м.text());
  });
  await пауза(1500);

  const естьМост = await стр.evaluate(() => !!(window.кухня && window.кухня.авто));
  проверка('мост Electron (с автосохранением) доступен', естьМост);

  // A1. Открыть проект v1: миграция
  const открыт = await вСтранице(стр, async (s) => {
    await s.getState().открыть('Пример_ кухня из шаблонов');
    const г = s.getState();
    return {
      экран: г.экран,
      версия: г.проект2.schemaVersion,
      объектовV2: г.проект2.объекты.length,
      объектовV1: г.проект.объекты.length,
      помещений: г.проект2.помещения.length,
      изменено: г.изменено,
      сообщение: г.сообщение && г.сообщение.текст,
    };
  });
  проверка('проект v1 открылся в редакторе', открыт.экран === 'редактор', JSON.stringify(открыт));
  проверка('после открытия: v2, 13 объектов, помещение одно', открыт.версия === 2 && открыт.объектовV2 === 13 && открыт.помещений === 1);
  проверка('до сохранения файл на диске остался v1 нетронутым', fs.readFileSync(path.join(данные, 'Проекты', 'Пример_ кухня из шаблонов.kitchen')).equals(исходныйТекст));

  // A2. Правка + сохранение → файл v2, исходник v1 в Бэкапы\
  await вСтранице(стр, (s) => {
    s.getState().добавитьМодуль('cabinet-base-400');
  });
  await пауза(300);
  await вСтранице(стр, async (s) => {
    await s.getState().сохранить();
  });
  await пауза(800);
  const файлV2 = JSON.parse(fs.readFileSync(path.join(данные, 'Проекты', 'Пример_ кухня из шаблонов.kitchen'), 'utf8'));
  проверка('сохранённый файл — schemaVersion 2, 14 объектов', файлV2.schemaVersion === 2 && файлV2.объекты.length === 14, `объектов ${файлV2.объекты.length}`);
  const бэкапы = fs.existsSync(path.join(данные, 'Бэкапы')) ? fs.readdirSync(path.join(данные, 'Бэкапы')) : [];
  const копияV1 = бэкапы.find((ф) => ф.endsWith('.v1.kitchen'));
  проверка('исходник v1 скопирован в Бэкапы\\<имя>.v1.kitchen байт в байт', копияV1 && fs.readFileSync(path.join(данные, 'Бэкапы', копияV1)).equals(исходныйТекст), копияV1);

  // A3. Повторное открытие v2
  const повтор = await вСтранице(стр, async (s) => {
    await s.getState().открыть('Пример_ кухня из шаблонов');
    const г = s.getState();
    return { версия: г.проект2.schemaVersion, объектов: г.проект2.объекты.length, изменено: г.изменено, сообщение: г.сообщение && г.сообщение.текст };
  });
  проверка('v2-файл открывается заново без миграции', повтор.версия === 2 && повтор.объектов === 14 && !повтор.изменено, JSON.stringify(повтор));

  // A4. Повторное сохранение не плодит .v1
  await вСтранице(стр, async (s) => {
    s.getState().обновитьГабариты(s.getState().проект2.объекты[0].id, { ш: 650 });
    await s.getState().сохранить();
  });
  await пауза(500);
  const бэкапы2 = fs.readdirSync(path.join(данные, 'Бэкапы'));
  проверка('второе сохранение не создаёт новых .v1-копий', бэкапы2.filter((ф) => ф.includes('.v1.')).length === 1, бэкапы2.join(', '));

  // A5. История: жест из 50 правок откатывается одним Ctrl+Z; правка цифрой отменяется
  const история = await вСтранице(стр, (s) => {
    const г0 = s.getState();
    const ид = г0.проект2.объекты[1].id;
    const x0 = г0.проект2.объекты[1].позиция[0];
    const записей0 = г0.прошлое.length;
    г0.начатьИзменение();
    for (let i = 1; i <= 50; i++) s.getState().обновитьОбъект(ид, { позиция: [x0 + i * 10, 0, г0.проект.объекты[1].позиция[2]] });
    const послеЖеста = s.getState();
    const записей = послеЖеста.прошлое.length - записей0;
    const x1 = послеЖеста.проект2.объекты[1].позиция[0];
    s.getState().отменить();
    const xОтмена = s.getState().проект2.объекты[1].позиция[0];
    s.getState().вернуть();
    const xВернуть = s.getState().проект2.объекты[1].позиция[0];
    // правка размера цифрой
    const ш0 = s.getState().проект2.объекты[1].габариты.ш;
    s.getState().обновитьГабариты(ид, { ш: 555 });
    const ш1 = s.getState().проект2.объекты[1].габариты.ш;
    s.getState().отменить();
    const шОтмена = s.getState().проект2.объекты[1].габариты.ш;
    return { записей, x0, x1, xОтмена, xВернуть, ш0, ш1, шОтмена };
  });
  проверка('жест из 50 правок — одна запись истории', история.записей === 1, `записей ${история.записей}`);
  проверка('Ctrl+Z откатывает жест целиком, Ctrl+Y возвращает', история.xОтмена === история.x0 && история.xВернуть === история.x1, JSON.stringify(история));
  проверка('правка размера цифрой отменяется', история.ш1 === 555 && история.шОтмена === история.ш0, `было ${история.ш0}, стало ${история.ш1}, после отмены ${история.шОтмена}`);

  // A6. Удаление → корзина
  const удаление = await вСтранице(стр, async (s) => {
    await s.getState().удалить('Удалить меня');
    return true;
  });
  const впапке = fs.readdirSync(path.join(данные, 'Проекты')).filter((ф) => ф.endsWith('.kitchen'));
  const вкорзине = fs.existsSync(path.join(данные, 'Проекты', '.корзина')) ? fs.readdirSync(path.join(данные, 'Проекты', '.корзина')) : [];
  проверка('удаление переносит проект в Проекты\\.корзина, а не стирает', удаление && !впапке.includes('Удалить меня.kitchen') && вкорзине.some((ф) => ф.startsWith('Удалить меня.')), вкорзине.join(', '));

  // A7. Очистка имени: попытка записи с путём
  const имяПроверка = await стр.evaluate(async () => {
    const р = await window.кухня.сохранить('..\\..\\Хитрое:имя', '{"schemaVersion":2}', undefined);
    return р;
  });
  проверка('имя проекта очищается (путь «..», двоеточие)', имяПроверка.ок && !имяПроверка.имя.includes('..') && !/[\\/:]/.test(имяПроверка.имя), JSON.stringify(имяПроверка.имя));
  const упал = await стр.evaluate(async () => (await window.кухня.открыть('..\\..\\x')).ок === false);
  проверка('открытие по имени с «..» отклоняется', упал);
  fs.rmSync(path.join(данные, 'Проекты', `${имяПроверка.имя}.kitchen`), { force: true });

  /* ---------------------------------------------------------------- автосохранение */
  await вСтранице(стр, (s) => {
    const г = s.getState();
    г.создать('Работа до сбоя', { длина: 3600, ширина: 2800, высота_стен: 2700, толщина_стен: 100, форма: 'прямоугольник', обои: '#cbb79a', пол: '#8a6a4b', фон: '#171a1f' });
    s.getState().добавитьМодуль('cabinet-base-400');
    s.getState().добавитьМодуль('cabinet-sink-600');
    s.getState().добавитьМодуль('wall-600');
  });
  await пауза(6000); // интервал 2 с
  const авто = path.join(данные, 'Проекты', '.автосохранение', 'Работа до сбоя.kitchen');
  const автоЕсть = fs.existsSync(авто);
  const автоДанные = автоЕсть ? JSON.parse(fs.readFileSync(авто, 'utf8')) : null;
  проверка('автосохранение записалось (интервал 2 с)', автоЕсть && автоДанные.schemaVersion === 2 && автоДанные.объекты.length === 3, автоЕсть ? `объектов ${автоДанные.объекты.length}` : 'файла нет');
  проверка('основной файл при этом не создан (автосохранение отдельно)', !fs.existsSync(path.join(данные, 'Проекты', 'Работа до сбоя.kitchen')));

  // убиваем процесс
  браузер.disconnect();
  процесс.kill('SIGKILL');
  await пауза(1500);

  /* ---------------------------------------------------------------- запуск 2: восстановление */
  процесс = запуститьElectron();
  ({ браузер, стр } = await подключиться());
  стр.on('pageerror', (e) => ошибкиСтраницы.push(e.message));
  await пауза(3000);
  const найдено = await вСтранице(стр, (s) => s.getState().найденоАвто.map((х) => х.имя));
  проверка('после перезапуска найдена несохранённая работа', найдено.length === 1 && найдено[0] === 'Работа до сбоя', JSON.stringify(найдено));
  const окно = await стр.evaluate(() => {
    const э = document.querySelector('.восстановление');
    return э ? э.textContent : null;
  });
  проверка('на экране вопрос «Восстановить?»', !!окно && окно.includes('Восстановить'), окно);
  fs.mkdirSync(path.join(корень, 'проверка', 'v2'), { recursive: true });
  await стр.screenshot({ path: path.join(корень, 'проверка', 'v2', '1А1-восстановление.png') });

  await стр.evaluate(() => {
    const к = [...document.querySelectorAll('.восстановление button')].find((b) => b.textContent.includes('Восстановить'));
    к && к.click();
  });
  await пауза(1500);
  const восстановлено = await вСтранице(стр, (s) => {
    const г = s.getState();
    return { экран: г.экран, название: г.проект2.название, объектов: г.проект2.объекты.length, изменено: г.изменено, найдено: г.найденоАвто.length };
  });
  проверка('«Восстановить» открывает работу: 3 объекта, имя на месте, правки помечены несохранёнными', восстановлено.экран === 'редактор' && восстановлено.название === 'Работа до сбоя' && восстановлено.объектов === 3 && восстановлено.изменено === true, JSON.stringify(восстановлено));

  await вСтранице(стр, async (s) => {
    await s.getState().сохранить();
  });
  await пауза(700);
  проверка('после сохранения проект записан, автосохранение удалено', fs.existsSync(path.join(данные, 'Проекты', 'Работа до сбоя.kitchen')) && !fs.existsSync(авто));

  await стр.screenshot({ path: path.join(корень, 'проверка', 'v2', '1А1-редактор-после-восстановления.png') });
  проверка('ошибок в консоли окна нет', ошибкиСтраницы.length === 0, ошибкиСтраницы.slice(0, 3).join(' | '));

  браузер.disconnect();
  процесс.kill('SIGKILL');

  const упавшие = результаты.filter((р) => !р.ок);
  console.log(`\nИТОГ: ${результаты.length - упавшие.length} из ${результаты.length} проверок пройдено`);
  fs.writeFileSync(path.join(корень, 'проверка', 'проверка-1А1.json'), JSON.stringify({ дата: new Date().toISOString(), результаты }, null, 2), 'utf8');
  process.exit(упавшие.length ? 2 : 0);
})().catch((e) => {
  console.error('ПРОВЕРКА УПАЛА:', e.stack || e.message);
  process.exit(1);
});
