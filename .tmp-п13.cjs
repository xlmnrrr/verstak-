const fs = require('fs');
function прав(p, ф) {
  let s = fs.readFileSync(p, 'utf8');
  s = ф(s);
  fs.writeFileSync(p, s);
}
const зам = (s, a, b, все = false) => {
  if (!s.includes(a)) throw new Error('не найдено: ' + a.slice(0, 60));
  return все ? s.split(a).join(b) : s.replace(a, () => b);
};
